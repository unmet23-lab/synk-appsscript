import { Config } from "@remotion/cli/config";

/* 세로 릴(1080×1920)이 기본 과녁이다 — 컴포지션마다 다시 정한다. */
Config.setVideoImageFormat("jpeg");
Config.setOverwriteOutput(true);

/* 🔴 프레임 중간 포맷의 «품질»을 100 으로 올린다 (2026-09-06).
   Remotion 은 한 프레임씩 이미지로 뽑아 인코딩하는데, 그 중간 이미지가 JPEG 이고
   기본 품질이 **80** 이다. 즉 H.264 가 손대기 «전»에 이미 한 번 깎인 그림이 들어간다.
   그 뒤 H.264 가 한 번, 플랫폼(틱톡·인스타·유튜브)이 또 한 번 — 손실이 세 겹이 된다.
   🔑 우리 그림은 «펠트 재질»이라 그 손실이 정확히 아픈 자리를 친다 — 보풀·실땀·천 결은
   전부 고주파 디테일이고 JPEG 이 가장 먼저 버리는 것이 그것이다.
   ⚠ png 로 바꾸면 무손실이지만 굽는 시간이 크게 는다. 품질 100 이 그 사이의 답이다. */
Config.setJpegQuality(100);

/* 🔴 비트레이트를 «바닥이 있는 값»으로 못박는다 (2026-09-06 · 실측이 시켰다).
   앞 판은 CRF(품질 고정) 기본값에 맡겼는데, CRF 는 움직임이 적으면 비트레이트를 스스로 낮춘다.
   구운 파일을 ffprobe 로 재보니 **편마다 3.6 ~ 9.4 Mbps 로 갈렸다**(clip-01-1 = 3.63 · clip-01-2 = 9.39).
   우리 릴은 정지에 가까운 펠트 장면이 많아 낮은 쪽으로 쏠린다.
   🔴 3.6 Mbps 는 인스타 기준 「눈에 띄게 흐릿한」 구간이고, 세 플랫폼 권장은 모두 8~15 Mbps 다.
   🔑 왜 «바닥»이 중요한가 — 플랫폼은 받은 파일을 반드시 다시 압축하는데, 그때 원본에 여유가
   없으면 «품질에서 깎는 것»이 아니라 «굶은 데서 깎는 것»이 된다. 헤드룸을 주는 것이 이 값의 일이다.
   ⚠ videoBitrate 를 주면 crf 는 무시된다(Remotion 규약). 20 Mbps 를 넘기면 플랫폼이 그냥 버린다. */
Config.setVideoBitrate("12M");
Config.setEncodingMaxRate("16M");
Config.setEncodingBufferSize("24M");

/* 소리는 이미 275 kbps 로 나오고 있었다(실측). 값을 못박아 판마다 흔들리지 않게 한다.
   세 플랫폼 권장이 128~256 kbps 라 상단에 붙인다. 소리 크기 보정은 `영상/마스터.js` 가 따로 진다. */
Config.setAudioBitrate("256k");

/* 이 노트북 실측 여유 메모리가 3GB 안팎이다(08-26 13:57 = 2.94GB/15.41GB).
   동시성을 안 묶으면 크롬이 코어 수만큼 떠서 다른 세션의 굽기와 경합한다.
   숫자를 올리려면 «먼저 재고» 올린다 — 트랙 §0 의 겹침 규율과 같은 축이다. */
Config.setConcurrency(4);

/* 🔴 색을 bt709 로 «태그해서» 굽는다.
   첫 판 실측: pix_fmt=yuvj420p · color_range=pc · color_space=bt470bg — 전대역 + PAL 행렬이다.
   JPEG 중간 포맷(setVideoImageFormat)이 전대역이라 그렇게 찍혔다. 수신측이 limited 로 읽으면
   크림 종이 바탕이 흰색으로 뭉개지고, bt470bg→bt709 오태그 몫까지 얹히면 코랄의 G 채널이 어긋난다.
   🔑 색 판정은 «유호님 눈»이 축인 자리다(결정 08-26) — 판정한 색과 발행되는 색이 달라지면 그 판정이 헛돈다. */
Config.setColorSpace("bt709");
