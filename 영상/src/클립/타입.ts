/**
 * 클립 데이터의 «타입 정본» — 여기 하나뿐이다.
 *
 * 🔴 왜 따로 뺐나: 첫 판에서 이 타입들이 **`01_안녕하세요.ts`(01편 1화 데이터 파일) 안에** 살았다.
 *   컴포넌트가 그 데이터 파일에서 타입을 빌려 쓰고 있었으므로, 2편째를 만드는 순간
 *   45편 전량이 「1화 파일에 매달린」 모양으로 선다. 파일 하나를 지우면 44편이 같이 무너지는 자리였다.
 *   (트랙 §2-영상 08-26: 「대본 45편 중 자동으로 되는 편이 0편 — 그 전에 타입 분리가 먼저다」)
 *
 * 데이터는 이제 손으로 안 적는다 — `대본읽기.js` 가 대본 md 에서 읽어 `생성/대본클립들.ts` 로 쓴다.
 */

/**
 * 몽글이 한 장면에서 짓는 표정.
 *
 * ⚠ 쓸 수 있는 것이 이 둘뿐인 이유는 «그림이 셋뿐»이어서다(`public/몽글/` = 본체·눈감음·눈웃음).
 *   눈감음은 데이터가 고르는 값이 아니라 깜빡임이 **자동으로** 넣는다.
 *   감정 7종(집중·응원·감동·부끄·윙크·졸림·뾰로통)은 그림이 아직 없다 — 부르면 모듈이 던진다.
 */
export type 표정 = "본체" | "눈웃음";

/** 자막 한 장면. 대본 md 의 «[화면 자막]» 표 한 행이 이것 하나가 된다. */
export type 장면 = {
  /** 화면 코랄 알약에 찍히는 글자. 대본의 「타이밍」 칸을 학생이 읽을 말로 옮긴 것. */
  라벨: string;
  한국어: string;
  /**
   * 몽골어 병기. **없으면 빈 문자열이다 — 지어내지 않는다.**
   *
   * 🔴 첫 판이 여기서 샜다: 대본 클로징 행에는 몽골어 칸이 아예 없는데 코드가
   *   `Дууслаа — өчигдрийн би +1` 을 «지어내» 넣고 있었다(저장소 전수 검색 히트가 코드 그 한 줄뿐).
   *   파서는 **키릴 글자가 실제로 있는지**로만 가른다 — 판정 근거가 «구분자»가 아니라 «글자»다.
   */
  몽골어: string;
  프레임: number;
  표정: 표정;
  /** `영상/public/소리/` 안의 파일 이름. 없으면 조용히 간다. */
  소리?: string;
};

export type 클립 = {
  /** 컴포지션 id — **영문·숫자·하이픈만**(Remotion 규약, Root.tsx 참조). 예: `clip-01-1` */
  id: string;
  /** 사람이 읽는 이름. 파일명·목록·판정 쪽지에 쓴다. */
  제목: string;
  /** 대본 파일의 편 번호(01~09)와 그 안의 화 번호(1~5). */
  편: string;
  화: number;
  훅: string;
  장면들: 장면[];
  /** 훅 + 장면 전부. 30fps 기준 900f = 30초. */
  전체프레임: number;
  /** 이 클립이 나온 대본 md 의 저장소 상대경로 — 「어디서 왔나」를 데이터가 스스로 안다. */
  출처: string;
};
