/**
 * 한 편 안에서 **같은 몸짓이 잇달아 나오면 사이를 쉰다.**
 *
 * 🔴 실측(08-26)이 시켜서 넣었다: `clip-09-3`(「잠시만 기다려 주세요」 편)은 여섯 칸 중 **다섯이 움츠**였다.
 *   모든 줄에 「잠시만·기다」가 들어 있으니 규칙상 맞는 판정인데, 화면에서는 **30초 내내 움츠린 채**다.
 *   반복은 «강조»가 아니라 «정지»로 읽힌다 — 몸짓이 계속 있으면 몸짓이 없는 것과 같아진다.
 *
 * 🔑 규칙: **연달아 둘까지는 두고, 셋째부터 쉰다.**
 *   ⚠ 처음엔 「앞 칸과 같으면 무조건 쉰다」로 짰다가 **되돌렸다** — 그러면 count-01 의
 *     1위 「ㅋㅋ」가 앞 칸(꿀잼)과 같은 통통이라 «절정의 눈웃음»까지 깎였다.
 *     둘까지 두면 뜻이 살고, 셋째를 쉬면 09편 3화의 «다섯 칸 연속 움츠»가 깨진다.
 *     실측 — 09편 3화: 움츠×5 → 움츠·움츠·기본·움츠·움츠(최장 연속 5 → 2).
 */
export function 몸짓쉼표(목록: 몸짓[]): 몸짓[] {
  let 직전: 몸짓 = "기본";
  let 이어짐 = 0;
  return 목록.map((g) => {
    if (g !== "기본" && g === 직전) 이어짐 += 1;
    else 이어짐 = 0;
    const 낼것 = 이어짐 >= 2 ? "기본" : g;
    직전 = 낼것 === "기본" ? "기본" : g;
    if (낼것 === "기본") 이어짐 = 0;
    return 낼것;
  });
}

