export function 몸짓고르기(글: string): 몸짓 {
  const s = 글.trim();
  if (/맵|매워|매운|얼큰|불닭|화끈/.test(s)) return "바르르";
  if (/ㅋㅋ|웃음|하하|맛있|꿀맛|맛집|재미|꿀잼|좋아|최고|짱|반가|축하|기뻐/.test(s)) return "통통";
  if (/인정|맞아|동의|진짜|레알|정말|그렇/.test(s)) return "끄덕";
  if (/잠시만|기다|죄송|미안|천천히|조용|싸해|어색|갑자기/.test(s)) return "움츠";
  if (/헐|대박|설마|놀라|어떡해/.test(s)) return "쭉";
  if (/[?？]/.test(s)) return "갸웃";
  if (/[!！]/.test(s)) return "쭉";
  return "기본";
}
