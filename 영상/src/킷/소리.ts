/**
 * 킷 → Remotion 다리 «소리». 색·폰트와 같은 규율 — **여기는 값의 정본이 아니라 통로다.**
 *
 * 🔑 정본 사슬(한 값 두 곳 금지):
 *   `docs/브랜드_사운드킷/_사운드킷.md` 원문 「값의 정본은 `docs/디자인_토큰.json` 「사운드」다」
 *   → 토큰 `사운드.이벤트`(UI 킷 3 + 몽글 12 + 까몽 5 + 마린 4) + 옹알이 7(`tools/감각층소리합성.js` MURMURS)
 *   → `영상/소리어휘.js` 가 그 둘에서 표를 **파생**해 `클립/생성/소리표.ts` 로 쓴다(대본읽기가 매번 · git 밖)
 *   → 여기는 그 표를 읽고, 없는 이름은 **던진다**(조용한 폴백 금지 — `색()`·마스코트자산.js 와 같은 판단).
 *
 * 🗺 «어느 상황에 어느 소리»(배치)의 정본은 형제 저장소 **`SYNK-talk/lib/가이드목소리.js`** 하나다 —
 *   `_사운드킷.md` 가 그렇게 못 박았다. 여기 옮겨 적지 않는다. 영상 안의 배치(꼴 → 소리)는 `대본읽기.js` 의
 *   꼴소리·라벨소리·옹알이배치 표가 지고, 그 표는 이 어휘 «안에서만» 고른다(`발행검사.js` ④ 가 잰다).
 *
 * 🔑 이름 규약 — 킷 소리 = 토큰 이벤트 키 그대로(`몽글_먀앙` · `까몽_베에` · `획득`) ·
 *   옹알이 = `옹알이_<가이드>_<이름>`(`옹알이_까몽_궁금`). 파일 자리는 `자산모으기.js` 가 같은 규약으로 놓는다.
 *
 * 규격의 정본은 토큰 「사운드」 — 규칙 넷(400ms 이하 · 실패음 없음 · 사인·트라이앵글 · C 펜타토닉)은 UI 킷의
 * 규칙이고 가이드 목소리는 「캐릭터의 악기가 문법을 이긴다」(_사운드킷.md 「두 가족」). 영상은 소리를 새로
 * 만들지 않는다 — 있는 것을 «이름으로» 고를 뿐이다.
 */
import { 소리표 } from "../클립/생성/소리표";

export type 소리규격 = {
  이름: string;
  /** `public/` 아래 상대경로 — `staticFile()` 에 그대로 넣는다. */
  파일: string;
  가족: "UI 킷" | "가이드 목소리" | "옹알이";
  길이ms?: number;
  파형?: string;
  형태?: string;
  가이드?: string;
  합성번호?: number;
};

const 표 = 소리표 as Record<string, 소리규격>;

/** 소리 이름 하나를 규격(파일·길이…)으로 바꾼다. 없는 이름은 **던진다.** */
export function 소리(이름: string): 소리규격 {
  const s = 표[이름];
  if (!s) {
    throw new Error(
      `소리 표에 없는 이름: 「${이름}」 — 정본은 토큰 사운드.이벤트(+옹알이 7)다. 쓸 수 있는 이름: node 영상/소리어휘.js`,
    );
  }
  return s;
}

/** 쓸 수 있는 이름 전량(검사·목록용). */
export const 소리이름들: string[] = Object.keys(표);
