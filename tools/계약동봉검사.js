#!/usr/bin/env node
'use strict';
/* 계약 픽스처 «동봉» 게이트 — 계약 개정이 조립부를 두고 가는 것을 **커밋 전에** 막는다.
 *   (자율주행 판정 0814 #26 「세운다 · 좁은 판 그대로」 · 근거 memory `m0-contract-freeze` · 거부권 열림)
 *
 * ■ 무엇을 막나 — `계약/수집_교정_계약.json` 의 `픽스처_항목필드` 가 늘었는데 픽스처 조립부
 *   (`엔진_수집.js` 의 `항목.push({…})`)가 따라오지 않은 커밋.
 *
 * ■ 왜 사전 차단인가 (같은 자리 2번째 = 시스템 결함 · CLAUDE.md 신뢰성 조항)
 *   ① v9.173 `불변` ② v9.220 `대안태그`(`2d10108d`). 둘 다 같은 모양이다 — 계약에 칸을 늘리고
 *   조립부를 안 고쳤고, `tests/계약.test.js(⚠삭제됨 e75fc7fc 2026-08-19 — 지금 없다)` 가 **사후에** 빨개졌다. 그런데 이 저장소의 테스트는
 *   배포 게이트라, 그 적색은 고친 사람이 아니라 **그 뒤 커밋하는 모든 세션의 배포를 막는다**
 *   (주인 없는 적색 = 남의 배포를 막는다). 사후 검사는 탐지지 예방이 아니다.
 *
 * ■ 🔑 판정은 여기서 안 한다 — `tools/lib/계약동봉.js` 하나가 진다. 여기가 맡는 것은
 *   **무엇을 판정 대상으로 세우나**(=이 커밋이 끝난 뒤의 HEAD 내용)뿐이다.
 *
 * ■ 🔑 재는 것은 작업본이 아니라 **커밋 이후의 HEAD** 다 — 이게 이 가드의 전부다.
 *   `git commit -- 경로들` 은 범위를 못 박으므로, 작업본에서 양쪽을 다 고쳐 놓고 계약만
 *   커밋하면 **작업본은 초록인데 HEAD 는 빨갛다**(F302 「동봉으로 나가는 파일은 한 커밋에」의
 *   바로 그 자리). 작업본을 재는 검사는 원리상 그걸 못 본다.
 *     이후 내용 = 스테이징됐으면 인덱스(`:경로`) · 아니면 HEAD(`HEAD:경로`)
 *   (`git commit -- 경로` 도 임시 인덱스를 세워 훅에 물려주므로 `:경로` 가 곧 커밋될 내용이다.)
 *
 * ■ 🔑 **이번 커밋이 새로 낸 구멍만** 막는다 — HEAD 가 이미 깨져 있으면 말만 하고 통과시킨다.
 *   전량을 막으면 남이 낸 적색으로 내 커밋이 막히고, 그건 이 가드가 없애려는 바로 그 피해다
 *   (같은 훅의 `인용검사 --스테이징` 이 같은 이유로 같은 규약을 쓴다 · F103).
 *   그래서 **자기 처방이 실제로 통한다**: 조립부를 고쳐 같은 커밋에 담으면 그대로 지나간다(맹점 ③).
 *
 * ■ ⚠ 대가 (맹점 ④ — 새 장치엔 틀릴 때의 모습을 함께 적는다)
 *   틀리는 방향은 **거짓 초록**이다: 앵커 `항목.push({` 는 문구라, 조립부를 다른 모양으로
 *   (예: 객체를 따로 만들어 변수로 push) 바꾸면 판정층이 「못 쟀다」로 접고 이 게이트는 통과시킨다.
 *   그때 잡는 것은 사후 회귀 `tests/계약.test.js(⚠삭제됨 e75fc7fc 2026-08-19 — 지금 없다)` 다 — 그쪽은 앵커 부재 자체를 적색으로 단언한다.
 *   즉 앵커가 죽으면 **예방만 잃고 탐지는 남는다**. 「못 쟀다」를 조용히 넘기지 않고 찍는 이유가 이것이다.
 *   닫은 것: `tests/계약.test.js(⚠삭제됨 e75fc7fc 2026-08-19 — 지금 없다)` 안에 있던 같은 판정의 **사본 1벌**(블록찾기+필드검사)을 이 모듈로 접었다.
 */

const { execFileSync } = require('child_process');
const { 없는항목필드 } = require('./lib/계약동봉');

const 계약경로 = '계약/수집_교정_계약.json';
const 수집경로 = '엔진_수집.js';

/* [08-27 · 유호 「기술부채 진행」] 판 «번호» 대조 갈래 — 「계약 판 번호를 지키는 기계 0」(트랙 §8-B)의 처방.
 *   계약 `버전`(c13)과 `엔진_수집.js` SCHEMA_VER 손사본이 갈린 채 커밋되는 것을 막는다.
 *   실사고 = c12·c13 두 판을 c11 상수가 못 따라와 08-24 손 수리(v9.261) — 그때 「또 벌어지면 장치를
 *   제안한다」로 적어 둔 자리가 talk 장부(둘째 얼굴 08-25)로 재발해 §4 제안에 올라 있었고,
 *   유호님이 08-27 「전부 진행해줘」로 이 갈래를 여셨다. 규약은 동봉 대조와 같다:
 *   이번 커밋이 «새로 낸» 갈림만 막고, HEAD 에 이미 있던 갈림은 말만 하고 통과시킨다(F103). */
function 판대조(계약, 수집소스) {
  const 계약판 = String((계약 && 계약.버전) || '').trim();
  const m = String(수집소스 || '').match(/const SCHEMA_VER = '([^']+)'/);
  if (!계약판) return { 잼: false, 왜: '계약 JSON 에 `버전` 칸이 없다' };
  if (!m) return { 잼: false, 왜: "`const SCHEMA_VER = '…'` 앵커를 못 찾았다(앵커가 죽으면 예방만 잃는다 — 맹점 ④와 같은 무늬)" };
  return { 잼: true, 계약판: 계약판, 상수판: m[1], 갈림: 계약판 !== m[1] };
}

const 말 = (s) => process.stderr.write(s + '\n');

function git(args) {
  /* ☠️ `maxBuffer` 를 손으로 준다 — 형제 게이트가 그 자리에서 저장소를 멈췄다(2026-09-07).
   *   node 기본은 1MiB 이고, 읽는 파일이 그걸 넘으면 `git show` 가 ENOBUFS 로 죽는다.
   *   그러면 예외를 삼키는 자리가 「파일이 없다」로 읽어 **모든 세션의 커밋**을 막는다.
   *   여기 두 파일은 지금 각각 77KB·128KB 라 아직 멀지만, 함정은 크기가 아니라 «빠진 인자»다. */
  return execFileSync('git', args, {
    encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 256 * 1024 * 1024,
  });
}

/* ☠️ `-z` 인 이유는 옆 게이트와 같다 — 기본 출력은 비ASCII 를 `"\352\263\204…"` 로 이스케이프해서
 *   한글 경로 대조가 **영원히 안 맞는다**. 그리고 그 모양은 「검사가 통과했다」와 똑같다. */
function 스테이징목록() {
  try {
    return new Set(git(['diff', '--cached', '--name-only', '-z', '--diff-filter=ACMR'])
      .split('\0').filter(Boolean));
  } catch (_) { return new Set(); }
}

/** `ref:경로` 를 읽는다. ref `''` = 인덱스. 없으면 `null`. */
function 판본(ref, 경로) {
  try { return git(['show', `${ref}:${경로}`]); } catch (_) { return null; }
}

function main() {
  const 스테이징 = 스테이징목록();
  const 계약담김 = 스테이징.has(계약경로);
  const 수집담김 = 스테이징.has(수집경로);
  /* 발동 조건 = 불변식의 **두 입력 중 하나라도** 이 커밋에 있을 때.
   * 계약 쪽만 보면 반대 방향이 통째로 안 보인다 — 조립부에서 칸을 지우는 커밋도 같은 적색을 낳고,
   * 그 피해(남의 배포가 막힌다)는 글자 그대로 같다. 판정 자체는 하나라 규칙이 갈라지지 않는다. */
  if (!계약담김 && !수집담김) return 0;

  const 계약원문 = 판본(계약담김 ? '' : 'HEAD', 계약경로);
  const 수집뒤 = 판본(수집담김 ? '' : 'HEAD', 수집경로);
  if (계약원문 === null || 수집뒤 === null) {
    말(`[계약동봉] 재료가 없어 동봉 대조를 **못 했다**(계약=${계약원문 === null ? '없음' : '있음'} · 조립부=${수집뒤 === null ? '없음' : '있음'}) — 막지 않는다.`);
    return 0;
  }

  let 계약;
  try {
    계약 = JSON.parse(계약원문);
  } catch (e) {
    말(`[계약동봉] 커밋될 계약 JSON 이 파싱되지 않는다 — ${e.message}`);
    말('  깨진 계약은 모든 파생 검사를 통째로 무의미하게 만든다. 고친 뒤 다시 커밋한다.');
    return 1;
  }

  const 뒤 = 없는항목필드(계약, 수집뒤);
  if (!뒤.잼) {
    말(`[계약동봉] 동봉 대조를 **못 했다** — ${뒤.왜}`);
    말('  막지 않는다(따를 수 없는 처방은 우회를 정상 통로로 만든다). 옛 사후 회귀 `tests/계약.test.js` 는 08-19 대청소(e75fc7fc)로 걷혔다 — 지금 이 자리를 상시로 보는 기계는 이 검사기뿐이다.');
    return 0;
  }

  /* 「이번 커밋이 새로 낸 구멍」을 가르려면 앞뒤 둘 다 같은 자로 재야 한다 —
   * HEAD 를 못 재면 「깨끗했다」가 아니라 **모름**이고, 모름을 0으로 두면 남의 옛 구멍이
   * 전부 내 것으로 셈해져 무한 차단이 된다. 그래서 못 잰 앞은 「뒤와 같다」로 접는다. */
  const 계약앞원문 = 판본('HEAD', 계약경로);
  const 수집앞 = 판본('HEAD', 수집경로);
  let 앞없는칸 = 뒤.없는칸;
  if (계약앞원문 !== null && 수집앞 !== null) {
    try {
      const 앞 = 없는항목필드(JSON.parse(계약앞원문), 수집앞);
      if (앞.잼) 앞없는칸 = 앞.없는칸;
    } catch (_) { /* HEAD 가 깨져 있었다 — 앞을 못 잰다. 위 기본값(=뒤)이 그대로 산다 */ }
  }

  const 새구멍 = 뒤.없는칸.filter((f) => !앞없는칸.includes(f));

  if (새구멍.length) {
    말(`[계약동봉] 차단 — 이 커밋이 계약에 칸을 늘리는데 픽스처 조립부가 안 따라온다: ${새구멍.map((f) => `「${f}」`).join(' · ')}`);
    말('');
    말('  이대로 커밋하면 동봉이 HEAD 에서 갈린다(옛 회귀 `tests/계약.test.js` 는 08-19 대청소로 걷혀 지금 빨개지는 자리는 이 검사기다). 그 적색은 고친 사람이 아니라');
    말('  그 뒤 커밋하는 **모든 세션의 배포**를 막는다 — 같은 형태가 v9.173·v9.220 두 번 났다.');
    말(`  ⚠ 작업본은 초록일 수 있다: 커밋 범위(\`-- 경로\`)에서 \`${수집담김 ? 계약경로 : 수집경로}\` 가 빠지면 HEAD 만 깨진다(F302).`);
    말('');
    말(`  → 조립부에 그 칸을 만들고 **같은 커밋에** 담는다:  git add -- ${수집경로} 계약/  &&  git commit …`);
    말(`     자리: ${수집경로} 의 \`항목.push({\` 블록 (\`${새구멍[0]}: …\` 를 더한다)`);
    말('     비워 둘 칸이라도 **이름은 박는다** — 없으면 채점기가 `fx.칸 || []` 로 읽어');
    말('     「검사 통과」와 「검사 안 함」이 같은 모양이 된다(v9.173 실사고).');
    말(`  → 늘린 칸이 픽스처 형식이 아니라면 계약의 \`픽스처_항목필드\` 가 아니라 다른 절에 넣는다.`);
    return 1;
  }

  /* ── 판 번호 대조 (동봉과 같은 새구멍 규약) — ⚠ 동봉 경고의 조기 반환보다 «앞»이다.
   *    뒤에 두면 남의 옛 fixture 구멍이 남아 있는 동안 판 갈림 커밋이 조용히 지나간다(codex P2 637f585d). ── */
  const 판뒤 = 판대조(계약, 수집뒤);
  if (!판뒤.잼) {
    말(`[계약판] 판 번호 대조를 **못 했다** — ${판뒤.왜} · 막지 않는다(「못 쟀다」는 「깨끗하다」가 아니다).`);
  } else if (판뒤.갈림) {
    let 앞갈림 = true; // HEAD 를 못 재면 「뒤와 같다」로 접는다(동봉 대조와 같은 까닭)
    try {
      const 판앞 = 판대조(JSON.parse(판본('HEAD', 계약경로) || 'null'), 판본('HEAD', 수집경로) || '');
      if (판앞.잼) 앞갈림 = 판앞.갈림;
    } catch (_) { /* HEAD 가 깨져 있었다 — 기본값 유지 */ }
    if (!앞갈림) {
      말(`[계약판] 차단 — 이 커밋이 판을 가른다: 계약 \`버전\` = ${판뒤.계약판} vs SCHEMA_VER = '${판뒤.상수판}'.`);
      말('  판 번호는 «행에 박히는» 값이라, 갈린 채 쓰인 행은 영원히 그 판이다(소급 기입 금지 — c11 실사고 그대로).');
      말(`  → 계약 판을 올리는 손이 **같은 커밋에서** ${수집경로} 의 SCHEMA_VER 를 고친다:  git add -- ${계약경로} ${수집경로}`);
      return 1;
    }
    말(`[계약판] ⚠ 판이 이미 갈려 있다(계약 ${판뒤.계약판} vs 상수 '${판뒤.상수판}') — 이 커밋이 낸 것은 아니라 막지 않는다. 주인을 찾아 알린다.`);
  } else {
    말(`[계약판] 계약 버전 = SCHEMA_VER = '${판뒤.상수판}' — 일치.`);
  }

  if (뒤.없는칸.length) {
    말(`[계약동봉] ⚠ 조립부에 없는 계약 칸 ${뒤.없는칸.length}건 — ${뒤.없는칸.map((f) => `「${f}」`).join(' · ')}`);
    말('  **이 커밋이 낸 것은 아니다**(HEAD 에 이미 있었다) — 막지 않는다. 남의 옛 구멍으로 내 커밋을 막으면');
    말('  그게 이 가드가 없애려는 피해 그 자체다. 다만 스위트는 이미 빨갛다 — 주인을 찾아 알린다.');
    사각보고();
    return 0;
  }

  말(`[계약동봉] 픽스처 ${계약.픽스처_항목필드.length}칸 전부 조립부에 있다 — 통과.`);
  사각보고();
  return 0;
}

/* 「검사가 자기 사각을 스스로 적는다」(§4 제안 ⓑ — 유호 08-27 진행 지시로 채택).
 *   산문 주석 속 사각은 틀려도 안 빨개진다 — 출력에 실어야 읽는 사람이 «지금» 본다. */
function 사각보고() {
  말('[사각] 이 검사가 «안» 보는 것: ①DB 실물(engine.schema_migrations 착지 — talk `tools/배포빚.js` 몫) ②형제 저장소의 착지판·src/계약판.js(그쪽 검사 몫) ③이미 쓰인 행의 판 값(소급 불가 — 어떤 검사도 못 고친다).');
}

process.exit(main());
