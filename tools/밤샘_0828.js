#!/usr/bin/env node
/**
 * 밤샘 0828 — 유호님 픽 순서대로 «전부» 굽는다 (유호 지시 08-28 「전부 부탁해 · 나 자러 갈거야」)
 *
 * ■ 순서 (유호님이 그대로 주셨다 — 바꾸지 않는다)
 *   ①녹음 셋(구조2) → ③앱 아이콘 → ①나머지 25(조작·조작2·표시2) → ②오브 19
 *   앱 아이콘은 블렌더가 아니라 크롬이라 «가볍다» — 여기 배치는 무거운 굽기 사이에 끼워도 값이 없다.
 *   그래서 아이콘은 세션이 앞에서 손으로 끝내고, 이 파일은 **블렌더 갈래 셋만** 진다.
 *
 * ■ 왜 파일로 있나 — 세션이 죽어도 살아야 한다
 *   08-24 밤 실측: 세션이 죽으면 그 세션이 띄운 굽기가 전부 같이 죽었다(222장이 그렇게 사라졌다).
 *   🔴 **세션의 `Start-Process` 는 «떼어낸 것»이 아니다** — 작업 개체(job object)에 묶여 같이 죽는다
 *      (08-26 정정). 떼려면 **WMI 로 띄운다**(아래 「띄우는 법」).
 *
 * ■ 🔴 이 밤의 새 실측 — 「부모만 죽이면 블렌더는 고아로 살아 램을 문다」 (08-28 03:47)
 *   드라이버를 실수로 둘 걸었다가 하나를 껐는데, **껴진 것은 node 부모뿐이고 blender 자식은 살아서
 *   4.6GB 를 물고 있었다.** 그 바람에 «성한» 굽기가 WorkingSet 9MB 로 굶었다(건강하면 2,000MB+).
 *   ⇒ 이 파일은 시작할 때 **고아 블렌더를 먼저 걷는다.** 그리고 「이미 돌면 물러난다」를 지킨다.
 *
 * ■ 램 문지기 (유호 지시 「노트북 프리징 걸리지않게 조절하면서」)
 *   이 기계는 16GB 온보드에 Arc 내장 GPU 가 시스템 램을 나눠 쓴다 — 굽기의 병목은 GPU 가 아니라 «램»이다.
 *   단계에 들어가기 «전»에 여유 램을 재고, 바닥(1,800MB) 아래면 회복될 때까지 기다린다.
 *   블렌더는 «끝날 때» 파일을 쓰므로 기다리다 늦어도 잃는 것은 0 이다.
 *
 * ■ 이어굽기 — 끊겨도 처음부터 안 간다
 *   세트굽기가 「이미 다 난 항목」을 건너뛴다(08-28 에 그 판정을 투명 모드까지 고쳤다 — 그 전에는
 *   영영 안 나는 `<이름>.png` 를 물어 **건너뛰기가 원리상 0** 이었다). 그러니 이 파일은 몇 번을
 *   다시 불러도 안전하다.
 *
 * 띄우는 법(PowerShell · 세션에서 떼어낸다):
 *   $cls = [wmiclass]'Win32_Process'
 *   $cls.Create('"C:\Program Files\nodejs\node.exe" "…\tools\밤샘_0828.js" > "…\밤샘.log" 2>&1', 'C:\…\SYNK-appsscript')
 *   ⇒ 그리고 트랙.md 에 「돌고 있음 + 로그 절대경로」를 적고 옆 세션에 알린다.
 *
 * 🔴 **`cmd.exe /c` 로 감싸야 한다**(08-28 실측 사고 · 내가 밟았다). 위 줄을 그대로 쓰면 안 된다:
 *   WMI `Win32_Process.Create` 는 **셸을 안 거친다** — `>` 와 로그 경로와 `2>&1` 이 리디렉션이
 *   아니라 **node 의 argv 로 그대로** 들어간다. 증상이 고약하다: 굽기는 «멀쩡히 돌고»
 *   (이 파일이 남는 argv 를 안 보니까) **로그 파일만 아예 안 생긴다.**
 *   나는 그 경로를 트랙과 옆 세션에 「여기 있다」고 알린 «뒤에» 알았다 —
 *   **없는 파일을 가리키는 안내는 없느니만 못하다.**
 *   ⇒ 바른 꼴: `cmd.exe /c ""<node>" "<이 파일>" > "<로그>" 2>&1"` (바깥 따옴표 두 겹 = cmd 규칙)
 *   🔑 그래도 밤을 버리지는 않는다: **판정은 로그가 아니라 파일이다**(이 저장소의 오랜 규율).
 *      「끝났나」는 `node tools/명품재굽기.js --검사 …` 와 산출 폴더가 답한다.
 */
'use strict';
const { spawnSync, execFileSync } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');

const 루트 = path.resolve(__dirname, '..');
const 노드 = process.execPath;
const 부품방 = 'docs/캐릭터/요소부품_0828';   // 앱용 누끼 — 지면용(요소공방_0822)과 «따로» 둔다
const 램바닥MB = 1800;
const 기다림상한분 = 45;

const 시각 = () => new Date().toLocaleTimeString('ko-KR');
const 말 = (s) => { console.log(`${s}`); try { process.stdout.write(''); } catch (_) {} };

/** PowerShell 한 줄을 돌리고 첫 줄을 돌려준다 — 실패하면 빈 문자열(문지기가 «모르면 통과»여야 한다). */
function ps(명령) {
  try {
    return String(execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', 명령],
      { encoding: 'utf8', timeout: 30000 })).trim();
  } catch (_) { return ''; }
}

const 여유램MB = () => Number(ps('[int]((Get-CimInstance Win32_OperatingSystem).FreePhysicalMemory/1KB)')) || 0;

/** 살아 있는 블렌더 수 — 내 자식은 아직 없을 때만 부른다(단계 «사이»에서만 쓴다). */
const 블렌더수 = () => Number(ps("(Get-CimInstance Win32_Process -Filter \"Name='blender.exe'\").Count")) || 0;

/** 부모가 이미 없는 블렌더를 걷는다 — 08-28 의 그 사고. 성한 굽기의 부모는 살아 있으니 안 걸린다. */
function 고아걷기() {
  const 죽인것 = ps([
    "$live=(Get-CimInstance Win32_Process|%{$_.ProcessId});",
    "$n=0; Get-CimInstance Win32_Process -Filter \"Name='blender.exe'\" | %{",
    "  if($live -notcontains [int]$_.ParentProcessId){ Stop-Process -Id $_.ProcessId -Force -EA SilentlyContinue; $n++ } };",
    '$n',
  ].join(' '));
  if (죽인것 && 죽인것 !== '0') 말(`  🧹 고아 블렌더 ${죽인것}개를 걷었다 — 램을 물고 있었다.`);
}

/** 남의 굽기가 돌면 «죽이지 않고 물러난다»(트랙 §0 겹침 규율). 램도 같이 지킨다. */
function 자리비었나(라벨) {
  const 끝시각 = Date.now() + 기다림상한분 * 60 * 1000;
  let 알렸나 = false;
  for (;;) {
    고아걷기();
    const 남 = 블렌더수();
    const 램 = 여유램MB();
    if (남 === 0 && 램 >= 램바닥MB) {
      if (알렸나) 말(`  ▶ 자리가 났다 — 램 ${램}MB · ${시각()}`);
      return true;
    }
    if (Date.now() > 끝시각) {
      말(`  ⏭ ${기다림상한분}분을 기다려도 자리가 안 났다(블렌더 ${남} · 램 ${램}MB) — ${라벨} 건너뛴다.`);
      return false;
    }
    if (!알렸나) {
      말(`  ⏳ 기다린다 — 블렌더 ${남}개 · 여유 램 ${램}MB(바닥 ${램바닥MB}) · ${시각()}`);
      알렸나 = true;
    }
    spawnSync(노드, ['-e', 'setTimeout(()=>{},60000)'], { timeout: 65000 });   // 1분
  }
}

function 단계(이름, 인자들) {
  말(`\n■ ${이름} — ${시각()}`);
  if (!자리비었나(이름)) return;
  const 시작 = Date.now();
  const r = spawnSync(노드, 인자들, { cwd: 루트, stdio: 'inherit' });
  const 분 = Math.round((Date.now() - 시작) / 60000);
  말(`■ ${이름} 끝 — 종료코드 ${r.status} · ${분}분 · ${시각()}`);
  /* 🔴 종료코드로 성패를 판정하지 «않는다» — 블렌더는 스크립트가 죽어도 0 을 낼 수 있다.
   *   판정은 각 도구가 파일 시각으로 한다(세트굽기·명품재굽기 안에 있다). 여기서는 시간만 적는다. */
}

말(`■■ 밤샘 0828 시작 — ${new Date().toLocaleString('ko-KR')} · pid ${process.pid}`);
말(`   여유 램 ${여유램MB()}MB · 블렌더 ${블렌더수()}개`);

/* ① 녹음 셋이 든 세트. 앞 세션이 이미 돌리고 있으면 여기서는 건너뛰기로 지나간다. */
단계('① 구조2 — 녹음 셋 + 파이핑·주머니·바늘·고르개·접힘 (8장 · 앱 누끼)',
  ['tools/세트굽기.js', '--세트', '구조2', '--더', '투명=1', '--샘플', '256', '--너비', '1800', '--밖', 부품방]);

/* ①나머지 — 학생이 매일 누르는 조작·표시 스무 장. */
단계('① 조작·조작2·표시2 — 20장 (앱 누끼)',
  ['tools/세트굽기.js', '--세트', '조작,조작2,표시2', '--더', '투명=1', '--샘플', '256', '--너비', '1800', '--밖', 부품방]);

/* ② 오브 19색 — 08-24 옛 자(AgX)로 난 것만. 남은 수는 도구가 «파일 시각»으로 그 자리에서 센다. */
단계('② 오브 19색 — 옛 자로 난 것만 다시 (≈3시간)',
  ['tools/명품재굽기.js', '--라이브러리만', '--이어', '2026-08-26T11:18']);

말(`\n■■ 밤샘 0828 끝 — ${new Date().toLocaleString('ko-KR')}`);
말('   🔎 아침에 볼 것: node tools/명품재굽기.js --검사 "2026-08-26T11:18" --갈래 라이브러리,오브');
말(`   🔎 앱 누끼 산출: ${부품방}  (몸·접지 두 층 · 알파가 잘려야 한다)`);
