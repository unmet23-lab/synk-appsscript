#!/usr/bin/env node
/**
 * 4D 깊이 격자 — **앱(SYNK-talk) 반입**.
 *
 * ■ 무엇을 하나
 *   마스코트 정본 누끼 PNG 에서 깊이(z)를 재서 talk `contents/깊이.json` 으로 놓는다.
 *   앱의 `src/마스코트몸.js`(Skia 격자)가 그 z 만큼 정점을 밀어 «옆을 본다»를 만든다.
 *
 * ■ 🔴 왜 필요했나 (09-02 실측)
 *   유호님이 08-26 에 직접 지시하신 「막 옆도 보고 이런 느낌」의 4D 층이 **릴에만** 돌고 있었다.
 *   학생 손의 앱은 숨·쫀득까지였다. 앱은 이미 Skia `Vertices` 격자를 쓰고 있어서,
 *   z 한 축만 얹으면 되는 자리였다 — **새 굽기 0 · 새 그림 0**.
 *
 * ■ 정본 관계 (사본이 조용히 갈라지지 않게)
 *   · 수식의 주인 = `tools/lib/깊이격자.js` 하나(릴 `영상/깊이뽑기.js` 도 같은 모듈을 부른다)
 *   · 그림의 주인 = `tools/lib/마스코트자산.js`(그것도 스스로 안 알고 `docs/디자인_토큰.json` 에서 판다)
 *   · 반입 사본 = talk `contents/깊이.json` — **대조는 talk `tests/깊이.test.js` 가 한다**
 *     (혼잣말 반입과 같은 규율 · 형제 저장소가 없으면 skip 이고 fail 이 아니다)
 *
 * ■ ⚠ 앱 그림은 336² webp, 정본은 4096² png(09-05 판올림 전에는 1024²) — 그래도 같은 격자다
 *   실측(09-02): 둘 다 정사각이고 **크롭이 없다**(축소만). z 격자는 정규화 좌표(u,v) 위에 있어
 *   픽셀 크기와 무관하다. ⇒ 정본 PNG 에서 재도 앱 그림에 그대로 맞는다.
 *   🔴 언젠가 webp 를 «잘라서» 만들면 이 전제가 깨진다 — 그때는 이 주석이 아니라
 *      talk 회귀(`tests/깊이.test.js` 의 종횡비 줄)가 먼저 운다.
 *
 * 쓰기: node tools/깊이반입.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const 저장소 = path.join(__dirname, '..');
const { 기본N: N, 앱용뽑기 } = require(path.join(저장소, 'tools', 'lib', '깊이격자.js'));
const 마스코트 = require(path.join(저장소, 'tools', 'lib', '마스코트자산.js'));

/* 어느 가이드의 어느 컷에서 재나 — **앱이 «기본»으로 그리는 바로 그 컷**이다.
 * 까닭: 깊이는 실루엣과 눈 자리에서 나오므로 컷마다 미세하게 다르다. 앱이 기본 컷 위에서
 * 표정을 갈아끼우는 구조라(마스코트.js), 기본 컷의 z 를 쓰는 것이 실물과 가장 가깝다.
 * 🔑 마린은 09-05 에 들어왔다(정본 `62a750363` · 앱 반입 talk `11cd442` 뒤). 그전에는
 *   「그림 외주 대기」로 비워 두고 앱이 몽글로 폴백했다 — 빈 칸을 비슷한 것으로 안 메운다. */
const 대상 = [
  { 가이드: '몽글', 절대: () => 마스코트.절대경로('본체', { 누끼: true }) },
  { 가이드: '까몽', 절대: () => path.join(저장소, 마스코트.까몽경로('본체', { 누끼: true })) },
  { 가이드: '마린', 절대: () => path.join(저장소, 마스코트.마린경로('본체')) },
];

const talk = path.join(저장소, '..', 'SYNK-talk');
if (!fs.existsSync(talk)) {
  console.error(`🔴 형제 저장소가 없다: ${talk} — 반입할 곳이 없다.`);
  process.exit(1);
}

/* ── 🔴 09-02 수리 — 유호님 「너무 많이 심각할정도로 찌그러져보이거든」 ──────────
 *
 * 첫 판은 z 를 격자에서 «생것 그대로» 실었고, 앱은 그것을 «몸 안 평균 대비 편차»로 썼다.
 * 실측이 둘을 드러냈다:
 *   ① **몸 안 z 최소 0.176 · 중앙 0.895** — 편차로 밀면 실루엣 가장자리가 −0.669,
 *      몸 한복판이 +0.055 다. 즉 **가장자리가 한복판보다 12배 크게, 게다가 반대 방향으로**
 *      움직인다. 테두리가 통째로 출렁이니 「찌그러짐」으로 보이는 것이 당연하다.
 *   ② **이웃 칸 사이 z 점프가 0.592**(가로) — 29칸 격자에서 한 칸 만에 z 가 절반 넘게 뛴다.
 *      앱 격자(12×14)로 겹선형 읽으면 그 급변이 «한 칸이 튀어나온 것»으로 확대된다.
 *
 * 처방 둘 (릴은 안 건드린다 — 유호님이 이미 보시고 통과시킨 판이다):
 *   ⓐ **부드럽게 2회** — 점프 0.592 → 0.194 로 줄면서 눈 봉우리는 산다(최대 1.30 → 1.13).
 *      몸 «밖»(z=0)은 이웃 평균에 안 넣는다 — 넣으면 실루엣이 번져 테두리가 흐려진다.
 *   ⓑ **「기준」을 같이 싣는다** — 앱은 `max(0, z − 기준)` 으로 민다. 기준을 몸 안 하위 10%로
 *      잡으면 **실루엣 가장자리가 0 이 되어 제자리에 못 박히고 안쪽만 미끄러진다.**
 *      이것이 「고개를 돌린다」의 실제 물리다(원기둥이 돌면 윤곽은 그대로고 무늬가 흐른다).
 *      평균을 빼는 것(첫 판)과 다르다 — 평균은 가장자리를 «음수»로 만든다.
 *      🔑 0 에서 자르므로 몸 밖(z=0)과 가장자리가 **이어진다** — 첫 판의 `zv>0` 조건문이
 *        만들던 불연속(한쪽은 0, 이웃은 크게 밀림 = 격자 찢김)이 원리적으로 사라진다.
 * ──────────────────────────────────────────────────────────────────────── */

const 격자 = {};
const 기준 = {};
const 보고 = [];
for (const { 가이드, 절대 } of 대상) {
  const 원 = 절대();
  if (!fs.existsSync(원)) {
    console.error(`🔴 ${가이드}: ${원} 이 없다 — 정본 누끼가 사라졌다.`);
    process.exit(1);
  }
  /* z 가 전부 0 이면 뽑기() 가 그 자리에서 던진다(08-26 에 실제로 죽어 있던 층이다). */
  const { z, 기준: 이기준, 눈대몸, 몸색, 통계 } = 앱용뽑기(원);
  격자[가이드] = z;
  /* 🔑 「기준」 — 앱은 `max(0, z − 기준)` 으로 민다(위 ⓑ). 실루엣은 못 박히고 안쪽만 흐른다.
   *   앱에서 매번 841칸을 정렬하지 않게 여기서 재서 준다(한 판정엔 자 하나). */
  기준[가이드] = 이기준;
  보고.push({ 가이드, 원: path.basename(원), ...통계, 몸색, 기준: 기준[가이드], 눈대몸, 편평: 통계.부드러운최대 });
}

const 나갈곳 = path.join(talk, 'contents', '깊이.json');
fs.writeFileSync(
  나갈곳,
  `${JSON.stringify(
    {
      _주:
        '⚠ 여기는 «반입 사본»이다 — 고치지 마라. 정본 수식 = SYNK-appsscript tools/lib/깊이격자.js · '
        + '그림 정본 = 〃 tools/lib/마스코트자산.js(누끼 본체). 다시 만들기 = node tools/깊이반입.js. '
        + '드리프트는 tests/깊이.test.js 가 잡는다. z 는 부드럽게 2회를 지난 값이고, 앱은 max(0, z − 기준) 으로 민다.',
      /* 🔴 «생성 시각»을 굽지 않는다(09-05 에 뺐다 · 유호 지시).
       *   있으면 그림이 하나도 안 바뀌어도 돌릴 때마다 파일이 달라져서, 「다시 구웠나」를
       *   파일 지문으로 못 잰다 — 09-05 에 정본이 갈렸는지 확인하다가 이것 때문에 헛짚었다.
       *   ⚠ 같은 무늬가 이 저장소에 이미 두 번 있었다: `예비과제굽기.js` 가 커밋 해시를
       *     구워 CI 를 닷새 빨갛게 세웠고(08-31), `강사지식빌드.js` 머리말이 그 사연을 쥔다.
       *   ⇒ **생성물에는 «내용에서 나오는 것»만 넣는다.** 언제 만들었나는 git 이 안다.
       *   읽는 곳이 없는 것을 확인하고 뺐다(talk `src`·`lib`·`tests`·`contents` 전수 0건). */
      N,
      기준,
      가이드: 격자,
    },
    null,
    0,
  )}\n`,
  'utf8',
);

console.log(`4D 깊이 반입 — ${N + 1}×${N + 1} 칸 · → ${path.relative(저장소, 나갈곳)}`);
for (const r of 보고) {
  console.log(
    `  ${r.가이드}(${r.원})  z 최대 ${r.편평.toFixed(2)}(생것 ${r.최대.toFixed(2)}) · 기준 ${r.기준}`
    + ` · 눈대몸 ${r.눈대몸.toFixed(2)}배 · 몸이 있는 칸 ${r.산것}/${r.칸}`,
  );
}
console.log(`  파일 ${(fs.statSync(나갈곳).size / 1024).toFixed(1)}KB`);
