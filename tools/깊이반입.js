#!/usr/bin/env node
/**
 * 4D 깊이 격자 — **앱(SYNK-talk) 반입**.
 *
 * ■ 무엇을 하나
 *   마스코트 정본 누끼 PNG 에서 깊이(z)를 재서 talk `contents/깊이.json` 으로 놓는다.
 *   앱의 `src/마스코트몸.js`(Skia 격자)가 그 z 만큼 정점을 밀어 «옆을 본다»를 만든다.
 *
 * ■ 🔴 왜 필요했나 (09-02 실측)
 *   유호님이 08-26 에 직접 지시하신 「막 옆도 보고 이런 느낌」의 4D 층이 **릴에만** 돌고 있었다.
 *   학생 손의 앱은 숨·쫀득까지였다. 앱은 이미 Skia `Vertices` 격자를 쓰고 있어서,
 *   z 한 축만 얹으면 되는 자리였다 — **새 굽기 0 · 새 그림 0**.
 *
 * ■ 정본 관계 (사본이 조용히 갈라지지 않게)
 *   · 수식의 주인 = `tools/lib/깊이격자.js` 하나(릴 `영상/깊이뽑기.js` 도 같은 모듈을 부른다)
 *   · 그림의 주인 = `tools/lib/마스코트자산.js`(그것도 스스로 안 알고 `docs/디자인_토큰.json` 에서 판다)
 *   · 반입 사본 = talk `contents/깊이.json` — **대조는 talk `tests/깊이.test.js` 가 한다**
 *     (혼잣말 반입과 같은 규율 · 형제 저장소가 없으면 skip 이고 fail 이 아니다)
 *
 * ■ ⚠ 앱 그림은 336² webp, 정본은 1024² png — 그래도 같은 격자다
 *   실측(09-02): 둘 다 정사각이고 **크롭이 없다**(축소만). z 격자는 정규화 좌표(u,v) 위에 있어
 *   픽셀 크기와 무관하다. ⇒ 정본 PNG 에서 재도 앱 그림에 그대로 맞는다.
 *   🔴 언젠가 webp 를 «잘라서» 만들면 이 전제가 깨진다 — 그때는 이 주석이 아니라
 *      talk 회귀(`tests/깊이.test.js` 의 종횡비 줄)가 먼저 운다.
 *
 * 쓰기: node tools/깊이반입.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const 저장소 = path.join(__dirname, '..');
const { 기본N: N, 뽑기 } = require(path.join(저장소, 'tools', 'lib', '깊이격자.js'));
const 마스코트 = require(path.join(저장소, 'tools', 'lib', '마스코트자산.js'));

/* 어느 가이드의 어느 컷에서 재나 — **앱이 «기본»으로 그리는 바로 그 컷**이다.
 * 까닭: 깊이는 실루엣과 눈 자리에서 나오므로 컷마다 미세하게 다르다. 앱이 기본 컷 위에서
 * 표정을 갈아끼우는 구조라(마스코트.js), 기본 컷의 z 를 쓰는 것이 실물과 가장 가깝다.
 * 🔑 마린 칸은 **없다** — 그림 외주 대기. 빈 칸을 비슷한 것으로 안 메운다(앱은 몽글로 폴백). */
const 대상 = [
  { 가이드: '몽글', 절대: () => 마스코트.절대경로('본체', { 누끼: true }) },
  { 가이드: '까몽', 절대: () => path.join(저장소, 마스코트.까몽경로('본체', { 누끼: true })) },
];

const talk = path.join(저장소, '..', 'SYNK-talk');
if (!fs.existsSync(talk)) {
  console.error(`🔴 형제 저장소가 없다: ${talk} — 반입할 곳이 없다.`);
  process.exit(1);
}

const 격자 = {};
const 중심 = {};
const 보고 = [];
for (const { 가이드, 절대 } of 대상) {
  const 원 = 절대();
  if (!fs.existsSync(원)) {
    console.error(`🔴 ${가이드}: ${원} 이 없다 — 정본 누끼가 사라졌다.`);
    process.exit(1);
  }
  /* z 가 전부 0 이면 뽑기() 가 그 자리에서 던진다(08-26 에 실제로 죽어 있던 층이다). */
  const { z, 몸색, 통계 } = 뽑기(원);
  격자[가이드] = z;
  /* 🔑 «몸 안 평균»을 같이 싣는다 — 앱은 절대 z 가 아니라 **이 값 대비 편차**로 민다.
   *   까닭이 화면 크기에 있다: 릴의 마스코트는 540~1080px 인데 앱은 **84px** 이다.
   *   같은 세기(시차 0.075)를 쓰면 눈의 이동이 ±0.6px 이라 **안 보인다**(계산 09-02).
   *   세기를 그냥 올리면 이번엔 몸 «전체»가 왔다 갔다 하는데, 앱은 바깥 Animated.View 가
   *   이미 부유·기울기를 돌리고 있어 흔들림 축이 겹친다(릴에서 유호님이 「멀미」로 잡으신 그 축).
   *   ⇒ 평균을 빼면 **몸 전체는 제자리에 서고 눈·돌출부만 앞서 움직인다** — 84px 에서
   *      「고개를 돌렸다」로 읽히는 것은 절대 이동이 아니라 바로 그 **어긋남**이다.
   *   앱에서 매번 841칸을 평균 내지 않게 여기서 재서 준다(한 판정엔 자 하나). */
  중심[가이드] = Math.round(통계.평균 * 1000) / 1000;
  보고.push({ 가이드, 원: path.basename(원), ...통계, 몸색 });
}

const 나갈곳 = path.join(talk, 'contents', '깊이.json');
fs.writeFileSync(
  나갈곳,
  `${JSON.stringify(
    {
      _주:
        '⚠ 여기는 «반입 사본»이다 — 고치지 마라. 정본 수식 = SYNK-appsscript tools/lib/깊이격자.js · '
        + '그림 정본 = 〃 tools/lib/마스코트자산.js(누끼 본체). 다시 만들기 = node tools/깊이반입.js. '
        + '드리프트는 tests/깊이.test.js 가 잡는다.',
      _생성: new Date().toISOString(),
      N,
      중심,
      가이드: 격자,
    },
    null,
    0,
  )}\n`,
  'utf8',
);

console.log(`4D 깊이 반입 — ${N + 1}×${N + 1} 칸 · → ${path.relative(저장소, 나갈곳)}`);
for (const r of 보고) {
  console.log(
    `  ${r.가이드}(${r.원})  z 최대 ${r.최대.toFixed(2)} · 몸 안 평균 ${r.평균.toFixed(2)}`
    + ` · 몸이 있는 칸 ${r.산것}/${r.칸} · 몸색 rgb(${r.몸색.join(',')})`,
  );
}
console.log(`  파일 ${(fs.statSync(나갈곳).size / 1024).toFixed(1)}KB`);
