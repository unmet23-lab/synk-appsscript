function 유물검증(유물) {
  const 이곳 = 유물.filter((i) => !i.저장소).map((i) => String(i.파일).replace(/\\/g, '/'));
  const 형제 = [...new Set(유물.filter((i) => i.저장소).map((i) => i.저장소))];
  /* 🔑 「둘 다 비면 빈 배열」 방어는 **두지 않는다** — 호출부가 `유물.length` 로 이미 막고 있어
   *   도달할 수 없고, 도달 못 하는 방어는 변이가 안 잡힌다(실측 2026-08-08 · 변이 ⑤ 통과 =
   *   그 줄을 지워도 회귀가 전부 초록이었다). 없는 것보다 나쁜 건 있는데 안 도는 것이다. */
  const 줄 = ['   ⚠ **이어받기 전에 초록인지 먼저 잰다** — 유물은 빨간 채로 남을 수 있고, 미커밋이라 CI 가 원리상 못 본다(F247).'];
  const 따옴 = (fs_) => fs_.map((f) => `"${f}"`).join(' ');
  const 테스트 = 이곳.filter((f) => /(^|\/)tests\/.+\.test\.js$/.test(f));
  if (테스트.length) 줄.push(`     · 회귀: node --test ${따옴(테스트)}`);
  // 테스트가 아닌 코드·설정 — 구문검사는 값싸고, 깨진 판은 이 층에서 먼저 걸린다.
  const 코드 = 이곳.filter((f) => /\.(js|mjs|cjs)$/i.test(f) && !테스트.includes(f));
  if (코드.length) {
    const 앞 = 코드.slice(0, 6);
    줄.push(`     · 구문: node --check ${따옴(앞)}`
      + (코드.length > 앞.length ? `  (외 ${코드.length - 앞.length}건 — 전량은 위 목록)` : ''));
  }
  if (이곳.length && !테스트.length && !코드.length) {
    줄.push('     · 코드가 아니라 돌릴 검사가 없다 — 그래도 **내용은 읽고** 커밋한다(문서도 낡은 채 실린다).');
  }
  if (형제.length) {
    줄.push(`     · 형제 ${형제.join('·')} 의 유물은 **그 저장소에서 따로 잰다**: `
      + 형제.map((s) => `node --test 를 \`../${s}\` 에서`).join(' · '));
  }
  줄.push('     · 빨갛거나 못 쟀으면 **커밋하지 않는다** — 그대로 실으면 빨간 판이 master 로 간다(F225).');
  return 줄;
}
