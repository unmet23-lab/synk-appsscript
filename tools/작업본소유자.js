/** 내가 만진 경로를 **내 뒤에 남이 커밋**했는가 (F187·F188 · 2026-08-07).
 *
 * ■ 왜 위 판정으로는 원리적으로 안 보이나
 *   `판정들` 은 전부 **미커밋 목록**(`git status`)에서 출발한다. 그래서 같은 사건의 두 좌석이
 *   둘 다 사각이다:
 *     · **F187** — 경로가 더럽긴 한데 판정은 `내것`이라 조용하다. 내 작업본이 남의 커밋을
 *       안 담았으면 그대로 커밋할 때 남의 줄이 **삭제로** 실린다. git 은 오류를 안 낸다.
 *     · **F188** — 내 수정이 남의 커밋에 덮여 경로가 **깨끗해졌다**. 깨끗하면 `git status` 에
 *       아예 안 올라와서 이 도구가 못 본다. 증상은 「조용함」뿐이고, 내가 「측정했다」고 적은
 *       숫자만 근거를 잃는다.
 *   둘은 한 사건의 양쪽 좌석이라 **질문 하나**로 잰다: *내가 만진 뒤 남이 그 경로를 커밋했는가.*
 *   더러움/깨끗함은 그 답에 붙는 **꼬리표**이지 별개 검사가 아니다(두 검사로 적으면 갈라진다).
 *
 * ■ 시계 — 커밋 그래프가 아니라 시각이다
 *   `baseline` SHA 를 못 쓴다: 형제(`../SYNK-talk`)의 커밋은 이 저장소 이력에 없어
 *   `기준..HEAD` 안에 원리적으로 못 들어간다. 그래서 경로별 `dirtyChecked` 스탬프를 쓴다 —
 *   **내가 그 경로를 마지막으로 만진 때**다. 그 뒤 커밋만 센다(다시 만졌다면 그때 현재 내용을
 *   읽었으므로 스테일이 아니다). `%ct` 는 초 단위라 1초를 얹어 **더 보여주는 쪽**으로 틀린다.
 *
 * ■ 형제도 본다 — 그리고 못 봤으면 못 봤다고 말한다
 *   F187·F188 은 **둘 다 talk 파일**에서 났다. 형제를 빼면 등재된 실사고 두 건을 다 놓친다.
 *   저장소 목록은 `store.siblings` 고정 후보 그대로다(🚫 디렉터리 전수 탐색 — 넓히면 남의 트리가
 *   판정에 끌려온다). 스탬프가 없거나 git 이 실패한 경로는 **못잼으로 센다** — 안 잰 것과
 *   0건이 같은 모양이면 이 장치는 있으나 마나다.
 *
 * ■ 주인은 트레일러로 가른다
 *   `Session-Id` 가 없으면 **남이라고 단정하지 않는다** — 형제엔 스탬퍼가 늦게 붙어 주인 없는
 *   커밋이 남아 있다(F144). 목록에는 넣되 ❔로 표시한다(모름은 안전이 아니다).
 *
 * ■ 공용 장부는 뺀다
 *   보드·마찰장부는 **모든 세션이 규약상 만진다.** 안 빼면 매 세션 울려서 그 순간부터 아무도
 *   안 읽는다(track-collision 이 신설 당일 실측한 그 자리). 목록은 `store.공용장부` 하나다.
 */
function 뒤늦은남의커밋(나, ss, 더러움) {
  const 빈 = { 항목: [], 못잼: 0 };
  if (!나) return 빈;
  const 내 = ss.find((s) => s.sid === 나);
  if (!내 || !내.touched.length) return 빈;
  const 장부 = new Set(store.공용장부);

  /* 저장소별로 묶어 **git 을 저장소당 한 번** 부른다 — 경로마다 부르면 만진 파일 수만큼 프로세스가 뜬다. */
  const 묶음 = new Map();
  let 못잼 = 0;
  for (const 좌표 of 내.touched) {
    let 뿌리 = ROOT; let 상대 = 좌표; let 저장소 = null;
    for (const s of store.siblings(ROOT)) {
      const 접두 = store.siblingPrefix(s.저장소);
      if (좌표.startsWith(접두)) { 뿌리 = s.뿌리; 상대 = 좌표.slice(접두.length); 저장소 = s.저장소; break; }
    }
    if (장부.has(상대)) continue;
    const 언제 = Number(내.검사시각[좌표] || 0);
    if (!언제) { 못잼 += 1; continue; }
    if (!묶음.has(뿌리)) 묶음.set(뿌리, { 저장소, 경로들: [] });
    묶음.get(뿌리).경로들.push({ 상대, 언제, 좌표 });
  }

  const 결과 = [];
  for (const [뿌리, { 저장소, 경로들 }] of 묶음) {
    const 가장이른 = Math.min(...경로들.map((p) => p.언제));
    const out = git(['log', `--since=@${Math.floor(가장이른 / 1000)}`, '--no-merges', '--name-only',
      `--format=%x01%H${SEP}%ct${SEP}%(trailers:key=Session-Id,valueonly)`,
      '--', ...경로들.map((p) => p.상대)], 뿌리);
    if (out === null) { 못잼 += 경로들.length; continue; }

    /* `--name-only` 는 커밋 머리줄 뒤에 경로들을 늘어놓는다. 머리줄은 SOH 로 시작하므로
     * 그 한 글자로 가른다 — 경로에 개행이 없다는 가정만 쓴다(git 이 그런 경로는 따옴표로 싼다). */
    const 걸린 = new Map();
    let 지금 = null;
    for (const 줄 of out.split(/\r?\n/)) {
      if (줄.startsWith(머리)) {
        const [해시, ct, 주인] = 줄.slice(머리.length).split(SEP);
        지금 = { 해시: String(해시 || '').slice(0, 7), 때: (Number(ct) || 0) * 1000, 주인: String(주인 || '').trim() };
        continue;
      }
      if (!지금 || !줄) continue;
      if (!걸린.has(줄)) 걸린.set(줄, []);
      걸린.get(줄).push(지금);
    }

    for (const p of 경로들) {
      // 초 단위 절삭 보정 1초 — 같은 초에 든 커밋을 놓치느니 한 번 더 보여준다.
      const 커밋 = (걸린.get(p.상대) || []).filter((c) => c.때 + 1000 >= p.언제 && c.주인 !== 나);
      if (커밋.length) 결과.push({ 파일: p.상대, 저장소, 더럽나: 더러움.has(p.좌표), 커밋 });
    }
  }
  return { 항목: 결과, 못잼 };
}

function 조사() {
  const 나 = store.safeId(process.env.CLAUDE_CODE_HOST_SESSION_ID || '');
  const ss = 세션들();
  const 파일들 = 미커밋들();
  if (파일들 === null) {
    return {
      git못부름: true, 나, 항목: [], 세션수: ss.length, 못본형제: [], 원격: null, 보드: null,
      뒤늦음: { 항목: [], 못잼: 0 },   // 모양을 맞춘다 — 소비자가 갈래마다 다른 값을 보면 갈라진다
      배포뒤처짐: null,               // null = 못 잼(0건 아님) · 위 갈래는 git 자체를 못 부른 자리다
    };
  }

  const 항목 = 판정들(파일들, ss, 나, ROOT, null);
  /* 형제 저장소도 **같은 판정**을 거친다. 못 읽으면 건너뛰지 않고 이름을 들고 나간다 —
   * 「형제를 못 봤다」와 「형제가 깨끗하다」가 같은 모양이면 이 확장이 있으나 마나다. */
  const 못본형제 = [];
  for (const { 뿌리, 저장소 } of store.siblings(ROOT)) {
    const 목록 = 미커밋들(뿌리);
    if (목록 === null) { 못본형제.push(저장소); continue; }
    항목.push(...판정들(목록, 형제세션들(뿌리, 저장소, ss), 나, 뿌리, 저장소));
  }
  /* 「지금 내 작업본이 더러운가」의 좌표를 `touched` 와 **같은 공간**으로 맞춘다(형제는 접두를 붙인다).
   * ⚠ 다른 작업 트리(`트리`)의 미커밋은 여기서 뺀다 — 그건 내 작업본이 아니라 남의 트리다. */
  const 더러움 = new Set(항목
    .filter((i) => !i.트리)
    .map((i) => (i.저장소 ? store.siblingPrefix(i.저장소) + i.파일 : i.파일)));

  return {
    git못부름: false, 나, 항목, 세션수: ss.filter(살았나).length, 못본형제,
    원격: 원격대기(), 보드: 보드선점(ROOT, 나), 뒤늦음: 뒤늦은남의커밋(나, ss, 더러움),
    배포뒤처짐: 배포뒤처짐(),
  };
}

