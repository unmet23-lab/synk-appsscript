    /* 착수 표식만 본다 — ✅종결 줄의 꼬리가 낡는 것은 다른 축이고(F256) 처방도 다르다(그쪽은 이관이 답). */
    if (칸.length < 4 || !(칸[3] || '').includes('🔵')) continue;
    const 지문 = r.파일.replace(/\.md$/, '');
