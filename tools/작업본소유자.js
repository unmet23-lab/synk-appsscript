// 왜 있나:
//   세션 시작 시 `git status` 는 **두 가지를 같은 모양으로** 보여준다.
//     ⓐ 전 세션이 남기고 끝난 미완 → 이어받는 게 맞다
//     ⓑ 지금 살아서 돌고 있는 남의 작업본 → 손대면 사고다
//   F073 실사고: 보드의 「진행중」 줄을 ⓐ로 읽고 편집했는데 실제로는 ⓑ였고,
//   내 편집이 6분 뒤 남의 커밋에 그대로 실려 나갔다(uncommitted-swept-by-peer 의 반대 방향).
