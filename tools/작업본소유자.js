    줄.push('   **모름은 안전이 아니다** — 만지기 전에 그 저장소에서 직접 본다:');
    줄.push(`   git -C ../${Object.keys(저장소별)[0]} status  ·  git -C ../${Object.keys(저장소별)[0]} log --oneline -5`);
