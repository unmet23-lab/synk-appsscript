//
//   🔑 정보가 없었던 게 아니다 — **아무도 안 읽고 있었다.**
//      `track-collision` 훅이 세션마다 `track-<프로젝트>-<세션>.json` 에 만진 파일 목록을
//      이미 쌓고 있고, 그 파일의 mtime 이 곧 심장박동이다. 이 도구는 **읽는 쪽**이다.
//      (쓰는 쪽은 그 훅 소유다 — 여기서 다시 구현하지 않는다. 판정층을 둘로 만들면 갈라진다.)
