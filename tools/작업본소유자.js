#!/usr/bin/env node
// 작업본소유자 — 「이 미커밋 변경은 누구 것인가」 (F073)
//
// 왜 있나:
//   세션 시작 시 `git status` 는 **두 가지를 같은 모양으로** 보여준다.
//     ⓐ 전 세션이 남기고 끝난 미완 → 이어받는 게 맞다
//     ⓑ 지금 살아서 돌고 있는 남의 작업본 → 손대면 사고다
//   F073 실사고: 보드의 「진행중」 줄을 ⓐ로 읽고 편집했는데 실제로는 ⓑ였고,
//   내 편집이 6분 뒤 남의 커밋에 그대로 실려 나갔다(uncommitted-swept-by-peer 의 반대 방향).
//   같은 트랙 병렬 3번째다(F070 가드 중복 · 크루카드 포크).
//
//   🔑 정보가 없었던 게 아니다 — **아무도 안 읽고 있었다.**
//      `track-collision` 훅이 세션마다 `track-<프로젝트>-<세션>.json` 에 만진 파일 목록을
//      이미 쌓고 있고, 그 파일의 mtime 이 곧 심장박동이다. 이 도구는 **읽는 쪽**이다.
//      (쓰는 쪽은 그 훅 소유다 — 여기서 다시 구현하지 않는다. 판정층을 둘로 만들면 갈라진다.)
//
// ⚠ 「모름」을 「안전」으로 바꾸지 않는다.
//    Edit·Write 를 안 거친 변경(Bash 스크립트·외부 앱·git 조작)은 만진 기록이 없다.
//    그건 ⓐ도 ⓑ도 아니라 **❔모름**이고, 그렇게 표시한다. 실측에서 14건 중 8건이 이랬다.
//
// 쓰는 법
//   node tools/작업본소유자.js          사람용 표
//   node tools/작업본소유자.js --hook   SessionStart 훅용 — 🔴가 있을 때만 말한다
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

// SYNK_OWNER_ROOT = **보는 저장소**만 바꾸는 이음매(로직은 안 끈다 · SYNK_TRACK_ROOT 와 같은 패턴).
const ROOT = process.env.SYNK_OWNER_ROOT || path.resolve(__dirname, '..');
// ⚠ lib 는 ROOT 가 아니라 **이 파일 옆**에서 가져온다 — lib 은 이 저장소가 배포하는 것이고
//   ROOT 는 「어느 작업 트리를 보느냐」일 뿐이다. ROOT 기준으로 require 하면 픽스처마다
//   lib 사본을 깔아야 하고, 그건 곧 판정기가 갈라진다는 뜻이다.
const store = require(path.join(__dirname, '..', '.claude', 'hooks', 'lib', 'handoff-store.js'));
// 표 칸 가르기는 이 한 통로만 쓴다 — 날 `split('|')` 은 백틱 안 파이프에서 칸을 밀어낸다(F119·F253).
const { 칸나누기 } = require(path.join(__dirname, 'lib', '표.js'));
const 보드lib = require(path.join(__dirname, 'lib', '보드.js'));   // 커밋된 보드 줄 = 정본 폴더 파생(F250)
/* 「세션 id → 보드 지문 8자리」도 여기 다시 적지 않는다 — 접두를 떼는 규칙이 갈라지면
 * 내 줄을 남의 선점으로 읽는다(실측: `local_` 를 안 뗀 판이 내 선언을 그대로 띄웠다 · F165). */
const { 지문: 보드지문 } = require(path.join(__dirname, '..', '.claude', 'hooks', 'lib', 'board-id.js'));

/* 워크트리 — 이 도구의 사각지대였다 (F079 · 옆 세션 local_dee95eb9 이 실사고로 잡아 넘겼다).
 * 두 겹이었고 **둘 다 「보이는 것이 0건」으로 조용히 새는** 방향이다:
 *   ⓐ `git status` 는 자기 트리만 본다 — 실측: 옆 트리가 2건을 들고 있는데 메인은 0건으로 셌다.
 *   ⓑ 🔴 더 깊은 것 — 상태 파일 접두의 `projectKey` 가 **트리마다 다르다**
 *      (실측: 메인 cec367f48f vs 워크트리 1fc2df68ae·9514265e22·80c1561a3e).
 *      감지 로직을 아무리 고쳐도 **재료가 갈라져 있어** 워크트리 세션은 파일 목록에서부터 안 잡힌다.
 * 처방 = 쓰는 쪽(track-collision)이 **메인 트리 키로 통일**했고(ba17f78), 읽는 이쪽도 같은 키를 쓴다.
 *   메인에서 돌 때 값이 안 변하므로 오늘의 계약은 안 깨진다 — 넓히기만 한다. */
let wt = null;
try { wt = require(path.join(__dirname, '..', '.claude', 'hooks', 'lib', 'worktrees.js')); } catch (_) { wt = null; }

/** 상태 파일 접두의 기준 — 트리가 달라도 **메인 하나로** 모은다. lib 이 없으면 옛 동작 그대로. */
function 키기준(r) {
  if (!wt) return r;
  try { return wt.mainWorktree(r) || r; } catch (_) { return r; }
}

/** 심장박동 유효 시간. 이보다 오래된 세션은 「끝난 것」으로 본다.
 *  짧게 잡으면 살아있는 세션을 죽었다고 해 사고가 나고(위험한 방향),
 *  길게 잡으면 끝난 세션을 살아있다고 해 조심하게 된다(안전한 방향). 그래서 넉넉히 잡는다. */
const 살아있음_분 = Number(process.env.SYNK_OWNER_ALIVE_MIN || 30);

/** 지금 이 프로세스의 세션 id. 심장박동을 **재지 않아도 되는 유일한 세션**이다 — 내가 돌고 있다. */
const 나지금 = store.safeId(process.env.CLAUDE_CODE_HOST_SESSION_ID || '');

/** 심장박동이 아직 뛰는가. 인계문수거(F111)도 **이 판정 하나**를 쓴다 — 살았다/죽었다를
 *  두 곳에 적으면 갈라지고, 갈라진 쪽의 증상은 「살아있는 세션의 인계문을 거둬 감」이다.
 *
 * 🔑 **F252 의 죽음 도장을 여기 넣지 않은 것은 의도다**(다음 사람이 「빠뜨렸다」고 읽지 않게).
 *   도장은 ⚪(= 남의 작업본을 커밋해도 된다)를 낼 때만 요구한다 — 되돌림 비용이 거기서만 크다.
 *   이 판정의 다른 소비자들은 비용이 반대다: 인계문수거가 쉬는 세션의 인계문을 일찍 거두면
 *   그 세션이 다시 쓸 뿐이지만(무해), 강제 종료 탓에 영영 안 거두면 미추적으로 소멸한다(F025).
 *   auto-commit·board-move 도 같다 — 여기에 도장을 요구하면 새는 방향이 「소멸」로 뒤집힌다.
 *
 * 🔴 **나 자신은 심장박동으로 재지 않는다** (F264 · 2026-08-09 실사고). 박동은 `Edit|Write|MultiEdit`
 *   에서만 뛰는데(track-collision 매처) 「살아있나」로 소비된다 — 그래서 선언만 써 두고 30분 넘게
 *   읽기·조사만 한 세션은 **자기 파일을 자기 것으로 증명하지 못한다**: 판정이 `내것`→`❔모름`으로
 *   떨어지고 git-scope-guard ⑧ 이 자기 커밋을 막는다(실측: 3회차 탈출구로야 통과). 위 F252 가
 *   「쉬는 세션과 죽은 세션이 같은 모양」이라 한 그 병인데, **나에 대해서는 프록시가 필요 없다** —
 *   이 코드가 도는 것 자체가 증거다. 남에 대해서는 그대로 박동을 본다(도장 규칙 무수정). */
const 살았나 = (s) => (나지금 !== '' && s.sid === 나지금) || s.분 <= 살아있음_분;

/** SessionEnd 죽음 도장이 찍혔나 — 「침묵」과 「끝남」을 가르는 유일한 재료다(F252 · `끝남` 필드). */
const 마감했나 = (s) => !!(s && s.끝남) && !(나지금 !== '' && s.sid === 나지금);

/**
 * **선언(보드 줄)의 주인으로서** 아직 살아 있나 — 남의 줄을 «옮기거나 겹침으로 막는» 소비자용.
 * 지금 소비자 둘: `board-move` 원칙⑥ · `board-guard` ⑧(겹침 차단). 둘이 서로 다른 생사를 보면
 * 한쪽은 막고 한쪽은 통과시키는 **따를 수 없는 처방**이 되므로 판정을 여기 하나로 둔다.
 *
 * 🔴 왜 `살았나` 로는 안 되나 (F304 · 2026-08-12 실측):
 *   `살았나` 는 심장박동 30분 창이라 **승계 자리에서 언제나 참이다** — 인계는 앞 세션이 끊긴
 *   «직후»에 일어나므로, 승계 세션이 board-move 를 두드리는 시각은 **원리상 늘 창 안**이다.
 *   그래서 board-guard 가 내주는 처방(「죽은 세션의 줄이면 board-move 로 치운다」)이 가리키는
 *   문은 승계 자리에서 30분간 항상 잠겨 있었다 — 장치를 달아 놓고 그 처방을 다른 가드가
 *   막는 F103 그 모양이고, 막힌 쪽에 남는 출구는 우회뿐이다.
 *   실측 08-12: 도장이 찍혔는데 `살았나` 가 「살았다」로 세는 세션이 **4건**이었고, 그 줄들이
 *   활성/전체 상한(12·18)을 각각 넘겨 **새 세션의 선언 자체가 막히는** 지경까지 갔다(20줄).
 *
 * 🔑 이 판정은 **죽음 쪽으로만** 움직인다 — 도장이 없으면 `살았나` 그대로이고, 되살아나면
 *   track-collision 이 도장을 지운다(되살아남 = 도장 없음). 그래서 `살았나` 본체는 안 건드린다:
 *   거기에 도장을 요구하면 「도장 없는 강제 종료」가 영원히 살아있음이 되어 인계문이 안 거둬지고
 *   미추적으로 소멸한다(F025 · 위 `살았나` 주석이 그것을 의도로 못박았다).
 * ⚠ **나 자신은 언제나 산 주인이다** — 내가 도는 중에 내 상태 파일에 옛 도장이 남아 있어도
 *   그 줄은 내 것이다(`살았나` 가 나를 특례로 두는 것과 같은 축 · F264).
 */
const 선언살았나 = (s) => 살았나(s) && !마감했나(s);

/* ⚪ 유물 주장의 반증 여유. 심장박동이 멎은 뒤에 바뀐 파일은 그 세션의 것일 수 없다.
 *  🔴 실사고 2026-08-04(F090): 이 도구가 `Code.js` 를 ⚪「이어받아도 된다」로 내놨는데, 실제로는
 *     **살아있는** 세션이 `node tools/bump-version.js`(Bash)로 방금 고친 것이었다. Bash 가 쓴 파일은
 *     만진 기록이 안 남고(track-collision 은 Edit·Write 만 본다), 40분 전 끝난 세션의 **옛 기록이
 *     그 자리를 이겼다.** 새는 방향은 언제나 통과다 — 그대로 이어받아 커밋했으면 F073 재현이다.
 *  그래서 유물 주장은 파일 mtime 으로 반증한다. **판정을 올리지 않고 「모름」의 범위만 넓힌다** —
 *  ⚪는 「손대도 된다」고 말하는 유일한 칸이라, 확신이 없으면 거기 두지 않는 것이 맞다.
 *  여유가 필요한 이유: track-collision 은 PreToolUse 라 상태 파일이 **파일보다 먼저** 쓰인다. */
const 유물여유_분 = Number(process.env.SYNK_OWNER_STALE_MIN || 2);

/* 형제 저장소 — 이 도구의 두 번째 사각지대였다 (F134·F137 · 2026-08-06 세 번째 재현).
 *   워크트리(위)는 **같은 저장소의 다른 체크아웃**이라 이미 세는데, `../SYNK-talk` 는
 *   **다른 저장소**라 `git status` 에 애초에 안 나온다. 그런데 이 프로젝트의 트랙은 두 저장소를
 *   함께 만진다(보드 줄 절반이 「SYNK-talk: …」다). 실측 3건 전부 **새는 방향이 「0건」**이다:
 *     F134 되감기 가드가 talk 를 향한 명령을 appsscript 상태로 판정 · F137 남이 편집 중인 talk
 *     파일을 「비었다」고 읽고 내 트랙으로 선언 · 08-06 이 세션 시작에서 talk 미커밋 3건(그 중
 *     하나는 45초 전에 쓰인 살아있는 작업본)이 이 도구 출력에 **한 줄도 안 나왔다**.
 *   목록·좌표 규칙은 여기 적지 않는다 — `lib/handoff-store.js` 하나에서 파생시킨다(쓰는 쪽
 *   track-collision 이 같은 함수를 쓴다 · 양쪽에 적으면 갈라지고 증상은 「전부 모름」이다). */

/** ⏱ 네트워크를 건너는 유일한 칸(`git fetch`)의 시간 예산. 기본은 아래 `git()` 과 **같은 5초**라
 *  이 상수만으로는 아무 행동도 안 바뀐다 — 예산에 **이름을 준 것**이 전부다.
 *  대가(새 이름의 값): 회귀가 만료를 재현할 손잡이가 생겼고(안 그러면 부하를 흉내 낼 방법이 없다),
 *  「로컬 git 이 5초 걸리는 것」과 「원격이 5초 걸리는 것」이 앞으로 따로 조정될 수 있다.
 *  🚫 값을 키우는 것은 이 신고(#Q98)의 처방이 **아니다** — 부하는 언제든 그 위로 간다(29초 회차 실측). */
const 원격시간예산_ms = Number(process.env.SYNK_OWNER_FETCH_TIMEOUT_MS || 5000);

/** ⏱ 로컬 git 한 칸의 시간 예산(F489). 위와 같은 5초라 값으로는 아무것도 안 바뀐다 — **이름을 준 것**이
 *  전부고, 그 이름이 회귀의 유일한 손잡이다(부하를 흉내 낼 다른 방법이 없다).
 *  🚫 여기서도 값을 키우는 것은 처방이 아니다 — 부하는 언제든 그 위로 간다(#Q98 29초 회차 실측). */
const 로컬시간예산_ms = Number(process.env.SYNK_OWNER_GIT_TIMEOUT_MS || 5000);

/** git 결과를 **세 갈래로** 낸다 — 「돌려 봤더니 실패」와 「시간이 다 돼 못 쟀다」는 다른 사실이다.
 *
 * 🔴 왜 갈랐나 (#Q98 · 08-15 실측): `spawnSync` 는 타임아웃 만료도 `r.error` 로 낸다. 아래 `git()`
 *   은 그걸 실패와 함께 `null` 로 접었고, 그 `null` 이 훅에서 「⚠ 원격을 **못 읽었다**(fetch 실패)」
 *   라는 **단정**으로 나갔다. 실측 회차의 origin 은 로컬 폴더라 네트워크가 아예 없었는데도 그랬다 —
 *   진짜 원인은 옆 세션들의 CI 로 node 프로세스가 40개 넘게 떠 있어 같은 파일의 검사들이
 *   0.3~2.9초 → 3~37초로 기어간 것이다. 즉 **부하가 곧 거짓 경보**였다.
 *   급소는 테스트가 아니라 실사용이다: 같은 5초가 세션 시작의 진짜 fetch 에도 걸려 있어서,
 *   노트북이 바쁘면 훅이 없는 실패를 알리고 사람을 원격 확인으로 보낸다. 따를 수 없는 경보가
 *   반복되면 그 절이 통째로 꺼진다(F103) — 그래서 **문장을 가르는 것**이 처방이다(F207 미측정≠실패).
 * ⚠ `ETIMEDOUT` 만 못쟀다로 센다 — `ENOENT`(git 자체가 없다)까지 여기 넣으면 「못 쟀다」가
 *   「git 이 없다」를 덮어, 이번엔 반대 방향으로 새는 문장이 된다. */
function git상세(args, cwd = ROOT, timeout = 로컬시간예산_ms) {
  const r = spawnSync('git', ['-c', 'core.quotepath=false', ...args], {
    cwd, encoding: 'utf8', timeout, windowsHide: true,
  });
  if (r.error && (r.error.code === 'ETIMEDOUT' || r.signal)) return { 상태: '못쟀다', 출력: null };
  if (r.error || r.status !== 0) return { 상태: '실패', 출력: null };
  return { 상태: '됨', 출력: String(r.stdout || '') };
}

