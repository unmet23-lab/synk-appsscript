/** 이 트리가 **새로 지은 것**이 있나 — F583(2026-08-17 · 시작 훅이 낸 제 경보를 재서 발굴).
 *
 * 🔴 왜 필요한가: 아래 `워크트리갇힘` 은 `rev-list --count` 로 **커밋 수**를 센다. 그런데
 *   `git merge origin/master` 로 화해만 하고 멈춘 트리(reconcile 류)는 **머지 노드 하나**만
 *   남기므로 그 값이 1 이 되고, 화면엔 F403 실사고(수리 163줄·회귀 245줄 유실)와 **똑같은
 *   최고 경보**가 나간다. 실측 `6df8320b`: 전체 1 · `--no-merges` 0 · `--cc` 빈 출력.
 *   🔑 새는 방향이 「경보」라 조용하지 않고 시끄럽다 — 그 시끄러움이 정확히 이 함수 위쪽
 *   주석이 경계한 것이다(「배경 소음이 된 경고는 진짜가 섞여도 안 읽힌다」).
 *
 * 🔑 **휴리스틱이 0이다.** 아래 `워크트리갇힘` 주석이 「기계가 못 가른다」고 적은 것은
 *   «재타이핑된 같은 수리»(patch-id)이고 그건 지금도 못 가른다 — 그 판정은 안 건드린다.
 *   여기서 가르는 것은 DAG 로 결정되는 부분집합 하나뿐이다:
 *     ① `--no-merges master..HEAD` = 0  ⇒ 내용을 지닌 커밋이 전부 이미 master 안이다.
 *     ② 그 머지들의 `diff-tree --cc` 가 전부 빔 ⇒ 손 충돌해결(evil merge)도 없다.
 *   둘이 서면 이 트리가 **새로 쓴 줄은 한 줄도 없다.**
 *
 * ⚠ 남는 것 하나(대가): 머지가 **고른 조합**(어느 쪽을 취했나)은 master 와 다를 수 있다.
 *   ①②가 서도 그건 안 잰다 — 잃는 것이 「새 줄」이 아니라 「선택」이라, 처방에 그렇게 적는다.
 * ⚠ 세 칸이다(F207) — 한 번이라도 못 재면 `잼:false` 로 내려 **시끄러운 쪽에 그대로 둔다.**
 *   모름을 「볼 것 없음」으로 접으면 새는 방향이 곧 유실이다.
 * ⚠ 비용: 갇힘 **후보에만** 부른다(보통 0건 · 그때 스폰 0). 후보가 있어도 ①이 0 아니면
 *   거기서 끝나 스폰 1회다 — 시끄러운 쪽은 어차피 전문을 받으므로 더 잴 것이 없다.
 */
function 고유내용(head, 뿌리) {
  const 못잼 = { 잼: false, 내용커밋: null, 손해결: null };
  const n = git상세(['rev-list', '--count', '--no-merges', `master..${head}`], 뿌리);
  if (n.상태 !== '됨') return 못잼;
  const 내용커밋 = Number(String(n.출력 || '').trim());
  if (!Number.isFinite(내용커밋)) return 못잼;
  if (내용커밋 > 0) return { 잼: true, 내용커밋, 손해결: null };   // 볼 것이 있다 — ②를 잴 이유가 없다
  const m = git상세(['rev-list', '--merges', `master..${head}`], 뿌리);
  if (m.상태 !== '됨') return 못잼;
  const 머지들 = String(m.출력 || '').split(/\r?\n/).filter((s) => s.trim());
  let 손해결 = 0;
  for (const sha of 머지들) {
    /* `diff-tree --cc` 는 첫 줄에 SHA 만 찍고, **모든 부모와 다른** hunk 가 있을 때만 그 아래에
     * 조합 diff 를 붙인다. 즉 「SHA 한 줄뿐」이 곧 「손으로 해결한 자리가 없다」다. */
    const d = git상세(['diff-tree', '--cc', sha], 뿌리);
    if (d.상태 !== '됨') return 못잼;
    if (String(d.출력 || '').split(/\r?\n/).filter((l) => l.trim()).length > 1) 손해결 += 1;
  }
  return { 잼: true, 내용커밋: 0, 손해결 };
}

