const 구분선인가 = (셀들) => 셀들.every((c) => /^:?-{2,}:?$/.test(c));

/** 표시용으로 다듬는다 — 백틱·굵게는 md 문법이라 시트에서 잡음이다. */
function 벗기기(s) {
  return String(s)
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\*\*([^*]*)\*\*/g, '$1')
    .trim();
}

/** 그대로 둬야 하는 것 — `{…}` 자리표시자. 검수자에게 «경고»가 아니라 «정보»로 준다. */
function 자리표시자(s) {
  const 잡힌 = String(s).match(/\{[^}\s]{1,20}\}/g);
  return 잡힌 ? [...new Set(잡힌)].join(' ') : '';
}

/* 섹션 열을 «언어 중립 코드»로 접는다 (2026-08-12 · 산출물을 눈으로 보고 잡은 자리).
 * 첫 판은 검수표 제목을 그대로 실었다 — 그랬더니 몽골인 검수자가 받는 표에
 * 「1. 주간 다이제스트 — 13조각」·「g1t01 · 과제 기한 부탁」 같은 **한국어**가 들어갔다.
 * 안내문만 몽골어로 만들고 정작 매 행에 한국어를 둔 것이라, 설계 §0 의 벽 ①이 산출물에 그대로 남았다.
 *
 * 🔑 번역 사전을 여기 두지 않는다 — 검수표 제목은 계속 바뀌고 사전은 그날부터 낡는다.
 *   대신 **코드만 뽑고, 그 코드가 무슨 뜻인지는 안내 탭 한 곳에서** 몽골어로 말한다
 *   (같은 판정을 두 곳에 적지 않는다). 못 알아보는 제목은 그대로 낸다 — 조용히 비우지 않는다. */
function 섹션코드(제목) {
  const s = String(제목 || '').trim();
  const 문항 = /\b(g\d[a-z]?\d{2,})\b/i.exec(s);
  if (문항) return 문항[1];
  const 번호 = /^(\d+)\s*[.．]/.exec(s);
  if (번호) return `§${번호[1]}`;
  return s.slice(0, 12);
}

/**
 * 검수표 md 한 벌 → 조각 배열.
 * @returns {{조각:Array, 경고:string[]}}
 */
function 조각들(묶음) {
  const 전체 = path.join(ROOT, 묶음.파일);
  if (!fs.existsSync(전체)) return { 조각: [], 경고: [`파일 없음: ${묶음.파일}`] };

  const 줄들 = fs.readFileSync(전체, 'utf8').split(/\r?\n/);
  const 조각 = [];
  const 경고 = [];
  let 섹션 = '';
  let 직전 = null;      // 구분선 앞 줄 = 머리 후보
  let 판 = null;        // 지금 표의 열 판정({원문, 초안, 열수}) · null = 검수 대상 아님
  let 표수 = 0;         // 검수 대상으로 잡힌 표 개수

  for (let i = 0; i < 줄들.length; i += 1) {
    const 줄 = 줄들[i];

    const 제목 = /^#{2,3}\s+(.*)$/.exec(줄);
    if (제목) { 섹션 = 벗기기(제목[1]); 판 = null; 직전 = null; continue; }

    if (!/^\s*\|/.test(줄)) { 판 = null; 직전 = null; continue; }

    const 셀 = 셀가르기(줄);

    if (구분선인가(셀)) {
      /* 머리에서 «누가 쓰는 열인가»를 읽는다 — 표식이 없으면 검수 대상 표가 아니다. */
      const 머리 = 직전 || [];
      const 확정 = 머리.findIndex((c) => c.includes(확정열표식));
      if (확정 < 0) { 판 = null; continue; }     // 근거표·실측표 — 조용히 지나간다(이상 아님)
      표수 += 1;
      판 = {
        열수: 머리.length,
        원문: 머리.findIndex((c) => c.includes(원문열표식)),
        초안: 머리.findIndex((c) => c.includes(초안열표식)),
      };
      /* 원문 열을 못 찾으면 확정 열 «바로 앞»을 원문으로 본다(L 처럼 「한국어」라 안 적은 표). */
      if (판.원문 < 0) 판.원문 = Math.max(0, 확정 - 1);
      continue;
    }

    if (!판) { 직전 = 셀; continue; }            // 아직 구분선 전 = 머리 후보로 들고 있는다

    /* 처방 ② — 열 수가 다르면 조용히 건너뛰지 않는다. 건너뛰면 조각이 소리 없이 사라진다. */
    if (셀.length !== 판.열수) {
      경고.push(`${묶음.파일}:${i + 1} 열 ${셀.length}개(머리는 ${판.열수}) — 이 행을 못 담았다: ${줄.slice(0, 60)}…`);
      continue;
    }

    const 한국어 = 벗기기(셀[판.원문]);
    if (!한국어) continue;                       // 빈 행(표 꼬리)은 조각이 아니다

    const 초안 = 판.초안 < 0 ? '—' : (벗기기(셀[판.초안]) || '—');
    조각.push({ 섹션: 섹션코드(섹션), 한국어, 초안, 그대로: 자리표시자(셀[판.원문]) });
  }

  /* 표식 열을 하나도 못 찾았다 = 검수표가 문구를 바꿨다. 조용한 0건이 가장 나쁜 결말이라 세운다. */
  if (표수 === 0) 경고.push(`${묶음.파일} — 「${확정열표식}」 표식이 붙은 열이 하나도 없다. 검수표 머리 문구가 바뀌었는지 본다(이 도구의 표 선별 축이다).`);

  return { 조각, 경고 };
}

