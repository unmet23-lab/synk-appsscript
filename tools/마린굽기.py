#   ■ 재질 문법은 몽글이·까몽 그대로다(세계가 갈리면 친구가 아니다):
#     · 갑옷도 **니들펠트**다 — 매끈 슬라브로 깔면 플라스틱 장난감이 된다. 짧은 퍼(0.024~0.032)로
#       눌린 펠트 면을 내고, 실루엣에만 보풀이 선다.
#     · 또렷한 것은 **광 나는 구슬** — 헬멧 렌즈가 몽글이 눈구슬의 자리를 그대로 받는다(캐치라이트 포함).
