# 펠트 마린 굽기 — 「우주 갑옷 전사」의 **킷 번역** 시안 (유호 지시 08-26 「매우 귀엽게 · 몽글이랑 까몽이 느낌」).
#
#   번역 선: 원작 조형의 복제가 아니라 **그 인상을 SYNK 공방 문법으로 옮긴 것**이다 —
#   까몽이 「투슬리스의 인상 → 잉크 펠트 · 초록 구슬눈 · 기운 지느러미」로 번역된 것과 같은 자다.
#   가져오는 인상 넷: ①거대한 둥근 어깨판 ②가로로 빛나는 헬멧 렌즈 한 쌍 ③앞으로 튀어나온
#   호흡기 주둥이 ④등 뒤 배기구 두 대. 이 넷이 있으면 3등신으로 뭉개도 «그 전사»로 읽힌다.
#
#   ■ 귀여움은 **비례가 낸다** — 원작은 8등신에 머리가 작다. 뒤집는다:
#     머리(헬멧)를 몸통보다 크게 · 다리를 뭉툭하게 · 어깨판은 «원작보다 더» 키운다.
#     어깨를 같이 키우는 것이 핵심이다. 머리만 키우면 그냥 아기가 되고, 어깨가 남아야 «전사 아기»다.
#
#   ■ 재질 문법은 몽글이·까몽 그대로다(세계가 갈리면 친구가 아니다):
#     · 갑옷도 **니들펠트**다 — 매끈 슬라브로 깔면 플라스틱 장난감이 된다. 짧은 퍼(0.024~0.032)로
#       눌린 펠트 면을 내고, 실루엣에만 보풀이 선다.
#     · 또렷한 것은 **광 나는 구슬** — 헬멧 렌즈가 몽글이 눈구슬의 자리를 그대로 받는다(캐치라이트 포함).
#     · 갑옷 판의 이음매는 용접이 아니라 **실땀**이다 — 이 공방에서 조각을 잇는 말은 바느질 하나뿐.
#   ⚠렌즈를 Coral 로 두는 것이 이 번역의 한 수다: 원작 렌즈의 붉은 빛 = SYNK 기본색.
#     빌려온 인상과 우리 색이 같은 자리에서 만난다.
#
#   ■ 받침은 밝은 천(Oat) — Lapis 갑옷은 중간 휘도라 밤천에 두면 실루엣이 먹힌다.
#
#   호출: blender --background --python tools/마린굽기.py -- 출력=... [갑옷=Lapis] [렌즈=Coral]
#         [각도=정면|우34|좌34] [품질=초벌|조율] [너비=1024] [샘플=96] [장치=CPU]
#     품질 초벌 = 형태만 보는 회전판(자식 12 · 털 35%) · 조율 = 중간판(자식 35) · 없으면 정본.
