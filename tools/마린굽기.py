        def 조각(칸, 라벨, 색이름, 털길이, 털수, 기울=0.0, 크리스=0.30, 부호=0):
            z, hz, x, hx, y, hy = 골격[칸]
            퍼(판((hx, hy, hz), (부호 * x, y, z), 기울=부호 * 기울 if 부호 else 기울, 크리스=크리스),
              라벨, 색이름, 털길이, 털수)

        for 부호 in (-1, 1):
            조각('부츠', '부츠' + str(부호), 관절색, 0.015, 3400, 크리스=0.26, 부호=부호)
            조각('다리', '다리' + str(부호), 갑옷색, 0.015, 3400, 부호=부호)
        조각('허리', '허리', 관절색, 0.013, 4600, 크리스=0.34)
        조각('흉갑', '흉갑', 갑옷색, 0.014, 19000, 크리스=0.28)

        # ── 어깨판(폴드론) — 🔑 이 캐릭터의 서명. **테 두른 판 두 겹**이다 ──────────
