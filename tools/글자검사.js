function 인자들(argv) {
  const 값 = {}, 여럿 = { 기준: [] }, 위치 = [];
  const 깃발 = new Set(['--엔진없이', '--기록', '--json']);
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (깃발.has(a)) 값[a.slice(2)] = true;
    else if (a === '--기준') 여럿.기준.push(argv[++i]);
    else if (a.startsWith('--')) 값[a.slice(2)] = argv[++i];
    else 위치.push(a);
  }
  return { 값, 여럿, 위치 };
}

