function 기준못씀(키, 판본, 파일) {
  const g = 판본?.검수?.글자;
  if (씨앗키.includes(키) && !g) return null;
  if (!g || g.결과 !== '통과') return `글자 검사 통과 기록이 없다(${g ? g.결과 : '기록 없음'})`;
  let 지문 = null;
  try { 지문 = 판본글.sha256(파일); } catch { /* 아래에서 다름으로 */ }
  if (!지문 || g.지문 !== 지문) return '글자 검사 통과 기록의 지문이 지금 영상과 다르다(검사 뒤 다시 구운 판)';
  return null;
}
/** 판본 영상 옆 렌더.json의 「인사초」(나라 인사 길이 — 판본렌더.mjs가 적는다). 기록이 없거나 인사가 없는 판은 0 */
const 인사FPS = 검사.밀기FPS; // 판본렌더.mjs · 편마다의 timeline.ts FPS — 기준 판 밀기 필터와 한 값(tools/lib/글자검사.js)
