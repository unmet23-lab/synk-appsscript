#!/usr/bin/env node
/* 보드수거 — 주인이 마감을 선언한 **완료** 줄을 아카이브로 거둔다 (F368 의 남은 절반)
 *
 * 왜 있나 (2026-08-12 · F368 앞 절반이 탐지를 세운 뒤 남은 자리):
 *   `tools/board.js` 는 이제 「이 줄의 주인이 아직 있나」를 말한다. 그런데 **치우는 손은 여전히
 *   사람**이었다 — 실측 그날 표 18줄 중 15줄이 마감한 주인의 것이었고, 새 세션이 자기 줄을
 *   선언하려면 남의 완료 줄부터 손으로 옮겨야 했다(`board-guard` 가 처방을 주긴 한다).
 *   철학 정본 ㉡ 「사람 손을 늘리는 해법을 쓰지 않는다 — 사람이 누르는 칸은 **판단이 필요한
 *   자리 하나만** 남긴다」의 정면이다. 판단이 필요 없는 자리를 기계가 가져간다.
 *
 * ■ 무엇을 거두나 — 세 조건이 **동시에** 참인 줄만
 *   ① `완료행` (상태 칸이 끝났다고 적혔다 · 판정 정본 = `tools/lib/보드.js`)
 *   ② 주인 없음 (`주인없는줄들` — 마감 도장이 찍혔거나 심장박동이 끊겼다)
 *   ③ **🎫 가 없다**
 *
 *   ③ 이 이 도구의 급소다. 완료 줄에도 🎫(이어받기 일감)가 붙는다 — 「내 트랙은 끝났고, 여기
 *   다음 사람이 집을 것이 있다」. 그 줄을 자동으로 아카이브에 넣으면 일감이 **조용히** 사라진다.
 *   이 저장소가 반복해 쓰는 원칙 그대로다: 조용한 누수가 시끄러운 비용보다 나쁘다.
 *   그래서 🎫 줄은 남기고 `board.js` 가 계속 「주인 없음 · 🎫」로 드러낸다 — 집을지 말지는
 *   실물을 열어 봐야 아는 **판단**이고, 판단은 사람 몫으로 남기는 그 한 칸이다.
 *   🚫 `--🎫포함` 같은 손잡이는 두지 않는다 — 탈출구가 곧 우회다.
 *
 * ■ 어떻게 거두나 — **직접 안 쓴다. `tools/board-move.js` 에 위임한다.**
 *   그쪽이 원칙 ①~⑥(줄끝 실측 · 메모리 검증 · 아카이브 먼저 · 한 커밋 원자 · 깨끗할 때만 ·
 *   산 주인 거절)을 이미 지고 있다. 여기서 파일을 쓰면 그 보장이 두 벌이 되고, 갈라진 쪽의
 *   증상은 **「줄이 통째로 사라졌다」**다 — F046 이 정확히 그 사고다.
 *   덤으로 산 주인 검사가 **한 번 더** 걸린다: 조사 시점과 실행 시점 사이에 되살아난 세션은
 *   board-move 가 종료 코드 6 으로 거절하고, 그건 실패가 아니라 정상 판정이다.
 *
 * ■ 못 거두면 **왜 못 거뒀는지를 낸다** (F571 · 2026-08-17 실사고)
 *   옛 판은 종료 코드만 읽어 「실패 5건」에서 멈췄다 — 사유를 `spawnSync` 로 **이미 받아 놓고**
 *   버렸다. 그날 실측: 죽은 세션의 고아 미커밋 1줄이 ①board-move 원칙⑤(모든 이관 거절)
 *   ②이 도구(완료 줄 5건) ③`git merge origin/master`(로컬 master 57 뒤 = F542·F565·F566 의
 *   방아쇠)를 **함께** 잠갔는데, board-move 가 낸 완성형 처방(F433 — 명령까지 적힌)이 3시간 넘게
 *   아무 화면에도 안 갔다. ①은 옳은 거절이고 ③은 git 의 정상 동작이다 — 몇 시간짜리로 만든 것은
 *   ②의 침묵뿐이었다.
 *   ⚠ 이 결함은 **안 도는 쪽이 아니라 도는데 쓸모없는 값을 내는 쪽**으로 샜다(CLAUDE.md 가드
 *     맹점 ④). 훅은 매 세션 발화했고 「실패 5건」은 실패를 정확히 보고했다 — 그래서 아무도
 *     결함으로 안 읽었다. 조용한 실패가 아니라 **시끄러운데 못 따를 실패**다.
 *   🔑 사유 문장은 **여기서 짓지 않는다** — board-move 가 정본이고 이 도구는 파이프다(두 곳에서
 *     지으면 갈라지고, 갈라진 쪽은 여기서도 「통과」 방향이다).
 *
 * ■ 못 재면 아무것도 안 한다
 *   `주인없는줄들` 이 `null`(폴더를 못 읽거나 생사를 못 잼)이면 **한 줄도 거두지 않는다.**
 *   여기서 「0건」으로 접으면 미실행이 통과와 같은 모양이 된다(F207). 그 방향은 이 도구에선
 *   특히 나쁘다 — 「아무도 안 살아 있다」로 읽히면 **산 세션의 줄을 통째로 쓸어낸다.**
 *
 * 쓰는 법
 *   node tools/보드수거.js           보고만 — 무엇을 거둘지 / 무엇을 왜 안 거두는지
 *   node tools/보드수거.js --실행     실제로 거둔다(board-move 가 줄마다 한 커밋)
 *   node tools/보드수거.js --hook    SessionStart 용 — 거둔 게 있을 때만 말한다(빈손이면 침묵)
 */
'use strict';
const path = require('path');
const { spawnSync } = require('child_process');

const 보드lib = require(path.join(__dirname, 'lib', '보드.js'));
const { 인자게이트 } = require(path.join(__dirname, 'lib', '인자게이트.js'));
/* 커밋 가능 상태 판정은 `인계문수거` 것을 그대로 쓴다 — rebase·merge·분리 HEAD 를 여기 다시
 * 적으면 두 수거 도구가 서로 다른 「지금 커밋해도 되나」를 보게 된다(그쪽 머리말과 같은 축). */
const { 커밋못하는이유 } = require(path.join(__dirname, '인계문수거.js'));
/* 잠금 나이 판정도 같은 이유로 한 통로다 — 두 수거기가 서로 다른 「고아인가」를 보면 갈라진다. */
const 잠금lib = require(path.join(__dirname, 'lib', 'git잠금.js'));

/* `SYNK_BOARD_ROOT` 는 `tools/board.js`·`tools/board-move.js` 와 **같은 이름의 이음매**다.
 * 이름이 갈리면 조사와 실행이 서로 다른 저장소를 보고, 그 방향은 「거둘 게 없다」(=침묵)다. */
const ROOT = process.env.SYNK_BOARD_ROOT || path.resolve(__dirname, '..');
/* ⚠ 이음매는 **부를 때** 읽는다 — 톱레벨 const 로 굳히면 이 모듈을 `require` 하는 회귀가
 * 나중에 세운 스텁을 못 물리고 **진짜 board-move 가 돌아 버린다**(실측: 종료 코드 시험 3개가
 * 전부 「옮김」으로 초록이 됐다 — 스텁이 안 물린 것이 통과와 같은 모양이었다 · F207 축).
 * 훅처럼 한 번 돌고 죽는 파일이면 차이가 없지만, 이 파일은 모듈로도 산다. */
const 이관도구 = () => process.env.SYNK_BOARD_MOVE_BIN || path.join(__dirname, 'board-move.js');
/* board-move 는 git 커밋까지 하므로 훅의 `--dry` 검증(8초)보다 넉넉해야 한다.
 * ⚠ 넘긴 것을 **성공으로 세지 않는다** — 타임아웃은 `못받음` 이고, 못받음은 다음 실행이 다시 본다. */
const 실행제한 = () => Number(process.env.SYNK_BOARD_SWEEP_TIMEOUT_MS) || 60000;
const 원칙6 = 6;   // board-move 종료 계약(0 옮겼다 · 1 못 옮겼다 · 6 주인 생존) — 그쪽 머리말

/**
 * 무엇을 거둘 수 있나. `null` = 판정 불가(생사를 못 쟀다 — 「0건」이 아니다).
 * 반환: { 대상[], 티켓[], 문구없음[], 전체수, 완료수 }
 */
function 조사(root) {
  const R = root || ROOT;
  const 주인없음 = 보드lib.주인없는줄들(R);
  if (주인없음 === null) return null;
  /* 유일성의 분모는 board-move 가 후보를 찾는 범위와 **같아야** 한다 — 그쪽은 `줄들 ∪ 유령들`
   * 을 본다(규격 밖 줄도 치울 수 있어야 하니까 · F322). 여기서 유령을 빼면 유령과 겹치는
   * needle 이 「유일」로 뽑히고, board-move 는 「세션 파일 2개에 걸린다」로 죽는다. */
  const 전부 = [...(보드lib.줄들(R) || []), ...(보드lib.유령들(R) || [])];
  const 전체 = 전부.map((r) => r.줄);

  const 대상 = []; const 티켓 = []; const 문구없음 = [];
  for (const r of 주인없음) {
    if (!보드lib.완료행(r.줄)) continue;          // ① 아직 도는 트랙 — 안 건드린다
    if (r.이어받기) { 티켓.push(r); continue; }    // ③ 🎫 — 일감이 산다(위 머리말)
    /* 🔑 [F405] 이 통로는 `옮기기()` 에서 **SYNK_BOARD 로 파일을 못박고** board-move 를 부른다 —
     *   그래서 「그 파일 안에서만 유일한」 문구도 안전하다. 안 넘기면 보드 승계 규약(board-guard ④
     *   — 죽은 세션 트랙은 트랙 칸을 **바이트 그대로** 옮겨 적어라)이 만든 쌍둥이 줄은 어떤 needle
     *   도 전역 유일이 아니라 영영 `null` 이 되고, **규약을 지킬수록 안 치워지는 줄이 늘었다.** */
    const 파일줄 = 전부.filter((x) => x.파일 === r.파일).map((x) => x.줄);
    const 문구 = 보드lib.이관문구(r.줄, 전체, 파일줄);
    if (!문구) { 문구없음.push(r); continue; }     // 유일 문구를 못 고르면 board-move 가 못 찾는다
    대상.push({ ...r, 문구 });
  }
  return { 대상, 티켓, 문구없음, 전체수: 전체.length, 완료수: 전체.filter(보드lib.완료행).length };
}

/* 사유를 몇 줄까지 옮기나. board-move 의 die 블록은 실측 7줄(사유 2 + 처방 4 + 꼬리 1)이라
 * 넉넉하다. ⚠ **자르면 자른 사실을 말한다** — 조용한 절단은 「사유가 이게 전부」로 읽힌다. */
const 사유줄상한 = () => Number(process.env.SYNK_BOARD_SWEEP_REASON_LINES) || 20;

/** 자식이 낸 말에서 사유를 고른다. board-move 는 거절을 `die`(stderr)로 내고 진행 보고는
 *  stdout 으로 낸다 — 그래서 stderr 가 먼저다. 둘 다 비면 **빈 문자열이 아니라** 그 사실을 적는다:
 *  「사유 없음」과 「안 물어봤음」이 같은 모양이면 이 트랙(F571)이 그대로 되돌아온다. */
function 사유고르기(r) {
  const e = String((r && r.stderr) || '').trim();
  const o = String((r && r.stdout) || '').trim();
  const 본문 = e || o;
  if (!본문) return '(board-move 가 아무 말도 안 했다 — 종료 코드만 왔다)';
  const 줄들 = 본문.split(/\r?\n/);
  const 상한 = 사유줄상한();
  if (줄들.length <= 상한) return 본문;
  return [...줄들.slice(0, 상한), `… (사유 ${줄들.length - 상한}줄 더 — 전문은 board-move 를 직접 돌려 본다)`].join('\n');
}

/* 「못받음」의 뜻을 **한 곳에서만** 적는다 — 이 판정은 언제나 미실행이고, 미실행은 통과가
 * 아니다(F207). 갈래마다 이 문장을 적었더니 OS 가 갈래를 바꾸는 순간 조용히 빠졌다. */
const 못받음 = (왜) => ({ 판정: '못받음', 사유: `${왜}\n(답을 못 받았다 — 미실행이지 통과가 아니다. 다음 실행이 다시 본다)` });

/**
 * 한 줄을 board-move 에 넘긴다 → `{ 판정, 사유 }`.
 *   판정 = `'옮김' | '거절' | '실패' | '못받음'`
 *   사유 = 실패·못받음일 때 board-move 가 낸 말 그대로(옮김·거절은 `''`)
 *
 * 🔑 [F571] 옛 판은 종료 코드만 보고 판정 문자열 하나로 접었다 — `spawnSync` 가 `encoding:'utf8'`
 *   로 사유를 **이미 받아 놓고도** 버렸다. 그 침묵의 값: 죽은 세션의 고아 미커밋 1줄이 이관·수거·
 *   `git merge` 셋을 함께 잠갔는데 화면엔 「실패 5건」만 떴고, board-move 가 낸 **따를 수 있는
 *   처방**(F433 · 명령까지 완성형)이 3시간 넘게 아무에게도 안 갔다.
 * ⚠ 여기서 재가공하지 않는다 — 사유 문장은 board-move 가 정본이고, 두 곳에서 지으면 갈라진다.
 *   이 함수가 하는 일은 «고르기»(어느 스트림인가·몇 줄까지)뿐이다.
 * ⚠ **틀릴 때의 모습**: board-move 가 사유 없이 죽으면 위 「아무 말도 안 했다」가 나간다 —
 *   빈칸보다 시끄럽지만, 새는 방향이 「원인 없음」이 아니라 「여기가 빈칸이다」다.
 */
function 옮기기(c, root) {
  const R = root || ROOT;
  const env = {
    ...process.env,
    SYNK_BOARD_ROOT: R,
    SYNK_BOARD_ARCHIVE: 보드lib.아카이브경로(R),
    /* 어느 파일인지 알면 넘긴다 — 안 넘기면 board-move 가 **자기 옆 저장소**의 보드를 본다
     * (픽스처·워크트리에서 통째로 빗나간다 · board-guard 이관판정과 같은 이유). */
    SYNK_BOARD: path.join(보드lib.폴더(R), c.파일),
  };
  let r;
  try {
    r = spawnSync(process.execPath, [이관도구(), c.문구], {
      encoding: 'utf8', timeout: 실행제한(), env, windowsHide: true,
    });
  } catch (e) { return 못받음(`spawn 자체가 실패했다: ${e && e.message}`); }
  if (!r || r.error || r.signal || typeof r.status !== 'number') {
    /* 타임아웃이 **어느 칸으로 오는지는 OS 마다 다르다** — 실측: Windows 는 `r.error`(ETIMEDOUT),
     * POSIX 는 `r.signal`(SIGTERM). 그래서 「미실행」이라는 뜻은 갈래마다 적지 않고 `못받음()`
     * 한 곳에서 붙인다 — 갈래에 적으면 다른 OS 에서 그 문장이 조용히 빠진다(첫 판이 그랬다). */
    const 왜 = !r ? '답 객체가 없다'
      : r.error ? `${r.error.message || r.error}(제한 ${실행제한()}ms)`
      : r.signal ? `신호 ${r.signal} 로 끊겼다(제한 ${실행제한()}ms)`
      : '종료 코드가 숫자가 아니다';
    return 못받음(`${왜}\n${사유고르기(r)}`);
  }
  if (r.status === 0) return { 판정: '옮김', 사유: '' };
  /* 거절(원칙⑥ · 주인이 되살아났다)은 **정상 판정**이라 사유를 안 싣는다 — 실으면 정상이
   * 실패의 얼굴로 화면에 서고, 그러면 이 도구의 적색이 다시 안 읽히게 된다. */
  if (r.status === 원칙6) return { 판정: '거절', 사유: '' };
  return { 판정: '실패', 사유: 사유고르기(r) };
}

function 실행(조사결과, root) {
  const 결과 = { 옮김: [], 거절: [], 실패: [], 못받음: [] };
  for (const c of 조사결과.대상) {
    const { 판정, 사유 } = 옮기기(c, root);
    결과[판정].push({ ...c, 사유 });
  }
  return 결과;
}

/** 실패·못받음의 사유를 **같은 사유끼리 묶어** 화면에 낼 블록으로 만든다.
 *  묶는 이유는 실측이다: 잠금 하나가 원인이면 5건이 **글자까지 같은** 사유를 낸다 —
 *  그걸 5번 찍으면 처방이 소음에 묻히고, 소음에 묶인 처방은 안 읽혀 없는 것과 같다. */
function 사유블록(결과) {
  const 묶음 = new Map();
  for (const 칸 of ['실패', '못받음']) {
    for (const c of 결과[칸] || []) {
      const 키 = `${칸} ${c.사유 || ''}`;
      if (!묶음.has(키)) 묶음.set(키, { 칸, 사유: c.사유 || '', 건: [] });
      묶음.get(키).건.push(c.지문 || c.파일);
    }
  }
  if (!묶음.size) return '';
  const 조각 = [];
  for (const { 칸, 사유, 건 } of 묶음.values()) {
    조각.push(`   ▼ ${칸} ${건.length}건 (${건.join(' · ')}) — board-move 가 낸 사유 그대로:`);
    for (const l of String(사유).split(/\r?\n/)) 조각.push(`     ${l}`);
  }
  return 조각.join('\n') + '\n';
}

const 짧게 = (줄) => String(줄).replace(/\s+/g, ' ').slice(0, 64);

if (require.main === module) {
  const argv = process.argv.slice(2);
  /* 🔑 목록은 눈으로 정하지 않았다 — `CLI도구들()` 이 재고, 회귀 ④ 가 매번 다시 센다.
   * ⚠ **`조사()` 보다 먼저** 판정한다 — 이 도구의 `--실행` 은 파일을 옮기는 쪽이라, 오타가
   *   「보고 모드」로 조용히 접히면 사람은 거둔 줄 알고 넘어간다. */
  const 아는플래그 = ['--hook', '--실행'];
  const 플래그오류 = 인자게이트('보드수거', argv, 아는플래그);
  if (플래그오류) { process.stderr.write(`\n🔴 ${플래그오류}\n\n`); process.exit(1); }
  const 모드 = argv.includes('--hook') ? 'hook' : argv.includes('--실행') ? '실행' : '보고';
  const r = 조사();

  if (r === null) {
    /* 못 잼을 0건으로 접지 않는다 — 훅에서도 한 줄은 낸다(미실행과 통과가 같은 모양이면 안 된다). */
    process.stdout.write('[보드수거] 줄 주인의 생사를 **못 쟀다** — 한 줄도 안 거뒀다(「거둘 것 0건」이 아니다)\n');
    process.exit(0);
  }

  if (모드 !== 'hook') {
    process.stdout.write(
      `[보드수거] 표 ${r.전체수}줄 · 완료 ${r.완료수}줄 → 거둘 수 있는 것 ${r.대상.length}건` +
      `${r.티켓.length ? ` · 이어받기 일감이라 남기는 것 ${r.티켓.length}건` : ''}` +   // 표식 글자 금지 — F612
      `${r.문구없음.length ? ` · 문구를 못 고른 것 ${r.문구없음.length}건` : ''}\n`);
    for (const c of r.대상) process.stdout.write(`   거둠 ${c.지문 || c.파일}  ${짧게(c.줄)}…\n`);
    for (const c of r.티켓) process.stdout.write(`   남김 ${c.지문 || c.파일}  🎫 이어받기 일감이 산다 — 집을지는 판단이라 사람 몫\n`);
    for (const c of r.문구없음) process.stdout.write(`   스킵 ${c.지문 || c.파일}  유일 문구를 못 골랐다 — board-move 가 그 줄을 특정 못 한다\n`);
  }

  if (모드 === '보고') {
    if (r.대상.length) process.stdout.write('   거두려면: node tools/보드수거.js --실행\n');
    process.exit(0);
  }
  if (!r.대상.length) process.exit(0);   // hook 빈손은 침묵 — 잔소리하는 장치는 읽히지 않게 된다

  const 막힘 = 커밋못하는이유();
  if (막힘) {
    process.stdout.write(`[보드수거] 지금은 커밋할 수 없다(${막힘}) — 한 줄도 안 거뒀다, 다음 실행이 다시 본다\n`);
    process.exit(0);
  }

  const 결과 = 실행(r);
  const 꼬리 = [
    결과.거절.length ? `되살아나 거절 ${결과.거절.length}건(원칙⑥ — 정상 판정이다)` : '',
    결과.실패.length ? `실패 ${결과.실패.length}건` : '',
    결과.못받음.length ? `답 못 받음 ${결과.못받음.length}건(미실행이지 통과가 아니다)` : '',
    r.티켓.length ? `이어받기 ${r.티켓.length}건은 남겼다` : '',   // 표식 글자 금지 — F612
  ].filter(Boolean).join(' · ');

  /* 🔑 [F571] 사유는 **판정과 함께** 낸다 — 옛 판은 「실패 N건」에서 멈췄고, board-move 가 낸
   *   완성형 처방(F433)이 화면에 한 번도 안 왔다. 이 블록은 실패·못받음이 있을 때만 서므로
   *   평상시(전건 옮김) 출력은 한 자도 안 늘어난다 — 상시 비용 0. */
  const 사유 = 사유블록(결과);

  if (!결과.옮김.length) {
    /* 사유 중 재시도로 **영영 안 풀리는** 하나는 여기서 이름을 댈 수 있다 — 잠금의 나이다(F493).
     * 거절(원칙⑥)은 정상 판정이라 분모에서 뺀다: 그때 잠금 얘기를 꺼내면 오경보다. */
    const 잠금 = 결과.실패.length ? 잠금lib.고아잠금줄(ROOT) : '';
    process.stdout.write(`[보드수거] 거두지 못했다${꼬리 ? ` — ${꼬리}` : ''}\n${사유}${잠금 ? 잠금 + '\n' : ''}`);
    process.exit(모드 === '실행' ? 2 : 0);   // 명시 실행의 실패는 소리 내고, 훅은 다음 기회에 맡긴다
  }
  /* ⚠ **부분 실패가 숨는 자리였다** — 한 건이라도 옮기면 옛 판은 꼬리에 「실패 N건」만 적고
   *   끝났다. 남은 N 건은 다음 실행에도 같은 이유로 막히므로 사유는 여기서도 서야 한다. */
  process.stdout.write(
    `[보드수거] 마감한 주인의 완료 줄 ${결과.옮김.length}건을 아카이브로 거뒀다(F368)${꼬리 ? ` · ${꼬리}` : ''}\n` +
    사유 +
    `   되찾기 — 그 세션이 되살아나면 \`node tools/board.js\` 가 아카이브에 있다고 알린다\n`);
  process.exit(0);
}

module.exports = { 조사, 실행, 옮기기, 사유블록 };
