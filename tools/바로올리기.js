  if (r.작업본) 줄.push(`작업본: ${r.작업본}(${r.가지}) · 바탕 ${짧게(r.바탕)} · ${r.원격} ${짧게(r.원격머리)}${r.다시한수 ? ` · 그새 origin이 움직여 ${r.다시한수}번 다시` : ''}`);
