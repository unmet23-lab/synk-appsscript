'use strict';
/**
 * 솔리오 「방문자 분석」이 읽는 요약 한 장(판 1)을 만들고 쓴다.
 * 자리: %LOCALAPPDATA%\synk\site-visits\summary.json(PC 앱 desktop/src/site-visits.cjs가 같은 자리를 읽는다).
 * 요약에는 집계 숫자와 상태만 들어간다. 칸마다 상태는 「됨」 · 「측정 전」 · 「권한 기다림」 · 「등록 전」(네이버) · 「못 읽음」이고, 까닭은 화면에 그대로 보이는 문장이다.
 *
 * 꼴(판 1):
 *  { 판: 1, 만든때, 기간날수, 세는쪽[], 안세는쪽[],
 *    방문: { 상태, 까닭, 받은때, 낡음?, 마지막기록, 사람, 앞사람, 본쪽, 갈래[{이름,수}], 들어온곳[{이름,수}], 첫쪽[{쪽,이름,수}], 날마다[{날,수}], AI방문 },
 *    쪽: { 상태, 까닭, 받은때, 쪽들[{쪽,이름,본수,떠남수,머문시간,끝까지,떠남비율}] },
 *    행동: { 상태, 까닭, 받은때, 문의{합,나눔[]}, 앱받기{합,나눔[]}, 문의비율, 앱받기비율, 처음들어온곳별[] },
 *    목적: { 상태, 까닭, 받은때, 방문, 고른방문, 고른칸[{이름,수}] },
 *    검색: { 구글: { 상태, 까닭, 받은때, 시작, 끝, 노출, 클릭, 평균순위, 앞{노출,클릭,평균순위}, 검색어[{말,노출,클릭}], 쪽[{쪽,노출,클릭}] },
 *            네이버: { 상태, 까닭 } },
 *    AI: { 상태, 까닭, 회차날, 서비스[{이름,설명,일반질문,답받음,언급,인용,브랜드질문,브랜드답받음,브랜드인용}], 앞회차{날,서비스[]}|null, 멈춤{}, AI방문 } }
 */
const fs = require('fs');
const os = require('os');
const path = require('path');

const 판 = 1;

function 요약자리() {
  if (process.env.SYNK_SITE_VISITS_SUMMARY) return process.env.SYNK_SITE_VISITS_SUMMARY;
  const 바탕 = process.env.LOCALAPPDATA || path.join(os.homedir(), 'AppData', 'Local');
  return path.join(바탕, 'synk', 'site-visits', 'summary.json');
}

function 요약읽기(자리 = 요약자리()) {
  try { const j = JSON.parse(fs.readFileSync(자리, 'utf8')); return j && j.판 === 판 ? j : null; } catch { return null; }
}

/** 임시 파일에 다 쓰고 바꾼다 — 앱이 반쯤 쓴 파일을 읽지 않게 */
function 요약쓰기(요약, 자리 = 요약자리()) {
  fs.mkdirSync(path.dirname(자리), { recursive: true });
  const 임시 = `${자리}.${process.pid}.tmp`;
  fs.writeFileSync(임시, JSON.stringify(요약, null, 1));
  fs.renameSync(임시, 자리);
  return 자리;
}

const 칸 = (상태, 까닭, 더 = {}) => ({ 상태, 까닭, ...더 });

/** 'M월 D일' — 화면 글에 쓰는 날짜 */
function 월일(iso) {
  const d = new Date(iso);
  if (!Number.isFinite(+d)) return '';
  const k = new Date(+d + 540 * 60000);
  return `${k.getUTCMonth() + 1}월 ${k.getUTCDate()}일`;
}

/**
 * 단계 결과 하나를 요약 칸으로. 실패했고 앞 요약에 3일 안의 「됨」 값이 있으면 그 값을 낡음 표시와 함께 이어 쓴다.
 * @param 결과 { 칸 } | { 오류, 까닭 } | { 상태, 까닭 }
 */
function 칸고르기(결과, 앞칸, 지금, 기본까닭) {
  if (결과 && 결과.칸) return { ...결과.칸, 받은때: new Date(지금).toISOString() };
  if (결과 && 결과.오류 && 앞칸 && 앞칸.상태 === '됨' && 앞칸.받은때 && +지금 - Date.parse(앞칸.받은때) < 3 * 24 * 3600 * 1000) {
    return { ...앞칸, 낡음: true, 까닭: `오늘은 읽지 못해 ${월일(앞칸.받은때)} 값을 보입니다.` };
  }
  if (결과 && 결과.상태) return 칸(결과.상태, 결과.까닭 || 기본까닭);
  return 칸('못 읽음', (결과 && 결과.까닭) || 기본까닭);
}

/**
 * 단계 결과들 → 요약 한 장.
 * @param 단계 { 방문: {칸:{방문,쪽,행동}}|{오류,까닭}|{상태,까닭}, 목적, 구글, 네이버: {상태,까닭}, AI: {회차, 앞회차}|{상태,까닭} }
 */
function 요약만들기({ 단계, 앞요약 = null, 지금 = new Date(), 세는쪽 = [], 안세는쪽 = [], 기간날수 = 7 }) {
  const 앞 = 앞요약 || {};
  const 방문결과 = 단계.방문 || {};
  const 셋 = 방문결과.칸 || null;
  const 방문 = 칸고르기(셋 ? { 칸: 셋.방문 } : 방문결과, 앞.방문, 지금, '방문 기록을 읽지 못했습니다.');
  const 쪽 = 칸고르기(셋 ? { 칸: 셋.쪽 } : 방문결과, 앞.쪽, 지금, '방문 기록을 읽지 못했습니다.');
  const 행동 = 칸고르기(셋 ? { 칸: 셋.행동 } : 방문결과, 앞.행동, 지금, '방문 기록을 읽지 못했습니다.');
  const 목적 = 칸고르기(단계.목적, 앞.목적, 지금, '홈 방문 목적 기록을 읽지 못했습니다.');
  const 구글 = 칸고르기(단계.구글, 앞.검색?.구글, 지금, '구글 서치콘솔을 읽지 못했습니다.');
  const 네이버 = 단계.네이버 || 칸('확인 안 함', '네이버 서치어드바이저 등록을 아직 확인하지 않았습니다.');

  let AI;
  const a = 단계.AI || {};
  if (a.회차) {
    AI = {
      상태: '됨', 까닭: null, 회차날: a.회차.날,
      서비스: a.회차.서비스.map(({ 판정들, ...셈 }) => 셈),
      앞회차: a.앞회차 ? { 날: a.앞회차.날, 서비스: a.앞회차.서비스.map(({ 판정들, ...셈 }) => 셈) } : null,
      멈춤: a.회차.멈춤 || {},
    };
  } else {
    AI = 칸(a.상태 || '측정 전', a.까닭 || '첫 회차를 아직 재지 않았습니다.');
  }
  AI.AI방문 = 방문.상태 === '됨' ? (방문.AI방문 ?? null) : null;

  return {
    판, 만든때: new Date(지금).toISOString(), 기간날수, 세는쪽, 안세는쪽,
    방문, 쪽, 행동, 목적, 검색: { 구글, 네이버 }, AI,
  };
}

module.exports = { 판, 요약자리, 요약읽기, 요약쓰기, 요약만들기, 칸고르기, 월일 };
