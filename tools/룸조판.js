#!/usr/bin/env node
'use strict';
/**
 * 룸조판 — Loom 의 «배치 판단층» L4.5 (2026-09-01 · 설계 정본 = `docs/Loom_배치판단층_설계_v1.md`)
 *
 * ══ 한 문장 ═══════════════════════════════════════════════════════════════
 *   **원고를 던지면 지면이 선다.** 지금까지 Loom 은 「입히는 것」(CSS·재질·부품)까지 자동인데
 *   «어느 지면으로, 무엇을 어디에» 는 세션(AI)이 매번 손으로 정했다 — 그 판단을 통로로 옮긴다.
 *   새 발명이 아니라 **counter 원리의 확장**이다: 「원고에 h2 만 써도 유리 원판 번호가 선다」를
 *   「의미를 적으면 지면이 선다」로 넓힌다.
 *
 * ══ 다섯 걸음 ══════════════════════════════════════════════════════════════
 *   ① 규격 — `--지면` > 원고 머리말 `지면:` 순. **둘 다 없으면 후보를 말하고 멈춘다**
 *      (조용한 추정 금지 — 추정이 틀리면 지면 «전체»가 틀린 옷을 입는다).
 *   ② 구조 — 마크다운 → 의미 마크업. `##`→절 · `1.`→순번 · `-`→불릿 · `>`→인용 · 표→표 ·
 *      `**굵은 수**`→히어로수 **후보**. 마크업을 손으로 짜는 일이 사라진다.
 *   ③ 배치 — 규칙이 서는 것은 코드가(counter·율·부품 훅 = 결정론 = 재현 가능),
 *      **갈리는 것은 원고의 힌트 주석이 이긴다**(`<!--조판: 히어로-->`).
 *   ④ 검증 — 아래 다섯. 어기면 빨강으로 멈춘다(«생성됐는데 나쁜» 지면이 통로를 못 지난다).
 *   ⑤ 출력 + **지면방 등재까지**. 태어나는 순간 등록부에 든다.
 *
 * ══ 🔑 판단을 «원고»에 남기는 까닭 ═════════════════════════════════════════
 *   AI 의 배치 판단이 코드 밖·세션 «안»에 살면 재현이 안 된다. 원고에 살면 「원고가 정본」
 *   게이트(`--재현`)가 그 판단까지 지킨다. 그리고 이 갈래 덕에 **AI 가 좋아질수록 이 층도
 *   좋아진다** — 힌트를 더 잘 다는 것은 모델 몫이고, 규칙은 안 늙는다.
 *
 * ══ 새로 짓지 «않은» 것 (통로를 늘리면 갈린다) ═════════════════════════════
 *   · 지면 CSS·골격·모션 = `tools/펠트문서.js` 의 `스킨()`+`스크립트()` 그대로.
 *     ⚠`loom.css({지면:'문서'})` «만» 쓰면 표·판·레일·표지가 통째로 맨몸이 된다 — 그 층은
 *       펠트문서 §② 골격이 진다. 스킨이 이미 loom.css 를 품고 있어 정본은 여전히 하나다.
 *   · 잉크 대비 = `lib/룸잉크.js` · 훅(닿나) = `lib/loom훅.js` · 자립형 = `펠트문서.검사()`
 *   · 등록 = `lib/지면방.js` (조판은 그 표에 «한 줄»을 넣을 뿐, 판정 규칙을 따로 안 든다)
 *   · 마크다운 파서는 **직접 짠다** — 이 저장소는 npm 의존 0 이다(`package.json` 자체가 없다).
 *
 * ══ 대가 — 틀릴 때의 모습 (짓기 전에 적는다 · 설계 §6) ═════════════════════
 *   · **마크다운 방언**: 표·중첩 목록에서 변환이 «조용히 다른 그림»을 낼 수 있다
 *     ⇒ 닫은 것 = ④의 «구조 왕복»(원고 블록 수 == 지면 블록 수)과 «줄 회수»(삼켜진 줄 0).
 *       파서가 한 줄을 못 읽고 버리는 것이 이 층의 유일한 조용한 실패라, 그 자리를 둘로 문다.
 *   · **힌트가 늘어 원고가 마크업이 되는 것** ⇒ 힌트 어휘를 «세는 분모»로 둔다(아래 `힌트어휘`).
 *     시작은 둘(히어로·장끊기)이고, **모르는 낱말은 적색**이다(조용히 무시하면 어휘가 샌다).
 *     열을 넘으면 이 설계가 틀린 것이다 — 늘릴 때 설계 문서를 함께 고친다.
 *   · **조판 지면과 손 지면의 공존기** ⇒ 등재 사유에 «통로»를 적는다(어느 통로에서 났는지가
 *     파일에 남아야 다음 사람이 손으로 고치지 않는다).
 *
 * ══ 통로 ═══════════════════════════════════════════════════════════════════
 *   node tools/룸조판.js <원고.md> [--지면 문서] [--내놔 docs/xxx.html] [--등재안함]
 *   node tools/룸조판.js --재현            # 원고 → 같은 지면이 나오나(원고가 정본인가)
 *   node tools/룸조판.js --규격            # 아는 규격과 아직 없는 규격
 */

