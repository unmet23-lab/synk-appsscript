/* ══════════════════════════════════════════════════════════════════════════
   ② 구조 — 마크다운 → 블록
   ══════════════════════════════════════════════════════════════════════════ */

/** 힌트 어휘 — **세는 분모**다. 모르는 낱말은 적색(조용히 무시하면 어휘가 샌다). */
const 힌트어휘 = {
  히어로: { 뜻: '이 블록의 첫 «굵은 수»를 히어로수로 세운다(지면당 1점)', 지면: ['문서'] },
  장끊기: { 뜻: '여기서 장을 끊는다', 지면: [] },   // 덱 전용 — 2보에서 산다
};

const 빈줄 = (s) => !String(s).trim();

/** 머리말(`---` 블록) 가르기. 값은 «키: 값» 한 줄씩 — YAML 흉내를 내지 않는다(내면 갈린다). */
function 머리말가르기(원문) {
  const 줄들 = String(원문).replace(/^\uFEFF/, '').split(/\r?\n/);
  const 흠 = [];
  if (줄들[0] !== undefined && 줄들[0].trim() === '---') {
    const 끝 = 줄들.findIndex((l, i) => i > 0 && l.trim() === '---');
    if (끝 > 0) {
      const 머리말 = {};
      for (let i = 1; i < 끝; i += 1) {
        if (빈줄(줄들[i])) continue;
        const m = 줄들[i].match(/^\s*([^:]+?)\s*:\s*(.*)$/);
        if (!m) { 흠.push(`머리말 ${i + 1}행을 못 읽었다(«키: 값» 한 줄이어야 한다): ${줄들[i]}`); continue; }
        머리말[m[1].trim()] = m[2].trim();
      }
      return { 머리말, 몸통줄: 줄들.slice(끝 + 1), 몸통시작: 끝 + 1, 흠 };
    }
    흠.push('머리말이 안 닫혔다 — `---` 한 줄로 닫는다');
  } else {
    흠.push('머리말(`---` 블록)이 없다 — 제목·지면·내놔를 적을 자리가 없다');
  }
  return { 머리말: {}, 몸통줄: 줄들, 몸통시작: 0, 흠 };
}

/** HTML 로 나가는 글자 — 원고는 마크다운이라 `<`·`&` 는 **글자**다(태그가 아니다). */
const 벗기기 = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/* 자리표 넷 — **이스케이프로 적는다.** 이 파일 첫 판은 NUL(U+0000)·SOH 를 소스에 그대로
 * 물고 있었다: 화면에는 공백으로 보이고, 읽는 사람도 편집 도구도 그 줄을 못 읽는다
 * (memory `heredoc-eats-backslashes` 와 같은 계열 — 보이지 않는 바이트가 조용히 산다).
 * 사설 영역(U+E000~)을 쓰는 까닭 = 본문 글자로 절대 안 쓰이는 자리라서다. */
const 코드칸시작 = '\uE000', 코드칸끝 = '\uE001';
const 굵시작 = '\uE002', 굵끝 = '\uE003';
const 자리표든가 = /[\uE000-\uE003]/;

/**
 * 줄 안 문법 — `**굵게**` · `` `코드` `` · `[글](곳)`.
 * ⚠**밖으로 나가는 링크는 여기서 문다.** `펠트문서.검사()` 의 자립형 게이트가 폰트 밖 외부
 *   `href` 를 흠으로 세므로, 조용히 내보내면 ④에서 «따르기 어려운» 적색이 난다.
 *   같은 판정을 두 자로 재지 않는다 — 게이트는 그대로 두고 **여기서 이름 대고 막는다**.
 */
function 줄안(원문, 흠, 줄번호) {
  if (자리표든가.test(원문)) {
    흠.push(`${줄번호}행 — 조판이 쓰는 자리표(U+E000~E003)가 원고에 있다. 지우고 다시 적어라`);
  }
  let s = 벗기기(원문);
  const 후보 = [];
  /* 코드부터 — 코드 «안»의 별표·대괄호를 문법으로 읽으면 명령이 깨진다. */
  const 코드칸 = [];
  s = s.replace(/`([^`]+)`/g, (_, 안) => `${코드칸시작}${코드칸.push(안) - 1}${코드칸끝}`);
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (전체, 글, 곳) => {
    if (/^https?:/i.test(곳)) {
      흠.push(`${줄번호}행 — 밖으로 나가는 링크(${곳})는 자립형 지면에 못 싣는다. `
        + '주소는 백틱으로 감싸 «글자»로 적거나, 저장소 상대경로를 써라.');
      return 전체;
    }
    return `<a href="${곳}">${글}</a>`;
  });
  /* 굵게 — 「굵은 글씨」인지 「히어로수」인지는 ③이 정한다. 여기선 **자리만** 잡는다.
     ⚠안쪽의 코드 자리표를 지우지 않는다 — 지우면 «`5`분» 같은 글자가 조용히 사라진다. */
  s = s.replace(/\*\*([^*]+)\*\*/g, (_, 안) => {
    const 속 = 안.trim();
    if (히어로후보인가(속)) 후보.push(속);
    return `${굵시작}${속}${굵끝}`;
  });
  s = s.replace(new RegExp(`${코드칸시작}(\\d+)${코드칸끝}`, 'g'), (_, i) => `<code>${코드칸[Number(i)]}</code>`);
  return { 글: s, 후보 };
}

/**
 * 이것이 «수»인가 — 히어로수 후보의 자. 숫자로 시작하고 짧아야 한다.
 * ⚠넓히지 않는다. 넓히면 굵은 글씨가 죄다 후보가 되고, 그러면 ③의 「첫째만」이 엉뚱한 것을 집는다.
 */
function 히어로후보인가(글) {
  const t = String(글).trim();
  return /^[0-9]/.test(t) && t.length <= 10 && !/\s{2}/.test(t);
}

/**
 * 몸통 → 블록들. **줄 회수를 함께 잰다** — 파서가 한 줄을 조용히 버리는 것이
 * 이 층의 유일한 조용한 실패라, 어느 줄이 어느 블록에 먹혔는지를 세어 둔다.
 * @returns {{블록:Array, 흠:string[], 회수:number[]}} 회수[i] = i행을 먹은 블록 수
 */
function 블록들(몸통줄, 몸통시작 = 0) {
  const 블록 = [];
  const 흠 = [];
  const 회수 = new Array(몸통줄.length).fill(0);
  const 행 = (i) => 몸통시작 + i + 1;                 // 사람이 읽는 1-기반 원고 행번호
  const 먹기 = (a, b) => { for (let i = a; i <= b; i += 1) 회수[i] += 1; };
  let 대기힌트 = null;
  let i = 0;

  const 붙이기 = (블록하나) => {
    if (대기힌트) { 블록하나.힌트 = 대기힌트; 대기힌트 = null; }
    블록.push(블록하나);
  };

  while (i < 몸통줄.length) {
    const 줄 = 몸통줄[i];
    if (빈줄(줄)) { i += 1; continue; }

    /* 힌트 주석 — 블록이 아니라 «다음 블록에 붙는 판단»이다. */
    const 힌 = 줄.match(/^\s*<!--\s*조판\s*:\s*(.+?)\s*-->\s*$/);
    if (힌) {
      const 낱말 = 힌[1].trim();
      먹기(i, i);
      if (!힌트어휘[낱말]) {
        흠.push(`${행(i)}행 — 모르는 조판 힌트 «${낱말}». 아는 어휘는 ${Object.keys(힌트어휘).join('·')} 뿐이다`
          + '(어휘를 늘리려면 `docs/Loom_배치판단층_설계_v1.md` 를 함께 고친다 — 설계 §6).');
      } else if (대기힌트) {
        흠.push(`${행(i)}행 — 힌트가 연달아 둘이다(«${대기힌트.낱말}» 다음 «${낱말}»). 한 블록에 하나만 붙는다`);
      } else {
        대기힌트 = { 낱말, 행: 행(i) };
      }
      i += 1;
      continue;
    }

    /* 코드 울타리 — 안쪽은 문법을 안 읽는다(명령 한 줄이 지면에서 깨지면 따라 할 수가 없다). */
    const 울 = 줄.match(/^\s*```(.*)$/);
    if (울) {
      const 시작 = i;
      let j = i + 1;
      while (j < 몸통줄.length && !/^\s*```\s*$/.test(몸통줄[j])) j += 1;
      if (j >= 몸통줄.length) {
        흠.push(`${행(시작)}행 — 코드 울타리(\`\`\`)가 안 닫혔다`);
        먹기(시작, 몸통줄.length - 1);
        i = 몸통줄.length;
        continue;
      }
      먹기(시작, j);
      붙이기({ 종류: '코드', 줄: 몸통줄.slice(시작 + 1, j), 행: 행(시작) });
      i = j + 1;
      continue;
    }

    /* 실금 — `---` 세 개 이상. 목록(`- `)보다 «먼저» 본다. */
    if (/^\s*(-{3,}|_{3,})\s*$/.test(줄)) { 먹기(i, i); 붙이기({ 종류: '실금', 행: 행(i) }); i += 1; continue; }

    /* 제목 */
    const 제 = 줄.match(/^(#{2,3})\s+(.+?)\s*$/);
    if (제) {
      먹기(i, i);
      붙이기({ 종류: 제[1].length === 2 ? '절' : '소제목', 글: 제[2], 행: 행(i) });
      i += 1;
      continue;
    }
    if (/^#\s+/.test(줄)) {
      흠.push(`${행(i)}행 — 「# 한 칸」 제목은 안 쓴다. 지면 제목은 머리말 «제목:» 이 진다(표지가 그것을 세운다)`);
      먹기(i, i); i += 1; continue;
    }

    /* 표 — 머리줄 + 구분줄이 «둘 다» 있어야 표다. */
    if (/^\s*\|/.test(줄) && i + 1 < 몸통줄.length && /^\s*\|[\s:|-]+\|\s*$/.test(몸통줄[i + 1])) {
      const 시작 = i;
      let j = i + 2;
      while (j < 몸통줄.length && /^\s*\|/.test(몸통줄[j])) j += 1;
      먹기(시작, j - 1);
      붙이기({
        종류: '표',
        머리: 표칸(몸통줄[시작]),
        몸: 몸통줄.slice(시작 + 2, j).map(표칸),
        행: 행(시작),
      });
      i = j;
      continue;
    }

    /* 인용 */
    if (/^\s*>\s?/.test(줄)) {
      const 시작 = i;
      let j = i;
      while (j < 몸통줄.length && /^\s*>\s?/.test(몸통줄[j])) j += 1;
      먹기(시작, j - 1);
      붙이기({ 종류: '인용', 줄: 몸통줄.slice(시작, j).map((l) => l.replace(/^\s*>\s?/, '')), 행: 행(시작) });
      i = j;
      continue;
    }

    /* 목록 — 순번(1.)·불릿(-). 항목 하나가 여러 줄이면 이어 붙인다. */
    const 목 = 목록머리(줄);
    if (목) {
      const 시작 = i;
      const 항목 = [];
      let j = i;
      while (j < 몸통줄.length) {
        const 이줄 = 몸통줄[j];
        if (빈줄(이줄)) break;
        const 머 = 목록머리(이줄);
        if (머) {
          if (머.들여쓰기 > 0) {
            흠.push(`${행(j)}행 — 중첩 목록은 1보가 못 짠다(설계 §6 「마크다운 방언」). 평평하게 펴거나 절을 나눠라`);
            먹기(j, j); j += 1; continue;
          }
          if (머.종류 !== 목.종류) break;            // 목록 종류가 바뀌면 다른 블록이다
          항목.push({ 글: [머.글], 행: 행(j) });
        } else if (항목.length && /^\s+\S/.test(이줄)) {
          항목[항목.length - 1].글.push(이줄.trim());   // 이어지는 줄
        } else break;
        먹기(j, j);
        j += 1;
      }
      붙이기({ 종류: 목.종류, 항목, 행: 행(시작) });
      i = j;
      continue;
    }

    /* 문단 — 위 어느 것도 아닌 연속 줄. */
    {
      const 시작 = i;
      let j = i;
      while (j < 몸통줄.length && !빈줄(몸통줄[j])
             && !/^\s*(#{1,3}\s|>|```|\|)/.test(몸통줄[j])
             && !/^\s*(-{3,}|_{3,})\s*$/.test(몸통줄[j])
             && !(j > 시작 && 목록머리(몸통줄[j]))
             && !/^\s*<!--\s*조판\s*:/.test(몸통줄[j])) j += 1;
      먹기(시작, j - 1);
      붙이기({ 종류: '문단', 줄: 몸통줄.slice(시작, j), 행: 행(시작) });
      i = j;
    }
  }

  if (대기힌트) 흠.push(`${대기힌트.행}행 — 힌트 «${대기힌트.낱말}» 뒤에 블록이 없다(붙을 자리가 없다)`);

  흠.push(...줄회수흠(몸통줄, 회수, 몸통시작));

  return { 블록, 흠, 회수 };
}

/**
 * 🔴 삼켜진 줄 — 이 층의 유일한 «조용한» 실패를 재는 자. 담긴 횟수가 1 이 아닌 줄을 낸다.
 *
 * 🔑 **순수 함수로 떼어 둔다.** 파싱 루프 «안»에 두면 실원고가 건강한 한 그 분기가 영영
 *    안 밟혀서 회귀가 원리적으로 못 닿는다 — 실측 2026-09-01 변이: 이 셈을 통째로 꺼도
 *    시험 22건이 **전부 초록**이었다(구멍). 못 닿는 게이트는 없는 게이트다.
 *    (`지면방.분모확인()`·`점검({상태읽기})` 를 떼어 둔 것과 같은 계열.)
 */
function 줄회수흠(몸통줄, 회수, 몸통시작 = 0) {
  const 흠 = [];
  for (let k = 0; k < 몸통줄.length; k += 1) {
    if (빈줄(몸통줄[k])) continue;
    const 행 = 몸통시작 + k + 1;
    if (회수[k] === 0) 흠.push(`${행}행이 어느 블록에도 안 담겼다(조용히 사라진다): ${String(몸통줄[k]).trim().slice(0, 40)}`);
    else if (회수[k] > 1) 흠.push(`${행}행이 블록 ${회수[k]}개에 겹쳐 담겼다`);
  }
  return 흠;
}

const 표칸 = (줄) => String(줄).trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map((s) => s.trim());

/** 목록 머리 — `1. ` 이면 순번, `- `·`* ` 면 불릿. */
function 목록머리(줄) {
  const m = String(줄).match(/^(\s*)(\d+\.|[-*])\s+(.*)$/);
  if (!m) return null;
  return { 들여쓰기: m[1].length, 종류: /\d/.test(m[2]) ? '순번' : '불릿', 글: m[3] };
}

/* ══════════════════════════════════════════════════════════════════════════
   ③ 배치 판단 — 규칙은 코드가 · 갈리는 것은 힌트가
   ══════════════════════════════════════════════════════════════════════════ */

/**
 * 히어로수 배치. **지면당 1점**(Loom 철칙 ④ 「신호 1점」)이라 여럿이면 하나를 골라야 하고,
 * 「고른다」가 곧 이 층이 존재하는 이유다.
 *   · 힌트가 있으면 **힌트가 이긴다**(그 블록의 첫 후보).
 *   · 힌트가 없고 후보가 여럿이면 **첫째만 취하고 나머지를 보고**한다(조용히 버리지 않는다).
 *   · 힌트가 둘이면 흠 — 1점 규율을 사람이 깬 것이라 코드가 대신 못 정한다.
 */
function 히어로판단(블록) {
  const 보고 = [];
  const 흠 = [];
  const 후보들 = [];
  for (const b of 블록) for (const c of (b.후보 || [])) 후보들.push({ 블록: b, 값: c, 행: b.행 });

  const 힌트단블록 = 블록.filter((b) => b.힌트 && b.힌트.낱말 === '히어로');
  for (const b of 블록) {
    if (!b.힌트) continue;
    const 어 = 힌트어휘[b.힌트.낱말];
    if (어 && 어.지면.length === 0) {
      보고.push(`${b.힌트.행}행 힌트 «${b.힌트.낱말}» — 문서 지면에서는 아직 하는 일이 없다(${
        b.힌트.낱말 === '장끊기' ? '2보 덱' : '다음 보'}에서 산다). 지금은 그냥 지나간다.`);
    }
  }

  if (힌트단블록.length > 1) {
    흠.push(`«히어로» 힌트가 ${힌트단블록.length}개다 — 히어로수는 지면당 1점이라 코드가 대신 못 고른다`
      + `(${힌트단블록.map((b) => b.힌트.행 + '행').join(' · ')}). 하나만 남겨라.`);
    return { 고른것: null, 보고, 흠 };
  }

  let 고른것 = null;
  if (힌트단블록.length === 1) {
    const b = 힌트단블록[0];
    if (!(b.후보 || []).length) {
      흠.push(`${b.힌트.행}행 «히어로» 힌트 — 그 블록에 굵은 수가 없다(`
        + '히어로수 후보 = `**16**` 처럼 숫자로 시작하는 굵은 글자다)');
      return { 고른것: null, 보고, 흠 };
    }
    고른것 = { 블록: b, 값: b.후보[0], 행: b.행, 근거: '원고 힌트' };
    const 나머지 = 후보들.filter((c) => !(c.블록 === b && c.값 === b.후보[0]));
    if (나머지.length) {
      보고.push(`히어로수 후보 ${후보들.length}개 중 힌트가 가리킨 «${고른것.값}»(${고른것.행}행)를 세웠다. `
        + `나머지 ${나머지.length}개는 굵은 글자로 남는다: ${나머지.map((c) => `«${c.값}»(${c.행}행)`).join(' · ')}`);
    }
  } else if (후보들.length) {
    고른것 = { ...후보들[0], 근거: '힌트 없음 — 첫째' };
    if (후보들.length > 1) {
      보고.push(`히어로수 후보가 ${후보들.length}개인데 힌트가 없다 — **첫째 «${고른것.값}»(${고른것.행}행)만** 세웠다. `
        + `나머지 ${후보들.length - 1}개는 굵은 글자로 남는다: ${후보들.slice(1).map((c) => `«${c.값}»(${c.행}행)`).join(' · ')}. `
        + '다른 것을 세우려면 그 블록 «위»에 `<!--조판: 히어로-->` 를 둔다.');
    }
  }
  return { 고른것, 보고, 흠 };
}

/* ══════════════════════════════════════════════════════════════════════════
   ②→ 마크업 — 블록을 Loom 부품이 «닿는» 모양으로 편다
   ══════════════════════════════════════════════════════════════════════════ */

/** 본문 구간 표식 — ④의 «구조 왕복»이 이 사이만 센다(표지·레일은 골격이지 원고가 아니다). */
const 본문시작 = '<!--조판:본문시작-->';
const 본문끝 = '<!--조판:본문끝-->';

/**
 * 굵게 자리를 실제 태그로. 히어로로 뽑힌 «그 하나»만 `.히어로수` 가 된다.
 *
 * 🔴 **«값»이 아니라 «블록 신원»으로 고른다.** 첫 판은 문자열이 같으면 세웠는데, 같은 수가
 *   앞 블록에도 있으면 힌트가 가리킨 것이 아니라 **엉뚱한 것**이 히어로가 된다 — 화면은
 *   멀쩡하고 지면당 1점도 지켜져서, 틀린 줄을 아무도 모른다(맞는 얼굴로 틀린 값).
 *   그래서 호출부가 «이 블록이 히어로 블록인가»를 먼저 판정해 값을 넘긴다.
 * ⚠뽑히지 않은 굵은 글자는 `<b>` 로 **남는다** — 원고의 글자는 원고의 것이라 안 지운다.
 */
function 굵은자리풀기(글, 히어로값, 쓸까) {
  const 정규 = new RegExp(`${굵시작}([^${굵끝}]*)${굵끝}`, 'g');
  return String(글).replace(정규, (_, 안) => {
    if (히어로값 !== null && 쓸까.남았나 && 안 === 히어로값) {
      쓸까.남았나 = false;
      return `<span class="히어로수">${안}</span>`;
    }
    return `<b>${안}</b>`;
  });
}

/** 블록 하나 → HTML 한 덩어리. **덩어리는 늘 0열에서 시작한다**(④가 그것을 센다). */
function 블록마크업(b, 문맥) {
  /* 히어로수는 «히어로 블록»에서만 선다 — 다른 블록에서는 값이 같아도 굵은 글자로 남는다. */
  const 풀기 = (s) => 굵은자리풀기(s, 문맥.히어로블록 === b ? 문맥.히어로값 : null, 문맥.쓸까);
  switch (b.종류) {
    case '절':
      return `<h2 id="${b.id}" class="듦">${풀기(b.글HTML)}</h2>`;
    case '소제목':
      return `<h3 class="듦">${풀기(b.글HTML)}</h3>`;
    case '문단':
      return `<p class="듦">${풀기(b.글HTML)}</p>`;
    case '불릿':
      return `<ul class="듦">\n${b.항목HTML.map((g) => `  <li>${풀기(g)}</li>`).join('\n')}\n</ul>`;
    case '순번':
      return `<ol class="듦">\n${b.항목HTML.map((g) => `  <li>${풀기(g)}</li>`).join('\n')}\n</ol>`;
    case '인용':
      return `<blockquote class="유리 듦">${풀기(b.글HTML)}</blockquote>`;
    case '실금':
      return '<hr class="실금">';
    case '코드':
      /* ⚠`overflow-x` 를 줄에 붙인다 — 코드 한 줄이 길면 유리 판을 뚫고 나간다.
         스킨에 `.코드` 규칙을 새로 짓지 않는 이유 = CSS 정본을 둘로 만들지 않으려고(F498 계열). */
      return `<pre class="유리 듦" style="overflow-x:auto;margin:var(--단) 0;padding:var(--참) var(--단)"><code>${
        b.줄.map(벗기기).join('\n')}</code></pre>`;
    case '표':
      /* 표틀 = 유리판 위의 실금(펠트문서 골격 §②). `.표틀` 없이 표만 두면 좁은 화면에서 넘친다. */
      return `<div class="유리 표틀 듦">\n  <table>\n    <thead><tr>${
        b.머리HTML.map((c) => `<th>${풀기(c)}</th>`).join('')}</tr></thead>\n    <tbody>\n${
        b.몸HTML.map((r) => `      <tr>${r.map((c) => `<td>${풀기(c)}</td>`).join('')}</tr>`).join('\n')
      }\n    </tbody>\n  </table>\n</div>`;
    default:
      /* 🔴 여기 오면 «종류는 늘었는데 그리는 자리를 안 만든» 것이다. 조용히 빈 줄로 두면
         구조 왕복이 그것을 잡지만, 무엇이 빠졌는지는 안 나온다 — 이름 대고 던진다. */
      throw new Error(`그릴 줄 모르는 블록 종류: ${b.종류}(${b.행}행) — 블록마크업() 에 자리를 만들어라`);
  }
}

/** 지면의 «본문 블록 수» — 산출물을 **다시 읽어** 센다(만든 값을 그대로 믿지 않는다). */
function 지면블록수(html) {
  const a = String(html).indexOf(본문시작);
  const b = String(html).indexOf(본문끝);
  if (a < 0 || b < 0) return null;
  return String(html).slice(a + 본문시작.length, b)
    .split('\n')
    .filter((l) => /^<(h2|h3|p|ul|ol|blockquote|hr|pre|div)\b/.test(l)).length;
}

/* ══════════════════════════════════════════════════════════════════════════
   조립 — 원고 → 지면 HTML
   ══════════════════════════════════════════════════════════════════════════ */

/**
 * @returns {{html:string|null, 흠:string[], 보고:string[], 잰것:object}}
 *   흠이 하나라도 있으면 **html 을 안 낸다** — 나쁜 지면이 통로를 지나는 것이 이 층의 실패다.
 */
function 조판(원문, { 지면: 지면인자, 원고경로 = '(원고)' } = {}) {
  const 흠 = [];
  const 보고 = [];
  const 가른것 = 머리말가르기(원문);
  흠.push(...가른것.흠);
  const 머리말 = 가른것.머리말;

  /* ① 규격 — 조용한 추정 금지. */
  const 지면이름 = 지면인자 || 머리말['지면'] || null;
  if (!지면이름) {
    흠.push('규격을 못 정했다 — `--지면` 도 원고 머리말 `지면:` 도 없다. **추정하지 않는다**'
      + '(추정이 틀리면 지면 전체가 틀린 옷을 입는다).\n'
      + `        후보: ${Object.entries(규격들).map(([n, v]) => `«${n}» ${v.뜻}`).join('\n              ')}\n`
      + `        아직 없는 규격: ${Object.entries(아직없는규격).map(([n, v]) => `«${n}» → ${v}`).join(' · ')}`);
  } else if (!규격들[지면이름]) {
    흠.push(아직없는규격[지면이름]
      ? `규격 «${지면이름}» 은 아직 없다 — ${아직없는규격[지면이름]}. 지금 되는 것은 «문서» 하나다`
      : `모르는 규격 «${지면이름}» — 아는 것은 ${Object.keys(규격들).join('·')} 뿐이다`);
  }

  for (const 키 of ['제목']) if (!머리말[키]) 흠.push(`머리말에 «${키}:» 가 없다 — 표지를 세울 재료가 없다`);

  /* ② 구조 */
  const { 블록, 흠: 구조흠 } = 블록들(가른것.몸통줄, 가른것.몸통시작);
  흠.push(...구조흠);
  if (!블록.length) 흠.push('본문 블록이 0개 — 머리말만 있고 몸통이 없다');

  /* 줄 안 문법을 펴면서 히어로수 «후보»를 모은다. */
  const 절들 = [];
  for (const b of 블록) {
    b.후보 = [];
    const 담기 = (원, 받는곳) => {
      const r = 줄안(원, 흠, b.행);
      b.후보.push(...r.후보);
      return (b[받는곳] = r.글);
    };
    if (b.종류 === '절') { 담기(b.글, '글HTML'); b.id = `s${절들.length + 1}`; 절들.push(b); }
    else if (b.종류 === '소제목') 담기(b.글, '글HTML');
    else if (b.종류 === '문단') 담기(b.줄.join(' '), '글HTML');
    else if (b.종류 === '인용') 담기(b.줄.join(' '), '글HTML');
    else if (b.종류 === '불릿' || b.종류 === '순번') {
      b.항목HTML = b.항목.map((it) => { const r = 줄안(it.글.join(' '), 흠, it.행); b.후보.push(...r.후보); return r.글; });
    } else if (b.종류 === '표') {
      b.머리HTML = b.머리.map((c) => { const r = 줄안(c, 흠, b.행); b.후보.push(...r.후보); return r.글; });
      b.몸HTML = b.몸.map((row) => row.map((c) => { const r = 줄안(c, 흠, b.행); b.후보.push(...r.후보); return r.글; }));
    }
  }

  /* ③ 배치 판단 */
  const 히어로 = 히어로판단(블록);
  흠.push(...히어로.흠);
  보고.push(...히어로.보고);

  const 잰것 = {
    블록: 블록.length, 절: 절들.length,
    히어로후보: 블록.reduce((n, b) => n + (b.후보 || []).length, 0),
    히어로: 히어로.고른것 ? `${히어로.고른것.값} (${히어로.고른것.근거})` : '없음',
    힌트: 블록.filter((b) => b.힌트).length,
  };

  if (흠.length) return { html: null, 흠, 보고, 잰것 };

  /* 마크업 */
  const 문맥 = {
    히어로블록: 히어로.고른것 ? 히어로.고른것.블록 : null,
    히어로값: 히어로.고른것 ? 히어로.고른것.값 : null,
    쓸까: { 남았나: !!히어로.고른것 },
  };
  const 본문 = 블록.map((b) => 블록마크업(b, 문맥)).join('\n\n');
  const html = 지면조립({ 머리말, 본문, 절들, 원고경로 });

  /* 만든 값을 그대로 믿지 않는다 — 산출물을 다시 읽어 센다. */
  잰것.지면블록 = 지면블록수(html);
  return { html, 흠, 보고, 잰것 };
}

/** 표지·레일·꼬리 — 지면의 «골격». 펠트문서 원고 규약(`<!--펠트스킨-->`)을 그대로 탄다. */
function 지면조립({ 머리말, 본문, 절들, 원고경로 }) {
  /* ⚠자리표까지 걷는다 — 레일·<title> 은 굵게 자리를 «푸는» 자리가 아니라서,
     안 걷으면 사설 영역 문자가 그대로 실린다(눈에 안 보이는 채로). */
  const 민 = (s) => String(s || '').replace(/<[^>]+>/g, '').replace(/[\uE000-\uE003]/g, '').trim();
  const 제목 = 벗기기(머리말['제목']);
  const 꼭지 = 머리말['꼭지'] ? 벗기기(머리말['꼭지']) : 'SYNK';
  const 한줄 = 머리말['한줄'] ? 벗기기(머리말['한줄']) : '';
  const 메타 = 머리말['메타'] ? 벗기기(머리말['메타']) : '';
  const 오브글자 = 민(제목).slice(0, 1);

  const 레일 = 절들.length
    ? `<nav class="레일" aria-label="차례">
  <p class="꼭지">${민(제목)}</p>
  <ol>
${절들.map((b, i) => `    <li><a href="#${b.id}"><span class="n">${String(i + 1).padStart(2, '0')}</span> ${민(b.글HTML)}</a></li>`).join('\n')}
  </ol>
</nav>`
    : '';

  return `<!doctype html><html lang="ko"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${민(제목)}</title>
${펠트문서.표식}

</head>
<body>
<div class="판">

${레일}

<div class="글">

<header class="표지">
  <div class="오브" aria-hidden="true">${오브글자}</div>
  <div>
    <p class="꼭지">${꼭지}</p>
    <h1>${제목}</h1>
${한줄 ? `    <p class="한줄">${한줄}</p>\n` : ''}${메타 ? `    <p class="메타">${메타}</p>\n` : ''}  </div>
</header>

${본문시작}

${본문}

${본문끝}

<hr class="실금">
<footer>
  <p class="작게">조판 산출물(손 편집 금지) — 원고 정본 = <code>${원고경로}</code>.
     다시 내려면 <code>node tools/룸조판.js ${원고경로}</code>.
     손으로 고치면 다음 조판이 되돌린다(원고가 정본).</p>
</footer>
<div class="쪽번호">SYNK</div>

</div><!-- /글 -->
</div><!-- /판 -->
</body></html>
`;
}

/** 스킨 주입 — 재료는 `펠트문서` 가 쥔다(순서·내용의 정본은 거기 하나다). */
function 스킨입히기(원고html) {
  if (!원고html.includes(펠트문서.표식)) throw new Error('표식이 없다 — 지면조립()이 ' + 펠트문서.표식 + ' 를 안 넣었다');
  return 원고html.replace(펠트문서.표식, 펠트문서.스킨([], '무채') + '\n' + 펠트문서.스크립트());
}

/** 원고 → 완성 지면(메모리). */
function 지면내기(원문, 옵션 = {}) {
  const r = 조판(원문, 옵션);
  return r.html ? { ...r, html: 스킨입히기(r.html) } : r;
}

