#!/usr/bin/env node
/**
 * 밤샘 0830 — 까몽 시안 다섯을 «정본 규격»으로 승격한다
 *   (유호 지시 08-30 「굽기작업 애매하게 끝난거 많잖아 · 지금 자러갈거니까 전부 오래걸려도 되니까 이어서 진행해」)
 *
 * ■ 🔑 이 밤이 겨누는 것 = 「한 세트가 두 규격으로 갈려 있다」
 *   실측(08-30 04:4x): 까몽 8컷 중 확정 3(본체·눈감음·눈웃음)이 **1024px**, 시안 5(놀람·윙크·
 *   졸림·으쓱·민망)가 **700px** 이다. 그래서 창구가 다섯을 안 내준다:
 *     node -e "…console.log(M.까몽누끼컷)"  →  [본체, 눈감음, 눈웃음]   ← 다섯이 빠진다
 *   까닭은 `마스코트자산.js` 의 `까몽누끼컷` 이 `누끼 && 규격==='정본'` 으로 거르기 때문이고,
 *   그 가드는 옳다 — 영상 `컷맞추기.js` 가 **픽셀 자리로 덮어** 크기가 갈린 컷이 한 벌에 섞이면
 *   인덱스가 어긋난 채 그림은 나오고 종료코드는 0 이 된다.
 *   ⇒ 다섯을 1024 로 다시 구워 규격을 올리는 것이 이 갈래를 닫는 유일한 길이다.
 *
 * ■ 🔴 안 굽는 것 — 확정 3(본체·눈감음·눈웃음). 다음 세션이 다시 세지 않게 적어 둔다
 *   셋의 mtime(08-26)은 굽기 자(`몽글친구굽기.py` 08-29 00:22)보다 **옛것**이라
 *   `까몽굽기.js` 의 «자보다 옛것이면 다시 굽는다» 규율에 걸린다. 그런데 **그림은 안 바뀐다**:
 *   그 자 이동(`95cd4eded`)은 덧붙이기다 — `구슬눈(부호, 배=1.0, 곁눈=0.0)` 으로 인자를
 *   «기본값 0» 으로 늘렸고 `elif 표정=='으쓱'/'민망'` 두 갈래를 더했을 뿐, 확정 3이 지나는 길은
 *   한 줄도 안 바뀌었다(diff 로 확인 08-30). 다시 구우면 같은 그림에 1.5시간을 태운다.
 *   🔑 이것이 트랙 §0 의 「203장 헛불」과 **같은 병**이다 — 검사기의 기준이 «파일 mtime»이지
 *     «렌더에 닿은 마지막 커밋»이 아니라서 난다. 그래서 이 파일은 표정을 손으로 못 박는다.
 *
 * ■ 🔴 램이 이 밤의 진짜 제약이다 — 08-29 세션이 실측으로 못 박아 둔 것을 그대로 따른다
 *   · 1024 로 걸면 블렌더가 **7.6~9.2GB**, 여유 램이 97~227MB 를 오간다(프리징 문턱).
 *   · 700 으로 내려도 **8.4GB** 까지 올라간다 ⇒ 램을 먹는 것은 픽셀이 아니라 **털 기하**다
 *     (Cycles 는 렌더 «전»에 5~6백만 가닥의 BVH 를 세우고, 그 크기는 해상도와 무관하다).
 *   · 그러니 이 캐릭터의 굽기 비용은 **한 판 ≈8GB 고정**이고, 16GB 기계에서 줄일 것은
 *     해상도가 아니라 **띄워 둔 세션 수**다.
 *   ⇒ 그래서 08-29 의 램바닥 1,800MB 를 **2,600MB 로 올린다.** 08-30 04:5x 실측으로 이 기계에
 *     세션이 일곱 떠 있고 여유가 3.9GB 였다 — 1,800 문지기는 그 상태를 «통과»시키고, 통과시키면
 *     블렌더가 페이징에 빠져 «돌긴 도는데 20% 속도»가 된다(§2-G 44분 사고). 기다리는 편이 싸다.
 *   ⚠ 그래도 **무한히 기다리지는 않는다** — 아침에 「아무것도 안 됨」이 「좀 느림」보다 훨씬 나쁘다.
 *     상한을 120분으로 넉넉히 준다(밤이라 세션이 하나씩 꺼지며 램이 풀린다).
 *
 * ■ 순서 = **싼 것 먼저** (누끼 → 몸). 08-26 실측이 그 값을 갈라 두었다
 *   같은 1024·96샘플·CPU 에서 누끼 9.7~16.5분 · 받침천 판(몸) 18.8~45.1분 — **몸이 ≈3배 비싸다**
 *   (투명 필름이라 1차 광선 대부분이 배경에서 바로 끝나기 때문).
 *   그리고 값도 누끼가 크다: `까몽누끼컷` 이 영상 통로가 쓰는 창구라, 누끼 다섯만 승격돼도
 *   영상이 세 표정에서 여덟 표정으로 풀린다. **밤이 반만 돌아도 값이 남는 순서**로 세운다.
 *
 * ■ 장치 = CPU. 이 캐릭터는 GPU(Arc ONEAPI)에서 예외가 아니라 프로세스째 나간다
 *   (까몽굽기.js 머리말 · 17:40 굽기 실물 — 10.9분 태우고 파일 0).
 *
 * ■ `--다시` 를 주는 까닭 — 700px 판이 «자보다 새것»이라 안 주면 다섯 다 건너뛴다.
 *   ⚠ 덮어써도 잃는 것은 없다: 블렌더는 «끝날 때» 파일을 쓰므로 도중에 죽으면 옛 판이 그대로 남는다.
 *
 * 띄우는 법(PowerShell · 세션에서 떼어낸다 — 세션이 죽어도 굽기는 산다):
 *   $cls = [wmiclass]'Win32_Process'
 *   $cls.Create('cmd.exe /c ""C:\Program Files\nodejs\node.exe" "…\tools\밤샘_0830.js" > "…\밤샘0830.log" 2>&1"', 'C:\…\SYNK-appsscript')
 *   🔴 `cmd.exe /c` 로 «반드시» 감싼다 — WMI Create 는 셸을 안 거쳐서, 안 감싸면 `>` 와 로그 경로가
 *     리디렉션이 아니라 node 의 argv 로 들어간다. 굽기는 멀쩡히 돌고 로그만 아예 안 생긴다(08-28 실측).
 * 🔑 판정은 로그가 아니라 파일이다 — 아침에 볼 것은 `docs/캐릭터/친구공방_0825/` 와 `docs/까몽_시안.html`.
 */
'use strict';
const { spawnSync, execFileSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const 루트 = path.resolve(__dirname, '..');
const 노드 = process.execPath;
/* 08-29 의 1,800 에서 올렸다 — 위 ■램 절 참조. 한 판이 ≈8GB 를 물므로 2,600 도 넉넉하진 않지만,
 * 이보다 높이면 세션 일곱이 떠 있는 밤에 영영 자리가 안 난다(그러면 아침에 0장이다). */
const 램바닥MB = 2600;
const 기다림상한분 = 120;

const 시각 = () => new Date().toLocaleTimeString('ko-KR');
const 말 = (s) => { console.log(s); try { process.stdout.write(''); } catch (_) {} };

/** PowerShell 한 줄 — 실패하면 빈 문자열(문지기는 «모르면 통과»여야 굽기를 안 막는다). */
function ps(명령) {
  try {
    return String(execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', 명령],
      { encoding: 'utf8', timeout: 30000 })).trim();
  } catch (_) { return ''; }
}

const 여유램MB = () => Number(ps('[int]((Get-CimInstance Win32_OperatingSystem).FreePhysicalMemory/1KB)')) || 0;
const 블렌더수 = () => Number(ps("(Get-CimInstance Win32_Process -Filter \"Name='blender.exe'\").Count")) || 0;

/* ── 완주 도장 ──────────────────────────────────────────────────────────────
 * 오늘 새벽 `밤굽기.js` 에 선 규약을 그대로 쓴다(새 원장을 안 만든다 — 이미 있는 자리에 얹는다).
 *   상태:"돌는중" = 착수 도장. 아침까지 그대로면 «잡을 수 없는 죽음»(재부팅·강제 kill)
 *   상태:"멈춤"   = 잡은 죽음(예외·신호·비정상 종료)
 *   상태:"완주"   = 끝까지 갔다.  파일 없음 = 아예 안 돌렸다
 * ⚠ 완주 ≠ 합격. 「잘 구워졌나(미학)」는 유호님 눈이 판정 축이고 여기서 안 잰다.
 */
const 도장길 = path.join(루트, 'docs', '_ops', '밤굽기도장.json');
let 도장끝 = false;
const 단계기록 = [];
function 도장(상태, 사유) {
  try {
    const 임시 = `${도장길}.${process.pid}.tmp`;
    fs.mkdirSync(path.dirname(도장길), { recursive: true });
    const 벌 = { 시각: new Date().toISOString(), 무엇: '밤샘_0830.js', 상태, 완주: 상태 === '완주', 사유 };
    fs.writeFileSync(임시, `${JSON.stringify(벌, null, 2)}\n`, 'utf8');
    fs.renameSync(임시, 도장길);
  } catch (_) { /* 도장 실패로 굽기를 멈추지 않는다 — 굽기가 본체다 */ }
}
process.on('exit', (코드) => { if (!도장끝) 도장('멈춤', `끝까지 못 갔다 — 종료코드 ${코드} · 지나온 단계: ${단계기록.join(' · ') || '없음'}`); });
for (const 신호 of ['SIGINT', 'SIGTERM', 'SIGHUP', 'SIGBREAK']) {
  process.on(신호, () => { 도장('멈춤', `신호 ${신호} 로 끊겼다 · 지나온 단계: ${단계기록.join(' · ') || '없음'}`); 도장끝 = true; process.exit(130); });
}
process.on('uncaughtException', (e) => { 도장('멈춤', `예외로 죽었다 — ${(e && e.message) || e} · 지나온 단계: ${단계기록.join(' · ') || '없음'}`); 도장끝 = true; process.exit(1); });

/** 부모가 이미 없는 블렌더를 걷는다 (08-28 사고 — 부모만 죽으면 자식이 4.6GB를 물고 산다).
 *  성한 굽기의 부모는 살아 있으니 안 걸린다. 단계 «사이»에서만 부른다(내 자식이 없을 때). */
function 고아걷기() {
  const 죽인것 = ps([
    "$live=(Get-CimInstance Win32_Process|%{$_.ProcessId});",
    "$n=0; Get-CimInstance Win32_Process -Filter \"Name='blender.exe'\" | %{",
    "  if($live -notcontains [int]$_.ParentProcessId){ Stop-Process -Id $_.ProcessId -Force -EA SilentlyContinue; $n++ } };",
    '$n',
  ].join(' '));
  if (죽인것 && 죽인것 !== '0') 말(`  🧹 고아 블렌더 ${죽인것}개를 걷었다 — 램을 물고 있었다.`);
}

/** 남의 굽기가 돌면 «죽이지 않고 물러난다»(트랙 §0 겹침 규율). 램 바닥도 같이 지킨다. */
function 자리비었나(라벨) {
  const 끝시각 = Date.now() + 기다림상한분 * 60 * 1000;
  let 알렸나 = false;
  for (;;) {
    고아걷기();
    const 남 = 블렌더수();
    const 램 = 여유램MB();
    if (남 === 0 && 램 >= 램바닥MB) {
      if (알렸나) 말(`  ▶ 자리가 났다 — 램 ${램}MB · ${시각()}`);
      return true;
    }
    if (Date.now() > 끝시각) {
      말(`  ⏭ ${기다림상한분}분을 기다려도 자리가 안 났다(블렌더 ${남} · 램 ${램}MB) — ${라벨} 건너뛴다.`);
      return false;
    }
    if (!알렸나) {
      말(`  ⏳ 기다린다 — 블렌더 ${남}개 · 여유 램 ${램}MB(바닥 ${램바닥MB}) · ${시각()}`);
      알렸나 = true;
    }
    spawnSync(노드, ['-e', 'setTimeout(()=>{},60000)'], { timeout: 65000 });
  }
}

function 단계(이름, 인자들) {
  말(`\n■ ${이름} — ${시각()}`);
  if (!자리비었나(이름)) { 단계기록.push(`${이름.split(' ')[0]}=건너뜀`); return; }
  const 시작 = Date.now();
  const r = spawnSync(노드, 인자들, { cwd: 루트, stdio: 'inherit' });
  말(`■ ${이름} 끝 — 종료코드 ${r.status} · ${Math.round((Date.now() - 시작) / 60000)}분 · ${시각()}`);
  단계기록.push(`${이름.split(' ')[0]}=${r.status}`);
  /* 🔴 종료코드로 성패를 판정하지 «않는다» — 판정은 까몽굽기.js 안에서 «파일 시각 + 종료상태»
   *   두 축이 같이 한다. 여기서는 걸린 시간만 적는다. */
}

말(`■■ 밤샘 0830 시작 — ${new Date().toLocaleString('ko-KR')} · pid ${process.pid}`);
말(`   여유 램 ${여유램MB()}MB · 블렌더 ${블렌더수()}개 · 램바닥 ${램바닥MB}MB · 기다림 상한 ${기다림상한분}분`);
말('   과녁 = 까몽 시안 다섯의 «정본 승격» 10장(누끼 5 → 몸 5) · 1024px · 샘플 96 · CPU');
말(`   로그 ${path.join(os.tmpdir(), '밤샘0830.log')} (띄우개가 여기로 리디렉션했을 때)`);
도장('돌는중', '돌고 있다 — 아직 안 끝났다 (이 도장이 그대로면 도중에 죽은 것이다)');

/* ① 누끼 다섯 — **싼 것 먼저**(≈3배 싸다) 그리고 **값도 크다**.
 *   `까몽누끼컷` 이 «누끼 && 규격 정본» 으로 거르므로, 이 다섯이 1024 로 서면 영상 통로가
 *   세 표정에서 여덟 표정으로 풀린다. 밤이 반만 돌아도 그 값은 남는다. */
단계('① 까몽 누끼 다섯 — 1024 정본 승격 (놀람·윙크·졸림·으쓱·민망)',
  ['tools/까몽굽기.js', '--다시', '--표정', '놀람,윙크,졸림,으쓱,민망', '--누끼',
    '--너비', '1024', '--샘플', '96', '--장치', 'CPU', '--시트없이']);

/* ② 몸 다섯 — 받침천 판. 장당 18.8~45.1분(08-26 실측)이라 이 밤의 큰 몫이다.
 *   누끼가 먼저 섰으므로 여기서 끊겨도 창구는 이미 풀려 있다. */
단계('② 까몽 몸 다섯 — 1024 정본 승격 (놀람·윙크·졸림·으쓱·민망)',
  ['tools/까몽굽기.js', '--다시', '--표정', '놀람,윙크,졸림,으쓱,민망',
    '--너비', '1024', '--샘플', '96', '--장치', 'CPU', '--시트없이']);

/* ③ 판정 지면 — 🔑 굽기와 지면은 한 벌이다(트랙 §0). 앞 단계를 `--시트없이` 로 돌린 것은
 *   매 단계마다 그리면 중간 판이 최종 판인 척 남기 때문이다. 여기서 한 번만 그린다. */
단계('③ 까몽 시안 지면 다시 그리기 (docs/까몽_시안.html)', ['tools/까몽시트.js']);

말(`\n■■ 밤샘 0830 끝 — ${new Date().toLocaleString('ko-KR')}`);
말('   🔴 굽고 «끝»이 아니다 — 다섯이 1024 로 섰으면 `tools/lib/마스코트자산.js` 의 `까몽컷` 에서');
말('      그 다섯의 `규격` 을 「시안」→「정본」 으로 올려야 `까몽누끼컷` 이 여덟을 내준다.');
말('      🔑 이것이 정본 §10 의 「굽기와 등재는 한 벌」 — 승격 굽기는 등재까지 가야 끝난다.');
말('   🔎 아침에 볼 것 ① 실물 규격: 다섯이 1024px 인가');
말('   🔎 아침에 볼 것 ② 창구: node -e "const M=require(\'./tools/lib/마스코트자산.js\');console.log(M.까몽누끼컷)" — 여덟이어야');
말('   🔎 아침에 볼 것 ③ 지면: docs/까몽_시안.html — 여덟 칸이 «한 규격»으로 서 있나');
도장('완주', `끝까지 갔다 · 단계별: ${단계기록.join(' · ')} — 그림이 «좋은가»는 여기서 안 잰다(사람 몫)`);
도장끝 = true;
