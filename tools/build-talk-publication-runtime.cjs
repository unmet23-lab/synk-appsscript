'use strict';
// Vendor the existing Talk registration implementation, with inspectable source
// hashes. No credentials, installed dependencies, or working-tree discovery.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
function build(talkRoot,{check=false}={}){
  if(!path.isAbsolute(talkRoot))throw Error('Talk root must be absolute');
  const entries=['lib/synkbrief-publication.js','tools/synkbrief-drive-manifest-upload.js','lib/synkbrief-drive.js'];
  const sources=new Map(),hashes={};
  function visit(id){
    if(sources.has(id))return;
    const file=path.resolve(talkRoot,id);
    if(!file.startsWith(path.resolve(talkRoot)+path.sep))throw Error('source outside Talk');
    const raw=fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n');hashes[id]=crypto.createHash('sha256').update(raw).digest('hex');sources.set(id,'');
    const source=raw.replace(/^#![^\n]*\n/,'').replace(/require\(\s*(['"])(\.[^'"]+)\1\s*\)/g,(_,q,ref)=>{
      const target=path.posix.normalize(path.posix.join(path.posix.dirname(id),ref));
      visit(target);return '__load('+JSON.stringify(target)+')';
    });
    sources.set(id,source);
  }
  entries.forEach(visit);
  const result="'use strict';\n// Generated by tools/build-talk-publication-runtime.cjs; edit Talk sources.\nconst __modules={\n"+
    [...sources].sort(([a],[b])=>a.localeCompare(b)).map(([id,source])=>JSON.stringify(id)+":function(module,exports,__load,require){\n"+source+"\n}").join(',\n')+
    "\n};\nconst __cache={};function __load(id){if(__cache[id])return __cache[id].exports;const m={exports:{}};__cache[id]=m;__modules[id](m,m.exports,__load,require);return m.exports;}\n"+
    'module.exports={...__load('+JSON.stringify(entries[0])+'),...__load('+JSON.stringify(entries[1])+'),...__load('+JSON.stringify(entries[2])+')};\n';
  const dir=path.join(root,'tools/lib/generated');
  const outputs={'talk-publication.cjs':result,'talk-publication.sources.json':JSON.stringify({schemaVersion:1,files:Object.fromEntries(Object.entries(hashes).sort())},null,2)+'\n'};
  if(check){
    for(const [name,content] of Object.entries(outputs))if(!fs.existsSync(path.join(dir,name))||fs.readFileSync(path.join(dir,name),'utf8').replace(/\r\n/g,'\n')!==content)throw Error('Talk publication output is stale: '+name);
  }else{
    fs.mkdirSync(dir,{recursive:true});for(const [name,content] of Object.entries(outputs))fs.writeFileSync(path.join(dir,name),content);
  }
  return {files:sources.size,bytes:Buffer.byteLength(result),checked:check};
}
if(require.main===module){
  if(process.argv.length>4||(process.argv[3]&&process.argv[3]!=='--check'))throw Error('usage: node tools/build-talk-publication-runtime.cjs <absolute Talk root> [--check]');
  console.log(JSON.stringify(build(process.argv[2],{check:process.argv[3]==='--check'})));
}
module.exports={build};
