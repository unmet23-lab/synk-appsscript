'use strict';
const { spawnSync, execFileSync } = require('node:child_process');
const path = require('node:path');

const 루트 = path.resolve(__dirname, '..');
const 노드 = process.execPath;
const 램바닥MB = 1800;
const 기다림상한분 = 45;

const 시각 = () => new Date().toLocaleTimeString('ko-KR');
const 말 = (s) => { console.log(s); try { process.stdout.write(''); } catch (_) {} };

/** PowerShell 한 줄 — 실패하면 빈 문자열(문지기는 «모르면 통과»여야 굽기를 안 막는다). */
function ps(명령) {
  try {
    return String(execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', 명령],
      { encoding: 'utf8', timeout: 30000 })).trim();
  } catch (_) { return ''; }
}

const 여유램MB = () => Number(ps('[int]((Get-CimInstance Win32_OperatingSystem).FreePhysicalMemory/1KB)')) || 0;
const 블렌더수 = () => Number(ps("(Get-CimInstance Win32_Process -Filter \"Name='blender.exe'\").Count")) || 0;

/** 부모가 이미 없는 블렌더를 걷는다 (08-28 사고 — 부모만 죽으면 자식이 4.6GB를 물고 산다).
 *  성한 굽기의 부모는 살아 있으니 안 걸린다. 단계 «사이»에서만 부른다(내 자식이 없을 때). */
function 고아걷기() {
  const 죽인것 = ps([
    "$live=(Get-CimInstance Win32_Process|%{$_.ProcessId});",
    "$n=0; Get-CimInstance Win32_Process -Filter \"Name='blender.exe'\" | %{",
    "  if($live -notcontains [int]$_.ParentProcessId){ Stop-Process -Id $_.ProcessId -Force -EA SilentlyContinue; $n++ } };",
    '$n',
  ].join(' '));
  if (죽인것 && 죽인것 !== '0') 말(`  🧹 고아 블렌더 ${죽인것}개를 걷었다 — 램을 물고 있었다.`);
}

/** 남의 굽기가 돌면 «죽이지 않고 물러난다»(트랙 §0 겹침 규율). 램 바닥도 같이 지킨다. */
function 자리비었나(라벨) {
  const 끝시각 = Date.now() + 기다림상한분 * 60 * 1000;
  let 알렸나 = false;
  for (;;) {
    고아걷기();
    const 남 = 블렌더수();
    const 램 = 여유램MB();
    if (남 === 0 && 램 >= 램바닥MB) {
      if (알렸나) 말(`  ▶ 자리가 났다 — 램 ${램}MB · ${시각()}`);
      return true;
    }
    if (Date.now() > 끝시각) {
      말(`  ⏭ ${기다림상한분}분을 기다려도 자리가 안 났다(블렌더 ${남} · 램 ${램}MB) — ${라벨} 건너뛴다.`);
      return false;
    }
    if (!알렸나) {
      말(`  ⏳ 기다린다 — 블렌더 ${남}개 · 여유 램 ${램}MB(바닥 ${램바닥MB}) · ${시각()}`);
      알렸나 = true;
    }
    spawnSync(노드, ['-e', 'setTimeout(()=>{},60000)'], { timeout: 65000 });
  }
}

function 단계(이름, 인자들) {
  말(`\n■ ${이름} — ${시각()}`);
  if (!자리비었나(이름)) return;
  const 시작 = Date.now();
  const r = spawnSync(노드, 인자들, { cwd: 루트, stdio: 'inherit' });
  말(`■ ${이름} 끝 — 종료코드 ${r.status} · ${Math.round((Date.now() - 시작) / 60000)}분 · ${시각()}`);
  /* 🔴 종료코드로 성패를 판정하지 «않는다» — 판정은 까몽굽기.js 안에서 «파일 시각 + 종료상태»
   *   두 축이 같이 한다. 여기서는 걸린 시간만 적는다. */
}

말(`■■ 밤샘 0829 시작 — ${new Date().toLocaleString('ko-KR')} · pid ${process.pid}`);
말(`   여유 램 ${여유램MB()}MB · 블렌더 ${블렌더수()}개`);
말('   과녁 = 까몽 감정 세트 7장(몸 2 · 누끼 5) · 700px · 샘플 96 · CPU');

/* ① 몸 둘 — 으쓱·민망 «신규». 놀람·윙크·졸림은 이미 700 이라 손대지 않는다(자보다 낡았지만
 *   그 자의 이동은 «두 표정을 더한» 것뿐이라 기존 셋의 그림이 안 바뀐다 — 아래 🔑).
 *   🔑 08-29 자 이동(`95cd4eded`)은 **덧붙이기다**: `구슬눈(부호, 배=1.0, 곁눈=0.0)` 로 인자를
 *     «기본값 0» 으로 늘렸고 `elif 표정 == '으쓱'/'민망'` 두 갈래를 더했다. 기존 표정이 지나는
 *     길은 한 줄도 안 바뀌었다 ⇒ 다시 구우면 같은 그림이 나온다(시간만 태운다). */
단계('① 까몽 몸 둘 — 으쓱·민망 신규 (700px · 시안 등급)',
  ['tools/까몽굽기.js', '--표정', '으쓱,민망', '--너비', '700', '--시트없이']);

/* ② 누끼 다섯 — `영상/컷맞추기.js` 가 «까몽누끼컷» 창구로 이걸 집는다. 지금은 3컷뿐이라
 *   영상이 세 표정에 갇혀 있다. 확정 3의 누끼(1024)는 그대로 두고 시안 다섯을 700 으로 더한다. */
단계('② 까몽 누끼 다섯 — 영상 통로가 쓰는 알파 컷 (700px · 투명=1)',
  ['tools/까몽굽기.js', '--표정', '놀람,윙크,졸림,으쓱,민망', '--누끼', '--너비', '700', '--시트없이']);

/* ③ 판정 지면 — 🔑 굽기와 지면은 한 벌이다(트랙 §0). 굽고 시트를 안 그리면 유호님이 폴더를 보셔야 한다.
 *   앞 두 단계는 `--시트없이` 로 돌렸다: 매 단계마다 그리면 중간 판이 최종 판인 척 남는다. 여기서 한 번만 그린다. */
단계('③ 까몽 시안 지면 다시 그리기 (docs/까몽_시안.html)', ['tools/까몽시트.js']);

말(`\n■■ 밤샘 0829 끝 — ${new Date().toLocaleString('ko-KR')}`);
말('   🔴 굽고 «끝»이 아니다 — `tools/lib/마스코트자산.js` 의 `까몽컷` 은 표정마다 «누끼가 있나»를');
말('      boolean 으로 쥔다. 놀람·윙크·졸림·으쓱·민망 다섯이 지금 false 다. **누끼를 구웠으면 true 로**');
말('      바꿔야 `까몽누끼컷` 이 그 다섯을 내주고 영상·지면이 쓴다(안 바꾸면 누끼 가드가 「없다」로 던진다).');
말('      🔑 이것이 정본 §10 의 「굽기와 등재는 한 벌」 — 08-26 에 구운 셋을 08-29 까지 아무 코드도 몰랐다.');
말('   🔎 아침에 볼 것 ① 지면: docs/까몽_시안.html — 여덟 칸이 다 차 있나');
말('   🔎 아침에 볼 것 ② 실물: docs/캐릭터/친구공방_0825/{,누끼/} — 몸 8 · 누끼 8');
말('   🔎 아침에 볼 것 ③ 창구: node -e "const M=require(\'./tools/lib/마스코트자산.js\');console.log(M.까몽누끼컷)"');
