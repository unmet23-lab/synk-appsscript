#!/usr/bin/env node
/**
 * 엔진 히어로 굽기 — 소개서 7벌의 표지 얼굴을 «부품»이 아니라 «사진»으로 굽는다.
 *   (유호 교정 09-01 「요소가 부족해 · 저정도 요소나 재질을 쓰는 것도 탈락 · 훨씬 더 명품화」)
 *
 * ■ 무엇이 다른가 — 같은 물건인데 «부품»과 «히어로»는 다른 그림이다
 *   `요소부품굽기.js`(부품) = 투명 알파 두 층 · 평평한 조명 · 1100px.
 *      어느 배경에도 얹히는 것이 일이라 **무대도 심도도 없다** — 그래서 크게 키우면 밋밋하다.
 *      09-01 에 표지가 그 부품을 그대로 키워 쓰다가 「탈락」이 났다.
 *   이 도구(히어로) = **무대 위에 놓인 한 장의 사진**. 판(밤천)을 살리고 · 결 조명으로 섬유를 세우고 ·
 *      얕은 심도로 뒤를 눕힌다. 로고배지·플레이팅이 «명품»으로 읽힌 문법이 정확히 이 셋이다.
 *
 * ■ 레시피의 근거 (전부 요소굽기.py 가 이미 쥔 손잡이 — 새 렌더 코드를 안 짓는다)
 *   · `조명=결광2` — 펠트 «결»의 조명(키를 작고 가깝게 = 자연 비네트 + 은은한 후광).
 *     🔴 `식탁`(창빛)을 쓰지 않는다: 그 조명은 **내려보기 카메라(40~59°) 전용**이고
 *        우리 요소들은 세운 물건(84~90°)이라 빛이 «스치기만» 한다(요소굽기.py 조명 절 실측).
 *        카메라는 형태 함수가 쥐므로 인자로 못 눕힌다 — 조명을 카메라에 맞추는 쪽이 맞다.
 *   · `투명=0` — 판을 살린다. 알파로 오려내면 물건이 «떠서» 스티커가 된다(룸장면 §3-4 ③ 「뒤」).
 *     지면은 검은 무대라 밤천 판이 그대로 이어진다.
 *   · `심도` + `조리개=1.4` — 부품 기본값(0.9)보다 조여 주인공의 실땀은 살리고 뒤만 눕힌다.
 *     ⚠더 열면(수 작게) 실땀까지 뭉갠다 — 히어로는 «크게 보는» 그림이라 그 선이 부품보다 빡빡하다.
 *   · `색관리=Khronos PBR Neutral` — 제품 자산 렌더의 자. AgX 는 채도를 눌러 「탁한 회갈색」을
 *     만든다(08-24 「색이 씻긴다」의 진범). 명품 재굽기가 같은 이유로 이 자로 갔다.
 *   · 너비 1800 · 샘플 320 — 표지는 지면에서 가장 크게 서는 그림이다(부품은 1100/160).
 *
 * ■ 무엇을 굽나 — 엔진마다 «자기 물건» 한 점 (뜻이 맞는 자리에만 · 배정 근거는 표에)
 *   형태·옵션은 `요소부품굽기.js` 부품표에서 그대로 가져온다(레시피를 두 곳에 적지 않는다).
 *
 * ■ 🔴 지금 굽지 않는다 — 밤 대기열 몫이다(유호 지시 09-01 「전부 대기열로 올려줘 지금 바로 굽지 마」).
 *   09-01 18시 실측 여유 램 0.87GB · 문지기 바닥 6,000MB. 낮에 걸면 08-30 의 「38분에 0장」을 다시 산다.
 *   부르는 자리 = `tools/밤샘_0902.js` ④단계(자체 램문지기를 지난다).
 *
 * 사용:  node tools/엔진히어로굽기.js                 (안 구운 것만)
 *        node tools/엔진히어로굽기.js --다시          (있어도 다시)
 *        node tools/엔진히어로굽기.js --엔진 Reed     (하나만)
 *        node tools/엔진히어로굽기.js --분모          (무엇이 났고 무엇이 안 났나 · 굽지 않는다)
 * 뒤처리: 굽고 나면 `python tools/룸자산화.py` → `docs/Loom_자산/구운재질.json` 에 실리고,
 *        원고의 `<!--히어로:이름-->` 이 그것을 부른다(스킨 = tools/펠트문서.js).
 */
'use strict';
const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const 루트 = path.resolve(__dirname, '..');
const { 블렌더 } = require('./세트굽기.js');
const 밖 = path.join(루트, 'docs', 'Loom_자산', '구움');

/* ── 배정 — 엔진마다 «자기 물건» ────────────────────────────────────────────────
 * 🔑 뜻이 맞는 자리에만 준다. 억지로 채우면 그림이 «벽지»가 된다(Loom 설계 §3-4 ②).
 * 🔑 이름은 `히어로_<엔진>` — 부품(`요소_*`)과 한 폴더에 사니 이름으로 갈래가 갈려야 한다. */
const 배정 = [
  { 엔진: 'Core',   형태: '게이지고리', 옵션: { 진행: '0.68' }, 까닭: '두뇌 = 차오르는 이해' },
  { 엔진: 'Loom',   형태: '폼폼',       옵션: {},               까닭: '재질 그 자체 — 털공' },
  { 엔진: 'Vellum', 형태: '기호',       옵션: { 기호: '말풍선' }, 까닭: '닿는 면 = 말이 오가는 자리' },
  { 엔진: 'Trail',  형태: '매듭',       옵션: {},               까닭: '떠난 뒤에도 잇는다 = 맺음' },
  { 엔진: 'Prism',  형태: '기호',       옵션: { 기호: '차트' },  까닭: '분포로 갈라 보여준다' },
  { 엔진: 'Temper',형태: '도장',       옵션: { 본문: '참' },    까닭: '판정·담금질의 도장' },
  { 엔진: 'Reed',   형태: '녹음',       옵션: { 상태: '말하는중' }, 까닭: '소리의 물건 — 파형 자수' },
];

/* 히어로 레시피 — 부품과 갈리는 값만 여기 적는다(같은 값은 요소굽기.py 기본이 진다).
 *
 * 🔴 **색관리를 여기서 넘기지 않는다 — 2026-09-03 에 걷었다.**
 *   이 표에 `색관리: 'Khronos PBR Neutral'` 이 박혀 있었다. 그 자는 **08-24 낮에 222장을
 *   완주하고 전면 반려당한 바로 그것**이다 — 유호 반려문 「현실에서 사는 느낌이 안 나.
 *   그냥 AI로 만든 쨍한 느낌밖에」. 그날 밤 정본이 **AgX + Punchy** 로 확정됐다(결정.md).
 *   그런데 09-01 히어로 설계가 「제품사진 = PBR 중립」이라는 «내 추론»으로 그 자를 되살렸고,
 *   09-03 에 유호님이 같은 반려를 다시 하셨다 — 「왜 이렇게 쨍하게 나와」.
 *   ⇒ 색은 요소굽기.py 기본(AgX + Punchy)이 진다. 여기서 덮지 않는다.
 *   🔑 배운 것: **「사진처럼」은 색관리 이름이 아니라 무대·조명·심도가 만든다.** 그리고
 *      펠트 털의 디테일은 가닥 사이 미세 명암이라, 감쇠 없는 자에서는 흰 털이 통째로
 *      «한 덩어리 빛»이 된다(요소굽기.py 5535행 주석 · NPC·떡볶이에서 실물 확인).
 *      09-03 에 게이지 고리가 «안개»로 나온 것도 조리개가 아니라 이 자 탓이었다.
 */
const 레시피 = {
  조명: '결광2',
  투명: '0',
  실감: '심도',
  조리개: '1.4',
  샘플: '320',
  너비: '1800',
};

const 인자 = (() => {
  const a = {}; const v = process.argv.slice(2);
  for (let i = 0; i < v.length; i += 1) {
    if (!v[i].startsWith('--')) continue;
    a[v[i].slice(2)] = (v[i + 1] && !v[i + 1].startsWith('--')) ? v[i += 1] : '1';
  }
  return a;
})();

const 산출 = (b) => path.join(밖, `히어로_${b.엔진}.png`);

function 분모() {
  console.log(`■ 엔진 히어로 분모 — ${배정.length}장`);
  let 남 = 0;
  for (const b of 배정) {
    const 있 = fs.existsSync(산출(b));
    if (!있) 남 += 1;
    console.log(`  ${있 ? '✅' : '⬜'} ${b.엔진.padEnd(7)} ${b.형태.padEnd(6)} ${b.까닭}`);
  }
  console.log(`\n  합계 ${배정.length} = 구움 ${배정.length - 남} + 안 구움 ${남}`);
  console.log('  ▶ 굽기는 밤 대기열이 부른다 — tools/밤샘_0902.js ④단계(램문지기를 지난다)');
  return 남;
}

function main() {
  if (인자['분모']) { 분모(); return; }
  const BL = 블렌더();
  if (!BL) { console.error('🔴 blender.exe 를 못 찾았다 — BLENDER_EXE 로 경로를 준다.'); process.exit(1); }
  fs.mkdirSync(밖, { recursive: true });

  const 고른 = 인자['엔진'] ? 인자['엔진'].split(',').map((s) => s.trim()) : null;
  const 목록 = 고른 ? 배정.filter((b) => 고른.includes(b.엔진)) : 배정;
  if (!목록.length) {
    console.error(`🔴 모르는 엔진 — 아는 것은 ${배정.map((b) => b.엔진).join('·')}`);
    process.exit(1);
  }
  const 다시 = !!인자['다시'];
  console.log(`■ 엔진 히어로 굽기 — ${목록.length}장 · ${레시피.너비}px · 샘플 ${레시피.샘플} · 조명 ${레시피.조명} · 심도 f/${레시피.조리개}`);

  let 난것 = 0;
  for (const b of 목록) {
    const 출력 = 산출(b);
    if (!다시 && fs.existsSync(출력)) { console.log(`  · 이미 있다 — ${path.basename(출력)}`); continue; }
    const 옵션 = Object.entries(b.옵션).map(([k, v]) => `${k}=${v}`);
    const 인자들 = [
      '--background', '--factory-startup', '--python', path.join(루트, 'tools', '요소굽기.py'), '--',
      `형태=${b.형태}`, ...옵션,
      `조명=${레시피.조명}`, `투명=${레시피.투명}`, `실감=${레시피.실감}`, `조리개=${레시피.조리개}`,
      /* 색관리는 «안 넘긴다» — 요소굽기.py 기본(AgX + Punchy)이 정본이다(위 레시피 주석). */
      `샘플=${레시피.샘플}`, `너비=${레시피.너비}`,
      '장치=GPU', `출력=${출력}`,
    ];
    const 시작 = Date.now();
    const r = spawnSync(BL, 인자들, { cwd: 루트, stdio: 'inherit' });
    const 분 = ((Date.now() - 시작) / 60000).toFixed(1);
    /* 완주 판정은 **파일**로 한다 — 블렌더는 렌더가 반만 나가도 exit 0 을 낸다(밤굽기 규율). */
    if (r.status !== 0 || !fs.existsSync(출력)) {
      console.error(`  🔴 ${b.엔진} 실패 — 종료 ${r.status} · 파일 ${fs.existsSync(출력) ? '있음' : '없음'} (${분}분)`);
      continue;
    }
    난것 += 1;
    console.log(`  ✅ ${b.엔진}  ${path.basename(출력)}  ${(fs.statSync(출력).size / 1024).toFixed(0)}KB · ${분}분`);
  }
  console.log(`\n■ 끝 — ${난것}/${목록.length}장`);
  console.log('  ▶ 다음: python tools/룸자산화.py  →  node tools/펠트문서.js --전량');
  console.log('  🔑 «좋은가»는 여기서 안 잰다 — 유호님 눈이 판정 축이다.');
}

if (require.main === module) main();
module.exports = { 배정, 레시피 };
