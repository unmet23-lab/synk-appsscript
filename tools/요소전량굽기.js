/** 블렌더 찾기 — 오브굽기.js 와 같은 순서(환경변수 → 표준 설치 경로). */
function 블렌더() {
  if (process.env.BLENDER_EXE && fs.existsSync(process.env.BLENDER_EXE)) return process.env.BLENDER_EXE;
  const 뿌리들 = ['C:\\Program Files\\Blender Foundation', 'C:\\Program Files (x86)\\Blender Foundation'];
  for (const b of 뿌리들) {
    if (!fs.existsSync(b)) continue;
    for (const d of fs.readdirSync(b).sort().reverse()) {
      const p = path.join(b, d, 'blender.exe');
      if (fs.existsSync(p)) return p;
    }
  }
  return null;
}

/** PNG 가로폭 — IHDR 은 규격상 첫 청크라 앞 24바이트면 읽힌다(라이브러리 없이). */
function 가로폭(파일) {
  let fd;
  try {
    fd = fs.openSync(파일, 'r');
    const b = Buffer.alloc(24);
    if (fs.readSync(fd, b, 0, 24, 0) < 24) return 0;
    if (b.toString('latin1', 1, 4) !== 'PNG') return 0;
    return b.readUInt32BE(16);
  } catch { return 0; } finally { if (fd !== undefined) fs.closeSync(fd); }
}

function main() {
  const BL = 블렌더();
  if (!BL) { console.error('🔴 blender.exe 를 못 찾았다 — BLENDER_EXE 로 경로를 준다.'); process.exit(1); }

  let 대상 = 부품표;
  if (인자['것']) {
    const 고른 = 인자['것'].split(',').map((s) => s.trim());
    const 모름 = 고른.filter((n) => !부품표.some((k) => k.이름 === n));
    if (모름.length) { console.error('🔴 모르는 부품:', 모름.join(', ')); process.exit(2); }
    대상 = 부품표.filter((k) => 고른.includes(k.이름));
  }

  // 이어굽기 — 이미 그 너비인 판은 건너뛴다. 「합계 = 굽는다 + 건너뛴다」로 찍어 조용한 0 을 막는다.
  const 전체 = 대상.length;
  let 건너뜀 = [];
  if (!인자['다시']) {
    건너뜀 = 대상.filter((k) => 가로폭(path.join(루트, k.밖, k.파일)) === Number(너비));
    대상 = 대상.filter((k) => !건너뜀.includes(k));
  }
  console.log(`■ 요소 전량 굽기 ${너비}px · GPU — 합계 ${전체} = 굽는다 ${대상.length} + 건너뛴다 ${건너뜀.length}`);
  if (건너뜀.length) console.log(`  (이미 ${너비}px: ${건너뜀.map((k) => k.이름).join(', ')})`);
  if (!대상.length) { console.log('■ 굽을 것이 없다 — 다시 구우려면 --다시'); return; }
  const 시작 = Date.now();
  let 실패 = 0;

  대상.forEach((k, i) => {
    const 파일 = path.join(루트, k.밖, k.파일);
    fs.mkdirSync(path.dirname(파일), { recursive: true });
    process.stdout.write(`  [${String(i + 1).padStart(2)}/${대상.length}] ${k.이름.padEnd(13)} `);
    const r = spawnSync(BL, [
      '-b', '-P', path.join(루트, 'tools', '요소굽기.py'), '--',
      `형태=${k.형태}`, `샘플=${k.샘플 || '96'}`, `너비=${너비}`, '장치=GPU',
      ...(k.더 || []), `출력=${파일}`,
    ], { cwd: 루트, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    // ⚠blender 는 스크립트가 죽어도 exit 0 을 낼 수 있다 — 파일로 판정한다(오브굽기.js 와 같은 규율).
    const 됐나 = r.status === 0 && fs.existsSync(파일) && fs.statSync(파일).size > 2048;
    if (됐나) console.log(`✅ ${Math.round(fs.statSync(파일).size / 1024)}KB`);
    else { console.log('🔴 실패'); 실패++; if (r.stderr) console.log('     ' + String(r.stderr).trim().split('\n').slice(-2).join(' / ')); }
  });

  const 초 = Math.round((Date.now() - 시작) / 1000);
  console.log(`■ 끝 — 성공 ${대상.length - 실패} · 실패 ${실패} · ${Math.floor(초 / 60)}분 ${초 % 60}초`);
  process.exit(실패 ? 1 : 0);
}

