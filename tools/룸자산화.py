# 🔴 **생것(raw) PNG 은 원본이 아니다.** 제미나이가 낸 `<이름>.png` 는 흰 바탕이 붙은 채라
#   알파가 통째로 불투명이다. 그대로 실으면 알파 상자가 화면 전체가 되어 부품이 «흰 네모»가 된다.
#   흰 바탕을 걷어 `<이름>.avif` 로 담는 것은 다듬는 자(`tools/공방뒤처리.py`)의 몫이고,
