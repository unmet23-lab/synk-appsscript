const 절대 = (rel) => path.join(ROOT, rel);

/** 한 지면의 «있어야 할 판» — 늘 먼저 뜯고 다시 얹으므로 멱등이다. */
function 굽는다(rel, 지면) {
  const 원본 = fs.readFileSync(절대(rel), 'utf8');
  const r = 얹기모듈.얹기(원본, { 지면 });
  return { 원본, ...r };
}

/** 등록 안 된 채 안 입은 지면 — 생성기 몫일 수 있으므로 ❔ 로만 낸다(적색 아님). */
function 미등록들() {
  const 등록경로 = new Set(등록.map(([rel]) => rel));
  const 점검 = require('./lib/지면방.js').점검();
  return 점검.갈래.입는다
    .filter((r) => !등록경로.has(r.경로))
    .filter((r) => !얹기모듈.얹힘(fs.readFileSync(절대(r.경로), 'utf8')))
    .map((r) => r.경로);
}

function 본다() {
  const 적용 = process.argv.includes('--적용');
  let 낡음 = 0; let 새로 = 0; let 그대로 = 0; const 못얹음 = [];

  console.log('■ 지면얹기 — 손 HTML 에 Loom 부품을 입힌다\n');
  for (const [rel, 지면, 사유] of 등록) {
    const { 원본, html, 훅, 얹힘, 같나, 사유: 막힌사유, 범위흠 } = 굽는다(rel, 지면);
    if (!얹힘) {
      못얹음.push([rel, 막힌사유 || '알 수 없음']);
      console.log(`  🔴 ${rel}\n       ${지면} · ${막힌사유}`);
      if (범위흠) console.log(`       ${범위흠}`);
      continue;
    }
    /* 🔑 「같나」는 `얹기` 가 낸 것을 그대로 쓴다 — 여기서 `html === 원본` 으로 다시 견주면
       체크아웃이 CRLF 로 내려준 지면이 **내용과 무관하게** 전부 「낡았다」가 된다
       (09-03 실측: 등록 12 중 8벌 · `git diff` 0줄 · `tools/lib/loom얹기.js` 의 `최신` 머리말). */
    if (같나) { 그대로 += 1; console.log(`  ✅ ${rel}  (${지면} · 훅 ${훅.length})`); continue; }
    const 이미 = 얹기모듈.내가얹음(원본);
    if (이미) 낡음 += 1; else 새로 += 1;
    console.log(`  ${적용 ? '✍' : '🔴'} ${rel}  (${지면} · 훅 ${훅.length}) — ${이미 ? '얹힌 CSS 가 낡았다' : '아직 안 입었다'}`);
    console.log(`       ${사유}`);
    if (적용) fs.writeFileSync(절대(rel), html);
  }

  const 미등록 = 미등록들();
  if (미등록.length) {
    console.log(`\n  ❔ 안 입었는데 이 목록에 없는 지면 ${미등록.length} — **생성기 몫일 수 있다**(적색 아님):`);
    for (const r of 미등록) console.log(`     · ${r}`);
  }

  console.log(`\n  분모 ${등록.length} = 그대로 ${그대로} + ${적용 ? '얹음' : '얹어야'} ${새로 + 낡음}(새 ${새로} · 낡음 ${낡음}) + 못얹음 ${못얹음.length}`);
  if (못얹음.length) return 1;                       // 훅 0·자리 없음 = 사람이 봐야 한다
  if (!적용 && 새로 + 낡음 > 0) return 1;             // 낡은 채 초록으로 지나가지 않는다
  return 0;
}

if (require.main === module) process.exit(본다());
