#!/usr/bin/env node
'use strict';
/* 변이 검사의 공용 통로 — 「변이 N/N」을 **검증된 숫자**로 만든다.
 *
 * ■ 왜 있나 (같은 병 5번째 · 전부 실측이다)
 *   이 저장소는 회귀의 탐지력을 «변이»로 증명한다 — 소스를 일부러 망가뜨려 회귀가 빨개지는지 본다.
 *   그런데 그 하네스를 **세션마다 스크래치패드에 새로 써 왔고**(저장소에 통로가 0이었다), 다섯 번
 *   조용히 틀렸다. 다섯 다 새는 방향이 「초록」이라 눈에 안 띄었다:
 *     ① 2026-08-07  적색을 TAP `not ok` 로 셌는데 `node --test` **기본 리포터는 `✖` 를 쓴다**
 *                   → 진짜 적색 4건이 전부 「적색 0건」으로 읽혔다  (memory mutation-test-side-effects)
 *     ② handoff-owner-by-name  변이 하네스가 **미측정을 「못 잡음」으로** 읽었다
 *     ③ remote-ci-verify       변이시험 사본이 git init 안 하면 통째로 skip
 *     ④ F470 (08-15)  치환 정규식 불일치로 **조용한 미적용** — 그 초록을 「구멍 없음」으로 읽을 뻔했다
 *     ⑤ F477 (08-15)  CRLF 파일에 `\n` 정규식 → 변이 2건 미적용, 「변이 4/4」가 나올 뻔했다
 *
 * ■ 🔴 ⑤는 사고가 아니라 이 저장소의 기본 상태다 (2026-08-15 실측)
 *   `core.autocrlf=true` + `.gitattributes` 가 LF 를 **일부 경로에만** 고정한다.
 *   그래서 추적 중인 `.js` **72개 중 CRLF 63 · 순LF 0 · 섞임 9** — 작업본은 사실상 전부 CRLF다.
 *   `String.replace` 는 안 맞으면 예외도 경고도 없이 **원본을 그대로 돌려준다**. 그러면
 *   변이본 === 원본이라 시험이 초록이고, 그 초록은 「회귀가 못 잡았다」와 **모양이 같다.**
 *   즉 `\n` 을 쓴 변이 정규식은 이 저장소에서 상시 사각이다.
 *
 * ■ 이 통로가 못 하게 만드는 것 셋 (판정을 두 갈래로 접지 않는다)
 *   ㉠ **미적용을 판정으로 접기** — 찾기가 0번/2번 이상 맞으면 그건 결과가 아니라 «안 쟀다»다.
 *      포획도 구멍도 아닌 **세 번째 칸**으로 찍고, 그 건이 있으면 「N/N」을 아예 안 낸다.
 *   ㉡ **세는 층이 죽은 채 세기** — 적색 판정의 권위는 **exit status** 다(사람글 파싱이 아니다).
 *      TAP 은 «이름과 분모»에만 쓴다. 둘이 어긋나면(exit≠0 인데 실패 0건) 그것도 미측정이다.
 *   ㉢ **0건 실행을 통과로** — 기준선이 초록이어도 **몇 건 돌았는지**를 함께 안 내면 못 가른다(F207).
 *      실측: `--test-name-pattern` 이 0건을 고르면 exit 0 이다 — 통과와 완전히 같은 모양이다.
 *
 * ■ 🔑 기준선을 같은 통로로 함께 돌리는 것이 ①의 유일한 탐지기다
 *   기준선이 「적색 0」인 건 정상이라 그것만으론 못 본다. 그래서 여기선 기준선에 **초록 + 분모>0**
 *   을 둘 다 요구하고, 하나라도 어긋나면 변이를 한 건도 안 돌리고 멈춘다 — 그 판의 모든 숫자가
 *   이미 무의미하기 때문이다.
 *
 * ■ ⚠ 이 통로가 «안» 지는 것 (억지로 넓히지 않는다 — 넓히면 하루 만에 꺼진다)
 *   · **부작용**: 안전 가드를 끄는 변이(`--dry`·`if (!force)` 계열)는 그 가드가 막던 일을 실제로
 *     실행한다. 2026-08-01 에 `bump-version` 변이가 진짜 채번을 태워 **origin 에 태그를 push** 했다.
 *     여기선 그걸 못 막는다 — 격리는 호출부가 진다(`환경` 으로 `SYNK_TEST_SRC_ROOT` 를 넘긴다 ·
 *     그 이음매를 가진 시험은 7벌뿐이다 · memory `mutation-test-side-effects`).
 *   · **원복**: 제자리 변이는 `finally` 로 되돌리고 바이트까지 대조하지만, 프로세스가 강제 종료되면
 *     그 자리에 변이본이 남는다. 그때는 `git diff` 가 드러낸다(그래서 변이 대상은 미커밋이 아니어야 한다).
 *
 * 쓰는 법 — 스크래치패드에 **계획만** 쓰고 이 도구를 CLI 로 부른다:
 *   // 계획.js — 부르지 않는다. exports 만 한다.
 *   module.exports = {
 *     시험: ['tests/보드유령.test.js'],
 *     변이들: [
 *       { 이름: '문턱을 지운다', 파일: 'tools/board-move.js', 찾기: 'if (넘었나)', 바꾸기: 'if (false)' },
 *     ],
 *   };
 *   // 그리고: node tools/변이.js <계획.js>
 *
 * 🔴 계획이 **스스로 `변이검사()` 를 부르면 안 된다** (2026-08-15 실측 · 옛 머리말이 그렇게 가르쳤다).
 *   그러면 계획을 `require` 하는 순간 한 번 돌고, CLI 가 빈 exports 로 **또 한 번** 부른다 —
 *   화면에는 「변이 8/8」이 멀쩡히 찍힌 **뒤에** 스택 트레이스가 붙어서, 읽는 사람이 그 판을
 *   실패로 읽는다. 숫자는 맞는데 화면이 틀린 자리다. 아래 CLI 가 이제 그 모양을 이름 대고 막는다.
 */

const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');

/** 그 파일이 실제로 쓰는 줄끝 — 「무엇을 재는지」를 먼저 정하는 자리다(추정하지 않는다). */
function 줄끝(원문) {
  return /\r\n/.test(원문) ? '\r\n' : '\n';
}

/**
 * 찾기 문자열을 **그 파일의 줄끝으로 번역해서** 센다 — ⑤가 난 자리를 원천에서 없앤다.
 * 호출부는 늘 `\n` 으로 쓰면 되고, CRLF 인지 아닌지 알 필요가 없다.
 * @returns {{횟수:number, 실제찾기:string}}
 */
function 맞춰보기(원문, 찾기) {
  const eol = 줄끝(원문);
  const 실제찾기 = eol === '\n' ? 찾기 : 찾기.split('\n').join('\r\n');
  let 횟수 = 0;
  let i = 원문.indexOf(실제찾기);
  while (i !== -1) { 횟수 += 1; i = 원문.indexOf(실제찾기, i + Math.max(1, 실제찾기.length)); }
  return { 횟수, 실제찾기 };
}

/**
 * 변이를 만든다. **판정을 세 갈래로 낸다** — 「적용」 아니면 못 잰 이유를 이름으로 돌려준다.
 * 여기서 `못찾음`·`모호` 를 예외로 안 던지는 이유: 한 건이 안 걸려도 나머지는 재야 하고,
 * 그 건은 **통과로 세지 않고 따로 찍히면** 되기 때문이다(그게 F477 의 처방이다).
 * @returns {{상태:'적용'|'못찾음'|'모호', 변이본?:string, 횟수:number}}
 */
function 적용(원문, 찾기, 바꾸기) {
  if (typeof 찾기 !== 'string' || 찾기 === '') {
    return { 상태: '모호', 횟수: 0, 사유: '찾기가 빈 문자열이다' };
  }
  const { 횟수, 실제찾기 } = 맞춰보기(원문, 찾기);
  if (횟수 === 0) return { 상태: '못찾음', 횟수 };
  /* 두 곳 이상 맞으면 **어디를 망가뜨렸는지 모른 채** 숫자가 나온다 — 그건 측정이 아니다.
   * Edit 도구가 같은 이유로 유일성을 요구한다. 전부 바꾸고 싶으면 찾기를 좁히는 것이 맞다. */
  if (횟수 > 1) return { 상태: '모호', 횟수 };
  const eol = 줄끝(원문);
  const 실제바꾸기 = eol === '\n' ? 바꾸기 : 바꾸기.split('\n').join('\r\n');
  const 변이본 = 원문.replace(실제찾기, () => 실제바꾸기);
  /* 벨트+멜빵 — 위 셋을 다 지나고도 바이트가 같으면 그건 «찾기 === 바꾸기» 다.
   * 그 건을 초록으로 세면 F477 이 그대로 재발한다. */
  if (변이본 === 원문) return { 상태: '모호', 횟수, 사유: '바꾼 결과가 원본과 같다' };
  return { 상태: '적용', 변이본, 횟수 };
}

/** TAP 요약에서 분모를 뽑는다. **없으면 `null`** — 「0」으로 접지 않는다(0 과 모름은 다르다). */
function 분모뽑기(출력) {
  const 집기 = (이름) => {
    const m = 출력.match(new RegExp('^# ' + 이름 + ' (\\d+)$', 'm'));
    return m ? Number(m[1]) : null;
  };
  const 실패이름 = [];
  for (const 줄 of 출력.split(/\r?\n/)) {
    const m = 줄.match(/^\s*not ok \d+ - (.+?)\s*$/);
    if (m) 실패이름.push(m[1]);
  }
  return { 전체: 집기('tests'), 통과: 집기('pass'), 실패: 집기('fail'), 건너뜀: 집기('skipped'), 실패이름 };
}

/**
 * 「이 판을 잰 것으로 칠 수 있나」 — **판정은 여기 하나뿐이다**(두 곳에 적으면 갈라진다).
 * 순수 함수로 떼어 둔 이유: 이 판정의 회귀를 spawn 시나리오를 꾸며서 재려 하면 못 재는 칸이
 * 생긴다. 실제로 자기변이 M8·M10 이 그 사각으로 빠져나갔고, 떼어내고서야 픽스처로 물렸다.
 * @returns {string|null} 못 잰 이유(사람이 읽는 한 문장) · 잰 판이면 null
 */
function 미측정판정({ 적색, 상태코드, 오류, 요약 }) {
  if (오류) return `시험을 못 띄웠다(${오류.code || 오류.message})`;
  if (요약.전체 === null) return 'TAP 요약이 없다 — 리포터가 바뀌었거나 시험이 로드 전에 죽었다';
  if (요약.전체 === 0) return '0건 실행 — 통과와 같은 모양이라 분모 없이는 못 가른다(F207)';
  /* 🔴 ③의 실제 얼굴 — 「전부 skip」이다(실측 2026-08-15: skip 은 `# tests` 분모에 **그대로 센다**.
   *   한 건 통과 + 한 건 skip 이 `tests=2 pass=1 skipped=1` 로 나온다). 그래서 전체만 보면 안 보인다.
   *   판별식 = **통과 0 이면서 실패 0** — 그 판은 아무것도 검증하지 않았다. 통과 0 «만» 으로 접으면
   *   안 된다: 변이가 전 검사를 빨갛게 만든 판도 통과 0 인데 그건 정당한 포획이다. */
  if (요약.통과 === 0 && 요약.실패 === 0) {
    return `통과 0 · 실패 0 (전체 ${요약.전체} · skip ${요약.건너뜀 ?? '?'}) — 아무것도 검증되지 않았다`;
  }
  /* 판정층(exit)과 세는층(TAP)이 어긋나면 어느 쪽도 못 믿는다 — ①이 살던 자리가 정확히 여기다. */
  if (적색 && 요약.실패 === 0) return `exit=${상태코드} 인데 실패 0건 — 시험 밖에서 죽었다`;
  if (!적색 && 요약.실패 > 0) return `exit=0 인데 실패 ${요약.실패}건 — 판정층과 세는층이 어긋났다`;
  return null;
}

/**
 * 시험을 돌리고 **판정과 분모를 갈라서** 돌려준다.
 * 판정 권위 = exit status. TAP = 이름·분모 전용(㉡ — 사람글로 판정하지 않는다).
 */
function 시험돌리기(시험, 환경) {
  /* 🔴 `NODE_TEST_CONTEXT` 를 **반드시 지운다** (2026-08-15 실측 · 조건 하나만 바꿔 대조).
   *   `node --test` 는 자식 시험 프로세스에 이 변수를 심는다. 그걸 물려받은 손자 프로세스는
   *   `--test-reporter=tap` 을 줘도 TAP 을 **한 줄도 안 낸다**(v8 직렬화로 갈아탄다):
   *     평범한 env                 → '# tests' 있음
   *     NODE_TEST_CONTEXT=child-v8 → '# tests' 없음 ← 여기
   *   그러면 분모가 통째로 사라져 이 통로가 「미측정」만 낸다. 이 통로의 회귀가 자기 자신을
   *   시험 안에서 부르므로 **안 지우면 회귀가 원리상 못 돈다** — 리포터를 남의 환경에 맡기지 않는다. */
  const 자식환경 = { ...process.env, ...환경 };
  delete 자식환경.NODE_TEST_CONTEXT;

  const r = spawnSync(
    process.execPath,
    ['--test', '--test-reporter=tap', ...시험],
    { cwd: ROOT, encoding: 'utf8', env: 자식환경, maxBuffer: 64 * 1024 * 1024 },
  );
  const 출력 = (r.stdout || '') + (r.stderr || '');
  const 요약 = 분모뽑기(출력);
  const 적색 = r.status !== 0;

  /* 세는 층이 죽었는지 **그 자리에서** 본다 — 이게 ①이 10일간 안 보였던 이유다.
   * 판정 본문은 `미측정판정` 한 곳에만 산다(같은 판정을 두 곳에 적으면 갈라진다). */
  const 미측정 = 미측정판정({ 적색, 상태코드: r.status, 오류: r.error, 요약 });

  return { 적색, 상태코드: r.status, 미측정, ...요약 };
}

/**
 * 변이 검사 한 판. **기준선을 먼저 돌려 세는 층이 살아 있는지 증명한 뒤에만** 변이를 돈다.
 * @returns {{포획:number, 구멍:number, 미적용:number, 분모:number, 줄들:object[]}}
 */
function 변이검사({ 시험, 변이들, 환경 = {}, 조용히 = false }) {
  if (!Array.isArray(시험) || !시험.length) throw new Error('[변이] 돌릴 시험 파일이 0건이다');
  if (!Array.isArray(변이들) || !변이들.length) throw new Error('[변이] 변이가 0건이다');
  const 말 = (s) => { if (!조용히) console.log(s); };

  말('[변이] 기준선 — 변이 없이 돌린다(세는 층이 살아 있는지 증명하는 유일한 자리)');
  const 기준선 = 시험돌리기(시험, 환경);
  if (기준선.미측정) throw new Error(`[변이] 기준선이 미측정이다: ${기준선.미측정} — 이 판의 모든 숫자가 무의미하다`);
  if (기준선.적색) {
    throw new Error(
      `[변이] 기준선이 이미 적색이다(실패 ${기준선.실패}건: ${기준선.실패이름.slice(0, 3).join(' · ')}) — `
      + '변이가 잡은 것과 원래 빨간 것을 구별할 수 없다',
    );
  }
  말(`[변이] 기준선 초록 · 시험 ${기준선.전체}건 통과 — 분모가 섰다`);

  const 줄들 = [];
  for (const [i, v] of 변이들.entries()) {
    const 이름 = v.이름 || `변이 ${i + 1}`;
    const 절대 = path.isAbsolute(v.파일) ? v.파일 : path.join(ROOT, v.파일);
    const 원문 = fs.readFileSync(절대, 'utf8');
    const 만듦 = 적용(원문, v.찾기, v.바꾸기);

    if (만듦.상태 !== '적용') {
      const 사유 = 만듦.사유 || (만듦.상태 === '못찾음'
        ? `찾기가 0번 맞았다(줄끝=${줄끝(원문) === '\r\n' ? 'CRLF' : 'LF'})`
        : `찾기가 ${만듦.횟수}번 맞아 어디를 바꿨는지 모른다`);
      줄들.push({ 이름, 판정: '미적용', 사유 });
      말(`  ⚠ 미적용  ${이름} — ${사유}`);
      continue;
    }

    let 결과;
    try {
      fs.writeFileSync(절대, 만듦.변이본);
      결과 = 시험돌리기(시험, 환경);
    } finally {
      fs.writeFileSync(절대, 원문);
      const 되돌아왔나 = fs.readFileSync(절대, 'utf8') === 원문;
      if (!되돌아왔나) throw new Error(`[변이] 🔴 원복 실패 — ${v.파일} 에 변이본이 남았다. git diff 로 확인하라`);
    }

    if (결과.미측정) {
      줄들.push({ 이름, 판정: '미적용', 사유: 결과.미측정 });
      말(`  ⚠ 미적용  ${이름} — ${결과.미측정}`);
    } else if (결과.적색) {
      줄들.push({ 이름, 판정: '포획', 빨개진검사: 결과.실패이름 });
      말(`  ✔ 포획    ${이름} — 빨개진 검사: ${결과.실패이름.slice(0, 2).join(' · ') || '(이름 없음)'}`);
    } else {
      줄들.push({ 이름, 판정: '구멍' });
      말(`  ✖ 구멍    ${이름} — 망가뜨렸는데 ${결과.전체}건이 전부 초록이다`);
    }
  }

  const 포획 = 줄들.filter((r) => r.판정 === '포획').length;
  const 구멍 = 줄들.filter((r) => r.판정 === '구멍').length;
  const 미적용 = 줄들.filter((r) => r.판정 === '미적용').length;

  /* 보고 문장이 스스로 갈래를 밝힌다 — 「N/N」은 **미적용 0일 때만** 쓸 수 있는 말이다.
   * 미적용이 하나라도 있으면 분모가 거짓말을 하므로 그 표기를 아예 안 만든다(F207 · memory 0-분모). */
  말('');
  말(미적용 === 0
    ? `[변이] 변이 ${포획}/${포획 + 구멍}  (구멍 ${구멍} · 미적용 0)`
    : `[변이] 🔴 «N/N» 을 못 쓴다 — 미적용 ${미적용}건 = 안 쟀다. 포획 ${포획} · 구멍 ${구멍} · 미적용 ${미적용} (분모 ${줄들.length})`);

  return { 포획, 구멍, 미적용, 분모: 줄들.length, 기준선, 줄들 };
}

module.exports = { 변이검사, 적용, 맞춰보기, 줄끝, 시험돌리기, 분모뽑기, 미측정판정 };

if (require.main === module) {
  const 계획경로 = process.argv[2];
  if (!계획경로) {
    console.error('쓰는 법: node tools/변이.js <계획.js>');
    console.error('  계획 파일은 { 시험: [...], 변이들: [...] } 을 module.exports 한다 (머리말 참고)');
    process.exit(2);
  }
  const 계획 = require(path.resolve(계획경로));
  /* 계획이 스스로 돌고 빈 exports 를 남긴 모양 — 이름을 대고 막는다.
     안 막으면 「변이 N/N」 뒤에 스택 트레이스가 붙어 맞는 판이 실패로 읽힌다. */
  if (!계획 || !Array.isArray(계획.시험)) {
    console.error('\n🔴 계획 파일이 `시험` 배열을 exports 하지 않았다.');
    console.error('   계획이 스스로 `변이검사(...)` 를 부르고 있지 않은지 본다 — 계획은 **exports 만** 한다.');
    console.error('   (그 모양이면 계획을 require 할 때 한 번 돌고, 여기서 빈 계획으로 또 돈다:');
    console.error('    화면엔 맞는 「변이 N/N」이 찍힌 뒤 스택이 붙어서, 맞는 판이 실패로 읽힌다.)');
    process.exit(2);
  }
  const 결과 = 변이검사(계획);
  /* 미적용이 남았으면 **0 으로 끝내지 않는다** — 그 판은 통과가 아니라 미측정이다. */
  process.exit(결과.미적용 > 0 ? 3 : 0);
}
