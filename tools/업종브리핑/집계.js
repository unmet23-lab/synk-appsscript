const 퍼센트 = (a, b) => (b > 0 ? Math.round((a / b) * 100) : null);
const 한자리 = (x) => (Number.isFinite(x) ? Math.round(x * 10) / 10 : null);
const 날짜 = (s) => new Date(`${s}T00:00:00Z`);
const 날짜글 = (d) => d.toISOString().slice(0, 10);
const 달날 = (s) => `${Number(s.slice(5, 7))}월 ${Number(s.slice(8, 10))}일`;

function 지표묶음() {
  const 지표 = {};
  const 넣기 = (이름, 값, 단위, 출처, 설명) => {
    if (값 === null || 값 === undefined || (typeof 값 === 'number' && !Number.isFinite(값))) return;
    지표[이름] = { 값, 단위, 출처, 설명 };
  };
  return { 지표, 넣기 };
}

// ── 네이버 검색: 하루 값 → 주(월요일 시작) 평균, 해마다 지금 앞뒤 반년 안 정점 ─────────────
function 주평균(시작, 하루값) {
  const 주 = new Map();
  하루값.forEach((v, i) => {
    if (!Number.isFinite(v)) return;
    const d = new Date(날짜(시작).getTime() + i * 하루);
    const 월 = new Date(d.getTime() - ((d.getUTCDay() + 6) % 7) * 하루);
    const k = 날짜글(월);
    if (!주.has(k)) 주.set(k, []);
    주.get(k).push(v);
  });
  return [...주.entries()].filter(([, vs]) => vs.length === 7).map(([주, vs]) => ({ 주, 값: 한자리(vs.reduce((s, x) => s + x, 0) / 7) }));
}

/** 이번 해 기준일에서 k해 앞 같은 날을 가운데 두고 앞뒤 반년 안의 정점 주 — 다가올 정점과 지난 정점을 나눈다 */
function 해마다정점(주들, 기준일, 해수 = 3) {
  const 줄 = [];
  for (let k = 1; k <= 해수; k++) {
    const 가운데 = new Date(날짜(기준일)); 가운데.setUTCFullYear(가운데.getUTCFullYear() - k);
    const 앞 = 주들.filter((w) => { const t = 날짜(w.주).getTime(); return t > 가운데.getTime() && t <= 가운데.getTime() + 182 * 하루; });
    const 뒤 = 주들.filter((w) => { const t = 날짜(w.주).getTime(); return t <= 가운데.getTime() && t > 가운데.getTime() - 182 * 하루; });
    const 최고 = (ws) => (ws.length ? ws.reduce((a, b) => (b.값 > a.값 ? b : a)) : null);
    // 창 가장자리에 걸린 값은 봉우리가 아니다 — 가운데에서 두 주 안이고 건너편 첫 주가 더 높으면 뺀다(오르는 중인 비탈을 정점으로 읽지 않게)
    const 가장자리 = (p, 건너편) => p && 건너편 && Math.abs(날짜(p.주).getTime() - 가운데.getTime()) <= 14 * 하루 && 건너편.값 >= p.값;
    const 다가올 = 최고(앞), 지난 = 최고(뒤);
    줄.push({ 해: k, 다가올: 가장자리(다가올, 뒤[뒤.length - 1]) ? null : 다가올, 지난: 가장자리(지난, 앞[0]) ? null : 지난 });
  }
  return 줄;
}

/** 정점 주들의 달·날 범위. 기준(가운데 날들)을 주면 가운데에서 떨어진 날수로 줄 세워 해를 넘기는 범위가 뒤집히지 않게 한다 */
function 달날구간(주들, 가운데들 = null) {
  const 쌍 = 주들.map((w, i) => [w, 가운데들 ? 가운데들[i] : null]).filter(([w]) => Boolean(w));
  if (!쌍.length) return null;
  if (가운데들) {
    쌍.sort((a, b) => (날짜(a[0].주) - a[1]) - (날짜(b[0].주) - b[1]));
    const [첫, 끝] = [쌍[0][0].주.slice(5), 쌍[쌍.length - 1][0].주.slice(5)];
    const 월 = (s) => Number(s.slice(0, 2)), 일 = (s) => Number(s.slice(3, 5));
    if (첫 === 끝) return `${월(첫)}월 ${일(첫)}일`;
    return 월(첫) === 월(끝) && 일(첫) <= 일(끝) ? `${월(첫)}월 ${일(첫)}~${일(끝)}일` : `${월(첫)}월 ${일(첫)}일~${월(끝)}월 ${일(끝)}일`;
  }
  const ds = 쌍.map(([w]) => w.주.slice(5)).sort();
  const 월 = (s) => Number(s.slice(0, 2));
  const 일 = (s) => Number(s.slice(3, 5));
  const [a, b] = [ds[0], ds[ds.length - 1]];
  if (a === b) return `${월(a)}월 ${일(a)}일`;
  return 월(a) === 월(b) ? `${월(a)}월 ${일(a)}~${일(b)}일` : `${월(a)}월 ${일(a)}일~${월(b)}월 ${일(b)}일`;
}

function 검색집계(검색, 기준일, 넣기) {
  const 그림 = [];
  for (const 묶음 of 검색.묶음 || []) {
    const 주들 = 주평균(검색.시작, 묶음.하루 || []);
    if (주들.length < 60) continue;
    const 정점 = 해마다정점(주들, 기준일);
    const 이름 = 묶음.이름;
    const 가운데 = (k) => { const d = new Date(날짜(기준일)); d.setUTCFullYear(d.getUTCFullYear() - k); return d.getTime(); };
    const 다가올쌍 = 정점.filter((p) => p.다가올), 지난쌍 = 정점.filter((p) => p.지난);
    const 다가올 = 다가올쌍.map((p) => p.다가올), 다가올가운데 = 다가올쌍.map((p) => 가운데(p.해));
    const 지난 = 지난쌍.map((p) => p.지난), 지난가운데 = 지난쌍.map((p) => 가운데(p.해));
    // 다가올 정점이 지난 정점보다 높은 해가 많으면 「앞으로 오를」 묶음, 아니면 「정점을 지난」 묶음
    const 앞이큼 = 정점.filter((p) => p.다가올 && p.지난 && p.다가올.값 > p.지난.값).length;
    const 방향 = 앞이큼 * 2 >= 정점.length ? '앞으로 오름' : '정점 지남';
    // 두 해 넘게 봉우리가 잡혀야 범위를 말한다 — 한 해짜리를 「세 해 동안」으로 읽지 않게
    if (다가올.length >= 2) 넣기(`검색.${이름}.다가올정점`, 달날구간(다가올, 다가올가운데), '', '네이버 검색어 트렌드', `${이름} 검색이 지난 해들(${다가올.length}해) 가운데 지금부터 반년 안에서 가장 높았던 주의 범위`);
    if (지난.length >= 2) 넣기(`검색.${이름}.지난정점`, 달날구간(지난, 지난가운데), '', '네이버 검색어 트렌드', `${이름} 검색이 지난 해들(${지난.length}해) 가운데 지금 앞 반년 안에서 가장 높았던 주의 범위`);
    넣기(`검색.${이름}.흐름`, 방향, '', '네이버 검색어 트렌드', '세 해 가운데 다가올 정점이 지난 정점보다 높았던 해가 반 이상이면 앞으로 오름');
    const 마지막 = 주들[주들.length - 1];
    const 작년주 = 날짜글(new Date(날짜(마지막.주).getTime() - 364 * 하루));
    const 작년 = 주들.find((w) => w.주 === 작년주);
    if (작년 && 작년.값 > 0) 넣기(`검색.${이름}.작년대비`, 퍼센트(마지막.값, 작년.값), '%', '네이버 검색어 트렌드', `가장 최근 주(${마지막.주}) ${이름} 검색이 작년 같은 주의 몇 %인지`);
    그림.push({ 이름, 주들, 정점: 정점.map((p) => ({ 해: p.해, 다가올: p.다가올, 지난: p.지난 })) });
  }
  return 그림;
}

// ── 네이버 쇼핑: 비중·순위·하위 클릭 ───────────────────────────────────────
function 비중(줄) {
  const 합 = (줄 || []).reduce((s, x) => s + (Number(x.상대) || 0), 0);
  return (줄 || []).map((x) => ({ 이름: x.이름, 값: x.값, 비중: 합 > 0 ? Math.round((Number(x.상대) / 합) * 100) : null }));
}

function 쇼핑집계(쇼핑, 넣기, 강조연령 = null) {
  const 나이 = 비중(쇼핑.비중?.Age);
  for (const a of 나이) 넣기(`쇼핑.연령.${a.이름}`, a.비중, '%', '네이버 쇼핑인사이트', `분야 클릭 가운데 ${a.이름} 비중`);
  const 고른 = 강조연령?.length ? 나이.filter((a) => 강조연령.includes(a.이름)) : null;
  const 둘 = (고른?.length === 2 ? 고른 : [...나이].filter((a) => Number.isFinite(a.비중)).sort((a, b) => b.비중 - a.비중).slice(0, 2)).sort((a, b) => Number(a.값) - Number(b.값));
  if (둘.length === 2) {
    const 붙음 = Math.abs(Number(둘[1].값) - Number(둘[0].값)) === 10;
    const 이름 = 붙음 ? `${둘[0].이름.replace('대', '')}·${둘[1].이름}` : `${둘[0].이름}·${둘[1].이름}`;
    넣기('쇼핑.주연령', 이름, '', '네이버 쇼핑인사이트', 고른?.length === 2 ? '설정에서 정한 두 연령' : '분야를 가장 많이 누르는 두 연령');
    넣기('쇼핑.주연령비중', 둘[0].비중 + 둘[1].비중, '%', '네이버 쇼핑인사이트', '그 두 연령의 클릭 비중 합(반올림한 두 값의 합)');
  }
  const 기기 = 비중(쇼핑.비중?.Device);
  const 폰 = 기기.find((d) => d.값 === 'mo' || /모바일/.test(d.이름 || ''));
  if (폰) 넣기('쇼핑.모바일', 폰.비중, '%', '네이버 쇼핑인사이트', '분야 클릭 가운데 휴대폰 비중');
  const 성별 = 비중(쇼핑.비중?.Gender);
  const 여 = 성별.find((g) => g.값 === 'f');
  if (여) 넣기('쇼핑.여성', 여.비중, '%', '네이버 쇼핑인사이트', '분야 클릭 가운데 여성 비중');
  return { 나이, 순위: (쇼핑.순위 || []).map((r) => ({ 이름: r.이름, 낱말: r.낱말 || [] })), 클릭: (쇼핑.클릭 || []).flat() };
}

// ── 유튜브: 각도·길이별 튄 비율 ──────────────────────────────────────────
const 길이구간 = [['15초 이하', 0, 15], ['16~30초', 16, 30], ['31~60초', 31, 60], ['61초 이상', 61, Infinity]];

function 묶음통계(편들) {
  const 튄 = 편들.filter((v) => v.튄편).length;
  return { 편수: 편들.length, 튄편수: 튄, 튄비율: 퍼센트(튄, 편들.length), 배수중앙: 한자리(median(편들.map((v) => v.배수).filter(Number.isFinite))) };
}

function 영상집계(후보, 각도표, 넣기, 유튜브 = {}) {
  const 전체 = 묶음통계(후보);
  if (유튜브.시작일) 넣기('영상.시작일', 달날(유튜브.시작일), '', '유튜브', '이 날 이후 올라온 쇼츠만 봤다');
  if (Number.isFinite(유튜브.검색어수)) 넣기('영상.검색어수', 유튜브.검색어수, '개', '유튜브', '쇼츠를 찾은 검색어 수(설정)');
  if (Number.isFinite(유튜브.읽은검색어수)) 넣기('영상.읽은검색어수', 유튜브.읽은검색어수, '개', '유튜브', '실제로 검색을 마친 검색어 수(한도로 멈추면 설정보다 적다)');
  넣기('영상.편수', 전체.편수, '편', '유튜브', '본 쇼츠 수(기간 안, 3분 이하, 최소 조회 이상, 제외 낱말 뺌)');
  넣기('영상.튄편수', 전체.튄편수, '편', '유튜브', '그 채널 평소 조회의 3배를 넘긴 쇼츠 수');
  넣기('영상.튄비율', 전체.튄비율, '%', '유튜브', '본 쇼츠 가운데 튄 쇼츠 비율');
  const 각도들 = new Map();
  for (const v of 후보) for (const a of 각도표[v.id] || []) { if (!각도들.has(a)) 각도들.set(a, []); 각도들.get(a).push(v); }
  const 각도줄 = [];
  for (const [a, 편들] of 각도들) {
    if (편들.length < 3) continue; // 세 편이 안 되면 비율을 말하지 않는다
    const s = 묶음통계(편들);
    각도줄.push({ 이름: a, ...s });
    넣기(`영상.각도.${a}.편수`, s.편수, '편', '유튜브 · 제목 나누기', `「${a}」로 나뉜 쇼츠 수`);
    넣기(`영상.각도.${a}.튄비율`, s.튄비율, '%', '유튜브 · 제목 나누기', `「${a}」 쇼츠 가운데 튄 쇼츠 비율`);
    넣기(`영상.각도.${a}.배수중앙`, s.배수중앙, '배', '유튜브 · 제목 나누기', `「${a}」 쇼츠의 평소 대비 배수 중앙값`);
  }
  각도줄.sort((a, b) => b.튄비율 - a.튄비율);
  const 길이줄 = 길이구간.map(([이름, lo, hi]) => ({ 이름, ...묶음통계(후보.filter((v) => v.길이 >= lo && v.길이 <= hi)) })).filter((g) => g.편수 > 0);
  for (const g of 길이줄) 넣기(`영상.길이.${g.이름}.튄비율`, g.튄비율, '%', '유튜브', `${g.이름} 쇼츠 가운데 튄 쇼츠 비율`);
  // 짧은 쪽부터 전체 평균보다 자주 튄 구간이 이어지는 데까지
  let 끝 = -1;
  for (let i = 0; i < 길이줄.length; i++) { if (길이줄[i].편수 >= 5 && 길이줄[i].튄비율 > 전체.튄비율) 끝 = i; else break; }
  if (끝 >= 0) 넣기('영상.잘튀는길이', 길이구간[끝][2] === Infinity ? '길이와 상관없이' : `${길이구간[끝][2]}초 이하`, '', '유튜브', '짧은 쪽부터 전체 평균보다 자주 튄 길이 구간이 이어지는 데까지');
  // 작은 채널 예: 튄 편 가운데 구독이 가장 적은 채널(조회 5만 이상)
  const 작은 = 후보.filter((v) => v.튄편 && Number.isFinite(v.구독) && v.조회 >= 50000).sort((a, b) => a.구독 - b.구독)[0];
  if (작은) {
    넣기('영상.작은채널.구독', 작은.구독, '명', '유튜브', '튄 쇼츠(조회 5만 이상) 가운데 구독자가 가장 적은 채널의 구독자 수');
    넣기('영상.작은채널.조회', 작은.조회, '회', '유튜브', '그 쇼츠의 조회 수');
    넣기('영상.작은채널.길이', 작은.길이, '초', '유튜브', '그 쇼츠의 길이');
    넣기('영상.작은채널.채널', 작은.채널, '', '유튜브', '그 채널 이름');
  }
  const 튄순 = 후보.filter((v) => v.튄편).sort((a, b) => (b.배수 || 0) - (a.배수 || 0)).slice(0, 8)
    .map((v) => ({ id: v.id, 제목: v.제목, 채널: v.채널, 구독: v.구독, 조회: v.조회, 배수: 한자리(v.배수), 길이: v.길이, 주소: `https://www.youtube.com/shorts/${v.id}` }));
  return { 전체, 각도줄, 길이줄, 튄순 };
}

// ── 댓글: 주제별 수·비율·좋아요 ──────────────────────────────────────────
function 댓글집계(댓글목록, 주제표, 넣기) {
  // 댓글목록: [{키, 영상, 글, 좋아요}] (채널 주인 댓글은 이미 뺌)
  넣기('댓글.수', 댓글목록.length, '개', '유튜브 댓글', '읽은 상위 댓글 수(채널 주인 댓글 뺌)');
  넣기('댓글.영상수', new Set(댓글목록.map((c) => c.영상)).size, '편', '유튜브 댓글', '댓글을 읽은 쇼츠 수');
  const 주제들 = new Map();
  for (const c of 댓글목록) for (const t of 주제표[c.키] || []) { if (!주제들.has(t)) 주제들.set(t, []); 주제들.get(t).push(c); }
  const 줄 = [];
  for (const [t, cs] of 주제들) {
    if (t === '기타') continue;
    const s = { 이름: t, 수: cs.length, 비율: 퍼센트(cs.length, 댓글목록.length), 좋아요: cs.reduce((n, c) => n + (c.좋아요 || 0), 0), 영상수: new Set(cs.map((c) => c.영상)).size };
    줄.push(s);
    넣기(`댓글.주제.${t}.수`, s.수, '개', '유튜브 댓글 · 댓글 나누기', `「${t}」로 나뉜 댓글 수`);
    넣기(`댓글.주제.${t}.비율`, s.비율, '%', '유튜브 댓글 · 댓글 나누기', `읽은 댓글 가운데 「${t}」 비율`);
    넣기(`댓글.주제.${t}.좋아요`, s.좋아요, '개', '유튜브 댓글 · 댓글 나누기', `「${t}」 댓글에 붙은 좋아요 합`);
    넣기(`댓글.주제.${t}.영상수`, s.영상수, '편', '유튜브 댓글 · 댓글 나누기', `「${t}」 댓글이 달린 쇼츠 수`);
  }
  줄.sort((a, b) => b.수 - a.수);
  // 글 단계에 넘길 표본: 주제마다 좋아요 많은 순 8개(원문은 페이지에 싣지 않는다)
  const 표본 = {};
  for (const [t, cs] of 주제들) 표본[t] = [...cs].sort((a, b) => b.좋아요 - a.좋아요).slice(0, 8).map((c) => ({ 키: c.키, 영상: c.영상, 좋아요: c.좋아요, 글: c.글 }));
  표본['좋아요 많은 순'] = [...댓글목록].sort((a, b) => b.좋아요 - a.좋아요).slice(0, 12).map((c) => ({ 키: c.키, 영상: c.영상, 좋아요: c.좋아요, 글: c.글 }));
  return { 줄, 표본 };
}

// ── 메타 광고: 카드 글 읽기·주제 비율·오래 돈 광고 ────────────────────────────
/** 라이브러리 카드 글(「라이브러리 ID:」 뒤) → {id, 시작, 광고주, 본문, 제목} */
function 광고카드읽기(글) {
  const 줄 = String(글).split('\n').map((l) => l.replace(/​/g, '').trim()).filter(Boolean);
  if (!줄.length) return null;
  const id = (줄[0].match(/\d{6,}/) || [])[0];
  if (!id) return null;
  const m = /(\d{4})\.\s*(\d{1,2})\.\s*(\d{1,2})\.(?:에 게재 시작함|\s*~)/.exec(글);
  const 달 = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6, Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12 };
  const e = m ? null : /(?:Started running on|^)\s*([A-Z][a-z]{2}) (\d{1,2}), (\d{4})/m.exec(글);
  const 시작 = m ? `${m[1]}-${String(m[2]).padStart(2, '0')}-${String(m[3]).padStart(2, '0')}`
    : (e && 달[e[1]] ? `${e[3]}-${String(달[e[1]]).padStart(2, '0')}-${String(e[2]).padStart(2, '0')}` : null);
  const i = 줄.findIndex((l) => /광고 상세 정보 보기|See ad details/i.test(l));
  let 광고주 = null, 뒤 = 줄;
  if (i >= 0 && i + 1 < 줄.length) { 광고주 = 줄[i + 1]; 뒤 = 줄.slice(i + 2); }
  if (/^(광고|Sponsored)$/i.test(뒤[0] || '')) 뒤 = 뒤.slice(1);
  const 주소칸 = 뒤.findIndex((l) => /^[A-Z0-9.-]+\.[A-Z]{2,}$/.test(l));
  const 본문 = (주소칸 >= 0 ? 뒤.slice(0, 주소칸) : 뒤.slice(0, 4)).join(' ').slice(0, 300);
  const 제목 = 주소칸 >= 0 && 뒤[주소칸 + 1] ? 뒤[주소칸 + 1].slice(0, 160) : '';
  return { id, 시작, 광고주, 본문, 제목 };
}

function 광고모으기(메타) {
  const 광고 = new Map();
  for (const g of 메타.검색 || []) for (const c of g.카드 || []) {
    const a = 광고카드읽기(c);
    if (a && !광고.has(a.id)) 광고.set(a.id, { ...a, 검색어: g.검색어 });
  }
  return [...광고.values()];
}

function 광고집계(전체광고, 주제표, 기준일, 넣기, 플랫폼낱말 = []) {
  // 검색어가 우연히 걸린 다른 업종 광고는 모든 광고 숫자에서 뺀다(10-30 스킨케어: 「가장 오래 돈 광고」가 치과 광고였다)
  const 무관 = 전체광고.filter((a) => (주제표[a.id] || []).includes('업종과 무관'));
  const 광고 = 전체광고.filter((a) => !(주제표[a.id] || []).includes('업종과 무관'));
  if (무관.length) 넣기('광고.무관.수', 무관.length, '개', '메타 광고 라이브러리 · 문구 나누기', '검색에 걸렸지만 이 업종 광고가 아니어서 뺀 광고 수');
  const n = 광고.length;
  const 앱 = (이름) => 쇼핑앱.test(이름 || '') || 플랫폼낱말.some((w) => String(이름 || '').toLowerCase().includes(String(w).toLowerCase()));
  넣기('광고.수', n, '개', '메타 광고 라이브러리', '같은 검색어로 지금 게재 중인 광고 가운데 읽은 수(노출 많은 순 위쪽)');
  const 해외 = 광고.filter((a) => 해외직구.test(a.광고주 || ''));
  넣기('광고.해외직구.수', 해외.length, '개', '메타 광고 라이브러리', '테무·알리·쉬인 같은 해외 직구 앱 광고 수');
  넣기('광고.해외직구.비율', 퍼센트(해외.length, n), '%', '메타 광고 라이브러리', '읽은 광고 가운데 해외 직구 앱 광고 비율');
  const 주제들 = new Map();
  for (const a of 광고) for (const t of 주제표[a.id] || []) { if (!주제들.has(t)) 주제들.set(t, 0); 주제들.set(t, 주제들.get(t) + 1); }
  const 줄 = [];
  for (const [t, k] of 주제들) {
    if (t === '기타' || t === '업종과 무관') continue;
    줄.push({ 이름: t, 수: k, 비율: 퍼센트(k, n) });
    넣기(`광고.주제.${t}.수`, k, '개', '메타 광고 라이브러리 · 문구 나누기', `「${t}」를 말하는 광고 수`);
    넣기(`광고.주제.${t}.비율`, 퍼센트(k, n), '%', '메타 광고 라이브러리 · 문구 나누기', `읽은 광고 가운데 「${t}」를 말하는 광고 비율`);
  }
  줄.sort((a, b) => b.수 - a.수);
  const 일수 = (a) => (a.시작 ? Math.round((날짜(기준일).getTime() - 날짜(a.시작).getTime()) / 하루) : null);
  const 브랜드 = 광고.filter((a) => !해외직구.test(a.광고주 || '') && !앱(a.광고주) && Number.isFinite(일수(a)));
  const 오래 = [...브랜드].sort((a, b) => 일수(b) - 일수(a));
  // 게재 시작일이 절반 넘게 읽혀야 기간 지표를 낸다(화면 언어가 바뀌면 조용히 빠지지 않게)
  const 날짜읽힘 = 광고.filter((a) => a.시작).length;
  const 기간됨 = n > 0 && 날짜읽힘 * 2 >= n;
  if (기간됨 && 오래[0]) {
    넣기('광고.최장.일수', 일수(오래[0]), '일', '메타 광고 라이브러리', '브랜드 광고(해외 직구·쇼핑 앱 뺌) 가운데 가장 오래 게재 중인 광고의 일수');
    넣기('광고.최장.광고주', 오래[0].광고주, '', '메타 광고 라이브러리', '그 광고의 광고주');
  }
  const 한달 = 광고.filter((a) => 일수(a) >= 30).length;
  if (기간됨) 넣기('광고.30일이상.비율', 퍼센트(한달, n), '%', '메타 광고 라이브러리', '30일 넘게 게재 중인 광고 비율(오래 도는 광고는 팔리는 광고일 가능성이 높다)');
  const 표본 = (기간됨 ? 오래 : []).slice(0, 5).map((a) => ({ id: a.id, 광고주: a.광고주, 일수: 일수(a), 본문: a.본문, 제목: a.제목 }));
  return { 줄, 표본, 기간됨 };
}

/**
 * 한꺼번에: {유튜브, 네이버, 메타, 나누기, 기준일} → {지표, 그림, 표본, 상태}
 * 막힌 갈래는 건너뛰고 상태에 까닭을 남긴다(그 갈래의 지표는 아예 없다 — 글 단계가 근거로 못 든다).
 */
function 집계({ 유튜브, 네이버, 메타, 나누기 = {}, 기준일, 설정 = {} }) {
  const { 지표, 넣기 } = 지표묶음();
  const 그림 = {};
  const 표본 = {};
  const 상태 = {};
  if (네이버?.상태?.검색 === '됨' && 네이버.검색) { 그림.검색 = 검색집계(네이버.검색, 기준일, 넣기); 상태.검색 = '됨'; } else 상태.검색 = 네이버?.상태?.검색 || '안 읽음';
  if (네이버?.상태?.쇼핑 === '됨' && 네이버.쇼핑) { 그림.쇼핑 = 쇼핑집계(네이버.쇼핑, 넣기, 설정.네이버?.강조연령); 상태.쇼핑 = '됨'; } else 상태.쇼핑 = 네이버?.상태?.쇼핑 || '안 읽음';
  if (유튜브?.상태 === '됨') {
    그림.영상 = 영상집계(유튜브.후보, 나누기.영상 || {}, 넣기, 유튜브);
    상태.영상 = '됨';
    const 댓글목록 = [];
    for (const [영상, cs] of Object.entries(유튜브.댓글 || {})) cs.forEach((c, i) => { if (!c.주인) 댓글목록.push({ 키: `${영상}#${i}`, 영상, 글: c.글, 좋아요: c.좋아요 }); });
    if (댓글목록.length) { const d = 댓글집계(댓글목록, 나누기.댓글 || {}, 넣기); 그림.댓글 = d.줄; 표본.댓글 = d.표본; 상태.댓글 = '됨'; } else 상태.댓글 = '댓글 없음';
  } else { 상태.영상 = 유튜브?.까닭 || '안 읽음'; 상태.댓글 = 상태.영상; }
  if (메타 && Object.values(메타.상태 || {}).some((s) => s === '됨')) {
    const 광고 = 광고모으기(메타);
    const a = 광고집계(광고, 나누기.광고 || {}, 기준일, 넣기, 설정.메타?.플랫폼낱말 || []);
    그림.광고 = a.줄; 표본.광고 = a.표본; 상태.광고 = a.기간됨 ? '됨' : '됨(게재 시작일을 절반 넘게 못 읽어 기간 지표는 뺌)';
  } else 상태.광고 = 메타 ? Object.values(메타.상태 || {}).join(' · ') || '안 읽음' : '안 읽음';
  // 나누기가 Claude로 안 돼 낱말 규칙으로 나눈 수 — 페이지 「만든 방법」에 밝힌다
  for (const 종류 of ['댓글', '영상', '광고']) {
    const n = (나누기.낱말로?.[종류] || []).length;
    if (n) 넣기(`나누기.낱말로.${종류}`, n, '개', '나누기', `Claude 나누기가 안 돼 낱말 규칙으로 나눈 ${종류} 수`);
  }
  return { 지표, 그림, 표본, 상태 };
}

