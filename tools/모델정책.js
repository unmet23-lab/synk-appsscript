/* 실행자 픽 — `--실행 sol|luna` · `--효력 <값>` 은 1회성. 모르는 이름은 기본값으로 접지 않고 거절한다
 * (검수선택 과 같은 이유 — 오타를 조용히 luna 로 읽으면 「sol 로 돌렸다」고 믿는 상태가 생긴다). */
function 실행설정(argv) {
  const a = Array.isArray(argv) ? argv : [];
  let 이름 = 실행기본;
  if (a.includes('--실행')) {
    const v = a[a.indexOf('--실행') + 1];
    if (!v || /^--/.test(v)) throw 확인불가('`--실행` 뒤에 픽이 없다 — `--실행 sol` 또는 `--실행 luna`');
    이름 = v;
  }
  const n = String(이름).toLowerCase().replace(/[^a-z]/g, '').replace(/^gpt/, '').replace(/max$/, '');
  if (!Object.prototype.hasOwnProperty.call(실행선택지, n)) {
    throw 확인불가(`모르는 실행 선택지 "${이름}" — 가능: ${Object.keys(실행선택지).join(' · ')}`);
  }
  const 픽 = { ...실행선택지[n], 이름: n };
  if (a.includes('--효력')) 픽.effort = String(a[a.indexOf('--효력') + 1] || '');
  return 픽;
}

