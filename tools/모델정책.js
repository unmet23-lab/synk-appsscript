/* 자리 하나를 물으면 «누구 손인가»를 답한다. **키가 첫째**이고, 번호·이름 조각·갈래도 받는다.
 * 🔴 검사 자리는 여기서 벤더를 «안» 돌려준다 — `검수자(지은쪽)` 를 부르라고 답한다.
 *   지은 쪽을 모르는 채 검사자를 정하면 그게 곧 「지은 자가 검사」라서, 조용히 접지 않고 되묻게 한다. */
function 배치(자리, 지은쪽) {
  const q = String(자리 == null ? '' : 자리).trim();
  if (!q) throw 확인불가('배치를 물으려면 키나 자리 번호나 이름 조각을 준다 — 예: 배치("과제글") · 배치(22)');
  const n = Number(q);
  /* 🔑 **키를 먼저 본다** — 번호는 자리를 끼우면 밀리므로 «부르는 값»으로 쓰지 않는다(09-05 ⓐ). */
  const 키로찾음 = 배치표.filter((r) => r.키 === q);
  const 찾음 = 키로찾음.length
    ? 키로찾음
    : Number.isInteger(n)
      ? 배치표.filter((r) => r.n === n)
      : 배치표.filter((r) => r.이름.includes(q) || r.갈래 === q);
  if (!찾음.length) throw 확인불가(`모르는 자리 "${q}" — 배치표에 없다(키 ${배치표.length}개 · 번호 1~${배치표.length} · 이름 조각)`);
  return 찾음.map((r) => {
    if (r.손 !== '검수자가정한다') return { ...r };
    if (!지은쪽) {
      return { ...r, 손: null, 되물음: '이 자리는 «누가 지었느냐»가 검사자를 정한다 — 배치(13, "gpt") 처럼 지은 쪽을 같이 준다' };
    }
    const d = 검수자(지은쪽);
    return { ...r, 손: d.검수벤더, 근거: d.왜, 통로: d.통로, 지은쪽: d.지은쪽 };
  });
}

/* 실행자 픽 — `--실행 sol|luna` · `--효력 <값>` 은 1회성. 모르는 이름은 기본값으로 접지 않고 거절한다
 * (검수선택 과 같은 이유 — 오타를 조용히 luna 로 읽으면 「sol 로 돌렸다」고 믿는 상태가 생긴다). */
function 실행설정(argv) {
  const a = Array.isArray(argv) ? argv : [];
  let 이름 = 실행기본;
  if (a.includes('--실행')) {
    const v = a[a.indexOf('--실행') + 1];
    if (!v || /^--/.test(v)) throw 확인불가('`--실행` 뒤에 픽이 없다 — `--실행 sol` 또는 `--실행 luna`');
    이름 = v;
  }
  const n = String(이름).toLowerCase().replace(/[^a-z]/g, '').replace(/^gpt/, '').replace(/max$/, '');
  if (!Object.prototype.hasOwnProperty.call(실행선택지, n)) {
    throw 확인불가(`모르는 실행 선택지 "${이름}" — 가능: ${Object.keys(실행선택지).join(' · ')}`);
  }
  const 픽 = { ...실행선택지[n], 이름: n };
  if (a.includes('--효력')) 픽.effort = String(a[a.indexOf('--효력') + 1] || '');
  return 픽;
}

