'use strict';
/* 재질의 금지 — 판정 **한 벌** (F126 · F389).
 *
 * 유호님이 **이미 답한** 항목이 대기 표식을 달고 되살아나는 것을 막는 술어들이다.
 * 목록·표식·판정의 정본은 이 파일 하나다:
 *   · tests/재질의금지.test.js(⚠삭제됨 e75fc7fc 2026-08-19 — 지금 없다) — 탐지력 픽스처 + repo 안(보드·docs)·형제 실물 검사
 *   · tools/rot-check.js(재질의 절) — repo 밖(메모리) 실물 warn (F389 가 게이트에서 뗀 발동 자리)
 * 두 곳에 판정을 각자 적으면 갈라지고, 갈라진 쪽의 새는 방향은 「통과」다.
 * 항목·표식이 왜 이 모양인지(거짓양성 경계 포함)는 테스트 파일 머리말과 픽스처가 진다. */

const fs = require('node:fs');
const path = require('node:path');

/**
 * 유호님이 답을 확정해 **다시 묻지 않기로** 한 주제.
 * 새로 추가할 때는 반드시 「언제·무엇으로 확정됐나」를 적는다 —
 * 사유 없는 금지는 다음 사람이 지울 수 없다.
 */
const 재질의금지 = [
  {
    주제: '동의문',
    // 「동의 문구」·「동의문」·「동의 6항목」 — 띄어쓰기 변형 포함
    패턴: /동의\s*(문구|문|6\s*항목)/,
    확정: '2026-08-06 유호님이 직접 준비 완료 (F126). AI 초안 몫도 대기 항목도 아니다.',
  },
];

/** 유호님께 배달되는 대기 표식 */
const 대기표식 = /⏳|⛔|\[\[막힘>/;
/** 같은 줄에 이게 있으면 「해소를 적은 줄」이라 통과시킨다 */
const 해소표식 = /✅|🚫재질의|🚫재제안|준비\s*완료|~~/;

/** 한 줄이 위반인가 — 대기 표식 + 금지 주제 + 해소 표기 없음 */
function 위반인가(줄, 항목) {
  if (!대기표식.test(줄)) return false;
  if (!항목.패턴.test(줄)) return false;
  return !해소표식.test(줄);
}

/** 파일을 줄 단위로 검사해 위반 목록을 낸다 */
function 파일검사(경로, 표시경로) {
  const 위반 = [];
  const 줄들 = fs.readFileSync(경로, 'utf8').split(/\r?\n/);
  줄들.forEach((줄, i) => {
    for (const 항목 of 재질의금지) {
      if (위반인가(줄, 항목)) 위반.push(`${표시경로}:${i + 1} [${항목.주제}]`);
    }
  });
  return 위반;
}

/** 폴더의 *.md 전부를 검사한다 — 표시 경로는 `접두/파일명` */
function 폴더검사(dir, 접두) {
  const 위반 = [];
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith('.md')) continue;
    위반.push(...파일검사(path.join(dir, f), 접두 ? `${접두}/${f}` : f));
  }
  return 위반;
}

module.exports = { 재질의금지, 대기표식, 해소표식, 위반인가, 파일검사, 폴더검사 };
