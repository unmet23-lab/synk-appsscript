const 제외 = [/^ARC-AGI-3-Agents\//, /(^|\/)node_modules\//, /^docs\/_ops\/마찰신호\.md$/,
  /^docs\/_ops\/장부\//, /^evals\/출력_[^/]*\.json$/, /^\.claude\/skills\/last30days\//];

/** 이 경로를 열어 볼 것인가. 경로는 **저장소 뿌리 기준 슬래시 표기**여야 한다(git 이 주는 그대로). */
function 대상인가(파일) {
  if (!대상확장자.has(path.extname(파일).toLowerCase())) return false;
  return !제외.some((re) => re.test(파일));
}

/**
 * 한 파일의 본문에서 걸린 자리를 `파일:줄  U+xxxx` 로 낸다 — 빈 배열이면 깨끗하다.
 * 🔑 본문을 **인자로 받는다**: 스위트는 작업 트리를, pre-commit 은 인덱스(스테이징된 실물)를
 *   읽어야 하는데 그 차이는 «수집»의 몫이지 «판정»의 몫이 아니다.
 */
function 걸린줄(파일, 본문) {
  if (!옛글자.test(본문)) return [];                      // 파일 단위로 먼저 걸러 빠르게
  const 결과 = [];
  본문.split(/\r?\n/).forEach((ln, i) => {
    const ch = [...new Set([...ln].filter((c) => 옛글자.test(c)))];
    if (ch.length) {
      결과.push(`${파일}:${i + 1}  ${ch.map((c) => 'U+' + c.codePointAt(0).toString(16).toUpperCase()).join(' ')}`);
    }
  });
  return 결과;
}

