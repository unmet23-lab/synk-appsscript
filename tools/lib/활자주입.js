/* 활자주입 — 「이 HTML 에 브랜드 활자가 **실제로 박혔는가**」를 재는 한 곳.
 *
 * 왜 있나 (2026-08-10 실사고):
 *   발표물 `_src_*.html` 은 활자 자리에 마커만 있는 **원본**이고, 빌드가 그 자리에
 *   base64 `@font-face` 를 부어 산출물을 만든다. 그래서 원본은 폴백 활자로 조판된다 —
 *   글자 폭이 달라 한 줄이 더 접히고, 넘침 검사가 **원본에서만** 18px 적색을 낸다.
 *   그런데 발표물린트의 사용법 머리말이 시키는 명령이 `docs/발표물/*.html` 이라
 *   원본까지 함께 재서 **거짓양색**이 나왔다(실측: `_src_02_학부모_안내문_A4_kr` 6/6 적색,
 *   같은 내용의 산출물은 0/8). 거짓양성은 곧 「검사를 끄는 손버릇」이고, 실제로 두 세션이
 *   이 적색 앞에서 서로 반대 결론을 적고 죽었다.
 *
 * 🔑 판정을 **복제하지 않는다.** 옮겨 오기 전 같은 조건식이 세 곳에 따로 적혀 있었다
 *   (`발표물빌드.js` 산출물 검사 · `지도대장.js` 임베드 검사 · 그리고 넘침 검사가 넷째가 될 뻔했다).
 *   마커 문자열도 마찬가지다 — 뿌리는 쪽(`인쇄본빌드`·`지도대장`)과 확인하는 쪽이 갈리면
 *   마커를 바꾼 날 확인이 조용히 통과한다(새는 방향은 언제나 「통과」).
 */
'use strict';

/** 빌드가 활자를 부어 넣는 자리. 뿌리는 쪽과 확인하는 쪽이 **이 한 글자**를 같이 쓴다. */
const 마커 = '/*@FONTS@*/';

/**
 * **빌드 산출물 검사** — 활자가 제대로 박혔는가.
 * ⚠ 두 조건을 **둘 다** 본다 — `@font-face` 가 있어도 마커가 남아 있으면 치환이 반만 된 것이고,
 *   마커가 없어도 `@font-face` 가 없으면 애초에 안 박힌 것이다. 하나만 보면 그 절반이 샌다.
 */
function 주입됐나(html) {
  const s = String(html || '');
  return /@font-face/.test(s) && !s.includes(마커);
}

/**
 * **조판 측정 대상 판정** — 아직 안 구운 원본인가.
 * 🔑 `주입됐나` 의 반대가 **아니다.** 그 둘을 한 함수로 합치면 `@font-face` 가 애초에 없는
 *   문서(시스템 활자만 쓰는 페이지·회귀 픽스처)까지 「원본」으로 삼켜 **넘침 탐지가 통째로 꺼진다**
 *   (실측: 이 갈래를 안 나눴을 때 탐지 회귀 2건이 조용히 통과했다).
 *   가르는 건 마커 하나다 — 마커가 남아 있으면 활자가 들어올 자리가 비어 있다는 **문서 자신의 선언**이고,
 *   마커가 없으면 그 문서는 지금 조판이 곧 최종 조판이다.
 */
function 원본인가(html) {
  return String(html || '').includes(마커);
}

module.exports = { 마커, 주입됐나, 원본인가 };
