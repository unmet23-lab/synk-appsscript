'use strict';
/**
 * 모르는 `--` 플래그를 거절하는 **공용 판정** — 도구마다 목록은 다르고, 판정은 하나다.
 *
 * ■ 🔴 왜 이 저장소에도 필요한가 (2026-08-18 실측 · `local_88739beb`)
 *   형제 저장소(SYNK-talk)는 같은 병을 **다섯 번** 겪고 이 통로를 세웠다:
 *   F400(배포대조·읽기) → F435(원격SQL·읽기) → F436(원격SQL·쓰기) → 2026-08-14 실측
 *   (`--운영` 을 받을 수 있는 도구 11 중 die 하는 것은 1) → F592/F594(가드가 자기 분모에 눈이 멂).
 *   **그 통로가 이 저장소에는 안 왔다.** 실측: `tools/` 에서 `process.argv` 를 «코드로» 읽는 도구
 *   전량 중 게이트를 건 것은 손에 꼽고, 나머지는 모르는 낱말을 조용히 흘린다.
 *   내가 직접 밟은 자리 — `node tools/이해대장.js --빨강` 은 오류 없이 **전량 판을 다 냈다**.
 *   사람은 자기가 부탁한 좁힘이 된 줄 안다(그게 F400·F435 의 모양 그대로다).
 *
 *   🔑 급소는 «읽기 도구»가 아니라 **트랙을 닫는 도구**다. `작업가지.js --닫기`(머지·원격 가지
 *   거둠)·`대기열.js --확정대조` 가 전부 이 사각에 살았다. 직전 세션(`local_61375a0b`)이 바로 그
 *   `작업가지.js` 의 **조용한 실패 셋**(F567·F577·F580)을 고쳤다 — 삼켜지는 플래그는 같은 병의
 *   네 번째 입이고, 새는 방향이 셋과 똑같이 「통과」다.
 *
 * ■ 🔑 왜 「목록」이 아니라 「판정」만 공용인가
 *   도구마다 아는 낱말이 다르다. 목록을 여기서 세면 멀쩡한 인자가 죽는다. 그래서 공용은
 *   **판정 하나**뿐이고, 도구는 자기 낱말을 스스로 선언한다:
 *     const 아는플래그 = ['--닫기', '--열기'];
 *     const 플래그오류 = 인자게이트('작업가지', args, 아는플래그);
 *     if (플래그오류) die(플래그오류);
 *
 * ■ ⚠ 형제와 **일부러 다른 한 칸** — `공용플래그` 를 안 옮겼다
 *   형제의 `공용플래그 = ['--운영']` 은 그쪽 `lib/자격증명.js 읽기()` 가 도구를 안 가리고 조준에
 *   쓰기 때문에 있다. 이 저장소엔 그런 전역 낱말이 **없다**(실측 2026-08-18: `tools/lib/`·훅에서
 *   `--운영` 을 읽는 코드 0줄 · `작업본소유자.js` 의 그 낱말은 **주석 안**이다).
 *   없는 것을 옮겨 오면 조준 축 0인 도구가 `--운영` 을 받아 주고 아무것도 안 갈아탄다 —
 *   그게 형제의 F592 다. **생기면 그날 여기 넣는다.**
 *
 * ■ ⚠ 이 장치가 틀릴 때의 모습 = **거짓양성**(맞는 얼굴로 틀린 값 · CLAUDE.md 맹점 ④)
 *   선언에서 낱말 하나를 빠뜨리면 되던 명령이 죽고, 그건 따를 수 없는 처방이 된다(F103).
 *   그래서 회귀(`tests/도구인자게이트.test.js`)가 ①차단문이 「아는 것」이라 부른 낱말이 실제로
 *   통과하는지 ②게이트를 «부르고 답을 버리는» 자리가 없는지를 기계로 센다.
 *   🔑 **닫은 것**: 도구마다 손으로 쓰던 「모르는 낱말」 판정을 여기 하나로 모은다 — 사본이
 *   생기면 한쪽만 `--키=값` 이나 `--` 종결자를 다르게 다루고, 갈라진 쪽이 조용히 통과한다.
 *
 * ⚠ 값을 받는 낱말(`--학생 홍길동`)의 **값** 쪽은 안 본다 — `--` 로 시작하지 않아 애초에 안 걸린다.
 *
 * 🔴 **`--키=값` 꼴은 쓴다 — 첫 판의 「전수 실측」이 틀렸다**(2026-08-18 부착 중 반증).
 *   `검수꾸러미.js:294` 가 `args.find((a) => a.startsWith('--회차')).split('=')[1]` 로 **`--회차=3`
 *   을 정식으로 받는다**(`--회차 3` 도 받는 두 입구). 낱말 전체를 통짜로 대조하던 첫 판은 그
 *   도구에 게이트를 다는 순간 **되던 명령을 죽였다** — 이 장치가 틀릴 때의 모습 그대로다(F103).
 *   그래서 대조는 **`=` 앞의 키**로 한다. 실측이라 적었던 전수 조사가 왜 틀렸는지도 남긴다:
 *   그 조사는 «CLI 에서 실제로 들어오는 표기»가 아니라 «소스에 낱말 그 자체로 인용된 것»을 셌고,
 *   `--회차=3` 은 소스 어디에도 그 모양으로 안 적혀 있다(`startsWith` 로 받으니까).
 */

/**
 * 모르는 `--` 인자만 골라낸다. **순수 함수** — 파일·네트워크 없이 회귀가 여기를 문다(F296).
 * 🔑 `--키=값` 은 **키**로 대조한다(위 머리말 실측) — 값이 매번 달라 선언으로는 못 덮는다.
 */
function 모름(args, 아는것) {
  const 준것 = args || [];
  const 아는 = 아는것 || [];
  const 키 = (a) => (a.includes('=') ? a.slice(0, a.indexOf('=')) : a);
  return 준것.filter((a) => typeof a === 'string' && a.startsWith('--')
    && !아는.includes(a) && !아는.includes(키(a)));
}

/**
 * 도구가 부르는 통로 — 모르는 낱말이 있으면 **사람이 따라갈 수 있는** 한 줄을 돌려준다(없으면 null).
 * 막는 것은 도구 몫이다(`die` 의 모양이 도구마다 다르다).
 *
 * 🔑 차단문에 **아는 낱말 전량**을 싣는다 — 안 실으면 처방 없는 차단이고, 처방 없는 차단은
 *   우회를 정상 통로로 만든다(F103). 회귀가 「차단문이 시킨 낱말이 실제로 통과하는가」를 센다.
 */
function 인자게이트(도구, args, 아는것) {
  const 모른것 = 모름(args, 아는것);
  if (!모른것.length) return null;
  const 목록 = (아는것 || []).join(' ');
  /* 🔴 «아는 낱말 0» 은 문장이 깨지는 자리다 — 위치 인자만 받는 도구에 게이트를 달면
   *   「… 가 아는 것은  뿐이다」로 나가고, 낱말이 통째로 빈 자리라 읽는 사람은 **도구가 고장
   *   났다**고 읽는다. 처방이 없는 차단은 우회를 정상 통로로 만든다(F103).
   *   🔑 형제 저장소가 같은 날 같은 자리를 독립으로 고쳤다(#Q113 갈래③) — 두 판이 갈리지
   *   않게 그 문장 모양을 그대로 따른다. */
  const 아는말 = 목록
    ? `${도구} 가 아는 것은 ${목록} 뿐이다.`
    : `${도구} 는 «--» 낱말을 하나도 안 받는다 (위치 인자만 받는다).`;
  return `모르는 플래그 ${모른것.join(' ')} — ${아는말}`
    + ' 조용히 무시하면 「딴 과녁을 재고 초록」이 된다(형제 F400·F435 계열).';
}

module.exports = { 모름, 인자게이트 };
