/** 구운 자산을 읽는다 — 없으면 `null`(그럼 이 층 전체가 안 나가고 CSS 흉내가 산다). */
function 구운재질() {
  try {
    if (!fs.existsSync(구운길)) return null;
    const j = JSON.parse(fs.readFileSync(구운길, 'utf8'));
    return j && j['부품'] && Object.keys(j['부품']).length ? j : null;
  } catch (e) {
    return null;
  }
}

