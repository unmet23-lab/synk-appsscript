/** 범위 «자신»으로 접히는 선택자 — 그 안에 가두면 원리적으로 안 맞는 것들. */
const 컨테이너선택자 = /^(body|html|article)\b/;

/**
 * 선택자 하나를 범위 안으로.
 * 🔑 판정을 «맨요소인가»가 아니라 **«전역이어도 되는가»**로 세웠다(실측 교훈).
 *    앞의 모양으로 물으면 `a:not(.민):not(.레일 a)::before` 처럼 괄호 안에 공백이 든 선택자에서
 *    뼈 추출이 실패하고, 실패는 **「안 가둔다」로 떨어진다** — 즉 새는 방향이 「남의 판을 때린다」다.
 *    뒤의 모양으로 물으면 모르는 것은 전부 가두므로, 새더라도 «안 맞는다» 쪽으로 샌다.
 */
function 선택자범위(sel, 범위) {
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(sel);
  const [, 왼, 몸, 오른] = m;
  if (!몸) return sel;
  if (몸.startsWith(':root') || /^[.#]/.test(몸)) return sel;   // 부품 클래스·변수 = 전역(이름이 서로 소)
  const 컨 = 컨테이너선택자.exec(몸);
  /* `body` → `.룸` · `body.어쩌고` → `.룸.어쩌고` — 머리만 갈아 끼우고 꼬리 조건은 살린다. */
  if (컨) return 왼 + 범위 + 몸.slice(컨[0].length) + 오른;
  return 왼 + 범위 + ' ' + 몸 + 오른;
}

