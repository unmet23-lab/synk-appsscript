/*
 * 램문지기 — 「굽기를 지금 걸어도 되나」를 재는 자. **이 값을 아는 곳은 여기 하나다.**
 *
 * 🔑 왜 파일을 따로 뒀나 (08-31)
 *   이 문지기는 원래 `tools/밤샘_0830.js`(하루짜리 스크립트) 안에만 살고 있었고,
 *   상시 도구 `tools/밤굽기.js` 에는 **한 줄도 없었다**(`grep -c` 실측 0건).
 *   그대로 두면 둘 중 하나다 — ⓐ 상시 도구가 문지기 없이 돌거나,
 *   ⓑ 매일 밤 스크립트를 새로 뜨면서 값이 갈리거나. 실제로 갈려 있었다: 0828·0829 는 1,800,
 *   0830 은 6,000. **한 값을 두 곳이 알면 반드시 갈린다.**
 *   ⇒ 값과 재는 법을 여기 한 곳에 두고, 밤굽기·밤샘이 둘 다 이것을 읽는다.
 *   ⚠ `밤굽기.js` 를 `require` 하는 것으로는 못 푼다 — 그 파일은 스크립트라 읽는 순간 굽기가 시작된다.
 *
 * ■ 쓰는 법
 *     const 문지기 = require('./lib/램문지기');
 *     if (!문지기.자리비었나('③ 라이브러리', 말)) return;   // 말 = 로그 함수(없으면 console.log)
 */
'use strict';

const { execFileSync } = require('node:child_process');

/* 🔴 **6,000MB.** 08-30 에 같은 장면을 두 번 걸어 실측으로 정했다 — 이 값이 그 밤의 성패를 갈랐다.
 *   · 04:51 착수 · 여유 3,036MB → **38분에 0장.** 코어 점유 1코어의 80%(16코어 중 5%) ·
 *     Pages Input 169,737/초 로 스래싱이 안 풀렸다. 걷자 여유가 294MB → 7,435MB 로 돌아왔다.
 *   · 05:35 착수 · 여유 6,716MB → **41.5분에 1장.** 초반 코어 점유 223%.
 *   ⇒ 가른 것은 «장면»도 «해상도»도 아니고 **착수 시점 여유 램** 하나였다.
 *   🔑 왜 그렇게 예민한가: 그 장면은 **커밋 17.2GB 를 요구**하는데 이 기계 물리램은 15.4GB 다
 *     (08-30 실측 · 두 번 다 17,241~17,245MB 로 같았다 = 기계 상태가 아니라 «장면의 요구»).
 *     즉 **어떻게 해도 일부는 스왑**된다. 그 스왑을 «감당»하느냐 «스래싱»에 빠지느냐가
 *     착수 시점에 물리램을 얼마나 쥘 수 있었나로 갈린다.
 *   ⚠ 2,600(08-30 첫 값)도 1,800(08-29 값)도 **너무 낮다** — 둘 다 3.0GB 를 통과시킨다.
 *   ⚠ 반대로 이보다 높이면 세션이 여럿인 밤에 자리가 영영 안 난다. 6,000 은 그 사이의 실측선이다.
 *   ⚠ 「세션을 닫으면 풀린다」는 거짓이다 — claude 20개의 WS 합계가 1.17GB 뿐이라 모자란 ≈11GB 에
 *     한참 못 미친다(08-30 옆 세션 실측). 기다릴 것은 세션이 아니라 **여유 램 숫자**다. */
const 램바닥MB = 6000;

/* ── 한시 바닥(프로브) — 08-31 낮 실측이 연 통로 ──────────────────────────────
 *   그날 여유 램이 3.1~4.3GB 에 갇혀 6,000 이 «영영» 안 왔다(claude 창 ≈3.9GB 는 유호님 손 ·
 *   워킹셋 반납으로도 천장이 ≈4.2GB). 성공 실측 최저는 3,375MB(08-30) — 4,000대 착수는
 *   실패점(3,036)보다 성공점에 훨씬 가깝다. 그래서 «감시를 단 채» 낮은 바닥으로 붙이는 통로를 둔다.
 *   🔴 규약 둘: ①이 통로를 쓰는 쪽이 **반드시 스래싱 감시**(렌더 단계 코어 점유 <1.2코어 지속
 *     = 걷는다)를 같이 단다 — 감시 없는 한시 바닥은 04:51 의 「38분 0장」을 다시 산다.
 *     ②3,000 미만은 안 받는다 — 실패 실측(3,036)보다 낮은 값은 프로브가 아니라 사고다.
 *   env 이름이 ASCII 인 까닭: 밖(cmd/WMI)을 건너는 «키»는 ASCII 만 산다(한글 env 는
 *   코드페이지에 깨진다 — workflow-schema-ascii-keys 와 같은 병). */
const 한시바닥MB = (() => {
  const v = Number(process.env.RAM_FLOOR_TEMP || 0);
  return v >= 3000 ? v : 0;
})();

/* 6,000MB 는 까다로워서 한 시간을 기다려야 날 수도 있다. 그래도 무한은 안 한다:
 * 아침에 「아무것도 안 됨」이 「좀 느림」보다 훨씬 나쁘다. */
const 기본상한분 = 150;

/* ── 밤 길이만큼 기다리는 통로 (09-01 신설) ─────────────────────────────────
 *   🔴 왜 뚫었나: 08-31 아침에 ①단계가 **150분을 다 쓰고 그냥 건너뛰었다**(07:52 → 10:22).
 *   램이 «없어서»가 아니라 램이 «나는 시각»이 상한보다 늦어서다 — 여유 램을 쥐고 있는 것은
 *   유호님 창(claude·ChatGPT·크롬 = 09-01 실측 4,499MB)이고, 그 창이 언제 닫히는지는 굽기가 못 정한다.
 *   ⇒ 밤새 걸어 두는 판에서는 상한이 «밤 길이»여야 한다. 150분은 «낮에» 거는 판의 값이다.
 *   ⚠ 무한은 여전히 안 만든다 — 아침에 「기다리다 끝났다」가 로그에 남아야 다음 밤을 고칠 수 있다.
 *   env 이름이 ASCII 인 까닭은 RAM_FLOOR_TEMP 와 같다(밖을 건너는 «키»는 ASCII 만 산다). */
const 기다림상한분 = (() => {
  const v = Number(process.env.RAM_WAIT_MIN || 0);
  return v >= 1 ? v : 기본상한분;
})();

/** PowerShell 한 줄 — 실패하면 빈 문자열. **문지기는 «모르면 통과»여야 한다**(재는 자가 굽기를 막으면 안 된다). */
function ps(명령) {
  try {
    return String(execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', 명령],
      { encoding: 'utf8', timeout: 30000 })).trim();
  } catch (_) { return ''; }
}

/** 여유 물리램(MB). 못 재면 0 — 0 은 «바닥 미만»이라 기다리게 되지만, 상한이 있어 영영 멈추진 않는다. */
const 여유램MB = () => Number(ps('[int]((Get-CimInstance Win32_OperatingSystem).FreePhysicalMemory/1KB)')) || 0;

/* 🔴 프로세스를 셀 때 `tasklist /FI` 를 쓰지 않는다 — 한글 로케일·MSYS 경로 변환 때문에 늘 0건이다
 *   (08-25 에 옆 세션이 그것으로 「굽기가 멈췄다」를 오진했다).
 *   🔑 세는 자는 **하나**다. 밤굽기는 `Get-Process`, 밤샘은 `Win32_Process` 로 각자 세고 있었는데,
 *     같은 판정을 두 자로 재면 반드시 어긋난다. 가벼운 쪽(`Get-Process`)으로 통일한다. */
function 블렌더수() {
  return Number(ps('@(Get-Process blender -ErrorAction SilentlyContinue).Count')) || 0;
}

/** 부모가 이미 없는 블렌더를 걷는다 (08-28 사고 — 부모만 죽으면 자식이 4.6GB 를 물고 산다).
 *  성한 굽기의 부모는 살아 있으니 안 걸린다. 단계 «사이»에서만 부른다(내 자식이 없을 때).
 *  ⚠ 여기만 `Win32_Process` 를 쓴다 — 부모 pid 는 `Get-Process` 가 안 준다. */
function 고아걷기(말) {
  const 죽인것 = ps([
    "$live=(Get-CimInstance Win32_Process|%{$_.ProcessId});",
    "$n=0; Get-CimInstance Win32_Process -Filter \"Name='blender.exe'\" | %{",
    "  if($live -notcontains [int]$_.ParentProcessId){ Stop-Process -Id $_.ProcessId -Force -EA SilentlyContinue; $n++ } };",
    '$n',
  ].join(' '));
  if (죽인것 && 죽인것 !== '0') 말(`  🧹 고아 블렌더 ${죽인것}개를 걷었다 — 램을 물고 있었다.`);
}

const 시각 = () => new Date().toLocaleTimeString('ko-KR');

/**
 * 지금 굽기를 걸어도 되는 자리인가. 되면 `true`, 상한까지 기다려도 안 나면 `false`.
 * 남의 굽기가 돌면 **죽이지 않고 물러난다**(트랙 §0 겹침 규율).
 *
 * @param {string} 라벨   못 기다렸을 때 로그에 적을 단계 이름
 * @param {(s:string)=>void} [말]  로그 함수. 안 주면 console.log — 부르는 쪽이 파일 로그를 쓰면 그걸 준다.
 * @param {{잔다?:(초:number)=>void}} [옵션]  기다리는 법. 안 주면 PowerShell Start-Sleep.
 */
function 자리비었나(라벨, 말 = console.log, 옵션 = {}) {
  const 잔다 = 옵션.잔다 || ((초) => { ps(`Start-Sleep -Seconds ${초}`); });
  const 끝시각 = Date.now() + 기다림상한분 * 60 * 1000;
  const 바닥 = 한시바닥MB || 램바닥MB;   // 한시 프로브가 서 있으면 그 값이 이 판의 바닥이다(위 규약 둘 참조)
  let 알렸나 = false;
  for (;;) {
    고아걷기(말);
    const 남 = 블렌더수();
    const 램 = 여유램MB();
    if (남 === 0 && 램 >= 바닥) {
      if (알렸나) 말(`  ▶ 자리가 났다 — 램 ${램}MB · ${시각()}`);
      return true;
    }
    if (Date.now() > 끝시각) {
      말(`  ⏭ ${기다림상한분}분을 기다려도 자리가 안 났다(블렌더 ${남} · 램 ${램}MB) — ${라벨} 건너뛴다.`);
      return false;
    }
    if (!알렸나) {
      말(`  ⏳ 기다린다 — 블렌더 ${남}개 · 여유 램 ${램}MB(바닥 ${바닥}${한시바닥MB ? ' 🔶한시' : ''}) · ${시각()}`);
      알렸나 = true;
    }
    잔다(60);
  }
}

/** 착수 로그 한 줄 — 「무엇으로 쟀나」가 로그에 남게(수는 자와 같이 적는다). */
const 상태줄 = () => `여유 램 ${여유램MB()}MB · 블렌더 ${블렌더수()}개 · 램바닥 ${한시바닥MB || 램바닥MB}MB${한시바닥MB ? ' (🔶한시 프로브 — 감시 필수)' : ''} · 기다림 상한 ${기다림상한분}분`;

module.exports = { 램바닥MB, 기다림상한분, 여유램MB, 블렌더수, 고아걷기, 자리비었나, 상태줄 };
