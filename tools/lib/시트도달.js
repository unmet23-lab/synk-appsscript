/**
 * 시트층 «도달» 장부를 값으로 꺼내고 검사하는 **유일한 통로**.
 *
 * ■ 왜 있나 — 래칫 셋이 이 층을 원리상 못 본다
 *   형제 저장소(SYNK-talk `lib/이벤트검증.js`)의 래칫 셋은 전부 **앱 사건 14종**만 센다.
 *   그런데 `docs/엔진도달_설계.md` §2-1 이 「지금 실제로 데이터가 쌓이는 유일한 곳」이라 부른
 *   곳은 시트층이다 — 거기엔 도달 검사가 0이었다. 장부 정본은 `엔진_셋업확장.js` 의
 *   `수집도달_()`·`시트도달상한_()` 이고, 이 파일은 그것을 **읽고 재는 자** 하나다.
 *
 * ■ 통로가 하나여야 하는 이유는 `tools/lib/문법뱅크.js` 가 적어 둔 것과 같다
 *   자르는 규칙이 두 곳에 적히면 한쪽만 낡고, **낡은 쪽은 「못 찾음」이 아니라 「엉뚱한 값을
 *   조용히 통과」로 샌다.** 회귀(`tests/시트도달.test.js`)와 화면(`tools/이해대장.js`)이
 *   같은 자를 쓰게 두는 것이 이 파일의 전부다.
 *
 * ■ 검사는 **순수 함수**다 — 탐지력은 픽스처가 지고 실저장소엔 거짓양성만 묻는다
 *   `검사()` 는 파일을 안 읽는다(원문을 인자로 받는다). 그래서 「빠뜨린 키」·「거짓 지목」·
 *   「래칫 초과」를 **가짜 장부로 실제로 재볼 수 있다**. 실저장소가 초록인 것만으로는
 *   탐지력이 0인 검사와 구분이 안 된다(CLAUDE.md 신뢰성 맹점②).
 */
