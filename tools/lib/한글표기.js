function 칸글자(칸) {
  const 덧 = [];
  for (const k of Object.keys(칸이름)) {
    if (칸[k] === undefined) continue;
    if (k === 'ㅣ앞' && typeof 칸[k] === 'object') { 덧.push(`ㅣ앞 ${Object.entries(칸[k]).map(([가, 나]) => `${가}→${나}`).join(' ')}`); continue; }
    if (k === '자음별') { for (const [자, 꼴] of Object.entries(칸[k])) 덧.push(`${자} 뒤 ${보이기(꼴)}`); continue; }
    if (k === '뒤별') {
      const 묶음 = {};
      for (const [자, 꼴] of Object.entries(칸[k])) (묶음[꼴] = 묶음[꼴] || []).push(자);
      for (const [꼴, 자들] of Object.entries(묶음)) 덧.push(`${자들.join('')} 앞 ${보이기(꼴)}`);
      continue;
    }
    덧.push(`${칸이름[k]} ${보이기(칸[k])}`);
  }
  return [보이기(칸.글자), ...덧].join(' · ');
}
