function 덩이표기(덩이, 판, 문자, 옵션) {
  const 낱말들 = [];
  let 지금 = { 음: [], 끊음: [] };
  let 사이 = '';
  for (const ch of 덩이) {
    const s = 풀기(ch);
    if (s) {
      지금.끊음.push(지금.음.length > 0 && 사이 === '-');
      지금.음.push(s);
      사이 = '';
    } else if (ch === ' ') {
      if (지금.음.length) 낱말들.push(지금);
      지금 = { 음: [], 끊음: [] };
    } else {
      사이 = ch;
    }
  }
  if (지금.음.length) 낱말들.push(지금);
  const 낸말 = [];
  낱말들.forEach((말, wi) => {
    const 앞말 = wi > 0 ? 낱말들[wi - 1].음[낱말들[wi - 1].음.length - 1] : null;
    let 낸 = '';
    let 앞꼴 = '';
    말.음.forEach((s, i) => {
      const 앞 = 말.음[i - 1] || null;
      const 뒤 = 말.음[i + 1] || null;
      const 첫 = 첫소리꼴(판, s, 앞, i === 0 ? 앞말 : null);
      const 꼴 = 첫 + 모음꼴(판, s, 앞, 뒤, 첫) + 받침꼴(판, s, 뒤);
      if (옵션.조각) 옵션.조각.push(꼴);
      if (i > 0) {
        let 이음 = 말.끊음[i] ? '-' : (판.구분 || '');
        if (!말.끊음[i] && s.초 === 'ㅇ' && 대표(앞.종) === '' && 판.충돌식.some(g => g.앞.test(앞꼴) && g.뒤.test(꼴))) 이음 = '-';
        낸 += 이음;
      }
      낸 += 꼴;
      앞꼴 = 꼴;
    });
    for (const g of 판.고침식) 낸 = 낸.replace(g.식, g.바꿈);
    낸 = 낸.normalize('NFC');
    if (옵션.금칙 !== false) {
      const 붙인 = 낸.replace(/-/g, ''); // 하이픈으로 끊어도 욕설 꼴은 그대로 읽힌다 — 글꼴 규칙만 하이픈 있는 그대로 본다
      for (const g of 판.금칙식) if (g.식.test(g.종류 === '글꼴' ? 낸 : 붙인)) throw new 금칙오류(문자, g, 낸);
    }
    낸말.push(낸);
  });
  return 낸말.join(' ');
}

// 표기(글, 문자, { 발음: true | 발음으로 옵션, 금칙: false }) — 한글 음절만 바꾸고 문장부호 · 띄어쓰기 · 다른 글자는 그대로 둔다.
function 표기(글, 문자, 옵션 = {}) {
  const 판 = 문자표(문자);
  let 바탕글 = String(글).normalize('NFC');
  if (옵션.발음) 바탕글 = 발음으로(바탕글, 옵션.발음 === true ? {} : 옵션.발음);
  return 바탕글.replace(/[가-힣]+(?:[ -][가-힣]+)*/g, 덩이 => 덩이표기(덩이, 판, 문자, 옵션)).normalize('NFC');
}

// 음절표기(글, 문자, 옵션) — 노래 칸처럼 한 음절씩 보일 때(Fable 5.2 P2-10). 낱말을 한 번에 적어 문맥(울림 · 받침 · 모음 꼴)을
// 지킨 뒤 음절마다 나눈다 — 음절을 따로 표기()하면 낱말 줄과 달라진다(먹어 HI मॉ गॉ ≠ मगॉ). 칸에 홀로 서는 꼴도 금칙으로 다시 본다
// (음식 KY «ымсик»은 지나가도 칸 «сик»은 멈춤). 받침 꼴 끝의 하이픈(MN н- 등)은 칸 사이 경계라 뺀다. 한글 음절 수만큼 돌려준다.
function 음절표기(글, 문자, 옵션 = {}) {
  const 판 = 문자표(문자);
  const 조각 = [];
  표기(글, 문자, { ...옵션, 조각 });
  return 조각.map(꼴 => {
    let 칸 = 꼴.replace(/-+$/, '');
    for (const g of 판.고침식) 칸 = 칸.replace(g.식, g.바꿈);
    칸 = 칸.normalize('NFC');
    if (옵션.금칙 !== false) for (const g of 판.금칙식) if (g.식.test(칸)) throw new 금칙오류(문자, g, 칸);
    return 칸;
  });
}

// 발음줄(글, 문자, 옵션) — 화면에 넣을 때 쓰는 입구(Fable 5.2 P2-9). 금칙에 걸린 줄은 멈추지 않고 로마자로 떨어진다.
//   → { 줄, 문자 } · 걸렸으면 { 줄(로마자), 문자: 'latin', 금칙 } — 편 기록에 남길 것. 옵션.음절이면 줄 대신 음절(배열).
function 발음줄(글, 문자, 옵션 = {}) {
  const 내기 = c => (옵션.음절 ? { 음절: 음절표기(글, c, 옵션) } : { 줄: 표기(글, c, 옵션) });
  try {
    return { ...내기(문자), 문자 };
  } catch (e) {
    if (!e.금칙 || 문자 === 'latin') throw e;
    return { ...내기('latin'), 문자: 'latin', 금칙: e.금칙 };
  }
}

