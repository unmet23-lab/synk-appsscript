function 경계(a, b, o) {
  const F = a.종;
  const I = b.초;
  if (!F) return;
  if (I === 'ㅇ') {
    if (!o.연음 || F === 'ㅇ') return;
    if (F === 'ㅎ' || F === 'ㄶ' || F === 'ㅀ') {
      if (!o.ㅎ탈락) return;
      a.종 = '';
      if (F === 'ㄶ') b.초 = 'ㄴ';
      if (F === 'ㅀ') b.초 = 'ㄹ';
      return;
    }
    if (o.구개음화 && b.중 === 'ㅣ' && (F === 'ㄷ' || F === 'ㅌ' || F === 'ㄾ')) {
      if (F === 'ㄾ') { a.종 = 'ㄹ'; b.초 = 'ㅊ'; } else { a.종 = ''; b.초 = F === 'ㄷ' ? 'ㅈ' : 'ㅊ'; }
      return;
    }
    if (겹연음[F]) { [a.종, b.초] = 겹연음[F]; return; }
    a.종 = '';
    b.초 = F;
    return;
  }
  if (I === 'ㅎ') {
    if (o.거센소리 && 겹거센[F]) { [a.종, b.초] = 겹거센[F]; return; }
    if (o.거센소리 && 거센[F]) {
      a.종 = '';
      b.초 = 거센[F];
      if (o.구개음화 && F === 'ㄷ' && b.중 === 'ㅣ') b.초 = 'ㅊ';
      return;
    }
    if (o.대표음) a.종 = 대표(F);
    return;
  }
  if (F === 'ㅎ' || F === 'ㄶ' || F === 'ㅀ') {
    const 남 = F === 'ㅎ' ? '' : F === 'ㄶ' ? 'ㄴ' : 'ㄹ';
    if (o.거센소리 && (I === 'ㄱ' || I === 'ㄷ' || I === 'ㅈ')) { a.종 = 남; b.초 = 거센[I]; return; }
    if (o.거센소리 && I === 'ㅅ') { a.종 = 남; b.초 = 'ㅆ'; return; }
    if (o.비음화 && I === 'ㄴ') {
      a.종 = 남 || 'ㄴ';
      if (남 === 'ㄹ' && o.유음화) b.초 = 'ㄹ';
      return;
    }
  }
  let R = o.대표음 ? 대표(F) : F;
  let J = I;
  if (o.비음화 && (J === 'ㄴ' || J === 'ㅁ') && (R === 'ㄱ' || R === 'ㄷ' || R === 'ㅂ')) R = { ㄱ: 'ㅇ', ㄷ: 'ㄴ', ㅂ: 'ㅁ' }[R];
  if (J === 'ㄹ') {
    if (o.유음화 && R === 'ㄴ') R = 'ㄹ';
    else if (o.비음화 && (R === 'ㅁ' || R === 'ㅇ')) J = 'ㄴ';
    else if (o.비음화 && (R === 'ㄱ' || R === 'ㅂ')) { J = 'ㄴ'; R = R === 'ㄱ' ? 'ㅇ' : 'ㅁ'; }
  }
  if (o.유음화 && R === 'ㄹ' && J === 'ㄴ') J = 'ㄹ';
  if (o.된소리 && (R === 'ㄱ' || R === 'ㄷ' || R === 'ㅂ') && 된[J]) J = 된[J];
  a.종 = R;
  b.초 = J;
}

function 낱말발음(낱말, o) {
  const 음 = [...낱말].map(풀기);
  for (let i = 0; i < 음.length; i++) {
    if (i + 1 < 음.length) 경계(음[i], 음[i + 1], o);
    else if (o.대표음) 음[i].종 = 대표(음[i].종);
  }
  for (const s of 음) {
    if (o.ㅈㅊ뒤ㅕ && (s.초 === 'ㅈ' || s.초 === 'ㅉ' || s.초 === 'ㅊ') && s.중 === 'ㅕ') s.중 = 'ㅓ';
    if (o.자음뒤ㅢ && s.초 !== 'ㅇ' && s.중 === 'ㅢ') s.중 = 'ㅣ';
  }
  return 음.map(묶기).join('');
}

