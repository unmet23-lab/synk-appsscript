#!/usr/bin/env node
// master동기 — 「이 트리의 로컬 master 가 진실이다」라는 가정을 기계로 깬다.
//
// 왜 있나 (2026-08-17 실측 · `local_1d940103`):
//   로컬 master 가 origin 보다 **5 앞 / 57 뒤**로 갈라진 채 굳어 있었다. 갈라짐은 두 생산자가 만든다 —
//     ① `작업가지.js --닫기` 는 origin 에서 PR 을 머지하고 **로컬 master 를 전진시키지 않는다.**
//        그래서 origin 은 하루에 수십 건 앞서가고 로컬은 제자리다.
//     ② `인계문수거.js` 는 master 에 **직접 커밋하고 push 가 없다.** 그게 SessionStart 훅과
//        `/close` 6단계에 물려 있어, 밀리지 않은 커밋이 계속 «태어난다» — 이 진단을 재는
//        3분 사이에 3건이 새로 났다(82c7556b·e119a328·4c8aac9f).
//   ①이 만든 「뒤처짐」과 ②가 만든 「앞섬」이 만나면 fast-forward 가 불가능해지고,
//   그때부터 `git push origin master` 는 non-fast-forward 로 거절된다 — 즉 **자기 힘으로 못 빠져나온다.**
//
// 무엇이 망가지나: 로컬 판을 읽는 층이 전부 «맞는 얼굴로» 거짓을 낸다.
//   F542(보드 줄 — 「트랙 없이 끝난 세션」 단정) · F565(가지 층의 기준) · F566(커밋 목록 — 「커밋 없음」).
//   셋 다 같은 뿌리라, 호출부마다 고치면 네 번째 얼굴이 또 나온다(CLAUDE.md 신뢰성: 3번째는
//   원인을 쓸 수 없게 만든다). 그래서 이 파일은 **증상 셋이 아니라 생산자 둘**을 막는다.
//
// 🔑 이 통로가 하는 일은 «자동 해결»이 아니라 **드리프트를 0 으로 유지**하는 것이다.
//   갈라진 뒤의 반입은 남의 미커밋과 충돌할 수 있어 사람(세션)의 판정이 필요하다 —
//   그건 여기서 하지 않는다. 여기가 지키는 것은 「갈라지기 전에 붙여 둔다」뿐이다.
//
// ⚠ 대가 (틀릴 때의 모습을 적는다 — CLAUDE.md 「새 장치엔 대가를 함께 적는다」)
//   · `밀기` 는 network 왕복 1회를 세션 시작 경로에 얹는다. **커밋이 실제로 났을 때만** 부르므로
//     빈손 세션엔 0회다(수거는 죽은 세션이 있을 때만 커밋한다) — 그게 이 통로의 스로틀이다.
//   · `전진` 이 실패하는 정상 사유가 있다: 남의 미커밋이 ff 를 막는다. 그건 **막아야 맞다**
//     (남의 바이트를 덮지 않는다). 그래서 실패를 삼키지 않고 사유와 처방을 문장으로 돌려준다.
//   · 틀리는 방향: git 조회가 실패하면 «0 건»처럼 보일 수 있다. 그래서 못 세면 `null`(모름)을
//     돌려주고, 부르는 쪽이 0 과 구별해 찍는다(F207).
//   닫을 것: **없다.** 새 훅·새 상시 계기를 안 만들고 이미 도는 두 통로에 함수 두 개를 얹었다
//   (그래서 물러날 자리도 그 두 호출뿐이다).
'use strict';

const { spawnSync } = require('node:child_process');
const path = require('node:path');

const 기본가지 = 'master';

/** git 한 판. 성공/출력/오류를 한 꼴로 — 실패를 예외로 던지지 않는다(부르는 쪽이 판정한다). */
function 기본실행(인자들, 뿌리) {
  const r = spawnSync('git', ['-C', 뿌리, ...인자들], { encoding: 'utf8' });
  if (r.error) return { 성공: false, 출력: '', 오류: String(r.error.message || r.error) };
  return {
    성공: r.status === 0,
    출력: String(r.stdout || '').trim(),
    오류: String(r.stderr || '').trim(),
  };
}

/**
 * 이 트리가 워크트리면 **메인 작업 트리**를 돌려준다 — master 가 체크아웃돼 있는 자리다.
 * 워크트리 안에서 `merge --ff-only` 를 쳐도 그 트리의 detached·가지 HEAD 가 움직일 뿐
 * 메인의 master 는 그대로다(그게 이 버그의 절반이었다).
 */
function 메인뿌리(뿌리, { 실행 = 기본실행 } = {}) {
  const b = 실행(['rev-parse', '--git-common-dir'], 뿌리);
  if (!b.성공) return 뿌리;                                  // 모름 — 옛 동작 그대로(판정하지 않는다)
  const 공통 = path.resolve(뿌리, b.출력);
  if (path.basename(공통) !== '.git') return 뿌리;           // bare 등 — 손대지 않는다
  return path.dirname(공통);
}

/** `A..B` 개수. 못 세면 **null(모름)** 이지 0 이 아니다(F207). */
function 개수(범위, 뿌리, { 실행 = 기본실행 } = {}) {
  const r = 실행(['rev-list', '--count', 범위], 뿌리);
  if (!r.성공) return null;
  /* 🔴 빈 출력을 0 으로 접지 않는다 — `Number('')` 는 **0 이고 유한하다.** 그래서
   * `Number.isFinite` 만 보면 「아무것도 못 읽었다」가 「갈라짐 없다」로 번역된다
   * (이 줄의 첫 판이 그랬고, 변이 검사가 그 자리를 잡아냈다 · F207 의 정확한 모습). */
  if (!r.출력) return null;
  const n = Number(r.출력);
  return Number.isFinite(n) ? n : null;
}

/** 지금 갈라짐 — `{앞선, 뒤처진}`. 각각 null 이면 «못 셌다». */
function 갈라짐(뿌리, 옵션 = {}) {
  const 가지 = 옵션.가지 || 기본가지;
  return {
    앞선: 개수(`origin/${가지}..${가지}`, 뿌리, 옵션),
    뒤처진: 개수(`${가지}..origin/${가지}`, 뿌리, 옵션),
  };
}

/**
 * master 직접 커밋을 **그 자리에서 민다** (생산자 ②를 막는다).
 *
 * 부르는 자리: master 에 커밋을 만든 도구가 커밋 **직후**. 커밋과 push 는 한 벌이다 —
 * 안 민 커밋은 이 노트북에만 있고, 서버측 잠금도 PR 도 origin 에 올라온 것만 지킨다.
 *
 * 돌려주는 것: `{한것, 밀린수, 실패, 처방}` — `실패` 가 비어 있지 않으면 부르는 쪽이 **소리쳐야** 한다.
 */
function 밀기(뿌리, 옵션 = {}) {
  const 실행 = 옵션.실행 || 기본실행;
  const 가지 = 옵션.가지 || 기본가지;

  /* HEAD 가 master 가 아니면 안 민다. ref 는 워크트리 사이에 공유되므로, 가지 위에서 부르면
   * 「방금 내가 만든 커밋」과 무관한 master 를 밀게 된다 — 조준이 밀린 승인과 같은 꼴이다. */
  const 현재 = 실행(['rev-parse', '--abbrev-ref', 'HEAD'], 뿌리);
  if (!현재.성공) {
    return { 한것: '못셈', 밀린수: null, 실패: '현재 가지를 못 읽어 밀기를 판정 못 했다',
      처방: `git -C ${뿌리} status` };
  }
  if (현재.출력 !== 가지) {
    return { 한것: '건너뜀', 밀린수: 0, 실패: '',
      처방: '', 사유: `HEAD 가 ${현재.출력} — ${가지} 직접 커밋이 아니라 밀 자리가 아니다` };
  }

  const { 앞선 } = 갈라짐(뿌리, { ...옵션, 실행, 가지 });

  if (앞선 === null) {
    return { 한것: '못셈', 밀린수: null, 실패: `앞선 커밋 수를 못 셌다(origin/${가지} 참조가 없거나 git 조회 실패)`,
      처방: `git fetch origin ${가지} 로 원격 참조를 세운 뒤 git push origin ${가지}` };
  }
  if (앞선 === 0) return { 한것: '없음', 밀린수: 0, 실패: '', 처방: '' };

  const r = 실행(['push', 'origin', `${가지}:${가지}`], 뿌리);
  if (r.성공) return { 한것: '밀었다', 밀린수: 앞선, 실패: '', 처방: '' };

  const 첫줄 = (r.오류 || r.출력).split(/\r?\n/).find((l) => l.trim()) || '사유 모름';
  const 갈라짐인가 = /non-fast-forward|fetch first|behind/i.test(r.오류 || r.출력);
  return {
    한것: '실패',
    밀린수: 0,
    실패: `${앞선}건을 못 밀었다 — ${첫줄}`,
    처방: 갈라짐인가
      ? `이미 갈라졌다(앞 ${앞선}). 반입은 남의 미커밋과 충돌할 수 있어 자동으로 하지 않는다 — `
        + `detached 워크트리에서 푼다: git worktree add --detach <임시> ${가지} && (그 안에서) git merge origin/${가지} && git push origin HEAD:${가지}`
      : `git push origin ${가지} 를 직접 돌려 사유를 본다`,
  };
}

/**
 * 로컬 master 를 origin 까지 **전진**시킨다 (생산자 ①을 막는다).
 *
 * `--ff-only` 고정이다: 머지 커밋을 만들지 않고, 남의 미커밋이 있으면 git 이 **거절한다**.
 * 그 거절은 버그가 아니라 이 통로의 안전선이다 — 남의 바이트를 덮는 대신 사유를 낸다.
 *
 * 돌려주는 것: `{한것, 전진수, 실패, 처방}`.
 */
function 전진(뿌리, 옵션 = {}) {
  const 실행 = 옵션.실행 || 기본실행;
  const 가지 = 옵션.가지 || 기본가지;
  const 메인 = 옵션.메인건너뛰기 ? 뿌리 : 메인뿌리(뿌리, { 실행 });

  if (!옵션.fetch건너뛰기) {
    const f = 실행(['fetch', 'origin', 가지], 메인);
    if (!f.성공) {
      const 첫줄 = (f.오류 || f.출력).split(/\r?\n/).find((l) => l.trim()) || '사유 모름';
      return { 한것: '실패', 전진수: 0, 실패: `fetch 실패 — ${첫줄}`,
        처방: `git -C ${메인} fetch origin ${가지}` };
    }
  }

  const { 뒤처진 } = 갈라짐(메인, { ...옵션, 실행, 가지 });
  if (뒤처진 === null) {
    return { 한것: '못셈', 전진수: null, 실패: `뒤처진 수를 못 셌다(origin/${가지} 참조 없음?)`,
      처방: `git -C ${메인} fetch origin ${가지}` };
  }
  if (뒤처진 === 0) return { 한것: '없음', 전진수: 0, 실패: '', 처방: '' };

  /* 메인 트리의 현재 가지가 master 가 아니면 ff 를 치지 않는다 — 남이 그 트리에서 다른 가지를
   * 보고 있을 수 있고, 그때 checkout 을 끼우는 것은 남의 화면을 바꾸는 짓이다. */
  const 현재 = 실행(['rev-parse', '--abbrev-ref', 'HEAD'], 메인);
  if (!현재.성공) {
    return { 한것: '실패', 전진수: 0, 실패: '메인 트리의 현재 가지를 못 읽었다',
      처방: `git -C ${메인} status` };
  }
  if (현재.출력 !== 가지) {
    return { 한것: '건너뜀', 전진수: 0,
      실패: `메인 트리가 ${가지} 가 아니라 ${현재.출력} 위에 있다 — 남의 화면을 바꾸지 않는다(뒤처짐 ${뒤처진})`,
      처방: `그 트리가 ${가지} 로 돌아온 뒤: git -C ${메인} merge --ff-only origin/${가지}` };
  }

  const m = 실행(['merge', '--ff-only', `origin/${가지}`], 메인);
  if (m.성공) return { 한것: '전진했다', 전진수: 뒤처진, 실패: '', 처방: '' };

  const 첫줄 = (m.오류 || m.출력).split(/\r?\n/).find((l) => l.trim()) || '사유 모름';
  const 막힌것 = 막는파일들(메인, { 실행 });
  return {
    한것: '실패',
    전진수: 0,
    실패: `${뒤처진}건을 못 받았다 — ${첫줄}`,
    처방: 막힌것.length
      ? `미커밋이 ff 를 막는다(${막힌것.slice(0, 3).join(' · ')}${막힌것.length > 3 ? ` 외 ${막힌것.length - 3}` : ''}). `
        + '남의 것이면 그대로 두고 보고한다(node tools/작업본소유자.js) — 그 세션이 커밋하면 저절로 풀린다.'
      : `git -C ${메인} merge --ff-only origin/${가지} 를 직접 돌려 사유를 본다`,
  };
}

/** ff 를 막을 수 있는 미커밋 경로들. 못 읽으면 빈 배열(=모름) — 부르는 쪽 문구가 그때 일반형이 된다. */
function 막는파일들(뿌리, { 실행 = 기본실행 } = {}) {
  const r = 실행(['-c', 'core.quotepath=false', 'status', '--porcelain'], 뿌리);
  if (!r.성공) return [];
  return r.출력.split(/\r?\n/).filter((l) => l.trim()).map((l) => l.slice(3).trim());
}

/**
 * 결과를 사람이 읽는 한 줄로. **성공도 찍는다** — 안 돈 것과 통과가 같은 모양이면 안 된다(F207).
 * `이름` = 어느 통로가 불렀나(보고 앞머리).
 */
function 줄내기(이름, 결과) {
  if (!결과) return `[${이름}] master동기 결과가 없다 — 안 돈 것인지 확인이 필요하다`;
  if (결과.실패) return `[${이름}] 🔴 ${결과.실패}\n   → ${결과.처방}`;
  switch (결과.한것) {
    case '밀었다': return `[${이름}] ✅ master ${결과.밀린수}건 밀었다 — 좌초 0`;
    case '전진했다': return `[${이름}] ✅ 로컬 master 를 ${결과.전진수}건 전진시켰다 — 뒤처짐 0`;
    case '없음': return `[${이름}] master 는 이미 origin 과 같다(할 일 0)`;
    case '건너뜀': return `[${이름}] master동기 건너뜀 — ${결과.사유 || '조건 밖'}`;
    default: return `[${이름}] master동기 — ${결과.한것}`;
  }
}

module.exports = { 밀기, 전진, 갈라짐, 메인뿌리, 막는파일들, 줄내기, 기본실행, 기본가지 };
