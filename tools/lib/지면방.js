/**
 * 추적 HTML 전건.
 * 🔴 **0건과 「아무것도 못 봤다」를 같은 모양으로 두지 않는다** — git 을 못 읽으면 던진다.
 *    빈 목록을 조용히 돌려주면 「미분류 0건」이 초록으로 나오고, 그게 이 장치의 최악 실패다.
 */
/* 🔑 게이트를 **순수 함수로 떼어 둔다.** 안에 두면 실저장소에선 그 분기가 영영 안 밟혀
 *   회귀가 원리적으로 못 닿는다 — 실측: 이 줄을 `return []` 로 바꿔도 시험 12건이 전부 초록이었다
 *   (변이 검사가 「구멍」으로 잡아냈다 · 08-16). 못 닿는 게이트는 없는 게이트다. */
function 분모확인(목록) {
  if (!목록.length) throw new Error('추적 HTML 이 0건 — 저장소를 잘못 가리켰다(분모 없음).');
  return 목록;
}

function 지면들() {
  let out;
  try {
    out = execFileSync('git', ['-C', 루트, 'ls-files', '-z', '*.html'], { encoding: 'utf8', maxBuffer: 1 << 24 });
  } catch (e) {
    throw new Error('git ls-files 를 못 돌렸다 — 분모를 못 셌다(0건이 아니다): ' + e.message);
  }
  return 분모확인(out.split('\0').filter(Boolean));
}

/**
 * 이 «본문»에 Loom CSS 가 **얹혀** 있나. 마커는 `loom.js` 가 CSS 에 박는 주석이다(`마커()`).
 * ⚠**이것만으로는 「입었다」가 아니다** — 얹기만 하면 부품이 0개여도 참이 된다(F517①).
 *   실측 08-16: 발표물 6벌에 그대로 얹었으면 전파가 13/21 로 «초록»이 되는데
 *   화면은 한 픽셀도 안 바뀐 상태였다. 판정은 아래 `상태()` 가 낸다.
 */
const 입은표시 = (원문) => /\/\*loom부품:/.test(원문);

/**
 * 이 «본문»의 상태 — **셋이다.** 둘로 뭉치면 어디서 멈췄는지가 사라진다.
 *   `안얹힘` CSS 가 없다 — **일감**이다(적색 아님).
 *   `마커만` CSS 는 얹혔는데 **닿는 훅이 0** — 화면은 안 바뀐다. **결함**이다(적색).
 *   `입음`  얹혔고 닿는다.
 * 🔑 파일읽기와 갈라 둔 이유 — 술어가 늘 참을 내도 실저장소에선 「전파 21/21」이 그냥
 *    맞는 얼굴로 보인다. 픽스처가 물려면 **문자열을 받는 자리**가 있어야 한다.
 */
function 상태(원문) {
  const p = 훅.파일판정(원문);
  if (!p.마커) return { 상태: '안얹힘', 마커: 0, 닿은: [] };
  return { 상태: p.닿은.length ? '입음' : '마커만', 마커: p.마커, 닿은: p.닿은 };
}

/** 이 지면이 지금 Loom 을 입고 있나 — 얹혔고 **닿는다**. */
function 입었나(경로, fs = require('fs')) {
  return 지면상태(경로, fs).상태 === '입음';
}

/** 이 지면의 상태 셋. 파일이 없으면 `안얹힘`. */
function 지면상태(경로, fs = require('fs')) {
  const p = path.join(루트, 경로);
  if (!fs.existsSync(p)) return { 상태: '안얹힘', 마커: 0, 닿은: [] };
  return 상태(fs.readFileSync(p, 'utf8'));
}

/**
 * 전건 점검 — 이 함수 하나가 L5 의 분모이자 판정이다.
 * @param {{상태읽기?:(경로:string)=>{상태:string}}} [주입]
 *   🔑 `상태읽기` 를 갈아끼울 수 있게 둔 이유: 실저장소는 지금 **「마커만」이 0건**이라,
 *      여기 배선을 통째로 끊어도(`마커만 = []`) 실물 검사가 전부 초록이다 —
 *      변이 검사가 그 구멍을 잡아냈다(08-17). 병든 지면을 요구하지 않고 탐지력을 세우려면
 *      **아픈 판을 손으로 만들어 넣을 자리**가 있어야 한다(`분모확인()` 을 뗀 것과 같은 계열).
 */
function 점검({ 상태읽기 = 지면상태 } = {}) {
  const 갈래 = { 입는다: [], 보류: [], 제외: [], 미분류: [] };
  const 포획 = new Map(표.map((t) => [t.판정 + '\0' + t.패턴, 0]));

  for (const 경로 of 지면들()) {
    const r = 분류(경로);
    const s = r.판정 === '입는다' ? 상태읽기(경로) : undefined;
    갈래[r.판정].push({ 경로, ...r, 상태: s, 입음: s ? s.상태 === '입음' : undefined });
    if (r.패턴) 포획.set(r.판정 + '\0' + r.패턴, 포획.get(r.판정 + '\0' + r.패턴) + 1);
  }

  /* 🔑 셋으로 나눠 담는다. 옛 판은 `!입음` 하나였는데, 그러면 **결함(마커만)이 일감(안얹힘)
   *    사이에 섞여** 영영 안 보인다 — 「아직 안 입은 지면」 목록에 한 줄 더 있을 뿐이니까. */
  const 입음 = 갈래.입는다.filter((r) => r.입음);
  const 마커만 = 갈래.입는다.filter((r) => r.상태 && r.상태.상태 === '마커만');
  return {
    갈래,
    전파: {
      입음: 입음.length,
      분모: 갈래.입는다.length,
      안입음: 갈래.입는다.filter((r) => r.상태 && r.상태.상태 === '안얹힘'),
      마커만,
    },
    포획,
    빈규칙: 표.filter((t) => 포획.get(t.판정 + '\0' + t.패턴) === 0),
    규칙흠: 규칙검증(),
  };
}

/**
 * 이 판의 **적색 건수**. 둘이다 — 미분류(분모가 샌다 · F514) + 마커만(술어가 샌다 · F517①).
 * 🔑 CLI 안에 두지 않는다 — 루프 «안»의 게이트는 픽스처가 못 닿고, 못 닿는 게이트는
 *    변이 검사에서 구멍으로 나온다(`분모확인()` 을 떼어 둔 것과 같은 계열).
 * ⚠안 입은 지면(`안입음`)은 여기 안 온다. 그건 일감이고, 주인 없는 적색은 남의 배포를 막는다.
 */
function 적색수(r) {
  return r.갈래.미분류.length + r.규칙흠.length + r.전파.마커만.length;
}

/* ── 규칙 자체의 검증 ──────────────────────────────────────────────────────
 * 「대가」 절에서 닫기로 한 것 둘. 장치가 자기 규칙을 검사하지 않으면
 * 규칙이 낡는 방향은 언제나 «통과»다(가드 맹점 ④). */
function 규칙검증(쓸표 = 표) {
  const 흠 = [];
  for (const t of 쓸표) {
    if (!t.사유 || !t.사유.trim()) 흠.push(`사유 없는 항목: ${t.판정} ${t.패턴}`);
    /* 🔑 예외구를 두지 않는다. 첫 판에 「한 벌」을 빠져나갈 구멍으로 넣었더니
     *    조건 없는 보류가 실제로 하나 통과했다(실측 08-16 · 이 검사가 잡았다).
     *    가드에 만든 구멍은 «내가 만들었으니 안전하다»의 얼굴로 남는다. */
    if (t.판정 === '보류' && !t.사유.includes('조건'))
      흠.push(`보류인데 «조건»이 없다: ${t.패턴} — 조건 없는 보류는 영구 보류다`);
    // docs 최상위 와일드카드 금지 — 살아있는 새 지면이 태어나는 층이다.
    if (t.판정 === '제외' && /^docs\/[^/]*\*/.test(t.패턴))
      흠.push(`docs 최상위 와일드카드 제외 금지: ${t.패턴} — 새 지면이 조용히 삼켜진다`);
  }
  return 흠;
}

