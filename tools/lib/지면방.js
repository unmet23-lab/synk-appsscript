/** 아주 작은 글롭 — `*` 는 «/ 를 넘지 않는 한 조각», 접두 `*_x.html` 은 파일명 꼬리. */
function 맞나(패턴, 경로) {
  const re = new RegExp('^' + 패턴
    .replace(/[.+^${}()|[\]\\]/g, '\\$&')
    .replace(/\*/g, '[^/]*') + '$');
  if (re.test(경로)) return true;
  // `*_자립형.html` 처럼 디렉터리를 안 적은 패턴은 파일명에도 물린다.
  return !패턴.includes('/') && re.test(path.posix.basename(경로));
}

const 표 = [
  ...입는다.map(([패, 사]) => ({ 판정: '입는다', 패턴: 패, 사유: 사 })),
  ...보류.map(([패, 사]) => ({ 판정: '보류', 패턴: 패, 사유: 사 })),
  ...제외.map(([패, 사]) => ({ 판정: '제외', 패턴: 패, 사유: 사 })),
];

/** 한 경로의 판정. 첫 매치가 이긴다(개별 등재가 패턴보다 위). */
function 분류(경로) {
  const r = 표.find((t) => 맞나(t.패턴, 경로));
  return r ? { ...r } : { 판정: '미분류', 패턴: null, 사유: null };
}

