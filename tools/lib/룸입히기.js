#!/usr/bin/env node
/**
 * 룸입히기 — 「이 지면에 Loom 을 **얹는다**」를 재고 실행하는 한 곳 (2026-08-19)
 *
 * ══ 왜 있나 ═══════════════════════════════════════════════════════════════
 *   얹는 절차(훅을 세고 → 있으면 마지막 `</style>` 뒤에 붙이고 → 결과를 확인한다)가
 *   `발표물빌드.js` 안에만 살았다. 그건 **발표물에서만** 참이었고, 나머지 지면(생성기 5벌·
 *   손파일 4벌)이 같은 절차를 필요로 하는 순간 «호출부마다 베끼기»가 된다.
 *   CLAUDE.md 신뢰성 절: **3번째 = 원인을 쓸 수 없게 만든다** — 호출부마다 고치는 대신
 *   잘못 쓸 수 없는 공용 통로를 낸다. 지금이 그 3번째다(발표물 + 생성기 + 손파일).
 *
 *   ⚠ 이 파일은 **새 판정을 만들지 않는다.** 「닿나」는 `loom훅.js` 가, 「CSS 는 무엇인가」는
 *     `loom.js` 가 그대로 진다. 여기 있는 것은 «얹는 절차»뿐이다 — 판정을 하나 더 들면
 *     그게 곧 갈라지는 자리다(F517①이 정확히 그 사고였다).
 *
 * ══ 세 가지 규율 ══════════════════════════════════════════════════════════
 *   ① **훅 0 이면 안 얹는다**(F517②). 얹기만 하면 부품이 0개여도 `지면방` 의 마커 술어가
 *      「입었다」로 켜진다 — 화면은 한 픽셀도 안 바뀐 채로 진척만 초록이 된다.
 *   ② **되풀이해도 같다**(멱등). 생성기는 돌 때마다 이걸 부르므로, 얹기 전에 옛 블록을
 *      먼저 뜯는다. 안 그러면 생성할 때마다 Loom 블록이 한 겹씩 쌓인다.
 *   ③ **마지막 `</style>` «뒤»에 얹는다.** 앞에 두면 부품 클래스와 원고 클래스의 특정도가
 *      같아(`.칩` vs `.tag` = 0,1,0) 동점에서 원고가 이긴다 — 훅은 늘었는데 화면은 그대로인,
 *      딱 「맞는 얼굴로 틀린 값」이다.
 *
 * ══ 대가 — 이 장치가 틀릴 때의 모습 ═══════════════════════════════════════
 *   뜯기 정규식이 `<style data-loom=…>` 를 못 찾으면 **블록이 겹겹이 쌓인다**(멱등이 깨진다).
 *   그 방향은 「통과」다 — 파일이 커질 뿐 화면은 멀쩡해 보인다. ⇒ 닫은 것 = `입히기()` 가
 *   얹은 뒤 **블록 개수를 세어** 1 이 아니면 던진다(`겹침수()`). 회귀는 `tests/룸입히기.test.js`
 *   가 「두 번 돌려도 1」을 픽스처로 문다.
 *   그리고 **닫지 않은 것**: `</style>` 이 없는 지면은 던진다 — 폴백으로 `</head>` 앞에 넣으면
 *   원고 CSS 뒤가 아니라 «앞»이 될 수 있어 ③이 조용히 깨진다. 안 도는 쪽이 안전한 자리다.
 */

'use strict';

const loom = require('./loom.js');
const loom훅 = require('./loom훅.js');

/** 얹은 블록의 여는 표식. `data-loom` 값이 곧 «어느 프리셋으로 입었나»의 기록이다. */
const 열기표식 = (지면) => `<style data-loom="${지면}">`;

/**
 * 얹은 블록을 통째로 되뜯는 표식 — 멱등의 근거이자 `--check` 가 원고와 1:1 대조하는 통로.
 *
 * 🔑 **정규식 객체를 내보내지 않고 «만들어» 준다.** `/g` 가 붙은 객체는 `lastIndex` 를 들고
 *   다녀서 `.test()` 를 두 번 부르면 true→false 로 갈린다 — 호출부가 그걸 모르면
 *   「한 번은 얹혔다, 다음 번은 안 얹혔다」로 **조용히** 오판한다(새는 방향은 「통과」다).
 *   부르는 쪽이 매번 새 객체를 받으면 그 사고가 원리적으로 안 난다.
 */
const 뜯기패턴 = '\\n?<style data-loom="[^"]*">[\\s\\S]*?<\\/style>';
const 뜯기정규식 = (전역 = true) => new RegExp(뜯기패턴, 전역 ? 'g' : '');

/**
 * 이 마크업이 실제로 부르는 Loom 훅 — **닿는 선택자들**의 이름.
 * @param {object} 옵션 `{지면, css}` — `css` 를 주면 그것을 쓴다(여러 벌 돌 때 재조립을 안 하려고).
 * ⚠마크업만 본다 — 원고 CSS 안에 우연히 같은 이름이 있어도 그건 훅이 아니다(`loom훅` 이 가른다).
 */
function 훅들(html, 옵션 = {}) {
  const 지면 = 옵션.지면 || '부품만';
  const css = 옵션.css || loom.css({ 지면 });
  return loom훅.닿는선택자들(css, html).map((d) => d.선택자).sort();
}

/** 얹을까 — **훅이 하나라도 있을 때만.** 이 한 줄이 「마커만 켜진 초록」을 막는 게이트다. */
const 얹을까 = (훅) => 훅.length > 0;

/** 이미 얹힌 블록 수. 멱등이 깨졌는지 «세어서» 안다 — 있나 없나로는 겹침을 못 본다. */
const 겹침수 = (html) => (String(html).match(뜯기정규식()) || []).length;

/** 얹힌 Loom 블록을 전부 뜯는다. 얹기 전에 이걸 부르는 것이 멱등의 전부다. */
const 뜯기 = (html) => String(html).replace(뜯기정규식(), '');

/**
 * 얹기 — 원고의 **마지막 `</style>` 뒤**에 둔다(규율 ③).
 * @throws `</style>` 이 없으면 — 폴백을 두지 않는 이유는 머리말 「닫지 않은 것」 참고.
 */
function 얹기(html, css, 지면) {
  const i = String(html).lastIndexOf('</style>');
  if (i < 0) throw new Error('지면에 </style> 이 없다 — 얹을 자리를 못 찾았다');
  const 뒤 = i + '</style>'.length;
  return html.slice(0, 뒤) + '\n' + 열기표식(지면) + '\n' + css + '\n</style>' + html.slice(뒤);
}

/**
 * 입히기 — 한 벌의 전 과정. **이것 하나만 부르면 된다.**
 *
 * @param {string} html   원본(이미 얹혀 있어도 된다 — 먼저 뜯는다)
 * @param {object} 옵션
 *   @param {string} 옵션.지면  프리셋(기본 `부품만` — 남의 지면에 얹는 자리라 범위가 걸린다)
 *   @param {string} 옵션.css   조립된 CSS 를 밖에서 준다(여러 벌을 돌 때 6번 조립하지 않으려고)
 * @returns {{html:string, 훅:string[], 얹음:boolean}}
 *   `얹음 false` = 훅이 0 이라 **일부러 안 얹었다**(실패가 아니다 — 부품을 달면 다음에 입는다).
 */
function 입히기(html, 옵션 = {}) {
  const 지면 = 옵션.지면 || '부품만';
  const css = 옵션.css || loom.css({ 지면 });

  /* 먼저 뜯는다 — 옛 블록이 남아 있으면 훅 판정도 그 CSS 를 마크업으로 오독할 수 있고,
   * 무엇보다 얹기가 겹친다(규율 ②). */
  const 맨몸 = 뜯기(html);
  const 훅 = 훅들(맨몸, { 지면, css });
  if (!얹을까(훅)) return { html: 맨몸, 훅, 얹음: false };

  const 결과 = 얹기(맨몸, css, 지면);

  /* 「돌았다」가 아니라 **결과**를 본다. 둘 다 «통과» 쪽으로 새는 자리라 세어서 막는다. */
  const n = 겹침수(결과);
  if (n !== 1) throw new Error(`Loom 블록이 ${n}개다 — 1개여야 한다(멱등 깨짐)`);
  if (!/\/\*loom부품:/.test(결과)) throw new Error('Loom 을 얹었는데 부품 마커를 못 찾겠다');

  return { html: 결과, 훅, 얹음: true };
}

module.exports = { 열기표식, 뜯기패턴, 뜯기정규식, 훅들, 얹을까, 겹침수, 뜯기, 얹기, 입히기 };
