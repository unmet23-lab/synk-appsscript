"""색잣대 — 「다시 구웠는데 색이 나아졌나」를 재는 **하나의** 자.

■ 왜 파일이 따로 서나 (08-24)
  `굽기대조.py` 와 `재굽기_전후.py` 가 각자 재고 있었고, 같은 오브를 두고 한쪽은 «채도 +75.7%»,
  다른 쪽은 «+37.8%» 를 냈다. **잣대가 둘이면 숫자가 둘이고, 그러면 판정을 못 한다.**
  ⇒ 재는 법은 여기 한 곳에서만 나온다.

■ 이 자가 고치는 두 함정 — 둘 다 08-24 에 실물로 밟았다
  ① **판마다 문턱을 걸면 «서로 다른 화소 무리»를 비교하게 된다.**
     옛 화면은 바탕이 문턱 위(회색)라 화소의 51%가 뽑히고, 새 화면은 바탕이 문턱 아래(거의 검정)라
     6%만 뽑혔다. 그 둘의 평균 밝기를 견주니 **+305%** 가 나왔다 — 숫자는 맞고 뜻이 없다.
     ⇒ 마스크는 «둘 중 하나라도 문턱을 넘는 화소»의 **합집합**으로 한 번만 만들어 두 판에 같이 쓴다.
  ② **맨 HSV 채도는 어두운 화소에서 폭발한다.** (3,1,1) 같은 거의 검은 화소의 S 가 0.67 이다.
     그래서 바탕이 어두워진 판이 «채도 +396%» 로 찍혔다.
     ⇒ **밝기로 가중한다**: Σ(S·V) / Σ(V). 밝은 면이 색을 말하고 검은 바탕은 값에 거의 기여하지 않는다.
     사람 눈도 어두운 화소를 색으로 안 읽으니, 이쪽이 눈에도 더 가깝다.

■ 쓰는 법
    from lib.색잣대 import 쌍재기, 홑재기
    옛값, 새값 = 쌍재기(옛이미지, 새이미지)      # {'채도','밝기','대비'}
    값 = 홑재기(이미지)                          # 짝이 없을 때만(옛 판이 git 에 없는 장)
"""
import colorsys

문턱기본 = 45          # r+g+b 합. 무대(검정)와 물건을 가르는 선 — 굽기대조.py 가 쓰던 값 그대로.
재는폭 = 320           # 이 폭으로 줄여서 잰다. 값은 폭에 거의 안 흔들리고 속도가 크게 다르다.


def _줄이기(im, W=재는폭):
    t = im.convert('RGB')
    return t.resize((W, max(1, round(W * t.height / t.width))))


def _통계(화소들):
    if not 화소들:
        return None
    가중, 무게 = 0.0, 0.0
    밝 = []
    for (r, g, b) in 화소들:
        _, 채, 값 = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
        가중 += 채 * 값          # ← 함정 ②: 어두운 화소는 그 무게만큼만 센다
        무게 += 값
        밝.append(0.2126 * r + 0.7152 * g + 0.0722 * b)
    m = sum(밝) / len(밝)
    return {'채도': (가중 / 무게) if 무게 else 0.0,
            '밝기': m,
            '대비': (sum((x - m) ** 2 for x in 밝) / len(밝)) ** 0.5}


def 쌍재기(옛im, 새im, 문턱=문턱기본):
    """두 판을 «같은 화소 무리»에서 잰다. 크기가 달라도 된다(옛 1080 · 새 1800 처럼)."""
    a, b = _줄이기(옛im), _줄이기(새im)
    if a.size != b.size:
        b = b.resize(a.size)
    pa, pb = list(a.getdata()), list(b.getdata())
    골 = [i for i in range(len(pa)) if sum(pa[i]) > 문턱 or sum(pb[i]) > 문턱]   # ← 함정 ①
    if not 골:
        return None, None
    return _통계([pa[i] for i in 골]), _통계([pb[i] for i in 골])


def 홑재기(im, 무대뺌=True, 문턱=문턱기본):
    """짝이 없을 때만 쓴다 — 이 값은 «다른 홑값»과만 견줄 수 있다(쌍값과 섞지 않는다)."""
    s = _줄이기(im)
    return _통계([(r, g, b) for (r, g, b) in s.getdata() if (not 무대뺌) or r + g + b > 문턱])
