// 대표 노트 채점(2026-11-17 유호님 「이건 내가 직접하는게 아니라 클로드 api로 할게」) — 코치 판정과 채점 AI의 「하나만 고친다면」을 맞대는 규칙만 둔다.
// 네트워크 · 파일을 쓰지 않는다. 부르는 쪽: tools/대표노트채점.mjs. 시험: tests/대표노트채점.test.mjs.
// 기준의 원문: docs/드라마말하기_기획.md 4-1(노트 종류) · 4-2(노트 고르기, 확신 순서) · 4-3 3번(평가 세트 — 오노트 분모는 실제 준 노트 수,
// 노트를 안 준 비율도 숨기지 않는다, 두 평가자가 겹쳐 본다). 합격선(사업계획서 v7.6): 50개 중 대표 기준과 맞는 노트 40개 이상, 틀린 노트 2개 이하.

export const 노트갈래 = Object.freeze(['없음', '끝맺음', '길이', '빠진말']);
const 코치갈래 = Object.freeze({ ending: '끝맺음', length: '길이', missing: '빠진말' });
const 끝맺음이름 = Object.freeze({ polite: '해요체', formal: '합쇼체', plain: '반말' });

/** 코치(판정 규칙 judgeLine)의 결과를 채점 갈래로 옮긴다. 소리 관문에 걸린 테이크(status≠ok)는 노트가 없고 세지 않는다(관문). */
export function 코치결정(result) {
  if (!result || result.status !== 'ok') return { 갈래: '관문', 관문: result?.status ?? '없음', 노트: '없음', 끝맺음: null, 빠진말: '', 확실: false };
  if (result.verdict !== 'note' || !result.note) return { 갈래: '노트', 노트: '없음', 끝맺음: null, 빠진말: '', 확실: !!result.sure };
  const n = result.note;
  return {
    갈래: '노트', 노트: 코치갈래[n.kind] ?? '없음',
    끝맺음: n.kind === 'ending' ? (끝맺음이름[n.want] ?? null) : null,
    빠진말: n.kind === 'missing' ? String(n.word ?? '') : '',
    확실: false,
  };
}

/**
 * 채점 AI의 답을 다듬는다. 확신이 「높음」이 아니면 기준글 1번 · 7번(「확신이 없으면 노트를 주지 않는다」)대로 노트 없음으로 본다 — 원래 답은 남긴다.
 * 스키마가 강제되지 않는 둘째 채점(카본)은 「보통」 · 빈 값 따위를 낼 수 있어, 「높음」이 아닌 것은 모두 확신 없음이다.
 */
export function 채점결정(답) {
  if (!답 || typeof 답 !== 'object') return null;
  const 원래 = 노트갈래.includes(답.노트) ? 답.노트 : null;
  if (!원래) return null;
  const 낮음 = 답.확신 !== '높음';
  const 노트 = 낮음 ? '없음' : 원래;
  return {
    노트, 원래노트: 원래, 확신: 낮음 ? '낮음' : '높음',
    끝맺음: 노트 === '끝맺음' && ['해요체', '합쇼체', '반말'].includes(답.끝맺음_바랄것) ? 답.끝맺음_바랄것 : null,
    빠진말: 노트 === '빠진말' ? String(답.빠진말 ?? '').trim() : '',
    까닭: String(답.까닭 ?? '').trim(), 기준밖: String(답.기준밖 ?? '').trim(),
  };
}

const 맨말 = (v) => String(v ?? '').normalize('NFC').replace(/[\s\p{P}「」]/gu, '');
const 앞같은길이 = (a, b) => { let i = 0; while (i < a.length && i < b.length && a[i] === b[i]) i++; return i; };
/**
 * 두 말이 같은 낱말의 다른 꼴인가 — 한쪽이 다른 쪽 안에 있거나(「제출 기한」 · 「제출기한을」), 앞 세 글자 이상이 같고 짧은 쪽이 그 뒤로 한 글자만
 * 남을 때다(「길을 잃어서」 · 「길을 잃다」의 「다」). 「어디에 있는지」 · 「어디에 내야」처럼 뒤가 두 글자 넘게 다르면 다른 말이다(Fable 11-17).
 */
const 같은꼴 = (a, b) => {
  if (!a || !b) return false;
  if (a.includes(b) || b.includes(a)) return true;
  const n = 앞같은길이(a, b);
  return n >= 3 && Math.min(a.length, b.length) - n <= 1;
};

/**
 * 빠진 말이 같은 말을 가리키나 — 두 말이 같은 낱말의 다른 꼴이거나, 같은 핵심 말(낱말이나 그 허용 표현)을 가리키면 같다. 어느 쪽을 먼저 넣어도 답이 같다.
 * 핵심 말을 가리키는지는 그 낱말 · 허용 표현과 같거나, 세 글자 이상인 표현을 품을 때로 본다(「어디」처럼 짧은 표현이 들어 있기만 해서는 같다고 하지 않는다).
 */
export function 같은빠진말(가말, 나말, keys = []) {
  const a = 맨말(가말), b = 맨말(나말);
  if (!a || !b) return false;
  if (같은꼴(a, b)) return true;
  const 가리킴 = (x, k) => [k.word, ...(k.alts || [])].map(맨말).filter(Boolean).some((f) => f === x || (f.length >= 3 && x.includes(f)));
  return keys.some((k) => 가리킴(a, k) && 가리킴(b, k));
}
const 높임갈래 = (v) => (v === '반말' ? '반말' : '높임');

/**
 * 한 줄을 맞댄다. 돌려주는 것: 일치(같은 갈래와 같은 대상, 둘 다 노트 없음도 일치) · 다른노트(코치도 채점도 노트를 줬지만 갈래나 대상이 다름) ·
 * 코치만노트(채점은 고칠 것 없음) · 놓침(채점은 노트, 코치는 노트 없음) · 관문(소리 관문 — 세지 않음) · 채점없음(채점 AI가 답하지 못함).
 * 끝맺음은 높임을 바라는지 반말을 바라는지까지 견준다(해요체와 합쇼체는 같은 갈래).
 */
export function 맞대기(코치, 채점, spec = {}) {
  if (!코치 || 코치.갈래 === '관문') return '관문';
  if (!채점) return '채점없음';
  const c = 코치.노트, j = 채점.노트;
  if (c === '없음' && j === '없음') return '일치';
  if (c === '없음') return '놓침';
  if (j === '없음') return '코치만노트';
  if (c !== j) return '다른노트';
  // 해요체와 합쇼체는 둘 다 맞는 끝이라(기준 2) 바라는 꼴이 둘 사이에서 달라도 같은 노트다. 한쪽은 반말을, 다른 쪽은 높임을 바라면 다른 노트다.
  if (c === '끝맺음') return !코치.끝맺음 || !채점.끝맺음 || 높임갈래(코치.끝맺음) === 높임갈래(채점.끝맺음) ? '일치' : '다른노트';
  if (c === '빠진말') return 같은빠진말(코치.빠진말, 채점.빠진말, spec.keys) ? '일치' : '다른노트';
  return '일치';
}

/**
 * 모아 세기. rows: [{맞댐, 코치노트, 확인?:'맞는 지적'|'틀린 지적'|'애매'|null, 두채점같음?:bool, 의도?, 채점노트?}]
 * 확인은 코치가 노트를 줬는데 채점과 다를 때(다른노트 · 코치만노트) 채점 AI에게 코치 노트를 보여 주고 물은 답이다.
 * 오노트 = 확인이 「틀린 지적」인 코치 노트. 분모는 코치가 실제로 준 노트 수(기획 4-3). 관문과 채점없음은 어느 셈에도 넣지 않는다.
 */
export function 세기(rows) {
  const 셈 = (f) => rows.filter(f).length;
  const 센줄 = rows.filter((r) => r.맞댐 !== '관문' && r.맞댐 !== '채점없음');
  const 코치노트 = 센줄.filter((r) => ['일치', '다른노트', '코치만노트'].includes(r.맞댐) && r.코치노트 !== '없음');
  const 오노트 = 코치노트.filter((r) => r.확인 === '틀린 지적').length;
  const 애매 = 코치노트.filter((r) => r.확인 === '애매').length;
  // 채점과 다른 코치 노트인데 확인 답이 없으면(호출 실패) 오노트인지 모른다 — 숨기지 않고 따로 센다. 합격선은 이것이 0일 때만 판정한다.
  const 확인못함 = 코치노트.filter((r) => r.맞댐 !== '일치' && !['맞는 지적', '틀린 지적', '애매'].includes(r.확인)).length;
  const 일치 = 센줄.filter((r) => r.맞댐 === '일치').length;
  const 노트일치 = 코치노트.filter((r) => r.맞댐 === '일치').length;
  const 놓침 = 센줄.filter((r) => r.맞댐 === '놓침').length;
  // 채점이 노트를 준 줄 = 놓침 + 다른노트 + 노트끼리 일치.
  const 채점노트수 = 놓침 + 센줄.filter((r) => r.맞댐 === '다른노트').length + 노트일치;
  const 둘째 = 센줄.filter((r) => typeof r.두채점같음 === 'boolean');
  const 의도 = 센줄.filter((r) => r.의도 && r.채점노트);
  const 비 = (a, b) => (b ? a / b : null);
  return {
    표본: rows.length, 관문: 셈((r) => r.맞댐 === '관문'), 채점없음: 셈((r) => r.맞댐 === '채점없음'), 센표본: 센줄.length,
    일치, 일치율: 비(일치, 센줄.length), 둘다없음: 일치 - 노트일치,
    // 「둘 다 노트 없음」이 일치를 채우는 것을 가리지 않게 노트 쪽 비율도 낸다(Fable 11-17).
    채점노트수, 노트일치, 채점노트중코치같음: 비(노트일치, 채점노트수), 코치노트중일치: 비(노트일치, 코치노트.length),
    코치노트수: 코치노트.length, 오노트, 오노트율: 비(오노트, 코치노트.length), 애매, 확인못함,
    // 코치 노트도 맞는 지적이었던 줄 — 채점이 다른 것을 먼저 골랐거나(순서만다름), 채점은 고칠 것이 없다고 봤다(채점이놓침).
    순서만다름: 코치노트.filter((r) => r.맞댐 === '다른노트' && r.확인 === '맞는 지적').length,
    채점이놓침: 코치노트.filter((r) => r.맞댐 === '코치만노트' && r.확인 === '맞는 지적').length,
    // 기획 4-3 「노트를 안 준 비율도 숨기지 않는다」 — 노트를 적게 줄수록 오노트가 주니, 코치가 노트를 주지 않은 줄의 비율과
    // 그 가운데 채점은 고칠 것이 있다고 본 줄(놓침)을 함께 낸다.
    노트안준비율: 비(센줄.length - 코치노트.length, 센줄.length),
    놓침, 놓침율: 비(놓침, 센줄.length),
    두채점: 둘째.length ? { 견준줄: 둘째.length, 같음: 둘째.filter((r) => r.두채점같음).length } : null,
    의도견줌: 의도.length ? { 견준줄: 의도.length, 같음: 의도.filter((r) => r.의도 === r.채점노트).length } : null,
  };
}

/**
 * 합격선 — 50개를 기준으로 쓴 사업계획서 값(일치 40/50 = 80%, 틀린 노트 2/50)을 표본 크기에 비례해 본다. 표본이 50 미만이면 「표본 모자람」.
 * 확인하지 못한 코치 노트가 있거나 센 표본이 없으면 오노트 합격은 모른다(null). 「애매」를 모두 틀린 지적으로 쳐도 지키는지(오노트애매포함)를 함께 낸다.
 */
export function 합격선(셈) {
  const n = 셈.센표본, 한도 = Math.floor((2 * n) / 50);
  const 모름 = 셈.확인못함 || !n;
  return {
    표본모자람: n < 50,
    일치: 셈.일치율 != null && 셈.일치율 >= 0.8,
    오노트: 모름 ? null : 셈.오노트 <= 한도,
    오노트애매포함: 모름 ? null : 셈.오노트 + 셈.애매 <= 한도,
  };
}
