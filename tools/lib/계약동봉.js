const 항목앵커 = Object.freeze({ 시작: '항목.push({', 끝: '});' });

/** 소스에서 블록 한 덩이. 못 찾으면 `null`(≠ 빈 문자열 — 「못 쟀다」다). */
function 블록찾기(소스, 시작표식, 끝표식) {
  if (typeof 소스 !== 'string') return null;
  const j = 소스.indexOf(시작표식);
  if (j === -1) return null;
  const e = 소스.indexOf(끝표식, j + 시작표식.length);
  if (e === -1) return null;
  return 소스.slice(j, e);
}

/** 블록이 그 필드를 **키로** 만드는가. 값·주석에 이름만 스쳐도 통과하면 안 되므로 `이름:` 꼴만 센다. */
function 필드있나(블록, 필드) {
  const 안전 = String(필드).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(^|[\\s{,])${안전}\\s*:`, 'm').test(블록);
}

/**
 * 계약이 약속한 `픽스처_항목필드` 중 조립부가 **안 만드는** 칸.
 * @returns {{잼:true, 없는칸:string[]} | {잼:false, 왜:string}}
 *   못 잰 경우를 값으로 돌려준다 — 예외로 던지면 부르는 쪽마다 다르게 접고, 접는 방향은 통과다.
 */
function 없는항목필드(계약, 수집소스) {
  const 목록 = 계약 && 계약.픽스처_항목필드;
  if (!Array.isArray(목록)) return { 잼: false, 왜: '계약에 `픽스처_항목필드` 배열이 없다' };
  const 블록 = 블록찾기(수집소스, 항목앵커.시작, 항목앵커.끝);
  if (블록 === null) {
    return { 잼: false, 왜: `픽스처를 만드는 자리를 못 찾았다(앵커 \`${항목앵커.시작}\`) — 조립 방식이 바뀌었다면 이 판정층도 함께 옮겨라` };
  }
  return { 잼: true, 없는칸: 목록.filter((f) => !필드있나(블록, f)) };
}

module.exports = { 항목앵커, 블록찾기, 필드있나, 없는항목필드 };
