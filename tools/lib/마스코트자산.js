/* 마스코트 «현행 정본»의 유일한 주인 — 경로는 여기서만 나온다.
 *
 * 왜 다시 썼나 (실측 2026-08-19): 예전의 이 파일은 「이 경로가 마스코트인가」만 알았다.
 * 「어느 것이 현행인가」는 아무도 몰라서, 도구마다 자기가 아는 폴더를 손으로 적었다.
 * 그 결과 마스코트 세트가 10벌 공존했고 — 유호님 확정판은 코드 참조 6회, 옛판이 20회였다.
 * 새 세션이 「마스코트」를 검색하면 가장 오래된 판이 1등으로 나오는 상태였다.
 *
 * 그래서 이 파일은 이제 **하나의 세트만 안다.** 옛 경로를 적으면 그건 없는 파일이라
 * 그 자리에서 깨진다 — 조용히 옛 그림이 나오는 것보다 낫다.
 *
 * 정본 = 펠트코랄_0815 (유호님 확정 2026-08-19 「본체는 펠트코랄0815 이거로 확정」).
 * 펠트(니들펠트 양모)는 SYNK 회사 전용 재질이고, 코랄이 그 위의 확정 색이다.
 */
'use strict';

const path = require('path');
const fs = require('fs');

/* 정본 세트가 사는 곳 — **토큰에서 파생한다**(2026-08-20).
 *
 * 🔑 전엔 이 줄이 경로를 손으로 들었고, `docs/디자인_토큰.json` 의
 *   `재질.펠트.정본사진.평상복` 도 같은 경로를 따로 들었다 — **주인이 둘**이었다.
 *   지금은 값이 같아 보이지만, 다음 정본이 설 때 한쪽만 바뀌면 그 순간부터
 *   「어느 게 현행인가」가 다시 갈린다(그게 마스코트 10벌 공존을 만든 병이다).
 *   ⇒ 토큰이 유일한 주인이고, 이 파일은 **JS 쪽 창구**다.
 *   Python·브라우저는 이 모듈을 못 부르니 같은 토큰 JSON 을 직접 읽는다 —
 *   그래서 주인을 «JS 모듈」이 아니라 «언어 중립인 JSON」에 둔다. */
const 토큰경로 = path.join(__dirname, '..', '..', 'docs', '디자인_토큰.json');
const 정본폴더 = (() => {
  const 평상복 = JSON.parse(fs.readFileSync(토큰경로, 'utf8'))['재질']['펠트']['정본사진']['평상복'];
  if (!평상복) throw new Error('토큰 재질.펠트.정본사진.평상복 이 비었다 — 정본 경로의 주인이 사라졌다');
  return path.posix.dirname(평상복.split(path.sep).join('/'));
})();

/* 표정별 파일. 배경이 붙은 판과 누끼(투명) 판이 따로 있다 —
 * 지면에 얹을 때는 누끼, 배경째 보여줄 때는 그냥 쓴다. */
const 표정 = {
  본체:   '재염색_본체.png',
  눈감음: '재염색_눈감음.png',
  눈웃음: '재염색_눈웃음.png',
  우34:   '재염색_우34.png',
  좌34:   '재염색_좌34.png',
};
const 누끼표정 = { 본체: 1, 눈감음: 1, 눈웃음: 1 };  // 누끼/ 아래에 있는 것만

/** 표정 하나의 저장소 상대 경로. `누끼=true` 면 투명판을 준다.
 *  없는 표정을 부르면 조용히 다른 걸 주지 않고 던진다 — 조용한 폴백이 이 사고의 원인이었다. */
function 경로(이름 = '본체', { 누끼 = false } = {}) {
  const f = 표정[이름];
  if (!f) throw new Error(`마스코트 표정 「${이름}」은 정본에 없다. 있는 것: ${Object.keys(표정).join(', ')}`);
  if (누끼 && !누끼표정[이름]) throw new Error(`표정 「${이름}」은 누끼판이 없다. 있는 것: ${Object.keys(누끼표정).join(', ')}`);
  return 누끼 ? `${정본폴더}/누끼/${f}` : `${정본폴더}/${f}`;
}

/** 절대 경로 — repo 루트를 기준으로 짓는다. */
function 절대경로(이름, opts) {
  return path.join(__dirname, '..', '..', 경로(이름, opts));
}

/* 브라우저 안(문자열로 주입되는 코드)에서도 같은 판정을 쓰게 «정규식 소스»로 낸다.
 * 정규식 객체를 넘기면 문자열화에서 이스케이프가 갈린다 — 소스를 넘기고 저쪽에서 짓는다. */
const 패턴소스 = '(펠트코랄_0815)[\\\\/]';

/** 이 경로가 «현행» 마스코트 그림인가. 옛 세트는 이제 저장소에 없으므로 여기서도 참이 아니다. */
function 마스코트경로다(경로문자열) {
  return new RegExp(패턴소스).test(String(경로문자열 || ''));
}

module.exports = {
  정본폴더,
  표정: Object.keys(표정),
  경로,
  절대경로,
  패턴소스,
  마스코트경로다,
  /* 옛 이름 호환 — 지면방·브랜드렌더린트가 폴더 목록을 기대한다. 이제 한 벌뿐이고,
   * 이름도 손으로 안 든다(위 정본폴더에서 파생 — 두 곳에 적으면 그 순간 갈린다). */
  마스코트폴더: [path.posix.basename(정본폴더)],
};
