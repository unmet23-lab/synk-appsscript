/* 🔑 08-29: 감정 창구 셋에 «가이드» 인자를 뚫었다(기본값 몽글 — 기존 호출부는 한 톨도 안 바뀐다).
 *   그전엔 세 창구가 전부 몽글에 하드와이어라, 까몽 컷이 여섯 장 구워져 있어도 **감정으로 물을
 *   통로가 원리상 없었다**. 위 머리말이 적어 둔 「어휘는 기계가 읽는 자리에 둔다」가 몽글에만
 *   적용돼 있던 셈이다. 새 가이드(마린)가 서면 토큰에 표정표만 얹으면 이 창구가 그대로 받는다. */
function 감정표뽑기(가이드) {
  const v = 토큰['캐릭터'] && 토큰['캐릭터'][가이드] && 토큰['캐릭터'][가이드]['표정'];
  if (!v) {
    const 있는것 = Object.keys(토큰['캐릭터'] || {}).filter((k) => !k.startsWith('_'));
    throw new Error(`토큰 캐릭터.${가이드}.표정 이 없다 — 표정 어휘의 주인이 사라졌다. 표정표가 선 가이드: ${있는것.join(', ')}`);
  }
  return v;
}
const 감정표 = 감정표뽑기('몽글');   // 몽글 기본 — 아래 창구들의 기본값

/** 감정 하나가 «지금» 어느 컷으로 나는가. 그림이 없으면 조용히 기본으로 안 물러선다 — 던진다. */
function 감정컷(감정, 가이드) {
  const 표 = 가이드 && 가이드 !== '몽글' ? 감정표뽑기(가이드) : 감정표;
  const v = 표[감정];
  if (!v) throw new Error(`${가이드 || '몽글'}의 표정 「${감정}」은 어휘에 없다. 있는 것: ${Object.keys(표).join(', ')}`);
  if (!v['컷']) {
    throw new Error(`표정 「${감정}」은 아직 그림이 없다(상태 ${v['상태']}). `
      + `조용히 기본으로 덮으면 «없는 표정»이 영원히 안 보인다 — 부르는 쪽이 정하라.`);
  }
  return v['컷'];
}

/** 감정 → 그림 경로. `누끼=true` 면 투명판 · `가이드='까몽'` 이면 까몽 공방 경로. */
function 감정경로(감정, opts) {
  const 가이드 = opts && opts['가이드'];
  const 컷 = 감정컷(감정, 가이드);
  return 가이드 && 가이드 !== '몽글' ? 까몽경로(컷, opts) : 경로(컷, opts);
}

/** 「합계 = 갈래 + 갈래」로 센다 — 좋은 0 과 「안 재봤다」를 가른다(유호 지시). */
function 표정현황(가이드) {
  const 표 = 가이드 && 가이드 !== '몽글' ? 감정표뽑기(가이드) : 감정표;
  /* 씨앗 이름은 토큰이 실제 쓰는 상태와 같아야 한다 — 08-29 정정: 옛 씨앗의 「없음」은
     토큰에 없는 이름이라 영원히 빈 배열이었고, 실제 쓰이는 「워프·시안」은 동적 생성으로 뒤에 붙었다. */
  const 갈래 = { 정본: [], 임시대체: [], 합성후보: [], 시안: [], 워프: [], 퇴역: [] };
  for (const [이름, v] of Object.entries(표)) (갈래[v['상태']] || (갈래[v['상태']] = [])).push(이름);
  return { 합계: Object.keys(표).length, ...갈래 };
}

