/* 마스코트 «현행 정본»의 유일한 주인 — 경로는 여기서만 나온다.
 *
 * 왜 다시 썼나 (실측 2026-08-19): 예전의 이 파일은 「이 경로가 마스코트인가」만 알았다.
 * 「어느 것이 현행인가」는 아무도 몰라서, 도구마다 자기가 아는 폴더를 손으로 적었다.
 * 그 결과 마스코트 세트가 10벌 공존했고 — 유호님 확정판은 코드 참조 6회, 옛판이 20회였다.
 * 새 세션이 「마스코트」를 검색하면 가장 오래된 판이 1등으로 나오는 상태였다.
 *
 * 그래서 이 파일은 이제 **하나의 세트만 안다.** 옛 경로를 적으면 그건 없는 파일이라
 * 그 자리에서 깨진다 — 조용히 옛 그림이 나오는 것보다 낫다.
 *
 * 정본 = 펠트코랄_0815 (유호님 확정 2026-08-19 「본체는 펠트코랄0815 이거로 확정」).
 * 펠트(니들펠트 양모)는 SYNK 회사 전용 재질이고, 코랄이 그 위의 확정 색이다.
 */
'use strict';

const path = require('path');
const fs = require('fs');

/* 정본 세트가 사는 곳 — **토큰에서 파생한다**(2026-08-20).
 *
 * 🔑 전엔 이 줄이 경로를 손으로 들었고, `docs/디자인_토큰.json` 의
 *   `재질.펠트.정본사진.평상복` 도 같은 경로를 따로 들었다 — **주인이 둘**이었다.
 *   지금은 값이 같아 보이지만, 다음 정본이 설 때 한쪽만 바뀌면 그 순간부터
 *   「어느 게 현행인가」가 다시 갈린다(그게 마스코트 10벌 공존을 만든 병이다).
 *   ⇒ 토큰이 유일한 주인이고, 이 파일은 **JS 쪽 창구**다.
 *   Python·브라우저는 이 모듈을 못 부르니 같은 토큰 JSON 을 직접 읽는다 —
 *   그래서 주인을 «JS 모듈」이 아니라 «언어 중립인 JSON」에 둔다. */
const 토큰경로 = path.join(__dirname, '..', '..', 'docs', '디자인_토큰.json');
const 토큰 = JSON.parse(fs.readFileSync(토큰경로, 'utf8'));
const 정본폴더 = (() => {
  const 평상복 = 토큰['재질']['펠트']['정본사진']['평상복'];
  if (!평상복) throw new Error('토큰 재질.펠트.정본사진.평상복 이 비었다 — 정본 경로의 주인이 사라졌다');
  return path.posix.dirname(평상복.split(path.sep).join('/'));
})();

/* 표정별 파일. 배경이 붙은 판과 누끼(투명) 판이 따로 있다 —
 * 지면에 얹을 때는 누끼, 배경째 보여줄 때는 그냥 쓴다. */
const 표정 = {
  본체:   '재염색_본체.png',
  눈감음: '재염색_눈감음.png',
  눈웃음: '재염색_눈웃음.png',
  우34:   '재염색_우34.png',
  좌34:   '재염색_좌34.png',
  /* 🔧 놀람은 «합성물»이고 누끼판만 있다 — 본체의 자기 구슬을 1.35배로 키워 얹은 것이다
     (출처 대장 = 누끼/README.md · 08-19). 원본 렌더가 아니라 배경판이 아예 없으므로,
     누끼로만 부르게 «기계로» 막는다 — 없는 파일 경로를 조용히 내주면 그것이 다음 사고다.
     🔑 파일·README·감정 어휘엔 다 있는데 이 목록에만 없어서 창구가 못 찾고 있었다(08-26 실측).
         그 사이 4D 시연은 컷 3장만 쓰고 놀람 한 장을 놀리고 있었다. */
  놀람:   '재염색_놀람.png',
};
const 누끼표정 = { 본체: 1, 눈감음: 1, 눈웃음: 1, 놀람: 1 };  // 누끼/ 아래에 있는 것만
const 누끼전용 = { 놀람: 1 };                    // 배경판이 «없는» 것 — 누끼로만 부른다

/** 표정 하나의 저장소 상대 경로. `누끼=true` 면 투명판을 준다.
 *  없는 표정을 부르면 조용히 다른 걸 주지 않고 던진다 — 조용한 폴백이 이 사고의 원인이었다. */
function 경로(이름 = '본체', { 누끼 = false } = {}) {
  const f = 표정[이름];
  if (!f) throw new Error(`마스코트 표정 「${이름}」은 정본에 없다. 있는 것: ${Object.keys(표정).join(', ')}`);
  if (!누끼 && 누끼전용[이름]) throw new Error(`표정 「${이름}」은 누끼판만 있다(합성물) — 누끼:true 로 부른다.`);
  if (누끼 && !누끼표정[이름]) throw new Error(`표정 「${이름}」은 누끼판이 없다. 있는 것: ${Object.keys(누끼표정).join(', ')}`);
  return 누끼 ? `${정본폴더}/누끼/${f}` : `${정본폴더}/${f}`;
}

/** 절대 경로 — repo 루트를 기준으로 짓는다. */
function 절대경로(이름, opts) {
  return path.join(__dirname, '..', '..', 경로(이름, opts));
}

/* ── 표정 어휘 — «감정 이름»으로 묻는 창구 (2026-08-26 신설 · 유호 지시 「정본에 세워줄래?」) ──
 *
 * 🔑 위의 `표정` 은 «그림 이름»이고(본체·눈감음·…), 여기 것은 «감정 이름»이다(기쁨·놀람·집중·…).
 *   둘은 1:1 이 아니다 — 우34·좌34 는 감정이 아니라 각도고, 눈웃음 한 컷을 여러 감정이 나눠 쓴다.
 *   그래서 어휘를 따로 든다. 주인은 토큰 `캐릭터.몽글.표정` 하나이고 이 파일은 JS 창구다
 *   (Python·브라우저는 이 모듈을 못 부르니 같은 토큰을 직접 읽는다 — 위 머리말과 같은 규율).
 *
 * 🔴 **왜 신설했나**: 표정 10종이 `docs/캐릭터/캐릭터_생명감_설계.md` §2 표 «안에만» 있었다.
 *   문서 안의 표는 사람은 읽지만 **코드는 못 읽는다.** 그 결과 셋이 벌어졌다 —
 *   ①오버레이가 컷표를 손으로 따로 적었고(사본) ②굽기 계획에 한 번도 안 들어갔고
 *   ③「몇 종이 서 있나」를 아무도 셀 수 없었다(유호님이 물으실 때까지 아무도 몰랐다).
 *   ⇒ **어휘는 문서가 아니라 기계가 읽는 자리에 둔다.** 세어지지 않는 목록은 관리되지 않는다.
 */
const 감정표 = (토큰['캐릭터'] && 토큰['캐릭터']['몽글'] && 토큰['캐릭터']['몽글']['표정']) || null;
if (!감정표) throw new Error('토큰 캐릭터.몽글.표정 이 없다 — 표정 어휘의 주인이 사라졌다');

/** 감정 하나가 «지금» 어느 컷으로 나는가. 그림이 없으면 조용히 기본으로 안 물러선다 — 던진다. */
function 감정컷(감정) {
  const v = 감정표[감정];
  if (!v) throw new Error(`표정 「${감정}」은 어휘에 없다. 있는 것: ${Object.keys(감정표).join(', ')}`);
  if (!v['컷']) {
    throw new Error(`표정 「${감정}」은 아직 그림이 없다(상태 ${v['상태']}). `
      + `조용히 기본으로 덮으면 «없는 표정»이 영원히 안 보인다 — 부르는 쪽이 정하라.`);
  }
  return v['컷'];
}

/** 감정 → 그림 경로. `누끼=true` 면 투명판. */
function 감정경로(감정, opts) { return 경로(감정컷(감정), opts); }

/** 「합계 = 갈래 + 갈래」로 센다 — 좋은 0 과 「안 재봤다」를 가른다(유호 지시). */
function 표정현황() {
  const 갈래 = { 정본: [], 임시대체: [], 합성후보: [], 없음: [], 퇴역: [] };
  for (const [이름, v] of Object.entries(감정표)) (갈래[v['상태']] || (갈래[v['상태']] = [])).push(이름);
  return { 합계: Object.keys(감정표).length, ...갈래 };
}

/* ── 가이드 상대역 — 까몽 (2026-08-26 신설) ──────────────────────────────────
 *
 * 🔴 왜 여기 넣나: 까몽 누끼 3장이 `docs/캐릭터/친구공방_0825/누끼/` 에 서 있는데
 *   **경로를 아는 코드가 없었다.** 소비자(영상 통로)가 자기 경로를 손으로 적으면 그 순간
 *   「어느 폴더가 현행인가」의 주인이 둘이 된다 — 이 파일 머리말이 적어 둔 마스코트 10벌 사고가
 *   상대역에서 다시 시작되는 자리다. 그래서 몽글과 «같은 창구»에서 나오게 한다.
 *
 * ⚠ 몽글과 다른 점 둘:
 *   ① 정본 폴더를 토큰에서 파생하지 못한다 — 토큰 `캐릭터.까몽` 은 «어휘»(컷 이름)만 들고
 *      경로는 일부러 안 든다(그 파일 주석: 「경로를 여기 또 적으면 그 순간 주인이 둘이 된다」).
 *      그래서 폴더 이름이 여기 한 번 적히고, 없으면 그 자리에서 깨진다.
 *   ② 컷이 셋뿐이다(본체·눈감음·눈웃음). 우34·좌34 는 아직 안 구웠다.
 *      토큰이 계획으로 다섯을 적어 두었으므로 «있는 것»과 «계획»을 여기서 가른다.
 */
const 까몽폴더 = 'docs/캐릭터/친구공방_0825';
const 까몽컷 = { 본체: 1, 눈감음: 1, 눈웃음: 1 };

/** 까몽 컷 하나의 저장소 상대 경로. `누끼=true` 면 투명판(지면에 얹을 때는 언제나 누끼). */
function 까몽경로(이름 = '본체', { 누끼 = false } = {}) {
  if (!까몽컷[이름]) {
    throw new Error(
      `까몽 컷 「${이름}」은 아직 안 구웠다. 있는 것: ${Object.keys(까몽컷).join(', ')} ` +
        `(조용히 다른 컷으로 물러서지 않는다 — 없는 표정이 영원히 안 보이게 된다)`,
    );
  }
  return 누끼 ? `${까몽폴더}/누끼/까몽_${이름}.png` : `${까몽폴더}/까몽_${이름}.png`;
}

/* 브라우저 안(문자열로 주입되는 코드)에서도 같은 판정을 쓰게 «정규식 소스»로 낸다.
 * 정규식 객체를 넘기면 문자열화에서 이스케이프가 갈린다 — 소스를 넘기고 저쪽에서 짓는다. */
const 패턴소스 = '(펠트코랄_0815)[\\\\/]';

/** 이 경로가 «현행» 마스코트 그림인가. 옛 세트는 이제 저장소에 없으므로 여기서도 참이 아니다. */
function 마스코트경로다(경로문자열) {
  return new RegExp(패턴소스).test(String(경로문자열 || ''));
}

module.exports = {
  정본폴더,
  표정: Object.keys(표정),          // «그림» 이름 — 본체·눈감음·눈웃음·우34·좌34
  감정: Object.keys(감정표),        // «감정» 이름 — 목록을 여기 적지 않는다(토큰이 주인 · 세려면 표정현황())
  감정표,
  감정컷,
  감정경로,
  표정현황,
  경로,
  절대경로,
  패턴소스,
  마스코트경로다,
  /* 가이드 상대역 — 까몽. 몽글과 «같은 창구»에서 경로가 나오게 한다(위 절 참조). */
  까몽폴더,
  까몽컷: Object.keys(까몽컷),
  까몽경로,
  /* 옛 이름 호환 — 지면방·브랜드렌더린트가 폴더 목록을 기대한다. 이제 한 벌뿐이고,
   * 이름도 손으로 안 든다(위 정본폴더에서 파생 — 두 곳에 적으면 그 순간 갈린다). */
  마스코트폴더: [path.posix.basename(정본폴더)],
};
