/** 까몽 컷 하나의 저장소 상대 경로. `누끼=true` 면 투명판(지면에 얹을 때는 언제나 누끼). */
function 까몽경로(이름 = '본체', { 누끼 = false } = {}) {
  if (!(이름 in 까몽컷)) {
    throw new Error(
      `까몽 컷 「${이름}」은 아직 안 구웠다. 있는 것: ${Object.keys(까몽컷).join(', ')} ` +
        `(조용히 다른 컷으로 물러서지 않는다 — 없는 표정이 영원히 안 보이게 된다)`,
    );
  }
  if (누끼 && !까몽컷[이름]['누끼']) {
    throw new Error(
      `까몽 「${이름}」은 누끼판이 없다(정본판만 있다). 누끼가 있는 컷: ` +
        `${Object.keys(까몽컷).filter((k) => 까몽컷[k]['누끼']).join(', ')} — ` +
        `없는 누끼 경로를 내주면 그림이 안 뜨는데 오류도 안 난다.`,
    );
  }
  /* 09-05 판올림 — 몽글과 같다. 한 컷에 파일 하나(전부 투명)라 `누끼` 가 결과를 안 가른다. */
  return `${까몽폴더}/까몽_${이름}.png`;
}

