/* 마스코트 그림을 «경로로» 알아보는 자리 — 목록의 유일한 주인.
 *
 * 왜 생겼나 (실측 2026-08-15): 같은 판정이 두 곳에 각각 적혀 있었다 —
 *   · `tools/시안굽기.js`      : data URI 로 굽기 «전에» `data-synk-mascot` 을 달지 정한다
 *   · `tools/브랜드렌더린트.js`: 마스코트가 어느 바닥 위에 있는지 «잴 대상»을 고른다
 * 둘 다 `마스코트_(누끼|렌더)/` 만 알았다. 그래서 홈페이지 시안을 펠트(`펠트코랄_0815/`)로
 * 갈아끼우자 **두 곳이 동시에 눈을 감았다** — 굽기는 표식을 안 달고, 린트는 그 그림을 못 봐서
 * 「마스코트 바닥 0건」이 나온다. 그 0 은 «깨끗함»이 아니라 «해당 없음»인데 출력은 똑같이 초록이다.
 * CLAUDE.md: 같은 판정을 두 곳에 적으면 갈라진다 — 목록은 하나에서 파생한다.
 *
 * 회귀: `tests/마스코트자산.test.js` 가 ①두 도구가 이 모듈에서 파생하는지 ②새 폴더가
 * 두 곳에 동시에 닿는지를 픽스처로 못박는다.
 */
'use strict';

/* 마스코트 «그림»이 사는 폴더들. 새 세트를 만들면 여기에만 적는다.
 * ⚠ 폴더 이름이지 파일 이름이 아니다 — 경로에 이 조각이 있으면 마스코트로 본다.
 * ⚠ `3D_0815` 는 일부러 뺐다: 그 폴더는 3D 파이프라인의 «입력·중간물»이 섞여 있어
 *   지면에 직접 얹는 자산이 아니다(홈페이지가 참조하면 그건 그 자체로 결함이다). */
/* 🔑 이 목록은 «알아보는» 목록이지 «허용» 목록이 아니다 — 둘을 헷갈리면 퇴역 자산이
 *   조용히 통과한다. 퇴역한 이름을 **빼지 않고 남기는** 이유가 그것이다:
 *   빼면 누가 그 경로를 다시 적었을 때 린트가 「마스코트가 아니다」로 보고 눈을 감는다.
 *   무엇을 «쓸 수 있나»는 `tests/마스코트정본.test.js` 가 진다(구판 경로면 fail). */
const 마스코트폴더 = [
  /* ⛔퇴역 2026-08-19(유호 확정 「이제 아예 안쓸거야」) — 파일도 지웠다. 알아보기 위해서만 남긴다. */
  '마스코트_렌더',      // 체리 원본 렌더(⚠ 알파가 전부 255 — 누끼가 아니었다)
  '마스코트_누끼',      // 위를 채도로 갈라 배경을 지운 사본
  '마스코트_정본',      // 08-14 유호 ③ 확정 세트(체리) — 이름이 「정본」이라 가장 헷갈리던 자리
  /* ✅현행 */
  '펠트코랄_0815',      // 08-15 유호 확정 「ㄱ 재염색」 = 현행 코랄 정본(펠트) · 유일한 의상
];

/** 퇴역한 세트 — 지면이 이걸 가리키면 구판이다(`tests/마스코트정본.test.js` 가 문다). */
const 퇴역폴더 = ['마스코트_렌더', '마스코트_누끼', '마스코트_정본'];

/* 브라우저 안(문자열로 주입되는 코드)에서도 같은 목록을 쓰게 «정규식 소스»로 낸다.
 * 정규식 객체를 넘기면 문자열화 과정에서 이스케이프가 갈린다 — 소스를 넘기고 저쪽에서 짓는다. */
const 패턴소스 = `(${마스코트폴더.join('|')})[\\\\/]`;

/** 경로가 마스코트 그림인가. 윈도 역슬래시도 같이 본다(사람이 실제로 쓰는 표기). */
function 마스코트경로다(경로) {
  return new RegExp(패턴소스).test(String(경로 || ''));
}

module.exports = { 마스코트폴더, 퇴역폴더, 패턴소스, 마스코트경로다 };
