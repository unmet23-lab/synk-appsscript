'use strict';
/* 뜻 대조 층 — 「역번역이 원문과 «같은 것»을 말하나」를 기계가 판정한다.
 *
 * 왜 필요한가(2026-09-02 자 시험 · 이 파일이 태어난 까닭):
 *   몽골어 검문 네 층에 «알려진 방식으로 부순» 문장 일곱을 태워 무엇을 잡나 셌다. 여섯은 잡혔는데
 *   **하나가 ✅통과 도장을 받고 나갔다** — 낱말 하나를 바꿔치기한 것(шалгалтын→хуримын · 시험장→결혼식장).
 *   역번역은 「왜냐하면 **결혼식장**에 AI가 함께 들어가지 않으니까」라고 **글자 그대로 찍어 놨다.**
 *   그런데도 통과한 까닭이 층마다 다르다:
 *     · 문법층 — **한국어 원문을 안 본다**(설계가 그렇다). 「결혼식장에 AI가 안 들어간다」는 문법이 멀쩡하다.
 *     · 맞춤법층 — `хуримын` 은 실재하는 몽골 낱말이라 조용하다.
 *     · 말투층 — 브랜드 위반이 아니다.
 *     · 역번역층 — **증거를 만들어 놓고 아무도 원문과 대조하지 않았다.**
 *   🔑 즉 구멍은 「자가 모자라다」가 아니라 **「역번역↔원문을 «뜻»으로 대조하는 층이 아예 없었다」**였다.
 *   그리고 이게 우리에게 가장 위험한 계열이다 — AI 가 낯선 낱말을 그럴듯한 다른 낱말로 바꿔치기하는 것.
 *   문법은 완벽한 채로 학부모가 딴 얘기를 읽는다.
 *
 * 🔴 왜 «다른 업체»여야 하나 — 장식이 아니다.
 *   역번역을 만든 것이 제미나이다. 같은 제미나이에게 「이 역번역이 원문과 같나」를 물으면
 *   **제 답을 제가 채점하는 것**이라 일관되게 「같다」고 한다. 그래서 이 층만은 codex(OpenAI)로 간다.
 *   🔑 다행히 **이 판정은 몽골어를 몰라도 된다** — 한국어 둘을 견주는 일이라 codex 가 잘하는 자리다.
 *   (저장소가 이미 codex 를 이종 검수에 쓴다 — 새 의존성이 0이다.)
 *
 * 🔴 실패 방향: 못 물어봤으면 「같다」가 아니라 **null(미측정)** 이다. 앞 층들과 같은 규약.
 */

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const 정책 = require(path.join(ROOT, 'tools', '모델정책.js'));
/* 🔴 벤더 한도 게이트를 «반드시» 지난다. codex-review.js 가 제 codex() 하나에 이 게이트를 둔
 *   까닭이 「새 호출 경로가 생겨도 못 샌다 — 라우팅은 훅보다 넓어야 한다」인데, 이 파일이
 *   바로 그 «새 호출 경로»다. 안 지나면 그 주석이 막으려던 구멍을 내가 뚫는 것이다. */
const 런 = require(path.join(ROOT, 'tools', 'lib', '검수런.js'));

/* codex 를 부를 때 우리 저장소가 늘 채우는 자물쇠. 번역 대조는 파일을 만질 일이 없으므로
 * 읽기전용·승인없음으로 잠근다(codex-review.js 의 잠금플래그와 같은 뜻). */
const 잠금 = ['--ignore-user-config', '-c', 'sandbox_mode="read-only"', '-c', 'approval_policy="never"'];

/* 🔴 윈도우에선 `codex` 가 셸 스크립트라 execFileSync 가 ENOENT 로 죽는다(2026-09-02 실측).
 *   codex-review.js 와 «같은» 통로를 쓴다 — cmd.exe /c <APPDATA>/npm/codex.cmd. */
function 실행자(args) {
  const isWin = process.platform === 'win32';
  if (!isWin) return { bin: 'codex', argv: args };
  const bin = path.join(process.env.APPDATA || '', 'npm', 'codex.cmd');
  if (!fs.existsSync(bin)) return null;
  return { bin: process.env.ComSpec || 'cmd.exe', argv: ['/c', bin, ...args] };
}

/* 🔴 잣대가 이 프롬프트의 전부다. 처음엔 「다르냐」만 물었더니 동의어까지 물고 늘어져
 *   **모든 문서가 걸렸다**(2026-09-02 실측: 캐러셀 셋이 셋 다 불통과 · 그 안의 진짜는 각 1건).
 *   자가 요란하면 사람이 자를 안 본다 — 안 재는 것과 같아진다. 그래서 «크기»를 함께 묻는다:
 *   문턱 = **「읽는 사람이 다르게 믿거나 다르게 행동하게 되나」**. 작은 것도 «적기는» 한다
 *   (사람이 보게) — 다만 게이트를 막지 않는다. */
const 프롬프트 = (원문, 역번역) => `아래는 한국어 원문과, 그것을 몽골어로 옮겼다가 다시 한국어로 «직역»해 되돌린 글이다.
직역이라 말투·어순이 어색한 것은 **정상이고 지적 대상이 아니다.** 오직 «뜻»만 본다.

찾을 것: 빠진 것 · 더해진 것 · 뒤집힌 것(긍정↔부정) · 바뀐 것(장소·수·이름·대상).

각 차이를 **크기로 가른다.** 잣대는 하나다 —
**이 글을 읽는 사람(몽골 학부모·지원자)이 «다르게 믿거나 다르게 행동하게» 되는가?**
  · 된다 → 큼   보기: 시험장→결혼식장(장소가 다르다) · 금지한다→금지하지 않는다(반대) ·
                      3일→5일(수가 다르다) · 무료→유료 · 필수→선택 · 이름이 다른 사람
  · 안 된다 → 작음  보기: 답↔대답 · 자란다↔형성된다 · 학원↔교육 센터 · ~습니다↔~다 ·
                      존댓말↔반말 · 어순 · 문장 길이 · 조사 차이
⚠ 애매하면 «작음»으로 둔다. 큰 것만 사람을 부른다.

【한국어 원문】
${원문}

【몽골어를 거쳐 되돌아온 한국어】
${역번역}

출력은 이 형식만. 다른 말 없이:
큼: <무엇이 무엇으로 — 왜 다르게 믿게 되나>      ← 큰 차이마다 한 줄. 없으면 이 줄 자체를 안 적는다
작음: <무엇이 무엇으로>                            ← 작은 차이마다 한 줄. 없으면 안 적는다
판정: 큰것 <개수>`;

/**
 * @returns {Promise<null | {같다: boolean, 이유: string, 원문답: string}>}
 *          null = **미측정**(codex 를 못 불렀거나 답을 못 읽었다). 「같다」가 아니다.
 */
async function 뜻대조(원문, 역번역, { timeoutMs = 180_000, 설정 = null } = {}) {
  if (!원문 || !역번역) return null;
  if (런.한도막나(런.한도상태())) return null; // 벤더 한도 — 미측정(통과 아님)
  const 픽 = 설정 || 정책.분석설정();
  const 부름 = 실행자(['exec', ...잠금, ...정책.코덱스플래그(픽), '--skip-git-repo-check', '-']);
  if (!부름) return null; // codex CLI 가 없다 — 미측정
  let out;
  try {
    out = execFileSync(부름.bin, 부름.argv, {
      input: 프롬프트(String(원문), String(역번역)),
      encoding: 'utf8', timeout: timeoutMs, windowsHide: true,
      maxBuffer: 8 * 1024 * 1024,
      stdio: ['pipe', 'pipe', 'pipe'],
    });
  } catch (e) {
    out = String((e && e.stdout) || '') + String((e && e.stderr) || '');
    if (!out.trim()) return null; // 못 불렀다 — 미측정
  }
  런.한도기록(out); // 한도 문구가 섞여 있으면 마커로 남긴다(다음 호출이 그걸 보고 막는다)
  /* 답 읽기: 「판정:」 줄을 «뒤에서» 찾는다. codex 는 프롬프트를 되울리므로 앞에서 찾으면
   * 내가 보낸 형식 안내문의 「판정: …」을 제 답으로 착각한다(실측 함정 · 09-02). */
  const 줄들 = String(out).split(/\r?\n/);
  let 끝 = -1, 큰수 = null;
  for (let i = 줄들.length - 1; i >= 0; i--) {
    const m = /^\s*판정:\s*큰것\s*(\d+)\s*(?:개)?\s*$/.exec(줄들[i]);
    if (m) { 끝 = i; 큰수 = Number(m[1]); break; }
  }
  if (큰수 === null) return null; // 형식을 못 읽었다 — 통과가 아니라 미측정

  /* 차이 줄은 판정 줄 «위»에서만 걷는다 — 위쪽엔 내가 보낸 프롬프트가 통째로 되울려 있어
   * 전체에서 걷으면 형식 안내문의 보기(「시험장→결혼식장」)까지 제 답으로 센다. */
  const 큰것 = [], 작은것 = [];
  for (let i = Math.max(0, 끝 - 60); i < 끝; i++) {
    const c = /^\s*큼:\s*(.+?)\s*$/.exec(줄들[i]);
    const s = /^\s*작음:\s*(.+?)\s*$/.exec(줄들[i]);
    if (c) 큰것.push(c[1]); else if (s) 작은것.push(s[1]);
  }
  /* 개수와 걷힌 줄이 어긋나면 «셈»을 믿는다(모델이 센 것) — 대신 그 사실을 드러낸다.
   * 조용히 한쪽을 고르면 「0건」과 「못 읽었다」가 또 같은 모양이 된다. */
  const 어긋남 = 큰수 !== 큰것.length;
  return {
    같다: 큰수 === 0,
    큰것, 작은것, 큰수, 어긋남,
    이유: 큰것.join(' · ') || (어긋남 ? `모델이 큰것 ${큰수}개라 했는데 줄을 못 걷었다` : ''),
    원문답: String(out).slice(-1500),
  };
}

module.exports = { 뜻대조, 프롬프트 };
