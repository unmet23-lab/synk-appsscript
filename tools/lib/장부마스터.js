#!/usr/bin/env node
/* 장부마스터 — 「이 신호가 **origin/master 에서 이미 닫혔나**」를 묻는 한 곳 (마찰 F625).
 *
 * 왜 있나 (2026-08-18 실측 · `local_ad0673f3`):
 *   승계한 트랙을 두 시간 짓고 커밋·push 까지 마친 뒤 master 를 당겼더니, 그 사이 원 세션이
 *   **같은 신호를 더 나은 판으로 닫아 놓았다.** 구현 한 벌 + 전량 CI 165초 + 변이 런 2회를
 *   통째로 버렸고, 장부는 같은 파일에 F616 행이 **둘**이 된 채 커밋됐다.
 *
 * 🔑 이 저장소의 점유·경합 장치는 전부 **「지금 누가 잡고 있나」**를 잰다
 *   (board-guard · `lib/보드.js` · track-collision · 대기열 점유). 그 판에서 답은 끝까지
 *   「내가 잡고 있다」로 **맞았다** — 잡은 사람이 나 하나였으니까. 못 본 것은 «잡혔나»가 아니라
 *   **«이미 끝났나»** 이고, 그 질문을 던지는 층이 0이었다. 이 파일이 그 층이다.
 *
 * ⚠ **판정을 여기서 짓지 않는다** — 「해소냐」는 `friction.js` 의 `상태()` 하나가 진다.
 *   여기는 ①어느 층을 열지 ②그 층을 어떻게 여는지만 안다. 같은 판정을 두 곳에 적으면
 *   갈라지고, 갈라진 쪽의 증상은 언제나 「통과」다(CLAUDE.md 신뢰성 ④).
 *
 * ⚠ **두 층을 다 연다**(F348). 행은 조각(`docs/_ops/장부/F0NN.md`)에도 살고 동결 아카이브
 *   (`docs/_ops/마찰신호.md`)에도 산다. 한 층만 열고 「master 에 없다」를 내면 그건 부정 판정을
 *   한 갈래로 낸 것이다 — F348 이 금지한 그 자리다. 같은 번호끼리는 **조각이 이긴다**
 *   (`friction.js read()` 와 같은 규칙 — 규칙이 갈리면 회귀가 먼저 빨개져야 한다).
 *
 * 〖대가 — 틀릴 때의 모습〗 (CLAUDE.md 「새 장치엔 대가를 함께 적는다」)
 *   · 못 읽으면 **`모름`** 이다. 부르는 쪽은 이것을 fail 이 아니라 **skip 으로 드러낸다**(F296) —
 *     즉 새는 방향이 「통과」다. 오프라인·얕은 클론 세션이 신호를 영영 못 닫는 쪽보다 이쪽을 고른다.
 *     그래서 `모름` 을 `없음`(=master 에 그 행이 없다)과 **절대 같게 다루지 않는다**.
 *   · `fetch` 에 타임아웃이 없다 — `master동기.전진` 과 **같은 실행기**를 쓴다(러너를 새로 만들면
 *     git 호출 모양이 저장소에 둘이 된다). 네트워크가 죽으면 git 자신의 실패로 떨어지고 `모름` 이 된다.
 *   · `당김:false` 로 부르면 **낡은 ref** 를 읽는다 — F625 의 그 판이 정확히 낡은 ref 였다
 *     (착수 직후 당긴 뒤 30커밋이 지났다). 그래서 기본값이 `true` 고, 결과에 `신선도` 를 함께 낸다.
 *   닫을 것: **없다.** 새 훅·새 상시 계기를 만들지 않고 이미 도는 쓰기 통로(`resolve`·`defer`)
 *   앞에 함수 하나를 둔다 — 물러날 자리도 그 두 호출뿐이다.
 */
'use strict';

const path = require('node:path');
const 동기 = require(path.join(__dirname, 'master동기.js'));
const { 칸나누기 } = require(path.join(__dirname, '표.js'));

/** 저장소 뿌리 기준 git 경로. 뿌리 **밖**이면 `null`(= 못 잰다) — 픽스처가 여기로 떨어진다. */
function git경로(뿌리, 파일) {
  const rel = path.relative(뿌리, 파일);
  if (!rel || rel.startsWith('..') || path.isAbsolute(rel)) return null;
  return rel.split(path.sep).join('/');
}

/** 본문에서 그 번호의 행 한 줄. 없으면 `null`. (표기 흔들림은 `조각행뽑기` 와 같은 `\s*` 규칙) */
function 행뽑기(본문, id) {
  const 정규 = new RegExp(`^\\|\\s*${id}\\s*\\|`, 'i');
  for (const l of String(본문 || '').split('\n')) {
    const t = l.trim();
    if (정규.test(t)) return t;
  }
  return null;
}

/**
 * `origin/<가지>` 에서 이 번호가 어떤 상태인가.
 *
 * 돌려주는 것 — `{ 상태, 해소문, 층, 기준, 신선도, 사유 }`
 *   · `상태` = `'해소'` · `'살아있음'`(열림·보류) · `'없음'`(그 번호가 master 에 아예 없다) · `'모름'`
 *   · `사유` 는 `'모름'` 일 때만 채워진다 — **왜 못 쟀는지**가 없으면 0과 구별이 안 된다(F207).
 *
 * @param {string} id  `F625` 꼴
 * @param {object} o
 *   `뿌리`·`장부`(동결 아카이브 경로)·`폴더`(조각 폴더 경로) — `friction.js` 의 상수를 그대로 받는다.
 *   `행상태(줄)` — **필수**. 장부 행 한 줄을 받아 `'해소'|'보류'|'열림'` 을 내는 함수(부르는 쪽의 판정).
 */
function 마스터판(id, o = {}) {
  const 실행 = o.실행 || 동기.기본실행;
  const 가지 = o.가지 || 동기.기본가지;
  const 뿌리 = o.뿌리;
  const 번호 = String(id || '').toUpperCase();
  const 모름 = (사유) => ({ 상태: '모름', 해소문: '', 층: '', 기준: '', 신선도: '', 사유 });

  if (!/^F\d+$/.test(번호)) return 모름(`번호 꼴이 아니다: ${id}`);
  if (typeof o.행상태 !== 'function') return 모름('행상태() 를 안 줬다 — 판정을 지어내지 않는다');

  const 조각경로 = git경로(뿌리, path.join(o.폴더, `${번호}.md`));
  const 장부경로 = git경로(뿌리, o.장부);
  if (!조각경로 && !장부경로) return 모름('장부가 저장소 밖이다 — git 으로 읽을 자리가 없다');

  const ref = `origin/${가지}`;
  const 있나 = 실행(['rev-parse', '--verify', '--quiet', `${ref}^{commit}`], 뿌리);
  if (!있나.성공) return 모름(`${ref} 참조가 없다(얕은 클론·원격 미설정)`);

  /* 낡은 ref 를 읽으면 이 장치는 **정확히 F625 의 그 판**을 다시 통과시킨다. 그래서 당긴다. */
  let 신선도 = '안 당김';
  if (o.당김 !== false) {
    const f = 실행(['fetch', '--quiet', 'origin', 가지], 뿌리);
    신선도 = f.성공
      ? '당김'
      : `낡을 수 있다(fetch 실패: ${((f.오류 || f.출력).split(/\r?\n/).find((l) => l.trim()) || '사유 모름').slice(0, 80)})`;
  }
  const 머리 = 실행(['rev-parse', '--short', ref], 뿌리);
  const 기준 = 머리.성공 ? 머리.출력 : '';

  /* 두 층을 **다 연다** — 한 층만 열고 「없다」를 내면 그건 한 갈래로 낸 부정 판정이다(F348). */
  let 열린층 = 0;
  const 후보 = [];
  for (const [층, 경로] of [['조각', 조각경로], ['동결 아카이브', 장부경로]]) {
    if (!경로) continue;
    const r = 실행(['show', `${ref}:${경로}`], 뿌리);
    /* 파일이 없어서 실패한 것과 git 이 죽어서 실패한 것을 `git show` 는 같은 종료코드로 낸다.
     * 가르는 재료는 **ref 가 살아 있다는 위의 확인**이다 — 거기까지 통과했으면 실패는
     * 「그 경로가 그 커밋에 없다」로 읽는다(그건 정상이고, 조각은 흔히 없다). */
    if (!r.성공) continue;
    열린층 += 1;
    const 줄 = 행뽑기(r.출력, 번호);
    if (줄) 후보.push({ 층, 줄 });
  }
  if (!열린층) return 모름(`${ref} 에서 장부를 못 읽었다(경로: ${[조각경로, 장부경로].filter(Boolean).join(' · ')})`);
  if (!후보.length) return { 상태: '없음', 해소문: '', 층: '', 기준, 신선도, 사유: '' };

  const 고른것 = 후보[0];                                   // 조각이 이긴다 — read() 와 같은 규칙
  const 행상태 = o.행상태(고른것.줄);
  const 해소문 = 마지막칸(고른것.줄).trim();
  return {
    상태: 행상태 === '해소' ? '해소' : '살아있음',
    해소문,
    층: 고른것.층,
    기준,
    신선도,
    사유: '',
  };
}

/** 행의 **마지막 칸**(해소 칸) 원문 — 보여 줄 문장을 뽑는 자리다.
 *  🔑 날 `split` 으로 가르지 않는다: 해소문에는 백틱 안 파이프(`` `a|b` ``)가 실제로 산다.
 *  칸 가르기는 저장소에 **한 통로**뿐이다(`lib/표.js` · `tests/표칸.test.js` 가 옛 통로를 금지한다). */
function 마지막칸(줄) {
  const 칸 = 칸나누기(String(줄));
  return 칸.length ? 칸[칸.length - 1] : '';
}

/**
 * 사람이 읽는 한 줄/한 덩이. **통과도 찍는다** — 안 돈 것과 통과가 같은 모양이면 안 된다(F207).
 * `막힘:true` 면 부르는 쪽이 **쓰기를 멈춘다**.
 */
function 문구(번호, 판, { 우회플래그 = '--마스터확인함', 조각경로 = '' } = {}) {
  const 꼬리 = `기준 origin/master ${판.기준 || '?'} · ${판.신선도}`;
  if (판.상태 === '해소') {
    return {
      막힘: true,
      글: `🔴 [friction] ${번호} 는 **origin/master 에서 이미 해소**다 — 여기서 닫으면 같은 번호의 행이 둘이 된다(F625 그 사고).\n`
        + `   그쪽 해소문(${판.층}): ${판.해소문.slice(0, 200)}${판.해소문.length > 200 ? '…' : ''}\n`
        + `   ${꼬리}\n`
        + '   처방 ① 그쪽 판을 받고 내 판은 버린다:\n'
        + `        git checkout origin/master -- ${조각경로 || `docs/_ops/장부/${번호}.md`}\n`
        + '   처방 ② 내 해소도 남겨야 하면 **두 문장을 합쳐** 다시 닫는다(그때만 우회한다):\n'
        + `        node tools/friction.js resolve ${번호} "…그쪽 문장 + 내 문장…" ${우회플래그}\n`
        + '   처방 ③ 알고 보니 다른 사건이면 새 번호로 신고한다:\n'
        + '        node tools/friction.js add 마찰 "…"',
    };
  }
  if (판.상태 === '모름') {
    return { 막힘: false, 글: `  ⓘ master 대조 **건너뜀** — ${판.사유} (중복 해소를 못 막았다 · F296 대로 fail 로 세우지 않는다)` };
  }
  if (판.상태 === '없음') return { 막힘: false, 글: `  ⓘ master 대조 ✓ — 그 번호가 origin/master 에 아직 없다 (${꼬리})` };
  return { 막힘: false, 글: `  ⓘ master 대조 ✓ — origin/master 에서도 열려 있다 (${판.층} · ${꼬리})` };
}

module.exports = { 마스터판, 문구, git경로, 행뽑기, 마지막칸 };
