'use strict';
/**
 * 트랙수대조 — 트랙에 적힌 «수»가 그 수의 정본과 어긋나는지 잰다.
 *
 * 🔴 왜 짓나 (유호 지시 2026-09-05 「자 만들어줘」)
 *   트랙은 색인이라 수가 많은데, 그 수를 **되잴 방법이 안 적혀 있으면 조용히 낡는다.**
 *   같은 날 실측: 말투 분모가 82 → 99 로 어긋나 있었고(17곳이 새로 붙었다),
 *   crewcard 배포 지문은 **세 번째로** 낡아 있었다. 둘 다 「자가 없어서」 아무도 못 알았다.
 *   반대로 소급 189건·지원사업 17건은 정본이 그 수를 적고 있는데도 대조하는 자가 없었다.
 *
 * 🔑 이 자의 뜻은 «완벽한 셈»이 아니라 «어긋남 알리기»다.
 *   항목 하나 = 「트랙이 적은 수」와 「그 수를 되잴 자리」의 짝. 둘이 다르면 든다.
 *
 * 🔴 **못 찾은 것을 «맞다»로 읽지 않는다.** 무늬가 아무것도 못 잡으면 그것을 따로 든다 —
 *   문서 한 줄이 고쳐지면 무늬가 죽고, 죽은 무늬는 «어긋남 0건»이라는 거짓 초록을 낸다.
 *   이 저장소가 여러 번 밟은 자리다(기억 `zero-is-a-success-face-taxonomy`).
 *
 * 쓰기: node tools/lib/트랙수대조.js
 *   문서에 표시한 같은 시점·분모끼리 대조한다. 현재 글검사 전량은 별도 실행한다.
 *   옛 --전부 인자는 호환상 허용하지만 과거 판정 수를 오늘의 기계 지적 수와 비교하지 않는다.
 */

const fs = require('fs');
const path = require('path');

const 트랙경로 = 'docs/_ops/트랙.md';

/**
 * 대조표 — 한 줄이 「트랙의 수 하나」와 「그것을 되잴 자리」를 짝짓는다.
 *
 * · `트랙` = 트랙에서 그 수를 집는 무늬(첫 묶음이 수여야 한다)
 * · `참` = 참값을 내는 자. 파일 대조면 `{파일, 무늬}`, 도구를 돌려야 하면 `{돌린다}`
 * · `뜻` = 이 수가 «무엇을 센 값»인지 한 줄. 어긋났을 때 사람이 읽을 말이다
 */
const 대조표 = [
  {
    이름: '소급 — 판정 대기 건수(09-03 색인 기록)',
    트랙: /남은 것 = 실물 판정 (\d+)건/,
    참: { 파일: 'docs/소급불가_색인_2026-09-03.md', 무늬: /(\d+)건은 «후보»다/ },
    뜻: '09-03 색인이 「N건은 «후보»다」로 적은 당시 수. 오늘의 미완료 건수는 후속 판정과 실제 결과를 확인한다',
  },
  {
    이름: '소급 — 전체 건수',
    /* 09-08: 옛 무늬 `/(\d+)건 중 실물로/` 가 죽어 있었다(트랙 문구가 바뀌었다).
       종료 코드가 «못잼»을 안 세던 탓에 조용히 지나갔다 — 심문이 잡았다. */
    트랙: /위 \d+·(\d+) 를 되잴 자/,
    참: { 파일: 'docs/소급불가_색인_2026-09-03.md', 무늬: /아래 (\d+)건 중/ },
    뜻: '색인 정본이 든 항목 전체 수',
  },
  {
    /* 🔴 위 둘은 «문서끼리» 잰다 — 두 문서가 함께 낡으면 초록이 난다(판정 0908 §5 가 적어 둔 구멍).
       이 줄이 그 구멍을 막는다: 색인이 «적은 수»를 재료 json 의 «실제 항목 수»에 댄다. */
    이름: '소급 — 색인이 적은 수 vs 재료의 실제 항목 수',
    트랙: /위 \d+·(\d+) 를 되잴 자/,
    참: {
      돌린다: (뿌리) => {
        const p = path.join(뿌리, 'docs', '_ops', '소급불가_울트라', '전량.json');
        const j = JSON.parse(fs.readFileSync(p, 'utf8'));
        if (!Array.isArray(j)) throw new Error('전량.json 이 배열이 아니다');
        return j.length;
      },
    },
    뜻: 'docs/_ops/소급불가_울트라/전량.json 의 항목 수(사람이 옮겨 적지 않은 유일한 수)',
  },
  {
    이름: '창업지원 — 전체 건수(신청·문의 관리 범위)',
    트랙: /창업·정부 지원사업 (\d+)건/,
    참: { 파일: 'docs/정부지원금_실행지.md', 무늬: /현행 범위는 신청·문의 (\d+)건이다/ },
    뜻: '실행지의 현행 신청·문의 관리 범위. 접수완료 수가 아니며 개별 상태는 최신 표를 읽는다',
  },
  {
    이름: '말투 — 09-08 판정 잔여',
    트랙: /09-08 기록의 남은 것 = \*\*(\d+)곳 판정\*\*/,
    참: { 파일: 'docs/말투_판정_0908.md', 무늬: /남은 (\d+)곳은 갈래가 셋이다/ },
    뜻: '09-08 판정의 잔여 수. 현재 글검사가 내는 전체 지적 수와 분모가 다르다',
  },
];

/** 현행 관리 범위 = 이전 목록 - 제외 + 포함. 접수 상태를 서로 더해 완료 수로 읽지 않는다. */
const 갈래검사 = [
  {
    이름: '창업지원 — 합계가 갈래의 합인가',
    파일: 'docs/정부지원금_실행지.md',
    무늬: /현행 범위는 신청·문의 (\d+)건이다[^\n]*?옛 (\d+)건 목록에서[^\n]*?(\d+)건을 제외하고[^\n]*?(\d+)건을 포함했다/,
    뜻: '실행지의 관리 범위 = 옛 목록 - 미신청 제외 + 새 관리 대상 포함',
  },
];

const 수뽑기 = (글, 무늬) => {
  const m = 글.match(무늬);
  return m ? Number(String(m[1]).replace(/,/g, '')) : null;
};

/**
 * @param {string} 뿌리 저장소 뿌리
 * @returns {{어긋남: object[], 못잼: object[], 맞음: object[]}}
 */
function 대조하기(뿌리 = process.cwd()) {
  const 어긋남 = [], 못잼 = [], 맞음 = [];
  const 트랙파일 = path.join(뿌리, 트랙경로);
  if (!fs.existsSync(트랙파일)) {
    return { 어긋남, 못잼: [{ 이름: '트랙 자체', 사유: `${트랙경로} 가 없다` }], 맞음 };
  }
  const 트랙글 = fs.readFileSync(트랙파일, 'utf8');

  for (const 항 of 대조표) {
    const 트랙값 = 수뽑기(트랙글, 항.트랙);
    if (트랙값 === null) {
      // 🔴 무늬가 죽은 것을 «맞다»로 읽지 않는다 — 그것이 거짓 초록의 통로다
      못잼.push({ 이름: 항.이름, 사유: `트랙에서 수를 못 집었다(무늬 ${항.트랙}) — 그 줄이 고쳐졌으면 여기 무늬도 같이 고친다`, 뜻: 항.뜻 });
      continue;
    }
    let 참값 = null, 사유 = null;
    try {
      if (항.참.돌린다) 참값 = 항.참.돌린다(뿌리);
      else {
        const p = path.join(뿌리, 항.참.파일);
        if (!fs.existsSync(p)) 사유 = `정본 ${항.참.파일} 이 없다(이름이 바뀌었으면 대조표를 고친다)`;
        else {
          참값 = 수뽑기(fs.readFileSync(p, 'utf8'), 항.참.무늬);
          if (참값 === null) 사유 = `정본 ${항.참.파일} 에서 수를 못 집었다(무늬 ${항.참.무늬})`;
        }
      }
    } catch (e) {
      사유 = `참값을 못 냈다 — ${e.message.split('\n')[0]}`;
    }
    if (참값 === null) { 못잼.push({ 이름: 항.이름, 사유, 트랙값, 뜻: 항.뜻 }); continue; }
    if (참값 !== 트랙값) 어긋남.push({ 이름: 항.이름, 트랙값, 참값, 뜻: 항.뜻 });
    else 맞음.push({ 이름: 항.이름, 값: 트랙값 });
  }

  for (const 항 of 갈래검사) {
    const p = path.join(뿌리, 항.파일);
    if (!fs.existsSync(p)) { 못잼.push({ 이름: 항.이름, 사유: `${항.파일} 이 없다`, 뜻: 항.뜻 }); continue; }
    const m = fs.readFileSync(p, 'utf8').match(항.무늬);
    if (!m) { 못잼.push({ 이름: 항.이름, 사유: `합계 줄을 못 찾았다(무늬 ${항.무늬})`, 뜻: 항.뜻 }); continue; }
    const 합계 = Number(m[1]);
    const 갈래수 = [Number(m[2]), -Number(m[3]), Number(m[4])];
    const 더한값 = 갈래수.reduce((a, b) => a + b, 0);
    if (!갈래수.length) { 못잼.push({ 이름: 항.이름, 사유: '갈래에서 수를 하나도 못 집었다', 뜻: 항.뜻 }); continue; }
    if (더한값 !== 합계) 어긋남.push({ 이름: 항.이름, 트랙값: 합계, 참값: 더한값, 뜻: `${항.뜻} · 갈래 ${갈래수.join('+')}` });
    else 맞음.push({ 이름: 항.이름, 값: 합계 });
  }

  return { 어긋남, 못잼, 맞음 };
}

module.exports = { 대조하기, 대조표, 갈래검사, 트랙경로 };

if (require.main === module) {
  const r = 대조하기(path.resolve(__dirname, '..', '..'));
  console.log(`[트랙수대조] 맞음 ${r.맞음.length} · 어긋남 ${r.어긋남.length} · 못잼 ${r.못잼.length}`);
  for (const x of r.어긋남) console.log(`  🔴 ${x.이름} — 트랙 ${x.트랙값} ≠ 참 ${x.참값}\n     ↳ ${x.뜻}`);
  for (const x of r.못잼) console.log(`  ⚠ ${x.이름} — ${x.사유}\n     ↳ ${x.뜻 || ''}`);
  for (const x of r.맞음) console.log(`  ✅ ${x.이름} = ${x.값}`);
  /* 🔴 종료 코드를 셋으로 가른다 — 0=맞음 · 1=어긋남 · 2=못 쟀다 (심문 09-08 P1).
   *   첫 판은 «어긋남»만 종료 상태에 넣어서, 재려는 파일이 아예 없어도 종료 0 이 나갔다.
   *   이 코드를 읽는 자동화에서는 «검증 불능»이 «통과»와 구별되지 않았다
   *   (zero-is-a-success-face-taxonomy). 「못 쟀다」는 0건이 아니다. */
  if (r.못잼.length) console.log(`  🔴 ${r.못잼.length}건은 «못 쟀다» — 0건이 아니다(종료 2).`);
  process.exitCode = r.어긋남.length ? 1 : (r.못잼.length ? 2 : 0);
}
