'use strict';

const fs = require('fs');
const path = require('path');

/** 재심 주기의 기준 요일 — 유호 아이디어 08-17 「매주 수요일」. 0=일 … 3=수.
 *  ⚠ 개원(2027-02-25) 후 수요일이 수업일이면 재조정한다 — 지금은 미개원이라 무관. */
const 주기요일 = 3;

/** 관측 로그 — append-only. 매 세션 적지 않는다(**바뀔 때만**) — 하루 수십 세션이라 매번 적으면
 *  파일이 신호가 아니라 소음이 된다. 그래서 「관측」 줄은 모델이 갈릴 때만 는다. */
const 로그상대경로 = path.join('docs', '_ops', '모델관측.jsonl');

/* ── 날짜: 문자열 YYYY-MM-DD 로만 다룬다 ───────────────────────────────
 * `new Date('2026-08-17')` 은 **UTC 자정**이라 한국 시간대에서 하루 밀린다.
 * 그래서 파싱도 조립도 로컬 생성자로만 한다(F 계열 시간대 사고 예방). */

function 날짜문자열(d) {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

function 날짜파싱(s) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(s || '').trim());
  if (!m) return null;
  const d = new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]));
  return Number.isNaN(d.getTime()) ? null : d;
}

/** 기준일 **다음**의 첫 주기요일. 기준일 자신이 그 요일이면 다음 주 같은 요일이다
 *  (같은 날 두 번 도래하지 않게 — 재심 당일에 또 뜨면 그 알림은 배경이 된다). */
function 다음주기일(기준) {
  const d = new Date(기준.getFullYear(), 기준.getMonth(), 기준.getDate());
  do { d.setDate(d.getDate() + 1); } while (d.getDay() !== 주기요일);
  return d;
}

/* ── 로그 ────────────────────────────────────────────────────────── */

/** jsonl 읽기 — 깨진 줄은 **버리지 않고 센다**. 조용히 건너뛰면 「기록이 없다」와
 *  「기록을 못 읽었다」가 같은 모양이 된다(F207). */
function 로그읽기(경로) {
  let 원문;
  try { 원문 = fs.readFileSync(경로, 'utf8'); } catch (_) { return { 줄들: [], 없음: true, 깨짐: 0 }; }
  const 줄들 = [];
  let 깨짐 = 0;
  for (const l of 원문.split('\n')) {
    const t = l.trim();
    if (!t) continue;
    try { 줄들.push(JSON.parse(t)); } catch (_) { 깨짐 += 1; }
  }
  return { 줄들, 없음: false, 깨짐 };
}

function 마지막(줄들, 사건) {
  for (let i = 줄들.length - 1; i >= 0; i--) if (줄들[i] && 줄들[i].사건 === 사건) return 줄들[i];
  return null;
}

/**
 * 장부만 읽어 「아직 재심 안 한 모델 변경」을 낸다 — 세션 모델을 못 읽는 자리(SessionStart)용.
 *
 * 🔑 «마지막 두 줄»을 비교하지 않는다. 가지 둘이 같은 변경을 각각 관측하고 머지되면 같은 모델이
 *   연달아 앉는데, 그때 마지막 두 줄만 보면 **갈린 사실이 통째로 증발한다**(조용한 통과 · 맹점 ④).
 *   그래서 «지금 모델이 시작된 자리»까지 거슬러 올라가 그 앞 줄과 비교한다.
 *
 * 🔑 그리고 **재심 줄이 끈다.** 라이브 판(세션 모델 비교)은 관측 줄을 적는 순간 저절로 꺼졌지만,
 *   장부 판은 지금 모델이 이미 장부에 있어 스스로 안 꺼진다 — 안 끄면 이 알림이 영구히 뜨고
 *   영구히 뜨는 알림은 배경이 된다(머리말 대가 ②와 같은 처방 = `--재심완료`).
 */
function 장부바뀜(줄들) {
  const 관측 = [];
  for (let i = 0; i < 줄들.length; i++) {
    const o = 줄들[i];
    if (o && o.사건 === '관측' && String(o.모델 || '').trim()) 관측.push({ 줄: o, 자리: i });
  }
  /* 관측이 0건이면 아래 «마지막»이 없다. 1건인 자리는 여기서 안 막는다 —
   *  그건 `시작 === 0` 이 이미 지고, 같은 판정을 두 곳에 적으면 그날 갈라진다(등록층 ④). */
  if (!관측.length) return null;

  const 지금 = 관측[관측.length - 1].줄.모델;
  let 시작 = 관측.length - 1;
  while (시작 > 0 && 관측[시작 - 1].줄.모델 === 지금) 시작 -= 1;
  if (시작 === 0) return null;                       // 처음부터 같은 모델이었다 — 갈린 적 없다

  for (let i = 관측[시작].자리 + 1; i < 줄들.length; i++) {
    if (줄들[i] && 줄들[i].사건 === '재심') return null;   // 갈린 뒤에 재심했다 — 닫힌 신호
  }
  const 이전 = 관측[시작 - 1].줄;
  return { 이전: 이전.모델, 지금, 이전날짜: 이전.날짜 || null };
}

/* ── 판정 ────────────────────────────────────────────────────────── */

/**
 * @param {object} o
 * @param {string|null} o.모델   현재 세션 모델 id (`lib/context-size.js` 의 `currentContext().model`)
 * @param {string} o.뿌리        저장소 루트
 * @param {Date}   [o.지금]      테스트 주입용
 * @returns {{측정:boolean, 사유?:string, 모델:string|null, 모델바뀜:object|null,
 *            주기도래:object|null, 적을줄:object|null, 깨짐:number}}
 */
function 판정({ 모델, 뿌리, 지금 } = {}) {
  const now = 지금 instanceof Date ? 지금 : new Date();
  const 오늘 = 날짜문자열(now);
  const 경로 = path.join(뿌리 || process.cwd(), 로그상대경로);
  const { 줄들, 깨짐 } = 로그읽기(경로);

  /* 🔴 모델을 못 읽으면 **여기서 멈춘다.** 「안 바뀌었다」로 접으면 그 침묵이 통과와 같은
   *   모양이 된다 — 새는 방향은 언제나 「통과」다(CLAUDE.md 신뢰성). 주기 판정은 모델과
   *   무관하므로 그것만 살려 낸다. */
  const 모델있음 = !!String(모델 || '').trim();

  const 마지막관측 = 마지막(줄들, '관측');
  const 모델바뀜 = (모델있음 && 마지막관측 && 마지막관측.모델 !== 모델)
    ? { 이전: 마지막관측.모델, 지금: 모델, 이전날짜: 마지막관측.날짜 || null }
    : null;

  /* 첫 관측이거나 모델이 갈렸을 때만 줄을 적는다(로그 비대 방지 — 위 상수 주석). */
  const 적을줄 = (모델있음 && (!마지막관측 || 모델바뀜))
    ? { 날짜: 오늘, 모델, 사건: '관측' }
    : null;

  const 마지막재심 = 마지막(줄들, '재심');
  let 주기도래 = null;
  if (!마지막재심) {
    /* 재심 기록이 아예 없다 = 제도 첫 회차. 도래로 친다 — 「한 번도 안 했다」가
     *  「방금 했다」와 같은 대접을 받으면 이 제도는 시작조차 안 한다(그게 0번 돌았던 병이다). */
    주기도래 = { 마지막재심: null, 사유: '첫 회차 — 재심 기록이 아직 없다' };
  } else {
    const 기준 = 날짜파싱(마지막재심.날짜);
    if (!기준) {
      주기도래 = { 마지막재심: 마지막재심.날짜 || null, 사유: '마지막 재심 날짜를 못 읽었다' };
    } else {
      const 도래일 = 다음주기일(기준);
      if (도래일 <= now) {
        주기도래 = {
          마지막재심: 마지막재심.날짜,
          도래일: 날짜문자열(도래일),
          지난날: Math.floor((now - 기준) / 86_400_000),
        };
      }
    }
  }

  if (!모델있음) {
    /* 🔑 이 세션 모델은 못 읽었다. 그래도 **장부는 읽힌 값의 기록**이라 축이 죽지 않는다 —
     *   SessionStart 가 바로 이 자리이고, 여기서 접었기 때문에 ㉠ 이 원리상 0 이었다(머리말). */
    if (마지막관측 && String(마지막관측.모델 || '').trim()) {
      return {
        측정: true,
        출처: '장부',
        모델: 마지막관측.모델,
        모델바뀜: 장부바뀜(줄들),
        주기도래,
        적을줄: null,          // 관측은 Stop 이 진다 — 두 곳에서 적으면 장부가 갈라진다
        깨짐,
      };
    }
    return {
      측정: false,
      출처: null,
      사유: '세션 모델도 장부도 비었다(첫 설치일·트랜스크립트 없음·손 실행) — 「안 바뀌었다」가 아니다',
      모델: null, 모델바뀜: null, 주기도래, 적을줄: null, 깨짐,
    };
  }
  return { 측정: true, 출처: '세션', 모델, 모델바뀜, 주기도래, 적을줄, 깨짐 };
}

/**
 * 모델을 **관측한다** — 값이 실제로 사는 시점(Stop)에서만 부른다.
 * 갈렸을 때(그리고 첫 회차)만 적는다 — 매 턴 적으면 장부가 신호가 아니라 소음이 된다.
 * @returns {object|null} 실제로 적은 줄 (안 적었으면 null)
 */
function 관측하기({ 뿌리, 모델, 지금 } = {}) {
  const m = String(모델 || '').trim();
  if (!m) return null;                                   // 못 읽었으면 **아무것도 안 적는다**
  const now = 지금 instanceof Date ? 지금 : new Date();
  const { 줄들 } = 로그읽기(path.join(뿌리 || process.cwd(), 로그상대경로));
  const 마지막관측 = 마지막(줄들, '관측');
  if (마지막관측 && 마지막관측.모델 === m) return null;   // 안 갈렸다
  const 줄 = { 날짜: 날짜문자열(now), 모델: m, 사건: '관측' };
  return 덧붙이기(뿌리, 줄) ? 줄 : null;
}

/** 관측/재심 줄 덧붙이기 — append-only. 실패해도 **부르는 쪽을 죽이지 않는다**(계기판이지 가드가 아니다). */
function 덧붙이기(뿌리, 줄) {
  if (!줄) return false;
  const 경로 = path.join(뿌리 || process.cwd(), 로그상대경로);
  try {
    fs.mkdirSync(path.dirname(경로), { recursive: true });
    fs.appendFileSync(경로, `${JSON.stringify(줄)}\n`, 'utf8');
    return true;
  } catch (_) { return false; }
}

/** 재심을 **실제로 돌렸다**고 적는다. 분모를 함께 받는다 —
 *  「12개 보고 0」과 「3개 보고 0」은 다르다(유호 확정 [[report-zero-with-denominator]]). */
function 재심완료({ 뿌리, 모델, 본것, 뒤집음, 지금 }) {
  const now = 지금 instanceof Date ? 지금 : new Date();
  return 덧붙이기(뿌리, {
    날짜: 날짜문자열(now),
    모델: 모델 || null,
    사건: '재심',
    본것: Number(본것) || 0,
    뒤집음: Number(뒤집음) || 0,
  });
}

