'use strict';
/**
 * Loom 얹기 — 남의 지면에 부품 CSS 를 «입히는» **공용 통로 하나**.
 *
 * ■ 왜 뗐나 (2026-08-18 · ④ 지면 배선)
 *   이 로직은 `tools/발표물빌드.js` 안에만 살았다. 남은 지면 12벌을 입히려면 생성기가
 *   최소 다섯이고(`이해대장.js`·`운영자료.js`·`자율기록.js`·`브랜드킷조립.py`·손 HTML),
 *   거기에 각자 베끼는 순간 **여섯 벌로 갈라진다.** 갈라지는 방향은 늘 「통과」다 —
 *   한쪽만 훅 게이트를 빠뜨리면 그 지면은 «부품 0인 채 마커만 켜진 초록»이 된다(F517②).
 *   CLAUDE.md 「3번째 = 원인을 쓸 수 없게 만든다 — 호출부마다 고치는 대신 공용 통로」.
 *
 * ■ 이 통로가 지는 판정 셋 (다른 데 베끼지 마라)
 *   ① **훅이 없으면 안 얹는다.** `지면방` 의 전파 술어는 CSS 주석 마커 하나라, 얹기만 하면
 *      부품이 0개여도 「입었다」로 켜진다. 그래서 «닿는 선택자»가 하나라도 있을 때만 얹는다.
 *   ② **재는 자는 `loom훅.js` 하나다.** 뿌리는 쪽과 세는 쪽(`지면방`)이 갈리면 조용히 통과한다(F517①).
 *   ③ **원고 CSS 「뒤」에 얹는다.** 부품 클래스와 원고 클래스는 특정도가 같아서(`.칩` vs `.tag` = 0,1,0)
 *      앞에 두면 동점에서 원고가 이긴다 — 훅은 늘었는데 화면은 그대로인, 딱 「맞는 얼굴로 틀린 값」이다.
 *
 * ■ ⚠ 이 장치가 틀릴 때의 모습 = **범위 누락**
 *   `부품만`·`인쇄부품` 프리셋은 맨요소 규칙(`ol>li`·`ul>li`)을 `.룸` 안으로 가둔다 —
 *   남의 지면의 모든 목록을 덮치지 않으려는 안전장치다. 그래서 지면에 `ol` 이 있어도
 *   **`class="룸"` 컨테이너가 없으면 순번·불릿이 어디에도 안 닿는다.** 훅 0 → 안 얹음 → 조용히 그대로.
 *   실측 2026-08-18: 안 입은 12벌 중 10벌이 정확히 이 상태였다(ol·ul 은 있는데 `.룸` 이 0).
 *   ⇒ `범위진단()` 이 그 자리를 이름째 낸다. **안 도는 쪽이 아니라 이쪽으로 샌다.**
 *
 * ■ 닫은 것 하나 / 안 닫은 것 하나
 *   닫음: 얹기가 **멱등**이다 — 얹기 전에 늘 먼저 뜯는다. 두 번 돌려도 블록이 안 쌓인다.
 *   못 닫음: 「그 지면에 이 프리셋이 맞나」는 안 잰다(통짜 지면 vs 남의 지면). 사람이 고른다.
 */

const loom = require('./loom.js');
const loom훅 = require('./loom훅.js');

/** 얹은 블록의 표식 — 프리셋 이름을 속성에 실어야 뜯기가 지면 종류를 안 가리고 돈다. */
const 뜯기정규식 = /\n?<style data-loom="[^"]*">[\s\S]*?<\/style>/g;

const CSS캐시 = new Map();
/** 프리셋 CSS 는 한 번만 만든다 — 지면 12벌을 도는 루프에서 매번 조립하면 그게 빌드 시간의 전부가 된다. */
function css(지면) {
  if (!CSS캐시.has(지면)) CSS캐시.set(지면, loom.css({ 지면 }));
  return CSS캐시.get(지면);
}

/**
 * 이 지면이 실제로 부르는 훅 — **닿는 선택자들**의 이름(정렬).
 * ⚠ 마크업만 본다 — 지면의 CSS 안에 우연히 같은 이름이 있어도 그건 훅이 아니다.
 */
function 훅들(html, 지면) {
  return loom훅.닿는선택자들(css(지면), html).map((d) => d.선택자).sort();
}

/** 얹을까 — 훅이 하나라도 있을 때만. 이 한 줄이 「마커만 켜진 초록」을 막는 게이트다. */
const 얹을까 = (훅) => 훅.length > 0;

/**
 * 이미 Loom 을 «입고» 있나 — 판정 자는 **마커** 하나다(`지면방` 과 같은 술어).
 *
 * 🔴 왜 `data-loom` 이 아닌가 (2026-08-18 실측): 입는 길이 **둘**이다.
 *   ⓐ 이 통로가 얹은 것 — `<style data-loom="…">` 블록 (발표물 3벌)
 *   ⓑ 지면이 **조립 단계에서 CSS 를 품은 것** — 엔진 소개서 6벌 + 부품 시연 (`data-loom` 이 없다)
 *   `data-loom` 으로만 재면 ⓑ 7벌이 통째로 「안 입었다」가 되고, 그 판정을 게이트로 쓰면
 *   이미 입은 지면에 **또 얹는다.** 두 술어가 갈리는 순간 새는 방향은 늘 그쪽이다.
 */
const 얹힘 = (html) => /\/\*loom부품:/.test(html);

/** 이 통로가 «직접» 얹은 블록이 있나 — 뜯기·멱등이 묻는 것은 이쪽이다(위와 다른 질문). */
const 내가얹음 = (html) => /<style data-loom="[^"]*">/.test(html);

/**
 * class 속성에 이 낱말이 통째로 들었나.
 * 🔴 정규식 `\b` 를 쓰지 않는다 — JS 의 `\w` 는 ASCII 라 **한글 앞뒤에 단어경계가 안 생긴다.**
 *   `class="[^"]*\b룸\b"` 는 `class="룸"` 에도 안 물린다(실측 2026-08-18 · 같은 함정을 이 트랙에서만 세 번 밟았다).
 *   그래서 경계를 «찾지» 않고 속성값을 **공백으로 쪼개 정확히 견준다** — 잘못 쓸 수 없는 모양이다.
 */
function 클래스있나(html, 낱말) {
  for (const m of html.matchAll(/class\s*=\s*"([^"]*)"/g)) {
    if (m[1].split(/\s+/).includes(낱말)) return true;
  }
  for (const m of html.matchAll(/class\s*=\s*'([^']*)'/g)) {
    if (m[1].split(/\s+/).includes(낱말)) return true;
  }
  return false;
}

/** 얹은 블록을 도로 뜯는다 — `--check` 가 원고와 1:1 대조하려면 되돌릴 수 있어야 한다. */
const 뜯기 = (html) => html.replace(뜯기정규식, '');

/**
 * 얹을 자리 — 지면의 **마지막 `</style>` 뒤**. `<style>` 이 하나도 없으면 `</head>` 앞.
 * 두 자리 다 「지면 자신의 CSS 뒤」라는 조건을 만족한다(판정 ③). 어느 쪽도 없으면 못 얹는다 —
 * 조용히 앞에 붙이면 특정도 동점에서 지면이 이겨 «훅은 늘고 화면은 그대로»가 된다.
 */
function 끼울자리(html) {
  const i = html.lastIndexOf('</style>');
  if (i >= 0) return { 위치: i + '</style>'.length, 기준: '마지막 </style> 뒤' };
  const h = html.search(/<\/head>/i);
  if (h >= 0) return { 위치: h, 기준: '</head> 앞' };
  return null;
}

/**
 * 범위 진단 — 「맞는 얼굴로 틀린 값」이 나는 자리를 이름째 낸다.
 * 반환 `null` = 문제 없음 / 문자열 = 사람이 읽을 사유.
 */
function 범위진단(html, 지면) {
  const 범위 = loom.기본범위[지면];
  if (!범위) return null;                       // 통짜 지면은 범위가 없다 — 이 진단이 애초에 안 걸린다
  const 맨요소 = ['ol', 'ul'].filter((t) => new RegExp(`<${t}[\\s>]`, 'i').test(html));
  if (!맨요소.length) return null;
  const 범위클래스 = 범위.replace(/^\./, '');
  if (클래스있나(html, 범위클래스)) return null;
  return `${맨요소.join('·')} 은 있는데 \`${범위}\` 컨테이너가 없다 — `
    + `\`${지면}\` 프리셋은 맨요소 규칙을 \`${범위}\` 안에 가두므로 순번·불릿이 **어디에도 안 닿는다**. `
    + `본문을 감싸는 요소에 \`class="${범위클래스}"\` 를 더해라.`;
}

/**
 * 강제얹기 — **게이트 없이** 블록만 끼운다. 멱등(먼저 뜯는다).
 *
 * 🔴 이것을 일반 통로로 쓰지 마라 — 훅 0 인 지면에 얹으면 「부품 0인 채 마커만 켜진 초록」이 된다(F517②).
 *   쓰는 자리는 딱 둘이다:
 *     ① **픽스처** — 탐지력 회귀는 «그 고장난 판»을 만들 수 있어야 한다. 게이트가 얹기 안에 박혀 있으면
 *        픽스처가 버그를 못 만들고, 그 순간 탐지력 검사는 「버그가 아직 있을 것을 요구하는 회귀」도 못 되고
 *        **그냥 안 돈다**(실측 2026-08-18: 게이트를 얹기에 넣자 `발표물Loom` ⑨ 가 초록으로 뒤집혔다).
 *     ② 호출부가 **이미 게이트를 지난** 경우.
 *   그래서 이름이 「강제」다 — 부를 때 읽히라고.
 */
function 강제얹기(html, 지면) {
  if (!loom.지면들[지면]) throw new Error(`모르는 지면 프리셋: ${지면} — 아는 것은 ${Object.keys(loom.지면들).join('·')}`);
  const 벗은판 = 뜯기(html);
  const 자리 = 끼울자리(벗은판);
  if (!자리) throw new Error('`</style>` 도 `</head>` 도 없다 — 지면 CSS 뒤에 둘 자리가 없다');
  const 블록 = `\n<style data-loom="${지면}">\n${css(지면)}\n</style>`;
  return 벗은판.slice(0, 자리.위치) + 블록 + 벗은판.slice(자리.위치);
}

/**
 * 얹기 — 멱등. 늘 먼저 뜯고, 훅이 있을 때만 다시 얹는다.
 * @returns {{html:string, 훅:string[], 얹힘:boolean, 사유:string|null, 범위흠:string|null}}
 */
function 얹기(html, { 지면 }) {
  if (!loom.지면들[지면]) throw new Error(`모르는 지면 프리셋: ${지면} — 아는 것은 ${Object.keys(loom.지면들).join('·')}`);
  const 벗은판 = 뜯기(html);
  const 훅 = 훅들(벗은판, 지면);
  const 범위흠 = 범위진단(벗은판, 지면);

  if (!얹을까(훅)) {
    return { html: 벗은판, 훅, 얹힘: false, 범위흠, 사유: 범위흠 || '닿는 부품이 0 — 얹으면 마커만 켜진다' };
  }
  const 자리 = 끼울자리(벗은판);
  if (!자리) {
    return { html: 벗은판, 훅, 얹힘: false, 범위흠, 사유: '`</style>` 도 `</head>` 도 없다 — 지면 CSS 뒤에 둘 자리가 없다' };
  }
  const 새판 = 강제얹기(벗은판, 지면);   /* 블록을 만드는 자리는 하나다 — 두 곳에서 만들면 갈라진다 */

  /* 「돌았다」는 근거가 아니다 — 얹은 «결과»를 본다(마커 + 되뜯을 수 있는 블록). */
  if (!/\/\*loom부품:/.test(새판) || !new RegExp(`<style data-loom="${지면}">`).test(새판)) {
    throw new Error(`얹었는데 결과에 마커가 없다 — ${지면} 프리셋이 마커를 안 심는다`);
  }
  return { html: 새판, 훅, 얹힘: true, 범위흠, 사유: null };
}

module.exports = { 얹기, 강제얹기, 뜯기, 얹힘, 내가얹음, 클래스있나, 훅들, 얹을까, 범위진단, 끼울자리, css, 뜯기정규식 };
