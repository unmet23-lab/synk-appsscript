/**
 * Loom 얹기 — 남의 지면에 부품 CSS 를 «입히는» **공용 통로 하나**.
 *
 * ■ 왜 뗐나 (2026-08-18 · ④ 지면 배선)
 *   이 로직은 `tools/발표물빌드.js` 안에만 살았다. 남은 지면 12벌을 입히려면 생성기가
 *   최소 다섯이고(`이해대장.js`·`운영자료.js`·`자율기록.js`·`브랜드킷조립.py`·손 HTML),
 *   거기에 각자 베끼는 순간 **여섯 벌로 갈라진다.** 갈라지는 방향은 늘 「통과」다 —
 *   한쪽만 훅 게이트를 빠뜨리면 그 지면은 «부품 0인 채 마커만 켜진 초록»이 된다(F517②).
 *   CLAUDE.md 「3번째 = 원인을 쓸 수 없게 만든다 — 호출부마다 고치는 대신 공용 통로」.
 *
 * ■ 이 통로가 지는 판정 셋 (다른 데 베끼지 마라)
 *   ① **훅이 없으면 안 얹는다.** `지면방` 의 전파 술어는 CSS 주석 마커 하나라, 얹기만 하면
 *      부품이 0개여도 「입었다」로 켜진다. 그래서 «닿는 선택자»가 하나라도 있을 때만 얹는다.
 *   ② **재는 자는 `loom훅.js` 하나다.** 뿌리는 쪽과 세는 쪽(`지면방`)이 갈리면 조용히 통과한다(F517①).
 *   ③ **원고 CSS 「뒤」에 얹는다.** 부품 클래스와 원고 클래스는 특정도가 같아서(`.칩` vs `.tag` = 0,1,0)
 *      앞에 두면 동점에서 원고가 이긴다 — 훅은 늘었는데 화면은 그대로인, 딱 「맞는 얼굴로 틀린 값」이다.
 *
 * ■ ⚠ 이 장치가 틀릴 때의 모습 = **범위 누락**
 *   `부품만`·`인쇄부품` 프리셋은 맨요소 규칙(`ol>li`·`ul>li`)을 `.룸` 안으로 가둔다 —
 *   남의 지면의 모든 목록을 덮치지 않으려는 안전장치다. 그래서 지면에 `ol` 이 있어도
 *   **`class="룸"` 컨테이너가 없으면 순번·불릿이 어디에도 안 닿는다.** 훅 0 → 안 얹음 → 조용히 그대로.
 *   실측 2026-08-18: 안 입은 12벌 중 10벌이 정확히 이 상태였다(ol·ul 은 있는데 `.룸` 이 0).
 *   ⇒ `범위진단()` 이 그 자리를 이름째 낸다. **안 도는 쪽이 아니라 이쪽으로 샌다.**
 *
 * ■ 닫은 것 하나 / 안 닫은 것 하나
 *   닫음: 얹기가 **멱등**이다 — 얹기 전에 늘 먼저 뜯는다. 두 번 돌려도 블록이 안 쌓인다.
 *   못 닫음: 「그 지면에 이 프리셋이 맞나」는 안 잰다(통짜 지면 vs 남의 지면). 사람이 고른다.
 */

const loom = require('./loom.js');
const loom훅 = require('./loom훅.js');
/* 줄끝 «표기»는 뜻이 아니다 — 「같나」를 접어서 재는 정의는 저장소에 하나뿐이다.
 * 손으로 접으면 CRLF 축만 막히고 줄끝 공백 축이 그대로 샌다(#Q101 · 29벌 전부 반쪽이었다). */
const { 표기접기 } = require('../../tests/lib/소스검사.js');

/** 얹은 블록의 표식 — 프리셋 이름을 속성에 실어야 뜯기가 지면 종류를 안 가리고 돈다.
 * ⚠`\r?` 이 있어야 한다 — 이 저장소의 지면은 대부분 **CRLF** 라, `\n` 만 먹으면 앞의 `\r` 이
 *   원고 쪽에 고아로 남는다. 그러면 얹을 때마다 원고 `</style>` 뒤에 `\r` 이 하나 붙어
 *   **원고를 안 건드렸는데 원고가 갈린다**(09-01 실측: CRLF 지면 셋에서 재현 · LF 지면 넷은 무증상).
 *   해로운 자리는 화면이 아니라 **대조**다 — 「생성기 산출과 디스크가 같은가」를 재는 검사와
 *   재현 대조가 그 한 바이트에 갈린다(F630 계열). */
const 뜯기정규식 = /\r?\n?<style data-loom="[^"]*">[\s\S]*?<\/style>/g;

const CSS캐시 = new Map();
/** 프리셋 CSS 는 한 번만 만든다 — 지면 12벌을 도는 루프에서 매번 조립하면 그게 빌드 시간의 전부가 된다.
 * 천쓸까 — 이 지면에 `.오브` 가 없으면 기본색 천 data URI(실측 +17.4KB)는 그리지도 않을 짐이다
 * (실측 08-19: 이해대장·작동대장 `.오브` 0 인데 부품만 오버레이가 통째로 물었다). 오브 있는 지면만
 * 기본천을 문다 — 조항 ⓘ 「지정 없는 펠트 = 기본색」은 **펠트가 있는 자리**의 규정이지,
 * 펠트 없는 지면에 짐을 싣는 규정이 아니다.
 *
 * 🔴 쓴클래스 — 「**쓰는 것만 싣는다**」가 이 통로엔 없었다 (2026-09-02 실측).
 *   loom 의 `부르나` 는 08-19 부터 있었고 `펠트문서.js` 는 그것을 쓰는데, **이 통로만 안 넘겼다.**
 *   그래서 등록 지면 8벌이 저마다 **452KB** 를 물고 있었다 — 훅이 «둘»뿐인 지면도 똑같이 452KB 다.
 *   넘기니 8벌 합계 3,608KB → 988KB (**−72% · 2.56MB**). 그 차액은 전부 «안 그려지는 그림»이었다.
 *   재는 자는 `loom훅.마크업집합` 하나다 — 여기서 따로 세면 그 순간 갈린다([[constant-known-in-two-places]]).
 *   ⚠ `undefined` 를 넘기면 loom 이 「모른다」로 읽어 **전량**을 싣는다. 빈 Set 과 뜻이 다르다. */
function css(지면, 천쓸까 = true, 쓴클래스 = undefined) {
  const 서명 = 쓴클래스 ? [...쓴클래스].sort().join(',') : '∀';
  const 키 = `${지면}|${천쓸까 ? '천' : '맨'}|${서명}`;
  if (!CSS캐시.has(키)) {
    CSS캐시.set(키, loom.css({ 지면, 쓴클래스, ...(천쓸까 ? {} : { 천: null }) }));
  }
  return CSS캐시.get(키);
}

/** 이 지면 «마크업»이 부르는 클래스 — 구움층 `부르나` 의 입력. 세는 자는 `loom훅` 하나. */
const 쓴클래스 = (html) => loom훅.마크업집합(html).클래스;

/**
 * 이 지면이 실제로 부르는 훅 — **닿는 선택자들**의 이름(정렬).
 * ⚠ 마크업만 본다 — 지면의 CSS 안에 우연히 같은 이름이 있어도 그건 훅이 아니다.
 * 🔑 재는 CSS 와 «얹는» CSS 는 같은 것이어야 한다 — 안 그러면 「전량에는 있는데 실린 판엔 없는」
 *    선택자를 훅으로 세고, 그 지면은 부품 0 인 채 초록으로 뜬다(F517② 와 같은 자리).
 */
function 훅들(html, 지면) {
  return loom훅.닿는선택자들(css(지면, 클래스있나(html, '오브'), 쓴클래스(html)), html)
    .map((d) => d.선택자).sort();
}

/** 얹을까 — 훅이 하나라도 있을 때만. 이 한 줄이 「마커만 켜진 초록」을 막는 게이트다. */
const 얹을까 = (훅) => 훅.length > 0;

/**
 * 이미 Loom 을 «입고» 있나 — 판정 자는 **마커** 하나다(`지면방` 과 같은 술어).
 *
 * 🔴 왜 `data-loom` 이 아닌가 (2026-08-18 실측): 입는 길이 **둘**이다.
 *   ⓐ 이 통로가 얹은 것 — `<style data-loom="…">` 블록 (발표물 3벌)
 *   ⓑ 지면이 **조립 단계에서 CSS 를 품은 것** — 엔진 소개서 6벌 + 부품 시연 (`data-loom` 이 없다)
 *   `data-loom` 으로만 재면 ⓑ 7벌이 통째로 「안 입었다」가 되고, 그 판정을 게이트로 쓰면
 *   이미 입은 지면에 **또 얹는다.** 두 술어가 갈리는 순간 새는 방향은 늘 그쪽이다.
 */
const 얹힘 = (html) => /\/\*loom부품:/.test(html);

/** 이 통로가 «직접» 얹은 블록이 있나 — 뜯기·멱등이 묻는 것은 이쪽이다(위와 다른 질문). */
const 내가얹음 = (html) => /<style data-loom="[^"]*">/.test(html);

/**
 * class 속성에 이 낱말이 통째로 들었나.
 * 🔴 정규식 `\b` 를 쓰지 않는다 — JS 의 `\w` 는 ASCII 라 **한글 앞뒤에 단어경계가 안 생긴다.**
 *   `class="[^"]*\b룸\b"` 는 `class="룸"` 에도 안 물린다(실측 2026-08-18 · 같은 함정을 이 트랙에서만 세 번 밟았다).
 *   그래서 경계를 «찾지» 않고 속성값을 **공백으로 쪼개 정확히 견준다** — 잘못 쓸 수 없는 모양이다.
 */
function 클래스있나(html, 낱말) {
  for (const m of html.matchAll(/class\s*=\s*"([^"]*)"/g)) {
    if (m[1].split(/\s+/).includes(낱말)) return true;
  }
  for (const m of html.matchAll(/class\s*=\s*'([^']*)'/g)) {
    if (m[1].split(/\s+/).includes(낱말)) return true;
  }
  return false;
}

/** 얹은 블록을 도로 뜯는다 — `--check` 가 원고와 1:1 대조하려면 되돌릴 수 있어야 한다. */
const 뜯기 = (html) => html.replace(뜯기정규식, '');

/**
 * 얹을 자리 — 지면의 **마지막 `</style>` 뒤**. `<style>` 이 하나도 없으면 `</head>` 앞.
 * 두 자리 다 「지면 자신의 CSS 뒤」라는 조건을 만족한다(판정 ③). 어느 쪽도 없으면 못 얹는다 —
 * 조용히 앞에 붙이면 특정도 동점에서 지면이 이겨 «훅은 늘고 화면은 그대로»가 된다.
 */
function 끼울자리(html) {
  const i = html.lastIndexOf('</style>');
  if (i >= 0) return { 위치: i + '</style>'.length, 기준: '마지막 </style> 뒤' };
  const h = html.search(/<\/head>/i);
  if (h >= 0) return { 위치: h, 기준: '</head> 앞' };
  return null;
}

/**
 * 범위 진단 — 「맞는 얼굴로 틀린 값」이 나는 자리를 이름째 낸다.
 * 반환 `null` = 문제 없음 / 문자열 = 사람이 읽을 사유.
 */
function 범위진단(html, 지면) {
  const 범위 = loom.기본범위[지면];
  if (!범위) return null;                       // 통짜 지면은 범위가 없다 — 이 진단이 애초에 안 걸린다
  const 맨요소 = ['ol', 'ul'].filter((t) => new RegExp(`<${t}[\\s>]`, 'i').test(html));
  if (!맨요소.length) return null;
  const 범위클래스 = 범위.replace(/^\./, '');
  if (클래스있나(html, 범위클래스)) return null;
  return `${맨요소.join('·')} 은 있는데 \`${범위}\` 컨테이너가 없다 — `
    + `\`${지면}\` 프리셋은 맨요소 규칙을 \`${범위}\` 안에 가두므로 순번·불릿이 **어디에도 안 닿는다**. `
    + `본문을 감싸는 요소에 \`class="${범위클래스}"\` 를 더해라.`;
}

/**
 * 강제얹기 — **게이트 없이** 블록만 끼운다. 멱등(먼저 뜯는다).
 *
 * 🔴 이것을 일반 통로로 쓰지 마라 — 훅 0 인 지면에 얹으면 「부품 0인 채 마커만 켜진 초록」이 된다(F517②).
 *   쓰는 자리는 딱 둘이다:
 *     ① **픽스처** — 탐지력 회귀는 «그 고장난 판»을 만들 수 있어야 한다. 게이트가 얹기 안에 박혀 있으면
 *        픽스처가 버그를 못 만들고, 그 순간 탐지력 검사는 「버그가 아직 있을 것을 요구하는 회귀」도 못 되고
 *        **그냥 안 돈다**(실측 2026-08-18: 게이트를 얹기에 넣자 `발표물Loom` ⑨ 가 초록으로 뒤집혔다).
 *     ② 호출부가 **이미 게이트를 지난** 경우.
 *   그래서 이름이 「강제」다 — 부를 때 읽히라고.
 */
function 강제얹기(html, 지면) {
  if (!loom.지면들[지면]) throw new Error(`모르는 지면 프리셋: ${지면} — 아는 것은 ${Object.keys(loom.지면들).join('·')}`);
  const 벗은판 = 뜯기(html);
  const 자리 = 끼울자리(벗은판);
  if (!자리) throw new Error('`</style>` 도 `</head>` 도 없다 — 지면 CSS 뒤에 둘 자리가 없다');
  const 블록 = `\n<style data-loom="${지면}">\n${css(지면, 클래스있나(벗은판, '오브'), 쓴클래스(벗은판))}\n</style>`;
  return 벗은판.slice(0, 자리.위치) + 블록 + 벗은판.slice(자리.위치);
}

/**
 * 「디스크가 지금 산출과 같은가」 — **이 판정의 자는 여기 하나다.**
 *
 * ■ 🔴 왜 접고 재나 (2026-09-03 실측 · 등록 지면 8벌이 주인 없는 적색이었다)
 *   git 은 이 저장소를 `core.autocrlf=true` 로 체크아웃한다. 그래서 커밋된 지면(인덱스는 늘 LF)이
 *   윈도 작업본에 **통째로 CRLF 로** 내려온다 — 우리가 얹은 블록까지 함께. 그런데 생성기는 늘 LF 로
 *   블록을 짓는다. 바이트로 견주면 **줄 하나당 `\r` 한 개씩** 어긋나고, 그 지면은 내용이 한 글자도
 *   안 낡았는데 「얹힌 CSS 가 낡았다」로 exit 1 이 된다.
 *   실측 09-03(새 워크트리): 등록 12벌 중 8벌 적색 · `git diff` 는 **0줄** · 줄끝만 LF 로 접으면 전부 ✅.
 *   나머지 4벌이 초록이던 이유도 내용이 아니었다 — 그 넷엔 «외톨이 `\r`» 이 하나씩 남아 있어
 *   git 이 텍스트로 안 보고 줄끝을 안 건드렸을 뿐이다(09-01 에 고친 고아 `\r` 버그의 화석).
 *   ⇒ **넷은 «고장나서» 초록이었고 여덟은 «멀쩡해서» 빨갰다.** 병은 지면이 아니라 자에 있었다.
 *
 * ■ 🔑 왜 `.gitattributes` 로 못박지 않았나 (안 고른 처방을 적어 둔다)
 *   저장소의 html 130벌 중 **124벌**이 같은 조건이다. 그중 8벌만 `text eol=lf` 로 박으면 ⓐ 아직
 *   안 태어난 지면이 그대로 새고 ⓑ 이미 CRLF 로 받아 둔 다른 세션 작업본이 흔들린다(그 재정규화는
 *   CLAUDE.md 가 금하는 자리다). 그리고 이 워크트리는 **다시 체크아웃하기 전엔 초록이 되지도 않는다.**
 *   형제 게이트 `tools/발표물빌드.js` 는 같은 판정을 이미 접어서 재고 있었다 — 갈린 것은 이쪽뿐이다.
 *
 * ■ ⚠ 이 자가 틀릴 때의 모습 = **줄끝 표기 자체가 뜻인 대조에는 못 쓴다.**
 *   `tests/지면재현.test.js` 처럼 «바이트»를 지키는 검사는 원문을 봐야 한다 — 그쪽은 접지 않는다.
 *   여기서 접는 것이 안전한 이유는 하나다: 본문은 `뜯기`→`끼우기` 를 그대로 통과하므로 두 판이
 *   갈릴 수 있는 자리가 **우리가 지은 CSS 블록**뿐이고, 그 블록엔 줄끝 공백이 뜻인 자리가 없다.
 */
const 최신 = (원본, 새판) => 표기접기(원본) === 표기접기(새판);

/**
 * 얹기 — 멱등. 늘 먼저 뜯고, 훅이 있을 때만 다시 얹는다.
 * 🔑 `같나` 를 여기서 함께 낸다 — 호출부가 저마다 `===` 로 견주면 그 순간 자가 갈리고,
 *   갈린 쪽이 내는 것은 **주인 없는 적색**이다(위 머리말이 그 사고다).
 * @returns {{html:string, 훅:string[], 얹힘:boolean, 같나:boolean, 사유:string|null, 범위흠:string|null}}
 */
function 얹기(html, { 지면 }) {
  if (!loom.지면들[지면]) throw new Error(`모르는 지면 프리셋: ${지면} — 아는 것은 ${Object.keys(loom.지면들).join('·')}`);
  const 벗은판 = 뜯기(html);
  const 훅 = 훅들(벗은판, 지면);
  const 범위흠 = 범위진단(벗은판, 지면);

  if (!얹을까(훅)) {
    return { html: 벗은판, 훅, 얹힘: false, 같나: 최신(html, 벗은판), 범위흠, 사유: 범위흠 || '닿는 부품이 0 — 얹으면 마커만 켜진다' };
  }
  const 자리 = 끼울자리(벗은판);
  if (!자리) {
    return { html: 벗은판, 훅, 얹힘: false, 같나: 최신(html, 벗은판), 범위흠, 사유: '`</style>` 도 `</head>` 도 없다 — 지면 CSS 뒤에 둘 자리가 없다' };
  }
  const 새판 = 강제얹기(벗은판, 지면);   /* 블록을 만드는 자리는 하나다 — 두 곳에서 만들면 갈라진다 */

  /* 「돌았다」는 근거가 아니다 — 얹은 «결과»를 본다(마커 + 되뜯을 수 있는 블록). */
  if (!/\/\*loom부품:/.test(새판) || !new RegExp(`<style data-loom="${지면}">`).test(새판)) {
    throw new Error(`얹었는데 결과에 마커가 없다 — ${지면} 프리셋이 마커를 안 심는다`);
  }
  return { html: 새판, 훅, 얹힘: true, 같나: 최신(html, 새판), 범위흠, 사유: null };
}

module.exports = { 얹기, 강제얹기, 뜯기, 얹힘, 내가얹음, 클래스있나, 훅들, 얹을까, 범위진단, 끼울자리, css, 쓴클래스, 뜯기정규식, 최신 };

/* ── CLI ───────────────────────────────────────────────────────────────────
   node tools/lib/loom얹기.js <파일...> [--지면 부품만] [--확인]

   왜 붙나: 생성물은 생성기가 이 모듈을 부르지만, **손파일 지면은 부를 사람이 없다.**
   그런데 손파일도 「한 번 얹고 끝」이 아니다 — 토큰·프리셋이 바뀌면 CSS 가 바뀌므로 다시
   얹어야 한다. 손으로 N 벌을 얹으면 언젠가 N-1 벌만 얹고, **빠진 한 벌은 초록으로 보인다**
   (파일이 그대로 있으니까). `--확인` 이 그 낡음을 fail 로 드러내는 게이트다.
   ⚠생성물에는 쓰지 않는다 — 생성기가 다음 실행에 통째로 덮는다(같은 통로, 다른 호출부).
   ────────────────────────────────────────────────────────────────────────── */
if (require.main === module) {
  const fs = require('node:fs');
  const 인자 = process.argv.slice(2);
  const 확인만 = 인자.includes('--확인');
  const i지면 = 인자.indexOf('--지면');
  const 지면 = i지면 >= 0 ? 인자[i지면 + 1] : '부품만';
  const 파일들 = 인자.filter((a, i) => !a.startsWith('--') && !(i지면 >= 0 && i === i지면 + 1));

  if (!파일들.length) {
    console.error('용법: node tools/lib/loom얹기.js <파일...> [--지면 부품만] [--확인]');
    process.exit(2);
  }

  let 낡음 = 0, 입음 = 0, 못입음 = 0;
  for (const f of 파일들) {
    const 원본 = fs.readFileSync(f, 'utf8');
    let r;
    try { r = 얹기(원본, { 지면 }); }
    catch (e) { console.error(`🔴 ${f} — ${e.message}`); process.exitCode = 1; continue; }

    if (!r.얹힘) { 못입음++; console.log(`·  ${f} — 안 얹었다: ${r.사유}`); continue; }
    입음++;
    /* 자는 `얹기` 가 낸 `같나` 하나다 — 여기서 `===` 로 다시 견주면 체크아웃이 CRLF 로 준 지면이
       내용과 무관하게 통째로 「낡았다」가 된다(위 `최신` 머리말의 09-03 사고). */
    if (r.같나) { console.log(`✅ ${f} — 이미 최신 (훅 ${r.훅.length})`); continue; }
    낡음++;
    if (확인만) console.log(`🔴 ${f} — 낡았다(다시 얹어야 한다)`);
    else { fs.writeFileSync(f, r.html, 'utf8'); console.log(`✅ ${f} — 얹었다 (훅 ${r.훅.length}: ${r.훅.slice(0, 6).join('·')}${r.훅.length > 6 ? '…' : ''})`); }
  }

  /* 0 은 분모와 함께 쓴다(F207) — 몇 벌을 봤는지 안 밝히면 미실행이 통과와 같은 모양이다. */
  console.log(`\n${확인만 && 낡음 ? '🔴' : '✅'} 지면 ${파일들.length}벌 · 입음 ${입음} + 못입음 ${못입음} · ${확인만 ? `낡음 ${낡음}` : `새로 얹음 ${낡음}`}`);
  if (확인만 && 낡음) process.exitCode = 1;
}
