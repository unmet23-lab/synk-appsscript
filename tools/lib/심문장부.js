/* 심문 장부 해석기 — **개명 사슬을 푸는 자리는 하나여야 한다.**
 *
 * ■ 왜 있나 (2026-09-01 · 유호님 「개명 사건 줄 받게 지어줘」)
 *   심문 장부는 append-only 이력이라 «옛 이름»이 영원히 남는다. 그래서 문서를 개명하면
 *   장부가 가리키는 파일이 사라지고, 그때 두 자가 **서로 다르게 틀린다**:
 *     · `tools/ai스택점검.js` → 「추적 끊김」으로 **영원히 운다**(재심문해도 옛 줄은 그대로다).
 *     · `.claude/hooks/review-runs.js` → 파일이 없으니 `continue` 로 **영원히 침묵한다**(:206).
 *   실물: `docs/학생ID_종단_설계_v1.md` 가 `_v1` 없이 개명돼 **장부의 유일한 심문 이력**이
 *   그 상태였다 — 한쪽은 쉬지 않고 울고, 한쪽은 눈이 멀었다.
 *
 * 🔑 **고치는 방법은 장부를 고쳐 쓰는 게 아니다.** 이력은 이력이라 손대지 않고, «개명»이라는
 *   사건 줄을 하나 더 얹는다: `{종류:'개명', 옛대상, 새대상, 사유, 시각}`.
 *   그러면 옛 줄은 참인 채로 남고, 사슬을 따라 최종 이름을 구하는 일만 남는다.
 *
 * 🔑 **그 사슬 푸는 코드를 두 자가 각자 갖지 않게** 여기 모은다 — 같은 판정을 두 자로 재면
 *   반드시 어긋나고(one-ruler-per-judgment), 어긋난 쪽은 대개 조용하다.
 *
 * ⚠ 이 모듈은 **경로를 모른다.** 장부 경로의 정본은 `tools/codex-review.js`(심문경로)이고,
 *   여기서 또 정하면 그게 둘째 정본이 된다. 부르는 쪽이 경로나 행들을 준다.
 */

const fs = require('fs');

/** 한 줄이라도 못 읽으면 «셈에서 빠졌다»를 부르는 쪽이 말할 수 있게 수를 돌려준다. */
function 파싱(원문) {
  const 행 = [];
  let 못읽음 = 0;
  for (const l of String(원문 || '').split('\n')) {
    if (!l.trim()) continue;
    try { 행.push(JSON.parse(l)); } catch (_) { 못읽음++; }
  }
  return { 행, 못읽음 };
}

/** @returns {{행:Array, 못읽음:number}|null} null = 장부 파일이 없다(0줄과 갈린다). */
function 읽기(경로) {
  let raw;
  try { raw = fs.readFileSync(경로, 'utf8'); }
  catch (_) { return null; }
  return 파싱(raw);
}

/** 옛 → 새. 같은 옛 이름이 두 번 개명되면 **나중 줄이 이긴다**(장부는 시간 순). */
function 개명맵(행들) {
  const m = new Map();
  for (const r of 행들 || []) {
    if (r && r.종류 === '개명' && r.옛대상 && r.새대상) m.set(r.옛대상, r.새대상);
  }
  return m;
}

/* 사슬 끝까지 따라간다. **순환을 반드시 끊는다** — 장부는 사람도 쓰는 자리라 A→B→A 가 실제로
 * 가능하고, 순환에 빠지면 훅이 통째로 멈춘다(세션 시작이 안 열린다 = 제일 나쁜 고장).
 * 순환이면 「더 못 간다」를 사실대로 알린다 — 조용히 한 칸만 가지 않는다. */
function 최종이름(맵, 시작) {
  let 지금 = 시작;
  const 밟음 = new Set([시작]);
  const 사슬 = [];
  while (맵 && 맵.has(지금)) {
    const 다음 = 맵.get(지금);
    if (밟음.has(다음)) return { 이름: 지금, 사슬, 순환: true };
    사슬.push(다음);
    밟음.add(다음);
    지금 = 다음;
  }
  return { 이름: 지금, 사슬, 순환: false };
}

/**
 * 장부 행들을 두 자가 함께 쓸 꼴로 접는다.
 * @returns {{
 *   개명수:number,
 *   심문됨:Set<string>,          // 최종 이름 기준 — 「이 문서는 심문 이력이 있다」
 *   가리킨것:Set<string>,        // 최종 이름 기준 — 지문이 없는 줄도 포함(끊김은 이걸로 잰다)
 *   대상들:Map<string,{지문:string, 원본:string, 개명됨:boolean, 순환:boolean}>
 * }}
 * 🔑 **지문은 «심문할 때» 것이고 이름만 최종으로 바뀐다** — 그래야 개명 뒤에도
 *   「심문 때 그 바이트 그대로인가」를 잴 수 있다(그게 드리프트의 전부다).
 */
function 요약(행들) {
  const 맵 = 개명맵(행들);
  const 심문됨 = new Set();
  const 가리킨것 = new Set();
  const 대상들 = new Map();
  for (const r of 행들 || []) {
    if (!r || r.종류 !== '심문' || !r.대상) continue;
    const { 이름, 사슬, 순환 } = 최종이름(맵, r.대상);
    가리킨것.add(이름);
    // 「완료」만 심문으로 세지 않는다 — 옛 줄에는 상태 칸이 없다(있으면 완료만).
    if (r.상태 === '완료' || !r.상태) 심문됨.add(이름);
    if (r.대상지문) {
      대상들.set(이름, { 지문: r.대상지문, 원본: r.대상, 개명됨: 사슬.length > 0, 순환 });
    }
  }
  return { 개명수: 맵.size, 심문됨, 가리킨것, 대상들 };
}

/** 장부에 붙일 개명 줄. 쓰는 것은 부르는 쪽(경로를 아는 쪽)이 한다. */
function 개명줄(옛대상, 새대상, 사유, 시각) {
  return { 종류: '개명', 시각: 시각 || new Date().toISOString(), 옛대상, 새대상, 사유: 사유 || '' };
}

module.exports = { 파싱, 읽기, 개명맵, 최종이름, 요약, 개명줄 };
