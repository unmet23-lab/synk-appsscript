/**
 * loom훅 — 「이 Loom CSS 가 이 마크업에 **닿나**」를 재는 한 곳 (2026-08-17 · F517①)
 *
 * ══ 왜 있나 ═══════════════════════════════════════════════════════════════
 *   `지면방` 의 전파 술어는 CSS 주석 마커 하나(`/*loom부품:`)였다. 그래서 **얹기만 하면**
 *   부품이 0개여도 「입었다」로 켜졌다. 실측 08-16: 발표물 6벌은 부품 클래스가 6벌 전부 0인데
 *   그대로 얹었으면 전파가 10/21 → 13/21 로 «초록»이 됐다. 화면은 한 픽셀도 안 바뀐 채로.
 *   F514 가 «무엇을 세나»(분모)였다면 이건 «무엇을 세면 입은 것인가»(**술어**)다 —
 *   분모를 고쳐도 술어가 헐거우면 진척은 다시 거짓이다.
 *
 *   빌드 층(`발표물빌드.js`)은 이걸 자기 안에서 한 번 막았지만 그건 **발표물에서만** 참이었다.
 *   저장소의 나머지 지면은 여전히 마커만으로 켜졌다. 이 파일이 그 일반 해법이다.
 *
 * ══ 왜 «한 곳»인가 ════════════════════════════════════════════════════════
 *   뿌리는 쪽(빌드)과 확인하는 쪽(등록층)이 각자 판정을 들면 **갈라지고, 갈라지면 조용히
 *   통과한다** — 새는 방향은 언제나 「통과」다(CLAUDE.md 신뢰성 절). 그래서 두 호출부가
 *   같은 함수를 부른다. 빌드는 «얹기 전»(생성 CSS + 원고)에, 등록층은 «얹은 뒤»(파일 안
 *   마커 구간 + 그 파일 마크업)에 부를 뿐, 재는 자는 하나다.
 *
 * ══ 무엇을 훅으로 보나 ════════════════════════════════════════════════════
 *   선택자 하나가 «닿는다» = 그 선택자가 요구하는 클래스·태그가 **전부** 마크업에 있다.
 *   지면이 «입었다» = 닿는 선택자가 **하나 이상**.
 *   - `.룸 h2` → 룸 **그리고** h2 가 있어야 닿는다(범위 프리셋의 급소가 정확히 이 자리다).
 *   - `h2` → h2 만 있으면 닿는다(전역 프리셋은 맨요소로 입는다 — 이래야 이미 입은 7벌이
 *     거짓 강등되지 않는다. 실측: 그 7벌은 부품 클래스도 18~33개 쓰지만, 클래스만 세는
 *     술어는 전역 프리셋 지면을 원리적으로 못 읽는다).
 *   - `:not(…)`·`:is(…)`·`:where(…)`·`:has(…)` **안은 요구가 아니다** — 통째로 버린다.
 *     ⚠괄호 «안»의 공백에 속으면(`a:not(.레일 a)`) 실패가 「안 닿는다」쪽으로 떨어진다.
 *   - `html`·`body`·`*`·`:root` 는 **훅이 아니다.** 늘 있는 것은 증거가 아니다 —
 *     `.글,article,body{…}` 의 `body` 하나 때문에 술어가 통째로 참이 되면 고치나 마나다.
 *
 * ══ 마커 «구간»만 본다 ════════════════════════════════════════════════════
 *   파일에서 잴 때 Loom CSS 의 끝을 텍스트로 못 찾는다(끝 표식이 없고, 마지막 마커 뒤로도
 *   재질·낮 지면 층이 4.7만자 이어진다). 감싼 `</style>` 까지 긁으면 **원고 CSS 가 훅으로
 *   새어 들어와** 술어가 다시 헐거워진다. ⇒ 마커[i] → 마커[i+1] 구간만 쓴다. 이 구간은
 *   정의상 부품 CSS 이고, «부품이 닿나»가 우리가 묻는 바로 그 질문이다.
 *
 * ══ 대가 — 이 장치가 틀릴 때의 모습 ═══════════════════════════════════════
 *   선택자 문법을 못 읽으면 훅이 **적게** 나오고, 적게 나오면 멀쩡히 입은 지면이
 *   「마커만」(적색)으로 떨어진다 — 이 장치는 「통과」가 아니라 **거짓 적색** 쪽으로 샌다.
 *   (안전한 방향이지만 공짜는 아니다: 주인 없는 적색은 남의 배포를 막는다.)
 *   ⇒ 닫은 것 = ①`닿는선택자들()` 이 **닿은 선택자를 이름째** 돌려준다 — 적색이 떴을 때
 *     「무엇이 안 닿았나」가 출력에 그대로 나와서, 처방이 문법 추측이 아니라 실물이 된다.
 *     ②마지막 마커는 규칙 하나까지만 읽는다(그 뒤는 재질층이라 부품 훅이 아니다) —
 *     구간이 재질층을 삼켜 거짓 초록이 나는 쪽을 원리적으로 막는다.
 */

'use strict';

/** 늘 있는 것은 증거가 아니다 — 이 넷이 훅으로 세어지면 술어가 통째로 참이 된다. */
const 보편 = new Set(['html', 'body', '*', 'root']);

/** CSS 주석·문자열을 지운다. 문자열을 먼저 안 지우면 `content:"{"` 가 규칙 경계를 깬다. */
function 껍질벗기기(css) {
  return String(css)
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/g, '""');
}

/**
 * 규칙 프렐류드(= 선택자 목록)를 전부 뽑아 콤마까지 쪼갠다.
 * `@media`·`@page`·`@font-face` 의 프렐류드는 선택자가 아니라 버리고, 그 **안쪽** 규칙은 집는다.
 */
function 선택자들(css) {
  const t = 껍질벗기기(css);
  const out = [];
  /* ⚠앞에 `(?:^|[{}])` 를 두면 안 된다 — 그 `{` 를 **소비해** 버려서 바로 뒤따르는
   *   중첩 규칙이 구분자를 잃고 통째로 안 잡힌다(`@media print{ .룸 h2{…} }` 가 0건이었다 ·
   *   회귀가 물었다). `[^{}]*` 는 이미 중괄호에서 멈추므로 선행 구분자 자체가 필요 없다.
   *   선언 본문(`color:red`)은 뒤에 `{` 가 안 오므로 프렐류드로 안 잡힌다. */
  for (const m of t.matchAll(/([^{}]*)\{/g)) {
    const 프렐 = m[1].trim();
    if (!프렐 || 프렐.startsWith('@')) continue;
    for (const s of 프렐.split(',')) {
      const v = s.trim();
      if (v) out.push(v.replace(/\s+/g, ' '));
    }
  }
  return out;
}

/**
 * 선택자 → 그것이 닿으려면 마크업에 **반드시** 있어야 하는 훅들.
 * 클래스는 `.이름`, 태그는 `이름` 으로 돌려준다. 증거가 없으면 빈 배열(= 안 센다).
 */
function 필수훅(선택자) {
  let s = String(선택자);
  /* 함수형 의사클래스 «안»은 요구가 아니다. 중첩(`:not(:has(.번호))`)이 있어 안쪽부터 반복해 지운다. */
  for (let 전 = null; 전 !== s; ) {
    전 = s;
    s = s.replace(/:(?:not|is|where|has|matches)\([^()]*\)/gi, ' ');
  }
  s = s
    .replace(/::?[a-zA-Z-]+(?:\([^()]*\))?/g, ' ') // 남은 의사요소·의사클래스
    .replace(/\[[^\]]*\]/g, ' '); // 속성 선택자 — 요구로 세지 않는다(값까지 못 재므로)

  const 훅 = new Set();
  /* 클래스 이름은 «구분자가 아닌 것의 연속»으로 잡는다 — 한글 클래스(`.칩`·`.룸`)를 유니코드
   * 범위로 적으면 소스에 눈에 안 보이는 문자가 박힌다(실측: 첫 판이 NBSP 로 굳었다). */
  for (const m of s.matchAll(/\.((?:[^\s.#:>+~,[\]()*|="'{}/%!]|\\.)+)/g)) 훅.add('.' + m[1]);
  /* 결합자·공백으로 쪼갠 조각의 «머리»가 글자면 그것이 타입(태그) 선택자다. */
  for (const 조각 of s.split(/[\s>+~]+/)) {
    const m = 조각.match(/^([a-zA-Z][a-zA-Z0-9-]*)/);
    if (m && !보편.has(m[1].toLowerCase())) 훅.add(m[1].toLowerCase());
  }
  return [...훅];
}

/**
 * 마크업이 실제로 쓰는 클래스·태그.
 * ⚠`<style>`·`<script>` 안은 **마크업이 아니다** — 거기 적힌 이름은 «쓴 것»이 아니라 «정의한 것»이다.
 */
function 마크업집합(html) {
  const 본문 = String(html)
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, ' ')
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, ' ');
  const 클래스 = new Set();
  for (const m of 본문.matchAll(/\sclass\s*=\s*(?:"([^"]*)"|'([^']*)')/g)) {
    for (const c of (m[1] ?? m[2]).split(/\s+/)) if (c) 클래스.add(c);
  }
  const 태그 = new Set();
  for (const m of 본문.matchAll(/<([a-zA-Z][a-zA-Z0-9-]*)[\s>/]/g)) 태그.add(m[1].toLowerCase());
  return { 클래스, 태그 };
}

/** 마커[i] → 마커[i+1] 구간들. 마지막 하나는 **규칙 하나까지만**(그 뒤는 재질층이다). */
function 마커구간들(css) {
  const t = String(css);
  const ms = [...t.matchAll(/\/\*loom부품:([^*]+)\*\//g)];
  return ms.map((m, i) => ({
    이름: m[1],
    본문: t.slice(m.index, i + 1 < ms.length ? ms[i + 1].index : 첫규칙끝(t, m.index)),
  }));
}

/** `from` 뒤 첫 규칙이 닫히는 자리. 못 찾으면 문자열 끝. */
function 첫규칙끝(t, from) {
  const 열림 = t.indexOf('{', from);
  if (열림 < 0) return t.length;
  let 깊이 = 0;
  for (let i = 열림; i < t.length; i++) {
    if (t[i] === '{') 깊이++;
    else if (t[i] === '}' && --깊이 === 0) return i + 1;
  }
  return t.length;
}

/**
 * 이 CSS 의 선택자 중 이 마크업에 **닿는** 것들. `[{ 선택자, 훅 }]`.
 * @param {string} css   Loom 부품 CSS(생성본 전체 또는 파일에서 뽑은 마커 구간)
 * @param {string} html  마크업(원고 또는 산출물 — `<style>` 안은 알아서 뺀다)
 */
function 닿는선택자들(css, html) {
  const { 클래스, 태그 } = 마크업집합(html);
  const 본 = new Set();
  const 닿은 = [];
  for (const sel of 선택자들(css)) {
    if (본.has(sel)) continue;
    본.add(sel);
    const 훅 = 필수훅(sel);
    if (!훅.length) continue;
    if (훅.every((h) => (h.startsWith('.') ? 클래스.has(h.slice(1)) : 태그.has(h)))) 닿은.push({ 선택자: sel, 훅 });
  }
  return 닿은;
}

/**
 * 이 «파일 원문»이 Loom 을 입고 있나 — 마커 구간에서만 훅을 뽑아 잰다.
 * `{ 마커: n, 닿은: [...] }`. 마커 0 이면 안 얹힌 것이고, 마커>0·닿은 0 이면 **「마커만」**이다.
 */
function 파일판정(원문) {
  const 구간 = 마커구간들(원문);
  const 닿은 = 구간.length ? 닿는선택자들(구간.map((g) => g.본문).join('\n'), 원문) : [];
  return { 마커: 구간.length, 닿은 };
}

module.exports = { 보편, 껍질벗기기, 선택자들, 필수훅, 마크업집합, 마커구간들, 첫규칙끝, 닿는선택자들, 파일판정 };
