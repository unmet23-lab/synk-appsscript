#!/usr/bin/env node
/* 세션지문 — 「내가 누구인가」를 도구 층에서 읽는 **한 곳** (마찰 F632).
 *
 * ■ 왜 있나 (2026-08-18 실측 · 이 저장소의 클라우드 세션 하나)
 *   `CLAUDE_CODE_HOST_SESSION_ID` 가 **빈 문자열**인 기계가 실재한다. 그 변수를 읽는 자리는
 *   저장소에 205곳/55파일이고, 정규화가 셋(`store.safeId` · `보드id.지문` · 손 slice)·폴백이
 *   넷(`input.session_id` · `'unknown'`/`'nosid'`/날짜 · `''`)으로 갈려 있다. 훅 층은 훅 입력에서
 *   세션 id 를 주워 계속 도는데 **도구 층은 주울 자리가 없어 눈이 먼다.**
 *
 * 🔑 그래서 실제로 난 것은 「기능이 꺼진다」가 아니라 **「규약을 우회하게 된다」**였다:
 *   `대기열.js --집기` 가 `세션 지문을 못 읽었다` 한 줄로 끝나 **다음 명령이 없었고**, 정본이
 *   시키는 「선언부터」를 지키는 유일한 길이 보드 파일을 **손으로 쓰는 것**이 됐다.
 *   따를 수 없는 처방은 우회를 정상 통로로 만든다(F103) — 이 파일이 그 길을 낸다.
 *
 * ■ 판정을 새로 짓지 않는다
 *   지문 뽑기는 `.claude/hooks/lib/board-id.js` 의 `지문()` 하나가 진다. 여기서 다시 slice 하면
 *   같은 판정이 두 곳에 앉고, 갈라진 쪽의 증상은 언제나 「통과」다(CLAUDE.md 신뢰성 ④).
 *   이 파일이 새로 지는 것은 **①어디서 읽을지 ②그 출처를 이름으로 낼지** 둘뿐이다.
 *
 * 〖대가 — 틀릴 때의 모습〗 (CLAUDE.md 「새 장치엔 대가를 함께 적는다」)
 *   · `SYNK_SESSION_FINGERPRINT` 은 **사람이 손으로 주는 값**이다 — 남의 지문을 적으면 남의 보드 파일을
 *     고르게 된다. 그래서 ①꼴을 8자리 hex 로 못박고(보드 파일명 규격) ②틀리면 「없음」으로
 *     떨어뜨려 **막는 쪽**으로 샌다. 그리고 지정값도 board-guard 의 「내 파일에만」을 그대로 지난다
 *     (이 파일은 그 가드를 우회시키지 않는다 — 고르는 이름만 준다).
 *   · `출처: '없음'` 은 **「지문이 없다」가 아니라 「못 읽었다」**다. 부르는 쪽이 그 둘을 같게 다루면
 *     미측정이 판정의 얼굴을 쓴다(F207) — 그래서 `사유` 를 늘 함께 낸다.
 *   · 접두를 **지어내지 않는다.** sid 에 접두가 없으면 `sess_` 다 — `local_` 로 박으면 클라우드
 *     세션의 선언이 공유 선언판에서 provenance 를 잘못 말하고, 읽는 쪽은 접두를 전부 떼므로
 *     **파손이 안 나서 증상이 없다.**
 *   닫을 것: **없다.** 새 훅·새 상시 계기를 만들지 않고 이미 도는 두 도구의 읽는 자리를 바꿨다.
 *   ⚠ 205곳 전수 이관은 **안 했다** — `board-guard.js`·`보드.js`·`작업본소유자.js` 는 지금 남이
 *   만지는 자리라 한 판에 할 일이 아니다. 여기 온 것은 **해악을 실측한 두 자리**뿐이다.
 */
'use strict';

const path = require('node:path');

/* 🔴 board-id 는 **부를 때** 연다 (2026-08-18 실측 · CI 모사가 잡았다).
 *   맨 위에서 `require` 하면 이 파일을 물고 있는 `대기열.js` 가 **로드 시점에** 죽는다 —
 *   `tools/` 만 복사해 세우는 E2E 픽스처(`tests/대기열채번.test.js`)에는 `.claude/` 가 없어서,
 *   내 변경이 그 스위트 5건을 통째로 `MODULE_NOT_FOUND` 로 무너뜨렸다.
 *   ⚠ 그렇다고 지문 뽑기를 여기서 **다시 구현하지 않는다** — 같은 판정이 두 곳에 앉으면
 *   갈라지고, 갈라진 쪽의 증상은 언제나 「통과」다. 못 열면 이 파일의 대원칙대로
 *   **「못 읽었다」로 떨어진다**(사유에 그 사실을 적는다). */
let _보드id = null;
let _못연사유 = '';
function 보드id() {
  if (_보드id || _못연사유) return _보드id;
  try {
    _보드id = require(path.join(__dirname, '..', '..', '.claude', 'hooks', 'lib', 'board-id.js'));
  } catch (e) {
    _못연사유 = `board-id.js 를 못 열었다(${(e && e.code) || e}) — 지문 판정을 여기서 지어내지 않는다`;
  }
  return _보드id;
}

/** 지문 뽑기 — **판정은 board-id 하나가 진다.** 못 열면 빈 문자열이고, 그 사유는 `읽기().사유` 가 낸다. */
function 지문(sid) {
  const b = 보드id();
  return b ? b.지문(sid) : '';
}

/** 사람이 손으로 주는 지정값의 꼴 — 보드 파일명 규격(`<8자리 hex>.md`)과 같다. */
const 지정꼴 = /^[0-9a-f]{8}$/;

/** sid 의 **접두**(`local_`·`cloud_` …). 없으면 빈 문자열 — 여기서 지어내지 않는다. */
function 접두뽑기(sid) {
  const m = /^([a-z]+)_/.exec(String(sid || ''));
  return m ? `${m[1]}_` : '';
}

/** 접두를 모를 때 쓰는 이름. 읽는 쪽(`보드id.줄의지문`)이 받는 `[a-z]+_` 꼴이고, **모른다고 말한다.** */
const 기본접두 = 'sess_';

/** 보드 줄·파일명에 쓰는 표기 — `<접두><지문>`. 접두를 모르면 `sess_` 다(`local_` 로 박지 않는다). */
function 표기(sid) {
  const 값 = 지문(sid);
  if (!값) return '';
  return `${접두뽑기(sid) || 기본접두}${값}`;
}

/**
 * 지금 이 프로세스의 세션 지문.
 *
 * 출처 순서 — **앞이 이긴다**:
 *   `'지정'`   `SYNK_SESSION_FINGERPRINT`(또는 `옵션.지정`) — 사람이 명시한 값. **빈 기계의 유일한 길**이라 맨 위다.
 *   `'호스트'` `CLAUDE_CODE_HOST_SESSION_ID` — 평소 정본. `prepare-commit-msg` 가 박는 그 값이다.
 *   `'훅'`     `옵션.훅입력.session_id` — 훅 층이 이미 쓰던 폴백(도구는 이 입력이 없다).
 *   `'없음'`   아무 데서도 못 읽음 → `지문: ''` · `사유` 채움.
 *
 * @returns {{sid:string, 지문:string, 접두:string, 표기:string, 출처:string, 사유:string}}
 */
function 읽기(옵션 = {}) {
  const 환경 = 옵션.환경 || process.env;
  /* 판정기를 못 열었으면 **읽은 척하지 않는다** — 아래 갈래는 전부 `지문()` 위에 서 있어서,
   * 여기서 안 막으면 「호스트에서 읽었다 · 지문은 빈 문자열」이라는 맞는 얼굴의 거짓이 나온다. */
  if (!보드id()) return { sid: '', 지문: '', 접두: '', 표기: '', 출처: '없음', 사유: _못연사유 };
  const 지정 = String(옵션.지정 || 환경.SYNK_SESSION_FINGERPRINT || '').trim();
  if (지정) {
    const 후보 = 지문(지정);
    if (지정꼴.test(후보)) {
      return { sid: 지정, 지문: 후보, 접두: 접두뽑기(지정) || 기본접두, 표기: 표기(지정), 출처: '지정', 사유: '' };
    }
    /* 틀린 지정을 **조용히 흘리지 않는다** — 흘리면 아래 폴백이 답을 내고, 사람은 자기가 준 값이
     * 쓰인 줄 안다. 새는 방향을 「막는 쪽」에 둔다. */
    return { sid: '', 지문: '', 접두: '', 표기: '', 출처: '없음',
      사유: `SYNK_SESSION_FINGERPRINT 이 8자리 hex 가 아니다: "${지정}" (보드 파일명 규격 = docs/_ops/보드/<8자리 hex>.md)` };
  }

  const 호스트 = String(환경.CLAUDE_CODE_HOST_SESSION_ID || '').trim();
  if (호스트) {
    return { sid: 호스트, 지문: 지문(호스트), 접두: 접두뽑기(호스트) || 기본접두, 표기: 표기(호스트), 출처: '호스트', 사유: '' };
  }

  const 훅 = String((옵션.훅입력 && 옵션.훅입력.session_id) || '').trim();
  if (훅) {
    return { sid: 훅, 지문: 지문(훅), 접두: 접두뽑기(훅) || 기본접두, 표기: 표기(훅), 출처: '훅', 사유: '' };
  }

  return { sid: '', 지문: '', 접두: '', 표기: '', 출처: '없음',
    사유: 'CLAUDE_CODE_HOST_SESSION_ID 가 비어 있다(클라우드 세션에서 실측했다)' };
}

/**
 * 「못 읽었다」를 **따를 수 있는 처방**으로 바꾼다 (F103). 부르는 쪽은 이 문장을 그대로 붙인다 —
 * 처방을 호출부마다 적으면 하나만 낡는다(신뢰성 ④).
 * @param {string} 사유  `읽기().사유`
 * @param {string} 명령  다시 돌릴 명령(예: `node tools/대기열.js --집기 #Q99 --파일 "…"`)
 */
function 처방(사유, 명령 = 'node tools/board.js', { 플래그 = '' } = {}) {
  /* 🔴 **환경변수 이름은 ASCII 여야 한다** — 첫 판이 `SYNK_세션지문` 이었고, 그 처방을 그대로
   *   되먹이니 bash 가 `command not found` 를 냈다(POSIX 셸의 `VAR=값 명령` 은 이름을
   *   `[A-Za-z_][A-Za-z0-9_]*` 로 제한한다). 따를 수 없는 처방을 **처방 자리에서** 낸 셈이라,
   *   가드 맹점 ③(자기 처방을 되먹여 통과하는가)이 정확히 이 자리를 잡았다. */
  const 줄 = [`내 세션 지문을 못 읽었다 — ${사유}`,
    '   → **내 보드 파일 이름 8자리**를 직접 준다(없으면 그 이름으로 새로 만들면 된다):'];
  if (플래그) 줄.push(`        ${명령} ${플래그} <8자리hex>`);
  줄.push(`        SYNK_SESSION_FINGERPRINT=<8자리hex> ${명령}`);
  줄.push('   → 8자리는 아무 값이나 되는 것이 아니다: 이미 내 줄이 있으면 `docs/_ops/보드/` 의 그 파일 이름을 그대로 쓴다');
  줄.push('     (다른 값을 주면 남의 파일을 고르거나 유령 파일이 하나 더 생긴다 — board-guard 가 그때 짖는다).');
  return 줄.join('\n');
}

module.exports = { 읽기, 처방, 접두뽑기, 표기, 기본접두, 지문 };
