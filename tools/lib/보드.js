/** 상태 칸이 아직 도는 트랙인가. 표줄이 아니면 거짓(대상 아님). */
function 활성행(line) {
  if (!표줄(line)) return false;
  const decor = /^[\s*_`~>✅🔴⚠️☑️✔️🟢🟡]+/u;
  const { 완료, 활성 } = 활성어휘();
  const 칸 = 표.칸나누기(line);
  const status = (칸[칸.length - 1] || '').trim().replace(decor, '');
  // 첫 구절만 본다 — 뒤쪽 서술의 「…로 종결」·「라이브 실측」이 활성 줄을 완료로 뒤집지 않게.
  const 첫구절 = status.split(/[—(]/)[0];
  if (활성.some((w) => 첫구절.includes(w))) return true;
  // 「미완료」·「안 끝남」을 완료로 읽지 않는다 — 부정 접두가 붙은 것은 완료가 아니다.
  return !new RegExp(`(?<![미안못])(${완료.join('|')})`).test(첫구절);
}

/** 끝났다고 적힌 **데이터 행**인가 — 유령은 뺀다(조립기가 못 읽는 줄을 치울 대상으로 세지 않는다). */
function 완료행(line) {
  return 데이터행(line) && !활성행(line);
}

/** 이 줄을 `board-move` 에 넘길 **유일 문구** — 못 고르면 `null`.
 *
 * 태어난 곳은 `board-guard`(사람에게 낼 처방 명령)였고, 이제 `tools/보드수거.js` 가 같은 판정으로
 * board-move 를 **직접** 부른다. 두 벌이 되면 갈라지고, 갈라진 쪽의 증상은 「그 줄은 아무도 못
 * 치운다」다(가드가 내민 명령이 수거에선 안 맞거나 그 반대). 위 `데이터행` 과 같은 이유로 여기 모은다.
 *
 * 셸을 깨는 글자에서 자른다 — 큰따옴표 안에서 bash·PowerShell 이 **함께** 해석하는 `"`·백틱·`$`·`\`.
 * 수거는 셸을 안 거치지만 자르는 규칙은 그대로 둔다: 규칙이 갈리면 문구도 갈린다.
 * `*` 는 자르지 않는다(큰따옴표 안에서 확장되지 않고, 자르면 유일해질 여지만 좁아진다).
 *
 * 🔑 [F283] 첫 조각이 아니라 **비어 있지 않은 첫 조각**을 쓴다 — 트랙 칸이 백틱으로 시작하면
 *   첫 조각에 장식만 남아 비고, 그러면 그 줄은 처방 목록에서 **영구히 사라진다**(F103 축). */
function 이관문구(line, 전체) {
  const 조각들 = (표.칸나누기(line)[1] || '').split(/["`$\\]/)
    .map((s) => s.trim().replace(/^\*+/, '').trim()).filter(Boolean);
  for (const 안전 of 조각들) {
    for (let n = 4; n <= 안전.length + 3; n += 3) {
      const needle = 안전.slice(0, Math.min(n, 안전.length));
      if (전체.filter((l) => l.includes(needle)).length === 1) return needle;
    }
  }
  return null;
}

/** 파일에 **남은 게 상투구뿐인가** — 그러면 그 세션 파일은 지워도 되는 껍데기다 (2026-08-12).
 *
 * 왜 여기 있나: 판정을 쓰는 곳이 둘이다 — `tools/board-move.js`(줄을 뺀 **직후**)와
 * `tools/보드껍데기정리.js`(**이미 쌓인** 것). 두 곳에 적으면 갈라지고, 갈라진 쪽의 증상은
 * 「지워도 되는 줄 알았다」다. 위 `데이터행` 과 같은 이유로 `표줄` 에서 파생시킨다.
 *
 * 왜 지우나 (실측 2026-08-12): 이관이 지금까지 줄만 빼고 파일을 남겨, 보드 폴더 262개 중
 * 데이터행이 있는 건 18개뿐이고 0바이트 189 · 표 머리글만 55 가 죽은 껍데기였다(93%).
 * 껍데기는 조용하지 않다 — `board-guard` 는 PreToolUse 라 **파일을 쓸 때마다** 이 폴더를
 * 통째로 훑고, 그 훑기가 244개의 빈 파일을 매번 연다. 세션 수만큼 곱해지는 값이다.
 *
 * ⚠ 새는 방향을 「지운다」로 두지 않는다 — 판정은 **좁게**다:
 *   · `표줄` 이 하나라도 남으면 거짓이다. `표줄` 은 넓은 쪽이라 **유령까지 센다**(F322·F330·F331) —
 *     규격 밖 줄을 「데이터행이 아니니 빈 파일」로 읽어 조용히 지우면 그건 유령보다 나쁘다.
 *     유령은 적어도 파일에 남아 있었고 `board.js` 가 stderr 로 드러낸다.
 *   · 상투구(제목·표 머리글·구분선·빈 줄) 말고 **사람이 쓴 글이 한 줄이라도 있으면 거짓이다.**
 *     보드 파일은 규격이 좁지만 메모를 적어 둔 세션이 있을 수 있고, 그건 내 것이 아니다.
 */
function 껍데기인가(text) {
  for (const raw of String(text).split(/\r?\n/)) {
    const l = raw.trim();
    if (!l) continue;                          // 빈 줄
    if (표줄(l)) return false;                  // 데이터행이든 유령이든 **줄이 남아 있다**
    if (l.startsWith('#')) continue;           // `# 보드 — <지문>` 제목
    if (/^\|\s*날짜\s*\|/.test(l)) continue;    // 표 머리글
    if (/^\|[\s:|-]+\|$/.test(l)) continue;     // 구분선 |---|---|
    return false;                              // 그 밖의 글 = 사람이 쓴 것
  }
  return true;
}

/**
 * 폴더의 모든 세션 파일에서 표 행을 모은다.
 *
 * ⚠ 정렬은 **날짜 칸**으로만 한다. 파일 mtime 은 git 체크아웃·반입에서 통째로 새로 찍혀
 *   다른 기계에서 순서가 뒤집힌다 — 그러면 「내 줄이 어디 있나」가 기계마다 달라진다.
 *   같은 날짜끼리는 파일명(지문) 순 — 안정 정렬이라 어느 기계에서나 같은 표가 나온다.
 *
 * 🔑 폴더 자체를 못 읽으면 **null** 이다 — 「비었다」와 다르다. 부르는 쪽 중 하나(인계문)는
 *   그 차이로 「내 줄이 정말 없다」와 「보드를 못 봤다」를 가르고, 전자일 때만 다음 세션에게
 *   「보드를 다시 열 필요 없다」고 말한다. 둘을 같은 `[]` 로 뭉개면 못 본 것을 없다고 단정한다.
 */
/** 폴더의 **모든 표줄**을 한 번만 훑는다 — `줄들`(렌더 대상)과 `유령들`(규격 밖)이 여기서 갈린다.
 *  두 번 훑으면 두 스캐너가 갈라지고, 그게 지금 고치는 결함 그 자체다. */
function 훑기(root) {
  const dir = 폴더(root);
  let names;
  try { names = fs.readdirSync(dir).filter((n) => n.endsWith('.md')).sort(); } catch (_) { return null; }

  const 모음 = [];
  for (const name of names) {
    let txt;
    try { txt = fs.readFileSync(path.join(dir, name), 'utf8'); } catch (_) { continue; }
    txt.split(/\r?\n/).forEach((line, i) => {
      const l = line.replace(/\s+$/, '');
      if (!표줄(l)) return;
      const 사유 = 유령사유(l);
      모음.push({
        줄: l, 파일: name, 줄번호: i + 1, 사유,
        날짜: 사유.length ? '' : 표.칸나누기(l)[0].trim(),
      });
    });
  }
  return 모음;
}

function 줄들(root) {
  const 전부 = 훑기(root);
  if (전부 === null) return null;
  const 모음 = 전부.filter((r) => !r.사유.length);
  모음.sort((a, b) => (a.날짜 < b.날짜 ? -1 : a.날짜 > b.날짜 ? 1 : a.파일 < b.파일 ? -1 : a.파일 > b.파일 ? 1 : 0));
  return 모음;
}

/** 조립기가 못 읽는 줄들 — 가드는 세는데 표에는 없는 것. 폴더를 못 읽으면 `null`(「비었다」와 다르다). */
function 유령들(root) {
  const 전부 = 훑기(root);
  if (전부 === null) return null;
  return 전부.filter((r) => r.사유.length)
    .sort((a, b) => (a.파일 < b.파일 ? -1 : a.파일 > b.파일 ? 1 : a.줄번호 - b.줄번호));
}

/** 줄은 표에 있는데 **주인이 없는** 것 — 그 줄의 「▶다음」·「🎫」는 마감 시점에서 멈췄다.
 *
 * 🔴 사연 (2026-08-12 `local_38c31cad` 실측 — 한 세션이 트랙 하나 고르는 데 낚인 것만 셋):
 *   ①「🎫다음=clasp push(215~217)」 두 줄 — 이미 `a668c152` 가 v9.215~220 을 완주한 뒤였다
 *   ②「▶다음(미착수) `lib/멘탈게이지.js`·`lib/게임스냅샷.js` 신설」 — 둘 다 이미 형제에 있다
 *   ③ 대기열 S1-5 항목 — 본문이 「✅2단계 종결」인데 체크박스는 열려 있다
 *   셋 다 **주인이 마감을 선언한 뒤 굳은 줄**이다(「죽음」이 아니다 — 판정 재료는 마감 도장이고,
 *   도장 찍은 세션도 도구를 다시 부르면 되살아난다). 산 세션의 줄은 그 세션이 갱신하니 안 생긴다.
 *
 * 🔑 그런데 표에서 그 둘은 **글자 하나 다르지 않다.** 「지금 누가 뭘 잡았나」를 보라고 만든
 *   화면인데 정작 「그 누가 아직 있나」가 안 적힌다 — 새 세션은 규약대로 🎫 를 집었다가
 *   그게 이미 착지한 일임을 스스로 파헤쳐야 한다. 비용은 세션 수만큼 곱해진다(살아있는 세션 12).
 *
 * ⚠ 새는 방향을 못박는다 — 「주인 있음」으로 잘못 말하는 쪽이 사고고(다음 세션이 낡은 🎫 를
 *   집는다), 「주인 없음」으로 잘못 말하는 쪽은 사람이 실물을 한 번 더 여는 비용뿐이다.
 *   그래서 **모르면 「주인 없음」으로 기운다**: 파일 이름이 지문 꼴이 아니면(`유물-*.md`)
 *   `파일지문()` 이 `''` 을 주는데, 그것을 「내 것」이 아니라 주인 없음으로 센다(board-id 머리 ⚠).
 *
 * 🔑 「살아있음」은 **작업본소유자에서 그대로 가져온다** — 여기 다시 적으면 두 도구가 서로 다른
 *   생사를 보게 되고, 갈라진 쪽의 증상은 언제나 「통과」다(`board-move.js` 원칙 ⑥ 과 같은 통로).
 *   require 를 함수 안에 두는 것은 취향이 아니다: 작업본소유자가 이 파일을 top-level 로 물고 있어
 *   맞물면 순환이 된다.
 *
 * 폴더를 못 읽거나 생사를 못 재면 `null` — 「주인 없는 줄 0건」과 **다른 상태**다(F207). */
function 주인없는줄들(root) {
  const rows = 줄들(root);
  if (rows === null) return null;
  let 소유자;
  try { 소유자 = require(path.join(__dirname, '..', '작업본소유자.js')); } catch (_) { return null; }
  if (typeof 소유자.세션들 !== 'function' || typeof 소유자.선언살았나 !== 'function') return null;
  let 산지문;
  try {
    산지문 = new Set(소유자.세션들(root).filter((s) => 소유자.선언살았나(s)).map((s) => 보드id.지문(s.sid)));
  } catch (_) { return null; }
  return rows
    .filter((r) => { const f = 보드id.파일지문(r.파일); return !f || !산지문.has(f); })
    .map((r) => ({ ...r, 지문: 보드id.파일지문(r.파일), 이어받기: r.줄.includes('🎫') }));
}

/** 옛 `세션보드.md` 와 **같은 모양**의 전문. 디스크에 쓰지 않는다(위 머리말 🔑).
 *  폴더를 못 읽으면 `null` — 「못 봤다」를 「비었다」로 번역하지 않는다(`줄들` 🔑). */
function 텍스트(root) {
  const rows = 줄들(root);
  if (rows === null) return null;
  return 머리말.concat(rows.map((r) => r.줄)).join('\n') + '\n';
}

/** 아카이브 파일 자리. `SYNK_BOARD_ARCHIVE` 는 `tools/board-move.js` 와 **같은 이름의 이음매**다 —
 *  이름이 갈리면 수거는 A 에 쓰고 되찾기는 B 를 읽어, 되찾기가 언제나 「없다」가 된다. */
function 아카이브경로(root) {
  return process.env.SYNK_BOARD_ARCHIVE || path.join(String(root || '.'), 'docs', '세션보드_아카이브.md');
}

/** 아카이브에 있는 **그 지문의** 줄들 — 되살아난 세션이 자기 줄을 되찾는 자리 (2026-08-12).
 *
 * 왜 있나: 이관은 줄을 잃지 않지만(아카이브에 그대로 있다) **찾을 통로가 없었다.** F146 이
 *   그 사고고(줄을 잃은 세션은 다음 턴에 「트랙 없음」으로 접힌다 · F144 — 아카이브에 멀쩡히
 *   있어도 인계문은 보드만 본다), `tools/보드수거.js` 가 그 이관을 **기계로** 돌리는 이상
 *   되찾기도 기계여야 한다. 안 그러면 자동화가 F146 의 빈도만 올린다.
 *
 * 🔑 재료는 **줄에 적힌 지문**이다 — 아카이브는 줄만 옮기므로 파일명(=주인)이 거기서 사라진다.
 *   `board-guard` ③ 이 「새 줄은 주인을 말해야 한다」를 쓰는 순간 기계로 요구하므로 줄에 있다.
 *   지문이 없는 옛 줄은 원리상 못 찾는다 — 그래서 없는 것을 「0건」이라 단정하지 않고, 파일을
 *   못 읽으면 `null` 이다(「내 줄이 아카이브에 없다」와 「아카이브를 못 봤다」는 다른 상태다). */
function 아카이브된줄들(root, 지문) {
  const 찾을것 = String(지문 || '').toLowerCase();
  if (!/^[0-9a-f]{8}$/.test(찾을것)) return [];
  let txt;
  try { txt = fs.readFileSync(아카이브경로(root), 'utf8'); } catch (_) { return null; }
  return txt.split(/\r?\n/)
    .filter((l) => 표줄(l))
    .filter((l) => 보드id.줄의지문(l).some((f) => String(f).toLowerCase() === 찾을것));
}

