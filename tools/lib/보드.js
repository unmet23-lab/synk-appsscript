const 구절경계RE = /[·,(){}[\]|]|\s[—–]\s/;

/** 만지는 파일 칸에서 **비켜남 표기를 뺀** 텍스트. 자리를 재는 쪽은 전부 이걸 거친다.
 *
 * 🔑 소비자가 둘이다(`board-guard` 의 겹침 판정 · `track-collision` 의 내 자리 판정) — 그리고
 *   둘은 지금까지 **서로 다르게 틀렸다**(전자는 🚫만 조각째, 후자는 아예 안 뗌). 같은 판정을
 *   두 곳에 적으면 갈라지고, 갈라진 쪽이 조용히 틀린다(CLAUDE.md 가드 맹점 ④). 여기 하나뿐이다.
 * 🔑 길이를 안 지킨다 — 소비자 둘 다 결과를 **다시 훑을** 뿐 원본 좌표를 안 쓴다. */
function 만지는텍스트(파일칸) {
  return String(파일칸 || '').split(/\s·\s/).map((조각) => {
    const 금지 = 조각.indexOf(금지표식);
    let 산것 = 금지 >= 0 ? 조각.slice(0, 금지) : 조각;
    /* 머리형 부정(`읽기만=…`)은 `🚫` 와 같은 자리에서 같은 힘으로 자른다 — F524. */
    const 머리 = 부정머리RE.exec(산것);
    if (머리) 산것 = 산것.slice(0, 머리.index);
    const 구절 = [];
    let 남은 = 산것;
    for (;;) {
      const m = 구절경계RE.exec(남은);
      if (!m) { 구절.push(남은); break; }
      구절.push(남은.slice(0, m.index));
      남은 = 남은.slice(m.index + m[0].length);
    }
    return 구절
      .filter((p) => p.trim() && !부정꼬리RE.test(p.replace(/[`*]/g, '')))
      .join(' · ');
  }).join(' · ');
}

/** 이 줄을 `board-move` 에 넘길 **유일 문구** — 못 고르면 `null`.
 *
 * 태어난 곳은 `board-guard`(사람에게 낼 처방 명령)였고, 이제 `tools/보드수거.js` 가 같은 판정으로
 * board-move 를 **직접** 부른다. 두 벌이 되면 갈라지고, 갈라진 쪽의 증상은 「그 줄은 아무도 못
 * 치운다」다(가드가 내민 명령이 수거에선 안 맞거나 그 반대). 위 `데이터행` 과 같은 이유로 여기 모은다.
 *
 * 셸을 깨는 글자에서 자른다 — 큰따옴표 안에서 bash·PowerShell 이 **함께** 해석하는 `"`·백틱·`$`·`\`.
 * 수거는 셸을 안 거치지만 자르는 규칙은 그대로 둔다: 규칙이 갈리면 문구도 갈린다.
 * `*` 는 자르지 않는다(큰따옴표 안에서 확장되지 않고, 자르면 유일해질 여지만 좁아진다).
 *
 * 🔑 [F283] 첫 조각이 아니라 **비어 있지 않은 첫 조각**을 쓴다 — 트랙 칸이 백틱으로 시작하면
 *   첫 조각에 장식만 남아 비고, 그러면 그 줄은 처방 목록에서 **영구히 사라진다**(F103 축). */
function 이관문구(line, 전체, 파일줄들) {
  const 조각들 = (표.칸나누기(line)[1] || '').split(/["`$\\]/)
    .map((s) => s.trim().replace(/^\*+/, '').trim()).filter(Boolean);
  const 고르기 = (후보들) => {
    for (const 안전 of 조각들) {
      for (let n = 4; n <= 안전.length + 3; n += 3) {
        const needle = 안전.slice(0, Math.min(n, 안전.length));
        if (후보들.filter((l) => l.includes(needle)).length === 1) return needle;
      }
    }
    return null;
  };
  /* ① 표 **전체**에서 유일한 문구가 먼저다 — 파일을 안 넘기는 통로도 그대로 쓸 수 있는 needle 이다.
   *   (전체에서 유일하면 그 부분집합인 한 파일 안에서도 유일하니, 이 순서는 좁히는 쪽으로 안 샌다.) */
  const 전역 = 고르기(전체);
  if (전역) return 전역;
  /* ② 그래도 없으면 **그 파일 안에서만** 유일한 문구 — 단 파일을 넘긴 통로에게만 준다.
   *   ⚠ 이 줄이 정말 그 파일에 있을 때만이다. 아니면 needle 이 «다른 줄» 하나에 걸려
   *   유일해 보이고, 그건 엉뚱한 줄을 옮기는 길이다(F405 ⚠ 가 경고한 방향). */
  if (!Array.isArray(파일줄들) || !파일줄들.includes(line)) return null;
  return 고르기(파일줄들);
}

/** 파일에 **남은 게 상투구뿐인가** — 그러면 그 세션 파일은 지워도 되는 껍데기다 (2026-08-12).
 *
 * 왜 여기 있나: 판정을 쓰는 곳이 둘이다 — `tools/board-move.js`(줄을 뺀 **직후**)와
 * `tools/보드껍데기정리.js`(**이미 쌓인** 것). 두 곳에 적으면 갈라지고, 갈라진 쪽의 증상은
 * 「지워도 되는 줄 알았다」다. 위 `데이터행` 과 같은 이유로 `표줄` 에서 파생시킨다.
 *
 * 왜 지우나 (실측 2026-08-12): 이관이 지금까지 줄만 빼고 파일을 남겨, 보드 폴더 262개 중
 * 데이터행이 있는 건 18개뿐이고 0바이트 189 · 표 머리글만 55 가 죽은 껍데기였다(93%).
 * 껍데기는 조용하지 않다 — `board-guard` 는 PreToolUse 라 **파일을 쓸 때마다** 이 폴더를
 * 통째로 훑고, 그 훑기가 244개의 빈 파일을 매번 연다. 세션 수만큼 곱해지는 값이다.
 *
 * ⚠ 새는 방향을 「지운다」로 두지 않는다 — 판정은 **좁게**다:
 *   · `표줄` 이 하나라도 남으면 거짓이다. `표줄` 은 넓은 쪽이라 **유령까지 센다**(F322·F330·F331) —
 *     규격 밖 줄을 「데이터행이 아니니 빈 파일」로 읽어 조용히 지우면 그건 유령보다 나쁘다.
 *     유령은 적어도 파일에 남아 있었고 `board.js` 가 stderr 로 드러낸다.
 *   · 상투구(제목·표 머리글·구분선·빈 줄) 말고 **사람이 쓴 글이 한 줄이라도 있으면 거짓이다.**
 *     보드 파일은 규격이 좁지만 메모를 적어 둔 세션이 있을 수 있고, 그건 내 것이 아니다.
 */
function 껍데기인가(text) {
  for (const raw of String(text).split(/\r?\n/)) {
    const l = raw.trim();
    if (!l) continue;                          // 빈 줄
    if (표줄(l)) return false;                  // 데이터행이든 유령이든 **줄이 남아 있다**
    if (l.startsWith('#')) continue;           // `# 보드 — <지문>` 제목
    if (/^\|\s*날짜\s*\|/.test(l)) continue;    // 표 머리글
    if (/^\|[\s:|-]+\|$/.test(l)) continue;     // 구분선 |---|---|
    return false;                              // 그 밖의 글 = 사람이 쓴 것
  }
  return true;
}

/**
 * 폴더의 모든 세션 파일에서 표 행을 모은다.
 *
 * ⚠ 정렬은 **날짜 칸**으로만 한다. 파일 mtime 은 git 체크아웃·반입에서 통째로 새로 찍혀
 *   다른 기계에서 순서가 뒤집힌다 — 그러면 「내 줄이 어디 있나」가 기계마다 달라진다.
 *   같은 날짜끼리는 파일명(지문) 순 — 안정 정렬이라 어느 기계에서나 같은 표가 나온다.
 *
 * 🔑 폴더 자체를 못 읽으면 **null** 이다 — 「비었다」와 다르다. 부르는 쪽 중 하나(인계문)는
 *   그 차이로 「내 줄이 정말 없다」와 「보드를 못 봤다」를 가르고, 전자일 때만 다음 세션에게
 *   「보드를 다시 열 필요 없다」고 말한다. 둘을 같은 `[]` 로 뭉개면 못 본 것을 없다고 단정한다.
 */
/** 폴더의 **모든 표줄**을 한 번만 훑는다 — `줄들`(렌더 대상)과 `유령들`(규격 밖)이 여기서 갈린다.
 *  두 번 훑으면 두 스캐너가 갈라지고, 그게 지금 고치는 결함 그 자체다. */
function 훑기(root) {
  const dir = 폴더(root);
  let names;
  try { names = fs.readdirSync(dir).filter((n) => n.endsWith('.md')).sort(); } catch (_) { return null; }

  const 모음 = [];
  for (const name of names) {
    let txt;
    try { txt = fs.readFileSync(path.join(dir, name), 'utf8'); } catch (_) { continue; }
    txt.split(/\r?\n/).forEach((line, i) => {
      const l = line.replace(/\s+$/, '');
      if (!표줄(l)) return;
      const 사유 = 유령사유(l);
      모음.push({
        줄: l, 파일: name, 줄번호: i + 1, 사유,
        날짜: 사유.length ? '' : 표.칸나누기(l)[0].trim(),
      });
    });
  }
  return 모음;
}

function 줄들(root) {
  const 전부 = 훑기(root);
  if (전부 === null) return null;
  const 모음 = 전부.filter((r) => !r.사유.length);
  모음.sort((a, b) => (a.날짜 < b.날짜 ? -1 : a.날짜 > b.날짜 ? 1 : a.파일 < b.파일 ? -1 : a.파일 > b.파일 ? 1 : 0));
  return 모음;
}

