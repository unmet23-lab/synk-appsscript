/** 상태 칸 앞머리의 장식 — 판정하는 자리가 둘이 됐다(`활성행`·`완료의심`). 두 곳에 적으면 갈라진다. */
const 장식 = /^[\s*_`~>✅🔴⚠️☑️✔️🟢🟡]+/u;

/** 상태 칸의 **첫 구절** — 뒤쪽 서술의 「…로 종결」이 활성 줄을 완료로 뒤집지 않게 앞만 본다. */
function 상태첫구절(line) {
  const 칸 = 표.칸나누기(line);
  return String(칸[칸.length - 1] || '').trim().replace(장식, '').split(/[—(]/)[0];
}

/** 상태 칸이 아직 도는 트랙인가. 표줄이 아니면 거짓(대상 아님). */
function 활성행(line) {
  if (!표줄(line)) return false;
  const { 완료, 활성 } = 활성어휘();
  // 첫 구절만 본다 — 뒤쪽 서술의 「…로 종결」·「라이브 실측」이 활성 줄을 완료로 뒤집지 않게.
  const 첫구절 = 상태첫구절(line);
  if (활성.some((w) => 첫구절.includes(w))) return true;
  /* 🔑 완료 낱말이 있어도 **과녁이 저장소 밖이라고 스스로 말하면 활성이다**(F554 · 2026-08-17).
   *   판정은 `대기행` 하나에서 **파생**한다 — ⏳⏸ 를 여기 다시 적으면 그날 갈라진다(등록층 ④).
   *   왜 이제 필요해졌나: 완료 어휘에 「착지」가 들어오면서 `⏳ … 착지` 줄이 완료로 접힌다.
   *   그 방향은 **조용하다** — 바로 아래 「`완료행` 에 섞지 않는다」가 이미 적어 둔 사고다
   *   (보드수거가 아카이브로 가져가면, 유호님 답이 오는 날 그 트랙은 보드에도 인계문에도 없다).
   *   실측 2026-08-17 에 그 모양이 **3줄** 있었다(`⏳ … 착지`). */
  if (대기행(line)) return true;
  // 「미완료」·「안 끝남」을 완료로 읽지 않는다 — 부정 접두가 붙은 것은 완료가 아니다.
  return !new RegExp(`(?<![미안못])(${완료.join('|')})`).test(첫구절);
}

/** 끝났다고 적힌 **데이터 행**인가 — 유령은 뺀다(조립기가 못 읽는 줄을 치울 대상으로 세지 않는다). */
function 완료행(line) {
  return 데이터행(line) && !활성행(line);
}

