/** 보드 「만질 파일」 칸이 실제로 쓰는 **중괄호 축약**을 펼친다 — `A{,_자립형}.html` → 둘.
 *
 * 🔴 왜 필요한가 (F440 실측): 이 표기를 안 펼치면 그 조각은 **경로가 하나도 안 나온다.**
 *   `만지는텍스트` 의 구절 경계에 `{`·`}` 가 들어 있어(그건 그 판정에는 옳다) 조각이 셋으로
 *   쪼개지고 `.html` 이 홀로 남는다. 그래서 F440 을 낳은 바로 그 줄
 *   (`docs/캐릭터/자개_캐러셀_예시_0814{,_자립형}.html`)이 **경로 0개**로 읽힌다 —
 *   새는 방향이 「검사할 게 없다」라 조용히 통과한다(가드 맹점 ①: 사람이 실제로 쓰는 표기로 검사한다).
 *
 * ⚠ 펼친 수가 상한을 넘으면 **원문을 그대로 돌려준다** — 못 편 것을 「없다」로 만들지 않는다.
 * 🔑 **반복으로 돈다(재귀 아님).** 재귀판은 안쪽에서 상한에 걸려 원문을 돌려줘도 바깥이 그걸
 *   조각으로 이어붙여, 중괄호가 **반쯤 남은** 문자열이 나왔다(`a111{1,2}{1,2}….html`) —
 *   원문도 아니고 펼친 것도 아닌 제3의 값이라 어느 소비자도 못 읽는다. 회귀가 잡았다.
 */
function 중괄호펼치기(텍스트, { 상한 = 64 } = {}) {
  const 원문 = String(텍스트 || '');
  let 현재 = [원문];
  for (;;) {
    const 다음 = [];
    let 남았나 = false;
    for (const s of 현재) {
      const m = /\{([^{}]*)\}/.exec(s);
      if (!m) { 다음.push(s); continue; }
      남았나 = true;
      for (const 갈래 of m[1].split(',')) {
        다음.push(s.slice(0, m.index) + 갈래 + s.slice(m.index + m[0].length));
      }
      if (다음.length > 상한) return [원문];
    }
    if (!남았나) return 다음;
    현재 = 다음;
  }
}

/** 「만질 파일」 칸에서 **유호님이 여는 산출물**의 경로만 뽑는다.
 *
 * 대상 확장자는 **주지 않으면 안 뽑는다**(`null` 이면 빈 배열) — 손 목록을 여기 박으면
 * #Q89 가 방금 닫은 죄를 다시 짓는다. 부르는 쪽이 `운영자료.화면확장자()` 로 폴더에서 도출해 넘긴다.
 *
 * 비켜남 표기(🚫·「0」·「무변경」…)는 `만지는텍스트` 가 이미 뗀다 — 그 판정을 여기 베끼지 않는다.
 */
function 산출물경로들(파일칸, 확장자집합) {
  if (!확장자집합 || !확장자집합.size) return [];
  const 확 = [...확장자집합].map((e) => String(e).replace(/^\./, '').replace(/[^\w]/g, '')).filter(Boolean);
  if (!확.length) return [];
  const RE = new RegExp(`(?:^|[\\s(\`"'·])((?:[\\w가-힣.\\-]+[\\\\/])+[\\w가-힣.\\-]+\\.(?:${확.join('|')}))\\b`, 'g');
  const 본것 = new Set();
  for (const 갈래 of 중괄호펼치기(파일칸)) {
    for (const m of 만지는텍스트(갈래).matchAll(RE)) 본것.add(m[1].split('\\').join('/'));
  }
  return [...본것];
}

