'use strict';
const fs = require('fs');
const path = require('path');

/* 「다시 묻지 마라」로 읽히는 표기 — 하나에서 파생시킨다(두 곳에 적으면 갈라진다).
 * ⓐ 🚫 가 가까이 붙은 재질의/질의  ⓑ 재질의·질의 바로 뒤의 금지·불필요 */
const 재질의패턴 = /(?:🚫[^\n]{0,30}(?:재질의|질의)|(?:재질의|질의)\s*(?:금지|불필요))/;

/** 차단자 이름이 「유호님 답 대기」인가. 판별을 부르는 쪽마다 적으면 갈라진다. */
function 유호대기(차단값) {
  return typeof 차단값 === 'string' && 차단값 !== '' && /유호/.test(차단값);
}

/** 줄에 걸린 근거 토픽들 — `[[slug]]`. 중복은 접는다. */
function 토픽들(본문) {
  const out = new Set();
  for (const m of String(본문 || '').matchAll(/\[\[([^\]|\n]+)\]\]/g)) {
    const s = m[1].trim();
    if (s) out.add(s);
  }
  return [...out];
}

/** 토픽 본문에서 「이미 판정 났다」고 말하는 조각들. 날짜가 적혀 있으면 함께 든다. */
function 확정조각들(본문, 상한 = 3) {
  const out = [];
  for (const 줄 of String(본문 || '').split(/\r?\n/)) {
    const t = 줄.trim();
    if (!t || !재질의패턴.test(t)) continue;
    const d = /(?:\b\d{4}-)?\b(\d{2}-\d{2})\b/.exec(t);
    out.push({ 글: t.replace(/^#+\s*/, '').replace(/^[-*]\s*/, ''), 날짜: d ? d[1] : null });
    if (out.length >= 상한) break;
  }
  return out;
}

/**
 * 대상 줄들을 메모리와 대조한다. **판정은 안 한다** — 재료만 모은다(머리말 🔴).
 *
 * @param {{대상: Array<{층?: string, 씨앗?: string, 본문: string}>, 메모리뿌리: string}} 인자
 * @returns {{측정: boolean, 사유?: string, 대상수: number, 걸림: Array, 링크없음: Array, 못잼: Array}}
 */
function 대조({ 대상, 메모리뿌리 }) {
  const 목록 = Array.isArray(대상) ? 대상 : [];
  let 있나 = false;
  try { 있나 = !!메모리뿌리 && fs.statSync(메모리뿌리).isDirectory(); } catch (_) { 있나 = false; }
  if (!있나) {
    return {
      측정: false,
      사유: '메모리 디렉터리를 못 읽었다 — 저장소 밖이라 CI·다른 기계엔 없다',
      대상수: 목록.length, 걸림: [], 링크없음: [], 못잼: [],
    };
  }

  const 걸림 = [], 링크없음 = [], 못잼 = [];
  for (const it of 목록) {
    const 토픽 = 토픽들(it.본문);
    if (!토픽.length) { 링크없음.push(it); continue; }
    for (const t of 토픽) {
      const p = path.join(메모리뿌리, `${t}.md`);
      let txt = null;
      try { txt = fs.readFileSync(p, 'utf8'); } catch (_) { txt = null; }
      /* 링크가 가리키는 파일이 없다 = 「확정 없음」이 아니라 **못 쟀다**. 링크는 아직 안 쓴
       * 메모리를 가리킬 수 있다(인덱스 머리말이 그걸 허용한다) — 그래서 결함이 아니라 미측정이다. */
      if (txt === null) { 못잼.push({ ...it, 토픽: t, 사유: '토픽 파일이 없다' }); continue; }
      const 조각 = 확정조각들(txt);
      if (조각.length) 걸림.push({ ...it, 토픽: t, 조각 });
    }
  }
  return { 측정: true, 대상수: 목록.length, 걸림, 링크없음, 못잼 };
}

module.exports = { 재질의패턴, 유호대기, 토픽들, 확정조각들, 대조 };
