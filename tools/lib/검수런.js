/**
 * 런 하나의 현재 상태. **다섯 갈래로만 답한다** — 「모름」을 통과로 접지 않는다.
 *   진행 · 멈춤(죽었거나 매달림) · 완주미처분(주울 결과가 있다) · 실패미처분(주울 결과가 없다) · 처분됨
 */
function 판정(런, now) {
  if (!런) return null;
  const 분 = 경과분(런, now);
  /* 중단 = **의도적으로 끈 것**이라 이미 처분이다. 안 그러면 pid 가 사라진 그 런을 「멈춤」으로
   * 읽어 세션마다 계속 알리고, 사람은 껐는데도 뜨는 알림을 곧 통째로 무시하게 된다. */
  if (런.상태 === '중단') return { 갈래: '처분됨', 분 };
  if (런.상태 === '완주' || 런.상태 === '미결' || 런.상태 === '실패') {
    if (런.처분) return { 갈래: '처분됨', 분 };
    /* 🔑 끝난 런을 **한 바구니에 넣지 않는다.** 부르는 쪽이 이 한 칸만 보고 말을 짓기 때문에,
     * 뭉쳐 두면 한쪽이 다른 쪽의 얼굴로 나간다. 실측이 양방향으로 다 있다:
     *   · F509 — 결과 0바이트(코드 3)가 「✅ 결과가 이미 나와 있다」로 나갔다(44KB 로그가 전부 404).
     *   · F561 — 지적 13건을 찾은 코드 1이 「🔴 주울 답이 없다」로 나갔다(64분·P1 2건이 버려질 뻔).
     * 그래서 갈래가 **셋**이다 — 완주 · 미결(결과 있음·처리할 것 남음) · 실패(주울 결과 없음).
     *
     * 🔑 그리고 **쓰는 쪽을 믿지 않는다.** 종료코드가 있으면 그것으로 **다시 판독한다** —
     *   `상태` 칸은 힌트일 뿐이다. 그래서 ①이미 장부에 앉은 옛 기록이 고쳐 읽히고(F561 의
     *   그 런은 `상태:'실패'` + `종료코드:1` 로 앉아 있다) ②앞으로 어느 생산자가 라벨을 잘못
     *   적어도 안 샌다. 호출부마다 고치는 대신 **잘못 쓸 수 없는 판독**으로 만든 자리다.
     * ⚠ 종료코드가 없거나 뜻을 모르는 런은 `상태` 로 접되, 「모름」을 「결과 없음」이라고
     *   **말하지는 않는다** — `결과` 칸을 null 로 실어 부르는 쪽이 다른 문장을 쓰게 한다. */
    const 뜻 = 코드뜻(런.종료코드, 생산자(런));
    const 이름 = 뜻 ? 뜻.이름 : (런.종료코드 != null && Number(런.종료코드) !== 0 ? '실패' : 런.상태);
    const 결과 = 뜻 ? 뜻.결과 : null;
    if (이름 === '완주') return { 갈래: '완주미처분', 분, 결과 };
    if (이름 === '미결') return { 갈래: '미결미처분', 분, 결과 };
    return { 갈래: '실패미처분', 분, 결과 };
  }
  // 상태가 '진행' 인데 프로세스가 없다 = 밖에서 죽었다(정상 종료면 자식이 상태를 적었다).
  if (!살아있나(런.pid)) return { 갈래: '멈춤', 분, 사유: '프로세스 없음' };
  /* 시간 상한은 **무응답 시계**로 잰다 — 이어받아 다시 붙은 런까지 「멈춤」으로 읽으면
   * 처방을 따른 사람이 그 사실을 못 보고, 다음 세션이 같은 작업에 폴러를 또 붙인다(F511). */
  const 무 = 무응답분(런, now);
  if (무 != null && 무 > 멈춤분) {
    const 꼬리 = 런.재개 ? ` · 이어받은 뒤 ${무}분 무응답` : '';
    return { 갈래: '멈춤', 분, 사유: `${분}분 경과(상한 ${멈춤분})${꼬리}` };
  }
  return { 갈래: '진행', 분 };
}

/** 훅·조회가 함께 쓰는 한 줄 요약. 판정 어휘를 두 곳에 적지 않는다. */
function 요약() {
  const now = Date.now();
  const 목록 = 런목록().map((r) => ({ 런: r, 판: 판정(r, now) })).filter((x) => x.판);
  return {
    진행: 목록.filter((x) => x.판.갈래 === '진행'),
    멈춤: 목록.filter((x) => x.판.갈래 === '멈춤'),
    완주미처분: 목록.filter((x) => x.판.갈래 === '완주미처분'),
    /* ⚠ 새 칸이다 — 부르는 쪽이 이걸 안 읽으면 실패한 런이 **어느 알림에도 안 뜬다**(조용한 누락).
     * 읽는 곳을 같은 커밋에서 함께 고쳤다: `review-runs` 훅 · `codex-review --런목록`
     * (셋째였던 `마누스 --런목록` 은 2026-08-31 에 걷혔다). */
    실패미처분: 목록.filter((x) => x.판.갈래 === '실패미처분'),
    /* ⚠ 같은 이유의 새 칸(F561) — **결과는 있는데 처리할 것이 남은** 런이다. 이 칸을 안 읽으면
     * 검수가 찾아낸 차단 지적이 어느 알림에도 안 뜬다. 읽는 곳 셋을 같은 커밋에서 함께 고친다.
     * 회귀 `tests/검수런.test.js(⚠삭제됨 e75fc7fc 2026-08-19 — 지금 없다)` 가 **세 소비자 전부**에 이 칸이 닿는지 검사한다 —
     * 칸만 늘리고 라우팅을 안 넓히면 조용히 샌다(CLAUDE.md 가드 맹점 ③). */
    미결미처분: 목록.filter((x) => x.판.갈래 === '미결미처분'),
  };
}

/* 던져 놓고 **까먹는 것**이 이 설계의 유일한 새 위험이다(유호님이 정확히 그걸 우려했다).
 * 그래서 처분은 손으로 적는 도장이고, 도장이 없는 완주는 세션을 열 때마다 훅이 계속 알린다. */
function 처분(런ID, 사유) {
  return 런갱신(런ID, { 처분: { 시각: new Date().toISOString(), 사유: String(사유 || '') } });
}

/* 던진 뒤 HEAD 가 움직였나 — **F334 의 정면**이다.
 *   「채번·커밋한 순간 도는 리뷰는 지문이 낡아 무의미해졌는데, 그 프로세스를 안 끄고
 *    『이제 기다릴 이유 없음』도 안 알려 유호님이 괜히 기다렸다(쿼터도 계속 소모).」
 * ⚠ **낡음을 판정하지 않는다.** 대상 종류마다 낡는 조건이 다르다 — `--commit <sha>` 는 sha 가
 *   고정이라 그 검수 자체는 유효하고, `--uncommitted` 는 커밋되는 순간 무효다. 지어낸 판정을
 *   주면 멀쩡한 런을 끄게 된다. 사실만 전하고 끌지 말지는 사람이 정한다. */
function HEAD움직였나(런, 현재HEAD) {
  if (!런 || !런.HEAD || !현재HEAD) return false;   // 한쪽이라도 모르면 대조 안 한다
  return 런.HEAD !== 현재HEAD;
}

/* 「그 자리에서 끈다」의 손잡이 — F334 의 교훈이 요구한 동작이다.
 * ⚠ 상태가 `진행` 이 아니면 **거절한다.** 끝난 런의 pid 는 이미 남이 재사용했을 수 있고,
 *   그걸 죽이면 무관한 프로세스를 죽인다(pid 재사용은 실재한다 — `판정()` 이 시간 상한을
 *   함께 보는 이유와 같은 축). */
function 중단(런ID, 사유) {
  const r = 런읽기(런ID) || 런목록().find((x) => x.런ID === 런ID);
  if (!r) return { ok: false, 왜: '모르는 런' };
  if (r.상태 !== '진행') return { ok: false, 왜: `상태가 「${r.상태}」다 — 도는 중이 아닌 런은 안 끈다(pid 재사용 위험)` };
  if (!살아있나(r.pid)) {
    런갱신(런ID, { 상태: '중단', 끝: new Date().toISOString(), 중단사유: String(사유 || ''), 비고: '끄기 전 이미 죽어 있었다' });
    return { ok: true, 이미죽음: true };
  }
  try { process.kill(r.pid, 'SIGTERM'); } catch (e) { return { ok: false, 왜: `kill 실패: ${e.message}` }; }
  런갱신(런ID, { 상태: '중단', 끝: new Date().toISOString(), 중단사유: String(사유 || '') });
  return { ok: true, pid: r.pid };
}

/* 던질 때 자식에게 줄 인자 — **`--던지기` 를 반드시 뺀다.**
 * 안 빼면 자식이 또 던지고 그 손자가 또 던진다. 무한 재귀는 프로세스 폭발이라 되돌리기도 어렵다.
 * 회귀가 이걸 못박는다(이 함수가 있는 이유의 전부다). */
const 던지기플래그 = '--던지기';
function 자식인자(argv) {
  return (argv || []).filter((a) => a !== 던지기플래그);
}

/* 던진 런이 자기 끝을 적을 때 쓰는 환경변수 이름 — **한 곳에만 적는다.**
 * 갈라지면 「안 물려준다」와 「물려받았나 본다」가 서로 다른 키를 보고, 그 어긋남의
 * 새는 방향은 언제나 「도장이 찍힌다」= 통과다. */
const 런ID키 = 'SYNK_REVIEW_RUN_ID';
const 자식표식키 = 'SYNK_REVIEW_CHILD';

/**
 * 회차 자식(손자)에게 줄 환경 — **부모의 런ID 를 물려주지 않는다** (마찰 F352 · 2026-08-12).
 *
 * 🔴 왜 있나 (실측 사고): `병렬실행` 이 `env: { ...process.env, SYNK_REVIEW_CHILD: '1' }` 로
 *   자식을 띄웠다. 던진 런에서는 그 `process.env` 안에 `SYNK_REVIEW_RUN_ID` 가 들어 있어
 *   **손자가 부모의 런ID 를 그대로 상속**했고, 손자가 먼저 끝나며 `마감()` 을 불러
 *   런 상태를 「완주」로 덮었다. 부모는 그때 아직 회차 1 폴백을 태우는 중이었다.
 *   결과: 훅이 「✅ 완주했는데 안 주운 런」으로 알렸는데 `검수기록.jsonl` 은 **33줄 그대로**고
 *   배포 게이트는 닫힌 채였다 — 18분과 벤더 비용이 통째로 증발했고, 그 증발이
 *   **통과와 같은 모양**을 하고 있었다(F207 계열).
 *
 * 🔑 그래서 「호출부마다 조심한다」로 두지 않고 **통로를 하나 판다**. `...process.env` 를
 *   spawn 에 그대로 펼치는 것이 이 파일의 금지 표기고, 회귀가 그 표기를 막는다
 *   (CLAUDE.md 신뢰성 — 3번째는 원인을 쓸 수 없게 만든다).
 */
function 자식환경(원본) {
  const e = { ...(원본 || process.env), [자식표식키]: '1' };
  delete e[런ID키];
  return e;
}

/** 지금 이 프로세스가 회차 자식인가 — 자식은 **런 상태를 적을 자격이 없다.**
 *  `자식환경` 이 키를 지우므로 정상 경로에선 늘 false 지만, 등록층이 새는 날
 *  (새 spawn 자리가 `...process.env` 를 쓰는 날) 이 검사가 두 번째 벽이 된다. */
function 자식인가(env) {
  return !!(env || process.env)[자식표식키];
}

/* ────────────────────────────────── 벤더 한도 마커 (GPT/codex usage limit)
 *
 * 실측 2026-08-13 (런 `심문-2026-08-13T0104-87f15a`): 한도 소진 상태에서 던진 심문 3회차가
 * 15초 만에 전멸했고("You've hit your usage limit … try again at Aug 18th, 2026 12:39 PM"),
 * 그 판정이 이 tmp 방의 런 JSON 에만 남아 **던진 세션·처분 세션·다음 세션이 각자 다시
 * 발견했다** — 같은 절차 3번째라 기계로 옮긴다(CLAUDE.md 신뢰성). 마커는 런과 같은 방에
 * 산다: 세션 무관·이 기계 전역이고, 이 방을 쓰는 도구들만 이 판정을 소비한다.
 *
 * ⚠ 새는 방향 점검(가드 맹점):
 *   ① 리셋 시각을 **못 읽었으면 막지 않는다** — 열리는 시각을 모르는 차단은 따를 수 없는
 *      처방이고, 그 순간 우회가 정상 통로가 된다(F103). 그 경우 훅 알림만 낸다.
 *   ② 우회는 `--한도무시`(env `SYNK_REVIEW_QUOTA_PROBE`) 하나 — **성공 1회가 마커를 지우므로**
 *      오탐(요금제 변경 등으로 이미 풀린 마커)은 확인 강행 한 번으로 스스로 낫는다.
 *   ③ 시각은 **로컬로 읽는다** — codex CLI 가 로컬 시각으로 찍고, 마커도 이 기계 전용이다. */
const 한도패턴 = /You.?ve hit your usage limit/i;
const 한도무시키 = 'SYNK_REVIEW_QUOTA_PROBE';

function 한도경로() { return path.join(런뿌리(), '한도.json'); }

/** "… try again at Aug 18th, 2026 12:39 PM." → ISO(로컬 해석). 못 읽으면 null — 차단 대신 알림만.
 * ⚠ 줄끝 앵커($)로 자르지 않는다 — 실제 로그는 오류 조각들이 「 / 」로 한 줄에 이어 붙어
 *   (실측 87f15a: 「확인 불가 … / ERROR: … / ERROR: …」), 앵커 매칭이 첫 「try again at」부터
 *   줄끝까지 통째로 삼켜 Date 가 죽는다. **날짜 모양 자체**를 잡는다 — 모양이 바뀌면 null 로
 *   접혀 차단 없는 알림만 남는다(새는 방향이 「멀쩡한 통로를 막음」이 아니라 「알림」이다). */
function 한도리셋파싱(줄, 지금) {
  const s = String(줄 || '');
  const m = /try again at ([A-Za-z]{3,9} \d{1,2}(?:st|nd|rd|th)?,? \d{4},? \d{1,2}:\d{2}\s?[AP]M)/i.exec(s);
  if (m) {
    const d = new Date(m[1].replace(/(\d{1,2})(st|nd|rd|th)\b/i, '$1'));
    return Number.isFinite(d.getTime()) ? d.toISOString() : null;
  }
  /* 🔴 2026-08-29 실측 — 벤더가 **날짜 없이 시각만** 주는 판이 있다:
   *   `ERROR: You've hit your usage limit. … or try again at 9:37 PM.`
   *   위 정규식은 연·월·일을 요구해서 이걸 못 읽었고, 마커는 「리셋 시각을 못 읽었다」로 남았다.
   *   그러면 게이트가 **태우기 전에 못 막는다**(리셋을 모르는 차단은 따를 수 없는 처방이라 설계상
   *   안 막는다) — 즉 못 읽는 순간 그 방어가 통째로 꺼진다.
   * 🔑 날짜가 없으면 **가장 가까운 미래**로 읽는다: 오늘 그 시각이 이미 지났으면 내일이다.
   *   벤더 문구가 로컬 시간대로 오므로 로컬 기준으로 세운다.
   * ⚠ 지어내지 않는 선을 지킨다 — 형식이 아예 다르면 여전히 null 이다(「안 읽혔다」가 보여야 한다). */
  const t = /try again at (\d{1,2}):(\d{2})\s?([AP])M/i.exec(s);
  if (!t) return null;
  const 분 = Number(t[2]);
  let 시 = Number(t[1]) % 12;
  if (/p/i.test(t[3])) 시 += 12;
  if (!(시 >= 0 && 시 <= 23 && 분 >= 0 && 분 <= 59)) return null;
  const 기준 = new Date(지금 || Date.now());
  if (!Number.isFinite(기준.getTime())) return null;
  const d = new Date(기준);
  d.setHours(시, 분, 0, 0);
  if (d.getTime() <= 기준.getTime()) d.setDate(d.getDate() + 1);
  return d.toISOString();
}

/** 출력에서 한도 오류를 발견하면 마커를 적는다. 패턴이 없으면 null — 아무것도 안 쓴다. */
function 한도기록(텍스트, 지금) {
  const s = String(텍스트 || '');
  if (!한도패턴.test(s)) return null;
  const 줄 = (s.split('\n').find((l) => 한도패턴.test(l)) || '').trim();
  const 기록 = {
    감지시각: new Date(지금 || Date.now()).toISOString(),
    리셋시각: 한도리셋파싱(줄, 지금),
    원문: 줄.slice(0, 500),
    출처런: process.env[런ID키] || '',
  };
  /* 마커 쓰기 실패는 기능 실패가 아니다 — 원래 오류(한도)가 그대로 보고되므로 조용해지지 않는다. */
  try {
    fs.mkdirSync(런뿌리(), { recursive: true });
    fs.writeFileSync(한도경로(), JSON.stringify(기록, null, 2), 'utf8');
  } catch (_) { /* 위 참조 */ }
  return 기록;
}

/** 마커 현재 상태. 없거나 못 읽으면 null. `지남` 은 리셋 시각을 아는 마커에서만 참이 될 수 있다. */
function 한도상태(지금) {
  let r;
  try { r = JSON.parse(fs.readFileSync(한도경로(), 'utf8')); } catch (_) { return null; }
  const t = Date.parse((r && r.리셋시각) || '');
  return { ...r, 지남: Number.isFinite(t) ? (지금 || Date.now()) >= t : false };
}

/** 성공 1회 = 「한도가 풀렸다」의 유일한 실측 — 마커를 지운다. */
function 한도해제() {
  try { fs.rmSync(한도경로(), { force: true }); return true; } catch (_) { return false; }
}

/** 막나 — 판정은 이 한 곳이다(호출부가 각자 판정하면 갈리고, 새는 방향은 「태운다」다).
 *  리셋 시각이 있는 살아있는 마커만 막는다(①). 우회 env(②)는 여기서 본다. */
function 한도막나(상태, env) {
  if ((env || process.env)[한도무시키]) return false;
  return !!(상태 && !상태.지남 && 상태.리셋시각);
}

