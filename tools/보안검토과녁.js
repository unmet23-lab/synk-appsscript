#!/usr/bin/env node
'use strict';
/* 보안검토 과녁 — `/deploy` 4단계의 판단 층 게이트가 **내 것을 봤는지** 가른다 (마찰 F306)
 *
 * ■ 왜 있나 (2026-08-10 실사고)
 *   `/security-review` 가 **내 변경이 아니라 옆 세션의 문서를 읽고** 판정을 내려 했다.
 *   내 배포 대상은 `Code.js`·`엔진_두뇌.js`·`상담AI.js` 의 미커밋 리터럴 3줄이었는데, 스킬이
 *   넘긴 DIFF CONTENT 본문에는 그 셋이 **한 줄도 없었고** 대신 세션 `local_ed0a2064` 가 방금
 *   커밋한 인계문·보드 마크다운 5벌이 들어 있었다. 원인: 그 통로가 「브랜치가 origin 보다 앞선
 *   커밋」을 diff 대상으로 잡는데, 나는 앞선 트랙을 이미 push 했고 그 사이 남이 3커밋을 얹어
 *   **「내 앞선 커밋 = 남의 것」**이 됐다. 정작 내 배포 대상은 unstaged 라 본문 밖이었다.
 *   `git status` 절에는 내 파일이 보이므로 **겉보기엔 정상 실행**이다.
 *
 * ■ 왜 위험한가
 *   기계 검사(`deploy-security-check.js`)는 아는 패턴만 본다. **처음 보는 결함을 보는 층은
 *   여기뿐**이다. 남의 문서를 읽고 「취약점 없음」이 나오면 나는 그것을 내 코드의 보안 검토
 *   통과로 기록한다 — **미실행이 통과와 같은 모양으로 오는** F207 계열이고, 새는 방향은 언제나
 *   「통과」다. 세션이 10개 도는 시간대엔 우연이 아니라 상시 조건이다.
 *   2026-08-10 은 리터럴 3줄이라 실해가 0이었지만, 그건 운이지 장치가 아니다.
 *
 * ■ 무엇을 하나 — 신고문의 처방 후보 둘, 그대로
 *   ① **과녁을 명시로 넘긴다**(브랜치 추론에 안 맡긴다):  node tools/보안검토과녁.js
 *      배포집합 ∩ 미커밋 = `clasp push` 가 실어 나갈 «아직 git 에 없는» 바이트다.
 *   ② **보고서가 그 과녁을 실제로 언급했는지 대조한다**:  node tools/보안검토과녁.js --대조 <파일>
 *      하나도 안 언급했으면 **「미실행」**으로 적는다 — 0건과 미실행을 가르는 자리다.
 *
 * ■ 새는 방향을 못박는다
 *   · **못 잼은 0건이 아니다**(F207). git 을 못 부르거나 배포집합을 못 읽으면 `null` 이고,
 *     CLI 는 종료 코드 **2**(판정 불가)로 낸다 — 통과(0)로도 미실행(3)으로도 접지 않는다.
 *   · **과녁 0건**은 미실행이 아니다. 미커밋 배포 파일이 없으면 이 배포가 라이브에 새로 내보낼
 *     바이트가 없다는 뜻이라 대조할 것 자체가 없다 — 그 사실을 말하고 0 으로 끝낸다.
 *     여기서 「미실행」을 내면 정상 배포가 상시 막히고, 막힌 처방은 우회를 정상 통로로 만든다(F103).
 *   · **판정은 언급 여부까지다.** 보고서가 내 파일을 「봤다」는 것과 「제대로 봤다」는 다르다 —
 *     이 도구는 앞의 것만 잰다. 재는 것을 넘겨 말하면 그 초록이 또 다른 미실행을 덮는다.
 *
 * ■ 왜 파일로 받나
 *   보고서는 여러 줄이고 백틱·경로가 섞인다 — 셸 인용으로 넘기면 그 자체가 사고다
 *   (`shell-inline-guard` 가 막는 형태). 스크래치패드에 쓰고 경로를 준다. `-` 면 stdin.
 *
 * 쓰는 법
 *   node tools/보안검토과녁.js                 과녁 목록 + `/security-review` 에 붙일 문장
 *   node tools/보안검토과녁.js --대조 <경로>    보고서 대조 (0 돌았다 · 2 못 쟀다 · 3 미실행)
 *   node tools/보안검토과녁.js --대조 -         같은 것을 stdin 으로
 */

const fs = require('fs');
const path = require('path');

const ROOT = process.env.SYNK_REVIEW_ROOT || path.resolve(__dirname, '..');
const 점검 = require(path.join(__dirname, '배포판점검.js'));

/* 종료 코드는 **계약**이다 — 글자로 가르지 않는다(문구를 다듬는 순간 판정이 갈라진다).
 * board-move 가 6 을 판 것과 같은 이유다(그쪽 머리말). */
const 코드 = { 통과: 0, 못잼: 2, 미실행: 3 };

/**
 * 지금 배포가 라이브로 새로 내보낼 파일들 = 배포집합 ∩ 미커밋.
 * `null` = **못 쟀다**(git 실패·프로젝트 목록 못 읽음). 「0건」과 다르다.
 */
/* 테스트 이음매 — 급소(미실행 판정)를 CLI 끝까지 태우려면 과녁을 고정할 손잡이가 필요하다.
 * 실저장소의 미커밋은 옆 세션이 상시 바꾸므로 그걸로 재면 검사가 그날 운에 걸린다.
 * 🔑 **켜지면 스스로 밝힌다**(아래 CLI 가 한 줄 낸다) — 조용한 이음매는 곧 우회다. */
const 고정과녁 = () => (process.env.SYNK_REVIEW_TARGETS || '').split(',').map((s) => s.trim()).filter(Boolean);

function 과녁(root = ROOT) {
  if (process.env.SYNK_REVIEW_TARGETS !== undefined) return 고정과녁();
  /* ⚠ `claspProjects()` 는 **인자를 안 받는다**(자기 모듈의 ROOT 를 본다) — 그래서 `root` 가
   *   실제로 갈아 끼우는 것은 **git 층**(`미커밋집합`)이다. 회귀는 그 자리를 이음매로 쓴다. */
  let 프로젝트들;
  try { 프로젝트들 = 점검.claspProjects(); } catch (_) { return null; }
  if (!Array.isArray(프로젝트들) || !프로젝트들.length) return null;
  const 모음 = new Set();
  for (const p of 프로젝트들) {
    let 미커밋;
    try { 미커밋 = 점검.배포집합미커밋(p, root); } catch (_) { return null; }
    if (미커밋 === null) return null;        // 못 잼은 전파한다 — 한 갈래라도 모르면 전체가 모름
    for (const f of 미커밋) 모음.add(f);
  }
  return [...모음].sort();
}

/* 보고서가 그 파일을 말했는가 — **경로 전체**와 **파일 이름** 둘 다 받는다.
 * 보고서는 `Code.js` 처럼 이름만 쓰기도 하고 `docs/…/Code.js` 처럼 경로로 쓰기도 한다.
 * ⚠ 이름만 매칭하는 쪽이 느슨하지만, 여기서 좁게 틀리면 **정상 검토가 「미실행」으로** 나오고
 *   그 거짓 적색은 배포를 막는다 — 막힌 처방은 우회를 부른다(F103). 이 도구가 재는 것은
 *   「엉뚱한 것을 봤나」이지 「얼마나 꼼꼼히 봤나」가 아니므로, 느슨한 쪽이 재는 대상과 맞다. */
function 언급했나(보고서, rel) {
  const 이름 = rel.split('/').pop();
  return 보고서.includes(rel) || (이름.length >= 4 && 보고서.includes(이름));
}

/**
 * 보고서 대조. 반환 `{판정, 언급, 미언급, 과녁}` — `판정` = '돌았다'|'미실행'|'대상없음'|'못잼'.
 */
function 대조(보고서, root = ROOT) {
  const 목록 = 과녁(root);
  if (목록 === null) return { 판정: '못잼', 언급: [], 미언급: [], 과녁: null };
  if (!목록.length) return { 판정: '대상없음', 언급: [], 미언급: [], 과녁: [] };
  const 언급 = 목록.filter((f) => 언급했나(String(보고서 || ''), f));
  return {
    판정: 언급.length ? '돌았다' : '미실행',
    언급, 미언급: 목록.filter((f) => !언급.includes(f)), 과녁: 목록,
  };
}

module.exports = { 과녁, 대조, 언급했나, 코드 };

if (require.main === module) {
  const argv = process.argv.slice(2);
  const i = argv.indexOf('--대조');
  /* 이음매가 켜져 있으면 **판정보다 먼저** 말한다 — 이 줄이 없으면 고정 과녁으로 낸 초록이
   * 실측처럼 보이고, 그게 이 도구가 없애려던 모양 그 자체다(미실행이 통과와 같은 모양). */
  if (process.env.SYNK_REVIEW_TARGETS !== undefined) {
    process.stdout.write('⚠ [보안검토과녁] `SYNK_REVIEW_TARGETS` 로 과녁이 **고정됐다** — 실측이 아니다(테스트 이음매).\n');
  }

  if (i < 0) {
    const 목록 = 과녁();
    if (목록 === null) {
      process.stdout.write('[보안검토과녁] 과녁을 **못 쟀다**(git 실패·clasp 프로젝트 목록 못 읽음) — 「대상 0건」이 아니다.\n'
        + '   이 상태로 /security-review 를 부르면 그 결과가 내 것인지 알 방법이 없다(F306).\n');
      process.exit(코드.못잼);
    }
    if (!목록.length) {
      process.stdout.write('[보안검토과녁] 미커밋 배포 파일 **0건** — 이 배포가 라이브에 새로 내보낼 바이트가 없다.\n'
        + '   판단 층 검토의 대상이 없다는 뜻이다(미실행이 아니다). 다른 게이트는 그대로 지난다.\n');
      process.exit(코드.통과);
    }
    process.stdout.write(`[보안검토과녁] 검토 대상 ${목록.length}건 — 브랜치 추론에 안 맡기고 **명시로** 넘긴다(F306):\n`
      + 목록.map((f) => `   · ${f}`).join('\n')
      + '\n\n   채팅에 `/security-review` 를 부를 때 이 목록을 **함께 준다**:\n'
      + `   > 아래 ${목록.length}개 파일의 미커밋 변경만 검토한다 — ${목록.join(' · ')}\n`
      + '\n   받은 보고서는 스크래치패드에 저장하고 대조한다(그래야 0건과 미실행이 갈린다):\n'
      + '   node tools/보안검토과녁.js --대조 <보고서 경로>\n');
    process.exit(코드.통과);
  }

  const 경로 = argv[i + 1];
  if (!경로) { process.stderr.write('[보안검토과녁] 보고서 경로를 달라: --대조 <파일 | ->\n'); process.exit(1); }
  let 본문;
  try {
    본문 = 경로 === '-' ? fs.readFileSync(0, 'utf8') : fs.readFileSync(경로, 'utf8');
  } catch (e) {
    /* 보고서를 못 읽은 것을 「미실행」으로도 「통과」로도 접지 않는다 — 그건 판정 불가다. */
    process.stderr.write(`[보안검토과녁] 보고서를 못 읽었다(${e.code || e.message}) — 판정 불가다.\n`);
    process.exit(코드.못잼);
  }

  const r = 대조(본문);
  if (r.판정 === '못잼') {
    process.stdout.write('[보안검토과녁] 과녁을 **못 쟀다** — 보고서가 내 것을 봤는지 판정할 수 없다(「통과」가 아니다).\n');
    process.exit(코드.못잼);
  }
  if (r.판정 === '대상없음') {
    process.stdout.write('[보안검토과녁] 미커밋 배포 파일 0건 — 대조할 것이 없다(미실행이 아니다).\n');
    process.exit(코드.통과);
  }
  if (r.판정 === '미실행') {
    process.stdout.write(`🔴 [보안검토과녁] 보고서가 내 배포집합 파일을 **한 건도 언급하지 않았다** (과녁 ${r.과녁.length}건):\n`
      + r.과녁.map((f) => `   · ${f}`).join('\n')
      + '\n→ 이것은 「취약점 0건」이 아니라 **미실행**이다 — 그 통로는 브랜치 추론으로 대상을 잡아\n'
      + '   남의 커밋을 읽었을 수 있다(F306 실사고 그대로). 배포 보고에 「보안 검토 통과」라고 적지 않는다.\n'
      + '   → 위 목록을 명시로 주고 다시 부른다: node tools/보안검토과녁.js\n');
    process.exit(코드.미실행);
  }
  process.stdout.write(`[보안검토과녁] 보고서가 배포집합 ${r.언급.length}/${r.과녁.length}건을 언급했다 — **내 것을 봤다**.\n`
    + (r.미언급.length
      ? `   ⚠ 안 언급된 ${r.미언급.length}건: ${r.미언급.join(' · ')}\n`
        + '      (언급 0 이 아니므로 미실행은 아니다 — 다만 이 도구가 재는 것은 «봤나»까지다. 그 파일들이\n'
        + '       지적이 없어서 빠진 것인지 안 읽혀서 빠진 것인지는 이 층이 못 가른다.)\n'
      : ''));
  process.exit(코드.통과);
}
