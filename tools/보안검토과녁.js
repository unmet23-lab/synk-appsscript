#!/usr/bin/env node
'use strict';
/* 보안검토 과녁 — `/deploy` 4단계의 판단 층 게이트가 **내 것을 봤는지** 가른다 (마찰 F306)
 *
 * ■ 왜 있나 (2026-08-10 실사고)
 *   `/security-review` 가 **내 변경이 아니라 옆 세션의 문서를 읽고** 판정을 내려 했다.
 *   내 배포 대상은 `Code.js`·`엔진_두뇌.js`·`상담AI.js` 의 미커밋 리터럴 3줄이었는데, 스킬이
 *   넘긴 DIFF CONTENT 본문에는 그 셋이 **한 줄도 없었고** 대신 세션 `local_ed0a2064` 가 방금
 *   커밋한 인계문·보드 마크다운 5벌이 들어 있었다. 원인: 그 통로가 「브랜치가 origin 보다 앞선
 *   커밋」을 diff 대상으로 잡는데, 나는 앞선 트랙을 이미 push 했고 그 사이 남이 3커밋을 얹어
 *   **「내 앞선 커밋 = 남의 것」**이 됐다. 정작 내 배포 대상은 unstaged 라 본문 밖이었다.
 *   `git status` 절에는 내 파일이 보이므로 **겉보기엔 정상 실행**이다.
 *
 * ■ 왜 위험한가
 *   기계 검사(`deploy-security-check.js`)는 아는 패턴만 본다. **처음 보는 결함을 보는 층은
 *   여기뿐**이다. 남의 문서를 읽고 「취약점 없음」이 나오면 나는 그것을 내 코드의 보안 검토
 *   통과로 기록한다 — **미실행이 통과와 같은 모양으로 오는** F207 계열이고, 새는 방향은 언제나
 *   「통과」다. 세션이 10개 도는 시간대엔 우연이 아니라 상시 조건이다.
 *   2026-08-10 은 리터럴 3줄이라 실해가 0이었지만, 그건 운이지 장치가 아니다.
 *
 * ■ 무엇을 하나 — 신고문의 처방 후보 둘, 그대로
 *   ① **과녁을 명시로 넘긴다**(브랜치 추론에 안 맡긴다):  node tools/보안검토과녁.js
 *      과녁 = **두 갈래의 합집합**이다(F449 갈래 · #Q82 · 2026-08-15 에 ㉡을 얹었다):
 *        ㉠ 배포집합 ∩ **미커밋**        — `clasp push` 가 실어 나갈 «아직 git 에 없는» 바이트
 *        ㉡ 배포집합 ∩ **안 나간 변경**  — 커밋은 됐는데 «아직 라이브에 없는» 바이트
 *   ② **보고서가 그 과녁을 실제로 언급했는지 대조한다**:  node tools/보안검토과녁.js --대조 <파일>
 *      하나도 안 언급했으면 **「미실행」**으로 적는다 — 0건과 미실행을 가르는 자리다.
 *
 * ■ 🔴 왜 ㉡ 을 얹었나 (2026-08-15 실측 · F449 에서 갈라져 나온 #Q82)
 *   옛 판의 과녁은 ㉠ 뿐이라, **고쳐서 커밋해 두고 배포 전에 끊긴** 배포에서는 과녁이 0건으로
 *   나왔다. 그런데 도구는 거기서 멈추지 않고 「이 배포가 라이브에 새로 내보낼 바이트가 없다」고
 *   **단언**했다 — 재지 않은 축(HEAD Δ 라이브)에 대한 주장이라 거짓이고, 받아 적으면 그대로
 *   「검토 대상 없음 = 통과」로 배포 기록에 남는다. 처음 보는 결함을 보는 층은 여기뿐인데(위 ■)
 *   그 자리가 0이면 그 배포는 판단 층이 **안 돈** 것이다.
 *   ⚠ 드문 조건이 아니다: F444(Stop 훅 자동커밋이 트랙을 쪼갠다)·F447(`/close` 가 죽음 도장을
 *   안 찍는다)·컨텍스트 인계 — 커밋과 배포 사이가 끊기는 것은 이 저장소의 상시 동선이고,
 *   **끊긴 뒤 이어받은 세션에게는 과녁이 언제나 0건으로 보였다**(고칠 것을 커밋해 둔 것이 오히려
 *   검토를 끄는 조건이 된다). 실측: `694497ad` 를 라이브로 옮기는 배포에서 과녁 0건이 나왔고
 *   실제 델타는 `엔진_셋업확장.js` 1파일(24+/2−)이었다 — 그 세션은 손으로 계산해 우회했다.
 *
 * ■ 새는 방향을 못박는다
 *   · **못 잼은 0건이 아니다**(F207). git 을 못 부르거나 배포집합을 못 읽으면 `null` 이고,
 *     CLI 는 종료 코드 **2**(판정 불가)로 낸다 — 통과(0)로도 미실행(3)으로도 접지 않는다.
 *     ㉡ 의 기준선(`Code.js` 의 채번 줄)이 없어도 **못 잼**이다 — 한 갈래라도 모르면 전체가 모름이고,
 *     ㉠ 만 세어 「이게 전부」라고 적으면 그게 이 트랙이 고치려는 병 그 자체다.
 *   · **과녁 0건**은 미실행이 아니다. 두 갈래가 **둘 다 0**이면 대조할 것 자체가 없다 — 그 사실을
 *     말하고 0 으로 끝낸다. 여기서 「미실행」을 내면 정상 배포가 상시 막히고, 막힌 처방은 우회를
 *     정상 통로로 만든다(F103).
 *   · ⚠ **㉡ 의 기준선은 둘 중 하나다** — 어느 쪽인지 출력에 **글자로** 낸다(F474 · 2026-08-15):
 *     ㄱ **라이브 실측 판** — rot-check 이 바이트로 재서 도장에 남긴 「라이브가 서 있는 판」.
 *        이건 잰 축이라 0 을 그대로 읽어도 된다(그 뒤에 남이 배포했으면 넓게 나올 뿐 · 싼 쪽).
 *     ㄴ **마지막 채번 커밋** — 도장이 없거나 못 믿을 때. **간접 증거다**(F244): 「채번보다
 *        저장소가 앞섰다」를 볼 뿐 「그 채번이 라이브에 닿았나」는 원리상 못 가른다 — 0건을
 *        「라이브와 같다」로 **번역하지 않는다**(옛 판이 정확히 그 번역을 했다).
 *     🔴 ㄴ 에서 나온 0 을 **무한정으로 단언한 것**이 F474 다: 정상 순서가 채번→커밋→push→clasp 라
 *        끊기는 자리는 거의 언제나 채번 «뒤»이고, 그때 기준선은 페이로드 자신이 되어 자기 diff 를
 *        과녁 밖으로 떨군다. 실측: 라이브 v9.237 · HEAD v9.239 에서 도구는 0건, 참값은 5파일.
 *        ⇒ ㄴ 일 때는 첫 줄에 「**이 기준선으로는**」을 붙이고 따를 수 있는 처방을 함께 준다(F103).
 *   · ⚠ **삭제는 두 갈래 다 못 본다** — 과녁을 `배포집합`(디스크 훑기)과 교집합하기 때문이다.
 *     없는 파일은 검토할 수도 없다(그 형태는 라이브 대조의 저장소없음 갈래가 잡는다).
 *   · **판정은 언급 여부까지다.** 보고서가 내 파일을 「봤다」는 것과 「제대로 봤다」는 다르다 —
 *     이 도구는 앞의 것만 잰다. 재는 것을 넘겨 말하면 그 초록이 또 다른 미실행을 덮는다.
 *
 * ■ 왜 파일로 받나
 *   보고서는 여러 줄이고 백틱·경로가 섞인다 — 셸 인용으로 넘기면 그 자체가 사고다
 *   (`shell-inline-guard` 가 막는 형태). 스크래치패드에 쓰고 경로를 준다. `-` 면 stdin.
 *
 * 쓰는 법
 *   node tools/보안검토과녁.js                 과녁 목록 + `/security-review` 에 붙일 문장
 *   node tools/보안검토과녁.js --대조 <경로>    보고서 대조 (0 돌았다 · 2 못 쟀다 · 3 미실행)
 *   node tools/보안검토과녁.js --대조 -         같은 것을 stdin 으로
 */

const fs = require('fs');
const path = require('path');

const ROOT = process.env.SYNK_REVIEW_ROOT || path.resolve(__dirname, '..');
const 점검 = require(path.join(__dirname, '배포판점검.js'));
const { 인자게이트 } = require(path.join(__dirname, 'lib', '인자게이트.js'));

/* 종료 코드는 **계약**이다 — 글자로 가르지 않는다(문구를 다듬는 순간 판정이 갈라진다).
 * board-move 가 6 을 판 것과 같은 이유다(그쪽 머리말). */
const 코드 = { 통과: 0, 못잼: 2, 미실행: 3 };

/* 테스트 이음매 — 급소(미실행 판정)를 CLI 끝까지 태우려면 과녁을 고정할 손잡이가 필요하다.
 * 실저장소의 미커밋은 옆 세션이 상시 바꾸므로 그걸로 재면 검사가 그날 운에 걸린다.
 * 🔑 **켜지면 스스로 밝힌다**(아래 CLI 가 한 줄 낸다) — 조용한 이음매는 곧 우회다. */
const 고정과녁 = () => (process.env.SYNK_REVIEW_TARGETS || '').split(',').map((s) => s.trim()).filter(Boolean);

/**
 * 지금 배포가 라이브로 새로 내보낼 파일들 — **㉠미커밋 ∪ ㉡안 나간 변경**(머리말 ■).
 *
 * 반환 `{목록, 미커밋, 안나간, 가라앉힘, 기준}` · `null` = **못 쟀다**. 「0건」과 다르다.
 *   · `목록` = 합집합(정렬) — 부르는 쪽이 쓰는 값
 *   · `미커밋`·`안나간` = 갈래별 목록. **0을 분모와 함께 읽으려고** 따로 돌려준다(F207·보고 규약):
 *     합집합 0 이 「둘 다 0」인지 「한 갈래를 안 쟀다」인지 부르는 쪽이 가를 수 있어야 한다.
 *   · `가라앉힘` = ㉡ 중 라이브 실측 도장이 「바이트 동일」로 재운 것. 과녁에는 **안 넣되**
 *     구조로 돌려준다 — 조용히 지우면 부르는 쪽이 「이게 전부」로 읽는다(그 함수 머리말과 같은 이유).
 *   · `기준` = ㉡ 의 기준선 `{배포커밋, 제목, 커밋수}`. 「무엇에 견줘 앞섰나」를 말할 재료다.
 *
 * `모듈` 인자는 **회귀 픽스처의 이음매**다 — `claspProjects()` 가 자기 ROOT 고정이라 `root` 만으로는
 * 「배포 파일이 실제로 있는」 판을 못 세우고, 그러면 탐지력을 실저장소로만 잴 수 있다(가드 맹점 ②
 * — CI 에선 그게 곧 「자격증명이 없어서 초록」이다 · F296). ⚠ env 이음매와 달리 **CLI 로는 못 켠다**
 * — 우회 경로가 아니라 밝힐 것이 없다(`SYNK_REVIEW_TARGETS` 만 스스로 밝힌다).
 */
function 과녁상세(root = ROOT, 모듈 = 점검) {
  if (process.env.SYNK_REVIEW_TARGETS !== undefined) {
    const 고정 = 고정과녁();
    return { 목록: 고정, 미커밋: 고정, 안나간: [], 가라앉힘: [], 기준: null };
  }
  /* ⚠ `claspProjects()` 는 **인자를 안 받는다**(자기 모듈의 ROOT 를 본다) — 그래서 `root` 가
   *   실제로 갈아 끼우는 것은 **git 층**(`미커밋집합`·`안나간변경`)이다. */
  let 프로젝트들;
  try { 프로젝트들 = 모듈.claspProjects(); } catch (_) { return null; }
  if (!Array.isArray(프로젝트들) || !프로젝트들.length) return null;

  /* ㉠ 아직 git 에 없는 바이트 */
  const 미커밋 = new Set();
  for (const p of 프로젝트들) {
    let 것들;
    try { 것들 = 모듈.배포집합미커밋(p, root); } catch (_) { return null; }
    if (것들 === null) return null;        // 못 잼은 전파한다 — 한 갈래라도 모르면 전체가 모름
    for (const f of 것들) 미커밋.add(f);
  }

  /* ㉡ 커밋은 됐는데 아직 라이브에 없는 바이트.
   * 프로젝트 목록을 **넘겨준다** — 안 넘기면 그쪽이 `claspProjects()` 를 다시 부르고, 그러면
   * 같은 판정이 두 갈래로 갈린다(CLAUDE.md — 목록은 하나에서 파생). */
  let 안나간판;
  try { 안나간판 = 모듈.안나간변경(root, 프로젝트들); } catch (_) { return null; }
  if (안나간판 === null) return null;                 // git 을 못 불렀다
  if (안나간판.배포커밋 === null) return null;        // 기준선이 없다 = ㉡ 을 못 잰다(0건이 아니다)

  /* `안나간변경` 은 `git diff --name-only` 라 **삭제된 경로도** 낸다. 배포집합(디스크 훑기)과
   * 교집합해 떨군다 — 없는 파일은 검토 과녁이 될 수 없고, 「과녁 ⊆ 배포집합」 불변식도 여기서 산다. */
  const 배포전체 = new Set();
  for (const p of 프로젝트들) {
    try { for (const f of 모듈.배포집합(p, root)) 배포전체.add(f); } catch (_) { return null; }
  }
  const 안나간 = new Set();
  for (const 항 of 안나간판.프로젝트들 || []) {
    for (const f of 항.파일들 || []) if (배포전체.has(f)) 안나간.add(f);
  }
  const 가라앉힘 = [];
  for (const 항 of 안나간판.가라앉힘 || []) {
    for (const f of 항.파일들 || []) if (배포전체.has(f)) 가라앉힘.push(f);
  }

  /* ㉡ 이 **무엇에 견줘** 앞섰는지를 갈래로 낸다(F474) — 옛 판은 언제나 「마지막 채번」이라고
   * 적었고, 그 기준선이 곧 페이로드 자신인 자리에서 0건이 나왔다. 라이브 실측 판으로 갈아낀
   * 날에도 같은 문장이 나오면 **갈아낀 사실이 어디에도 안 보인다** — 0 의 분모는 갈래마다 다르다. */
  const 기준선 = Array.isArray(안나간판.기준선) ? 안나간판.기준선 : [];
  const 라이브들 = 기준선.filter((b) => b && b.종류 === '라이브실측');
  const 종류 = !기준선.length ? '채번'
    : 라이브들.length === 기준선.length ? '라이브실측'
      : 라이브들.length ? '섞임' : '채번';

  const 목록 = [...new Set([...미커밋, ...안나간])].sort();
  return {
    목록,
    미커밋: [...미커밋].sort(),
    안나간: [...안나간].sort(),
    가라앉힘: [...new Set(가라앉힘)].sort(),
    기준: {
      배포커밋: 안나간판.배포커밋,
      제목: 안나간판.제목 || '',
      커밋수: 안나간판.커밋수 || 0,
      종류,
      기준선,
      잰때: (라이브들[0] && 라이브들[0].잰때) || null,
    },
  };
}

/** 합집합 목록만. `null` = 못 쟀다. (옛 호출부·회귀가 쓰는 모양 그대로 남긴다.) */
function 과녁(root = ROOT, 모듈 = 점검) {
  const r = 과녁상세(root, 모듈);
  return r === null ? null : r.목록;
}

/* 보고서가 그 파일을 말했는가 — **경로 전체**와 **파일 이름** 둘 다 받는다.
 * 보고서는 `Code.js` 처럼 이름만 쓰기도 하고 `docs/…/Code.js` 처럼 경로로 쓰기도 한다.
 * ⚠ 이름만 매칭하는 쪽이 느슨하지만, 여기서 좁게 틀리면 **정상 검토가 「미실행」으로** 나오고
 *   그 거짓 적색은 배포를 막는다 — 막힌 처방은 우회를 부른다(F103). 이 도구가 재는 것은
 *   「엉뚱한 것을 봤나」이지 「얼마나 꼼꼼히 봤나」가 아니므로, 느슨한 쪽이 재는 대상과 맞다. */
function 언급했나(보고서, rel) {
  const 이름 = rel.split('/').pop();
  return 보고서.includes(rel) || (이름.length >= 4 && 보고서.includes(이름));
}

/**
 * 보고서 대조. 반환 `{판정, 언급, 미언급, 과녁}` — `판정` = '돌았다'|'미실행'|'대상없음'|'못잼'.
 */
function 대조(보고서, root = ROOT, 모듈 = 점검) {
  const 상세 = 과녁상세(root, 모듈);
  if (상세 === null) return { 판정: '못잼', 언급: [], 미언급: [], 과녁: null, 상세: null };
  const 목록 = 상세.목록;
  if (!목록.length) return { 판정: '대상없음', 언급: [], 미언급: [], 과녁: [], 상세 };
  const 언급 = 목록.filter((f) => 언급했나(String(보고서 || ''), f));
  return {
    판정: 언급.length ? '돌았다' : '미실행',
    언급, 미언급: 목록.filter((f) => !언급.includes(f)), 과녁: 목록, 상세,
  };
}

/* ── 사람이 읽는 문장 (순수 함수) ────────────────────────────────────────────
 * CLI 안에 두면 탐지력을 **실저장소 상태에 걸어야만** 잴 수 있다 — 과녁이 0건인 판을 연출할 수
 * 없으니 검사가 「지금 0건이면 본다」로 물러나고, 그러면 대개 그냥 지나간다(안 재고 초록).
 * F474 가 난 자리가 바로 이 문장들이므로 여기만은 픽스처가 진다(가드 맹점 ②). */

const 날짜 = (ms) => { try { return new Date(ms).toISOString().slice(0, 16).replace('T', ' '); } catch (_) { return '시각 모름'; } };

/** 기준선 **한 항목**을 사람이 읽는 조각으로 — `기준선:[{이름,종류,sha}]` 의 한 칸.
 *
 * 🔑 **기준선을 글자로 만드는 자리는 이 함수 하나다**(F608 · 2026-08-18). 왜 하나여야 하나:
 *   F474 를 고칠 때 요약줄(`기준표기`)은 갈래를 따라 갈라 냈는데, `/security-review` 에
 *   **붙여넣으라고 주는 블록**은 CLI 안에 남아 자기 문장을 따로 적었다. 그래서 같은 실행에서
 *   요약줄은 「(루트)=라이브 `600741b9`」라 하고 붙임 블록은 「마지막 채번 `bbd6477`」을 박아 냈다.
 *   `bbd64770` 은 HEAD 의 **조상**이라 배포집합 diff 가 **0줄**이고, `/deploy` 4단계는 그 블록을
 *   「그대로 붙여」라고 지시한다 — **지시를 지킬수록 검토가 빈 과녁을 받는다.** 새는 방향은 언제나
 *   「통과」다(검토자는 「변경 없음 = 볼 것 없음」을 내고, 그 0건이 「취약점 0건」의 얼굴로 남는다).
 *   같은 판정을 두 곳에 적으면 갈라진다 — 그래서 재료를 늘리는 게 아니라 **한 곳에서 파생**시킨다.
 *
 * ⚠ 채번 sha 를 7자로 자르는 것은 `안나간변경` 의 `배포커밋`(= `sha.slice(0,7)`)과 **같은 글자**를
 *   내려는 것이다. 자릿수가 갈리면 사람 눈엔 다른 커밋으로 보이고, 그 순간 이 함수가 없앤 갈라짐이
 *   자릿수 층에서 되살아난다. */
function 기준조각(b) {
  if (!b || !b.sha) return '';
  return b.종류 === '라이브실측'
    ? `**라이브 실측 판** \`${String(b.sha).slice(0, 8)}\``
    : `마지막 채번 \`${String(b.sha).slice(0, 7)}\``;
}

/** 기준선 **전체**를 「무엇에 견줬나」 한 덩이로. 요약줄과 붙임 블록이 **둘 다 이것**을 쓴다(F608).
 *
 * · 프로젝트가 몇이든 **견준 판이 하나면** 한 번만 말한다(이름을 붙이면 읽는 사람이 두 판이라 읽는다).
 * · 갈리면 **전부** 이름과 함께 낸다 — 옛 섞임 표기는 채번 쪽을 `crewcard=채번` 이라고만 적어
 *   **sha 를 아예 안 냈다**. 그러면 그 프로젝트의 diff 를 무엇에 견줬는지 되짚을 재료가 없다.
 * · 빈 문자열 = **기준선을 못 냈다.** 부르는 쪽은 그것을 「기준선 없음」으로 적을 뿐, 아무 sha 도
 *   대신 끼워 넣지 않는다(모름을 값으로 접는 것이 이 파일이 통째로 막으려는 병이다). */
function 견줌문(기준선) {
  const 목록 = (Array.isArray(기준선) ? 기준선 : []).filter((b) => b && b.sha);
  if (!목록.length) return '';
  const 조각들 = [...new Set(목록.map(기준조각))];
  if (조각들.length === 1) return 조각들[0];
  return `프로젝트마다 다르다 — ${목록.map((b) => `${b.이름}=${기준조각(b)}`).join(' · ')}`;
}

/* 기준선을 **글자로 낸다**(F474) — 0 의 분모는 「몇 갈래를 셌나」만이 아니라 「무엇에 견줬나」다.
 * 옛 판은 갈래와 무관하게 언제나 「마지막 채번」이라 적었고, 그래서 채번 «뒤»에 배포가 끊겨
 * 기준선이 페이로드 자신이 된 자리에서도 같은 문장이 나왔다 — 읽는 사람에겐 좋은 0 이었다.
 * 🔑 sha 는 `견줌문` 에서만 온다 — 여기서 따로 뽑으면 F608 이 자리만 옮겨 되살아난다. */
function 기준표기(s) {
  if (!s.기준) return ' (과녁 고정 이음매)';
  const 글 = 견줌문(s.기준.기준선);
  if (!글) return ` (기준 = **기준선을 못 냈다** — 무엇에 견줘 0인지 이 출력으로는 못 되짚는다)`;
  if (s.기준.종류 === '라이브실측') return ` (기준 = ${글} · ${날짜(s.기준.잰때)} 에 바이트로 쟀다)`;
  if (s.기준.종류 === '섞임') return ` (기준 = ${글})`;
  return ` (기준 = ${글} · 그 뒤 커밋 ${s.기준.커밋수}개)`;
}

/* 0 은 **분모와 함께** 낸다(유호 확정 08-14) — 「좋은 0」과 「안 재봤다」가 여기서 갈린다. */
const 분모줄 = (s) => `   합계 **${s.목록.length}건 = 미커밋 ${s.미커밋.length} + 안 나간 변경 ${s.안나간.length}**`
