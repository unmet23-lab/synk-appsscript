function 등록부() {
  const s = fs.readFileSync(굽기길, 'utf8');
  const a = s.indexOf('형태들 = {');
  const b = s.indexOf('if 형태 not in 형태들');
  if (a < 0 || b < 0) { console.error('🔴 등록부를 못 찾았다 — 요소굽기.py 가 바뀌었나'); process.exit(2); }
  return new Set([...s.slice(a, b).matchAll(/'([^']+)':/g)].map((m) => m[1]));
}

function 사전줄들() {
  const 줄들 = fs.readFileSync(사전길, 'utf8').split('\n');
  const 낸다 = [];
  let 절 = null;
  for (const 줄 of 줄들) {
    if (줄.startsWith('## ')) 절 = null;                 // ⚠절을 안 끊으면 §2~§4 의 표까지 빨려든다
    const m = /^### (1-[a-d])\./.exec(줄);
    if (m) [, 절] = m;
    if (!절 || !줄.startsWith('| ') ||줄.startsWith('| ---')) continue;
    const 칸 = 줄.replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
    if (칸[0] === '부품') continue;
    낸다.push({ 절, 이름: 칸[0], 실물: 칸[1] || '' });
  }
  return 낸다;
}

function main() {
  const 있는것 = 등록부();
  const 줄 = 사전줄들();
  const 없음 = []; const 모름 = [];
  for (const r of 줄) {
    if (!(r.이름 in 대응)) { 모름.push(r); continue; }
    const 형 = 대응[r.이름];
    if (형 !== null && !있는것.has(형)) 없음.push({ ...r, 형 });
  }
  if (!조용) {
    console.log(`■ 부품 대조 — 사전 줄 ${줄.length} · 등록부 형태 ${있는것.size}`);
    console.log(`  실물 있음 ${줄.length - 없음.length - 모름.length} · 없음 ${없음.length} · 대응표에 없는 줄 ${모름.length}`);
    for (const r of 없음) console.log(`  🔴 실물 없음  ${r.절}  ${r.이름}  → 형태 「${r.형}」 이 등록부에 없다`);
    for (const r of 모름) console.log(`  ⚠모르는 줄  ${r.절}  ${r.이름}  → tools/부품대조.js 의 대응표에 한 줄 더한다`);
  }
  if (없음.length || 모름.length) {
    console.log(`🔴 사전과 실물이 어긋났다 — 없음 ${없음.length} · 모르는 줄 ${모름.length}`);
    process.exit(1);
  }
  console.log('✅ 사전의 부품 줄이 전부 실물을 가진다.');
  return 0;
}

