# 몽글 친구 굽기 — «밤의 드래곤» 친구 시안 (유호 지시 08-25 「투슬리스처럼 생긴 몽글이 친구」).
#
#   저작권 선: 투슬리스(드림웍스) 복제가 아니라 **그 인상의 킷 번역**이다 —
#   짙은 잉크 펠트 몸 · 큰 초록 구슬 눈 · 귀 돌기 · 접은 날개 · 꼬리 지느러미.
#   서사도 번역한다: 꼬리 지느러미 한쪽은 **몽글이가 코랄 펠트로 기워 준 것**(Stitch 실땀 테두리) —
#   「부족한 반쪽을 친구가 채운다」를 SYNK 공방 문법(바느질)으로 말한다. 이름은 유호님 몫.
#
#   재질·조명·무대·렌더는 tools/요소굽기.py 정본이 쥔다(NPC세트굽기와 같은 앵커 치환 통로).
#   ⚠어두운 몸(Ink)이라 받침은 **밝은 천(Oat)** — 오브 명품판 ③ 「어두운 염료 → 다린천」 규칙.
#     Ink Deep 은 몸색으로 안 쓴다: 알베도 0.002 라 결이 통째로 죽는다(김 실측 08-22).
#
#   호출: blender --background --python tools/몽글친구굽기.py -- 출력=... [몸색=Ink] [눈색=Meadow]
#         [지느러미색=Coral] [너비=1024] [비율=1.0]
import sys, os

_인자 = {k: v for k, v in (a.split('=', 1) for a in sys.argv[sys.argv.index('--') + 1:])} if '--' in sys.argv else {}
REPO = _인자.get('저장소') or (
    os.path.dirname(os.path.dirname(os.path.abspath(globals()['__file__'])))
    if '__file__' in globals() else os.getcwd())

원문 = open(os.path.join(REPO, 'tools', '요소굽기.py'), encoding='utf-8').read()
앵커 = '카메라위치, 카메라피치 = 형태들[형태]()'
assert 원문.count(앵커) == 1, '요소굽기 실행부 앵커가 바뀌었다 — 이 시안 통로를 다시 맞춘다'
본문 = 원문.replace(앵커, '카메라위치, 카메라피치 = 친구시안()')

ns = {}

def _시안(bpy, math, random, g):
    """g = 요소굽기 전역(부품 창고)."""
    import mathutils
    베개몸, 짧은퍼 = g['베개몸'], g['짧은퍼']
    살재질, 털재질, 매끈재질 = g['살재질'], g['털재질'], g['매끈재질']
    직물결, 땀하나 = g['직물결'], g['땀하나']
    색 = g['색']

    몸색 = _인자.get('몸색', 'Ink')
    눈색 = _인자.get('눈색', 'Meadow')
    지느러미색 = _인자.get('지느러미색', 'Coral')
    # «품질=조율» — 형태 확인 회전용. 자식 털을 절반으로 줄여 GPU 메모리에 들어가게 한다.
    #   v1 실측: 정본값(자식 70)으로 총 470만 가닥 → Arc B390 OOM → CPU 되물림 41분.
    #   최종판은 이 인자 없이(정본 그대로) 굽는다 — 조율판을 정본으로 삼지 않는다.
    조율판 = _인자.get('품질', '') == '조율'

    실땀재 = 매끈재질('실땀', 색['Stitch'], 거칠기=0.5)
    눈구슬재 = 매끈재질('눈구슬', 색[눈색], 거칠기=0.15, 반사=0.2)   # 몽글 정본 문법 — 또렷한 것은 «광 나는 구슬»
    동공재 = 매끈재질('동공', 색['Ink Deep'], 거칠기=0.15, 반사=0.2)

    def 받침천판():
        """밤천판의 밝은 판 — 어두운 몸이 앉는 Oat 천(오브 명품판 ③ 규칙).
        v1 실측: 반높 1.72 는 당긴 카메라(7.5)에서 위 모서리가 무대 검정으로 새어 나왔다 — 키운다."""
        판 = 베개몸((2.6, 0.14, 2.6), 위치=(0, 0.95, 0.5), 크리스=0.34, 레벨=3)
        판.data.materials.append(직물결(매끈재질('받침천', 색['Oat'], 거칠기=0.96), 지름=5.2))
        return 판

    def 구(반경, 위치, 변형=None, 회전=None, 조각=48):
        bpy.ops.mesh.primitive_uv_sphere_add(radius=반경, location=위치, segments=조각, ring_count=조각 // 2)
        o = bpy.context.object
        if 변형:
            # 메시를 직접 편다 — obj.scale 은 퍼·소품 좌표와 어긋난다(NPC 1판 실측)
            o.data.transform(mathutils.Matrix.Diagonal((변형[0], 변형[1], 변형[2], 1.0)))
        if 회전:
            o.rotation_euler = tuple(math.radians(v) for v in 회전)
        bpy.ops.object.shade_smooth()
        return o

    def 스케일굽기(o):
        """오브젝트 스케일을 메시에 굽는다 — v2 실측: 베개몸의 비균등 스케일(예 y=0.06)이
        털 길이를 축별로 찌그러뜨려 날개·지느러미가 «맨살 판»으로 나왔다. 퍼를 심는 베개몸 부품은
        반드시 이걸 거친다(서브서프는 base 메시 위에 걸려 크리스가 그대로 산다)."""
        o.data.transform(mathutils.Matrix.Diagonal((o.scale[0], o.scale[1], o.scale[2], 1.0)))
        o.scale = (1.0, 1.0, 1.0)
        return o

    def 퍼(몸, 라벨, 색이름, 길이, 개수):
        짧은퍼(몸, 라벨, 살재질(라벨, 색[색이름]), 털재질(라벨, 색[색이름]), 길이=길이, 개수=개수)
        ps = 몸.particle_systems[-1].settings
        ps.clump_factor = 0.34            # 오브 명품판 — 성기면 스펀지·솜사탕으로 읽힌다
        ps.roughness_1 = 0.04
        ps.roughness_2 = 0.05
        if 조율판:
            ps.rendered_child_count = ps.child_percent = 35

    def 친구():
        받침천판()

        # ── 몸 — 앉은 자세의 뭉툭한 몸통(몽글이의 돔 문법을 눕힌 것) ─────────────
        몸 = 구(0.60, (0, 0.20, 0.55), 변형=(0.98, 1.06, 0.95))
        퍼(몸, '몸', 몸색, 0.065, 20000)

        # ── 머리 — 넓적하고 큰 둥근 머리(몸보다 큰 머리가 «아기 드래곤»의 비례) ───
        머리 = 구(0.58, (0, -0.12, 1.30), 변형=(1.14, 0.90, 0.84))
        퍼(머리, '머리', 몸색, 0.058, 22000)

        # ── 귀 돌기 — 머리 위 뒤쪽의 둥근 뿔 한 쌍 (v1: 작아서 «곰귀»로 묻혔다 — 키우고 세운다)
        for 부호 in (-1, 1):
            귀 = 구(0.17, (부호 * 0.38, 0.0, 1.80), 변형=(0.90, 0.72, 1.55),
                   회전=(-6, 부호 * 16, 0))
            퍼(귀, '귀' + str(부호), 몸색, 0.038, 2600)

        # ── 눈 — 큰 초록 구슬 + 둥근 동공(경계가 아니라 «호기심» 모드의 눈) ───────
        #   털 길이 0.058 위로 구슬이 떠야 산다(벨 1판 「자수 점은 털에 묻힌다」).
        for 부호 in (-1, 1):
            구(0.15, (부호 * 0.30, -0.56, 1.36), 변형=(1.0, 0.75, 1.0), 조각=32).data.materials.append(눈구슬재)
            구(0.075, (부호 * 0.29, -0.66, 1.36), 조각=32).data.materials.append(동공재)
        # (v3 의 앞발은 뺐다 — 검정 속 검정이라 식별 0. 몽글이도 발이 없다 — 미니멀이 세계관 문법이다.)

        # ── 접은 날개 — 등 뒤 위로 들린 한 쌍 (v4: 둥근 베개몸 끝이 «팔»로 읽혔다 — 끝이 가는 타원)
        for 부호 in (-1, 1):
            날개 = 구(0.17, (부호 * 0.72, 0.34, 1.04), 변형=(2.7, 0.30, 0.95),
                    회전=(0, 부호 * -38, 부호 * -12))
            퍼(날개, '날개' + str(부호), 몸색, 0.035, 4000)

        # ── 꼬리 — 몸 오른쪽으로 감아 바닥에 놓인 사슬 (v4: 끝 연결이 끊겨 보임 — 마디를 촘촘히)
        꼬리 = (((0.66, 0.50, 0.22), 0.19), ((1.04, 0.16, 0.17), 0.16),
               ((1.12, -0.28, 0.14), 0.14), ((1.02, -0.52, 0.13), 0.125),
               ((0.90, -0.66, 0.12), 0.115))
        for i, (자리, r) in enumerate(꼬리):
            마디 = 구(r, 자리)
            퍼(마디, '꼬리' + str(i), 몸색, 0.045, 2200)

        # ── 꼬리 지느러미 — 왼쪽은 제 것(몸색) · 오른쪽은 몽글이가 기워 준 코랄 ────
        #   v3 실측: 퍼 지느러미는 «발광 솜뭉치»로 읽혔다 — **재단한 펠트 시트**(직물결 면)로 간다.
        #   털 몸 사이에 «면»이 있어야 갈린다(도장 목 교훈) + «기워 붙인 패치» 서사와도 맞는 문법.
        끝 = 꼬리[-1][0]
        for 부호, 색이름, 라벨 in ((-1, 몸색, '지느왼'), (1, 지느러미색, '지느오')):
            판 = 스케일굽기(베개몸((0.24, 0.035, 0.13), 위치=(끝[0] - 0.05 + 부호 * 0.29, 끝[1] - 0.10, 0.17),
                      크리스=0.45))
            판.rotation_euler[1] = math.radians(부호 * -24)       # 화면 안에서 V 로 벌어진다
            판.data.materials.append(직물결(매끈재질(라벨, 색[색이름], 거칠기=0.96), 지름=1.0, 세기=0.55))
        # 기운 자국 — 코랄 시트 «윗변 안쪽»의 Stitch 실땀(몽글이 밑단 스티치와 같은 자리 문법).
        #   v5 실측 둘: 땀들이 붙어 «한 줄»이 됐다(땀:빈틈 1:1.5 로 벌린다) · 중앙 띠는 «라벨
        #   줄무늬»로 읽혔다(기운 자국은 가장자리 문법이다 — 윗변에서 살짝 안쪽으로).
        손 = random.Random(20260825)
        판중심x, 판중심z = 끝[0] - 0.05 + 0.29, 0.17
        for i in range(4):
            t = -1.05 + i * 0.7
            땀하나(판중심x + t * 0.14 * math.cos(math.radians(24)) + 손.uniform(-0.003, 0.003),
                  끝[1] - 0.15,
                  판중심z + 0.07 + t * 0.14 * math.sin(math.radians(24)) + 손.uniform(-0.003, 0.003),
                  0.04, 0.014, 실땀재, 회전y=-24 + 손.uniform(-7, 7), 회전z=0)

        # v1: (0,-12.6,1.15)·84° 는 캐릭터가 판 위 절반에 반쪽으로 붙었다 — 당기고 중심을 맞춘다.
        #   85mm·거리 7.5 → 보이는 높이 3.17. 캐릭터 1.95 = 화면 62%(마스코트 정본 컷과 같은 무게).
        return (0, -7.5, 0.98), 90

    return 친구()

def 친구시안():
    return _시안(ns['bpy'], ns['math'], ns['random'], ns)

ns['친구시안'] = 친구시안
ns['__name__'] = '__main__'
exec(compile(본문, os.path.join(REPO, 'tools', '요소굽기.py'), 'exec'), ns)
