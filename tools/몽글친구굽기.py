                #   솟음을 감은 눈의 **2.3배**(0.030→0.070) 주고 폭을 좁혀(0.108→0.094) 세운다.
                #   ✅유호 픽 08-26: 시안 셋(0.044·0.056·0.070) 중 **0.070**. 「높이 차가 표정을 가른다」 —
                #     각도가 아니다. 0.044 는 눈감음과 너무 닮아 다시 헷갈리고, 0.070 이라야 «낮고 넓은
                #     호 = 감은 눈 / 높고 좁은 호 = 웃는 눈»이 한눈에 갈린다. 손잡이는 시안용으로 남긴다.
