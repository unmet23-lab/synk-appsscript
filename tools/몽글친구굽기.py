        #     (가운데 0 · 오른쪽·아래가 +1), 셋째 수만 월드 깊이다.
        화면반 = 18.0 / 85.0        # 85mm · 센서 36mm — 깊이 y 에서 보이는 반폭 = 이 값 × (y + 7.5)
