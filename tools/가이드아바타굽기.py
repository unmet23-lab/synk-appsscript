# -*- coding: utf-8 -*-
"""가이드 아바타 굽기 — 학생 홈 「우리」 카드의 40px 원형 얼굴을 만든다.

왜 «따로» 굽나: 정본 컷(1024²)은 몸이 가운데 작게 앉고 여백이 넓다.
그걸 40px 원형에 `object-fit:cover` 로 넣으면 얼굴이 점이 된다 —
학생이 매일 보는 유일한 가이드 얼굴이 알아볼 수 없는 얼룩이 되는 자리다.
그래서 알파(또는 배경 대비)로 몸을 찾아 **꽉 차게 잘라** 굽는다.

정본 경로는 손으로 안 적는다 — `tools/lib/마스코트자산.js` 가 주인이고
여기서는 그 모듈을 node 로 물어본다(주인이 둘이 되면 마스코트 10벌 사고가 재현된다).

바탕: 킷 Paper(#FBF7F0) — 카드 배경과 같은 색이라 원형이 카드에 자연스레 앉고,
      브랜드렌더린트 「허용바닥」 넷에 들어 있다(코랄 몸이 코랄 면에서 뭉개지는 것을 피한다).

쓰기: python tools/가이드아바타굽기.py          40px 원형용 256 판 + 배포 160 판
      python tools/가이드아바타굽기.py --크게   인쇄물·큰 화면용 1024 판
      ⚠ --크게 는 «통신»이 필요하다(남의 기계에 4배를 맡긴다). 기본 굽기는 안 그렇다.
"""
import json
import subprocess
import sys
from pathlib import Path

from PIL import Image
import numpy as np

루트 = Path(__file__).resolve().parent.parent
날것 = 루트 / 'docs' / '캐릭터' / '가이드_아바타'
크기 = 256          # 저장소 정본 — 다른 지면(필름스트립·연재)에서 더 크게 쓸 여유
배포크기 = 160      # 드라이브로 나가는 판 — 표시 40px 의 4배(고밀도 화면까지 덮는다)
큰크기 = 1024       # 큰 판 — 인쇄물·큰 화면. 40px 원형과 달리 «자세히 보는» 자리다
여백 = 0.06         # 몸 bbox 바깥으로 두는 숨 — 원형에 잘려도 몸이 안 닿게
바탕 = (251, 247, 240)   # 킷 Paper #FBF7F0


def 정본경로(표현: str) -> Path:
    """마스코트자산 모듈에 «어느 파일인가»를 묻는다 — 경로를 여기 적지 않는다."""
    js = ("const a=require('./tools/lib/마스코트자산.js');"
          f"process.stdout.write(a.{표현});")
    out = subprocess.run([r'C:\Program Files\nodejs\node.exe', '-e', js],
                         cwd=str(루트), capture_output=True, text=True, encoding='utf-8')
    if out.returncode != 0:
        raise SystemExit(f'마스코트자산 모듈이 경로를 안 준다: {out.stderr.strip()}')
    p = 루트 / out.stdout.strip()
    if not p.exists():
        raise SystemExit(f'모듈이 준 경로에 파일이 없다: {p}')
    return p


def 몸마스크(im: Image.Image):
    """몸이 있는 픽셀. 알파가 있으면 알파로, 없으면 «모서리 색»과 다른 픽셀로 찾는다.
    조용한 폴백을 안 만든다 — 못 찾으면 그 자리에서 깨진다(빈 아바타가 라이브에 서는 것보다 낫다)."""
    a = np.array(im.convert('RGBA'))
    알파 = a[:, :, 3]
    if 알파.min() < 250:                      # 투명판
        return a, 알파 > 24
    rgb = a[:, :, :3].astype(np.int16)        # 배경이 박힌 판 — 네 모서리에서 무엇이 배경인지 배운다
    모서리 = np.concatenate([rgb[:12, :12].reshape(-1, 3), rgb[:12, -12:].reshape(-1, 3),
                            rgb[-12:, :12].reshape(-1, 3), rgb[-12:, -12:].reshape(-1, 3)])
    밝 = rgb.max(axis=2)
    모밝 = 밝[:12, :12].max()
    if int(np.median(모서리.max(axis=1))) < 90:
        """어두운 «무대» 배경(마린 렌더) — 색 거리로 재면 무대의 «질감»이 몸으로 잡힌다
        (거친 벽지라 픽셀마다 밝기가 출렁여 평균색과의 거리가 문턱을 넘는다 — 08-28 실측:
        아바타 모서리에 검은 점 노이즈가 그대로 실렸다). 밝기 하나로 가르면 깨끗하다:
        마린 무대는 최대 98이고 몸은 코랄 240·흰 250이라 사이가 넓다."""
        return a, 밝 > max(110, int(모밝) + 15)
    return a, np.abs(rgb - 모서리.mean(axis=0)).sum(axis=2) > 40


def 코어상자(마스크):
    """«몸통»만의 사각형 — 뻗은 팔·곁의 소품을 걷어낸다.

    🔑 왜 이 자인가(08-27 실측): 그냥 bbox 를 쓰면 까몽이 x 83~984 로 잡힌다 — 뻗은 팔과
    곁에 둔 코랄 알까지 문 값이다. 그 자로 자르니 몽글은 얼굴이 꽉 차는데 까몽만 얼굴이
    점이 됐다(셋이 나란히 설 때 «얼굴 크기가 서로 다른» 아바타가 된다).
    행마다 몸 픽셀을 세면 몸통·머리는 넓고 팔·소품은 얇다 — 최대 폭의 40% 선으로 갈린다.
    실측: 까몽 x 83~984 → **213~850** · 몽글 219~805 → 265~758(통짜라 거의 그대로).

    ⚠ 눈을 찾아 얼굴 크기를 재는 길을 먼저 갔다가 버렸다 — 몽글은 눈 «하나»를 좌우로
    갈랐고(눈간 76px 오판 → 얼굴 하나가 화면을 채웠다) 까몽은 귀 하이라이트가 섞였다.
    「자동 추적 휴리스틱은 이 몸들에서 배신한다」가 마린 트랙에서도 같은 결론이었다."""
    행 = 마스크.sum(axis=1)
    코어행 = np.where(행 >= 행.max() * 0.40)[0]
    if not len(코어행):
        raise SystemExit('몸통을 못 찾았다 — 코어 행이 0이다')
    m2 = 마스크.copy()
    밖 = np.ones(마스크.shape[0], bool)
    밖[코어행] = False
    m2[밖, :] = False
    열 = m2.sum(axis=0)
    코어열 = np.where(열 >= 열.max() * 0.40)[0]
    return 코어열.min(), 코어행.min(), 코어열.max() + 1, 코어행.max() + 1


def 자르기(원본: Path, 조임=1.0, 밀기=(0.0, -0.04), 얼굴=None):
    """조임·밀기는 «눈으로만 갈리는» 미세조정이다(→ 색·미학 판정은 숫자가 못 가른다).
    자동 상자가 몸통을 정확히 물어도 «얼굴이 차지하는 비율»은 캐릭터마다 다르다 —
    까몽은 털이 부풀어 몸통 상자가 얼굴의 1.6배로 잡히고, 뻗은 팔 한쪽이 40% 선을 넘어 든다.
    원형으로 잘린 꼴을 나란히 놓고 «얼굴 크기가 같아 보일 때»를 값으로 굳혔다(08-27).

    `얼굴=(cx, cy, 변)` — 원본 «비율»로 상자를 직접 준다. 마린처럼 몸통이 얼굴의 세 배인
    전신 렌더는 코어 상자로 잡으면 머리가 점이 된다 — 그런 몸은 자동 추적에 맡기지 않는다
    (「이 몸에서 꼭대기 휴리스틱은 늘 배신한다」 — 마린 트랙이 이미 세 번 적은 교훈)."""
    im = Image.open(원본).convert('RGBA')
    a, 마스크 = 몸마스크(im)
    w = h = 0
    if 얼굴:
        W, H = im.size
        변 = int(얼굴[2] * W)
        cx, cy = 얼굴[0] * W, 얼굴[1] * H
    else:
        x0, y0, x1, y1 = 코어상자(마스크)
        w, h = x1 - x0, y1 - y0
        변 = int(max(w, h) * (1 + 여백 * 2) * 조임)
        cx = x0 + w / 2 + 변 * 밀기[0]
        cy = y0 + h / 2 + 변 * 밀기[1]   # 얼굴 쪽으로 — 원형에 잘려도 눈이 가운데 남게
    if a[:, :, 3].min() >= 250:
        """배경이 «박힌» 판(마린 렌더의 어두운 무대) — 몸 밖을 Paper 로 갈아 끼운다.
        투명판은 아래 alpha_composite 이 알아서 Paper 를 깔지만, 불투명판은 무대째 잘려 와
        카드에 «검은 원»이 선다. 알파 최소값 하나로 두 갈래를 가른다."""
        칠 = np.array(im)
        칠[~마스크] = 바탕 + (255,)
        im = Image.fromarray(칠, 'RGBA')
    상자 = (int(cx - 변 / 2), int(cy - 변 / 2), int(cx + 변 / 2), int(cy + 변 / 2))
    잘린 = im.crop(상자)  # 원본 밖으로 나가는 몫은 투명으로 오고, 아래에서 Paper 가 메운다
    바닥 = Image.new('RGBA', 잘린.size, 바탕 + (255,))
    바닥.alpha_composite(잘린)
    return 바닥, {'원본크기': f'{im.width}x{im.height}', '몸통': f'{w}x{h}', '자른변': 변}


def 굽기(이름: str, 원본: Path, 나갈이름: str, 조임=1.0, 밀기=(0.0, -0.04), 얼굴=None):
    """자른 것을 저장소 정본(256)과 배포판(160)으로 낸다."""
    바닥, 잰것 = 자르기(원본, 조임, 밀기, 얼굴)
    나온 = 바닥.convert('RGB').resize((크기, 크기), Image.LANCZOS)
    날것.mkdir(parents=True, exist_ok=True)
    경로 = 날것 / 나갈이름
    나온.save(경로, 'PNG', optimize=True)
    # 배포판 — 드라이브에 올려 카드가 실제로 부르는 파일. 펠트 털은 PNG 압축이 안 먹어(128px 도 27KB)
    # 40px 원형 하나에 그 무게를 지우지 않는다. 바탕이 불투명 Paper 라 JPEG 로 잃는 게 없다.
    배포 = 날것 / (나갈이름[:-4] + '_배포.jpg')
    나온.resize((배포크기, 배포크기), Image.LANCZOS).save(배포, 'JPEG', quality=92, optimize=True)
    return {'이름': 이름, '원본': str(원본.relative_to(루트)).replace('\\', '/'),
            **잰것,
            '나온파일': 나갈이름, 'KB': round(경로.stat().st_size / 1024, 1),
            '배포판': 배포.name, '배포KB': round(배포.stat().st_size / 1024, 1)}


def 큰판(이름: str, 원본: Path, 나갈이름: str, 조임=1.0, 밀기=(0.0, -0.04), 얼굴=None):
    """큰 판(1024) — 인쇄물·큰 화면처럼 «자세히 보는» 자리에 쓴다.

    🔑 왜 남의 기계에 맡기나(09-03 실측): 자른 것이 몽글 590 · 까몽 800 · 마린 342 라
      1024 로 그냥 늘리면 털이 뭉갠다. 또렷함(이웃 픽셀과의 차이)으로 재니 맡긴 쪽이
      **몽글 4.4배 · 마린 13.7배 · 까몽 1.3배**였다. 4배로 받아 1024 로 줄인다 —
      마지막 크기에서 «지어내게» 두지 않고 줄이면서 눌러 담는 쪽이 깨끗하다.
    ⚠ 대신 색이 조금 민다 — 몸 평균색이 기준에서 몽글 10.3 · 마린 8.6 · 까몽 2.6.
      0~441 자에서 2% 안쪽이라 받아들였다. 킷 색을 그대로 써야 하는 자리에는 256 판을 쓴다.
    ⚠ 통신이 필요하다. 그래서 «기본 굽기에는 안 걸린다» — --크게 일 때만 돈다.
    ⚠ 조용한 폴백을 안 만든다: 못 부르면 그 자리에서 깨진다. 그냥 늘린 것이 맡긴 판의
      얼굴로 서면, 다음 사람이 그걸 또렷한 판이라고 믿는다."""
    import tempfile
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import 그림맡기기

    바닥, 잰것 = 자르기(원본, 조임, 밀기, 얼굴)
    native = 바닥.convert('RGB')
    with tempfile.TemporaryDirectory() as 임시:
        보낼것 = str(Path(임시) / 'crop.png')
        받을것 = str(Path(임시) / 'big.png')
        native.save(보낼것, 'PNG')
        if 그림맡기기.한판('확대', 보낼것, 받을것, '', None) != 0:
            raise SystemExit('큰 판을 못 받았다 — 남의 기계가 멈췄을 수 있다: '
                             'python tools/그림맡기기.py --살았나')
        받은 = Image.open(받을것).convert('RGB')
        나온 = 받은.resize((큰크기, 큰크기), Image.LANCZOS)
    경로 = 날것 / 나갈이름
    나온.save(경로, 'PNG', optimize=True)
    return {'이름': 이름, '원본': str(원본.relative_to(루트)).replace(chr(92), '/'),
            **잰것, '맡겨받은변': 받은.width,
            '나온파일': 나갈이름, 'KB': round(경로.stat().st_size / 1024, 1)}


def 차림표():
    """어떤 몸을 «어떤 상자»로 자를 것인가 — 한 곳에서만 적는다.
    256 판과 1024 판이 같은 상자를 써야 두 판의 얼굴이 어긋나지 않는다
    (값이 두 곳에 있으면 갈린다 — 마스코트 10벌 사고가 그 자리였다)."""
    표 = [
        ('몽글', 정본경로("경로('눈웃음',{누끼:true})"), {}),
        # ⚠ 까몽 귀는 «코어 상자 밖»이다 — 얇아서 40% 선을 못 넘는다(실측: 코어 y0=156, 귀 꼭대기 y≈100).
        #   상자를 위로 올려 담는다. 귀가 잘리면 고양이 실루엣이 죽고 「검은 덩어리 + 연두 눈」이 된다.
        ('까몽', 정본경로("까몽경로('눈웃음',{누끼:true})"), dict(조임=0.98, 밀기=(-0.07, -0.035))),
    ]
    # 🔴 09-05 저녁 — 마린이 정본_4K 에 섰다(`62a750363` · 유호 확정 「이거로 가자」 = 귀엽4_더세게).
    #   옛 우주복 렌더(`마린공방_0827`)를 손으로 가리키던 줄을 걷는다 — 이제 셋 다 같은 창구다.
    #   ⚠ 얼굴 상자는 «다시 골랐다». 옛 값 (0.494, 0.244, 0.38) 은 분홍 우주복 «전신» 기준이라
    #     새 몸(남색 헬멧·꽃주머니)에 그대로 쓰면 머리 위 허공을 자른다.
    #   실측(마린_눈웃음 4096²): 몸 bbox 2012x3230 으로 «세로로 길다»(까몽 3246x3058 · 몽글
    #     3155x3084 는 거의 정사각) ⇒ 코어 상자로는 머리가 점이 되므로 얼굴 상자가 여전히 필요하다.
    #     헬멧 bbox 는 1921x1867 로 거의 정사각이고, 노란 렌즈 중심이 헬멧의 78% 지점이다 —
    #     눈이 아래로 내려온 판이라 «렌즈»를 상자 한가운데 두면 헬멧 꼭대기가 잘린다.
    #     그래서 상자를 렌즈가 아니라 «헬멧»에 맞춰 세운다(꼭대기 위로 헬멧높이의 6% 숨).
    #   후보 넷(헬멧높이 ×1.00·1.15·1.25·1.40)을 정사각과 «원형» 둘로 굽고 눈으로 골랐다:
    #     ×1.00·1.15 는 원 안에서 헬멧 아래가 잘리고, ×1.40 은 얼굴이 점이 된다.
    #     ×1.25 = 헬멧이 온전히 들어가고 꽃주머니가 살짝 걸리는 자리(옛 0.38 과 같은 기준이다).
    표.append(('마린', 정본경로("마린경로('눈웃음')"), dict(얼굴=(0.499, 0.457, 0.570))))
    return 표


def main():
    크게 = '--크게' in sys.argv[1:]
    모르는 = [a for a in sys.argv[1:] if a != '--크게']
    if 모르는:
        print('모르는 인자다: %s (있는 것: --크게)' % ' '.join(모르는))
        return 2
    보고 = []
    for 이름, 원본, 옵 in 차림표():
        나갈이름 = '%s_아바타%s.png' % (이름, '_큰판' if 크게 else '')
        보고.append((큰판 if 크게 else 굽기)(이름, 원본, 나갈이름, **옵))
    print(json.dumps(보고, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    sys.exit(main())
