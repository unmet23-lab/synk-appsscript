/** `--재심완료` — 재심을 **실제로 돌렸다**고 장부에 적는다. 이걸 안 적으면 주기 알림이 매일 뜬다.
 *  분모(`--본것`)를 함께 받는 이유: 「12개 보고 0」과 「3개 보고 0」은 다르다(유호 확정). */
function 재심완료보고(argv) {
  const 수 = (플래그) => {
    const i = argv.indexOf(플래그);
    return i === -1 ? null : Number(argv[i + 1]);
  };
  const 본것 = 수('--본것');
  if (!Number.isFinite(본것) || 본것 < 0) {
    console.log('사용: node tools/대기열.js --재심완료 --본것 12 --뒤집음 2');
    console.log('  🔴 `--본것` 이 필수다 — 분모 없는 「뒤집음 0」은 「없다」와 「안 봤다」를 못 가른다.');
    return 1;
  }
  const 뒤집음 = Number.isFinite(수('--뒤집음')) ? 수('--뒤집음') : 0;
  let ok = false;
  try {
    const 신호 = require(path.join(ROOT, 'tools', 'lib', '재심신호.js'));
    ok = 신호.재심완료({ 뿌리: ROOT, 모델: 세션모델().모델, 본것, 뒤집음 });
  } catch (e) {
    console.log(`✗ 기록 실패 — ${(e && e.message) || e}`);
    return 1;
  }
  if (!ok) { console.log('✗ 모델관측 장부에 못 썼다(권한·경로).'); return 1; }
  console.log(`✅ 재심 기록: 본것 ${본것} · 뒤집음 ${뒤집음} — 다음 도래는 돌아오는 수요일이다.`);
  if (뒤집음 === 0) console.log('   (뒤집음 0 은 정상이다 — 유호 아이디어 08-17 「없으면 그대로 간다」.)');
  /* 같은 분모를 작동 대장의 «그 주 사진»에도 잇는다(유호 픽 ㉱ 08-17 — 「재심이 덮어쓴다」).
   *  두 장부가 지는 물음이 다르다: 모델관측=«언제 재심했나» · 작동대장=«그때 시스템이 어땠나».
   *  분모가 사진 **옆에** 붙어야 「통은 움직였는데 그 주에 아무도 안 봤다」가 보인다.
   *  ⚠ 여기서 터져도 재심 기록 자체는 이미 남았다 — 그 사실을 밝히고 넘어간다. */
  try {
    const b = require(path.join(ROOT, 'tools', '작동대장.js')).재심보강({ 본것, 뒤집음 });
    if (b.상태 === 'ok') console.log(`   📎 작동 대장 ${b.대상} 사진에 이 분모를 붙였다.`);
    else if (b.상태 === '사진없음') console.log('   ⚠ 작동 대장에 아직 사진이 없어 분모를 못 붙였다 — `node tools/작동대장.js --기록`.');
    else if (b.상태 === '이미있음') console.log(`   ⏭ 작동 대장 ${b.대상} 사진엔 이미 분모가 있다 — 덮어쓰지 않는다(append-only).`);
  } catch (e) {
    console.log(`   ⚠ 작동 대장에 분모를 못 붙였다 — ${(e && e.message) || e} (재심 기록 자체는 남았다)`);
  }
  return 0;
}

