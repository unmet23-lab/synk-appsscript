    큐,
    /* 파일 칸에만 앉은 `#Qnn`(트랙 칸에 없는 것) — 점유로는 안 세고 **드러내는 데만** 쓴다. */
    큐인용: new Set([...보드.큐표식(파일칸)].filter((k) => !큐.has(k))),
    자리: 보드.파일자리(파일칸, { 판꼬리: true }),
