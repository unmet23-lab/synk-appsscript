#!/usr/bin/env node
/* 작업 대기열 조회 — 「다음에 무엇을 집나」를 세션 시작에 3줄로 보여준다.
 *
 * 발단(유호님 질의 2026-08-09): 「새 창에 『이어서 해』만 치면 기획한 게 실행되나?」
 *   실측 답 = **절반**. 세션 시작 훅이 인계문·미커밋·유호님 답 대기까지는 물려주는데,
 *   **다음에 무엇을 지을지의 순서**가 어디에도 없어서 세션마다 다른 것을 집었다.
 *   그 자리를 `docs/_ops/작업대기열.md` 가 채우고, 이 도구가 그걸 세션에 발화한다.
 *
 * 🔑 스스로 발화하지 않는 장치는 안 돈다(CLAUDE.md) — 그래서 조회 명령이 아니라 훅이다.
 *   대신 **세 줄만** 낸다: 세션 시작에 이미 훅 다섯이 말하고 있어, 여기서 길어지면
 *   전부가 소음이 되고 아무도 안 읽는다.
 * 🔑 이미 남이 잡은 것을 추천하지 않는다 — 보드(`lib/보드.js`)와 대조해 걸러 낸다.
 *   대조를 못 하면(파일 없음·파싱 실패) **거르지 않고 그대로 보여주되 그 사실을 밝힌다**:
 *   조용히 빈 목록을 내면 「할 게 없구나」로 읽힌다(초록은 분모와 함께).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = process.env.CLAUDE_PROJECT_DIR || path.resolve(__dirname, '..');
const 대기열경로 = path.join(ROOT, 'docs', '_ops', '작업대기열.md');
const 대기열좌표 = 'docs/_ops/작업대기열.md';   // git pathspec — fs 경로와 따로 둔다
const 보일줄수 = 3;
const 낡음보일수 = 3;

/* 열린 항목 = `- [ ]`. 닫힌 것은 지우는 규약이라 `- [x]` 는 원래 없어야 하지만, 있으면 건너뛴다. */
function 항목들() {
  if (!fs.existsSync(대기열경로)) return null;
  const 줄들 = fs.readFileSync(대기열경로, 'utf8').split(/\r?\n/);
  const 결과 = [];
  let 층 = '';
  for (const 줄 of 줄들) {
    const h = /^##\s+(P\d[^\n]*)/.exec(줄);
    if (h) { 층 = h[1].trim(); continue; }
    const m = /^\s*-\s*\[ \]\s*(.+)$/.exec(줄);
    if (m) 결과.push({ 층, 본문: m[1].trim() });
  }
  return 결과;
}

/* 보드에 이미 선언된 트랙의 글자를 모은다 — 제목 몇 글자가 겹치면 「누가 잡았다」로 본다.
 * 느슨한 매칭이라 거짓양성(안 잡았는데 잡았다고 봄)이 날 수 있는데, 그 방향이 안전하다:
 * 겹쳐서 두 세션이 같은 걸 짓는 사고(F070)가 못 고르는 것보다 비싸다. */
function 보드글자() {
  try {
    const 보드 = require(path.join(ROOT, 'tools', 'lib', '보드.js'));
    const 표 = typeof 보드.읽기 === 'function' ? 보드.읽기() : null;
    if (표) return JSON.stringify(표);
  } catch { /* 아래 폴백 */ }
  try {
    const 디렉 = path.join(ROOT, 'docs', '_ops', '보드');
    return fs.readdirSync(디렉)
      .filter((f) => f.endsWith('.md') && !f.startsWith('유물-'))
      .map((f) => fs.readFileSync(path.join(디렉, f), 'utf8'))
      .join('\n');
  } catch { return null; }
}

/* ── 낡음 후보 — 「형제가 이 층을 걸고 끝냈는데 대기열은 그대로다」 (F289) ──────────────
 *
 * ■ 무엇이 샜나 (2026-08-09 실측)
 *   대기열 줄 하나가 08-08 에 이미 닫혔는데 08-09 까지 열린 채 남아, 새 세션이 그것을
 *   「막히지 않은 유일한 P1」로 골라 착수했다가 코드를 열어 보고서야 되돌렸다. 급소는
 *   **저장소 경계**다 — 일을 끝내는 커밋은 형제(SYNK-talk)에서 나고 대기열은 여기 있어서,
 *   「끝나면 그 줄을 지운다」 규약이 원리적으로 안 건너온다. 대기열은 「다음에 집을 것」의
 *   정본이라 낡은 줄은 조용한 오답이 아니라 **세션을 통째로 헛돌린다**(F070 직전까지 갔다).
 *
 * ■ 🔑 재료는 **일한 세션 자신의 선언**이지 내 추론이 아니다
 *   실측으로 세 신호를 견줬다(2026-08-09 · 오늘 대기열 8항목 · 형제 커밋 271건 대상):
 *     ① 줄이 지목한 **파일 경로**가 형제에서 바뀌었나 → 오탐 0 인데, 정작 F289 를 낳은 그
 *        줄엔 경로가 **하나도 없어**(식별자만 적혀 있었다) 못 잡는다.
 *     ② 줄의 **백틱 식별자**가 형제 diff 에 나왔나 → 4발 1적중. `engine.learners`·
 *        `learning_events` 같은 **도메인 낱말**이 아무 커밋에나 걸린다. 노이즈가 되면 꺼진다.
 *     ③ **형제 커밋 제목이 「대기열 P*n*」을 인용**했나 → 2발 2적중.
 *   ③만 추론이 아니다 — 그 층에서 일했다고 **그 세션이 스스로 적은 것**이고, 저 규약은 이미
 *   쓰이고 있었다(08-09 기준 형제 커밋 7건이 제목에 층까지 달고 있다). ①②는 안 짓는다.
 *
 * ■ ⚠ 이 검사가 **못 보는 것**(초록은 분모와 함께 읽는다)
 *   · 제목에 「대기열」을 안 적고 끝낸 커밋 — 규약 밖이라 원리상 안 보인다.
 *   · 층이 바뀌었는지만 재지 **줄마다 맞는지는 안 잰다.** 같은 층의 다른 줄을 고쳐도 조용해진다.
 *     그래서 문구가 「낡았다」가 아니라 **「대조하라」**다 — 판정은 여는 사람이 한다.
 *   · 형제가 없으면(CI·폰) **미측정**이다. 0건과 같은 모양으로 내지 않는다.
 *
 * ■ 처방을 따르면 꺼지는가 (F103 · 가드 맹점 ③)
 *   「대기열의 그 층을 갱신하고 커밋한다」 → 그 층의 blame 이 형제 커밋보다 뒤가 되어 조용해진다.
 *   즉 **차단 사유가 시키는 그 동작**이 그대로 출구다. 미커밋 갱신으로는 안 꺼지는데, 그게 맞다 —
 *   미커밋은 다음 세션에 안 건너간다(F025). 그래서 blame 기준은 작업본이 아니라 **HEAD** 다. */
const 층표기 = /^##\s+(P\d)/;
/* 🔑 층 절의 **끝**도 표기해야 한다 — 시작만 잡으면 마지막 P 절이 파일 끝까지 삼킨다.
 *   실측(2026-08-10 · 분리 반박 H2): 대기열은 `## P3` 다음에 `## 지금 막혀 있어…`(비-P)가
 *   오는 모양인데, 절 경계에서 안 끊어 §막힘 절 편집이 blame 상 **P3 에 귀속**됐다. 그래서
 *   `85b70f55`(53행 §막힘만 고친 커밋)가 P3 의 마지막 갱신 시각이 됐다 — 아무도 P3 를 안
 *   고쳤는데 형제의 「(대기열 P3)」 경보가 꺼진다. 새는 방향이 「통과」라 조용하다.
 *   `###` 이하는 안 끊는다 — 층 절 **안쪽**의 하위 제목이라 그 층 소속이 맞다. */
const 절경계 = /^#{1,2}\s/;

function git(args, 뿌리) {
  const r = spawnSync('git', ['-c', 'core.quotepath=false', ...args],
    { cwd: 뿌리, encoding: 'utf8', timeout: 10000, windowsHide: true });
  return (r.error || r.status !== 0) ? null : String(r.stdout || '');
}

/** HEAD 판 대기열의 **층별 마지막 갱신 시각** + 파일 전체의 마지막 갱신 시각.
 *  못 읽으면 `null` — 「안 바뀌었다」와 「못 쟀다」를 같은 값으로 접지 않는다. */
function 층별시각(뿌리 = ROOT) {
  const o = git(['blame', '--line-porcelain', 'HEAD', '--', 대기열좌표], 뿌리);
  if (o === null) return null;
  const 층 = {};
  let 전체 = 0;
  let 지금층 = null;
  let 시각 = null;
  for (const l of o.split('\n')) {
    if (l.startsWith('committer-time ')) { 시각 = Number(l.slice(15)); continue; }
    if (!l.startsWith('\t')) continue;                       // 본문 줄만 본다
    const 본문 = l.slice(1);
    if (!Number.isFinite(시각)) continue;
    if (시각 > 전체) 전체 = 시각;
    const m = 층표기.exec(본문);
    if (m) 지금층 = m[1];
    else if (절경계.test(본문)) 지금층 = null;    // 비-P 절로 넘어가면 귀속을 끊는다
    if (지금층) 층[지금층] = Math.max(층[지금층] || 0, 시각);
  }
  return 전체 ? { 층, 전체 } : null;
}

/** 형제가 「대기열(P*n*)」을 걸고 낸 커밋 중, 그 층이 그 뒤로 안 바뀐 것.
 *  @returns {{측정: boolean, 사유?: string, 미반영?: Array}} */
function 낡음후보(뿌리 = ROOT) {
  /* ⚠ 모듈은 **이 파일 옆**에서 부르고 좌표만 `뿌리` 로 푼다 — 픽스처 저장소엔 `.claude/` 도
   *   `tools/` 도 없어서, 부르는 자리까지 `뿌리` 로 바꾸면 회귀가 통째로 못 돈다. */
  const store = require('../.claude/hooks/lib/handoff-store.js');
  const 형제 = store.siblings(뿌리);
  if (!형제.length) return { 측정: false, 사유: '형제 저장소가 없다 — 대기열을 닫는 커밋은 거기서 난다' };

  const 시각 = 층별시각(뿌리);
  if (!시각) return { 측정: false, 사유: '대기열의 커밋 시각을 못 읽었다(아직 미커밋이거나 git 이 없다)' };

  /* 1초 밀기·형제 좌표는 **베끼지 않고 빌린다** — 그 규칙이 두 곳에 살면 한쪽이 조용히
   * 옛 판으로 남는다(그 이유는 rot-check.js 의 export 머리말). */
  const { 뒤커밋들 } = require('./rot-check.js');
  const 본것 = new Set();
  const 미반영 = [];
  /* 층 없는 인용(「(대기열)」)은 **파일 전체**를 기준으로 잰다 — 어느 층인지 모르는데 아무 층에나
   * 붙이면 한 커밋이 층 수만큼 울고, 그게 곧 소음이다. `null` 키가 그 자리다. */
  for (const 층 of [...Object.keys(시각.층), null]) {
    const 기준 = 층 ? 시각.층[층] : 시각.전체;
    for (const { 뿌리, 저장소 } of 형제) {
      for (const c of 뒤커밋들(뿌리, 기준)) {
        if (!c.제목.includes('대기열') || 본것.has(c.해시)) continue;
        const 적힌층 = (/대기열[^)\]]{0,12}?\b(P\d)\b/.exec(c.제목) || [])[1] || null;
        if (적힌층 !== 층) continue;      // 층이 갈리면 그 층 차례에서 잡힌다
        본것.add(c.해시);
        미반영.push({ 저장소, 해시: c.해시, 층: 적힌층, 제목: c.제목 });
      }
    }
  }
  return { 측정: true, 미반영, 층별: 층으로접기(미반영) };
}

/** 커밋 목록 → **층 단위** 한 줄. 🔑 세션이 고르는 단위가 층이라 알림도 층이어야 한다 —
 *  커밋마다 한 줄을 내면 한 층에서 세 번 일한 날 세 줄이 뜨고, 셋 다 처방이 같다(그 층을
 *  갱신하라). 같은 처방을 여러 줄로 내는 것이 곧 소음이고, 소음이 되면 이 알림은 꺼진다.
 *  ⚠ `최신` 은 `git log` 가 **역시간순**으로 주는 것에 기댄다(그래서 층마다 첫 것이 최신이다). */
function 층으로접기(미반영) {
  const 통 = new Map();
  for (const c of 미반영) {
    const k = c.층 || '층 미상';
    if (!통.has(k)) 통.set(k, { 층: k, 건수: 0, 최신: c });
    통.get(k).건수 += 1;
  }
  return [...통.values()].sort((a, b) => a.층.localeCompare(b.층));
}

/* 항목 제목에서 매칭에 쓸 씨앗을 뽑는다 — 굵게 표기(`**…**`) 안쪽이 트랙 제목에 해당한다. */
/* 차단자 표식 — 줄머리 `〖…〗`. 「열림」과 「지금 집을 수 있음」은 **같은 말이 아니다**.
 *
 * 왜 생겼나: 이 도구는 오래 「열림 N」만 냈는데, 실측(2026-08-12)에서 그 23건 중 지금 집을 수
 * 있는 것은 **3건**이었다 — 나머지는 유호님 답 13·선행 4·재료 0 1·시점 1·남이 점유 1 로 열자마자
 * 막힌다. 새 세션은 그걸 모르고 P0 부터 훑다가 시간을 태운다(내가 그렇게 태웠다). 죽은 줄과 산
 * 줄이 같은 모양이라 생긴 병이고 처방도 같다 — **읽는 자리에 드러낸다**(F368).
 *
 * 왜 산문에서 «추정»하지 않나: 해 봤고 틀렸다. 「몽골어 검수자 1인 선행」·「다음 마이그 조각과 한
 * 벌」처럼 차단자가 서술문 안에 녹아 있는 줄을 휴리스틱이 **전부 「지금 가능」으로 읽었다**(23건 중
 * 4건 오판). 새는 방향이 「집으라고 부른다」라서 제일 나쁘다. 그래서 표식은 **사람이 판정해 단다**.
 * 대신 미표기를 「지금 가능」으로 세지 않고 **미표기로 따로 센다** — 모름과 통과를 가른다(F207). */
const 차단표식 = /^〖\s*([^〗]+?)\s*〗\s*/;
const 집을수있음 = '지금';

function 차단(본문) {
  const m = 차단표식.exec(String(본문 || '').trim());
  if (!m) return null;                       // null = 미표기(모름). 「지금 가능」이 아니다.
  return m[1] === 집을수있음 ? '' : m[1];    // '' = 지금 집을 수 있다
}

function 씨앗(본문) {
  const 벗김 = String(본문 || '').trim().replace(차단표식, '');
  const m = /\*\*(.+?)\*\*/.exec(벗김);
  const s = (m ? m[1] : 벗김).replace(/[`*]/g, '').trim();
  return s.slice(0, 12);
}

function 출력() {
  const 전체 = 항목들();
  if (전체 === null) {
    console.log(`■ 작업 대기열 — 파일이 없다: ${path.relative(ROOT, 대기열경로)}`);
    return 0;
  }
  const 글자 = 보드글자();
  const 남은 = 글자 === null ? 전체 : 전체.filter((it) => !글자.includes(씨앗(it.본문)));

  if (!전체.length) {
    console.log('■ 작업 대기열 — 열린 항목 0. 새 일감을 찾았으면 docs/_ops/작업대기열.md 에 추가한다.');
    return 0;
  }

  console.log(`■ 작업 대기열 — 다음에 집을 것 (열림 ${전체.length}${글자 === null ? '' : ` · 남이 안 잡은 것 ${남은.length}`})`);

  /* 「열림」이 아니라 **「지금 집을 수 있는 것」**을 먼저 낸다 — 그게 이 도구에 묻는 질문이다. */
  const 지금 = 남은.filter((it) => 차단(it.본문) === '');
  const 미표기 = 남은.filter((it) => 차단(it.본문) === null);
  const 막힘 = new Map();
  for (const it of 남은) { const c = 차단(it.본문); if (c) 막힘.set(c, (막힘.get(c) || 0) + 1); }

  if (지금.length) {
    console.log(`  🟢 **지금 집을 수 있는 것 ${지금.length}건** — 여기부터 본다:`);
    for (const it of 지금.slice(0, 보일줄수)) {
      console.log(`    · [${it.층.split(' ')[0]}] ${씨앗(it.본문)}…`);
    }
    if (지금.length > 보일줄수) console.log(`    (그 밖 ${지금.length - 보일줄수}건 — 전문에서 〖${집을수있음}〗 을 찾는다)`);
  } else if (막힘.size || 미표기.length) {
    console.log('  🔴 **지금 집을 수 있는 줄이 0이다** — 아래 차단자를 풀거나, 새 일감을 발굴해 추가한다.');
  }

  if (막힘.size) {
    const 요약 = [...막힘.entries()].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(' · ');
    console.log(`  ⛔ 막힌 것 ${[...막힘.values()].reduce((a, b) => a + b, 0)}건 — ${요약}`);
  }
  /* 미표기를 「지금 가능」에 섞지 않는다 — 모름을 통과로 세면 이 줄이 다음 F368 이 된다. */
  if (미표기.length) {
    console.log(`  ❔ 미표기 ${미표기.length}건 — 열어봐야 안다. 판정했으면 줄머리에 〖${집을수있음}〗·〖⏳유호〗 처럼 단다.`);
    for (const it of 미표기.slice(0, 보일줄수)) console.log(`    · [${it.층.split(' ')[0]}] ${씨앗(it.본문)}…`);
  }

  if (글자 === null) console.log('  ⚠ 보드를 못 읽어 **남이 잡은 것을 못 걸렀다** — 고르기 전에 node tools/board.js 로 대조한다.');
  else if (!남은.length) console.log('  (전부 누군가 잡았다 — 보드에서 확인하고, 정말 없으면 새 일감을 추가한다)');

  /* 낡음 후보. 훅은 무슨 일이 있어도 세션을 방해하지 않는다 — 터지면 한 줄로 밝히고 넘어간다.
   * (침묵으로 죽는 것을 잡으려는 검사가 침묵으로 죽으면 아무 의미가 없다.) */
  let 낡음 = null;
  try { 낡음 = 낡음후보(); } catch (e) { 낡음 = { 측정: false, 사유: `대조기 고장 — ${(e && e.message) || e}` }; }
  if (낡음.측정 && 낡음.층별.length) {
    const 층수 = 낡음.층별.length;
    console.log('  ⚠ 낡음 후보 — 형제가 이 층을 걸고 커밋했는데 **그 층이 그 뒤로 안 바뀌었다.** 고르기 전에 대조한다:');
    for (const g of 낡음.층별.slice(0, 낡음보일수)) {
      const 뒤 = g.건수 > 1 ? ` (그 층 ${g.건수}건 중 최신)` : '';
      /* 제목 끝의 「(대기열 P1 …)」 꼬리는 떼고 자른다 — 층은 앞 대괄호가 이미 말했고, 안 떼면
       * 자를 자리를 그 꼬리가 다 먹어 **정작 무슨 일을 했는지가 잘려 나간다**(실측 1회). */
      const 제목 = g.최신.제목.replace(/\s*[(（]\s*대기열[^)）]*[)）]?\s*$/, '');
      console.log(`      [${g.층}] ${g.최신.저장소} ${g.최신.해시} ${제목.slice(0, 46)}${뒤}`);
    }
    // 자른 것은 숫자로 밝힌다 — 조용한 절단은 「이게 전부」로 읽힌다.
    if (층수 > 낡음보일수) console.log(`      … 외 ${층수 - 낡음보일수}개 층`);
  }

  /* 뒤 절반(형제 커밋 제목 규약)이 **위 낡음 대조의 재료**다 — 장치와 그 발동 조건은 같은 자리에
   * 있어야 한다. 여기 안 적으면 형제에서 일하는 세션은 그 규약을 볼 기회가 없고, 그러면 검사는
   * 원리상 아무것도 못 본다(장치만 있고 안 도는 F026 모양). */
  console.log('  전문: docs/_ops/작업대기열.md — 고르면 **내 보드 파일에 선언**하고, 끝내면 그 층을 갱신해 담는다'
    + ' (형제 저장소 커밋이면 제목에 「대기열 P*n*」 — 그게 낡음 대조의 재료다).'
    + (낡음.측정 ? '' : ` ⚠낡음 대조 미실행 — ${낡음.사유}`));
  return 0;
}

module.exports = { 항목들, 씨앗, 낡음후보, 층별시각, 차단, 차단표식, 집을수있음 };

