    # 🔴 눈 자리는 «크로마에 뚫린 구멍»으로 되잰다 (09-06 밤 실측 · 유호 지시로 다시 구운 여섯 벌).
    #   새로 구운 장에서 까몽의 눈이 흰자 위주로 그려지자, 색으로 찾는 자가 «엉뚱한 점을 자신 있게»
    #   물었다(잎망토는 망토 위, 몽골 모자는 브림 위). 그러면 눈 가리개가 모자를 뚫고, 진짜 눈은
    #   옷으로 남는다 — 못 찾는 것보다 나쁘다(못 찾으면 멈추기라도 한다).
    #   🔑 몸이 단색이라 «눈은 반드시 크로마에 뚫린 구멍 안»에 있다. 그 밖이면 눈이 아니다.
