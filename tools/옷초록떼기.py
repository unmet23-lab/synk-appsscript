    #     크림 양모는 따뜻한 기운(노랑)이라 걷어내도 안 줄어든다 — 그래서 안 파인다.
    눌린 = _빛걷은판(a, 바탕)
    채 = 눌린.max(axis=2) - 눌린.min(axis=2)
    밝 = 눌린.max(axis=2)
    #   🔴 번지는 조건은 «색이 거의 0인 곳»으로 좁힌다(09-06 다섯째 갈이).
    #     넓게 두면 번짐이 크림 옷으로 흘러 들어가 배지 코트·후드·앞치마가 파였다.
    #     그림자는 색이 아예 없고(채 0~8) 크림 양모는 따뜻한 기운이 남는다(채 14~20).
    #   🔴 그런데 «분필 흰색» 양모는 색이 아예 없어 이 자를 못 빠져나간다(09-06 저녁 · 여덟째 갈이).
    #     배지 코트의 흰 깃이 바탕으로 먹혀 찢어졌고, 그 조각이 «바탕»으로 세어지는 바람에
    #     자리 맞추는 자까지 끌려가 코트가 몸 밖으로 밀려났다(확신 0.71).
    #     🔑 색 말고 «거칠기»가 가른다 — 바탕은 매끈하고(실측 0.43) 양모는 결이 산다
    #       (제일 매끈한 흰 깃도 2.37 · 코트 한복판 7.9 · 몸 21.9). 사이가 다섯 배라 안 헷갈린다.
