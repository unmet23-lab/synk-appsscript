    #   스튜디오 바닥에 드리운 그림자는 바탕 씨앗에서 안 이어지는 장이 있어 옷으로 남는다.
    #   🔑 옷은 반드시 몸에 «닿아» 있다 — 술이 늘어져도 그 술은 옷 본체와 한 덩어리다.
    #     그림자는 몸에서 떨어져 있으므로 이 자 하나로 원리적으로 걸러진다.
    몸닿음 = ndimage.binary_dilation(크로마, np.ones((41, 41), bool))
    표2, 수2 = ndimage.label(옷, structure=np.ones((3, 3), bool))
