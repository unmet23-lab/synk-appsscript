    # 🔴 «화면»이 크로마(초록·파랑 스크린)인 장 — 09-06 밤 · 까몽부터 (인계 §① 의 뿌리를 파니 여기였다).
    #   흰 바탕에서는 「크림 옷 vs 흰 바탕」을 거칠기로, 「바닥 그림자」를 여러 자로 가르느라
    #   여덟 번을 갈았고 그래도 배지 코트·후드가 뜯겼다. 화면이 크로마면 그 자 전부가 필요 없다 —
    #   초록도 자홍도 아닌 곳이 곧 옷이다. 그림자는 어두운 초록이라 그대로 화면으로 걸린다.
