    눈볼그림 = 초록
    if 화면크로마 is not None:
        # 초록 홍채를 찾는 자가 초록 «화면»을 통째로 물지 않게, 화면은 희게 칠하고 본다
        b = a.copy()
        b[화면크로마] = 255
        눈볼그림 = Image.fromarray(b, 'RGB')
