        #   🔑 크로마 그림에는 색에 안 기대는 자가 하나 더 있다 — **눈은 크로마에 뚫린 구멍**이다.
        #     몸이 단색이라 몸 안의 «크로마 아닌 섬»은 눈밖에 없다(옷은 바깥과 이어진다).
