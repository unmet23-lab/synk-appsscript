def 자홍인가(a):
    """크로마 자홍 = 붉음과 파랑이 초록보다 뚜렷이 세다. 초록 옷(잎·새싹)을 안 먹는다."""
    r, g, b = a[:, :, 0].astype(np.int16), a[:, :, 1].astype(np.int16), a[:, :, 2].astype(np.int16)
    return (r - g > 14) & (b - g > 14) & (np.maximum(r, b) > 40)


def 초록인가(a):
    """크로마 초록 = 초록이 다른 둘보다 뚜렷이 세고, 색이 확실히 있다.
    잎사귀 초록(#7FA86A 계열)은 초록이 덜 세고 붉은빛이 남아 여기 안 걸린다."""
    r, g, b = a[:, :, 0].astype(np.int16), a[:, :, 1].astype(np.int16), a[:, :, 2].astype(np.int16)
    # 🔴 그늘진 초록도 잡는다(09-06 실측: 목도리가 엇갈린 틈에 어두운 초록이 남았다).
    #   문턱을 밝기가 아니라 «초록이 얼마나 더 센가»로 잡으면 그늘도 같이 걸린다.
    return (g - r > 14) & (g - b > 14) & (g > 40)


def _빛걷은판(a, 바탕):
    """크로마 빛 번짐(spill)을 걷어낸 그림을 낸다 — 색을 «잴 때»도, 조각을 «낼 때»도 같은 자를 쓴다.

    초록(또는 자홍)이 다른 둘보다 세면 그만큼만 깎아 회색 쪽으로 당긴다. 제 색으로 초록·자홍을
    가진 옷은 여기서 조금 죽지만, 그런 옷은 애초에 반대 색 바탕에 굽는다(잎망토·새싹·화관은 자홍).
    """
    rgb = a.astype(np.float32)
    if 바탕 == '자홍':
        넘침 = np.maximum(np.minimum(rgb[:, :, 0], rgb[:, :, 2]) - rgb[:, :, 1], 0)
        rgb[:, :, 0] -= 넘침
        rgb[:, :, 2] -= 넘침
    else:
        넘침 = np.maximum(rgb[:, :, 1] - np.maximum(rgb[:, :, 0], rgb[:, :, 2]), 0)
        rgb[:, :, 1] -= 넘침
    return rgb.clip(0, 255).astype(np.int16)


def 떼어낸다(초록경로, 몸경로, 눈결='검정', 바탕='초록'):
    몸 = Image.open(몸경로).convert('RGBA')
    초록 = Image.open(초록경로).convert('RGB')

    초록눈 = 눈들(초록, 눈결)
    정본눈 = 눈들(몸, 눈결)
    if 초록눈 is None or 정본눈 is None:
        raise SystemExit(f'🔴 눈을 못 찾았다(초록 {bool(초록눈)} · 정본 {bool(정본눈)}) — 사람이 본다')
    맞춤 = 눈에서_옮김(초록눈, 정본눈)
    if 맞춤 is None:
        raise SystemExit('🔴 두 눈 사이를 못 쟀다 — 사람이 본다')
    배율, c초, c정 = 맞춤

    a = np.asarray(초록)
    # 🔴 바탕이 «순백»이 아닌 장이 있다(09-06 실측 · 까몽 목도리는 옅은 회색 스튜디오 바닥으로 나왔다).
    #   밝기로만 자르면 그 회색이 옷으로 잡혀 조각에 네모 배경이 통째로 들어온다.
    #   ⇒ 「밝고 색이 거의 없고 «테두리에서 이어지는» 곳」을 바탕으로 본다.
    #   🔴 바탕 «색»을 네 귀퉁이에서 «재서» 정한다 (09-06 셋째 갈이).
    #     고정 문턱으로 잡으면 두 번 다 틀렸다 — 넓게 잡으면 크림 옷이 바탕으로 먹히고
    #     (SYNK 후드가 찢어졌다), 좁게 잡으면 옅은 회색 스튜디오 바닥을 놓친다
    #     (자홍 판이 회색으로 나와 까몽 여덟 벌에 배경 조각이 딸려 왔다).
    #     귀퉁이는 언제나 바탕이므로, 거기서 재면 밝든 회색이든 다 맞는다.
    귀 = np.concatenate([a[:60, :60].reshape(-1, 3), a[:60, -60:].reshape(-1, 3),
                         a[-60:, :60].reshape(-1, 3), a[-60:, -60:].reshape(-1, 3)])
    바탕색 = np.median(귀, axis=0).astype(np.int16)
    닮음 = np.abs(a.astype(np.int16) - 바탕색).sum(axis=2) < 40
    표0, 수0 = ndimage.label(닮음)
    큼 = a.shape[0] * a.shape[1] * 0.03
    테두리 = set(표0[0, :]) | set(표0[-1, :]) | set(표0[:, 0]) | set(표0[:, -1])
    테두리.discard(0)
    테두리 = {i for i in 테두리 if (표0 == i).sum() > 큼}
    씨앗 = np.isin(표0, list(테두리)) if 테두리 else (a > 244).all(axis=2)
    # 🔑 바탕에서 «번져 나가» 옅은 그림자까지 따라간다 (09-06 넷째 갈이).
    #   바탕에 깔린 부드러운 그림자는 바탕 색과 조금 달라 옷으로 잡히고, 얹으면 흰 얼룩이 된다.
    #   그림자는 «색이 거의 없고 바탕보다 아주 어둡지는 않은» 자리이고, 바탕과 «이어져» 있다.
    #   그래서 색 하나로 자르지 않고 바탕에서 번지게 한다 — 옷은 색이 있거나 짙어서 번짐이 멈춘다.
    #   🔴 색을 «크로마 빛을 걷어낸 뒤»에 잰다 (09-06 저녁 · 여섯째 갈이).
    #     바닥 그림자에는 몸의 크로마 빛이 번져 앉는다. 그래서 색이 0 이어야 할 그림자가
    #     채 15~27 로 재어졌고, 「색이 거의 0인 곳」 조건에 안 걸려 그림자가 옷으로 남았다
    #     (까몽 여덟 벌에 회색 덩어리가 딸려 왔다 — 넓이가 옷보다 커서 크기로도 못 걸렀다).
    #     빛 번짐은 그 자리의 «제 색»이 아니므로, 걷어낸 뒤에 재는 것이 옳다.
    #     크림 양모는 따뜻한 기운(노랑)이라 걷어내도 안 줄어든다 — 그래서 안 파인다.
    눌린 = _빛걷은판(a, 바탕)
    채 = 눌린.max(axis=2) - 눌린.min(axis=2)
    밝 = 눌린.max(axis=2)
    #   🔴 번지는 조건은 «색이 거의 0인 곳»으로 좁힌다(09-06 다섯째 갈이).
    #     넓게 두면 번짐이 크림 옷으로 흘러 들어가 배지 코트·후드·앞치마가 파였다.
    #     그림자는 색이 아예 없고(채 0~8) 크림 양모는 따뜻한 기운이 남는다(채 14~20).
    허용 = (채 < 11) & (밝 > int(바탕색.max()) - 70)
    흰 = ndimage.binary_propagation(씨앗, mask=(씨앗 | 허용))

    바탕인가 = 자홍인가 if 바탕 == '자홍' else 초록인가
    크로마 = 바탕인가(a)
    옷 = ~크로마 & ~흰
    # 🔴 눈은 초록이 아니라 «옷»으로 잡힌다(09-06 실측 · 첫 목소리 목도리에 검은 구슬 넷이 떴다).
    #   눈 자리는 이미 알고 있으니 그 둘레를 통째로 뺀다. 옷이 눈을 가리는 컷(안경·모자)에서도
    #   가려진 부분은 어차피 옷 쪽 픽셀이라 옷 덩어리에 붙어 살아남는다.
    h, w = 옷.shape
    눈지름 = max(24, int(abs(초록눈[1][0] - 초록눈[0][0]) * 0.32))
    yy, xx = np.ogrid[:h, :w]
    눈자리 = np.zeros_like(옷)
    for ex, ey in 초록눈:
        동그라미 = ((xx - ex) ** 2 + (yy - ey) ** 2) <= 눈지름 ** 2
        옷 &= ~동그라미
        눈자리 |= 동그라미
    # 🔴 눈을 «둘러싸인 어둠»으로도 뺀다 (09-06 저녁 실측 · 창가 밀짚모자에 검은 구슬 둘이 떠 있었다).
    #   위의 동그라미는 «찾아낸 눈»만 뺀다. 눈을 엉뚱한 데서 찾은 장에서는 진짜 눈이 옷으로 남는다.
    #   🔑 눈은 «크로마에 완전히 둘러싸인 어두운 섬»이다 — 그것 말고 그런 모양은 없다.
    #     옷은 어디선가 바깥과 이어지므로 이 자에 안 걸리고, 가슴에 붙은 밝은 배지(새싹)도
    #     어둡지 않아 안 걸린다. 마린의 버터 렌즈도 밝아서 무관하다.
    갇힘 = ndimage.binary_fill_holes(크로마) & ~크로마
    옷 &= ~(갇힘 & (밝 < 80) & (채 < 60))

    # 눈은 몸이지 옷이 아니다 — 초록 안에 박힌 검은 구슬을 옷으로 오해하지 않게 «구멍»을 메우기 전에 뺀다
    옷 = ndimage.binary_opening(옷, np.ones((7, 7), bool))
    표, 수 = ndimage.label(옷, structure=np.ones((3, 3), bool))
    if 수 == 0:
        raise SystemExit('🔴 초록이 아닌 곳이 없다 — 옷이 안 보이는 그림이다')
    크기 = ndimage.sum(옷, 표, range(1, 수 + 1))
    남길 = np.where(크기 >= max(크기.max() * 0.02, a.shape[0] * a.shape[1] * 1e-4))[0] + 1
    옷 = np.isin(표, 남길)

    # 🔴 «몸에 안 닿은 덩어리»는 옷이 아니다 (09-06 저녁 실측 · 까몽 여덟 벌에 회색 그림자가 딸려 왔다).
    #   스튜디오 바닥에 드리운 그림자는 바탕 씨앗에서 안 이어지는 장이 있어 옷으로 남는다.
    #   🔑 옷은 반드시 몸에 «닿아» 있다 — 술이 늘어져도 그 술은 옷 본체와 한 덩어리다.
    #     그림자는 몸에서 떨어져 있으므로 이 자 하나로 원리적으로 걸러진다.
    몸닿음 = ndimage.binary_dilation(크로마, np.ones((41, 41), bool))
    표2, 수2 = ndimage.label(옷, structure=np.ones((3, 3), bool))
    if 수2:
        닿는가 = ndimage.sum(몸닿음, 표2, range(1, 수2 + 1)) > 0
        # 🔴 «바탕보다 어둡고 색이 없는 회색 덩어리»는 바닥 그림자다 (09-06 저녁 · 일곱째 갈이).
        #   까몽은 다리와 꼬리가 넓게 뻗어 있어 바닥 그림자가 «몸에 닿아» 버린다 — 닿음만으로는 못 거른다.
        #   가르는 자는 색과 밝기다: 그림자는 색이 0 에 가깝고 바탕보다 뚜렷이 어둡다.
        #   흰 목도리·크림 후드는 바탕만큼 밝아서 안 걸리고, 색 있는 옷은 채도로 안 걸린다.
        #   ⚠ 제일 큰 덩어리는 면제한다 — 옷 본체를 통째로 버리는 일이 절대 없어야 한다.
        칸수 = ndimage.sum(옷, 표2, range(1, 수2 + 1))
        평균채 = ndimage.mean(채, 표2, range(1, 수2 + 1))
        평균밝 = ndimage.mean(밝, 표2, range(1, 수2 + 1))
        그림자다 = (평균채 < 10) & (평균밝 < int(바탕색.max()) - 18)
        그림자다[int(np.argmax(칸수))] = False
        옷 = np.isin(표2, np.where(닿는가 & ~그림자다)[0] + 1)
        if not 옷.any():
            raise SystemExit('🔴 몸에 닿은 옷 덩어리가 없다 — 사람이 본다')

    옷 = ndimage.binary_closing(옷, np.ones((9, 9), bool))
    # 🔴 옷 «안»에 갇힌 구멍을 메운다 (09-06 저녁 실측 · 까몽 조끼 한가운데가 뚫렸다).
    #   크로마 빛이 옷에 번지면(spill) 그 자리가 바탕으로 잡혀 옷 한복판에 구멍이 난다.
    #   🔑 옷의 «바깥»으로 이어진 빈 곳(배지 코트의 열린 앞섶)은 구멍이 아니라 바깥이라 안 메워진다.
    #   ⚠ 일부러 뚫린 옷을 메우지 않도록 «작은 구멍»만 메운다(옷 넓이의 18% 미만).
    메움 = ndimage.binary_fill_holes(옷) & ~옷
    표3, 수3 = ndimage.label(메움)
    if 수3:
        구멍크기 = ndimage.sum(메움, 표3, range(1, 수3 + 1))
        작은구멍 = np.where(구멍크기 < 옷.sum() * 0.18)[0] + 1
        옷 |= np.isin(표3, 작은구멍)
    # 🔑 초록 빛 번짐(spill)을 한 겹 깎는다 — 안 깎으면 옷 가장자리에 초록 테가 남는다
    옷 = ndimage.binary_erosion(옷, np.ones((13, 13), bool))

    알파 = Image.fromarray((옷 * 255).astype(np.uint8), 'L').filter(ImageFilter.GaussianBlur(1.6))
    # 🔑 남은 크로마 기운을 눌러 준다(de-spill) — 위에서 색을 잴 때 쓴 것과 «같은 자»다
    층0 = Image.fromarray(눌린.astype(np.uint8), 'RGB').convert('RGBA')
    층0.putalpha(알파)

    # 🔴 정본 좌표계로 옮긴다 — «몸»이 자다(09-06 저녁 · 유호 「몽글 조각판은 매우 별로」).
    #   전에는 두 눈만으로 옮겼다. 몽글의 눈은 구슬이라 굽는 장마다 크기가 달라져(배율 0.99~2.30)
    #   그 오차가 옷 크기가 됐다 — 모자가 머리 위로 뜨고 후드가 몸보다 커졌다.
    #   이제 눈은 «어디쯤»만 주고, «얼마나 큰가»는 크로마 몸의 실루엣이 정한다.
    몸알파 = np.asarray(몸)[:, :, 3] > 128
    맞음 = 몸으로_맞춘다(크로마 | 눈자리, 흰, 몸알파, (배율, c초, c정))
    if 맞음 is None:
        raise SystemExit('🔴 몸으로 자리를 못 잡았다 — 사람이 본다')
    sx, sy, dx, dy, 확신 = 맞음['sx'], 맞음['sy'], 맞음['dx'], 맞음['dy'], 맞음['확신']
    작 = 층0.resize((max(8, round(층0.width * sx)), max(8, round(층0.height * sy))), Image.LANCZOS)
    층 = Image.new('RGBA', 몸.size, (0, 0, 0, 0))
    층.paste(작, (round(dx), round(dy)), 작)
