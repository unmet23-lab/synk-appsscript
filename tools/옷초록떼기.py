        #     그래서 색이 어떻게 그려지든 눈은 찾힌다. 좁은 자·넓은 자가 다 실패할 때만 쓴다.
        h0, w0 = 크로마.shape
        초록눈 = _짝찾기(구멍, None, h0, w0)
