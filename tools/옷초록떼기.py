    #   그림자는 «색이 거의 없고 바탕보다 아주 어둡지는 않은» 자리이고, 바탕과 «이어져» 있다.
    #   그래서 색 하나로 자르지 않고 바탕에서 번지게 한다 — 옷은 색이 있거나 짙어서 번짐이 멈춘다.
    #   🔴 색을 «크로마 빛을 걷어낸 뒤»에 잰다 (09-06 저녁 · 여섯째 갈이).
    #     바닥 그림자에는 몸의 크로마 빛이 번져 앉는다. 그래서 색이 0 이어야 할 그림자가
    #     채 15~27 로 재어졌고, 「색이 거의 0인 곳」 조건에 안 걸려 그림자가 옷으로 남았다
