    #     1.5 로 두면 그 사이가 통째로 바탕에 먹혀 크림 옷의 가장자리가 뜯긴다(배지 코트·저고리·목도리).
    #     ⚠ 조이면 그림자가 덜 먹히는데, 그 몫은 아래 «몸 밖 회색 지우기»가 받는다.
    #       둘은 한 벌이다 — 하나만 조이면 되레 나빠진다(그렇게 한 번 갔다가 되돌렸다).
    허용 = (채 < 11) & (밝 > int(바탕색.max()) - 70) & (거칠 < 1.1)
