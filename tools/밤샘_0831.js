#!/usr/bin/env node
/**
 * 밤샘 0831 — 까몽 확정 세트를 «열 컷 · 한 규격(1024)»으로 완성한다
 *   (유호 확정 08-31 「웅 몸 다섯을 구우고 다섯을 확정 세트로 올리자. 랜더도 5/5로 전부 꽉 채워줘.
 *    지금 자러갈거니까 편하게」 · 결정.md 08-31)
 *
 * ■ 이 밤이 겨누는 것 — 어젯밤(밤샘_0830)이 남긴 두 자리를 닫는다
 *   ① **몸 다섯**(놀람·윙크·졸림·으쓱·민망) — 누끼는 1024 정본으로 섰는데 몸판이 아직 700px 다.
 *      다섯이 확정 세트로 승격됐으니(유호 08-31) 몸도 확정 규격으로 맞춘다.
 *   ② **우34·좌34 몸판** — 정본 5문법 격자의 두 칸이 «까몽에선 한 번도 안 구워진 채» 비어 있다.
 *      옛 기각(장당 100분대 시절)은 유호 확정 08-31 로 뒤집혔다.
 *
 * ■ 순서 = 각도 둘 → 몸 다섯. 까닭 둘:
 *   · 각도 둘이 **새 정보**다 — 까몽 꼬리(8마디 시침 + 기운 지느러미)를 34° 로 돌린 판은 처음이라,
 *     잘못 나온다면 아침에 일찍 보이는 쪽이 낫다. 몸 다섯은 «이미 좋은 그림»의 해상도 승격이라 무위험.
 *   · 「랜더 5/5」가 두 장으로 닫히는 독립 납품이다 — 밤이 반만 돌아도 격자 하나는 찬다.
 *
 * ■ 🔑 재개 안전 — 목록을 손으로 못 박지 않고 «폭»으로 그 자리에서 센다
 *   무엇을 구울지는 PNG IHDR 의 폭(≠1024 또는 없음)이 정한다. 그래서 이 파일은 도중에 죽어도
 *   그냥 다시 부르면 **남은 것만** 굽는다 — `--다시` 를 통째로 걸면 재개 때 끝난 장을 또 굽고
 *   (헛불), 안 걸면 700px 판이 「자보다 새것」이라 전부 건너뛴다(mtime 병 · 트랙 §0). 폭이 가른다.
 *   ⚠ 블렌더는 «끝날 때» 파일을 쓰므로 도중에 죽으면 옛 판이 그대로 남는다 — 폭 판정이 안전하다.
 *
 * ■ 비용 (수는 자와 함께)
 *   몸판(받침천)은 누끼의 ≈3배다(08-26 실측: 같은 1024·96·CPU 에서 누끼 9.7~16.5분 · 몸 18.8~45.1분).
 *   새 꼬리(8마디)로 누끼가 41.5~57.9분이 됐으니(08-30 실측) 몸은 **장당 ≈125분 추정 · 실측 아님**.
 *   일곱 장이면 **≈15시간 추정** — 유호 08-31 「오래걸려도 되니까 · 기회비용 절대 생각하지마」.
 *
 * ■ 장치 = CPU (GPU 는 이 캐릭터에서 프로세스째 죽는다 · 까몽굽기.js 머리말) · 램 문지기 = lib/램문지기 하나.
 *
 * ■ 등재는 이 파일이 안 한다 — 굽기가 끝나면 «세션»이 등재한다(굽기와 등재는 한 벌):
 *   ⓐ tools/lib/마스코트자산.js 까몽컷에 우34·좌34 { 누끼:false, 규격:'각도' } 추가
 *   ⓑ docs/디자인_토큰.json 캐릭터.까몽.컷 배열에 우34·좌34 추가(_컷주 갱신)
 *   ⓒ 트랙 §0 ① 갱신 + 커밋·push
 *   세션이 죽어 있으면 다음 세션 몫이다 — 트랙 §0 ① 이 이 꼬리를 쥔다.
 *
 * 띄우는 법(PowerShell · 세션에서 떼어낸다 — 세션이 죽어도 굽기는 산다):
 *   $cls = [wmiclass]'Win32_Process'
 *   $cls.Create('cmd.exe /c ""C:\Program Files\nodejs\node.exe" "…\tools\밤샘_0831.js" > "…\밤샘0831.log" 2>&1"', 'C:\…\SYNK-appsscript')
 *   🔴 `cmd.exe /c` 로 «반드시» 감싼다 — WMI Create 는 셸을 안 거쳐, 안 감싸면 `>` 가 node argv 로 들어간다(08-28 실측).
 * 🔑 판정은 로그가 아니라 파일이다 — 아침에 볼 것은 `docs/캐릭터/친구공방_0825/` 와 `docs/까몽_시안.html`.
 */
'use strict';
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const 루트 = path.resolve(__dirname, '..');
const 노드 = process.execPath;
const 문지기 = require('./lib/램문지기');

const 시각 = () => new Date().toLocaleTimeString('ko-KR');
const 말 = (s) => { console.log(s); };

/* ── 완주 도장 — 밤굽기.js 에 선 규약 그대로(새 원장을 안 만든다) ──────────────
 *   상태:"돌는중"=착수(아침까지 그대로면 잡을 수 없는 죽음) · "멈춤"=잡은 죽음 · "완주"=끝까지 갔다.
 *   완주 ≠ 합격 — 「잘 구워졌나(미학)」는 유호님 눈이 판정 축이고 여기서 안 잰다.
 *   커밋은 «완주» 상태만(돌는중 커밋 = 장부가 스스로 거짓말 · .gitignore 금지 = 유호 확정). */
const 도장길 = path.join(루트, 'docs', '_ops', '밤굽기도장.json');
let 도장끝 = false;
const 단계기록 = [];
function 도장(상태, 사유) {
  try {
    const 임시 = `${도장길}.${process.pid}.tmp`;
    fs.mkdirSync(path.dirname(도장길), { recursive: true });
    const 벌 = { 시각: new Date().toISOString(), 무엇: '밤샘_0831.js', 상태, 완주: 상태 === '완주', 사유 };
    fs.writeFileSync(임시, `${JSON.stringify(벌, null, 2)}\n`, 'utf8');
    fs.renameSync(임시, 도장길);
  } catch (_) { /* 도장 실패로 굽기를 멈추지 않는다 — 굽기가 본체다 */ }
}
process.on('exit', (코드) => { if (!도장끝) 도장('멈춤', `끝까지 못 갔다 — 종료코드 ${코드} · 지나온 단계: ${단계기록.join(' · ') || '없음'}`); });
for (const 신호 of ['SIGINT', 'SIGTERM', 'SIGHUP', 'SIGBREAK']) {
  process.on(신호, () => { 도장('멈춤', `신호 ${신호} 로 끊겼다 · 지나온 단계: ${단계기록.join(' · ') || '없음'}`); 도장끝 = true; process.exit(130); });
}
process.on('uncaughtException', (e) => { 도장('멈춤', `예외로 죽었다 — ${(e && e.message) || e} · 지나온 단계: ${단계기록.join(' · ') || '없음'}`); 도장끝 = true; process.exit(1); });

/* PNG IHDR 의 폭 — 헤더 24바이트만 읽는다(까몽시트.js 와 같은 자). 없으면 0. */
function png폭(p) {
  try {
    const fd = fs.openSync(p, 'r'); const b = Buffer.alloc(24);
    fs.readSync(fd, b, 0, 24, 0); fs.closeSync(fd); return b.readUInt32BE(16);
  } catch (_) { return 0; }
}
/* 🔴 09-05 저녁 — 옛 세트(친구공방_0825)를 지우면서 현행 정본으로 옮겼다.
   ⚠ 이 파일은 «08-31 그 밤»의 사슬이라 다시 돌 일이 없다. 그래도 경로는 맞춰 둔다 —
     없는 폴더를 가리키면 나중에 읽는 사람이 「그 밤이 어디에 구웠나」를 잘못 읽는다.
   ⚠ 아래 `남은것` 은 1024 를 문턱으로 쓴다. 그것도 그 밤의 규격이고 지금 정본은 4096 이다
     — 이 도구를 다시 쓸 일이 생기면 그 수부터 다시 정한다. */
const 방 = path.join(루트, 'docs', '캐릭터', '정본_4K');
const 몸파일 = (n) => path.join(방, `까몽_${n}.png`);
/** 1024 가 아니면(없음 포함) 굽는다 — 재개 때 끝난 장은 여기서 스스로 빠진다. */
const 남은것 = (이름들) => 이름들.filter((n) => png폭(몸파일(n)) !== 1024);

function 단계(이름, 인자들) {
  말(`\n■ ${이름} — ${시각()}`);
  if (!문지기.자리비었나(이름, 말)) { 단계기록.push(`${이름.split(' ')[0]}=건너뜀`); return; }
  const 시작 = Date.now();
  const r = spawnSync(노드, 인자들, { cwd: 루트, stdio: 'inherit' });
  말(`■ ${이름} 끝 — 종료코드 ${r.status} · ${Math.round((Date.now() - 시작) / 60000)}분 · ${시각()}`);
  단계기록.push(`${이름.split(' ')[0]}=${r.status}`);
  /* 성패 판정은 까몽굽기.js 안에서 «파일 시각 + 종료상태» 두 축이 같이 한다 — 여기선 시간만 적는다. */
}

말(`■■ 밤샘 0831 시작 — ${new Date().toLocaleString('ko-KR')} · pid ${process.pid}`);
말(`   ${문지기.상태줄()}`);
말('   과녁 = 까몽 확정 세트 «열 컷 · 1024» 완성: 각도 둘(우34·좌34 · 첫 굽기) → 몸 다섯(700→1024) → 지면');
말(`   로그 ${path.join(os.tmpdir(), '밤샘0831.log')} (띄우개가 여기로 리디렉션했을 때)`);
도장('돌는중', '돌고 있다 — 아직 안 끝났다 (이 도장이 그대로면 도중에 죽은 것이다)');

/* ① 각도 둘 — 첫 굽기라 «새 정보»가 크고, 두 장으로 「렌더 5/5」가 독립적으로 닫힌다. */
const 각도 = 남은것(['우34', '좌34']);
if (각도.length) {
  단계(`① 까몽 각도판 ${각도.length}(${각도.join('·')}) — 1024 첫 굽기`,
    ['tools/까몽굽기.js', '--다시', '--표정', 각도.join(','), '--너비', '1024', '--샘플', '96', '--장치', 'CPU', '--시트없이']);
} else { 말('■ ① 각도판 — 이미 다 1024 다 · 건너뛴다'); 단계기록.push('①=이미1024'); }

/* ② 몸 다섯 — 승격 재굽기(유호 확정 08-31). `--누끼` 를 «빼면» 몸판이다. */
const 몸 = 남은것(['놀람', '윙크', '졸림', '으쓱', '민망']);
if (몸.length) {
  단계(`② 까몽 몸 ${몸.length}(${몸.join('·')}) — 700 → 1024 승격`,
    ['tools/까몽굽기.js', '--다시', '--표정', 몸.join(','), '--너비', '1024', '--샘플', '96', '--장치', 'CPU', '--시트없이']);
} else { 말('■ ② 몸 다섯 — 이미 다 1024 다 · 건너뛴다'); 단계기록.push('②=이미1024'); }

/* ③ 판정 지면 — 굽기와 지면은 한 벌(트랙 §0). 앞 단계를 `--시트없이` 로 돌린 것은
 *   중간 판이 최종 판인 척 남지 않게다. 여기서 한 번만 그린다. */
단계('③ 까몽 판정 지면 다시 그리기 (docs/까몽_시안.html)', ['tools/까몽시트.js']);

/* 완주 — 폭으로 다시 세어 «몇이 1024 로 섰나»를 사유에 남긴다(합계 = 갈래+갈래). */
const 전체 = ['본체', '눈감음', '눈웃음', '우34', '좌34', '놀람', '윙크', '졸림', '으쓱', '민망'];
const 선것 = 전체.filter((n) => png폭(몸파일(n)) === 1024);
도장('완주', `끝까지 갔다 · 몸판 1024 = ${선것.length}/${전체.length}`
  + (선것.length < 전체.length ? ` (아직: ${전체.filter((n) => !선것.includes(n)).join(', ')})` : '')
  + ` · 단계별: ${단계기록.join(' · ')} — 그림이 «좋은가»는 여기서 안 잰다(사람 몫)`);
도장끝 = true;
말(`\n■■ 밤샘 0831 끝 — ${new Date().toLocaleString('ko-KR')} · 몸판 1024 = ${선것.length}/${전체.length}`);
