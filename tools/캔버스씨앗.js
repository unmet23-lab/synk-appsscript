#!/usr/bin/env node
/**
 * 캔버스씨앗 — 클로드 디자인(손으로 만지는 캔버스)에 **SYNK 킷을 통째로 실어 주는 통로**.
 *
 * ■ 왜 있나 (2026-09-03 · 유호 지시 「클로드 디자인 기능을 내가 못 쓰고 있는 것 같은데 자동화해줘」)
 *   클로드 디자인은 유호님이 **직접 끌고 고치는** 지면을 냅니다 — 지금까지 시각 산출물의
 *   모든 손질이 나를 거쳐야 했던 자리가, 거기서는 유호님 손으로 끝납니다.
 *   그런데 그 캔버스는 **빈 종이에서 시작**한다. 킷을 손으로 옮겨 적으면 그 순간 사본이 하나
 *   더 생기고, 사본은 반드시 갈린다([[constant-known-in-two-places]]).
 *   ⇒ 씨앗을 «그때그때 만든다». 저장해 두지 않으므로 **낡을 수가 없다.**
 *
 * ■ 두 갈래 — 어느 쪽인지 고르는 것이 이 도구의 전부다
 *   `--맨`   토큰만(색·서체·간격·반지름). 3KB 안팎. **뼈대를 잡는 동안** 쓴다.
 *            구운 재질이 없으므로 «가볍고 손으로 고치기 쉽다». 시안·배치 실험이 여기.
 *   `--가득` 구운 펠트 재질까지 전부(기본값). **완성본**이 여기다.
 *            🔴 킷 규칙 = 재질은 CSS 로 «흉내내지» 않는다. 완성본은 반드시 구운 실물을 싣는다.
 *   ⚠ 「맨으로 만들고 그대로 내보내는 것」이 이 도구가 새는 유일한 방향이다.
 *     그래서 `--맨` 산출물 머리에 그 경고가 박혀 나간다.
 *
 * 쓰기:
 *   node tools/캔버스씨앗.js                     씨앗을 화면에 낸다(붙여 넣을 <style> 한 덩어리)
 *   node tools/캔버스씨앗.js --맨                토큰만(가벼운 판)
 *   node tools/캔버스씨앗.js --부품 칩,절번호,도장   그 부품만 싣는다(기본 = 전량)
 *   node tools/캔버스씨앗.js --지면 부품만        어두운 무대용 프리셋(기본 = 밝은부품)
 *   node tools/캔버스씨앗.js --목록              쓸 수 있는 색·부품·간격 «이름표»만 낸다
 *   node tools/캔버스씨앗.js --쓰기 <파일> --판 A4  시작 아트보드를 파일로 지어 준다
 *
 * 종료 코드: 0 = 냈다 · 2 = 모르는 낱말·모르는 부품(조용히 넘기지 않는다)
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');

/* 모르는 낱말 거절 — 이 도구는 «무엇을 실을지»를 낱말로 받는다. 오타가 「전량 실었다」로 보이면 안 된다. */
const { 인자게이트 } = require('./lib/인자게이트.js');
const 아는플래그 = ['--맨', '--가득', '--부품', '--지면', '--목록', '--쓰기', '--판'];

const loom = require('./lib/loom.js');
const 토큰 = require(path.join(ROOT, 'docs', '디자인_토큰.json'));

/** 판 크기 — 캔버스 아트보드 한 장의 크기. 이름은 유호님이 부르는 말로 둔다. */
const 판들 = {
  A4: { w: 794, h: 1123, 설명: 'A4 세로 · 96dpi 기준(인쇄물 한 쪽)' },
  A4가로: { w: 1123, h: 794, 설명: 'A4 가로' },
  카드: { w: 1080, h: 1080, 설명: 'SNS 정사각(캐러셀 한 장)' },
  세로카드: { w: 1080, h: 1350, 설명: 'SNS 세로(피드에서 제일 큰 판)' },
  화면: { w: 1440, h: 1024, 설명: '데스크톱 웹 한 화면' },
  폰: { w: 390, h: 844, 설명: '앱 화면 한 장' },
};

/* ── 이름표 — 「무엇을 쓸 수 있나」를 킷에서 그대로 뽑는다 ──────────────────
   🔑 여기 손으로 적는 값이 «하나도 없다». 킷이 늘면 이 표도 그날 늘어난다. */

/** 쓰는 색 — 퇴역 대기는 뺀다(새 산출물에 쓰지 않는 것을 이름표에 올리면 쓰게 된다). */
function 색표() {
  return 토큰.색.킷
    .filter((c) => !/퇴역|retire/i.test(String(c.팔레트) + String(c.직책)))
    .map((c) => ({ 이름: c.이름, hex: c.hex, 직책: c.직책 }));
}

const 부품표 = () => 토큰.부품.목록.map((p) => ({ 이름: p.이름, 자리: p.자리 }));
const 간격표 = () => Object.keys(토큰.율.단계);

function 목록낸다() {
  const 색 = 색표();
  console.log('■ SYNK 캔버스에서 쓸 수 있는 이름표 (정본 = docs/디자인_토큰.json)\n');
  console.log(`● 색 ${색.length} — CSS 에서는 --변수로 온다(씨앗이 심는다)`);
  for (const c of 색) console.log(`   ${c.hex}  ${c.이름.padEnd(14)} ${c.직책 || ''}`);
  console.log(`\n● 부품 ${부품표().length} — class 이름 그대로 쓴다`);
  for (const p of 부품표()) console.log(`   .${p.이름.padEnd(10)} ${p.자리 || ''}`);
  console.log(`\n● 간격 ${간격표().length} — var(--이름) 으로 온다: ${간격표().join(' · ')}`);
  console.log(`\n● 서체 — ${토큰.서체.본문스택}`);
  console.log(`         모노 ${토큰.서체.모노스택}`);
  console.log(`\n● 판 크기 — ${Object.entries(판들).map(([k, v]) => `${k}(${v.w}×${v.h})`).join(' · ')}`);
  return 0;
}

/* ── 씨앗 ──────────────────────────────────────────────────────────────── */

/** 색 변수 — 이름을 CSS 가 받을 수 있는 꼴로 눕힌다(공백·숫자 → 붙임표). */
const 변수이름 = (이름) => '--' + String(이름).trim().toLowerCase().replace(/\s+/g, '-');

/**
 * 색·서체 — **두 갈래가 «둘 다» 이걸 싣는다.**
 *
 * 🔴 왜 여기가 갈리면 안 되나 (09-03 실측: 첫 판이 흰 바탕으로 나왔다)
 *   `loom.css()` 는 간격(`--칸`·`--단`)은 스스로 정의하지만 **색은 «바깥이 준다»고 본다** —
 *   실제 지면들은 자기 `:root` 에 킷 색을 적어 두기 때문이다. 그런데 캔버스 아트보드는
 *   **빈 종이**라 그 바깥이 없다. 그대로 실으면 `var(--paper)` 가 못 풀려 흰 바탕이 되고,
 *   화면은 «거의 맞는» 얼굴로 틀린다. ⇒ 씨앗이 그 자리를 메운다.
 */
function 색서체블록() {
  const 색 = 색표().map((c) => `  ${변수이름(c.이름)}: ${c.hex};   /* ${c.직책 || ''} */`).join('\n');
  return [
    ':root{',
    색,
    `  --글꼴: ${토큰.서체.본문스택};`,
    `  --모노: ${토큰.서체.모노스택};`,
    '}',
    토큰.서체.낫표교정,
  ].join('\n');
}

/** 간격 — **맨 갈래에서만** 싣는다. 가득 갈래는 `loom.css()` 가 같은 값을 이미 낸다(두 곳이 알면 갈린다). */
function 간격블록() {
  return [':root{', ...간격표().map((n) => {
    const v = 토큰.율.단계[n];
    const px = typeof v === 'object' ? (v.px ?? v.값 ?? v.크기) : v;
    return px == null ? null : `  --${n}: ${typeof px === 'number' ? px + 'px' : px};`;
  }).filter(Boolean), '}'].join('\n');
}

const 바닥 = 'body{ margin:0; background:var(--paper); color:var(--ink); font-family:var(--글꼴); }';

/** 토큰만 실은 «맨» 씨앗 — 구운 재질이 없다. 뼈대 잡는 동안만 쓴다. */
function 맨씨앗() {
  return [색서체블록(), 간격블록(), 바닥].join('\n');
}

/** 구운 재질까지 실은 «가득» 씨앗 — 완성본은 이쪽이다. 간격은 loom 이 낸다. */
function 가득씨앗(지면, 쓴클래스) {
  return [색서체블록(), loom.css({ 지면, ...(쓴클래스 ? { 쓴클래스 } : {}) }), 바닥].join('\n');
}

/**
 * 간격을 두 곳이 «다르게» 알고 있지 않은지 — 한 판정엔 자 하나.
 * 🔑 값이 같은지를 재는 것이지 「둘 다 있는지」가 아니다. 갈리면 조용히 지나가지 않고 던진다.
 * @returns {string[]} 어긋난 이름들(없으면 빈 배열)
 */
function 간격대조() {
  const loomCSS = loom.css({ 지면: '밝은부품' });
  const 어긋남 = [];
  for (const n of 간격표()) {
    const v = 토큰.율.단계[n];
    const 내값 = typeof v === 'object' ? (v.px ?? v.값 ?? v.크기) : v;
    if (내값 == null) continue;
    const m = loomCSS.match(new RegExp(`--${n}\\s*:\\s*([^;}]+)`));
    if (!m) continue;                                  // loom 이 안 내는 단계 = 대조할 것이 없다
    const 저값 = m[1].trim();
    if (저값 !== `${내값}px` && 저값 !== String(내값)) 어긋남.push(`${n}: 토큰 ${내값}px ↔ loom ${저값}`);
  }
  return 어긋남;
}

/**
 * 씨앗 한 덩어리 — 캔버스 아트보드에 그대로 붙여 넣는 `<style>`.
 * 머리에 «어떻게 지었나»를 박는다: 손으로 고치면 킷과 갈린다는 것을 읽는 사람이 알아야 한다.
 */
function 씨앗덩어리({ 맨, 지면, 부품 }) {
  const 명령 = `node tools/캔버스씨앗.js${맨 ? ' --맨' : ''} --지면 ${지면}${부품 ? ` --부품 ${[...부품].join(',')}` : ''}`;
  const 머리 = [
    '/* ── SYNK 캔버스 씨앗 — **생성물이다. 손으로 고치지 마라.** ─────────────',
    `   지은 명령: ${명령}`,
    '   정본: docs/디자인_토큰.json · tools/lib/loom.js',
    '   이 블록을 고치면 킷과 갈리고, 갈린 쪽은 조용히 옛 값을 퍼뜨린다.',
    맨
      ? '   🔴 이 판은 «맨»이다 — 구운 펠트 재질이 없다. 뼈대를 잡는 동안만 쓰고,\n'
        + '      내보내기 전에 `--가득` 으로 다시 지어 갈아 끼운다(킷: 재질은 CSS 로 흉내내지 않는다).'
      : '   ✅ 이 판은 «가득»이다 — 구운 펠트 재질이 실려 있다. 완성본에 그대로 쓴다.',
    '   ──────────────────────────────────────────────────────────────── */',
  ].join('\n');
  const 몸 = 맨 ? 맨씨앗() : 가득씨앗(지면, 부품);
  return `<style data-synk-씨앗="${맨 ? '맨' : '가득'}">\n${머리}\n${몸}\n</style>`;
}

/** 시작 아트보드 — 「빈 종이 앞에서 멈추는 것」을 없앤다. 골격만 주고 내용은 비운다. */
function 아트보드({ 판, 씨앗 }) {
  const p = 판들[판];
  return `<!-- SYNK 아트보드 · ${판} (${p.w}×${p.h}) — ${p.설명}
     클로드 디자인 캔버스에서 이 파일 하나가 «한 장»이다. 여러 장이면 파일을 여러 개 둔다. -->
<div class="룸" style="width:${p.w}px;min-height:${p.h}px;padding:var(--장, 48px);background:var(--paper);">
  <h1 style="margin:0 0 var(--칸, 16px)">제목을 여기에</h1>
  <p style="margin:0 0 var(--단, 24px);color:var(--deep-wool)">한 줄 설명을 여기에.</p>

  <h2>절 제목</h2>
  <p>본문. 이 지면의 부품 이름표는 <code>node tools/캔버스씨앗.js --목록</code> 이 낸다.</p>
</div>
${씨앗}
`;
}

/* ── CLI ───────────────────────────────────────────────────────────────── */

function 본다(argv) {
  const 플래그오류 = 인자게이트('캔버스씨앗', argv, 아는플래그);
  if (플래그오류) { console.error(플래그오류); return 2; }

  if (argv.includes('--목록')) return 목록낸다();

  const 값 = (이름) => { const i = argv.indexOf(이름); return i >= 0 ? argv[i + 1] : null; };
  const 맨 = argv.includes('--맨');
  if (맨 && argv.includes('--가득')) { console.error('🔴 --맨 과 --가득 은 같이 못 쓴다 — 둘 중 하나만 고른다.'); return 2; }

  const 지면 = 값('--지면') || '밝은부품';
  if (!loom.지면들[지면]) {
    console.error(`🔴 모르는 지면 프리셋: ${지면} — 아는 것은 ${Object.keys(loom.지면들).join('·')}`);
    return 2;
  }

  let 부품 = null;
  const 부품값 = 값('--부품');
  if (부품값) {
    const 아는부품 = new Set(부품표().map((p) => p.이름));
    const 준것 = 부품값.split(',').map((s) => s.trim()).filter(Boolean);
    const 모름 = 준것.filter((n) => !아는부품.has(n));
    if (모름.length) {
      /* 🔑 조용히 빼지 않는다 — 오타 하나가 「그 부품 없이 지었다」로 지나가면 화면만 허전해진다. */
      console.error(`🔴 모르는 부품 ${모름.join(' ')} — 이름표는 \`node tools/캔버스씨앗.js --목록\` 이 낸다.`);
      return 2;
    }
    부품 = new Set(준것);
  }

  /* 두 곳이 같은 간격을 다르게 알면 그 자리에서 멈춘다 — 씨앗이 갈린 값을 퍼뜨리면 되돌릴 자가 없다. */
  const 어긋남 = 간격대조();
  if (어긋남.length) {
    console.error('🔴 간격이 토큰과 loom 에서 갈렸다 — 씨앗을 내지 않는다:\n   ' + 어긋남.join('\n   '));
    return 2;
  }

  const 씨앗 = 씨앗덩어리({ 맨, 지면, 부품 });

  const 쓸곳 = 값('--쓰기');
  if (!쓸곳) {
    console.log(씨앗);
    console.error(`\n(씨앗 ${(씨앗.length / 1024).toFixed(0)}KB · ${맨 ? '맨' : '가득'} · ${지면}`
      + `${부품 ? ` · 부품 ${부품.size}종` : ' · 부품 전량'})`);
    return 0;
  }

  const 판 = 값('--판') || 'A4';
  if (!판들[판]) {
    console.error(`🔴 모르는 판: ${판} — 아는 것은 ${Object.keys(판들).join('·')}`);
    return 2;
  }
  fs.writeFileSync(쓸곳, 아트보드({ 판, 씨앗 }));
  console.log(`✅ ${쓸곳}  (${판} ${판들[판].w}×${판들[판].h} · 씨앗 ${(씨앗.length / 1024).toFixed(0)}KB · ${맨 ? '맨' : '가득'})`);
  console.log('   다음: 이 파일을 클로드 디자인 캔버스로 연다(스킬 `synk-canvas` 가 그 절차를 진다).');
  return 0;
}

if (require.main === module) process.exit(본다(process.argv.slice(2)));
module.exports = { 판들, 색표, 부품표, 간격표, 씨앗덩어리, 맨씨앗, 가득씨앗, 아트보드, 간격대조 };
