#!/usr/bin/env node
/* 발음밀도 — 한국어 지문의 «발음 현상 밀도»를 기계로 센다. (규격 `docs/발음데이터_규격.md` §2-1 의 자)
 *
 * 내력: 08-31 81 세션이 스크래치패드에 `topik-발음밀도.js` 로 지어 TOPIK 제83회 듣기 지문(I·II)을 쟀고,
 *   그 수(3축 27·55 등)가 규격 §2-1 의 배치 근거가 됐다. 자가 저장소 밖(48시간 걷기 대상)이라
 *   09-02 에 여기로 옮겼다 — 규격이 인용하는 수를 «다시 잴 수 있어야» 자다. 셈 규칙은 한 글자도 안 바꿨다.
 *
 * 무엇을 재나 — 「발음을 묻는 문항이 몇 개냐」가 아니다(TOPIK 듣기엔 그런 문항이 없다).
 *   재는 것은 **「이 소리 규칙을 모르면 못 알아듣는 자리가 지문에 얼마나 나오는가」** 다.
 *   자 = 한글 자모 분해 후 «앞 음절 종성 × 뒤 음절 초성» 환경 판정.
 *
 * ⚠ 이 자의 한계를 먼저 적는다(수는 자와 함께 적는다):
 *   · 표기 기준 판정이다 — 실제 발음은 낱말·문맥에 따라 예외가 있다(사잇소리·경음화 조건 등).
 *   · 경음화는 «필수 환경»(장애음 뒤 + 12항 4호 ㅎ계열 받침 뒤 ㅅ)만 센다.
 *     관형형 -(으)ㄹ 뒤 경음화, 한자어 안 ㄴ·ㅁ 뒤 경음화는 안 센다(과소 계상) — 표기만으로는 못 가른다.
 *   · 연음은 «띄어쓰기 없는 자리»만 센다(어절 안). 어절 경계 연음은 안 센다(과소 계상).
 *     ⇒ 「십만 원」은 연음 0·비음화 1 이다 — 규격 §2-3 검산(12↔13)이 이 규칙 하나로 닫혔다(09-02).
 *   ⇒ 그러므로 이 수는 **하한**이다. 실제 밀도는 이보다 높다.
 *
 * 🔍 09-03 교차검사 — 이 자를 es-hangul(토스 · 표준 발음법 9~20항 구현)과 나란히 돌렸다.
 *   저장소 한국어 문장 352줄로 재니 «헛셈 0»(우리가 센 것은 전부 실제로 소리가 바뀐다).
 *   그 검사가 찾아낸 구멍은 «ㄶ·ㅀ 뒤 ㅅ» 하나뿐이었고 지금 메웠다.
 *   ⛔ es-hangul 을 이 자의 «정본»으로 삼지 않는다 — 24항(어간 ㄴ·ㅁ 받침 뒤 어미 경음화)을
 *      명사와 어절 경계에까지 밀어 붙여 틀린 소리를 낸다: 「문장→문짱」·「친구→친꾸」·「한국어→한꾸거」.
 *      교차 검사자로만 쓴다(재현 = docs/_ops/발음자_교차검사_2026-09-03.md).
 * 선택지는 «인쇄돼 읽는» 것이라 분모에서 뺐다 — 학생이 «들어야» 하는 것은 대화 지문뿐이다.
 *
 * 입력: 발화 한 줄씩의 텍스트 파일(빈 줄·`#` 주석은 건너뜀). 기출 지문 파일은 저장소에 두지 않는다 —
 *   경로만 준다. 회귀는 `tests/발음밀도.test.js`(낱말 몇 개로 규칙을 못박는다).
 * 쓰기: node tools/발음밀도.js <지문.txt>
 */
'use strict';
const fs = require('fs');
const path = require('path');

const 초성표 = ['ㄱ','ㄲ','ㄴ','ㄷ','ㄸ','ㄹ','ㅁ','ㅂ','ㅃ','ㅅ','ㅆ','ㅇ','ㅈ','ㅉ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ'];
const 종성표 = ['','ㄱ','ㄲ','ㄳ','ㄴ','ㄵ','ㄶ','ㄷ','ㄹ','ㄺ','ㄻ','ㄼ','ㄽ','ㄾ','ㄿ','ㅀ','ㅁ','ㅂ','ㅄ','ㅅ','ㅆ','ㅇ','ㅈ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ'];

function 분해(ch) {
  const c = ch.charCodeAt(0) - 0xAC00;
  if (c < 0 || c > 11171) return null;
  return { 초: 초성표[Math.floor(c / 588)], 종: 종성표[c % 28] };
}

const 겹받침 = ['ㄳ','ㄵ','ㄶ','ㄺ','ㄻ','ㄼ','ㄽ','ㄾ','ㄿ','ㅀ','ㅄ'];
// 7종 중화 뒤 장애음(비음화·경음화의 앞자리)
const ㄱ류 = ['ㄱ','ㄲ','ㅋ','ㄳ','ㄺ'];
const ㄷ류 = ['ㄷ','ㅅ','ㅆ','ㅈ','ㅊ','ㅌ','ㅎ'];
const ㅂ류 = ['ㅂ','ㅍ','ㄼ','ㄿ','ㅄ'];
const 장애음 = [].concat(ㄱ류, ㄷ류, ㅂ류);

const 갈래들 = ['겹받침', '연음', '비음화', '유음화', '격음화', '경음화', '구개음화'];

/** 한 줄(발화)의 갈래별 건수와 보기. 어절 단위 — 연음은 어절 «안»에서만 센다. */
function 세기(줄) {
  const 셈 = {}; 갈래들.forEach(k => 셈[k] = 0);
  const 예 = {}; 갈래들.forEach(k => 예[k] = []);
  String(줄).split(/\s+/).forEach(어절 => {
    const cs = [...어절];
    for (let i = 0; i < cs.length; i++) {
      const a = 분해(cs[i]);
      if (!a) continue;
      if (겹받침.includes(a.종)) { 셈.겹받침++; 예.겹받침.push(어절); }
      const b = i + 1 < cs.length ? 분해(cs[i + 1]) : null;
      if (!b || !a.종) continue;
      const 짝 = cs[i] + cs[i + 1];
      // 연음 — 앞 종성 있고(ㅇ 제외) 뒤 초성이 ㅇ
      if (a.종 !== 'ㅇ' && b.초 === 'ㅇ') { 셈.연음++; 예.연음.push(짝); }
      // 비음화 — 장애음 + ㄴ/ㅁ
      if (장애음.includes(a.종) && (b.초 === 'ㄴ' || b.초 === 'ㅁ')) { 셈.비음화++; 예.비음화.push(짝); }
      // 유음화 — ㄴ+ㄹ · ㄹ+ㄴ
      if ((a.종 === 'ㄴ' && b.초 === 'ㄹ') || (a.종 === 'ㄹ' && b.초 === 'ㄴ')) { 셈.유음화++; 예.유음화.push(짝); }
      // 격음화 — 장애음+ㅎ · ㅎ계열+장애음
      if ((['ㄱ','ㄷ','ㅂ','ㅈ','ㄶ','ㅀ'].includes(a.종) && b.초 === 'ㅎ')
        || (['ㅎ','ㄶ','ㅀ'].includes(a.종) && ['ㄱ','ㄷ','ㅂ','ㅈ'].includes(b.초))) { 셈.격음화++; 예.격음화.push(짝); }
      // 경음화 — 장애음 + 평음
      if (장애음.includes(a.종) && ['ㄱ','ㄷ','ㅂ','ㅅ','ㅈ'].includes(b.초)) { 셈.경음화++; 예.경음화.push(짝); }
      // 경음화 — 표준 발음법 12항 4호: ㅎ 계열 «겹»받침(ㄶ·ㅀ) 뒤 ㅅ 은 [ㅆ] 이다(「않습니다[안씀니다]」·「싫소[실쏘]」).
      //   ㅎ 홑받침은 위 ㄷ류에 이미 있어 「좋소[조쏘]」가 잡히는데 겹받침 둘만 빠져 있었다.
      //   09-03 es-hangul 교차검사로 드러난 자리다(같은 검사에서 헛셈 0 · 이 갈래만 구멍이었다).
      else if (['ㄶ','ㅀ'].includes(a.종) && b.초 === 'ㅅ') { 셈.경음화++; 예.경음화.push(짝); }
      // 구개음화 — ㄷ/ㅌ + 이/히
      if ((a.종 === 'ㄷ' || a.종 === 'ㅌ') && (cs[i + 1] === '이' || cs[i + 1] === '히')) { 셈.구개음화++; 예.구개음화.push(짝); }
    }
  });
  return { 셈, 예 };
}

/** 지문 전체(발화 배열)의 합계 — 화면 출력과 회귀가 같은 것을 읽게 여기서 접는다. */
function 재기(발화들) {
  const 총 = {}; 갈래들.forEach(k => 총[k] = 0);
  const 예모음 = {}; 갈래들.forEach(k => 예모음[k] = new Set());
  let 하나이상 = 0;
  let 총글자 = 0;
  발화들.forEach(줄 => {
    const { 셈, 예 } = 세기(줄);
    const 합 = 갈래들.reduce((a, k) => a + 셈[k], 0);
    if (합 > 0) 하나이상++;
    갈래들.forEach(k => { 총[k] += 셈[k]; 예[k].forEach(v => 예모음[k].add(v)); });
    총글자 += [...줄.replace(/\s/g, '')].length;
  });
  const 총건 = 갈래들.reduce((a, k) => a + 총[k], 0);
  return { 총, 예모음, 하나이상, 총글자, 총건, 발화수: 발화들.length };
}

function 발화읽기(경로) {
  return fs.readFileSync(경로, 'utf8').split(/\r?\n/).map(s => s.trim()).filter(s => s && !s.startsWith('#'));
}

function main(argv) {
  const 경로 = argv[2];
  if (!경로 || !fs.existsSync(경로)) {
    console.error('쓰기: node tools/발음밀도.js <지문.txt>   (발화 한 줄씩 · # 주석 · 기출 지문은 저장소 밖에 둔다)');
    return 2;
  }
  const 발화들 = 발화읽기(경로);
  if (!발화들.length) { console.error(`발화 0줄 — ${경로}`); return 2; }
  const r = 재기(발화들);
  // 제목은 «읽은 파일»에서 낸다 — 리터럴로 박으면 다른 파일을 재고도 옛 제목이 찍힌다(08-31 실측: TOPIK I 을 재는데 「TOPIK II」로 나왔다)
  console.log(`# ${path.basename(경로)} — 듣기 «지문» 발음 현상 밀도 (기계 셈 · 표기 기준 하한)`);
  console.log('');
  console.log(`분모: 발화 ${r.발화수}개 · 글자 ${r.총글자}자 (선택지 제외 — 그건 읽는 것이지 듣는 것이 아니다)`);
  console.log(`발음 현상이 하나라도 든 발화: **${r.하나이상} / ${r.발화수}** (${Math.round(r.하나이상 / r.발화수 * 100)}%)`);
  console.log(`총 ${r.총건}건 · 발화당 평균 ${(r.총건 / r.발화수).toFixed(1)}건 · 10글자당 ${(r.총건 / r.총글자 * 10).toFixed(1)}건`);
  console.log('');
  console.log('갈래        건수   보기(중복 제거)');
  갈래들.forEach(k => {
    const 보기 = [...r.예모음[k]].slice(0, 6).join(' · ') || '—';
    console.log(`${k.padEnd(10)}${String(r.총[k]).padStart(4)}   ${보기}`);
  });
  return 0;
}

module.exports = { 갈래들, 세기, 재기, 발화읽기, 분해 };

if (require.main === module) process.exitCode = main(process.argv);
