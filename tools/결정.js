#!/usr/bin/env node
'use strict';
/**
 * 결정 — 확정 원문을 보존하고 현재 요청·후속 결정과 대조한다 (현행화 2026-09-09).
 * 14일은 최근 기록의 관찰 구간이다. 새 요청·달라진 근거가 있으면 경과일과 무관하게 재검토한다.
 * 안전 기록은 실제 보호 절차를 확인할 대상이며, 기록된 모든 행동을 영구 금지한다는 뜻이 아니다.
 * 읽기·화면·추가만 담당한다. 재검토나 기간 경과는 채택·실행 허가를 만들거나 가드를 바꾸지 않는다.
 * 구속일·구속중·영구는 기존 API 값 호환을 위해 남기되 정책 필드에서 표시용임을 명시한다.
 * 과거 운영 규칙: docs/_archive/결정_운영규칙_20260819.md.
 *
 *   node tools/결정.js                    전체 — 보호 경계 확인 / 최근 확정 / 과거 기록
 *   node tools/결정.js --훅                선택 요약 출력 (훅을 설치하지 않는다)
 *   node tools/결정.js --추가 "결정문" --근거 "유호 확정 08-19" [--성격 안전|확정]
 *   node tools/결정.js --json             기계 판독용
 *   종료 코드 0 — 이 도구는 아무것도 막지 않는다(계기판이다).
 */

const fs = require('fs');
const path = require('path');
const { 인자게이트 } = require('./lib/인자게이트.js');
/* 표를 가르고 담는 통로는 하나다 — 날 `split('|')` 은 백틱 «안»의 파이프까지 칸막이로 세서
 * 그 뒤 칸을 통째로 밀어 놓고도 오류를 안 낸다(F193 계열 · `tools/lib/표.js` 머리말).
 * 이 정본은 백틱 인용이 빽빽해서(`안전`·`node tools/…`) 정확히 그 함정 위에 있다. */
const { 칸나누기, 칸안전 } = require('./lib/표.js');

/* ⚠ `CLAUDE_PROJECT_DIR` 을 앞에 두는 것은 **결함이 아니라 시험 이음매**다 —
 *   `tests/결정정본.test.js` ⑥ 이 그 env 로 임시 뿌리를 갈아끼워 쓰기 경로를 통째로 태운다
 *   (08-26 에 이 줄을 `__dirname` 고정으로 바꿨다가 그 시험이 반박했다).
 * 🔴 워크트리에서 이 값이 «가지 사본»을 가리키는 것은 사실이고, 그건 자리를 바꿔서가 아니라
 *   **낡음을 드러내서** 고친다 — 아래 훅 출력의 「뒤처졌다」 한 줄이 그 자리다. */
const 루트 = process.env.CLAUDE_PROJECT_DIR || path.resolve(__dirname, '..');
const 정본 = path.join(루트, 'docs', '_ops', '결정.md');

/** 최근성 표시 기준. 구속일은 예전 소비자를 위한 호환 이름이며 재검토 대기기간이 아니다. */
const 관찰일 = 14;
const 구속일 = 관찰일;
const 정책 = Object.freeze({
  기준: '2026-09-09', 관찰일, 재검토대기일: 0,
  재검토: '현재 사용자 요청 또는 달라진 전제·기술·실물·근거가 있으면 경과일과 무관하게 재검토한다. 당시 이유 / 달라진 전제 / 지금 증거 / 바꾸려는 범위를 남기고 변함없는 반복은 억제한다.',
  현행성: '현재 요청과 후속 확정의 적용 범위를 원문에서 확인한다. 경과일은 결정의 무효나 현행성을 판정하지 않는다.',
  보호절차: '안전 기록의 인증·권한·학생 데이터·비가역 행동 보호 절차는 기간이 지나도 자동 해제되지 않는다. 이미 허용된 행동까지 일괄 금지하는 뜻은 아니다.',
  실행권한: '재검토·기간 경과·이 출력은 채택이나 실행 허가가 아니며 실제 권한·가드를 변경하지 않는다.',
  호환필드: '구속일·구속중·영구는 기존 API의 관찰 구분 값이다. 재검토 금지나 개별 행동의 영구 금지로 사용하지 않는다.',
});

const 시작표식 = '<!-- 결정표 시작 · tools/결정.js 가 이 구간만 읽고 쓴다 -->';
const 끝표식 = '<!-- 결정표 끝 -->';

const 성격들 = ['안전', '확정'];
const 기본성격 = '확정';

/* ── 읽기 ────────────────────────────────────────────────────────────────── */

/** 정본 전문. 없으면 null — **「0건」과 「파일이 없다」를 가른다**(F207: 미실행은 통과가 아니다). */
function 원문() {
  try {
    return fs.readFileSync(정본, 'utf8');
  } catch {
    return null;
  }
}

/** 표 구간만 잘라낸다. 표식이 없으면 null(손으로 지웠다는 뜻 — 조용히 0건으로 세지 않는다). */
function 표구간(문) {
  const a = 문.indexOf(시작표식);
  const b = 문.indexOf(끝표식);
  if (a < 0 || b < 0 || b < a) return null;
  return { 앞: 문.slice(0, a + 시작표식.length), 몸: 문.slice(a + 시작표식.length, b), 뒤: 문.slice(b) };
}

/** `YYYY-MM-DD` → 그날 0시 UTC. 로컬 시간대로 재면 한국 09시 이전에 하루가 갈린다(F296). */
function 날짜값(s) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(s || '').trim());
  if (!m) return null;
  return Date.UTC(+m[1], +m[2] - 1, +m[3]);
}

/** 오늘 0시 — **여기 사는 사람의 오늘**이다. 테스트가 얼릴 수 있게 손잡이를 둔다
 *  (시각 의존 검사는 CI 에서 깨진다 · F296).
 *  🔴 **UTC 를 쓰면 새벽 작업이 하루 전으로 찍힌다**(실측 08-23 06:12 KST → 표에 08-22).
 *     유호님은 UTC+9(한국)·UTC+8(몽골)에서 일하고 **새벽 작업이 흔하다** — UTC 기준이면
 *     오전 9시(한국) 이전의 모든 결정이 전날로 들어가고, 최근 기록 표시도 그만큼 어긋난다.
 *     표에 적히는 날짜가 「그날 유호님이 정한 날」과 달라지면 이 표는 근거로 못 쓴다. */
function 오늘값(기준) {
  if (기준 != null) return 날짜값(기준) ?? Date.parse(기준);
  const d = new Date();
  return Date.UTC(d.getFullYear(), d.getMonth(), d.getDate());   // 현지 달력의 날짜를 UTC 0시로 못박는다
}

/**
 * 표 한 줄 → 결정 하나. 파싱 못 한 줄은 **버리지 않고 `깨짐`으로 돌려준다** —
 * 조용히 빠지면 「없다」와 「못 읽었다」가 같은 모양이 된다.
 */
function 줄읽기(줄) {
  const 칸 = 칸나누기(줄);   // 양끝 `|` 를 버리고, 백틱 안의 파이프는 칸막이로 안 센다
  if (칸.length < 4) return null;
  const [날짜, 성격원, 결정, 근거] = 칸;
  if (!날짜 || /^-+$/.test(날짜) || 날짜 === '날짜') return null;   // 구분선·머리줄
  const 값 = 날짜값(날짜);
  if (값 == null) return { 깨짐: true, 원줄: 줄 };
  // 성격을 못 알아보면 확정으로 표시하고 미지성격으로 남긴다. 안전으로 자동 승격하지 않는다.
  const 성격 = 성격들.includes(성격원) ? 성격원 : 기본성격;
  return { 날짜, 값, 성격, 성격원, 결정: 결정 || '', 근거: 근거 || '', 미지성격: !성격들.includes(성격원) };
}

/**
 * 주어진 «본문»에서 결정 목록을 낸다 — **순수 함수**. 파일·시각에 안 기댄다.
 * 회귀가 무는 자리는 여기다: 탐지력은 픽스처가 지고, 실저장소 검사는 거짓양성만 본다(F296·맹점②).
 * `기준`(YYYY-MM-DD)으로 「오늘」을 얼릴 수 있어 14일 경계를 시각 의존 없이 못박는다.
 */
function 읽기문(문, 기준) {
  if (문 == null) return { 정책, 못읽음: true, 목록: [], 깨짐: [] };
  const 구간 = 표구간(문);
  if (!구간) return { 정책, 표없음: true, 목록: [], 깨짐: [] };

  const 오늘 = 오늘값(기준);
  const 목록 = [];
  const 깨짐 = [];
  for (const 줄 of 구간.몸.split('\n')) {
    if (!줄.includes('|')) continue;
    const r = 줄읽기(줄);
    if (!r) continue;
    if (r.깨짐) { 깨짐.push(r.원줄); continue; }
    const 지난일 = Math.floor((오늘 - r.값) / 86400000);
    r.지난일 = 지난일;
    r.최근 = 지난일 <= 관찰일;
    r.보호절차지속 = r.성격 === '안전';
    r.관찰구분 = r.보호절차지속 ? '보호 경계 확인' : r.최근 ? '최근 확정' : '과거 기록';
    // 기존 값은 보존하되 승인·금지 판정으로 쓰지 않는다. 새 소비자는 정책과 관찰구분을 읽는다.
    r.구속중 = r.보호절차지속 || r.최근;
    r.영구 = r.보호절차지속;
    목록.push(r);
  }
  return { 정책, 목록, 깨짐 };
}

/** 정본 파일을 읽어 낸다. 「파일 없음」·「표식 없음」·「0건」을 **세 칸으로 가른다**(F207). */
function 읽기(옵션) {
  return 읽기문(원문(), (옵션 || {}).기준);
}

/* ── 쓰기 ────────────────────────────────────────────────────────────────── */

/** 표 칸을 깨뜨리지 않게 소독한다 — 담는 통로도 `lib/표.js` 하나다(가르는 쪽과 짝이 맞아야 한다). */
function 칸청소(s) {
  return 칸안전(String(s == null ? '' : s)).replace(/\s+/g, ' ').trim();
}

function 오늘문자() {
  const d = new Date();                              // 현지 달력 — 위 `오늘값` 과 같은 기준이어야 한다
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/** 결정 한 줄을 표 «맨 위»에 넣는다(최신순). 정본이 없거나 표식이 없으면 쓰지 않고 알린다. */
function 추가(결정, 근거, 성격) {
  const 문 = 원문();
  if (문 == null) return { 실패: `정본이 없다: ${정본}` };
  const 구간 = 표구간(문);
  if (!구간) return { 실패: `표식을 못 찾았다 — 손으로 지웠나: ${시작표식}` };
  const 쓸성격 = 성격들.includes(성격) ? 성격 : 기본성격;
  const 새줄 = `| ${오늘문자()} | ${쓸성격} | ${칸청소(결정)} | ${칸청소(근거)} |`;

  /* 머리줄·구분선 «뒤»에 끼운다 — 맨 앞에 넣으면 표가 깨진다. */
  const 줄들 = 구간.몸.split('\n');
  let 자리 = 줄들.findIndex((l) => /^\s*\|\s*-+/.test(l));
  자리 = 자리 < 0 ? 줄들.length : 자리 + 1;
  줄들.splice(자리, 0, 새줄);

  fs.writeFileSync(정본, 구간.앞 + 줄들.join('\n') + 구간.뒤, 'utf8');
  return { 새줄, 성격: 쓸성격 };
}

/* ── 화면 ────────────────────────────────────────────────────────────────── */

const 상한 = 20;   // --훅 이 싣는 줄 수. 넘으면 건수만 내고 전문을 가리킨다.

/* 훅 한 줄의 길이 상한 — 08-22 실측: 전문을 그대로 실으니 훅 출력이 **10.7KB** 였고,
 * 그때 매 세션 상주(CLAUDE.md 4.2 + MEMORY.md 12.7 + 이것)가 27.6KB 로 **개편 전 지침
 * 하나(22.7KB)보다 커졌다**. 개편이 「체감이 안 된다」던 자리가 여기다.
 * 확정문은 대개 «제목 — 왜·어떻게» 꼴이라, 매 세션 필요한 «무엇»은 제목에 다 있다.
 * 전문은 사라지지 않는다 — `node tools/결정.js` 가 언제나 전량을 낸다. */
const 줄상한 = 100;

/** 확정문에서 «무엇»만 남긴다 — 첫 「 — 」 앞이 제목이면 그것, 아니면 앞을 자른다. */
function 요약(s) {
  const t = String(s || '').replace(/\s+/g, ' ').trim();
  if (t.length <= 줄상한) return t;
  const em = t.indexOf(' — ');
  if (em > 0 && em <= 줄상한) return `${t.slice(0, em)} …`;
  return `${t.slice(0, 줄상한).trim()}…`;
}

/** 세션 시작 한 벌 — **유호님 확정을 매 세션 눈앞에 놓는 것**이 이 도구의 존재 이유다. */
function 훅화면() {
  const r = 읽기();
  if (r.못읽음) {
    return `📌 결정 정본을 못 읽었다 — ${정본} 이 없다. 「확정 0건」이 아니라 **안 재봤다**다(F207).`;
  }
  if (r.표없음) {
    return `📌 결정 정본에 표식이 없다 — ${정본} 의 «결정표 시작/끝» 주석이 지워졌다. 복구 전엔 아무것도 안 세진다.`;
  }

  const 안전 = r.목록.filter((d) => d.보호절차지속);
  const 최근 = r.목록.filter((d) => !d.보호절차지속 && d.최근);
  const 과거 = r.목록.filter((d) => !d.보호절차지속 && !d.최근);

  const 줄 = [];
  줄.push(`📌 **확정 기록 ${r.목록.length}건** — 보호 경계 확인 ${안전.length} · 최근 ${관찰일}일 ${최근.length} · 과거 ${과거.length}`);
  줄.push(`   ${정책.재검토}`);
  줄.push(`   ${정책.현행성} ${정책.실행권한}`);
  줄.push(`   ${정책.보호절차}`);
  /* 🔴 **이 결정표가 «지금»인가** — 워크트리 시대의 새 급소(08-26 실측).
   *   가지 체크아웃의 `결정.md` 는 그 가지가 갈라진 시점의 사본이다. 실측에서 메인 178건 대
   *   워크트리 175건이었고, **낡았다는 표시가 어디에도 없었다** — 세션이 첫 화면부터 잘못된
   *   지도로 출발한다. 뒤처짐을 재서 «있으면» 한 줄 더한다(0이면 아무 말도 안 한다).
   * 🔑 origin 을 «건드리지 않는다» — 이미 받아 둔 `origin/master` 와만 견준다(네트워크 0). */
  try {
    const { execFileSync } = require('child_process');
    const 뒤 = execFileSync('git', ['rev-list', '--count', 'HEAD..origin/master'],
      { cwd: 루트, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    if (뒤 && 뒤 !== '0') {
      줄.push(`   ⚠ 이 결정표는 **이 체크아웃 기준**이다 — \`origin/master\` 보다 ${뒤}커밋 뒤처졌다. 커밋 차이로 문서의 현재 내용을 단정하지 말고 현재 요청과 최신 정본 원문을 대조한다.`);
    }
  } catch (_) { /* git 밖·원격 없음 — 모름을 경고로 번역하지 않는다 */ }

  const 확인목록 = [...안전, ...최근];
  const 실을것 = 확인목록.slice(0, 상한);
  for (const d of 실을것) {
    const 표 = d.보호절차지속 ? '보호 경계 확인' : `D+${d.지난일}`;
    줄.push(`   ${표} ${요약(d.결정)}`);
  }
  if (확인목록.length > 상한) 줄.push(`   … 외 ${확인목록.length - 상한}건`);
  줄.push(`   📖 위는 «무엇»만이다 — 왜·어떻게가 필요하면 \`node tools/결정.js\` 가 전문을 낸다.`);

  if (과거.length) 줄.push(`   과거 기록 ${과거.length}건 — 오래됐다는 이유만으로 무효로 보거나 변경하지 않는다.`);
  if (r.깨짐.length) {
    줄.push(`   ⚠ 못 읽은 줄 ${r.깨짐.length}건 — 날짜 형식(YYYY-MM-DD)이 깨졌다. 이 건수만큼 위 셈에서 빠져 있다.`);
  }
  const 미지 = r.목록.filter((d) => d.미지성격);
  if (미지.length) {
    줄.push(`   ⚠ 성격이 «안전·확정» 이 아닌 줄 ${미지.length}건 — 「확정」으로 세었으며 안전으로 자동 승격하지 않는다.`);
  }
  줄.push('   새 확정은 날짜·범위·근거를 `node tools/결정.js --추가`로 기록한다. AI의 구현 판단을 사용자 구술로 적지 않는다.');
  return 줄.join('\n');
}

function 전체화면() {
  const r = 읽기();
  if (r.못읽음) return `결정 정본이 없다: ${정본}`;
  if (r.표없음) return `결정 정본에 «결정표 시작/끝» 표식이 없다: ${정본}`;

  const 낸다 = [`결정 정본 — ${정본}`, `전체 ${r.목록.length}건 · 최근성 관찰 구간 ${관찰일}일 · 재검토 대기 ${정책.재검토대기일}일`,
    정책.재검토, 정책.현행성, 정책.보호절차, 정책.실행권한, ''];
  for (const 구분 of ['보호 경계 확인', '최근 확정', '과거 기록']) {
    const 목록 = r.목록.filter((d) => d.관찰구분 === 구분);
    낸다.push(`■ ${구분} (${목록.length})`);
    for (const d of 목록) {
      낸다.push(`  D+${d.지난일}  [${d.날짜}] ${d.결정}`);
      if (d.근거) 낸다.push(`        ↳ ${d.근거}`);
    }
    낸다.push('');
  }
  if (r.깨짐.length) {
    낸다.push('');
    낸다.push(`⚠ 못 읽은 줄 ${r.깨짐.length}건 (날짜 형식이 깨졌다 — 위 셈에서 빠져 있다):`);
    r.깨짐.forEach((l) => 낸다.push(`    ${l.trim().slice(0, 120)}`));
  }
  return 낸다.join('\n');
}

/* ── CLI ─────────────────────────────────────────────────────────────────── */

const 아는플래그 = ['--훅', '--json', '--추가', '--근거', '--성격'];

function main() {
  const args = process.argv.slice(2);
  const 오류 = 인자게이트('결정', args, 아는플래그);
  if (오류) { console.error(오류); process.exit(1); }

  const 값 = (이름) => {
    const i = args.indexOf(이름);
    return i >= 0 ? args[i + 1] : undefined;
  };

  if (args.includes('--추가')) {
    const 문구 = 값('--추가');
    if (!문구 || 문구.startsWith('--')) {
      console.error('--추가 에 결정문이 없다.  예) node tools/결정.js --추가 "…" --근거 "유호 확정 08-19"');
      process.exit(1);
    }
    const r = 추가(문구, 값('--근거') || '', 값('--성격'));
    if (r.실패) { console.error(r.실패); process.exit(1); }
    console.log(`결정 추가 (성격 ${r.성격} · ${r.성격 === '안전' ? '보호 경계 확인' : `최근성 관찰 ${관찰일}일`} · 재검토 대기 ${정책.재검토대기일}일)`);
    console.log(정책.재검토 + '\n' + 정책.보호절차 + '\n' + 정책.실행권한);
    console.log(`  ${r.새줄}`);
    return;
  }

  if (args.includes('--json')) {
    console.log(JSON.stringify(읽기(), null, 2));
    return;
  }

  console.log(args.includes('--훅') ? 훅화면() : 전체화면());
}

if (require.main === module) main();

