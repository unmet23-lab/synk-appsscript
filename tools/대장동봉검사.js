#!/usr/bin/env node
'use strict';
/* 이해대장 «동봉» 게이트 — 정본 개정이 화면을 두고 가는 커밋을 **커밋 전에** 막는다.
 *   (유호 지시 2026-08-14 「정본 고칠 때 이해대장 재생성 자동으로 되게 해줘」)
 *
 * ■ 무엇을 막나 — `docs/SYNK_철학.md` 는 이 커밋에 있는데 그 파생인 `docs/이해대장.html` 이 안 따라온 커밋.
 *
 * ■ 왜 사전 차단인가 — 같은 자리가 **하루에 네 번**이었다(08-13 23:35 · 08-14 00:06 · 05:58 · 13:0x).
 *   전부 「fix: 이해대장 생성물 재생성 — 주인 없는 적색이 남의 배포를 막고 있었다」다. `tests/이해대장.test.js`
 *   가 사후에 빨개지는데, 이 저장소의 스위트는 `/deploy` 2단계 게이트라 그 적색은 고친 사람이 아니라
 *   **그 뒤 커밋하는 모든 세션의 배포**를 막는다. 사후 검사는 탐지지 예방이 아니다(CLAUDE.md 신뢰성).
 *
 * ■ 🔑 판정은 여기서 안 한다 — `tools/이해대장.js --검사` 하나가 진다. 여기가 맡는 것은
 *   **무엇을 판정 대상으로 세우나**(=이 커밋이 끝난 뒤의 내용)뿐이다. 옆 계약동봉 게이트와 같은 규약.
 *
 * ■ 🔑 재는 것은 작업본이 아니라 **커밋 이후의 내용**이다 — `git commit -- 경로들` 은 범위를 못 박으므로,
 *   작업본에서 둘 다 고쳐 놓고 정본만 커밋하면 **작업본은 초록인데 HEAD 는 빨갛다**(F302 그 자리).
 *     이후 내용 = 스테이징됐으면 인덱스(`:경로`) · 아니면 HEAD(`HEAD:경로`)
 *
 * ■ ⚠ 대가 (맹점 ④ — 새 장치엔 틀릴 때의 모습을 함께 적는다)
 *   틀리는 방향은 **거짓 초록**이다: 형제 저장소를 못 읽는 기계에서는 판정층이 「못 쟀다」로 접고
 *   통과시킨다(막으면 그 세션은 정본을 한 글자도 못 고친다 · F103·F296). 그때 잡는 것은 사후 회귀다.
 *   즉 형제가 없으면 **예방만 잃고 탐지는 남는다.** 「못 했다」를 조용히 넘기지 않고 찍는 이유가 이것이다.
 *   닫은 것: 08-14 하루 네 번의 회수 커밋 — 이제 그 커밋을 «내기 전에» 묻는다.
 */

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');

/* ROOT 는 **이 파일이 속한 저장소**다 — `CLAUDE_PROJECT_DIR` 을 얹으면 안 된다(회귀 `tests/게이트뿌리`).
 *   그 변수가 다른 저장소를 가리키는 자리가 실재하고(워크트리 · F403), 그때 이 게이트는 **옆
 *   저장소의 인덱스를 재고 조용히 통과한다**(실측 `tests/대장동봉E2E.test.js`).
 * 🔑 `__dirname/..` 이 곧 답이다 — 훅은 `$ROOT/tools/…` 로 부르고 워크트리엔 제 사본이 있으니,
 *   이 파일의 자리가 곧 커밋되는 저장소다. git 에게 되묻는 판도 써 봤지만 그건 **cwd 를 따라가**
 *   남의 저장소에서 부르면 그 저장소를 답한다 — 더 많은 부품으로 더 넓은 사각을 만든다. */
const ROOT = path.resolve(__dirname, '..');
const 정본경로 = 'docs/SYNK_철학.md';
const 산출경로 = 'docs/이해대장.html';

/* 화면을 «만드는» 것은 정본만이 아니다 — 생성기와 그 부품도 같은 화면을 그린다.
 *   F520(2026-08-17 실측): Stop 훅의 자동커밋이 `tools/이해대장.js` 만 담아 화면을 두고 갔는데
 *   이 게이트는 **조용히 통과**시켰다. 발동 조건이 정본 한 칸이었기 때문이다.
 *   대조 4수(같은 낡음·스테이징 집합만 바꿈): 도구만 담음 → 판정기 exit 1 · 게이트 exit **0** /
 *   정본을 집합에 더함 → 게이트 exit 1. 훅은 두 경우 다 돌았다(㉠ 「훅을 안 지난다」는 거짓).
 * 🔑 여기 적는 것은 «판정»이 아니라 «언제 판정을 부를까»뿐이다 — 갈라짐은 그래서 안 난다.
 * ⚠ 대가 (맹점 ④ — 틀릴 때의 모습을 함께 적는다): 이 목록은 **손으로 적은 한 홉**이다.
 *   생성기가 새 입력을 읽기 시작하면 그 축은 다시 눈이 먼다 — 새는 방향은 언제나 「통과」다.
 *   닫은 것 = `tests/대장동봉.test.js` 의 실저장소 교차검사(생성기의 in-repo require 를 이 목록과 대조).
 *   **안 닫은 것** = 전이 입력이다. `tools/lib/시트도달.js` 는 엔진 원본(`Code.js`·`엔진_*.js`)을 읽으므로
 *   엔진을 고치는 커밋도 이 화면을 바꿀 수 있는데, 그 층까지 발동 조건에 넣으면 사실상 매 커밋이라
 *   E2E 가 못박은 「매 커밋 소음 0」을 깬다. 그 축은 사후 회귀(`tests/이해대장.test.js`)가 계속 진다. */
const 입력들 = [
  정본경로,                   // 파싱 원본
  'tools/이해대장.js',         // 생성기 — 레이아웃·킷·문구가 여기서 나온다 (F520 이 난 자리)
  'tools/lib/표.js',           // 칸나누기 — 파싱이 바뀌면 화면이 바뀐다
  'tools/lib/시트도달.js',     // 시트층 수집 셈
  'docs/_ops/엔진점수.jsonl',  // 엔진 점수 줄
];

const 말 = (s) => process.stderr.write(s + '\n');

function git(args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

/* ☠️ `-z` 인 이유는 옆 게이트와 같다 — 기본 출력은 비ASCII 경로를 `"\353\217..."` 로 이스케이프해서
 *   한글 경로 대조가 **영원히 안 맞는다**. 그리고 그 모양은 「검사가 통과했다」와 똑같다. */
/* 경로 → 상태 글자(A·M·D·R…). ⚠ `--diff-filter=ACMR` 로 **삭제를 걸러내면 안 된다**: 화면을
 * 지우는 커밋에서 그 경로가 목록에 없어 게이트가 HEAD 사본(= 커밋 뒤엔 없는 파일)을 재고
 * 조용히 통과했다(실측 `tests/대장동봉E2E.test.js` — 화면이 안 바뀌는 개정과 겹치면 그대로 샌다).
 * 이름이 바뀐 경우 원래 자리도 「없어진다」로 센다 — 커밋 뒤 그 경로에 파일이 없는 건 같다. */
function 스테이징상태() {
  const 표 = new Map();
  try {
    const 조각 = git(['diff', '--cached', '--name-status', '-z']).split('\0');
    for (let i = 0; i < 조각.length; i += 1) {
      const 글자 = (조각[i] || '')[0];
      if (!글자) continue;
      if (글자 === 'R' || 글자 === 'C') {
        if (글자 === 'R') 표.set(조각[i + 1], 'D');
        표.set(조각[i + 2], 글자);
        i += 2;
      } else {
        표.set(조각[i + 1], 글자);
        i += 1;
      }
    }
  } catch (_) { return new Map(); }
  return 표;
}

/** `ref:경로` 를 읽는다. ref `''` = 인덱스. 없으면 `null`. */
function 판본(ref, 경로) {
  try { return git(['show', `${ref}:${경로}`]); } catch (_) { return null; }
}

function main() {
  const 스테이징 = 스테이징상태();
  // 화면의 입력이 하나도 안 담긴 커밋은 이 게이트의 대상이 아니다(매 커밋 소음 0 · E2E 가 못박는다).
  // **지우는** 커밋도 마찬가지 — 그건 이 가드가 아니라 사람이 볼 일이고, 여기서 막으면 되돌릴 통로가 사라진다.
  const 담긴입력 = 입력들.filter((p) => { const s = 스테이징.get(p); return s && s !== 'D'; });
  if (!담긴입력.length) return 0;

  const 정본뒤 = 판본('', 정본경로);
  if (정본뒤 === null) {
    말(`[이해대장] 커밋될 정본을 못 읽어 동기 대조를 **못 했다**(${정본경로}) — 막지 않는다.`);
    return 0;
  }

  /* ⚠ 판정기가 통째로 없는 자리(부분 체크아웃·낡은 워크트리)를 차단으로 바꾸면 그 세션은
   * 정본을 한 글자도 못 고친다 — 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103).
   * 훅이 이 게이트에 대해 쓰는 규약(「없으면 막지 않고 말한다」)을 게이트도 그대로 쓴다.
   * 안 두면 `node` 가 MODULE_NOT_FOUND 로 1을 내고 그게 곧 차단이 된다(실측). */
  const 판정기 = path.join(ROOT, 'tools', '이해대장.js');
  if (!fs.existsSync(판정기)) {
    말(`[이해대장] 판정기가 없어 동기 대조를 **못 했다**(${판정기}) — 막지 않는다.`);
    return 0;
  }

  const 산출상태 = 스테이징.get(산출경로);
  const 산출뒤 = 산출상태 === 'D' ? null : 판본(산출상태 ? '' : 'HEAD', 산출경로);

  /* 임시 파일 두 벌 — 작업본을 건드리지 않는다. 옆 세션이 같은 파일을 읽는 중일 수 있고,
   * 커밋 훅이 작업본을 흔들면 그 자체가 남의 트랙을 깨는 사고다(F073 축). */
  const 방 = fs.mkdtempSync(path.join(os.tmpdir(), 'synk-대장-'));
  try {
    const 정본tmp = path.join(방, 'SYNK_철학.md');
    const 산출tmp = path.join(방, '이해대장.html');
    fs.writeFileSync(정본tmp, 정본뒤, 'utf8');
    if (산출뒤 !== null) fs.writeFileSync(산출tmp, 산출뒤, 'utf8');

    const r = spawnSync(process.execPath, [판정기, '--검사'], {
      cwd: ROOT,
      encoding: 'utf8',
      /* 처방이 «실제로 담긴 경로»를 대야 한다 — 정본이 안 담긴 커밋(생성기만 고친 커밋)에
       * 「docs/SYNK_철학.md 도 넣어라」를 내밀면 안 고친 파일을 담으라는 말이 되고, 그대로 따르면
       * 정작 담아야 할 생성기가 빠진다. 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103).
       * 문구는 판정기 한 곳이 짓는다 — 여기서 같이 지으면 두 곳이 갈린다(신뢰성 ④). */
      env: { ...process.env, SYNK_대장_정본: 정본tmp, SYNK_대장_산출: 산출tmp, SYNK_대장_담긴입력: 담긴입력.join(' ') },
    });
    if (r.stdout) process.stdout.write(r.stdout);
    if (r.stderr) process.stderr.write(r.stderr);
    if (r.status === null) {
      말('[이해대장] 판정기를 못 돌려 동기 대조를 **못 했다** — 막지 않는다.');
      return 0;
    }
    return r.status;
  } finally {
    try { fs.rmSync(방, { recursive: true, force: true }); } catch (_) { /* 임시방 청소 실패는 판정이 아니다 */ }
  }
}

process.exit(main());
