function 항목들(고른) {
  const 이름들 = 고른 === '전부' ? Object.keys(세트들) : 고른.split(',').map((s) => s.trim());
  const 낸다 = [];
  for (const s of 이름들) {
    if (!세트들[s]) {
      console.error(`🔴 모르는 세트: ${s} — 아는 것은 ${Object.keys(세트들).join('·')}·전부`);
      process.exit(1);
    }
    for (const it of 세트들[s]()) {
      낸다.push({ 세트: s, ...it, 이름: it.이름 || 안전(it.본문 || it.형태) });
    }
  }
  return 낸다;
}

