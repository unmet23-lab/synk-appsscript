  console.log(`■ 세트 굽기 — ${목록.length}장 · 샘플 ${견본} · ${너비}px · ${장치} · → ${밖뿌리}`);
  console.log(`  세트: ${[...new Set(목록.map((i) => i.세트))].join(' · ')}${다시 ? ' · 다시굽기' : ''}`);
  const 시작 = Date.now();
  const 실패 = [];
