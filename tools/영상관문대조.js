#!/usr/bin/env node
'use strict';
/* 영상 관문 대조 — 다시 검수 결과.json을 그 앞의 결과 파일들과 맞대어, 검수자가 옮겨 적은 지난 등급 · 번호가 맞는지와
 * 열려 있던 P0 · P1이 확인 없이 사라지지 않았는지 본다(2026-11-17).
 *
 * 왜: 영상 관문 워크플로(.claude/workflows/video-gate.js)는 파일을 읽지 못한다. 그래서 다시 검수에서 지난 지적의 번호 · 등급은
 *   다시 본 검수 에이전트가 지난 결과.json을 읽고 답에 옮겨 적는다. 컷 판정은 그 등급으로 갈린다(P0 · P1 「그대로」만 컷 판정에 든다).
 *   11-17 두 편의 다시 검수 세 번을 대조하니 100줄 가운데 4줄이 지난 결과와 달랐다. P2를 P1로 올려 적은 줄은 반박 없이 컷 판정에 들어갔고,
 *   P1을 P2로 낮춰 적은 줄은 「P2 · P3」 칸으로 빠진다. 이 도구는 그 줄을 찾아 알린다. 검수자를 부르지 않고 파일만 읽는다.
 *
 *   node tools/영상관문대조.js <다시 검수 결과.json> [--앞결과 <지난 결과.json>] [--json]
 *   node tools/영상관문대조.js <다시 검수 결과.json> --적기 "<이름>=고쳐짐:<본 것>" [--적기 "<이름>=그대로:<본 것>" …]
 *
 *   대조는 읽기만 한다. --적기만 그 결과.json의 「다시결과」에 줄을 더한다. 검수 세션이 「넣을 것」 · 「다시 보지 않은 것」을 직접 보고 정한 것을 남기는 길이다.
 *   이름은 이 도구가 찍은 그대로 적는다(「지난 F12」 꼴). 「그대로」로 적은 줄은 컷 판정에 들어간 줄이 되어 다음 다시 검수자가 넘겨받고,
 *   「고쳐짐」으로 적은 줄은 그 지적을 닫는다(같은 회차에 검수자의 「그대로」 줄이 있으면 닫히지 않는다). 열린 P0 · P1에만 적을 수 있다.
 *
 * 보는 법: 결과.json의 「앞결과」 칸을 따라 첫 관문까지 거슬러 올라가 결과 파일의 사슬을 읽는다(바로 앞 결과가 다른 자리에 있으면 --앞결과).
 *   사슬이 곧 장부다. 어느 관문에서 P0 · P1로 유지 · 확인된 지적은, 뒤 관문의 「다시결과」에 「고쳐짐」 줄이 생길 때까지 열린 지적이다.
 *   「그대로」 줄이 있거나 아무 줄이 없으면 계속 열려 있다. 그래서 한 회차에서 등급이 낮춰 적혔거나 검수자가 답하지 않았어도 지적을 잃지 않는다.
 *   지적의 이름은 표와 같은 꼴이다. 바로 앞 관문의 지적은 「지난 F12」, 한 번 더 앞 관문의 지적은 「지난 지난 F12」다.
 *
 * 알리는 것
 *   - 넣을 것: 열린 P0 · P1인데 이번에 낮춰 적혀 컷 판정에서 빠진 「그대로」 줄. 그 컷의 할 일에 넣는다.
 *   - 따져 볼 것: 처음 나온 관문에서 P2 · P3(또는 기각)인데 올려 적혀 컷 판정에 들어간 「그대로」 줄. 반박을 거치지 않은 P1이다.
 *     검수 세션이 근거 그림을 열어 P1이 맞는지 정하고, 아니면 그 컷의 할 일에서 뺀다.
 *   - 번호를 확인할 것: 「지난」 칸의 번호가 지난 결과에 없는 줄, 번호 꼴이 다른 줄(지난 결과의 「다시결과」에서 온 지적은 「지난 F12」로 적혀야 한다).
 *   - 다시 보지 않은 것: 열린 P0 · P1이 이번 판의 컷에 걸려 있는데 이번 「다시결과」에 그 지적의 줄이 없다. 검수 세션이 그 컷을 직접 본다.
 *     「고쳐짐」 줄이 생기기 전에는 다음 회차에도 다시 알린다.
 *   - 이번 판에 없는 열린 지적: 열린 P0 · P1인데 그 컷이 이번 판에 없었다. 틀린 것은 아니고, 아직 남은 일이다(끝 코드를 바꾸지 않는다).
 *   - 참고: 컷 판정은 그대로인데 등급 · 고칠곳이 처음 나온 관문과 다른 「그대로」 줄.
 * 못 가리는 것: 11-17 전에 나온 결과는 지난 결과의 「다시결과」에서 넘어온 지적도 「지난 」 없이 적었다. 그 번호가 지난 결과의 새 지적 번호와 겹치면
 *   새 지적으로 읽는다(가릴 길이 없다). 그런 줄은 「다시 보지 않은 것」으로 한 번 더 나오니 검수 세션이 「무엇」을 읽어 정한다.
 * 끝 코드: 0 넣을 것 · 따져 볼 것 · 번호를 확인할 것 · 다시 보지 않은 것이 없고 사슬을 첫 관문까지 읽음 · 2 볼 것이 있거나 사슬이 끊김 · 1 입력 오류. 시험: node --test tests/영상관문대조.test.js
 */
const fs = require('node:fs');
const path = require('node:path');

const 무거운등급 = g => g === 'P0' || g === 'P1';
const 등급순 = ['P0', 'P1', 'P2', 'P3'];

function 읽기(파일) {
  let 글;
  try { 글 = fs.readFileSync(파일, 'utf8'); } catch (e) { throw new Error(`결과 파일을 읽지 못했다: ${파일} (${e.code || e.message})`); }
  let j;
  try { j = JSON.parse(글); } catch (e) { throw new Error(`결과 파일이 JSON이 아니다: ${파일}`); }
  if (!j || !Array.isArray(j.지적)) throw new Error(`관문 결과 파일이 아니다(「지적」이 없다): ${파일}`);
  return j;
}

// 「다시결과」 줄에 붙은 이름. 11-17 전에 나온 결과에는 「번호」 칸이 없어 「지난」 칸으로 만든다.
const 줄이름 = f => String(f.번호 || `지난 ${String(f.지난 || '').trim()}`).trim();
const 적힌번호 = f => String(f.지난 || '').trim();
// 그 줄이 그 회차의 컷 판정에 들어갔나. 「컷판정에」 칸이 없는 옛 결과는 등급으로 가린다(그때 워크플로는 등급을 보지 않고 다 넣었지만, 고친 계산에 맞춘다).
const 들어갔나 = f => (f.컷판정에 ? f.컷판정에 === '들어감' : !(f.등급 === 'P2' || f.등급 === 'P3'));
const 컷나눔 = 컷글 => String(컷글).split(/[,\s]+/).filter(Boolean);

/* 결과 파일의 사슬을 첫 관문 쪽부터 차례로 돌려준다. 마지막이 대조할 결과다. 회차 수에 한도를 두지 않는다(한도에서 자르면 그 앞의 열린 지적이 말없이 사라진다).
 * 거슬러 올라가다 파일을 못 읽거나 같은 파일로 되돌아오면 거기서 멈춘다(끊긴 사슬). 읽은 데까지를 장부로 쓰되, 끊긴 사슬은 통과로 치지 않는다. */
function 사슬읽기(결과파일, 앞결과파일) {
  const 끝 = 읽기(결과파일);
  const 회차 = [{ 파일: 결과파일, r: 끝 }];
  if (끝.다시 !== true) return { 회차, 끊김: '' };
  const 바로앞 = 앞결과파일 || 끝.앞결과;
  if (!바로앞) throw new Error('지난 결과 자리를 모른다 — 결과.json에 「앞결과」가 없다. --앞결과 <지난 결과.json>을 준다');
  회차.unshift({ 파일: 바로앞, r: 읽기(바로앞) }); // 바로 앞 결과를 못 읽으면 여기서 멈춘다
  let 끊김 = '';
  const 본파일 = new Set([path.resolve(결과파일), path.resolve(바로앞)]);
  while (회차[0].r.다시 === true) {
    const 앞 = 회차[0].r.앞결과;
    if (!앞) { 끊김 = `${회차[0].파일}에 「앞결과」가 없다`; break; }
    if (본파일.has(path.resolve(앞))) { 끊김 = `「앞결과」가 이미 읽은 파일로 되돌아온다: ${앞}`; break; }
    let r;
    try { r = 읽기(앞); } catch (e) { 끊김 = e.message; break; }
    본파일.add(path.resolve(앞));
    회차.unshift({ 파일: 앞, r });
  }
  return { 회차, 끊김 };
}

/* 회차 i의 결과에 적힌 이름(새 지적의 id, 또는 다시결과 줄의 번호)이 가리키는 지적의 열쇠를 찾는다.
 * 열쇠: 「<처음 나온 회차>#<id>」. 사슬이 끊겨 처음 나온 관문을 못 읽으면 「<회차>~<줄 이름>」(그 줄을 뿌리로 삼는다).
 * 돌려주는 값: { 열쇠, 꼴다름 } 또는 null(그 이름의 지적이 없다). */
function 풀기(회차, i, 이름) {
  if (i < 0 || !이름) return null;
  const r = 회차[i].r;
  if (r.지적.some(f => f.id === 이름)) return { 열쇠: `${i}#${이름}`, 꼴다름: false };
  let 줄들 = (r.다시결과 || []).filter(f => 줄이름(f) === 이름);
  let 꼴다름 = false;
  if (!줄들.length && !이름.startsWith('지난 ')) {
    // 옛 꼴: 지난 결과의 「다시결과」에서 넘어온 지적을 「지난 」 없이 적었다. 그 결과의 새 지적에 같은 번호가 없을 때만(위에서 못 찾았을 때만) 그 줄로 본다
    줄들 = (r.다시결과 || []).filter(f => 줄이름(f) === `지난 ${이름}`);
    꼴다름 = 줄들.length > 0;
  }
  if (!줄들.length) {
    // 이 회차에 그 이름의 줄이 없어도 이름만으로 거슬러 올라간다. 「지난 X」는 바로 앞 회차의 X다.
    // 검수자가 한 회차 답하지 않은 지적은 그 회차 결과에 줄이 없다. 뒤 회차에서 그 지적을 다시 가리킬 수 있어야 「고쳐짐」으로 닫을 수 있다
    return 이름.startsWith('지난 ') && i >= 1 ? 풀기(회차, i - 1, 이름.slice('지난 '.length)) : null;
  }
  // 같은 지난 지적을 여러 관점이 봤어도 가리키는 지적은 하나다 — 첫 줄의 「지난」으로 거슬러 올라간다
  const 위 = 풀기(회차, i - 1, 적힌번호(줄들[0]));
  return { 열쇠: 위 ? 위.열쇠 : `${i}~${줄이름(줄들[0])}`, 꼴다름: 꼴다름 || !!(위 && 위.꼴다름) };
}

/* 사슬을 첫 관문부터 훑어 장부를 만든다. 대조할 회차(마지막) 바로 앞까지의 상태가 「전」이다.
 * 장부 줄: { 열쇠, 난회차, 이름(난 회차에서의 이름), 등급 · 상태(처음 나온 관문), 컷, 고칠곳, 열림 } */
function 장부짓기(회차, 끝회차) {
  const 장부 = new Map();
  for (let i = 0; i < 끝회차; i += 1) {
    const r = 회차[i].r;
    // 이 회차의 다시결과 — 지적마다 한 관점이라도 「그대로」면 열림, 모두 「고쳐짐」이면 닫힘
    const 묶음 = new Map();
    for (const f of r.다시결과 || []) {
      const 풀 = 풀기(회차, i - 1, 적힌번호(f));
      const 열쇠 = 풀 ? 풀.열쇠 : `${i}~${줄이름(f)}`; // 앞 회차를 못 읽었거나 없는 번호 — 이 줄을 뿌리로 삼는다
      if (!묶음.has(열쇠)) 묶음.set(열쇠, []);
      묶음.get(열쇠).push(f);
    }
    for (const [열쇠, 줄들] of 묶음) {
      const 남은 = 줄들.filter(f => f.상태 === '그대로');
      let 줄 = 장부.get(열쇠);
      if (!줄) {
        // 장부에 없는 지적: 처음 나온 관문에서 가벼웠거나(올려 적힌 것) 사슬이 끊겨 뿌리를 못 읽은 것. 끊긴 사슬의 줄만 뿌리로 받는다
        if (!열쇠.includes('~') || !남은.some(들어갔나)) continue;
        const 센 = 남은.filter(들어갔나).slice().sort((a, b) => 등급순.indexOf(a.등급) - 등급순.indexOf(b.등급))[0];
        줄 = { 열쇠, 난회차: i, 이름: 줄이름(센), 등급: 무거운등급(센.등급) ? 센.등급 : 'P1', 상태: '다시 검수 그대로', 컷: 센.컷, 고칠곳: 센.고칠곳 || '', 열림: true };
        장부.set(열쇠, 줄);
        continue;
      }
      줄.열림 = 남은.length > 0;
      if (남은.length) { 줄.컷 = 남은[0].컷 || 줄.컷; 줄.고칠곳 = 남은[0].고칠곳 || 줄.고칠곳; }
    }
    // 이 회차의 새 지적 — 반박을 거쳐 남은 P0 · P1(유지 · 확인)이 열린 지적이 된다
    for (const f of r.지적) {
      if ((f.상태 === '유지' || f.상태 === '확인') && 무거운등급(f.등급)) {
        장부.set(`${i}#${f.id}`, { 열쇠: `${i}#${f.id}`, 난회차: i, 이름: f.id, 등급: f.등급, 상태: f.상태, 컷: f.컷, 고칠곳: f.고칠곳 || '', 열림: true });
      }
    }
  }
  return 장부;
}

// 열쇠가 가리키는 지적이 처음 나온 관문에서 받은 등급 · 상태 · 고칠곳(장부에 없는 가벼운 지적 · 기각한 지적도 읽는다)
function 뿌리정보(회차, 열쇠) {
  const 자리 = 열쇠.indexOf('#');
  if (자리 < 0) return null;
  const f = 회차[Number(열쇠.slice(0, 자리))].r.지적.find(x => x.id === 열쇠.slice(자리 + 1));
  return f ? { 등급: f.등급 || '', 상태: f.상태 || '', 고칠곳: f.고칠곳 || '' } : null;
}

function 대조(결과파일, 앞결과파일) {
  const { 회차, 끊김 } = 사슬읽기(결과파일, 앞결과파일);
  const 끝 = 회차.length - 1;
  const r = 회차[끝].r;
  const 빈 = { 넣을것: [], 따져볼것: [], 번호확인: [], 안본것: [], 판밖열림: [], 참고: [] };
  if (r.다시 !== true) return { 다시: false, 줄수: 0, 사슬: 1, 끊김: '', ...빈 };
  const 장부 = 장부짓기(회차, 끝);
  const 지금이름 = 줄 => `${'지난 '.repeat(끝 - 줄.난회차)}${줄.이름}`;
  const { 넣을것, 따져볼것, 번호확인, 안본것, 판밖열림, 참고 } = 빈;
  const 본열쇠 = new Set();
  const 본줄 = new Set();
  const 들어간열쇠 = new Set();
  for (const f of r.다시결과 || []) {
    const 풀 = f.상태 === '그대로' && 들어갔나(f) ? 풀기(회차, 끝 - 1, 적힌번호(f)) : null;
    if (풀) 들어간열쇠.add(풀.열쇠);
  }
  for (const f of r.다시결과 || []) {
    const 이름 = f.번호 || `지난 ${적힌번호(f) || '(번호 없음)'}`;
    const 적힌등급 = '옮겨적은등급' in f ? f.옮겨적은등급 : f.등급; // 워크플로가 센 등급으로 바꿔 적은 줄은 검수자가 적은 값과 견준다
    const 줄 = { 번호: 이름, 컷: f.컷, 상태: f.상태, 적힌등급: 적힌등급 || '', 고칠곳: f.고칠곳, 관점: f.관점 || '' };
    const 풀 = 풀기(회차, 끝 - 1, 적힌번호(f));
    if (풀) 본열쇠.add(풀.열쇠);
    const 같은줄 = JSON.stringify([이름, f.컷, f.상태, 적힌등급, f.고칠곳]);
    if (본줄.has(같은줄)) continue;
    본줄.add(같은줄);
    if (!풀) {
      번호확인.push({ ...줄, 까닭: '지난 결과에 이 번호의 지적이 없다' });
      continue;
    }
    if (풀.꼴다름) 번호확인.push({ ...줄, 까닭: `지난 결과의 「다시결과」에서 온 지적이다. 「지난」 칸에 「지난 ${적힌번호(f)}」로 적혀야 한다(그러면 이번 표의 이름은 「지난 지난 ${적힌번호(f)}」)` });
    const 장부줄 = 장부.get(풀.열쇠);
    const 뿌리 = 장부줄 || 뿌리정보(회차, 풀.열쇠);
    if (!뿌리) continue; // 끊긴 사슬에서 가볍게 넘어온 줄 — 견줄 값이 없다
    줄.지난등급 = 뿌리.등급 || '';
    줄.지난상태 = 뿌리.상태 || '';
    if (f.상태 !== '그대로') continue; // 「고쳐짐」 줄은 컷 판정에 쓰이지 않는다
    const 들어감 = 들어갔나(f);
    const 들어가야 = !!장부줄; // 장부에 있는 지적 = 처음 나온 관문에서 P0 · P1 유지 · 확인
    if (들어가야 && !들어감) {
      // 같은 지적의 다른 줄(다른 관점 · 검수 세션이 적은 줄)이 이미 컷 판정에 들어가 있으면 넣을 것이 아니다
      if (!들어간열쇠.has(풀.열쇠)) 넣을것.push(줄);
      continue;
    }
    if (!들어가야 && 들어감) { 따져볼것.push({ ...줄, 까닭: 뿌리.상태 === '기각' ? '지난 결과에서 기각한 지적이다' : '처음 나온 관문에서는 반박을 거치지 않은 등급이다' }); continue; }
    if (줄.적힌등급 !== 줄.지난등급 || (뿌리.고칠곳 && f.고칠곳 !== 뿌리.고칠곳)) 참고.push({ ...줄, 지난고칠곳: 뿌리.고칠곳 || '' });
  }
  // 열려 있던 P0 · P1 가운데 이번에 아무 줄도 없는 것 — 이번 판의 컷에 걸렸으면 다시 보지 않은 것, 아니면 아직 남은 일
  const 이번컷 = new Set((r.컷별 || []).map(c => c.cut));
  const 걸림 = 컷글 => 컷글 === '전체' || 컷나눔(컷글).some(c => 이번컷.has(c));
  for (const 줄 of 장부.values()) {
    if (!줄.열림 || 본열쇠.has(줄.열쇠)) continue;
    const 낱 = { 번호: 지금이름(줄), 컷: 줄.컷, 등급: 줄.등급, 상태: 줄.상태, 고칠곳: 줄.고칠곳 };
    (걸림(줄.컷) ? 안본것 : 판밖열림).push(낱);
  }
  return { 다시: true, 앞결과: 회차[끝 - 1].파일, 줄수: (r.다시결과 || []).length, 사슬: 회차.length, 끊김, 넣을것, 따져볼것, 번호확인, 안본것, 판밖열림, 참고 };
}

const 세션관점 = '검수 세션(대조)';

/* 검수 세션이 직접 본 결과를 이번 결과.json의 「다시결과」에 적는다. 이 도구가 파일을 고쳐 쓰는 길은 이것뿐이다.
 * 항목: "<이름>=고쳐짐:<본 것>" 또는 "<이름>=그대로:<본 것>". 이름은 대조가 찍은 그대로(이번 표의 이름).
 * 열린 P0 · P1(장부에 있는 지적)에만 적는다. 등급 · 컷 · 고칠곳은 장부의 값을 쓴다. 같은 지적에 앞서 적은 세션 줄은 새 줄로 바꾼다. */
function 적기(결과파일, 항목들) {
  // 결과.json에 적힌 「앞결과」 사슬로만 적는다. 다른 사슬(--앞결과)을 기준으로 적으면 뒤 회차의 대조가 그 줄을 저장된 사슬의 다른 지적으로 읽는다
  const { 회차, 끊김 } = 사슬읽기(결과파일, '');
  if (끊김) throw new Error(`앞 결과를 첫 관문까지 읽지 못해 적지 않았다 — ${끊김}`);
  const 끝 = 회차.length - 1;
  const r = 회차[끝].r;
  if (r.다시 !== true) throw new Error('첫 관문 결과에는 적을 지난 지적이 없다');
  const 장부 = 장부짓기(회차, 끝);
  const 더할 = [];
  for (const 글 of 항목들) {
    const m = /^(지난 [^=]+)=(고쳐짐|그대로):([\s\S]+)$/.exec(String(글).trim());
    if (!m || !m[3].trim()) throw new Error(`--적기 꼴이 아니다: 「${글}」 — "<이름>=고쳐짐:<본 것>" 또는 "<이름>=그대로:<본 것>"으로 적는다`);
    const 이름 = m[1].trim();
    const 지난값 = 이름.slice('지난 '.length);
    const 풀 = 풀기(회차, 끝 - 1, 지난값);
    const 장부줄 = 풀 && 장부.get(풀.열쇠);
    if (!장부줄) throw new Error(`「${이름}」은 앞 결과들에서 열린 P0 · P1로 찾지 못했다 — 대조가 찍은 이름을 그대로 적는다`);
    더할.push({
      번호: 이름, 지난: 지난값, 컷: 장부줄.컷, 등급: 장부줄.등급, 상태: m[2], 무엇: m[3].trim(), 근거: [], 고칠곳: 장부줄.고칠곳, 관점: 세션관점,
      ...(m[2] === '그대로' ? { 컷판정에: '들어감' } : {}),
    });
  }
  const 이름들 = new Set(더할.map(x => x.번호));
  r.다시결과 = (r.다시결과 || []).filter(f => !(f.관점 === 세션관점 && 이름들.has(f.번호))).concat(더할);
  const 임시 = `${결과파일}.대조-임시`;
  fs.writeFileSync(임시, JSON.stringify(r), 'utf8');
  try { fs.renameSync(임시, 결과파일); } catch (e) { fs.rmSync(임시, { force: true }); throw new Error(`결과 파일에 쓰지 못했다: ${결과파일} (${e.code || e.message})`); }
  return 더할;
}

function 보고글(d) {
  if (!d.다시) return ['첫 관문 결과라 대조할 지난 지적이 없다.'];
  const 줄 = [`다시결과 ${d.줄수}줄을 앞 결과 ${d.사슬 - 1}개와 대조했다. 바로 앞 결과: ${d.앞결과}`];
  if (d.끊김) 줄.push('', `앞 결과를 첫 관문까지 읽지 못했다 — ${d.끊김}`, '읽은 데까지만 장부로 썼다. 그 앞에서 열린 P0 · P1이 빠졌을 수 있으니 통과로 치지 않는다. 앞 결과 파일을 제자리에 두고 다시 돌린다.');
  const 한줄 = x => `  ${x.번호} · ${x.컷} · ${x.상태} · 적힌 등급 ${x.적힌등급 || '(없음)'}${'지난등급' in x ? ` · 처음 나온 관문 ${x.지난등급 || '(없음)'}(${x.지난상태 || '상태 없음'})` : ''} · 고칠곳 ${x.고칠곳 || '(없음)'}`;
  const 열린줄 = x => `  ${x.번호} · ${x.컷} · 처음 나온 관문 ${x.등급 || '(없음)'}(${x.상태}) · 고칠곳 ${x.고칠곳 || '(없음)'}`;
  if (d.넣을것.length) {
    줄.push('', `넣을 것 ${d.넣을것.length}줄 — 열린 P0 · P1인데 낮춰 적혀 컷 판정에서 빠졌다. 그 컷의 할 일에 넣는다:`);
    for (const x of d.넣을것) 줄.push(한줄(x));
  }
  if (d.따져볼것.length) {
    줄.push('', `따져 볼 것 ${d.따져볼것.length}줄 — 컷 판정에 들어갔는데 처음 나온 관문에서는 P0 · P1 유지가 아니다. 근거 그림을 열어 P1이 맞는지 정하고, 아니면 그 컷의 할 일에서 뺀다:`);
    for (const x of d.따져볼것) 줄.push(`${한줄(x)} — ${x.까닭}`);
  }
  if (d.번호확인.length) {
    줄.push('', `번호를 확인할 것 ${d.번호확인.length}줄:`);
    for (const x of d.번호확인) 줄.push(`${한줄(x)} — ${x.까닭}`);
  }
  if (d.안본것.length) {
    줄.push('', `다시 보지 않은 것 ${d.안본것.length}줄 — 열린 P0 · P1이 이번 판의 컷에 걸려 있는데 이번 다시결과에 줄이 없다. 고쳐졌는지 그 컷을 직접 본다:`);
    for (const x of d.안본것) 줄.push(열린줄(x));
  }
  if (d.판밖열림.length) {
    줄.push('', `이번 판에 없는 열린 지적 ${d.판밖열림.length}줄 — 아직 고쳐졌다는 확인이 없고, 그 컷이 이번 판에 없었다. 남은 일이다:`);
    for (const x of d.판밖열림) 줄.push(열린줄(x));
  }
  if (d.참고.length) {
    줄.push('', `참고 ${d.참고.length}줄 — 「그대로」 줄 가운데 컷 판정은 바뀌지 않고 등급이나 고칠곳만 처음 나온 관문과 다르다:`);
    for (const x of d.참고) 줄.push(`${한줄(x)}${x.지난고칠곳 && x.지난고칠곳 !== x.고칠곳 ? ` · 처음 고칠곳 ${x.지난고칠곳}` : ''}`);
  }
  if (!d.넣을것.length && !d.따져볼것.length && !d.번호확인.length && !d.안본것.length && !d.끊김) 줄.push('', '컷 판정을 바꿀 차이는 없다.');
  return 줄;
}

function 실행(argv) {
  const 인자 = argv.slice();
  const json = 인자.includes('--json');
  const 앞자리 = 인자.indexOf('--앞결과');
  const 앞결과 = 앞자리 >= 0 ? 인자[앞자리 + 1] : '';
  const 적을것 = [];
  const 뺄자리 = new Set();
  if (앞자리 >= 0) { 뺄자리.add(앞자리); 뺄자리.add(앞자리 + 1); }
  인자.forEach((x, i) => { if (x === '--적기') { 뺄자리.add(i); 뺄자리.add(i + 1); 적을것.push(인자[i + 1]); } });
  const 나머지 = 인자.filter((x, i) => x !== '--json' && !뺄자리.has(i));
  if (나머지.length !== 1 || (앞자리 >= 0 && !앞결과) || 적을것.some(x => !x)) {
    return { 코드: 1, 줄: ['쓰는 법: node tools/영상관문대조.js <다시 검수 결과.json> [--앞결과 <지난 결과.json>] [--json] [--적기 "<이름>=고쳐짐:<본 것>" …]'] };
  }
  const 결과파일 = path.resolve(나머지[0]);
  const 앞 = 앞결과 ? path.resolve(앞결과) : '';
  if (적을것.length && 앞) return { 코드: 1, 줄: ['--적기는 --앞결과와 함께 쓰지 않는다 — 결과.json에 적힌 「앞결과」 사슬로만 적는다. 앞 결과 파일의 자리가 바뀌었으면 결과.json의 「앞결과」를 먼저 바로잡는다'] };
  let d;
  let 적은 = [];
  try {
    if (적을것.length) 적은 = 적기(결과파일, 적을것);
    d = 대조(결과파일, 앞);
  } catch (e) { return { 코드: 1, 줄: [e.message] }; }
  // 끊긴 사슬은 열린 지적을 다 읽지 못한 것이라 통과(0)로 치지 않는다
  const 걸림 = d.넣을것.length + d.따져볼것.length + d.번호확인.length + d.안본것.length + (d.끊김 ? 1 : 0);
  const 머리 = 적은.length ? [`결과.json에 검수 세션이 본 것 ${적은.length}줄을 적었다: ${적은.map(x => `${x.번호} ${x.상태}`).join(' · ')}`, ''] : [];
  return { 코드: 걸림 ? 2 : 0, 줄: json ? [JSON.stringify({ ...d, 적은 }, null, 1)] : 머리.concat(보고글(d)), 대조: d, 적은 };
}

if (require.main === module) {
  const { 코드, 줄 } = 실행(process.argv.slice(2));
  console.log(줄.join('\n'));
  process.exitCode = 코드;
}

