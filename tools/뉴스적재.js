#!/usr/bin/env node
/* 뉴스적재 — 부팅 브리핑(구글뉴스 RSS 3축)을 바탕화면 「SYNK 운영자료」의 누적 로그에 붙인다.
 *
 * 왜 있나 (유호 확정 2026-08-12 「수신자 교체」):
 *   `SYNK_BootBrief` 예약 작업은 08-05~08-11 에 **6번 성공 발송**했고 폴백은 0회였다 — 기계는 멀쩡했다.
 *   문제는 배달지였다. 유일한 출구가 `hermes send --to telegram` 이라 본문은 `%TEMP%` 파일에
 *   덮어써지고 사라졌고, 유호님은 안 읽는다고 확정했으며, **AI 컨텍스트에도 0글자 들어오지 않았다**
 *   (`.claude/hooks/`·`settings.json` 에 참조 0건 · SessionStart 에 실리는 건 철학카드·결정큐·대기열·작업본소유자 넷뿐).
 *   즉 「잘 도는 기계가 아무도 안 읽는 곳에 배달」 — 고칠 것은 수집이 아니라 수신자다.
 *
 * 설계 원칙 4:
 *   ① **바탕화면 경로를 여기서 판정하지 않는다** — `lib/바탕화면.js` 한 통로만 쓴다.
 *      경로 사본은 `tests/바탕화면통로.test.js` 가 문다(08-09 「안 보이는데?」 사고의 재발 방지).
 *   ② **요약과 원시를 같이 남긴다.** 헤르메스 6줄은 「사람이 읽기 좋은 것」 기준으로 고른 것이라
 *      「학원 판정에 필요한 것」과 기준이 다르다. 재료로 쓸 땐 걸러지기 전이 낫다.
 *   ③ **상한을 조용히 적용하지 않는다** — 오래된 구획을 버리면 몇 개를 버렸는지 출력에 밝힌다
 *      (CLAUDE.md 「초록은 분모와 함께만 읽는다」의 같은 축 — 잘라놓고 조용하면 전량으로 읽힌다).
 *   ④ **줄끝은 실측한다** — 기존 파일이 CRLF 면 CRLF 로 쓴다(board-move F046 과 같은 함정).
 *
 * 🚫 SessionStart 주입은 하지 않는다. 상주물은 세션 수만큼 곱해지고(CLAUDE.md 컨텍스트 절),
 *    이 파일은 마케팅·비자·개원 판정을 할 때만 열면 된다 — 상주 비용 0.
 *
 * 사용:
 *   node tools/뉴스적재.js --요약 <파일> [--원시 <파일>] [--날짜 <ISO>] [--상한 N]
 *   node tools/뉴스적재.js --어디                 적재 대상 파일 경로만 찍는다(읽으러 갈 때)
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { 찾기: 바탕화면 } = require('./lib/바탕화면.js');
const { 갈래폴더 } = require('./운영자료.js');

/** 로그 파일의 이름. 2026-08-17 재편으로 번호 접두(`NN_`)가 없어졌다 —
 *  옛 번호가 붙은 파일은 `로그찾기` 가 번호를 떼고 찾아내므로 이름이 바뀌어도 이어 쓴다. */
const 로그이름 = '시장뉴스_수집로그.md';
const 기본상한 = 60; // 구획 수. 하루 1~2회 × 두 달치. 그보다 오래된 시장 뉴스는 판정 재료가 아니다.
const 요일 = ['일', '월', '화', '수', '목', '금', '토'];

const 머리 = [
  '# SYNK 시장 뉴스 — 자동 수집 로그',
  '',
  '> 자동 생성 — 예약 작업 `SYNK_BootBrief` 가 PC 로그온 때(12시간에 1번) 구글뉴스 RSS 3축',
  '> (`몽골 유학` · `한국 유학 비자 정책` · `몽골 한국어`)을 긁어 헤르메스가 6줄로 줄인 것이다.',
  '> **위가 최신.** 요약은 사람이 읽기 좋게 고른 것이라, 판정 재료로는 각 구획의 「원시」가 낫다.',
  `> 최근 ${기본상한}구획만 남는다(그 아래는 자동으로 버려진다).`,
  '',
].join('\n');

/* ── 순수 함수(회귀가 이 넷을 붙든다) ─────────────────────────── */

/** 파일 내용에서 줄끝을 실측한다. CRLF 가 하나라도 있으면 CRLF. */
function 줄끝(내용) {
  return /\r\n/.test(String(내용 || '')) ? '\r\n' : '\n';
}

/** `2026-08-12T09:40:00` → `2026-08-12 (수) 09:40`. Date 를 받아 문자열만 만든다. */
function 시각표기(d) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} (${요일[d.getDay()]}) ${p(d.getHours())}:${p(d.getMinutes())}`;
}

/** 한 회분 구획. 요약이 비면 그 사실을 적는다 — 빈 구획을 조용히 만들지 않는다. */
function 구획만들기(시각, 요약, 원시) {
  const 줄 = ['---', '', `## ${시각}`, ''];
  줄.push(String(요약 || '').trim() || '(요약 없음 — 헤르메스 출력이 비었다)');
  const r = String(원시 || '').trim();
  if (r) 줄.push('', '### 원시 (요약이 버린 것까지 전부)', '', r);
  줄.push('');
  return 줄.join('\n');
}

/** 기존 내용 = 머리 + 구획들. 머리는 첫 `---` 앞까지다(없으면 전부가 머리). */
function 가르기(내용) {
  const s = String(내용 || '').replace(/\r\n/g, '\n');
  const m = /^---$/m.exec(s);
  if (!m) return { 머리: s, 구획들: [] };
  const 몸 = s.slice(m.index);
  // 구획 경계는 줄 하나짜리 `---`. 앞의 빈 줄까지 같이 먹어 재조립이 안정되게 한다.
  const 조각 = 몸.split(/^---$/m).slice(1);
  return { 머리: s.slice(0, m.index), 구획들: 조각.map((c) => '---' + c.replace(/\n+$/, '\n')) };
}

/** 새 구획을 맨 위에 얹고 상한을 넘긴 만큼 뒤에서 버린다. 버린 수를 같이 준다(③). */
function 합치기(기존내용, 새구획, { 상한 = 기본상한, 기본머리 = 머리 } = {}) {
  const { 머리: h, 구획들 } = 가르기(기존내용);
  const 전부 = [새구획, ...구획들];
  const 남길 = 전부.slice(0, 상한);
  return {
    내용: (h.trim() ? h.replace(/\n+$/, '\n\n') : 기본머리) + 남길.join('\n'),
    버린수: 전부.length - 남길.length,
  };
}

/** 폴더 목록에서 로그 파일을 찾는다. 번호를 뗀 이름으로만 본다(운영자료가 번호를 다시 매길 수 있다). */
function 로그찾기(이름들) {
  const 번호뗀 = (n) => n.replace(/^\d{2}_/, '');
  return 이름들.find((n) => 번호뗀(n) === 로그이름) || null;
}

/* ── 환경(여기부터 repo 밖) ───────────────────────────────────── */

/** 적재 대상 절대경로 + 폴백 여부. 폴더가 없으면 만든다. */
function 대상찾기({ 만들기 = true } = {}) {
  const { 경로: 바탕, 폴백 } = 바탕화면();
  if (!바탕) throw new Error('바탕화면을 못 찾았다');
  /* 뉴스 로그는 「그날 보는 것」이라 사업 갈래(`SYNK 자산\사업·운영`)에 쌓인다
   * — 갈래 자리는 운영자료가 정본이다(2026-08-13).
   * 🔴 실측 08-24: 여기가 `'운영'` 이었다. 08-20 에 두 커밋이 **이 순서로** 났기 때문이다:
   *    16:42 `1ec652e4` 이 파일을 「고아」로 삭제 → 20:11 `cf8a51f6` 갈래 재편(운영 → 방향·브랜드·사업·홍보).
   *    삭제가 먼저라 재편이 이 파일을 **못 따라왔다** — 없는 파일은 스윕에 안 걸린다.
   *    그래서 되살리기만 했으면 다음 로그온에 `모르는 갈래: 운영` 로 또 죽고, 스케줄러는 또
   *    「성공」을 반환했을 것이다(래퍼가 catch 로 삼킨다). 되살림은 «돌려 보기»까지가 한 벌이다. */
  const 폴더 = 갈래폴더(바탕, '사업');
  if (만들기) fs.mkdirSync(폴더, { recursive: true });
  const 있는것 = fs.existsSync(폴더) ? fs.readdirSync(폴더) : [];
  const 이름 = 로그찾기(있는것) || 로그이름;
  return { 파일: path.join(폴더, 이름), 폴더, 폴백, 새것: !로그찾기(있는것) };
}

function 읽기(p, 이름) {
  if (!p) return '';
  if (!fs.existsSync(p)) throw new Error(`${이름} 파일이 없다: ${p}`);
  return fs.readFileSync(p, 'utf8').replace(/^﻿/, '');
}

function main(argv) {
  const 인자 = argv.slice(2);
  const 값 = (k) => {
    const i = 인자.indexOf(k);
    return i >= 0 ? 인자[i + 1] : null;
  };

  if (인자.includes('--어디')) {
    const { 파일, 폴백, 새것 } = 대상찾기({ 만들기: false });
    console.log(파일 + (새것 ? '  (아직 없다)' : ''));
    if (폴백) console.error('⚠ 바탕화면 폴백 — 이 경로가 유호님 화면이 맞는지 눈으로 확인할 것');
    return 0;
  }

  const 요약경로 = 값('--요약');
  if (!요약경로) {
    console.error('쓰기: node tools/뉴스적재.js --요약 <파일> [--원시 <파일>] [--날짜 <ISO>] [--상한 N]');
    return 1;
  }

  const 요약 = 읽기(요약경로, '--요약');
  const 원시 = 값('--원시') ? 읽기(값('--원시'), '--원시') : '';
  const 날짜 = 값('--날짜') ? new Date(값('--날짜')) : new Date();
  if (Number.isNaN(날짜.getTime())) {
    console.error(`🔴 --날짜 를 못 읽었다: ${값('--날짜')}`);
    return 1;
  }
  const 상한 = 값('--상한') ? Number(값('--상한')) : 기본상한;

  const { 파일, 폴백 } = 대상찾기();
  if (폴백) console.error('⚠ 바탕화면 폴백 — 이 경로가 유호님 화면이 맞는지 눈으로 확인할 것');

  const 기존 = fs.existsSync(파일) ? fs.readFileSync(파일, 'utf8').replace(/^﻿/, '') : '';
  const eol = fs.existsSync(파일) ? 줄끝(기존) : '\r\n'; // 새로 만들면 Windows 메모장 기준(④)
  const { 내용, 버린수 } = 합치기(기존, 구획만들기(시각표기(날짜), 요약, 원시), { 상한 });

  fs.writeFileSync(파일, 내용.replace(/\r?\n/g, eol), { encoding: 'utf8' });
  console.log(`✅ 적재  ${파일}`);
  console.log(`   ${시각표기(날짜)} · 요약 ${요약.trim().split('\n').length}줄 · 원시 ${원시.trim() ? 원시.trim().split('\n').length : 0}줄` +
    (버린수 ? ` · 🗑 오래된 구획 ${버린수}개 버림(상한 ${상한})` : ''));
  return 0;
}

module.exports = { 줄끝, 시각표기, 구획만들기, 가르기, 합치기, 로그찾기, 로그이름, 기본상한, 머리 };

if (require.main === module) process.exit(main(process.argv));
