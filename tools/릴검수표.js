#!/usr/bin/env node
/**
 * 릴검수표 — 45화 장면형 대본에서 «몽골어가 빈 칸»만 뽑아 검수표 md 로 낸다.
 *
 * 왜 기계가 쓰나: 손으로 옮겨 적으면 대본을 고친 날 검수표가 거짓말한다. 오늘 실제로 겪었다 —
 *   45화를 쓸면서 빈 칸이 9 → 235 로 뛰었고, 손으로 적어 둔 수였으면 그 자리에서 낡았다
 *   (memory `constant-known-in-two-places` · 하루에 같은 병 네 번).
 *
 * 🔴 **AI 초안을 안 만든다.** 몽골어를 기계로 채우는 것은 금지다(원어민 검수 정책 ·
 *   `gemini-mn-check` 통로와 별개). 그래서 이 표에는 초안 열이 아예 없고, 검수자가 한국어에서
 *   바로 쓴다 — G1 문항팩(§L)과 같은 꼴이다.
 *
 * 🔑 **꼴이 곧 섹션이다.** 검수자에게 필요한 맥락은 «몇 편인가»가 아니라 «이 줄이 화면에서
 *   무슨 일을 하는가»다 — 그것이 말투를 정한다. 특히 「실수」 줄은 **일부러 어긋난 한국어**라
 *   고치면 안 되는데, 섹션이 그 사실을 매 행에 실어 나른다.
 *
 * 사용: node tools/릴검수표.js            → docs/릴대본_몽골어_검수표.md
 *       node tools/릴검수표.js --세기      파일 안 쓰고 수만 센다
 *
 * 그다음: node tools/검수꾸러미.js         (묶음 N 이 이 표를 읽어 시트로 낸다)
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const 생성경로 = path.join(ROOT, '영상', 'src', '클립', '생성', '대본클립들.ts');
const 낼곳 = path.join(ROOT, 'docs', '릴대본_몽골어_검수표.md');

/** 기본 가이드 한 벌만 센다 — 같은 대본이 가이드마다 한 벌씩 나므로 안 가르면 수가 두 배가 된다. */
const 기본가이드 = '몽글';

/**
 * 꼴 → 섹션 번호와 설명. **번호가 곧 언어 중립 코드다**(`검수꾸러미.js` 의 `섹션코드` 가
 * `## N.` 에서 `§N` 을 뽑는다). 뜻은 시트 안내 탭이 몽골어로 말한다 — 여기 두 번 적지 않는다.
 */
const 절들 = [
  /* 훅이 맨 앞이다 — 화면에서도 첫 2.5초이고, 검수자가 그 편의 «분위기»를 먼저 잡게 하려는 것이다.
     🔴 08-28 에 자리가 열렸다(유호 「훅에도 몽골어 자리 열어줘」). 그전에는 첫 2.5초가 몽골 학생에게
     한국어로만 떴다 — 릴에서 가장 중요한 자리인데 자리 자체가 없었다. */
  ['훅', '🔴 릴의 첫 2.5초 — 붙잡는 한 줄. 설명하지 말고 «궁금하게»'],
  ['상황', '문제가 일어나는 장면 — 담담한 서술체'],
  ['실수', '🔴 **일부러 어긋난 한국어** — 뜻을 옮기되 «고치지 마세요»'],
  ['반응', '그 말이 부른 결과 — 짧고 담담하게'],
  ['짧게', '같은 뜻의 더 짧은 판 — 급할 때 쓰는 말'],
  ['따라하기', '소리 내어 따라 하라는 안내 — 명령이 아니라 권유'],
  ['참여', '댓글을 부르는 질문 — 가볍고 친근하게'],
];

function 읽기() {
  if (!fs.existsSync(생성경로)) {
    throw new Error(`대본클립들이 없다: ${path.relative(ROOT, 생성경로)} — 먼저 node 영상/대본읽기.js`);
  }
  const s = fs.readFileSync(생성경로, 'utf8');
  // eslint-disable-next-line no-eval
  return eval(s.slice(s.indexOf('['), s.lastIndexOf(']') + 1));
}

function 모으기() {
  const 클립들 = 읽기().filter((c) => c.가이드 === 기본가이드);
  /* 같은 한국어가 여러 편에 나오면 **한 줄로 묶는다** — 같은 문장을 두 번 번역시키면 값도 두 배고
     무엇보다 **두 화면에 다른 몽골어가 설 수 있다**. 어느 편에 나오는지는 우리 쪽 메모로 남긴다. */
  const 지도 = new Map();
  let 빈칸 = 0;
  let 몽골어있음 = 0;
  const 담기 = (꼴, 한국어, 편) => {
    const 키 = `${꼴}::${한국어}`;
    if (!지도.has(키)) 지도.set(키, { 꼴, 한국어, 편들: [] });
    지도.get(키).편들.push(편);
  };
  for (const c of 클립들) {
    const 편 = `${c.편}-${c.화}`;
    /* 훅은 장면 배열 «밖»에 산다(클립의 제 칸이다). 여기서 빠뜨리면 자리는 열렸는데
       주문서에는 안 실리는 — 「열어 놓고 아무도 안 채우는」 자리가 된다. */
    if (c.훅몽골어) 몽골어있음 += 1;
    else { 빈칸 += 1; 담기('훅', c.훅, 편); }
    for (const s of c.장면들) {
      if (!s.꼴) continue;
      if (s.몽골어) { 몽골어있음 += 1; continue; }
      빈칸 += 1;
      담기(s.꼴, s.한국어, 편);
    }
  }
  return { 줄들: [...지도.values()], 빈칸, 몽골어있음, 편수: 클립들.length };
}

function 표만들기(줄들) {
  const 덩이 = [];
  절들.forEach(([꼴, 설명], i) => {
    const 것 = 줄들.filter((r) => r.꼴 === 꼴);
    if (!것.length) return;
    덩이.push(`## ${i + 1}. ${꼴} — ${설명} (${것.length}줄)`);
    덩이.push('');
    덩이.push('| № | 한국어 원문 | 몽골어 확정 ← 검수자가 씀 | 나오는 편(참고) |');
    덩이.push('|---|---|---|---|');
    것.forEach((r, n) => {
      /* 파이프는 표를 깨뜨린다 — 대본에 없지만 언젠가 들어오면 조용히 열이 밀린다. 미리 막는다. */
      const 안전 = r.한국어.replace(/\|/g, '\\|');
      덩이.push(`| ${n + 1} | ${안전} |  | ${r.편들.join(' ')} |`);
    });
    덩이.push('');
  });
  return 덩이.join('\n');
}

function main() {
  const { 줄들, 빈칸, 몽골어있음, 편수 } = 모으기();
  const 꼴셈 = 절들.map(([꼴]) => `${꼴} ${줄들.filter((r) => r.꼴 === 꼴).length}`).join(' · ');
  const 글자 = 줄들.reduce((t, r) => t + r.한국어.length, 0);

  console.log(`릴 대본 ${편수}화 · 「표현」 칸 몽골어 있음 ${몽골어있음} · 빈 칸 ${빈칸}`);
  console.log(`  ⇒ 중복 묶은 **고유 문장 ${줄들.length}줄** (${꼴셈})`);
  console.log(`  한국어 ${글자}자 · 평균 ${(글자 / 줄들.length).toFixed(1)}자`);
  if (process.argv.includes('--세기')) return;

  const 머리 = `# 릴 대본 — 몽골어 검수표 (묶음 N)

> ⚠ **기계가 쓴 파일이다 — 손으로 고치지 마라.** 정본은 대본 md
> (\`.claude/skills/synk-content/references/리드크루클립/\`)이고 이 파일은 \`node tools/릴검수표.js\` 의 산출물이다.
> 대본을 고치면 다시 돌린다. 시트로 내려면 \`node tools/검수꾸러미.js --내보내기\`.
>
> **실측** — 릴 ${편수}화(장면형 18초) · 「표현」 칸은 몽골어가 이미 있다(${몽골어있음}줄, 옛 판에서 옮겨 옴) ·
> 나머지 화면 자막 **${빈칸}칸이 비어 있고**, 같은 문장을 묶으면 **${줄들.length}줄**이다.
> 한국어 ${글자}자 · 평균 ${(글자 / 줄들.length).toFixed(1)}자 — 짧은 자막이라 문장이 아니라 «말»로 옮긴다.
>
> 🔴 **AI 초안이 없다.** 몽골어를 기계로 채우지 않는 것이 이 저장소의 정책이라, 검수자가 한국어에서 바로 쓴다.
> 🔴 **§3 「실수」 45줄은 일부러 어긋난 한국어다** — 화면에서 회색 취소선으로 서고 바로 다음 칸이 정답이다.
>    **뜻을 옮기되 «고치지 마세요».** 고쳐서 옮기면 그 편의 뜻이 통째로 무너진다(이 표에서 가장 큰 함정).
> 🆕 **§1 훅 ${편수}줄이 08-28 에 들어왔다**(유호 지시 「훅에도 몽골어 자리 열어줘」). 그전에는 릴의
>    **첫 2.5초가 몽골 학생에게 한국어로만** 떴다 — 가장 중요한 자리인데 자리 자체가 없었다.
>    훅은 «배우는 줄»이 아니라 «붙잡는 줄»이라, 뜻을 옮기기보다 **그 편을 보고 싶게 만드는 한 줄**로 쓴다.

---
`;
  fs.writeFileSync(낼곳, `${머리}\n${표만들기(줄들)}`, 'utf8');
  console.log(`\n✅ ${path.relative(ROOT, 낼곳)}`);
  console.log('   다음: node tools/검수꾸러미.js       (묶음 N 이 이 표를 읽는다)');
}

if (require.main === module) main();
