#!/usr/bin/env node
'use strict';
// Reproducible packaging only: source artwork is preserved. Eye-only composition is at runtime.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const repo = path.resolve(__dirname, '..');
const talk = path.resolve(repo, '../SYNK-talk');
const sharp = require(require.resolve('sharp', { paths: [talk] }));
const { 앱용뽑기 } = require('./lib/깊이격자.js');
const out = path.join(repo, 'experiences/loom-living');
const hash = p => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
async function main() {
  fs.mkdirSync(path.join(out, 'assets'), { recursive: true });
  const sources = {
    background: path.join(repo, 'docs/라디오/무대/dream_field.png'),
    mongle: path.join(repo, 'docs/캐릭터/정본_4K/몽글_본체.png'),
    closed: path.join(talk, 'assets/마스코트/몽글_눈감음.webp'),
    masks: path.join(talk, 'assets/브랜드/가이드눈마스크.json'),
    font: path.join(repo, 'experiences/20260909/shared/fonts/SUIT-Variable.woff2'),
    logo: path.join(repo, 'docs/홍보물/마케팅실행_20260909/브랜드킷/SYNK-Paper-정밀.svg'),
  };
  await sharp(sources.background).resize({ width: 2560, withoutEnlargement: true }).webp({ quality: 94, effort: 6 }).toFile(path.join(out, 'assets/garden.webp'));
  await sharp(sources.mongle).resize(1536, 1536).webp({ lossless: true, effort: 6 }).toFile(path.join(out, 'assets/mongle.webp'));
  fs.copyFileSync(sources.closed, path.join(out, 'assets/mongle-closed.webp'));
  fs.copyFileSync(sources.font, path.join(out, 'assets/SUIT-Variable.woff2'));
  fs.copyFileSync(sources.logo, path.join(out, 'assets/synk-paper.svg'));
  const masks = JSON.parse(fs.readFileSync(sources.masks, 'utf8')).characters.몽글;
  const tokens = JSON.parse(fs.readFileSync(path.join(repo, 'docs/디자인_토큰.json'), 'utf8'));
  const color = name => tokens.색.킷.find(v => v.이름 === name).hex;
  fs.writeFileSync(path.join(out, 'theme.css'), `/* Generated by tools/loom-living-build.cjs from design tokens. */\n:root{--paper:${color('Paper')};--ink:${color('Ink')};--night:${color('Ink Deep')};--stitch:${color('Stitch')};--oat:${color('Oat')};--stone:${color('Stone')};--butter:${color('Butter Soft')};}\n`);
  const depth = 앱용뽑기(sources.mongle, { N: 48, P: 256, 회: 5 });
  fs.writeFileSync(path.join(out, 'scene.json'), JSON.stringify({
    version: 1, id: 'mongle-wind-garden', renderer: 'webgl-2.5d', seed: 913,
    background: { src: './assets/garden.webp', width: 5504, height: 3072 },
    character: { src: './assets/mongle.webp', closed: './assets/mongle-closed.webp', masks: masks.eyes, depth },
    provenance: './provenance.json',
  }));
  const provenance = {
    createdAt: new Date().toISOString(), mode: 'existing-artwork-no-new-generation',
    purpose: 'One interactive Mongle and garden scene; source textures retained, controlled runtime deformation.',
    sources: Object.fromEntries(Object.entries(sources).map(([k,p]) => [k, { path: path.relative(repo,p).replaceAll('\\','/'), sha256: hash(p) }])),
    authority: ['DESIGN.md','docs/Loom_엔진_설계.md','docs/캐릭터/캐릭터_생명감_설계.md','docs/캐릭터/가이드_정본.md'],
    depth: 'Existing tools/lib/깊이격자.js rotational-shape estimate, not recovered full 3D geometry.',
    transformations: ['Background downscale/WebP compression','Body downscale/lossless WebP','Existing closed-eye source copied; only canonical elliptical eye areas composed in memory','Source body alpha and UV texture remain common throughout motion'],
    outputs: Object.fromEntries(['assets/garden.webp','assets/mongle.webp','assets/mongle-closed.webp','assets/SUIT-Variable.woff2','assets/synk-paper.svg','scene.json','theme.css'].map(p=>[p,{bytes:fs.statSync(path.join(out,p)).size,sha256:hash(path.join(out,p))}])),
  };
  fs.writeFileSync(path.join(out, 'provenance.json'), JSON.stringify(provenance, null, 2)+'\n');
  console.log(JSON.stringify({output:out,files:provenance.outputs},null,2));
}
main().catch(e=>{console.error(e.message);process.exitCode=1;});
