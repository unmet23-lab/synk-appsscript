const 보장급 = 4;

function 확인불가(msg) {
  const e = new Error(msg);
  e.확인불가 = true;
  return e;
}

const 정규화 = (s) => String(s == null ? '' : s).normalize('NFC').trim().replace(/\s+/g, ' ');

/* ── 🔴 문형 표기 정규화 — **첫 실행이 자기 결함을 드러내서 생긴 자리다**(08-31)
 *   완전 일치만 보던 첫 판이 「없다」로 센 것 중 셋이 **표기만 다를 뿐 실재했다**:
 *     요목 `-을수록`        = 뱅크 `-(으)ㄹ수록`(G704)
 *     요목 `-ㄴ 적이 있다`   = 뱅크 `-(으)ㄴ 적이 있다`(G509)
 *     요목 `-ㄹ 수 있다/없다` = 뱅크 `-(으)ㄹ 수 있다/없다`(G402)
 *   ⚠ 그렇다고 매칭을 느슨하게 풀면 **이번엔 반대로 샌다** — `-는 대신에`(G708)와 `-는 반면에`는
 *     뜻이 다른데 서로 비슷해 보인다. 새는 방향이 「통과」인 쪽이 언제나 더 위험하다.
 *   ⇒ 그래서 **판정을 셋으로 가른다**: ✅완전일치 · ❔비슷(사람이 확인) · 🔴없음.
 *     ❔는 **통과가 아니다** — 세되 초록으로 접지 않는다.
 *
 *   규칙은 «최소»로만 둔다(늘릴수록 거짓 초록이 는다):
 *     ① 괄호 선택 요소 제거 — `(으)`·`(이)`·`(느)`
 *     ② 공백 제거 — `-나 보다` ↔ `-나보다`
 *     ③ 어두 `-을` → `-ㄹ` (받침 이형태 · ①과 합쳐 `-(으)ㄹ` 도 `-ㄹ` 이 된다)
 *   🚫 `은/는` 은 **안 건드린다** — `-ㄴ 적이 있다`의 `ㄴ`(관형사형)과 `-는 반면에`의 `는`은
 *      같은 자리가 아니라, 통일하면 서로 다른 문형이 붙는다. */
const 문형정규화 = (s) => 정규화(s)
  .replace(/\([^)]*\)/g, '')
  .replace(/\s+/g, '')
  .replace(/^-을/, '-ㄹ');

/* ══════════════════════════════════ ① 뱅크 읽기
 * `엔진_콘텐츠AI.js` 는 Apps Script 소스라 require 로 못 읽는다(전역 스코프·GAS 전용 심볼).
 * 그래서 `GRAMMAR_BANK` 배열 리터럴만 원문에서 떼어 판다 — 실행하지 않는다. */
function 뱅크읽기() {
  let src;
  try { src = fs.readFileSync(뱅크파일, 'utf8'); }
  catch (e) { throw 확인불가(`문법 뱅크를 못 읽었다(${뱅크파일}) — ${e.message}`); }

  const 시작 = src.indexOf('const GRAMMAR_BANK = [');
  if (시작 < 0) throw 확인불가('`const GRAMMAR_BANK = [` 를 못 찾았다 — 뱅크가 옮겨졌거나 이름이 바뀌었다');

  /* 한 줄 = 한 항목이라는 규격에 기댄다(뱅크 머리 주석의 칸 규격 그대로).
   * [id, 이름, 설명, 도입급, 재출현급, 근거] — 뒤 칸이 늘어도 앞 여섯만 읽어 안 깨진다. */
  const 줄정규식 = /^\s*\['(G\d+)',\s*'((?:[^'\\]|\\.)*)',\s*'((?:[^'\\]|\\.)*)',\s*(\d+),\s*(null|\d+),\s*'([^']*)'/;
  const 항목들 = [];
  const 줄들 = src.slice(시작).split('\n');
  for (const 줄 of 줄들) {
    if (/^\s*\];/.test(줄)) break;            // 배열이 닫혔다
    const m = 줄정규식.exec(줄);
    if (!m) continue;
    항목들.push({
      id: m[1],
      이름: 정규화(m[2].replace(/\\'/g, "'")),
      설명: 정규화(m[3].replace(/\\'/g, "'")),
      도입급: Number(m[4]),
      재출현급: m[5] === 'null' ? null : Number(m[5]),
      근거: m[6],
    });
  }

  /* ── 대조군 ── */
  if (항목들.length < 60) {
    throw 확인불가(`뱅크 항목이 ${항목들.length}개뿐이다(60 미만) — 파서가 깨졌을 가능성이 크다`);
  }
  for (const 닻 of ['G201', 'G705']) {
    if (!항목들.some((g) => g.id === 닻)) throw 확인불가(`대조군 ${닻} 가 안 잡혔다 — 파서가 깨졌다`);
  }
  const 이상급 = 항목들.filter((g) => !급수들.includes(g.도입급));
  if (이상급.length) {
    throw 확인불가(`도입급이 1~5 밖인 항목 ${이상급.length}건(${이상급[0].id}=${이상급[0].도입급}) — 규격이 갈렸다`);
  }
  return 항목들;
}

/* ══════════════════════════════════ ② 커리큘럼 요목 읽기
 * 구조(정본 §3): `### Lv4 · … TOPIK 4급 …` 절 안에 `**문법 요목 …**` 이 오고, 그 아래
 * `- 분류 [태그]: 문형, 문형, 문형` 줄들이 온다. [확장]·[심화] 만 붙고 문형 이름이 없는 줄도 있다. */
function 요목읽기() {
  let src;
  try { src = fs.readFileSync(커리큘럼파일, 'utf8'); }
  catch (e) { throw 확인불가(`커리큘럼 정본을 못 읽었다(${커리큘럼파일}) — ${e.message}`); }

  const 절들 = new Map();                      // 급수 → { 문형들:[], 대조불가:[] }
  const 줄들 = src.split('\n');
  let 현재급 = null;
  let 요목안 = false;

  for (const 줄 of 줄들) {
    const 머리 = /^###\s+(?:【[^】]*】\s*)?Lv(\d)\b/.exec(줄);
    if (머리) {
      /* Lv 번호와 TOPIK 급은 정본에서 1:1 이다(Lv4 = TOPIK 4급). 6급 참조 절은 급수들 밖이라 걸러진다. */
      현재급 = Number(머리[1]);
      요목안 = false;
      if (급수들.includes(현재급) && !절들.has(현재급)) 절들.set(현재급, { 문형들: [], 대조불가: [] });
      continue;
    }
    if (/^###\s/.test(줄) || /^##\s/.test(줄)) { 현재급 = null; 요목안 = false; continue; }
    if (현재급 == null) continue;

    if (/^\*\*문법 요목/.test(줄)) { 요목안 = true; continue; }
    /* 다른 굵은 머리(어휘·평가·소요 기간)를 만나면 요목 구역이 끝난다. */
    if (요목안 && /^\*\*/.test(줄)) { 요목안 = false; continue; }
    if (!요목안 || !급수들.includes(현재급)) continue;

    const 항목 = /^-\s+(.*)$/.exec(줄.trim());
    if (!항목) continue;
    const 본문 = 항목[1].replace(/\*\*/g, '');
    const 콜론 = 본문.indexOf(':');
    const 분류 = 정규화((콜론 >= 0 ? 본문.slice(0, 콜론) : 본문).replace(/\[[^\]]*\]/g, ''));
    const 꼬리 = 콜론 >= 0 ? 본문.slice(콜론 + 1) : '';

    /* 괄호 주석(← *(…)*)은 문형이 아니다 — 떼고 센다. */
    const 조각들 = 꼬리.replace(/←[^,]*/g, '').replace(/\([^)]*\)/g, '').split(/[,·]/);
    const 문형들 = 조각들.map(정규화).filter((s) => /^-/.test(s));

    const 칸 = 절들.get(현재급);
    if (문형들.length) 칸.문형들.push(...문형들.map((f) => ({ 문형: f, 분류 })));
    else 칸.대조불가.push(분류 || 정규화(본문));   // 이름이 안 박힌 항목 — 통과에 넣지 않는다
  }

  /* ── 대조군 ── */
  for (const 급 of 급수들) {
    if (!절들.has(급)) throw 확인불가(`커리큘럼에서 Lv${급} 절을 못 찾았다 — 파서가 깨졌거나 정본 구조가 바뀌었다`);
  }
  const lv4 = 절들.get(4);
  if (!lv4.문형들.some((x) => x.문형 === '-는 반면에')) {
    throw 확인불가('대조군 「-는 반면에」(Lv4 요목)가 안 잡혔다 — 요목 파서가 깨졌다');
  }
  return 절들;
}

/* ══════════════════════════════════ ③ 대조 */
function 재기() {
  const 뱅크 = 뱅크읽기();
  const 요목 = 요목읽기();

  /* 뱅크가 «그 급에서 다루는» 것 = 도입급이 그 급이거나, 재출현급이 그 급인 것.
   * 둘을 갈라 세되 대조에는 합집합을 쓴다 — 재출현도 그 급 수업에서 실제로 다루기 때문이다. */
  const 급별 = 급수들.map((급) => {
    const 도입 = 뱅크.filter((g) => g.도입급 === 급);
    const 재출현 = 뱅크.filter((g) => g.재출현급 === 급);
    const 다루는이름들 = new Set([...도입, ...재출현].map((g) => g.이름));

    /* 정규화 이름 → 뱅크 항목(어느 것에 붙었는지 사람이 볼 수 있게 id 를 쥔다). */
    const 정규화맵 = new Map();
    for (const g of [...도입, ...재출현]) {
      const k = 문형정규화(g.이름);
      if (k && !정규화맵.has(k)) 정규화맵.set(k, g);
    }

    const 칸 = 요목.get(급);
    const 맞은것 = [];
    const 비슷한것 = [];
    const 빠진것 = [];
    for (const { 문형, 분류 } of 칸.문형들) {
      if (다루는이름들.has(문형)) { 맞은것.push({ 문형, 분류 }); continue; }

      const k = 문형정규화(문형);
      const 붙은것 = 정규화맵.get(k);
      if (붙은것) { 비슷한것.push({ 문형, 분류, 뱅크: 붙은것.이름, id: 붙은것.id, 축: '표기차' }); continue; }

      /* 슬래시 이형태 나열(`-다고/-냐고/-라고/-자고 하다`)은 위 규칙으로 안 붙는다.
       * 마지막으로 **양방향 부분 문자열**을 본다 — 느슨한 축이라 반드시 ❔ 로만 간다. */
      const 포함 = k && [...정규화맵.entries()].find(([bk]) => bk.includes(k) || k.includes(bk));
      if (포함) { 비슷한것.push({ 문형, 분류, 뱅크: 포함[1].이름, id: 포함[1].id, 축: '부분' }); continue; }

      빠진것.push({ 문형, 분류 });
    }
    return {
      급,
      보유: { 도입: 도입.length, 재출현: 재출현.length },
      근거갈래: { 요: 도입.filter((g) => g.근거 === '요').length, 표: 도입.filter((g) => g.근거 === '표').length },
      요목문형수: 칸.문형들.length,
      맞은것,
      비슷한것,
      빠진것,
      대조불가: 칸.대조불가,
    };
  });

  return { 뱅크총수: 뱅크.length, 급별 };
}

/* ══════════════════════════════════ ④ 출력 */
function 표출력(결과, 급필터) {
  const { 뱅크총수, 급별 } = 결과;
  console.log(`\n■ 급수 커버리지 — 문법 뱅크 ${뱅크총수}종 × 커리큘럼 정본 요목`);
  console.log(`  보장선 = TOPIK ${보장급}급(유호 확정 08-31). 못 지키면 게임 앱 유료기능이 부채가 된다.\n`);
  console.log('  급  │ 뱅크 보유(도입+재출현) │ 근거 요/표 │ 요목 문형 │ ✅쥔 것 │ ❔표기차 │ 🔴없다 │ 대조불가');
  console.log(' ─────┼────────────────────────┼────────────┼───────────┼─────────┼──────────┼────────┼─────────');
  for (const r of 급별) {
    const 표식 = r.급 === 보장급 ? '▶' : ' ';
    console.log(
      `  ${표식}${r.급}  │ ${String(r.보유.도입).padStart(9)} + ${String(r.보유.재출현).padStart(9)}  │`
      + ` ${String(r.근거갈래.요).padStart(4)}/${String(r.근거갈래.표).padStart(4)} │`
      + ` ${String(r.요목문형수).padStart(9)} │ ${String(r.맞은것.length).padStart(7)} │`
      + ` ${String(r.비슷한것.length).padStart(8)} │ ${String(r.빠진것.length).padStart(6)} │`
      + ` ${String(r.대조불가.length).padStart(7)}`,
    );
  }

  const 볼것 = 급별.filter((r) => (급필터 ? r.급 === 급필터 : r.빠진것.length + r.비슷한것.length > 0));
  for (const r of 볼것) {
    console.log(`\n  ── Lv${r.급}(TOPIK ${r.급}급) ${r.급 === 보장급 ? '◀ 보장선' : ''}`);
    if (r.빠진것.length) {
      console.log('     🔴 요목엔 있는데 뱅크에 없다 — 우리가 가르친다고 적어 두고 재료를 안 쥔 것:');
      for (const x of r.빠진것) console.log(`        · ${x.문형}   (${x.분류})`);
    } else if (!급필터 || r.급 === 급필터) {
      console.log('     ✅ 요목에 이름이 박힌 문형은 전부 뱅크에 있다(표기차 포함).');
    }
    if (r.비슷한것.length) {
      console.log('     ❔ 표기가 달라 붙였다 — **사람이 확인할 것**(통과로 세지 않았다):');
      for (const x of r.비슷한것) console.log(`        · 요목 ${x.문형}  ↔  뱅크 ${x.뱅크} (${x.id} · ${x.축})`);
    }
    if (r.대조불가.length) {
      console.log('     ❔ 대조 불가(요목에 문형 이름이 없다 — 통과에 «안» 넣었다):');
      for (const x of r.대조불가) console.log(`        · ${x}`);
    }
  }

  const 총 = (키) => 급별.reduce((s, r) => s + r[키].length, 0);
  const 총빠짐 = 총('빠진것');
  console.log(`\n  합계 = ✅${총('맞은것')} + ❔표기차 ${총('비슷한것')} + 🔴없다 ${총빠짐}`
    + `  (요목 문형 ${급별.reduce((s, r) => s + r.요목문형수, 0)}건) · 대조불가 ${총('대조불가')}건은 분모 밖`);
  console.log('  ⚠ 이 자는 «있나»만 잰다 — 그 문형의 설명이 «맞나»는 talk §8-B ⑥정확성(0.95)이 진다.\n');
  return 총빠짐;
}

function main() {
  const argv = process.argv.slice(2);
  const 아는플래그 = ['--json', '--급'];
  for (const a of argv) {
    if (a.startsWith('--') && !아는플래그.includes(a)) {
      console.error(`모르는 플래그 ${a} — 급수커버리지 가 아는 것은 ${아는플래그.join(' ')} 뿐이다.`);
      process.exit(2);
    }
  }
  const 급필터 = argv.includes('--급') ? Number(argv[argv.indexOf('--급') + 1]) : null;
  if (급필터 != null && !급수들.includes(급필터)) {
    console.error(`--급 은 ${급수들.join('·')} 중 하나여야 한다(우리 과정 상한은 5급).`);
    process.exit(2);
  }

  let 결과;
  try { 결과 = 재기(); }
  catch (e) {
    if (e.확인불가) {
      console.error(`\n🔴 확인 불가 — ${e.message}`);
      console.error('   이건 「빠진 것 0건」이 «아니다». 종료코드 2 로 나간다.\n');
      process.exit(2);
    }
    throw e;
  }

  if (argv.includes('--json')) {
    console.log(JSON.stringify({ 보장급, ...결과 }, null, 2));
    process.exit(결과.급별.some((r) => r.빠진것.length) ? 1 : 0);
  }

  const 총빠짐 = 표출력(결과, 급필터);
  process.exit(총빠짐 > 0 ? 1 : 0);
}

if (require.main === module) main();
module.exports = { 재기, 뱅크읽기, 요목읽기, 보장급, 급수들 };
