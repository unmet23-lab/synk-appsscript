def _시안(bpy, math, random, g):
    """g = 요소굽기 전역(부품 창고). 사장님 1역을 세 방식으로 짓는다."""
    베개몸, 짧은퍼 = g['베개몸'], g['짧은퍼']
    살재질, 털재질, 분필재질, 매끈재질 = g['살재질'], g['털재질'], g['분필재질'], g['매끈재질']
    직물결, 땀하나, 러닝스티치 = g['직물결'], g['땀하나'], g['러닝스티치']
