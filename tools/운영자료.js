/** 같은 계열의 옛 판을 걷는다. 기본은 **드라이런** — 지우려면 `--집행`.
 *  `방금` 을 주면 그 파일이 속한 계열만 본다(파일을 넣은 직후 자동 호출되는 자리). */
function 옛판정리(폴더, { 집행 = false, 조용히 = false, 방금 = null } = {}) {
  // 🔴 **하위폴더는 안 본다**(`하위: false`) — 이 함수는 지우는 함수다. 아래 `rmSync` 가
  //    `path.join(폴더, x.이름)` 로 지우므로 하위폴더 파일이 섞이면 **없는 경로를 지우고**
  //    `force: true` 라 조용히 성공한다 — 「🗑 걷었다」가 찍히는데 파일은 살아 있는 모양이다.
  //    계열 판정을 폴더 너머로 넓히지 않는 것은 그 자체로도 확정된 규율이다(🚫계열 넓히기).
  const 이름들 = 목록읽기(폴더, { 하위: false }).map((it) => it.이름);
  // 방금 넣은 파일에 판 표기가 없으면 걷을 계열 자체가 없다 — 여기서 끝낸다.
  // (계열만 을 null 로 두면 「제한 없음」이 되어 넣기와 무관한 파일까지 폴더 전체를 훑는다.)
  if (방금 && !계열키(방금)) return 0;
  const 계열만 = 방금 ? 계열키(방금).계열 : null;
  const 걷을것 = 옛판고르기(이름들, { 계열만 });
  // 🔴 「없다」를 혼자 내보내지 않는다 — 그 한 줄이 초록의 얼굴로 구판 4쌍을 덮고 있었다(2026-08-14).
  //    폴더 전체를 볼 때만 잰다(`방금` 은 넣은 파일 한 계열만 보는 자리라 분모가 다르다).
  const 의심 = 방금 ? [] : 짝의심(이름들);
  if (!걷을것.length) {
    if (!조용히) {
      console.log(`■ ${폴더}\n  걷어낼 옛 판이 없다 (파일 ${이름들.length}건)`);
      의심보고(의심);
    }
    return 0;
  }
  /* 🔴 F604 계보(F400→F435·F436→F493·F562→F543→F604 · 이 자리가 일곱째) — **로그가 행위보다 먼저였다.**
   *    옛 모양은 `console.log('🗑 …')` 를 찍고 **그 다음 줄에서** 지웠다. 그래서 `rmSync` 가 던지면
   *    (Windows 에서 파일이 열려 있으면 EBUSY·EPERM 이 실제로 난다) 못 지운 그 파일까지 「🗑 걷었다」로
   *    인쇄된 채 루프가 통째로 빠져나갔다. 이 함수는 try 밖이라(호출부 :946 try 는 갈래 계산만 감싼다)
   *    프로세스가 그대로 죽고, 앞의 N 건은 **이미 지워진 뒤**다 — 그리고 삭제 대상은 저장소 밖
   *    유호님 바탕화면이라 되돌릴 이력이 없다(F025).
   *    F604 와 새는 «방향»만 반대다: 저기는 했는데 「안 했다」, 여기는 안 했는데 「했다」.
   *  〖고친 것〗 ①행위 뒤에 찍는다 ②성공·실패를 갈라 **센다** ③한 건이 실패해도 나머지를 계속 시도한다
   *    (걷기는 멱등이라 접는 것보다 낫다) ④분모를 함께 낸다 — 「몇 건 중 몇 건」이 안 보이면 미실행과
   *    통과가 같은 모양이 된다(F207).
   *  〖틀릴 때의 모습〗 `rmSync({force:true})` 는 **없는 파일에도 안 던진다** — 그래서 `지움` 은
   *    「지웠다」가 아니라 「지운 뒤 없다」의 수다. 목록은 바로 위 `목록읽기` 가 방금 실측한 것이라
   *    지금은 둘이 같지만, 남이 동시에 지우면 그 한 건이 «내가 지운 것»으로 셈해진다.
   *  〖닫은 것 1개〗 옛 무조건 `return 0` — 부분 삭제가 종료코드 0 으로 나가던 자리다. */
  const 지움 = [];
  const 못지움 = [];
  for (const x of 걷을것) {
    if (!집행) { console.log(`[드라이런] ${x.이름}  — 같은 계열에 더 새 판이 있다`); continue; }
    try {
      fs.rmSync(path.join(폴더, x.이름), { force: true });
      지움.push(x.이름);
      console.log(`🗑 ${x.이름}  — 같은 계열에 더 새 판이 있다`);
    } catch (e) {
      못지움.push({ 이름: x.이름, 사유: e.code || e.message });
      console.error(`⚠ 못 지웠다  ${x.이름} — ${e.code || e.message}`);
    }
  }
  if (!집행) console.log(`\n  ${걷을것.length}건 — 지우려면 \`--옛판 --집행\``);
  else if (못지움.length) {
    console.error(`\n  🔴 대상 ${걷을것.length}건 중 **${지움.length}건 지웠고 ${못지움.length}건 남았다** — 부분 적용이다.`);
    console.error('     남은 것은 다시 부르면 그대로 다시 시도한다(걷기는 멱등이다).');
  } else if (!조용히) console.log(`\n  🗑 ${걷을것.length}건 중 ${지움.length}건 지웠다`);
  의심보고(의심);
  return 못지움.length ? 1 : 0;
}

