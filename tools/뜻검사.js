  // 것일 때만 확인할 것으로 내린다(그래도 --눈확인을 거쳐야 통과): 원본 = 동결된 원본의 그림 · 박자 · 짜임 불만(설계 20 — 판본은 글과 글꼴만 바꾼다),
  // 전제 = 한국어 글을 못 읽는다는 불만(시험관은 한국어를 모르는 것이 전제), 틀 = 판본 틀이 붙이는 정본 장면 · 박자 불만(인사 카드와 그 길이 ·
  // 끝 카드가 뜨는 때 — 고칠 자리는 인사 카드 정본 · 판본 틀이다). 같이 짚은 까닭이 갈래마다 다르면 목록으로 적고 기록은 「전제 · 틀」 한 글이다.
  // 불편 · 화면 결함 · 정답 오류 · 요약 · 웃음에는 못 쓴다(11-10 판본 시범).
  const 줄판정 = 사람판정.줄 && typeof 사람판정.줄 === 'object' ? 사람판정.줄 : {};
