    for (const [k, list] of map) {
      const 코드 = 칸 === '모름줄' ? '같이짚음' : '불편';
      const 판 = 칸 === '모름줄' ? 줄판정[k] : null;
      const 갈래 = 판 ? 판정갈래읽기(판.갈래) : null;
      const 판됨 = 갈래 && String(판.까닭 || '').trim();
      if (list.length >= 2 && 판됨) {
        out.push(찾음(확인, 코드, `${k}를 시험관 ${list.length}이 같이 짚었다 — 판정 「${갈래}」: ${String(판.까닭).trim()} — ${list.join(' / ')}`, { 줄: k, 판정: 갈래 }));
        내린줄.push({ 줄: k, 갈래, 까닭: String(판.까닭).trim(), 짚은수: list.length });
      } else if (list.length >= 2) out.push(찾음(고칠, 코드, `${k}를 시험관 ${list.length}이 같이 짚었다 — ${list.join(' / ')}`, { 줄: k }));
      else out.push(찾음(확인, 코드, `${k} — ${list[0]}`, { 줄: k }));
    }
