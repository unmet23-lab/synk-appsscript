/** 시험관 넷인가 — 새 언어 · 문자 체계 첫 3편 · 새 틀 · 문화 소재 · 같은 실수 다시(설계 9 · 12) */
// 문자 체계마다 첫 3편(원본 편)은 언어판 전부 시험관 넷이다(설계 README 「검수」 — 「문자 체계마다 첫 3편은 언어판 전부 시험관 넷」). 통과한 판본
// 기록 수가 아니라 편 수로 센다(11-11 Fable 5.2 끝 판 검수 P2-7: 판본 기록으로 세어 첫 원본의 라틴 판본 스무 개가 「20편」이 됐고, 둘째 원본
// 「화날때」의 판본들이 시험관 둘로 넘어갔다). 지금 보는 편(편)은 세지 않는다 — 그 편 앞에 통과한 편이 셋 있어야 시험관 둘이다.
function 넷판단({ 언어, 틀, 편 = null, 문화소재 = false, 딱지경고 = [], 기록 = [] }) {
  const L = 프로필.언어(언어);
  const 갈래 = 문자갈래(L?.문자);
  const 까닭 = [];
  const 통과들 = 기록.filter((r) => r.결과 === 통과);
  if (!통과들.some((r) => r.언어 === 언어)) 까닭.push(`새 언어(${L?.이름 || 언어} 뜻 검사 통과 기록 없음)`);
  const 같은문자 = new Set(통과들.map((r, i) => [r, i]).filter(([r]) => 문자갈래(r.문자 || 프로필.언어(r.언어)?.문자) === 갈래 && !(편 && r.편 === 편)).map(([r, i]) => r.편 || `(편 없음 ${i})`)).size;
  if (같은문자 < 3) 까닭.push(`문자 체계(${갈래}) 첫 3편 — 이 편 앞에 통과한 편 ${같은문자}`);
  if (틀 && !통과들.some((r) => r.언어 === 언어 && r.틀 === 틀)) 까닭.push(`새 틀(${틀} — 이 언어 통과 기록 없음)`);
  if (문화소재) 까닭.push('문화 소재(판본 글 「문화소재」)');
  if (딱지경고.length) 까닭.push(`문화 소재(관용구 대응 경고 ${딱지경고.length}개)`);
  const 마지막 = 기록.filter((r) => r.언어 === 언어).sort((a, b) => String(b.시각).localeCompare(String(a.시각)))[0];
  if (마지막?.다음은넷) 까닭.push(`같은 실수가 다시 나옴(지난 ${마지막.편} · ${마지막.판본})`);
  return { 넷: 까닭.length > 0, 까닭 };
}

/** 통과로 적힌 뜻 검사 기록의 시험관 수가 그 기록을 받은 때의 셈으로 모자랐는가 — 넷이어야 했는데 넷보다 적은 시험관으로 통과했으면
 *  { 수, 시험관, 까닭 }, 아니면 null(11-11 Fable 5.2 다시 검수 P1-넷1 · P2-넷2).
 *  · 「그때의 셈」은 그 기록보다 먼저 통과한 다른 기록만으로 센다. 지금 있는 기록 전부로 세면, 뒤에 다른 편 둘이 통과하는 순간 아무도 다시 받지 않은
 *    기록이 저절로 넉넉해진다. 다른 기록이 「먼저」인지는 그 기록의 처음통과(같은 판본이 통과로 다시 적힐 때 이어받는 첫 통과 시각), 없으면 시각으로 본다 —
 *    글을 고쳐 다시 통과한 판본이 「나중 것」이 되어 다른 판본을 헛되이 막지 않게 한다.
 *  · 시각이 없는 다른 기록은 먼저라고 볼 수 없어 세지 않는다(닫히는 쪽). 이 기록에 시각이 없으면 앞뒤를 가를 수 없어 지금 기록 전부로 센다.
 *  · 시험관 칸이 없는 옛 기록은 묻지 않는다(null).
 *  · 기록에 「시험관셈」(받은 때의 셈 — 채점 --기록이 얼려 적는다, 11-12 P1-시1)이 있으면 그 값만 읽는다. 지금 남아 있는 다른 편 기록으로 되짚으면,
 *    앞 편의 기록을 두 걸음(채점 --기록 = 확인할 것 → --눈확인 --기록 = 통과)으로 다시 받는 사이 「앞에 통과한 편」 수가 줄어 뒤 편의 정당한 시험관 둘
 *    통과가 「모자람」으로 뒤집히고, 그 판이 걸려 있으면 「걸린 뒤 바뀜」(묻지 않고 내리는 걸음)이 뜬다. 시험관셈이 없는 옛 기록만 위 셈으로 되짚는다. */
function 시험관모자람(뜻, { 언어, 틀 = null, 편 = null, 판본 = null, 기록 = [] }) {
  if (!뜻 || !Array.isArray(뜻.시험관) || 뜻.시험관.length >= 4) return null;
  const 셈 = 뜻.시험관셈;
  if (셈 && typeof 셈.넷 === 'boolean') {
    return 셈.넷 ? { 수: 뜻.시험관.length, 시험관: 뜻.시험관, 까닭: Array.isArray(셈.까닭) && 셈.까닭.length ? 셈.까닭 : ['받은 때의 셈 — 시험관 넷'] } : null;
  }
  const 때 = Date.parse(뜻.시각 || '');
  const 앞 = 기록.filter((r) => !(r.편 === 편 && r.판본 === 판본) && (!Number.isFinite(때) || Date.parse(r.처음통과 || r.시각 || '') < 때));
  const need = 넷판단({ 언어: 뜻.언어 || 언어, 틀: 뜻.틀 || 틀, 편, 기록: 앞 });
  return need.넷 ? { 수: 뜻.시험관.length, 시험관: 뜻.시험관, 까닭: need.까닭 } : null;
}

/** 받은 때의 셈(11-12 P1-시1) — 이 시험지를 만든 때(재료 시각)까지 통과해 있던 다른 기록으로 센 「시험관 넷이어야 하나」와 까닭. 채점 --기록이
 *  뜻 기록 「시험관셈」에 얼려 적고, 관문(시험관모자람)은 그 값만 읽는다. 지금의 규칙으로 다시 세니 옛 도구가 만든 재료의 셈(판본 수로 세던 때)에 기대지 않고,
 *  재료 시각으로 끊으니 시험관 둘의 옛 답을 뒤에(다른 편이 더 통과한 뒤) 다시 적어도 넉넉해지지 않는다. 시각이 없는 다른 기록은 세지 않는다. */
function 받은때셈(재료, { 기록 = null } = {}) {
  const 때 = Date.parse(재료.시각 || '');
  const 다른 = (기록 || 지난기록()).filter((r) => !(r.편 === 재료.편 && r.판본 === 재료.판본));
  const 앞 = Number.isFinite(때) ? 다른.filter((r) => Date.parse(r.처음통과 || r.시각 || '') < 때) : 다른;
  const 문화소재 = (재료.시험관넷?.까닭 || []).some((x) => String(x).startsWith('문화 소재(판본 글'));
  const need = 넷판단({ 언어: 재료.언어, 틀: 재료.틀 || null, 편: 재료.편 || null, 문화소재, 딱지경고: 재료.딱지경고 || [], 기록: 앞 });
  return { 넷: need.넷, 까닭: need.까닭, 센때: 재료.시각 || null };
}

