import {readFile,writeFile} from 'node:fs/promises';

// A downloaded book keeps the approved fonts without contacting SYNK or a CDN.
const root=new URL('../',import.meta.url);
const definitions=[['SUIT','SUIT.woff2'],['InterTight','InterTight.woff2']];
const fonts=await Promise.all(definitions.map(async([name,file])=>`@font-face{font-family:${name};src:url(data:font/woff2;base64,${(await readFile(new URL(`desktop/assets/launcher/${file}`,root))).toString('base64')}) format('woff2');font-weight:100 900;font-display:swap}`));
const licenses=await Promise.all(definitions.map(async([name])=>await readFile(new URL(`experiences/family-album/assets/${name}-LICENSE.txt`,root),'utf8')));
const output='// Generated by tools/build-member-book-assets.mjs. Do not edit font data.\n'+
  `export const BOOK_FONT_CSS=${JSON.stringify(fonts.join('\n'))};\n`+
  `export const BOOK_FONT_LICENSE=${JSON.stringify(licenses.join('\n\n'))};\n`;
const target=new URL('experiences/member-book-assets.mjs',root);
if(process.argv.includes('--check')){
  if(await readFile(target,'utf8')!==output)throw new Error('Member book assets differ from approved source fonts.');
  console.log('Member book fonts and licenses match approved assets.');
}else{await writeFile(target,output,'utf8');console.log('Built standalone member book fonts and licenses.');}
