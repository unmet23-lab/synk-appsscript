/** 글을 걸러 문제 목록을 돌려준다(빈 목록이면 통과). 허용낱말: 광고 이름처럼 숫자가 든 이름표 */
function 검사하기(글, { 지표, 표본댓글, 상태, 허용낱말 = [] }) {
  const 문제 = [];
  const 허용 = [...기본허용, ...허용낱말];
  const 바꿀 = 글.바꿀셋 || [];
  if ((글.타일 || []).length !== 4) 문제.push(`타일은 넷이어야 한다(지금 ${(글.타일 || []).length})`);
  if (바꿀.length > 3) 문제.push(`바꿀셋은 셋까지(지금 ${바꿀.length})`);
  if (바꿀.length < 3 && !String(글.덜낸까닭 || '').trim()) 문제.push(`바꿀셋이 ${바꿀.length}개다 — 셋을 못 채운 까닭을 덜낸까닭에 쓴다`);
  if ((글.예시 || []).length > 3) 문제.push('예시는 셋까지');
  const 글칸 = [];
  const 칸 = (경로, s) => 글칸.push([경로, String(s || '')]);
  칸('한줄', 글.한줄); 칸('덜낸까닭', 글.덜낸까닭);
  (글.타일 || []).forEach((t, i) => { 칸(`타일${i + 1}.라벨`, t.라벨); 칸(`타일${i + 1}.설명`, t.설명); if (!지표[t.지표]) 문제.push(`타일${i + 1}.지표 「${t.지표}」는 없는 지표`); });
  for (const c of 칸들) {
    칸(c, 글[c]);
    const 쓸수있음 = 갈래[c].상태.some((k) => 됨인가(상태[k]));
    if (!쓸수있음 && String(글[c] || '').trim()) 문제.push(`「${c}」 칸의 자료를 이번엔 못 읽었다(${갈래[c].상태.map((k) => `${k}: ${상태[k] || '없음'}`).join(' · ')}) — 이 칸은 빈 글로`);
  }
  if (멈춤낱말.test(String(글.랜딩 || ''))) 문제.push('「랜딩」 칸에 「멈췄다」를 썼다 — 평균 스크롤은 평균이라 「평균적으로 여기까지 내려왔다」로');
  바꿀.forEach((p, i) => {
    const 곳 = `바꿀셋${i + 1}`;
    칸(`${곳}.무엇`, p.무엇); 칸(`${곳}.왜`, p.왜); 칸(`${곳}.어떻게`, p.어떻게);
    for (const n of p.근거 || []) if (!지표[n]) 문제.push(`${곳}.근거 「${n}」는 없는 지표`);
    const 근거 = (p.근거 || []).filter((n) => 지표[n]);
    const g = 갈래[p.어디];
    if (!g) { 문제.push(`${곳}.어디 「${p.어디}」는 ${어디들.join(' · ')} 가운데 하나`); return; }
    if (!g.상태.some((k) => 됨인가(상태[k]))) { 문제.push(`${곳}은 「${p.어디}」를 바꾸자는데 그 자료를 이번엔 못 읽었다 — 읽은 갈래에서 고른다`); return; }
    const 갈래근거 = 근거.filter((n) => g.머리.some((h) => n.startsWith(h)));
    if (!갈래근거.length) 문제.push(`${곳}(${p.어디})의 근거에 그 갈래 지표(${g.머리.join(' ')}…)가 하나도 없다`);
    else if (!갈래근거.some((n) => 신호(n, 지표[n]) === '약함')) 문제.push(`${곳}(${p.어디})의 근거가 모두 약한 신호가 아니다(평소보다 낮음 · 하위 25% · 시청 유지 절반 아래 · 막힌 신호 따위) — 바꿀 까닭을 보이는 지표를 넣거나 이 항목을 뺀다`);
    if (p.어디 === '영상' && 유지낱말.test(String(p.왜 || '')) && !근거.some(유지지표인가)) 문제.push(`${곳}.왜가 영상 앞부분 · 길이를 말하는데 근거에 시청 유지 지표가 없다 — 조회만으로는 말할 수 없다`);
    if (p.어디 === '랜딩' && 멈춤낱말.test(`${p.왜} ${p.무엇}`)) 문제.push(`${곳}에 「멈췄다」를 썼다 — 평균은 평균으로`);
  });
  const 지 = 글.지킬것 || {};
  칸('지킬것.무엇', 지.무엇);
  for (const n of 지.근거 || []) if (!지표[n]) 문제.push(`지킬것.근거 「${n}」는 없는 지표`);
  if (String(지.무엇 || '').trim() && !(지.근거 || []).some((n) => 신호(n, 지표[n]) === '셈')) 문제.push('지킬것의 근거에 센 신호(평소보다 높음 · 상위 25% · 시청 유지 절반 넘음 따위)가 없다 — 없으면 지킬것을 빈 글로');
  for (const e of 글.예시 || []) {
    칸('예시', e.뜻);
    const 원문 = 표본댓글[e.댓글];
    if (!원문) 문제.push(`예시의 댓글 「${e.댓글}」는 넘겨준 표본에 없다`);
    else if (같은조각(e.뜻, 원문)) 문제.push(`예시 「${e.뜻}」가 댓글 원문을 그대로 옮겼다 — 뜻만 자기 말로`);
  }
  for (const [경로, s] of 글칸) {
    문제.push(...칸검사(경로, s, 지표, 허용));
    const 배 = s.replace(/\{\{[^{}]+\}\}/g, '□').match(고유어배수);
    if (배) 문제.push(`${경로}에 배수를 말로 풀어 쓴 곳이 있다(「${배[0]}」) — {{…평소대비}}로`);
  }
  return 문제;
}

function 지표글(지표) {
  return Object.entries(지표).map(([이름, x]) => {
    const s = 신호(이름, x);
    return `- ${이름} = ${typeof x.값 === 'number' ? x.값 : `「${x.값}」`}${x.단위} — ${x.설명}${s ? ` [${s === '약함' ? '약한 신호' : '센 신호'}]` : ''}`;
  }).join('\n');
}

