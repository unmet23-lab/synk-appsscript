/** 지표 하나가 「약함」(바꿀 근거) · 「셈」(지킬 근거) · null(어느 쪽도 아님) */
function 신호(이름, x) {
  if (!x) return null;
  const v = x.값;
  if (/\.평소대비$/.test(이름)) return v < 1 ? '약함' : v > 1 ? '셈' : null;
  if (/\.위치$/.test(이름)) return v === '하위 25%' ? '약함' : v === '상위 25%' ? '셈' : null;
  if (/\.(본비율|앞3초유지|평균조회율)$/.test(이름)) return v < 문턱.유지 ? '약함' : '셈';
  if (/\.완주율$/.test(이름)) return v < 문턱.완주율 ? '약함' : '셈';
  if (/^랜딩\.([^.]+\.)?평균스크롤$/.test(이름)) return v < 문턱.스크롤 ? '약함' : '셈';
  if (/^랜딩\.(헛클릭|분노클릭|되돌아감)비율$/.test(이름)) return v >= 문턱.막힘 ? '약함' : null;
  if (이름 === '댓글.수') return v === 0 ? '약함' : null;
  if (/^댓글\.주제\.(내용 헷갈림|반대·불신|AI 언급|품질·소재 걱정)\.수$/.test(이름)) return v > 0 ? '약함' : null;
  if (/^댓글\.주제\.(칭찬·감탄|구매 의도·후기|다음 편 요청)\.수$/.test(이름)) return v > 0 ? '셈' : null;
  return null;
}
