const 아는플래그 = ['--json', '--훅', '--hook', '--장부없이', '--처분', '--신판', '--사유'];

function 값(argv, 이름) {
  const i = argv.indexOf(이름);
  if (i === -1) return null;
  const v = argv[i + 1];
  if (!v || /^--/.test(v)) throw 확인불가(`\`${이름}\` 뒤에 값이 없다`);
  return v;
}

