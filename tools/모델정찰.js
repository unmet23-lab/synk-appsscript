function 글자만(s) {
  return String(s)
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, ' ')
    .trim();
}

/* 표 하나 = { 머리:[칸…], 줄들:[[칸…]…] }.
 * 머리를 `th` 로만 찾지 않는다 — 함정③(제미나이 폐기표는 `<thead><tr><td><b>Model</b>`). */
function 표들(html) {
  return [...String(html).matchAll(/<table[\s\S]*?<\/table>/g)].map((m) => {
    const 줄 = [...m[0].matchAll(/<tr[\s\S]*?>([\s\S]*?)<\/tr>/g)].map((r) =>
      [...r[1].matchAll(/<t[hd][^>]*>([\s\S]*?)<\/t[hd]>/g)].map((c) => 글자만(c[1])));
    return { 머리: 줄[0] || [], 줄들: 줄.slice(1) };
  });
}

/* 모델 ID 로 인정할 모양. 함정④(두 칸이 붙어 나온 `<pre>`)를 여기서 버린다. */
function 모델ID꼴(s) {
  if (!/^[a-z][a-z0-9]*(?:[.\-][a-z0-9]+)*$/.test(s)) return false;
  if (s.length > 60) return false;
  const 앞 = s.split('-')[0];
  if (앞.length > 2 && s.split(앞).length - 1 > 1) return false; // 벤더 접두어가 두 번 = 병합 산물
  return true;
}

