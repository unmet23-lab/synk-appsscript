// ══════════════════════════════════════════════ 계열·버전

/* `gemini-3.6-flash` → {벤더:gemini, 버전:[3,6], 꼬리:'flash'}
 * `gemini-3.1-pro-preview` → {꼬리:'pro-preview', 기준꼬리:'pro', 미리보기:true}
 * 기준꼬리를 따로 두는 이유: **미리보기가 정식이 되는 것도 「새 판」**이라 놓치면 안 된다. */
function 갈래(id) {
  const m = /^([a-z][a-z0-9]*)-(\d+(?:\.\d+)*)(?:-(.+))?$/.exec(String(id || ''));
  if (!m) return null;
  const 꼬리 = m[3] || '';
  return {
    id: String(id),
    벤더: m[1],
    버전: m[2].split('.').map(Number),
    꼬리,
    기준꼬리: 꼬리.replace(/(^|-)preview$/, ''),
    미리보기: /(^|-)preview$/.test(꼬리),
  };
}

function 버전비교(a, b) {
  const n = Math.max(a.length, b.length);
  for (let i = 0; i < n; i++) {
    const x = a[i] || 0;
    const y = b[i] || 0;
    if (x !== y) return x - y;
  }
  return 0;
}

function 신판찾기(우리id, 후보들) {
  const u = 갈래(우리id);
  if (!u) return [];
  const 나온것 = [];
  for (const c of 후보들) {
    if (c === 우리id) continue;
    const g = 갈래(c);
    if (!g || g.벤더 !== u.벤더 || g.기준꼬리 !== u.기준꼬리) continue;
    const d = 버전비교(g.버전, u.버전);
    if (d > 0) 나온것.push({ id: c, 왜: `버전 ${g.버전.join('.')} > ${u.버전.join('.')}` });
    else if (d === 0 && u.미리보기 && !g.미리보기) 나온것.push({ id: c, 왜: '같은 버전의 «정식»판 — 미리보기 졸업' });
  }
  return 나온것.sort((a, b) => 버전비교(갈래(b.id).버전, 갈래(a.id).버전));
}

