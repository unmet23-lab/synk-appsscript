/**
 * 열림 대기 감시 — **순수 함수**(네트워크·파일 없이 회귀가 직접 문다).
 *
 * 🔑 호출부 안에 두지 않는 이유: 그러면 실제 정찰 런으로만 닿아 **어떤 검사도 못 건다**.
 *   그리고 이 감시가 실제로 «발화하는지»는 열리는 날 처음 도는데, 그날 안 울면 영영 모른다
 *   (이 저장소가 심문 9일 즉사로 배운 자리 — 「켜짐」은 «돌고 있다»가 아니다).
 *
 * @param 후보 벤더 목록에서 모은 slug 집합(Set 또는 배열)
 * @param 캐시읽었나 코덱스 캐시를 읽었나 — false 면 「아직」이 아니라 **「못 봤다」**로 답한다
 * @param 표 열림대기 표(기본 = 정책 정본)
 * @returns 소견 줄 배열(뜬 것도 못 본 것도 없으면 빈 배열)
 */
function 열림줄들(후보, 캐시읽었나, 표 = (정책.열림대기 || {})) {
  const 이름목록 = Object.keys(표);
  if (!이름목록.length) return [];
  /* 🔴 못 읽었으면 침묵하지 않는다 — 침묵을 「아직 안 열렸다」로 읽으면 열린 날을 통째로 놓친다.
   *   코덱스 쪽 목록의 유일한 출처가 로컬 캐시라 이 갈래가 실제로 흔하다(캐시가 낡으면 확인 불가). */
  if (!캐시읽었나) {
    return [`⚠ 열림 대기(${이름목록.join(' · ')})를 **안 재봤다** — 코덱스 캐시가 확인 불가라 목록을 못 읽었다(「아직 안 열림」이 아니다)`];
  }
  const 있는것 = new Set(후보 || []);
  const 줄 = [];
  for (const [접두, 뜻] of Object.entries(표)) {
    const 이름들 = [접두, ...((뜻 && 뜻.별칭) || [])];
    /* 접두 일치까지 본다 — 벤더가 `gpt-6-astra-mini` 처럼 꼬리를 붙여 내놓아도 잡는다.
     * 정확히 같은 이름만 보면 그 무늬에서 조용히 놓친다. */
    const 뜬것 = [...있는것].filter((x) => 이름들.some((n) => x === n || String(x).startsWith(n + '-')));
    if (!뜬것.length) continue;
    줄.push(`🚪 **${접두} 가 벤더 목록에 떴다** — ${뜬것.join(' · ')} · 쓸 자리: ${((뜻 && 뜻.쓸자리) || []).join(' · ')}`);
    줄.push(`   → ${(뜻 && 뜻.열리면) || '효력을 프로브로 재고 tools/모델정책.js 에 옮겨 적는다'}`);
  }
  return 줄;
}

