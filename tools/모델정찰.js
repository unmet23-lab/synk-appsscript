/* 🔴 **한 값을 두 꼴이 아는 자리** — 장부는 출처상태를 «문자열 맵»(`{openai폐기:"OK"}`)으로 적고
 *   실행 결과는 «객체 맵»(`{openai폐기:{상태,말}}`)이다. 옛 판의 `훅에게()` 는 객체만 알아서,
 *   재사용 경로에서 `s.상태` 가 undefined 였다. 08-29 검증이 실물로 재현한 화면:
 *     🔴 OpenAI 공식 폐기: undefined      ← OK 였는데 🔴 로 뒤집혔다
 *     🔴 Gemini 공식 폐기: undefined      ← 실제로 죽은 건 이것 하나뿐
 *   훅은 **종료코드가 언제나 0**이라 신호가 「줄」 하나뿐인데, 하필 그 줄이 못 쓰게 됐다.
 *   이유는 장부의 `확인불가` 배열(`"키: 말"` 꼴)이 이미 쥐고 있었는데 훅이 그걸 안 봤다.
 *   🔑 두 꼴을 없앨 수는 없다(장부를 작게 유지하는 값이 있다) — 대신 **읽는 자리 한 곳**에서
 *      한 꼴로 되돌린다. 되살릴 말이 없으면 「없다」가 아니라 그렇게 적는다. */
function 출처상태되살리기(맵, 확인불가) {
  const 말들 = {};
  for (const s of 확인불가 || []) {
    const i = String(s).indexOf(': ');
    if (i > 0) 말들[String(s).slice(0, i)] = String(s).slice(i + 2);
  }
  const 나온것 = {};
  for (const [k, v] of Object.entries(맵 || {})) {
    if (v && typeof v === 'object') { 나온것[k] = v; continue; }
    const 상태 = String(v);
    나온것[k] = {
      상태,
      말: 말들[k] || (상태 === 'OK' ? '(장부엔 상태만 남는다)' : '이유가 장부에 안 남았다 — 다시 돌려야 안다'),
    };
  }
  return 나온것;
}

