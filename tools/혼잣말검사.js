#!/usr/bin/env node
'use strict';
/* 혼잣말검사 — 가이드 혼잣말 정본(docs/캐릭터/혼잣말_정본.json)의 상시 자 «하나».
 *
 * 왜 있나(08-28 유호 승인): 숙제 채점에서 「말이 안 되는 문구」가 대량 생산에 섞였던 병의 재발 방지.
 * 혼잣말 450~600은 손 검수가 불가능한 양이라, 커밋 전에 이 자를 기계로 통과해야 한다.
 *
 * 무엇을 재나:
 *  ① 스키마 — 필드·값 유효성(자리 13종 · 소재 12종(§5-4) · 급수 1~3 · 갈래 짧|긴)
 *  ② 짧은 갈래 어절수 ≤ 4 (가이드_정본.md §5-2)
 *  ③ talk 금지패턴 4종 «그대로» — SYNK-talk tests/lib/금지패턴.js 와 같은 정규식(숫자·비교·점수·평가어).
 *     ⚠ 두 벌이다 — talk 쪽이 개정되면 여기도 손으로 맞춘다(반입 게이트가 진짜 심판이라 여기는 예비 자).
 *  ④ 브랜드 금칙어(synk-brand) + 이모지·키릴 0 (몽골어 혼잣말은 검수 전 — talk lib/마스코트생명.js 61행)
 *  ⑤ 캐릭터 지문 교차 — 「이 몸」·「크앙」= 까몽 전용, 「측정 불가」= 마린 전용
 *  ⑤-b 세 줄 규칙(가이드_정본 §2-0 · 09-05) — 몽글은 세상에 묻는다(? ! 필수) · 까몽은 자기를 말한다(이 몸·용·나·내 필수) · 마린은 보고한다(? ! 0).
 *      소리만인 줄(「와아…!」「히히」「쿨… 쿨…」)은 말이 아니라 목소리라 밖이다.
 *  ⑥ 완전 중복 0 · id 중복 0
 *  ⑦ 분포 보고 — 캐릭터×자리·소재·갈래·급수 (합계 = 갈래+갈래)
 *  ⑧ 학생을 향한 말 몫 — 캐릭터마다 «너에게 하는 말»(너·네 · 명령/청유 · 물음 · 전원 · 같이)이 전체·idle 각각 3분의 1 이상, 3분의 2 이하.
 *      09-05 실측(유호 「마스코트마다 다른 맛으로 소통하는 맛」): 마린 7% — 보고만 하고 학생에게 말을 안 걸고 있었다(가이드_정본 §5-7).
 * 종료 코드: 위반 있으면 1. */
const fs = require('fs');
const path = require('path');
const 정본경로 = path.join(__dirname, '..', 'docs', '캐릭터', '혼잣말_정본.json');

const 자리들 = ['idle', '탭', '방치', '아침', '밤', '겨울', '여름', '차강사르', '무오류첫열람', '재도전',
  /* 09-02 신설 — 기억감 층(축 A). 「며칠 만인가」에 따라 갈린다: 잠깐 2~3일 · 오랜만 4~13일 · 한참 14일+ */
  '재회잠깐', '재회오랜만', '재회한참'];
const 소재들 = ['음식', '날씨', 'K-POP', '게임', '음악', '운동', '공부', '잠', '친구', '몽골', '한국', '계절'];

/* talk tests/lib/금지패턴.js 사본 — 개정 시 그쪽이 정본 */
const 한글수사 = '한|두|세|네|다섯|여섯|일곱|여덟|아홉|열|스무|일|이|삼|사|오|육|칠|팔|구|십|백|천|만';
const 단위 = '번|개|회|점|등|군데|가지|자리|줄|문장';
const 금지패턴 = [
  { 이름: '숫자', 정규식: new RegExp(`[0-9]|(?:${한글수사})\\s+(?:${단위})`) },
  { 이름: '남과의 비교', 정규식: /친구|다른 (학생|아이|사람)|평균|등수|순위|반에서/ },
  { 이름: '점수·등급', 정규식: /점수|퍼센트|%|등급|레벨|랭킹/ },
  { 이름: '평가어', 정규식: /잘했|잘 했|훌륭|최고|대단|멋져|멋있|완벽|천재/ },
];
const 브랜드금칙 = { 이름: '브랜드 금칙어', 정규식: /패배|졌다|실패|불운|하락|부족|늦었다|화이팅/ };
const 비한글 = { 이름: '이모지·키릴', 정규식: /[Ѐ-ӿ\u{1F000}-\u{1FAFF}☀-➿]/u };
const 지문교차 = [
  { 이름: '까몽 전용 어휘', 정규식: /이 몸|크앙/, 허용: '까몽' },
  { 이름: '마린 전용 어휘', 정규식: /측정 불가/, 허용: '마린' },
];

/* ⑤-b «세 줄 규칙» — 가이드_정본 §2-0(09-05 · 유호 「각각 개성이 확실히 보이도록 · 확실히 차이나게」).
 * 셋 다 말이 많으니(v2.0) 갈리는 것은 말의 «방향»이다: 몽글은 세상에 묻고, 까몽은 자기를 말하고, 마린은 보고한다.
 * 성격 설명은 사람이 잊지만 이 자는 안 잊는다. 09-05 실측: 이 자를 대기 전 걸린 줄 71(몽글 10 · 까몽 59 · 마린 2 — 마린 규칙을 «있어야 하는 것»까지 넓힌 뒤) → 문구만 고쳐 0. */
const 소리만 = /^(?:[\s…~!.?,]*(?:와아|와|히히|하하|음음|흥얼흥얼|하암|쿨|흠흠|훗|크앙|에취|콜록|히익|커흠|흥|음|앗)[\s…~!.?,]*)+$/;
const 까몽자기 = /이 몸|(?<![가-힣])까몽|(?<![가-힣])용(?:의|은|이|한테|한텐|에게|도|과|만|들|(?![가-힣]))|(?<![가-힣])내(?: |가|\s거)|(?<![가-힣])나(?: |는|도|한테|랑|를)|(?<![가-힣])난 |제자|…\s*아니|아니야|아니거든|놀란 게 아니|무, 무|이, 이|점프 연습/;
const 마린보고 = /(확인|완료|보고|수칙|측정|기록|전원|점호|임무|대기|관측|분석|보급|명령|판정|불가|규정|작전|경보|훈련|지급|권장|착용|기상|취침|소등|종료|시작|정렬|점검|모드|결과|인정|접수|감지|순찰|출발|배급|경로|전략|…|(?:나|인가|는가)\.\s*$|(?:^|\s)[가-힣]{1,4}\.(?:\s|$)|^[가-힣]+, )/;
/* ⑧ «학생을 향한 말» — 2인칭 · 명령/청유 · 물음 · 전원 · 같이. 보고만 하는 줄은 여기 안 걸린다(마린의 병이 그것이었다). */
const 향함 = /(?<![가-힣])너(?!무|머|희)|(?<![가-힣])네(?:가|게|겐|\s)|(?<![가-힣])넌 |전원|\?|[가-힣]라\.|해라|마라|자!|할래|볼래|줄래|봐!|봐\.|봐봐|같이|동행/;
const 향함바닥 = 1 / 3;
/* 천장 — 3분의 2 위면 «알림창»이다(정본 §5-7). 09-05 밤 실측: 아래만 있는 자로는 78% 를 못 잡았다. */
const 향함천장 = 2 / 3;
const 세줄규칙 = {
  몽글: { 이름: '몽글은 세상에 묻는다 — ? ! 이 없다', 통과: (s) => /[!?]/.test(s) },
  까몽: { 이름: '까몽은 자기를 말한다 — 이 몸·용·나·내가 없다', 통과: (s) => 까몽자기.test(s) },
  마린: { 이름: '마린은 보고한다 — ? ! 이 있거나, 보고 표식(한 낱말 문장 「비.」「확인.」 · 시그니처 · 「…」 · 「~인가.」)이 없다', 통과: (s) => !/[!?~]/.test(s) && 마린보고.test(s) },
};

const 데이터 = JSON.parse(fs.readFileSync(정본경로, 'utf8'));
const 문구들 = 데이터.문구;
const 위반 = [];
const 본문구 = new Map();
const 본id = new Set();

for (const 줄 of 문구들) {
  const 표 = `${줄.id ?? '?'} ${줄.캐릭터}/${줄.자리}`;
  if (!줄.id || 본id.has(줄.id)) 위반.push(`${표}: id 없음/중복`);
  본id.add(줄.id);
  if (!['몽글', '까몽', '마린'].includes(줄.캐릭터)) 위반.push(`${표}: 캐릭터 이상`);
  if (!자리들.includes(줄.자리)) 위반.push(`${표}: 자리 「${줄.자리}」 목록 밖`);
  if (!['짧', '긴'].includes(줄.갈래)) 위반.push(`${표}: 갈래 이상`);
  if (![1, 2, 3].includes(줄.급수)) 위반.push(`${표}: 급수 이상`);
  if (!Array.isArray(줄.소재) || !줄.소재.length || 줄.소재.some((s) => !소재들.includes(s)))
    위반.push(`${표}: 소재 이상 ${JSON.stringify(줄.소재)}`);
  if (typeof 줄.문구 !== 'string' || !줄.문구.trim()) { 위반.push(`${표}: 문구 없음`); continue; }
  if (줄.갈래 === '짧' && 줄.문구.trim().split(/\s+/).length > 4)
    위반.push(`${표}: 짧은 갈래인데 어절 ${줄.문구.trim().split(/\s+/).length} — 「${줄.문구}」`);
  for (const p of [...금지패턴, 브랜드금칙, 비한글])
    if (p.정규식.test(줄.문구)) 위반.push(`${표}: ${p.이름} — 「${줄.문구}」`);
  for (const z of 지문교차)
    if (z.정규식.test(줄.문구) && 줄.캐릭터 !== z.허용) 위반.push(`${표}: ${z.이름}를 ${줄.캐릭터}가 씀 — 「${줄.문구}」`);
  if (!소리만.test(줄.문구) && 세줄규칙[줄.캐릭터] && !세줄규칙[줄.캐릭터].통과(줄.문구))
    위반.push(`${표}: 세 줄 규칙 — ${세줄규칙[줄.캐릭터].이름} 「${줄.문구}」`);
  if (본문구.has(줄.문구)) 위반.push(`${표}: 완전 중복 (↔ ${본문구.get(줄.문구)})`);
  본문구.set(줄.문구, 줄.id);
}

/* 분포 — 좋은 0과 「안 재봤다」를 가른다: 합계 = 캐릭터 셋의 합 */
const 세기 = (키fn) => {
  const m = {};
  for (const 줄 of 문구들) { const k = 키fn(줄); m[k] = (m[k] || 0) + 1; }
  return m;
};
const 캐릭터별 = 세기((j) => j.캐릭터);
for (const c of ['몽글', '까몽', '마린']) {
  const 전체 = 문구들.filter((l) => l.캐릭터 === c);
  const 아이들 = 전체.filter((l) => l.자리 === 'idle');
  const 몫 = (xs) => xs.filter((l) => 향함.test(l.문구)).length / Math.max(1, xs.length);
  const a = 몫(전체), b = 몫(아이들);
  if (a < 향함바닥 || b < 향함바닥)
    위반.push(`${c}: 학생을 향한 말이 모자란다 — 전체 ${Math.round(a * 100)}% · idle ${Math.round(b * 100)}% (바닥 ${Math.round(향함바닥 * 100)}%) — 보고만 하는 줄에 「…너에게 한 마디」를 단다(정본 §5-7)`);
  if (a > 향함천장 || b > 향함천장)
    위반.push(`${c}: 학생을 향한 말이 넘친다 — 전체 ${Math.round(a * 100)}% · idle ${Math.round(b * 100)}% (천장 ${Math.round(향함천장 * 100)}%) — 매 줄 학생을 보면 알림창이다. 다정은 «새는» 것이다(정본 §5-7)`);
  console.log(`  ${c} 학생을 향한 말: 전체 ${전체.filter((l) => 향함.test(l.문구)).length}/${전체.length} (${Math.round(a * 100)}%) · idle ${아이들.filter((l) => 향함.test(l.문구)).length}/${아이들.length} (${Math.round(b * 100)}%)`);
}
console.log(`[혼잣말] 총 ${문구들.length} = 몽글 ${캐릭터별.몽글 || 0} + 까몽 ${캐릭터별.까몽 || 0} + 마린 ${캐릭터별.마린 || 0}`);
console.log('  갈래:', JSON.stringify(세기((j) => j.갈래)), '· 급수:', JSON.stringify(세기((j) => j.급수)));
for (const c of ['몽글', '까몽', '마린']) {
  const 소재분포 = {};
  for (const 줄 of 문구들) if (줄.캐릭터 === c) for (const s of 줄.소재) 소재분포[s] = (소재분포[s] || 0) + 1;
  console.log(`  ${c} 소재:`, 소재들.map((s) => `${s} ${소재분포[s] || 0}`).join(' · '));
}
console.log('  자리:', JSON.stringify(세기((j) => j.자리)));

if (위반.length) {
  console.error(`\n[혼잣말] 🔴 위반 ${위반.length}건:`);
  for (const v of 위반) console.error('  - ' + v);
  process.exit(1);
}
console.log(`[혼잣말] 정합 OK (${문구들.length}문구 · 위반 0)`);
