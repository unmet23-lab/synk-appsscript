#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
// The renderer imports the canonical Atlas projection; it must not maintain a
// second implementation of consent, occurrence times or comparison boundaries.
function buildMemberActivity({ sourceRoot = root, check = false, outputFile } = {}) {
  sourceRoot = path.resolve(sourceRoot);
  const target = outputFile || path.join(sourceRoot, 'desktop/renderer/generated/member-activity.mjs');
  const esbuild = require(require.resolve('esbuild', { paths: [path.join(root, 'experiences/synk-account')] }));
  const artifacts = [];
  for (const [entry, destination] of [['atlas/member-activity.js', target],
    ['experiences/synk-account/src/member-activity-data.mjs', path.join(path.dirname(target), 'member-activity-data.mjs')],
    ['atlas/member-understanding.js', path.join(path.dirname(target), 'member-understanding.mjs')],
    ['experiences/synk-account/src/member-understanding-data.mjs', path.join(path.dirname(target), 'member-understanding-data.mjs')]]) {
  const built = esbuild.buildSync({ absWorkingDir: sourceRoot, entryPoints: [entry], bundle: true, write: false, metafile: true,
    platform: 'browser', format: 'esm', target: ['es2022'], charset: 'utf8',
    banner: { js: '// Generated by tools/build-member-activity.js from canonical source. Do not edit.' } });
  const bytes = Buffer.from(built.outputFiles[0].contents), sha = value => crypto.createHash('sha256').update(value).digest('hex');
  const manifestFile = destination.replace(/\.mjs$/, '') + '.manifest.json';
  const manifest = { version: 1, entry, sha256: sha(bytes), sources: Object.fromEntries(Object.keys(built.metafile.inputs).sort().map(file =>
    [file.replace(/\\/g, '/'), sha(fs.readFileSync(path.join(sourceRoot, file), 'utf8').replace(/\r\n/g, '\n'))])) };
  for (const [file, content] of [[destination, bytes], [manifestFile, Buffer.from(JSON.stringify(manifest, null, 2) + '\n')]]) {
    const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === content.toString('utf8').replace(/\r\n/g, '\n');
    if (check && !same) throw new Error('Stale member activity artifact: run node tools/build-member-activity.js');
    if (!check && !same) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      const temporary = `${file}.build-${process.pid}-${crypto.randomUUID()}.tmp`;
      try { fs.writeFileSync(temporary, content, { flag: 'wx' });fs.renameSync(temporary, file); }
      finally { if (fs.existsSync(temporary)) fs.unlinkSync(temporary); }
    }
  }
  artifacts.push({ file: destination, manifestFile, bytes: bytes.length, sha256: sha(bytes) });
  }
  return { ...artifacts[0], artifacts, checked: check };
}
if (require.main === module) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check')) throw new Error('Usage: node tools/build-member-activity.js [--check]');
  const result = buildMemberActivity({ check: args.includes('--check') });
  console.log(`${result.checked ? 'Verified' : 'Built'} member activity browser artifacts (${result.artifacts.length} modules).`);
}
module.exports = { buildMemberActivity };
