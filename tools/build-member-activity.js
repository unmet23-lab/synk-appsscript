#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
// The renderer imports the canonical Atlas projection; it must not maintain a
// second implementation of consent, occurrence times or comparison boundaries.
function buildMemberActivity({ sourceRoot = root, check = false, outputFile } = {}) {
  sourceRoot = path.resolve(sourceRoot);
  const target = outputFile || path.join(sourceRoot, 'desktop/renderer/generated/member-activity.mjs');
  const esbuild = require(require.resolve('esbuild', { paths: [path.join(root, 'experiences/synk-account')] }));
  const entries = [['atlas/member-activity.js', target],
    ['experiences/synk-account/src/member-activity-data.mjs', path.join(path.dirname(target), 'member-activity-data.mjs')],
    ['atlas/member-understanding.js', path.join(path.dirname(target), 'member-understanding.mjs')],
    ['experiences/synk-account/src/member-understanding-data.mjs', path.join(path.dirname(target), 'member-understanding-data.mjs')]];
  const directory = path.resolve(path.dirname(target)), sharedDirectory = path.join(directory, 'member-shared');
  // One graph keeps the statement contract (including old document versions) in
  // one module. Entry filenames and their public exports stay unchanged.
  const built = esbuild.buildSync({ absWorkingDir: sourceRoot,
    entryPoints: entries.map(([entry, destination]) => ({ in: entry, out: path.basename(destination, '.mjs') })),
    outdir: directory, outExtension: { '.js': '.mjs' }, chunkNames: 'member-shared/chunk-[hash]',
    bundle: true, splitting: true, write: false, metafile: true,
    platform: 'browser', format: 'esm', target: ['es2022'], charset: 'utf8',
    banner: { js: '// Generated by tools/build-member-activity.js from canonical source. Do not edit.' } });
  const sha = value => crypto.createHash('sha256').update(value).digest('hex'), slash = value => value.replace(/\\/g, '/');
  const outputs = new Map(built.outputFiles.map(file => [slash(path.relative(directory, file.path)), Buffer.from(file.contents)]));
  const metadata = new Map(Object.entries(built.metafile.outputs).map(([file, value]) => [slash(path.relative(directory, path.resolve(sourceRoot, file))), value]));
  const entryNames = new Set(entries.map(([, destination]) => path.basename(destination)));
  for (const name of outputs.keys()) if (!entryNames.has(name) && !/^member-shared\/chunk-[A-Z0-9]{8}\.mjs$/.test(name)) throw new Error('Unexpected member activity output: ' + name);
  const files = Object.fromEntries([...outputs].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([name, bytes]) => [name, {
    sha256: sha(bytes), imports: metadata.get(name).imports.map(item => {
      const dependency = slash(path.relative(directory, path.resolve(sourceRoot, item.path)));
      if (item.external || !outputs.has(dependency)) throw new Error('Unbundled member activity dependency: ' + item.path);
      return dependency;
    }).sort(),
  }]));
  // Source receipts cover the entire single compilation, including shared code.
  const sources = Object.fromEntries(Object.keys(built.metafile.inputs).sort().map(file =>
    [slash(file), sha(fs.readFileSync(path.join(sourceRoot, file), 'utf8').replace(/\r\n/g, '\n'))]));
  const artifacts = [], writes = [...outputs].map(([name, bytes]) => [path.join(directory, name), bytes]);
  for (const [entry, destination] of entries) {
  const bytes = outputs.get(path.basename(destination));
  const manifestFile = destination.replace(/\.mjs$/, '') + '.manifest.json';
  const manifest = { version: 2, entry, sha256: sha(bytes), sources, files };
  writes.push([manifestFile, Buffer.from(JSON.stringify(manifest, null, 2) + '\n')]);
  artifacts.push({ file: destination, manifestFile, bytes: bytes.length, sha256: sha(bytes) });
  }
  // Only this builder's closed chunk directory may be pruned. Refuse unknown
  // files or links before changing anything; never walk another tree via a link.
  const info = file => { try { return fs.lstatSync(file); } catch (error) { if (error.code === 'ENOENT') return null;throw error; } };
  const assertRegular = file => { const stat = info(file);if (stat && (!stat.isFile() || stat.isSymbolicLink())) throw new Error('Unsafe member activity artifact: ' + file); };
  for (let folder = sharedDirectory; ; folder = path.dirname(folder)) {
    const stat = info(folder);if (stat && (!stat.isDirectory() || stat.isSymbolicLink())) throw new Error('Unsafe member activity directory: ' + folder);
    if (folder === path.dirname(folder)) break;
  }
  const stale = fs.existsSync(sharedDirectory) ? fs.readdirSync(sharedDirectory).map(name => {
    if (!/^chunk-[A-Z0-9]{8}\.mjs$/.test(name)) throw new Error('Unexpected member activity chunk: ' + name);
    const file = path.join(sharedDirectory, name);assertRegular(file);return file;
  }).filter(file => !outputs.has('member-shared/' + path.basename(file))) : [];
  for (const [file] of writes) assertRegular(file);
  if (check && stale.length) throw new Error('Stale member activity artifact: unexpected shared chunk');
  for (const [file, content] of writes) {
    const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === content.toString('utf8').replace(/\r\n/g, '\n');
    if (check && !same) throw new Error('Stale member activity artifact: run node tools/build-member-activity.js');
    if (!check && !same) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      const temporary = `${file}.build-${process.pid}-${crypto.randomUUID()}.tmp`;
      try { fs.writeFileSync(temporary, content, { flag: 'wx' });fs.renameSync(temporary, file); }
      finally { if (fs.existsSync(temporary)) fs.unlinkSync(temporary); }
    }
  }
  if (!check) for (const file of stale) { assertRegular(file);fs.unlinkSync(file); }
  return { ...artifacts[0], artifacts, files, totalBytes: [...outputs.values()].reduce((sum, bytes) => sum + bytes.length, 0), checked: check };
}
if (require.main === module) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check')) throw new Error('Usage: node tools/build-member-activity.js [--check]');
  const result = buildMemberActivity({ check: args.includes('--check') });
  console.log(`${result.checked ? 'Verified' : 'Built'} member activity browser artifacts (${result.artifacts.length} modules).`);
}
module.exports = { buildMemberActivity };
