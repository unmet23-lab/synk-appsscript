#!/usr/bin/env node
/* board — 세션별 파일에서 **조립한** 보드 표를 낸다.
 *
 * 정본은 `docs/_ops/보드/<지문>.md` 들이고 합쳐진 표는 디스크에 없다(F250 · tools/lib/보드.js).
 * 옛 `docs/세션보드.md` 를 열던 자리를 이 명령이 대신한다.
 */
'use strict';

const path = require('path');
const 보드 = require(path.join(__dirname, 'lib', '보드.js'));
// 낡음 «증거»는 별도 모듈 — 판정(완료·주인·🎫)은 보드.js 한 곳에 두고 여기선 파생만 쓴다.
const 낡음 = require(path.join(__dirname, 'lib', '보드낡음.js'));
// 지문 규칙은 한 곳에서만 산다 — 파일명과 줄 안의 지문이 갈라지지 않는 이유(board-id 머리말).
const 보드id = require(path.join(__dirname, '..', '.claude', 'hooks', 'lib', 'board-id.js'));

const ROOT = process.env.SYNK_BOARD_ROOT || path.resolve(__dirname, '..');
const 표 = 보드.텍스트(ROOT);

if (표 === null) {
  console.error(`[board] 보드 폴더가 없다: ${보드.폴더(ROOT)}`);
  console.error('  → 첫 선언이라면 그 폴더에 `<내 지문 8자리>.md` 를 만들어 표 행 한 줄을 쓴다.');
  process.exit(1);
}

process.stdout.write(표);

/* 유령 줄 — 표에는 안 뜨는데 **자리는 먹는** 줄(F322·F330·F331 · 사연 = tools/lib/보드.js).
 * 표만 내면 이 줄은 영원히 안 보인다: 쓴 세션은 「선언했다」고 믿고, 다음 세션은 상한이
 * 왜 넘쳤는지 모른 채 물려받은 위반을 안고 시작한다. **stdout 이 아니라 stderr** 로 낸다 —
 * 이 명령의 표를 파싱하는 자리가 있어서, 표 아래 글자를 붙이면 그쪽이 새 줄을 만난다. */
const 유령 = 보드.유령들(ROOT) || [];
if (유령.length) {
  console.error(`\n⚠ 유령 줄 ${유령.length}건 — 위 표에 **없는데** board-guard 는 세는 줄이다(상한을 먹는다):`);
  for (const g of 유령) {
    console.error(`  · ${g.파일}:${g.줄번호}  ${g.줄.replace(/\s+/g, ' ').slice(0, 60)}…`);
    g.사유.forEach((s) => console.error(`      ↳ ${s}`));
  }
  console.error('  → 주인이 살아 있으면 **그 세션이** 자기 파일에서 규격대로 고친다(남의 파일 편집은 F073).');
  console.error('    죽었고 완료 줄이면: node tools/board-move.js "<그 줄의 유일 문구>"');
}

/* 완료의심 — **완료 어휘가 낡았다**는 신호(F554 · 사연 = tools/lib/보드.js). 유령과 같은 자리에
 * 같은 이유로 낸다: 낡음이 조용하면 끝난 트랙이 영원히 활성으로 세어지고, 그 줄은 board-move 도
 * 보드수거도 못 집는다(따를 수 없는 처방 = F103). 실제로 4번째였다.
 * ⚠ 이것은 **막지 않는다** — 판정이 아니라 의심이라 헛것도 뜬다. 그래서 stderr 이고, 처방은
 *   「고쳐라」가 아니라 「둘 중 하나를 골라라」다(둘 다 그 세션이 자기 파일에서 할 수 있는 일). */
const 의심 = (보드.줄들(ROOT) || []).filter((r) => 보드.완료의심(r.줄));
if (의심.length) {
  console.error(`\n⚠ 완료의심 ${의심.length}건 — **활성으로 세는데** 상태 칸은 끝났다고 말하는 줄이다:`);
  for (const g of 의심) {
    console.error(`  · ${g.파일}:${g.줄번호}  ${보드.상태첫구절(g.줄).trim().slice(0, 56)}`);
  }
  console.error('  → 정말 끝났으면 상태 칸 첫 구절을 완료 어휘로 적는다'
    + `(${보드.활성어휘().완료.join('·')}) — 그래야 점유가 풀리고 수거가 집는다.`);
  console.error('    아직 도는 트랙이면 활성 어휘로 적는다(작업중·진행중·검증 중 …) — 그러면 이 줄은 사라진다.');
  console.error('    ⚠ 이 목록이 매주 같은 낱말로 는다면 그 낱말을 완료 어휘에 넣을 때다(그게 F554 였다).');
}

/* 주인 없는 줄 — 표에서는 산 줄과 **글자 하나 다르지 않은데** 마감 시점에서 굳은 줄이다.
 * 이 줄의 「▶다음」·「🎫」는 그 뒤 남이 해버렸어도 그대로 남는다(사연 = tools/lib/보드.js).
 * 유령과 같은 이유로 **stderr** 다 — 표를 파싱하는 곳이 넷이라 stdout 에는 한 글자도 안 붙인다. */
const 주인없음 = 보드.주인없는줄들(ROOT);
if (주인없음 === null) {
  /* 「0건」과 갈라 말한다 — 못 잰 것을 조용히 통과시키면 이 경고는 가장 필요한 날 사라진다(F207). */
  console.error('\n⚠ 줄 주인의 생사를 **못 쟀다**(「주인 없는 줄 0건」이 아니다) — 🎫 를 집기 전에 실물을 직접 연다.');
} else if (주인없음.length) {
  const 티켓 = 주인없음.filter((r) => r.이어받기);
  /* 「끝났다」고 단정하지 않는다 — 판정 재료는 **마감 도장**(SessionEnd)이지 죽음이 아니고,
   * 도장 찍은 세션도 도구를 다시 부르면 되살아난다(track-collision 이 도장을 지운다).
   * 그래도 경고는 유효하다: 마감을 선언한 순간부터 그 줄은 아무도 갱신하지 않는다. */
  console.error(`\n⚠ 주인이 **마감을 선언한** 줄 ${주인없음.length}건 — 그 시점에서 갱신이 멈췄다:`);
  /* 낡음 대조는 **기계가 한다**(F374). 여기 있던 자리는 「집기 전에 실물을 직접 연다」는 프로즈였고,
   * 그 처방이 세션 수만큼 곱해졌다 — 실측 7건 중 2건이 이미 나간 일감인데 표에서는 같은 모양이었다.
   * 판정은 여전히 사람 몫이다: 아래는 「낡았다」가 아니라 **증거**다(보드낡음.js 머리말 ⚠②). */
  const 증거들 = 낡음.줄별증거(주인없음.map((r) => r.줄), ROOT);
  let 재료없음 = 0;
  let 대기 = 0;
  주인없음.forEach((r, i) => {
    console.error(`  · ${r.지문 || r.파일}  ${r.줄.replace(/\s+/g, ' ').slice(0, 72)}…`);
    const ev = 증거들[i].증거;
    const 말 = 낡음.말들(ev);
    if (말.length) { for (const s of 말) console.error(`      ↳ ${s}`); return; }
    /* 재료가 없는 줄도 한 덩어리가 아니다 — 「내가 집을 줄이 아니다」는 잴 수 있다(보드낡음 `대기표식`). */
    if (ev.대기) { 대기 += 1; console.error(`      ↳ ${ev.대기} — **내가 집을 일감이 아니다**(과녁이 저장소 밖에 있다)`); return; }
    재료없음 += 1;
  });
  if (대기) {
    console.error(`\n  ⏳ ${대기}건은 **유호님·시점 대기**라 애초에 이어받을 줄이 아니다 — 대조할 것도, 집을 것도 없다.`);
  }
  if (재료없음) {
    console.error(`\n  ⚠ 그중 ${재료없음}건은 문구에 **대조할 재료가 없다**(경로도 커밋도 안 적혀 있다) — 「깨끗하다」가 아니라 «기계가 못 가른다»다. 그 줄은 직접 연다.`);
  }
  if (티켓.length) {
    console.error(`\n  그중 ${티켓.length}건이 이어받기 일감을 남겼다 — 위 ↳ 증거를 **먼저** 읽고 집는다.`);
    console.error('     「남이 이미 해버린 일」과 「내가 더 할 일」은 이 표에서 같은 모양이다 —');
    console.error('       갈라 주는 것은 표가 아니라 그 증거다(경로가 이미 있나 · 그 커밋이 이미 검수·합류했나).');
  }
  console.error('  → 완료 줄이면: node tools/board-move.js "<그 줄의 유일 문구>" (산 주인의 줄은 그 도구가 거절한다)');
}

/* 되찾기 — **내 줄이 보드에 없는데 아카이브에 있는** 자리 (2026-08-12 · `tools/보드수거.js` 와 한 벌).
 *
 * 왜 이 자리인가: 이관은 줄을 잃지 않는다(아카이브에 그대로다). 그런데 **찾을 통로가 없었다** —
 *   F146 이 그 사고고(줄을 잃은 세션은 다음 턴에 자기 트랙을 못 찾고 「트랙 없음」으로 접힌다 ·
 *   F144 — 아카이브에 멀쩡히 있어도 인계문은 보드만 본다). 수거를 기계로 돌리는 이상 되찾기도
 *   기계여야 한다: 안 그러면 자동화가 F146 의 **빈도만 올린다.**
 *   자리를 여기로 잡은 이유는 F368 과 같다 — 「없다」를 **읽는 자리**에서 드러낸다.
 *
 * ⚠ 조건을 좁게 잡는다. 보드에 내 줄이 **하나라도 있으면** 아무 말도 안 한다 — 그 세션은 이미
 *   자기 트랙을 찾았고, 옛 트랙의 아카이브 줄까지 매번 들이밀면 그건 소음이다(안 읽히는 장치가 된다).
 * ⚠ 유령까지 센다(`줄들` 이 아니라 훑기 전체) — 규격 밖이라 표에 안 뜰 뿐 **내 선언은 있다.**
 *   여기서 「내 줄 0」으로 읽으면 유령을 쓴 세션에게 「네 줄은 아카이브에 있다」고 거짓말한다. */
const 내지문 = 보드id.보드지문();
if (내지문) {
  const 내것 = [...(보드.줄들(ROOT) || []), ...(보드.유령들(ROOT) || [])]
    .filter((r) => 보드id.파일지문(r.파일) === 내지문);
  if (!내것.length) {
    const 아카 = 보드.아카이브된줄들(ROOT, 내지문);
    if (아카 === null) {
      console.error('\n⚠ 보드에 내 줄이 없다 — 아카이브를 **못 읽어** 거둬졌는지 판정 못 했다(「없다」가 아니다).');
    } else if (아카.length) {
      console.error(`\n🔁 보드에 내 줄이 없는데 **아카이브에 ${아카.length}건** 있다 — 마감 뒤 거둬진 내 줄이다(F368 수거).`);
      for (const l of 아카) console.error(`  · ${l.replace(/\s+/g, ' ').slice(0, 72)}…`);
      console.error(`  → 이어서 할 일이 남았으면 **줄을 되살리지 말고** ${보드.폴더('.')}\\${내지문}.md 에 새로 선언한다`);
      console.error('    (아카이브 줄은 그때의 기록이다 — 되붙이면 상한을 먹고 「지금 잡은 것」과 섞인다).');
    }
  }
}
