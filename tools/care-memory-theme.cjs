'use strict';
// Export only the Loom values the browser postcard actually consumes.
const fs = require('node:fs');
const path = require('node:path');
const loom = require('./lib/loom.js');
const target = path.resolve(__dirname, '../experiences/relationship-care/memory-theme.mjs');
function build() {
  const source = loom.정본();
  const theme = {
    source: 'Loom / docs/디자인_토큰.json',
    colors: { paper: source.색.Paper, ink: source.색.Black, accent: source.색['Coral 3'] },
    spaces: Object.fromEntries(Object.entries(source.율.단계).map(([name, value]) => [name, value.px])),
  };
  return `// Generated by node tools/care-memory-theme.cjs. Do not edit.\nexport const memoryTheme = ${JSON.stringify(theme, null, 2)};\n`;
}
if (require.main === module) {
  const result = build();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== result) throw new Error('Memory card Loom theme is stale');
  } else fs.writeFileSync(target, result);
}
module.exports = { build, target };
