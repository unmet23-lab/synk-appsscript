/* 기능체크 여러 회차를 하나로 — **나쁜 쪽이 이긴다.**
 * 한 회차라도 「깨짐」이면 깨진 것이다(다수결로 눌러 조용해지면 이 게이트가 막으려던 것이 통과한다).
 * 기능 이름이 손잡이다 — 회차마다 표현이 흔들리면 둘 다 남는데, 그건 조용한 누락보다 낫다. */
const 판정깊이 = { 정상: 0, 확인못함: 1, 의심: 2, 깨짐: 3 };
function 기능체크병합(모음) {
  const 산 = 모음.filter(Boolean);
  if (산.length <= 1) return 산[0] || null;
  const 표 = new Map();
  for (const r of 산) {
    for (const c of r.체크 || []) {
      const k = String(c.기능 || '');
      const 전 = 표.get(k);
      if (!전 || (판정깊이[c.판정] || 0) > (판정깊이[전.판정] || 0)) 표.set(k, c);
    }
  }
  const 학습 = [];
  const 본 = new Set();
  for (const r of 산) {
    for (const d of r.학습데이터 || []) {
      const k = JSON.stringify(d);
      if (본.has(k)) continue;
      본.add(k);
      학습.push(d);
    }
  }
  return { 체크: [...표.values()], 학습데이터: 학습 };
}

