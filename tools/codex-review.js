/* ── 진행 표식 — **조용한 죽음을 보이게 한다** (F333 · 2026-08-11 실측) ─────────────
 * 이 파일 머리말은 「통과와 미실행을 같은 모양으로 두지 않는다」를 종료코드로 지킨다. 그런데
 * 종료코드는 **이 프로세스가 살아서 반환할 때만** 존재한다. 밖에서 죽으면 catch 도 종료코드도
 * 없고, 남는 것은 이미 찍힌 머리말 몇 줄뿐이다 — 그게 F333 이 본 화면이다(헤더만·기록 0).
 *
 * 왜 그게 상수인가(추정이 아니라 산술):
 *   · ③ 최종검수 1회 = 1단계 분석 + 2단계 구조화 + 기능체크. 기본 회차 2 → 판단 패스 4번.
 *     max 추론 실측이 패스당 5~8분이므로 **정상 완주가 20~40분**이다(아래 「검수 중…」 줄의 근거).
 *   · 호출자(클로드 세션)의 포그라운드 셸 상한은 **10분**이고 기본은 2분이다.
 *   → 즉 ③ 은 포그라운드에서 **완주할 수 없다.** 가끔 죽는 게 아니라 언제나 죽는다.
 *     F333 의 4수는 전부 그 상한 안에서 죽었고, 죽음의 모양이 「헤더만」이라 도구 결함으로 읽혔다.
 *
 * 그래서 시작할 때 표식을 남기고 **정상 반환 시 지운다**(try/finally). 밖에서 죽으면 finally 가
 * 안 돌아 표식이 남고, 다음 실행이 그걸 읽어 「직전은 완주 못 했다」를 사람에게 말한다.
 * 남는 것이 증거고, 지워지는 것이 정상이다 — 새는 방향이 「통과」가 되지 않게 뒤집어 놓는다.
 *
 * ⚠ 표식은 **게이트가 아니다.** 검수기록과 섞지 않는다(섞으면 배포를 막는 장부에 「돌다 죽음」이
 *   행으로 들어가 판정이 갈린다). 세션별·프로젝트별로 갈라 남의 실행을 내 것으로 읽지 않는다.
 * 자리는 저장소 밖 임시 폴더의 **전용 디렉터리**다 — 미커밋 노이즈로 남의 작업본에 섞일 일이
 *   원천적으로 없다(F073).
 * ☠️ **`handoff-store.stateDir()` 안에 두면 안 된다**(2026-08-11 실측으로 잡았다 · 첫 판이 그랬다):
 *   그 폴더는 `handoff-store.sweep()` 이 청소하는데, 규칙이 `if (!j.at || 나이>TTL) unlink` 라
 *   **`at` 필드가 없는 내 표식은 나이와 무관하게 즉시 지워진다.** 세션이 여럿 도는 시간대엔
 *   남의 훅이 sweep 을 부르는 순간 사라져서, 실측에서 검수 시작 몇 초 뒤에 이미 없었다.
 *   증상은 「표식이 없다」 = 「완주했다」 — **증거를 지키려고 만든 장치가 정확히 반대로 샜다.**
 *   sweep 이 틀린 게 아니다(모르는 파일을 치우는 게 그 일이다) — **남의 청소 구역에 내 증거를
 *   둔 것이 틀렸다.** 그래서 폴더를 가른다. 이름 규칙만 그 모듈 것을 쓴다(같은 판정 두 벌 금지).
 * 회귀가 「stateDir 안이 아니다」를 못박는다 — 되돌리면 조용히 다시 샌다. */
function 진행파일() {
  if (process.env.SYNK_REVIEW_INFLIGHT) return process.env.SYNK_REVIEW_INFLIGHT;
  /* 지연 require — 이 모듈은 clasp-guard 훅도 부른다. 위(모델설정) 주석과 같은 축으로,
   * 훅 로드 경로에 새 require 사슬을 얹지 않는다(등록층에서 새면 방향은 언제나 「통과」다). */
  const store = require(path.join(ROOT, '.claude', 'hooks', 'lib', 'handoff-store.js'));
  const 세션 = store.safeId(process.env.CLAUDE_CODE_HOST_SESSION_ID || '');
  return path.join(os.tmpdir(), 'synk-검수진행', `${store.projectKey(ROOT)}-${세션}.json`);
}

function 진행시작(정보) {
  const p = 진행파일();
  /* 표식을 못 남기는 것이 검수를 막을 이유는 아니다 — 이건 증거지 게이트가 아니다.
   * 다만 조용히 넘기면 「표식이 없다 = 완주했다」가 거짓이 되므로 그 사실만 알린다. */
  try {
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, JSON.stringify({ ...정보, pid: process.pid, 시작: new Date().toISOString() }, null, 2));
  } catch (e) {
    console.error(`⚠ 진행 표식을 못 남겼다(${e.message}) — 이 실행이 밖에서 죽으면 그 사실이 안 남는다.`);
    return null;
  }
  return p;
}

function 진행종료() {
  try { fs.unlinkSync(진행파일()); } catch (_) { /* 없으면 그만 — 지우는 게 목적이다 */ }
}

function 낡은진행() {
  try { return JSON.parse(fs.readFileSync(진행파일(), 'utf8')); } catch (_) { return null; }
}

