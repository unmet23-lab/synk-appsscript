  // 제안 판정 — 클로드(또는 유호님)가 채택/기각을 장부에 남긴다
  if (argv.includes('--제안판정')) {
    const k = argv[argv.indexOf('--제안판정') + 1];
    const 채택 = argv.includes('--채택');
    const 기각 = argv.includes('--기각');
    const 사유 = argv.includes('--사유') ? argv[argv.indexOf('--사유') + 1] : '';
    if (!k || 채택 === 기각) {
      console.error('사용: --제안판정 <키> --채택 [--사유 "..."]  또는  --제안판정 <키> --기각 --사유 "왜"');
      return 2;
    }
    if (기각 && !사유) {
      console.error('기각에는 사유가 필요하다 — 없으면 다음 회차에 왜 안 하는지 설명할 수 없다.');
      return 2;
    }
    const 현황 = 제안현황();
    if (!현황.has(k)) {
      console.error(`모르는 제안 키 "${k}" — 오타로 허공에 판정을 남기면 진짜 제안이 미판정으로 남는다.`);
      return 2;
    }
    const p = 현황.get(k);
    /* 판정 행에도 **대상과 방향**을 박는다 — 지금까지 판정 행은 키만 들고 있어서, 그 판정이 어느
     * 변경의 제안에 대한 것이고 어느 방향 아래서 내려졌는지 **행 스스로 말하지 못했다.**
     * 대상·변경은 원 제안 행에서 그대로 **복사**한다(새로 계산하면 같은 판정을 두 곳에서 정하게 된다 —
     * 판정 시점의 작업본은 제안 시점과 이미 다르므로 다시 재면 딴 변경을 가리킨다). */
    append(제안경로, {
      종류: '판정', 시각: new Date().toISOString(),
      대상: p.대상 || null, 방향: 방향지문(), 변경: p.변경 || null,
      키: k, 상태: 채택 ? '채택' : '기각', 사유,
    });
    console.log(`${채택 ? '채택' : '기각'}: ${p.제목}${사유 ? ' — ' + 사유 : ''}`);
    console.log(채택
      ? '구현한 뒤 최종 검수(node tools/codex-review.js)를 돌린다 — 기능체크가 구현 여부까지 본다.'
      : '이 제안은 다음 선파악 프롬프트에 「기각됨」으로 실려 다시 올라오지 않는다.');
    return 0;
  }

  // 기각 등록
  if (argv.includes('--기각')) {
    const k = argv[argv.indexOf('--기각') + 1];
    const 사유 = argv.includes('--사유') ? argv[argv.indexOf('--사유') + 1] : '';
    if (!k || !사유) {
      console.error('사용: --기각 <키> --사유 "왜 기각했는지"  (사유 없는 기각은 받지 않는다 — 다음 회차에 왜 무시하는지 설명할 수 없다)');
      return 2;
    }
    const 원본 = jsonl(기록경로).flatMap((r) => r.지적 || []).find((f) => f.키 === k);
    append(기각경로, { 시각: new Date().toISOString(), 키: k, 파일: 원본 ? 원본.파일 : '(모름)', 제목: 원본 ? 원본.제목 : '(모름)', 사유 });
    console.log(`기각 등록: ${k} — ${사유}`);
    console.log('이 지적은 다음 검수 프롬프트에 「기각됨」으로 실려 다시 올라오지 않는다.');
    return 0;
  }

  // 게이트 조회
  if (argv.includes('--확인')) {
    let 최악 = 0;
    for (const p of 점검.claspProjects()) {
      const r = 게이트판정(p, ROOT);
      console.log(r.lines.join('\n'));
      if (r.level === 'block') 최악 = Math.max(최악, 1);
    }
    return 최악;
  }

  const 대상 = 대상결정(argv);
  if (!대상.파일들.length) {
    console.log('검수할 변경이 없다 — 대상 diff 가 비었다.');
    return 0;
  }
  const 기각들 = jsonl(기각경로);
  const 범위들 = 범위(대상.파일들);

  // 선택지는 둘뿐이다(sol·luna · 둘 다 max). `--효력` 은 1회성 조정 — 급하면 `--효력 high`.
  let 회차;
  try {
    모델설정.분석 = 정책.분석설정(argv);
    회차 = 정책.회차설정(argv);     // 기본 2 — 근거는 tools/모델정책.js
    모델플래그(모델설정.분석);      // 조합 검사를 **먼저** 한다 — 몇 분 기다린 뒤 오타를 알 이유가 없다
    모델플래그(모델설정.구조화);    // 2단계도 지금 — 1단계가 끝난 뒤 죽으면 그 몇 분이 통째로 버려진다
  } catch (e) {
    console.error('🔴 확인 불가 — 검수가 **안 돌았다**(통과가 아니다): ' + e.message);
    return 2;
  }

  /* 900 이 아닌 이유(F249 · 2026-08-08 실측): max 추론 검수가 900 초를 넘겼고, 타임아웃 없이
   * 직접 돌리니 15분을 넘겨 **완주해 P1 1건·P2 2건을 냈다** — 안 도는 게 아니라 못 기다린 것이었다.
   * 심문(위)이 1800 인데 더 무거운 검수가 900 이던 역전을 없앤다. */
  const 초 = argv.includes('--timeout') ? Number(argv[argv.indexOf('--timeout') + 1]) : 1800;

  // ① 설계 선파악 모드 — 버그 검수 대신 기능지도+업그레이드 제안만 내고 끝낸다
  if (argv.includes('--제안')) {
    console.log(`대상: ${대상.종류} ${대상.값} · 파일 ${대상.파일들.length}개`);
    try {
      return 제안실행(argv, 대상, 초 * 1000);
    } catch (e) {
      if (e.확인불가) {
        console.error('🔴 확인 불가 — 선파악이 **안 돌았다**: ' + e.message);
        console.error('   제안 단계는 게이트와 무관하다 — 최종 검수(버그+기능체크)로 그냥 진행해도 된다.');
        return 2;
      }
      throw e;
    }
  }

  console.log(`대상: ${대상.종류} ${대상.값} · 파일 ${대상.파일들.length}개`);
  console.log(`검수 범위(clasp 프로젝트): ${범위들.length ? 범위들.join(', ') : '없음 — 배포 파일이 아닌 변경'}`);

  /* 실행 전 정지 — 태우고 나서 「범위 밖이었다」를 알게 되는 자리를 없앤다(F314 · 위 설계 주석). */
  if (!argv.includes(범위밖탈출)) {
    const 정지 = 범위밖정지(대상, 범위들);
    if (정지) { console.error('\n' + 정지.join('\n')); return 2; }
  }
  if (기각들.length) console.log(`기각 이력 ${기각들.length}건으로 재발 지적을 걸러낸다.`);

  진행걸기(argv, { 단계: '③최종검수', 대상: { 종류: 대상.종류, 값: 대상.값 }, 회차, 인자: argv });

  console.log(`모델: 분석=${모델설정.분석.model}/${모델설정.분석.effort}(${모델설정.분석.이름}) · 구조화=${모델설정.구조화.model}/${모델설정.구조화.effort} · 판단 패스 ${회차}회`);
  console.log(`codex 검수 중… (읽기 전용 샌드박스 · 2단계 · ${모델설정.분석.effort} 추론 — xhigh 실측이 5~8분이었다` +
    (회차 > 1 ? ` · ${회차}회라 그 배로 걸린다` : '') + ')');
  console.log(소요안내(argv, 회차));

  let 결과;
  try {
    결과 = codex실행(대상, 초 * 1000, 회차);
  } catch (e) {
    if (e.확인불가) {
      console.error('🔴 확인 불가 — 검수가 **안 돌았다**(통과가 아니다): ' + e.message);
      // 타임아웃엔 로그인을 의심시키지 않는다 — F249 1회차가 이 힌트를 따라가 시간을 버렸다.
      if (!e.타임아웃) console.error('   codex 로그인 상태는 `codex login status` 로 본다.');
      return 2;
    }
    throw e;
  }

  /* ③-2 기능 전수 체크 — 버그 사냥(위)과 별개 패스로, 바뀐 기능 하나하나가 실제로 도는지 본다.
   * 유호님 설계(2026-08-05): 「검수자가 최종적으로 꼼꼼히 버그 체크하고 **업데이트되는 기능
   * 세세히 전부 체크**」. 지적 0건과 「기능 X 는 본 적도 없음」이 같은 모양이면 안 되는 자리다.
   * 깨짐은 P1 지적으로 변환돼 같은 게이트를 탄다. `--버그만` 은 유호님 「빠르게」 모드용. */
  /* 변경지문(change_id) — 기능체크에 **실제로 실릴 그 바이트**로 만든다. 그래야 선파악이 같은
   * 손잡이로 남긴 기능지도를 되찾을 수 있다. `--버그만` 이어도 장부엔 박는다(행마다 붙어야 계보다). */
  const diff본문 = 디프수집(대상);
  const 변경fp = 변경지문(diff본문);

  let 기체 = null;
  if (!argv.includes('--버그만')) {
    const 채택제안들 = 채택제안줄들();
    console.log(`기능 전수 체크 중… (같은 모델 · 별도 패스 · ${회차}회)`);
    try {
      const 프롬프트 = 기능체크프롬프트(diff본문, 채택제안들, 방향텍스트());
      const 모음 = [];
      /* 상한을 안 씌운다 — 여기 있던 `Math.min(초 * 1000, 900000)` 은 **처방이 안 닿는 자리**였다.
       * 2026-08-05 도입 당시엔 `초` 기본이 900 이라 무해한 no-op 이었는데, 08-08 에 F249 가 기본을
       * 1800 으로 올리면서 **그날부터 조용히 구속조건이 됐다** — 옆자리만 올리고 이 clamp 를 안 봤다.
       * 증상: 기능체크가 900 초에 끊기며 「`--timeout 1800` 로 늘려 다시 돌린다」를 처방하는데, 그
       * 플래그가 이 자리엔 원리상 안 닿아 **몇 번을 따라도 같은 자리에서 같은 초로 끊긴다**(F103 —
       * 따를 수 없는 처방은 우회를 정상 통로로 만든다 · 08-10 실측 2회, 900 초 ×2·×1).
       * 상한이 필요하면 호출자가 `--timeout` 으로 명시한다 — 여기서 몰래 깎지 않는다. */
      for (let i = 1; i <= 회차; i++) {
        모음.push(스키마실행(프롬프트, 기능체크스키마경로, 초 * 1000,
          `codex 기능체크${회차 > 1 ? ` ${i}/${회차}회` : ''}(${모델설정.분석.model}/${모델설정.분석.effort})`));
      }
      기체 = 기능체크병합(모음);
    } catch (e) {
      if (e.확인불가) {
        console.error('🔴 확인 불가 — 기능체크가 **안 돌았다**(통과가 아니다): ' + e.message);
        return 2;
      }
      throw e;
    }
  } else {
    console.log('(--버그만: 기능 전수 체크 생략 — 유호님 「빠르게」 모드)');
  }

  const 지적 = [...(결과.지적 || []), ...기능체크지적들(기체 && 기체.체크)].map((f) => ({ ...f, 키: 키(f) }));
