/* 표식을 «달았나» / «논했나» — `놓은줄()`(🎫) 과 `대기행()`(⏳·⏸) 의 **한 벌** 좁힘 (F612 · F629).
 *
 * 이 검사가 지키는 것: **끝난 줄이 「남의 대기를 인용했다」는 이유로 영원히 «활성»이 되지 않게,
 * 그리고 그걸 고치다 «진짜로 기다리는 줄»을 완료로 접지 않게.** 방향이 양쪽 다 나쁘다:
 *   · 좁게 틀리면 거짓 활성 — 끝난 줄이 자리를 문다(시끄럽다 · `보드수거` 가 원리상 못 치운다)
 *   · 넓게 틀리면 거짓 완료 — 기다리는 트랙이 보드에도 인계문에도 없어진다(조용하다 · F554)
 * 그래서 **정상 용례를 지키는 검사가 좁힘 검사보다 많다.** 그게 이 파일의 무게중심이다.
 *
 * 🔴 사연 — F612 가 🎫 에서 이 병을 닫을 때 **20줄 옆의 쌍둥이가 안 따라왔다.** 나는 F628 의
 *   분모를 `활성행()` 으로 세다 낚였다: 「30커밋 뒤면 놓친 활성 4줄」의 절반이 `✅**종결**` 로
 *   시작하는 줄이었고, 상태 칸 끝의 「⏸F612 안 집음」이 그것을 활성으로 뒤집고 있었다.
 *   즉 **측정층이 조용히 부풀어** 내 첫 수(176)가 통째로 틀렸다.
 */
const { test } = require('node:test');
const assert = require('node:assert');
const path = require('node:path');
const fs = require('node:fs');

const ROOT = path.resolve(__dirname, '..');
const 보드 = require(path.join(ROOT, 'tools', 'lib', '보드.js'));

const 줄 = (상태) => `| 2026-08-18 | **어떤 트랙** | \`tools/x.js\` | ${상태} |`;

// ───────────────────────────────── ① 정상 용례를 **안 죽인다** (넓게 틀리면 조용하다)

test('🔴 [629] 자기 대기는 그대로 대기다 — 실측 231 스팬 중 169가 이 꼴이다', () => {
  for (const 상태 of [
    '✅종결 — ⏳유호 = 그 칸을 추가할지',
    '✅**종결** · ⏳유호=2단계 진입(HF계정/Blender)',
    '1단계 착지 · ⏳ 유호 픽 대기',
    '⏸ **머지 대기** `96987881` (PR #7)',
    '✅착지 · ⏳CI 모사 미완',
    '✅종결 · ⏸잔여=리셋 후 재던지기',
    '✅종결 · ⏸이유=선행이 안 섰다',            // 「이」로 시작하는 낱말 — 조사가 아니다
  ]) {
    assert.strictEqual(보드.대기행(줄(상태)), true, `자기 대기를 죽였다 — 이 트랙은 보드에서 사라진다(F554): ${상태}`);
    assert.strictEqual(보드.활성행(줄(상태)), true, `완료 어휘가 대기를 덮었다: ${상태}`);
  }
});

test('🔴 [612] 🎫 정상 용례도 그대로다 — 조사 규칙을 더하며 실측 74 스팬 중 0건이 걸렸다', () => {
  for (const 상태 of ['🎫다음=이어받아라', '🎫 잔여=8/18 리셋 후', '🎫이어받아도 된다', '🎫 남은 건 없음']) {
    assert.strictEqual(보드.놓은줄(줄(상태)), true, `놓은 자리를 못 읽었다 — 그 줄은 영원히 잠긴다: ${상태}`);
  }
});

// ───────────────────────────────── ② «논한» 표식은 안 센다 (좁힘 — 실측한 세 갈래만)

test('🔑 [629] 셈·보고문의 대기 기호는 대기가 아니다 — 기호 **뒤**가 수인 꼴', () => {
  for (const 상태 of [
    '✅종결 — 막힌 것 12건 = ⏳ 3 · ⏸ 1',
    '✅착지 — 파일에 ⏳ 2줄인데 `--check` 는 0건',
  ]) {
    assert.strictEqual(보드.대기행(줄(상태)), false, `보고 숫자가 표식이 됐다 — 끝난 줄이 자리를 문다: ${상태}`);
  }
});

test('🔴 [629] **안 닫은 갈래를 여기 못박는다** — 수가 기호 «앞»에 오는 셈은 여전히 대기로 샌다', () => {
  /* 「활성 15 중 5줄이 ⏳·⏸」 — 사람 눈엔 명백한 보고문인데 기호 뒤에는 수가 없다.
   * 잡으려면 「앞에 수가 있으면 셈」이라는 규칙이 필요하고, 그건 «`F115` 는 ⏳ 연 채» 같은
   * 진짜 대기까지 죽인다(넓게 틀리는 쪽 = 조용한 쪽 · F554). 그래서 **안 닫았다.**
   * 🔑 이 검사는 «지금 못 하는 것»을 고정한다 — 나중에 닫으면 여기가 빨개져서 함께 고쳐진다.
   *   침묵으로 남기면 다음 사람이 이 좁힘을 «전부 잡는 것»으로 읽는다. */
  assert.strictEqual(보드.대기행(줄('✅종결 — 활성 15 중 5줄이 ⏳·⏸(아무도 못 닫는다)')), true,
    '이 갈래를 닫았다면 위 머리말의 「못 가르는 갈래」와 장부 F629 를 같은 커밋에서 갱신한다');
  /* 같은 이유로 **혼합 보고문**도 샌다: 「(⏳유호 11 · ⏸시점 1)」 은 통째로 셈인데 첫 기호 뒤가
   * `유호` 라 살아남는다. 「살아 있는 표식 하나면 대기」라는 규칙(아래 ③)과 정면으로 맞물린 자리라,
   * 여기만 예외로 두면 그 규칙이 무너진다 — 그래서 **역시 안 닫았다.** */
  assert.strictEqual(보드.대기행(줄('✅종결 — (⏳유호 11 · ⏸시점 1)')), true,
    '혼합 보고문 갈래 — 닫으려면 ③의 「하나면 대기」 규칙부터 다시 설계한다');
});

test('🔑 [629] 기호를 **명사로 부르면** 대기가 아니다 — 「⏸과 갈린 건」', () => {
  for (const 상태 of ['✅착지 — `f6457d2a` ⏸과 갈린 건 사실✗ 분모○', '✅종결 — ⏳는 유호 대기를 뜻한다']) {
    assert.strictEqual(보드.대기행(줄(상태)), false, `글자를 논한 것을 표식으로 읽었다: ${상태}`);
  }
});

test('🔑 [629] 백틱에 싸인 기호는 이름이다 — `` `⏳` `` (지금 실측 0건 · 예방 규칙임을 밝힌다)', () => {
  assert.strictEqual(보드.대기행(줄('✅종결 — `⏳` 는 유호 대기 표식이다')), false);
});

test('🔑 [612·629] 좁힘 판정이 **한 벌**이다 — 두 표식이 같은 규칙을 지난다', () => {
  /* 갈라지면 그날 한쪽만 고쳐진다 — 그게 F629 다(F612 가 🎫 를 닫을 때 쌍둥이가 안 따라왔다). */
  assert.strictEqual(보드.놓은줄(줄('✅종결 — 놓임 🎫 6건')), false, '🎫 쪽 셈 규칙이 죽었다');
  assert.strictEqual(보드.대기행(줄('✅종결 — 대기 ⏳ 6건')), false, '⏳ 쪽 셈 규칙이 안 산다');
  const 코드 = fs.readFileSync(path.join(ROOT, 'tools', 'lib', '보드.js'), 'utf8');
  /* 화살표 함수라 «정의»에는 `논해진표식(` 꼴이 안 나온다 — 세는 것은 **호출 두 곳**이다
   *   (`놓은줄` · `대기행`). 한쪽이 자기 사본으로 돌아가면 이 수가 1로 떨어진다. */
  const 부름 = (코드.match(/논해진표식\(/g) || []).length;
  assert.ok(부름 >= 2, `공용 판정을 두 판정이 다 안 부른다(호출 2 이상이어야 한다 · 실제 ${부름})`);
  assert.ok(!/놓음셈RE/.test(코드), '옛 사본이 남아 있다 — 안 도는 규칙을 다음 사람은 «도는 것»으로 읽는다');
});

// ───────────────────────────────── ③ 살아 있는 표식 하나면 대기다 (부분 좁힘이 전체를 끄지 않는다)

test('🔴 [629] 논한 기호와 진짜 기호가 **한 줄에 같이** 있으면 대기다 — 앞의 것이 뒤를 끄면 안 된다', () => {
  const 상태 = '✅종결 — 막힌 것 ⏳ 3건 · 그런데 이 트랙은 ⏳유호 답을 기다린다';
  assert.strictEqual(보드.대기행(줄(상태)), true, '셈이 먼저 나오면 뒤의 진짜 대기가 통째로 꺼졌다 — 새는 방향이 「조용함」이다');
});

test('🔴 [629] 상태 칸 **밖**의 기호는 여전히 안 센다 — 트랙 칸의 ⏳ 는 딴 줄을 가리키는 인용이다', () => {
  assert.strictEqual(보드.대기행(`| 2026-08-18 | **⏳ 가 붙은 남의 트랙을 조사** | \`x.js\` | ✅종결 |`), false);
});

// ───────────────────────────────── ④ 실저장소 — 뒤집힌 줄이 실제로 바로 섰나 (판정은 위 픽스처가 진다)

test('🔴 [629] 실저장소 — 이 좁힘으로 «활성 → 완료» 가 되는 줄은 **전부 첫 구절이 완료 어휘**다', () => {
  /* 이것이 F554 위험의 과녁이다: 진짜로 기다리는 줄(첫 구절이 «작업중»·«착수» 류)이 하나라도
   * 여기 끼면 그 트랙은 `보드수거` 에 실려 보드에서 사라진다 — 조용한 방향이라 아무도 못 본다.
   * ⚠ 값(몇 줄인가)은 단정하지 않는다 — 보드는 매일 바뀐다. **성질**만 못박는다. */
  const 파일들 = fs.readdirSync(path.join(ROOT, 'docs', '_ops', '보드'))
    .filter((f) => f.endsWith('.md')).map((f) => path.join(ROOT, 'docs', '_ops', '보드', f));
  const 아카이브 = path.join(ROOT, 'docs', '세션보드_아카이브.md');
  if (fs.existsSync(아카이브)) 파일들.push(아카이브);

  let 표줄수 = 0;
  const 어긴것 = [];
  for (const f of 파일들) {
    for (const line of fs.readFileSync(f, 'utf8').split(/\r?\n/)) {
      if (!보드.표줄(line)) continue;
      표줄수 += 1;
      if (보드.활성행(line)) continue;                       // 지금 완료로 서는 줄만 본다
      if (!/[⏳⏸]/.test(line)) continue;                      // 대기 기호가 아예 없으면 이 좁힘과 무관
      const 첫구절 = 보드.상태첫구절(line);
      if (!/(?<![미안못])(완료|종결|라이브|착지)/.test(첫구절)) {
        어긴것.push(`${path.basename(f)} :: ${첫구절.slice(0, 40)}`);
      }
    }
  }
  assert.ok(표줄수 > 100, `분모가 안 섰다 — 표줄 ${표줄수}건이면 이 검사는 아무것도 안 쟀다(F207)`);
  assert.deepStrictEqual(어긴것, [],
    '🔴 첫 구절이 완료 어휘가 **아닌** 줄이 대기 기호를 갖고도 완료로 섰다 — 기다리는 트랙이 조용히 사라지는 자리다(F554)');
});
