/* ── 상주 비용 «래칫» — 카드는 줄어들기만 한다 (2026-08-19 · 유호 확정 「① 카드 다이어트」) ──
 * 바로 위 검사(정본의 25%)는 **전문 통째 싣기**만 막는다 — 전문이 자라면 상한도 같이 자라서,
 * 다이어트해 놓은 자리가 조용히 되돌아가도 초록이다(실측: 다이어트 «전» 7,384 B 도 그 검사를 통과했다).
 * 그래서 정본과 무관한 **절대 상한**을 따로 건다.
 *
 * 대가(CLAUDE.md — 새 장치엔 함께 적는다):
 *  · 틀릴 때의 모습 = 정본에 층이 하나 늘어 카드가 정당하게 커질 때도 빨개진다. 그때는 요지 함수를
 *    손보거나(먼저) 이 숫자를 **재서** 올린다 — 올리는 순간 그 커밋이 「상주 비용을 늘렸다」는 기록이 된다.
 *  · 닫은 것 = 「얼마나 실을까」가 아무 데도 안 적혀 있어 자리마다 제각각 자라던 것을 숫자 하나로 묶었다.
 */
test('🔑 상주 비용 래칫 — 카드 출력은 «줄어들기만» 한다', (t) => {
  if (!fs.existsSync(정본)) return t.skip('docs/SYNK_철학.md 없음 — 이 환경에선 못 잰다');
  const 상한 = 1800;   // 2026-08-19 실측 1,657자(3,669 B) · 다이어트 전 3,247자(7,384 B)
  const r = 훅띄우기(HOOK, { encoding: 'utf8' });
  assert.ok(r.stdout.length > 0, '카드가 아무것도 안 냈다 — 0자는 통과가 아니라 미실행이다(F207)');
  assert.ok(r.stdout.length <= 상한,
    `카드가 ${r.stdout.length}자다 — 상한 ${상한}자를 넘었다. 매 세션 상주라 남은 턴 수만큼 곱해진다.\n`
    + '  먼저 볼 곳: philosophy-card.js 의 요지 함수(층별요지·줄별요지·문장상한) — 자리 하나가 통째로 실리고 있나.\n'
    + '  정본이 정당하게 자란 것이면 이 숫자를 **재서** 올린다(손으로 짐작해 올리지 않는다).');
  /* 내려간 것을 안 반영하면 상한이 곧 낡는다 — 그때는 이 단언이 «내려 적으라»고 말한다. */
  assert.ok(r.stdout.length >= 상한 - 500,
    `카드가 ${r.stdout.length}자로 상한 ${상한}보다 많이 줄었다 — 래칫을 내려 적어라`
    + '(안 내리면 다음 사람이 「아직 그만큼 여유가 있다」로 읽는다).');
});
