/* ── ①-c 「시키면서 안 싣는」 카드 — v1.4 에서 실제로 난 세 번째 죽는 방식 (2026-08-12) ────────
 * ②엔진 조항이 「㉠㉡㉢ 중 어디에 보태는지 대라」로 예리해지는 순간, 카드는 **자기가 시킨 것을
 * 안 싣는 상태**가 됐다 — ㉠㉡㉢ 은 다음 문단이라 뽑기() 의 빈 줄에서 잘렸다. 앵커는 성했으니
 * 실패 처리도 안 걸린다. 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103).
 * 그리고 「하지 않는 것 넷」은 인용 블록이라 `절머리` 에 걸려 **첫 줄만** 실렸다 — 08-12 에 고친
 * 「한 줄만 집던 병」이 다른 문으로 재발한 모양이다. 아래 픽스처가 그 두 문을 잠근다. */

const 인용_정본 = [
  '**한 문장: 가치.**',
  '',
  '> **하지 않는 것 넷.** 머리말.',
  '> **㉠ 첫째** — 설명 하나.',
  '> **㉡ 둘째** — 설명 둘.',
  '> **㉣ 넷째** — 설명 넷.',
  '',
  '**1. 다음 절이다.**',
  '',
].join('\n');

test('픽스처 — 인용 블록은 첫 줄이 아니라 «전부» 실린다(㉡㉢㉣ 를 조용히 버리지 않는다)', () => {
  const r = 인용뽑기(인용_정본, /^>\s*\*\*하지 않는 것 넷/);
  assert.ok(r, '인용 블록을 아예 못 찾았다');
  for (const 조각 of ['㉠ 첫째', '㉡ 둘째', '㉣ 넷째']) {
    assert.ok(r.includes(조각), `인용 블록의 "${조각}" 가 사라졌다 — 금지 조항이 반쪽이면 안 막는다`);
  }
  assert.ok(!r.includes('다음 절이다'), '인용이 끝난 뒤 다음 절까지 먹었다');
  assert.ok(r.includes('\n'), '넷이 한 줄로 뭉쳤다 — 읽는 쪽이 셋째·넷째를 흘린다');
});

test('픽스처 — 인용 앵커가 낡으면 null(조용한 빈 금지 목록 금지)', () => {
  assert.strictEqual(인용뽑기(인용_정본, /^>\s*\*\*하지 않는 것 다섯/), null);
});

