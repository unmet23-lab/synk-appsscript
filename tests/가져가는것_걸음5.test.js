'use strict';
/* 가져가는 것 — 걸음 5 회귀 (2026-09-03) · 설계 = docs/가져가는것_설계_v1.md §5-a ① · §5-b · §5-b-2 · §12-b
 *
 * 무엇을 지키나 — **졸업 날 손에 쥐는 책이 「자기만의 이야기」인가**:
 *   A. 채움 사다리 — 재료가 거의 없는 아이의 책도 **같은 두께**다.
 *      🔴 이게 이 걸음의 급소다: 그냥 두면 결석이 잦은 아이의 책이 눈에 보이게 얇아져,
 *      화면에서 등수를 안 띄우기로 한 규약이 **종이에서 되살아난다**.
 *   B. 반 공유 사진은 스프레드당 **최대 한 장** — 열여섯 명이 같은 책을 받으면 반 앨범이지 자기 이야기가 아니다.
 *   C. 닫는 쪽의 마지막 줄은 **비어 있다** — 다 채워 주지 않는 것이 설계다(§5-b).
 *   D. 말은 `contents_증서.js` 에서만 온다 · mn 은 빈칸 · 인쇄 금지 계약 0건.
 *   E. 통로를 나눠 쓴다 — 색·폰트·크롬·금칙 목록은 새로 안 짓는다(§12-a 「0벌 신설」).
 *
 * ⚠ 실학생 0명이라 재는 것은 픽스처와 순수 함수다. 실데이터 왕복은 **안 재봤다**.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const 기록 = require(path.join(ROOT, 'tools', '기록장조판.js'));
const 증서 = require(path.join(ROOT, 'tools', '증서조판.js'));
const 읽기 = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/\r\n/g, '\n');

const 뱅크 = 기록.문안();
const 쪽수세기 = (html) => (html.match(/<div class="쪽[ "]/g) || []).length;
const 굽기 = (모양, 시즌수) => {
  const { 쪽들, 장부 } = 기록.기록장(뱅크, 기록.픽스처(모양, 시즌수));
  return { html: 기록.지면('시험', 쪽들, 장부), 장부 };
};

/* ── A. 채움 사다리 ─────────────────────────────────────────────────────────── */

test('Ⓐ 재료가 거의 없는 아이의 책도 같은 두께다 — 결석이 두께로 보이지 않는다', () => {
  const 많음 = 쪽수세기(굽기('평시', 6).html);
  const 적음 = 쪽수세기(굽기('최소', 6).html);
  assert.equal(적음, 많음,
    `재료가 적은 아이의 책이 ${적음}쪽, 많은 아이가 ${많음}쪽 — 화면에서 안 띄우기로 한 비교가 종이에서 되살아났다`);
  assert.equal(많음, 2 + 6 * 2 + 5, '쪽 셈이 설계와 다르다(표지 1 + 여는 쪽 1 + 시즌×2 + 마무리 5)');
});

test('Ⓐ 재회전한 학생은 시즌 수만큼 늘어난다 — 6시즌은 기준선이지 고정값이 아니다', () => {
  assert.equal(쪽수세기(굽기('평시', 8).html), 2 + 8 * 2 + 5);
  assert.equal(쪽수세기(굽기('평시', 6).html) + 4, 쪽수세기(굽기('평시', 8).html),
    '시즌 두 개가 늘면 정확히 네 쪽이 는다(스프레드 하나 = 2쪽)');
});

test('Ⓐ 순간이 0장인 시즌도 스프레드가 안 빈다 — 고유 재료가 그 자리를 메운다', () => {
  const 칸 = 기록.시즌칸들({
    목표: '한국 친구에게 우리 집 이야기 들려주기',
    회고: '처음엔 말이 안 나왔어요.',
    한일: ['자기소개 영상 만들기'],
    고쳐쓴문장: '「나는 밥 먹었다」 → 「친구들과 같이 밥을 먹었어요」',
    카드: '오늘의 한 문장',
    순간: []
  });
  assert.equal(칸.length, 4, '순간 0장인 시즌의 스프레드가 비었다');
  assert.equal(칸.some((c) => c.갈래 === '순간'), false, '없는 순간을 지어냈다');
  // 다섯 갈래는 전부 «결석과 무관하게 그 아이만의 것»이어야 한다
  칸.forEach((c) => assert.ok(['목표', '회고', '한일', '고쳐쓴문장', '카드'].includes(c.갈래)));
});

test('Ⓐ 재료가 통째로 0인 시즌은 «지어내지 않고» 장부에 올린다', () => {
  assert.deepEqual(기록.시즌칸들({}), [], '빈 시즌에서 뭔가를 만들어 냈다');
  const { 장부 } = (() => {
    const 자료 = 기록.픽스처('평시', 1);
    자료.시즌 = [{}];
    return 기록.기록장(뱅크, 자료);
  })();
  assert.ok(장부.some((b) => b.includes('시즌') && b.includes('재료가 하나도 없다')),
    '빈 시즌이 장부에 안 올랐다 — 조용히 빈 쪽이 나가면 아무도 못 본다');
});

/* ── B. 반 공유 사진 ────────────────────────────────────────────────────────── */

test('Ⓑ 반 공유 사진은 스프레드당 한 장 — 열여섯 명이 같은 책을 받지 않는다', () => {
  const 칸 = 기록.시즌칸들({
    순간: [
      { 날짜: '6월 1일', 한줄: '반 사진 하나', 반공유: true },
      { 날짜: '6월 2일', 한줄: '반 사진 둘', 반공유: true },
      { 날짜: '6월 3일', 한줄: '반 사진 셋', 반공유: true }
    ],
    목표: '한국 친구에게 이야기 들려주기', 회고: '좋았어요', 한일: ['발표하기']
  });
  const 공유수 = 칸.filter((c) => c.갈래 === '순간' && c.값.반공유).length;
  assert.equal(공유수, 1, `반 공유 사진이 ${공유수}장 실렸다 — 자기만의 이야기가 반 앨범이 된다`);
  assert.ok(칸.length > 1, '남은 자리가 그 아이 고유 재료로 안 메워졌다');
});

test('Ⓑ 그 아이만 나온 순간은 먼저 들어간다 — 그게 「자기만의 이야기」다', () => {
  const 칸 = 기록.시즌칸들({
    순간: [
      { 날짜: '6월 1일', 한줄: '반 사진', 반공유: true },
      { 날짜: '6월 2일', 한줄: '내 사진' }
    ]
  });
  assert.equal(칸[0].값.한줄, '내 사진', '반 공유 사진이 고유 순간보다 앞에 왔다');
});

/* ── C. 닫는 쪽 ─────────────────────────────────────────────────────────────── */

test('Ⓒ 닫는 쪽의 마지막 줄은 비어 있다 — 조판기가 채우면 그 자리가 사라진다', () => {
  const { html } = 굽기('평시', 6);
  assert.ok(/class="빈줄자리"/.test(html), '학생이 쓸 빈 줄 자리가 없다');
  const i = html.indexOf('class="빈줄자리"');
  const 토막 = html.slice(i, i + 500);
  assert.equal((토막.match(/class="선"/g) || []).length, 2, '빈 줄이 두 줄이 아니다');
  assert.ok(/한 줄을 더 적어 보세요/.test(토막), '무엇을 하라는 말이 없다 — 빈 줄만 있으면 그냥 여백이다');
});

/* ── D. 말과 계약 ───────────────────────────────────────────────────────────── */

test('Ⓓ 말은 contents_증서.js 에서만 온다 — 조판기에 문장 0 · mn 은 빈칸', () => {
  const 뱅크소스 = 읽기('contents_증서.js');
  assert.ok(/const RECORD_BOOK_SAY = \{/.test(뱅크소스), '기록장 말 뱅크가 없다');
  const say = new Function(`${뱅크소스}\nreturn RECORD_BOOK_SAY;`)();
  assert.equal(say.닫는쪽.mn.빈줄, '', '몽골어를 지어냈다 — 검수자 0명이면 빈칸이 정직값이다');
  assert.ok(say.뒤표지.한줄.includes('졸업한 뒤에도'), '선배 카드 안내 한 줄이 없다(§5-b 뒤표지 안쪽)');

  /* 🔑 자를 «뱅크에서» 파생한다 — 손으로 낱말을 고르면 그 목록이 곧 또 하나의 사본이고,
   *   실제로 첫 판은 장부 이름(내가 읽는 것)과 픽스처(학생이 «쓴» 답의 견본)까지 잡아 거짓 적색을 냈다.
   *   묻는 것은 하나다: **뱅크가 쥔 문장이 조판기 안에도 박혀 있나.** */
  const 도구 = 읽기('tools/기록장조판.js');
  const 뱅크문장 = [];
  (function 훑기(o) {
    Object.values(o).forEach((v) => {
      if (typeof v === 'string' && v.length >= 8) 뱅크문장.push(v);
      else if (v && typeof v === 'object') 훑기(v);
    });
  })(say);
  const 박힌것 = 뱅크문장.filter((s) => 도구.includes(s));
  assert.deepEqual(박힌것, [],
    `조판기 안에 뱅크의 문장이 박혀 있다(${박힌것.length}개) — 말은 뱅크가 쥔다`);
});

test('Ⓓ 인쇄 금지 계약 0건 — 그리고 표식이 있어 발표물린트도 같은 자를 댈 수 있다', () => {
  const { html } = 굽기('평시', 6);
  assert.deepEqual(증서.금칙검사(html), [], '학생 손에 가는 책에 금칙 낱말이 있다');
  assert.ok(html.includes('data-synk-print="학생"'), '학생 인쇄물 표식이 없다 — 린트가 이 책을 분모 밖으로 본다');
});

test('Ⓓ 도장 쪽은 «개수»를 적지 않는다 — 세면 그게 비교가 된다', () => {
  const { html } = 굽기('평시', 6);
  const i = html.indexOf('함께한 날들');
  const 토막 = html.slice(i, html.indexOf('</div>', html.indexOf('도장판', i)) + 6);
  assert.equal(/\d+\s*일|\d+\s*번|\d+\s*회/.test(토막.replace(/\d{4}년 \d+월/g, '')), false,
    '출석을 숫자로 적었다 — 두 책을 나란히 놓는 순간 비교가 된다');
});

/* ── E. 통로 ────────────────────────────────────────────────────────────────── */

test('Ⓔ 통로를 나눠 쓴다 — 크롬 찾기·폰트 임베드·금칙 목록을 새로 안 짓는다(§12-a)', () => {
  const 도구 = 읽기('tools/기록장조판.js');
  assert.ok(/require\('\.\/증서조판\.js'\)/.test(도구), '실측·굽기 통로를 나눠 쓰지 않는다');
  assert.equal(/findChrome|execFileSync/.test(도구), false, '크롬 찾기를 다시 지었다 — 한 벌만 산다');
  assert.equal(/브랜드폰트_임베드/.test(도구), false, '폰트 임베드 통로를 다시 지었다');
  assert.ok(/require\('\.\/발표물린트\.js'\)/.test(도구), '학생 인쇄물 표식을 정본에서 안 받는다');
  // 색은 토큰에서만 — 손 hex 가 하나라도 있으면 토큰이 바뀌어도 종이가 안 따라온다
  const 손hex = (도구.match(/#[0-9A-Fa-f]{6}/g) || []);
  assert.deepEqual(손hex, [], `조판기에 손 hex 가 ${손hex.length}개 있다: ${손hex.join(' ')}`);
});
