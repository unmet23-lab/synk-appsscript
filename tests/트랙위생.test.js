'use strict';
/* 트랙 위생 자 회귀 — 2026-09-06 (유호 확정 「a로 가자, 새 자 세우고 다시 돌려줘」)
 *
 * 무엇을 지키나: **「일감이 많다」와 「한 불릿이 부풀었다」를 갈라 재는가.**
 *   옛 자는 「절 하나 ≤ 5KB」 하나뿐이라 둘이 같은 빨강이었다. 09-06 에 규칙을 한 줄도
 *   안 남기고 정본으로 다 뺐는데 5KB 넘은 절이 스물 → 열여덟에서 더 안 줄었고,
 *   그 실측이 «자가 틀린 곳에서 울고 있다»고 말했다.
 *
 * 🔑 그래서 재는 것은 「절이 큰가」가 아니라 **「불릿 하나가 부풀었나」**다.
 */
const { test } = require('node:test');
const assert = require('node:assert');
const { 잰다, 자판 } = require('../tools/트랙위생.js');

const 머리 = '## 0-시험. 아무 절\n\n현황: 한 줄.\n';

test('🔑 일감이 «많아» 절이 커진 것은 잡지 않는다 — 남은 일이 서른 개면 절은 커야 맞다', () => {
  const 불릿 = Array.from({ length: 40 }, (_, i) => `- [기계] 남은 일 ${i} — 짧은 한 줄이다.`).join('\n');
  const r = 잰다(머리 + 불릿 + '\n');
  assert.strictEqual(r.불릿수, 40);
  assert.strictEqual(r.부푼불릿.length, 0, '짧은 불릿이 마흔 개인 절을 부풀었다고 세면 안 된다');
});

test('🔴 불릿 «하나»가 상한을 넘으면 잡는다 — 그 자리가 재료를 정본으로 옮길 자리다', () => {
  const 긴 = '- [기계] 긴 불릿 — ' + '가'.repeat(자판.불릿최대); // 한글 3바이트라 확실히 넘는다
  const r = 잰다(머리 + 긴 + '\n');
  assert.strictEqual(r.부푼불릿.length, 1);
  assert.ok(r.부푼불릿[0].바이트 > 자판.불릿최대);
});

test('🔴 곁줄이 넷째 줄로 넘어가면 잡는다 — 셋까지는 색인이고 넷째부터는 재료다', () => {
  const 곁 = ['- [유호] 짧은 머리', '  곁 1', '  곁 2', '  곁 3', '  곁 4'].join('\n');
  const r = 잰다(머리 + 곁 + '\n');
  assert.strictEqual(r.부푼불릿.length, 1);
  assert.strictEqual(r.부푼불릿[0].곁줄, 4);
  // 셋까지는 통과한다
  const 셋 = ['- [유호] 짧은 머리', '  곁 1', '  곁 2', '  곁 3'].join('\n');
  assert.strictEqual(잰다(머리 + 셋 + '\n').부푼불릿.length, 0);
});

test('🔴 절 «머리»가 무거우면 잡는다 — 색인 머리가 일기가 되는 자리', () => {
  const 무거운 = '## 0-시험. 아무 절\n\n' + '현황: ' + '가'.repeat(자판.머리최대) + '\n';
  const r = 잰다(무거운);
  assert.strictEqual(r.무거운머리.length, 1);
});

test('🔑 곁줄은 그 «불릿»에 붙지 절 머리에 안 붙는다 — 두 번 세면 자가 스스로 부푼다', () => {
  const 본 = 머리 + ['- [기계] 머리 한 줄', '  곁줄 하나'].join('\n') + '\n';
  const r = 잰다(본);
  assert.strictEqual(r.무거운머리.length, 0, '곁줄을 절 머리로도 세고 있다');
  assert.strictEqual(r.불릿수, 1);
});

test('🚫 임자 태그가 없는 줄은 «일감 불릿»이 아니다 — 포인터·규칙 줄까지 세면 분모가 틀린다', () => {
  const 본 = 머리 + '- 자·규칙 → 정본은 `docs/_ops/트랙_규약.md` 다.\n- 🔑 아무 원리 한 줄.\n';
  assert.strictEqual(잰다(본).불릿수, 0);
});

test('🔴 «- »로 시작하는데 임자 태그가 없는 줄을 따로 센다 — 절 머리에 섞으면 무엇이 무거운지 가려진다', () => {
  const 본 = 머리 + ['- [기계] 임자 있는 일감', '- 🆕 임자 없는 줄 하나', '- ⏳ 임자 없는 줄 둘'].join('\n') + '\n';
  const r = 잰다(본);
  assert.strictEqual(r.불릿수, 1, '임자 없는 줄을 일감으로 세면 분모가 틀린다');
  assert.strictEqual(r.임자없음.length, 2);
  assert.strictEqual(r.무거운머리.length, 0, '임자 없는 줄을 절 머리 바이트에 더하면 §2-마케팅 이 4.3KB 로 보이던 그 자리다');
});

test('🔑 곁줄은 임자 없는 줄로 세지 않는다 — 들여쓴 줄은 «- »로 시작해도 그 불릿의 것이다', () => {
  const 본 = 머리 + ['- [유호] 머리', '  - 곁줄인데 대시로 시작한다'].join('\n') + '\n';
  const r = 잰다(본);
  assert.strictEqual(r.임자없음.length, 0);
  assert.strictEqual(r.불릿수, 1);
});

test('🔑 «일감이 아닌» 불릿 둘은 임자 없음으로 안 센다 — 안 빼면 예순둘 중 마흔이 오탐이다', () => {
  const 본 = 머리 + [
    '- ✅ [닫힘 09-05] 닫힌 것에는 임자가 아니라 상태가 붙는다',
    '- 🔑 규칙 한 줄 — 다음에 밟을 것이지 남은 일이 아니다',
    '- 자: 이 트랙을 재는 자',
    '- ⏳ 이건 남은 일이라 걸려야 한다',
  ].join('\n') + '\n';
  const r = 잰다(본);
  assert.strictEqual(r.임자없음.length, 1, '닫힘·규칙 줄까지 세면 「임자 없는 일감」이 묻힌다');
  assert.match(r.임자없음[0].머리, /남은 일이라/);
});

test('🔑 태그 안에 날짜·화살표가 섞여도 임자로 읽는다 — `[기계 09-06]`·`[유호 확정]`·`[기계 → 구현]`', () => {
  const 본 = 머리 + [
    '- ✅ [기계 09-06] 날짜가 붙은 태그',
    '- ✅ [유호 확정] 확정이 붙은 태그',
    '- 🔴 [기계 → 구현] 화살표가 붙은 태그',
  ].join('\n') + '\n';
  const r = 잰다(본);
  assert.strictEqual(r.불릿수, 3, '태그 안에 다른 말이 섞이면 못 읽던 자리다(09-06 실측 오탐 아홉)');
  assert.strictEqual(r.임자없음.length, 0);
});
