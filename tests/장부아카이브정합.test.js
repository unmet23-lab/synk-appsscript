/* 장부-아카이브 정합 — 2026-08-09 신설.
 *
 * 왜: 문서압축 병합이 원본을 `_archive/`로 옮기고도 진행 정본(철학_리라이팅_장부)을 안 고치는
 *   실수가 **두 병합 연속**으로 났다(③ 2/4 IP 반박 치명 ② · ③ 3/4 집필 규범 반박 치명 C1).
 *   증상: 다음 세션이 장부를 열고 아카이브된 파일을 「산 리라이팅 대상」으로 읽는다.
 *   CLAUDE.md 신뢰성: 같은 절차 2번째 = 실수가 아니라 시스템 결함 — 그래서 기계로 옮긴다.
 *
 * 무엇을 지키나: 장부의 어떤 줄이 `_archive/`에 실존하는 파일의 이름을 담고 있는데, 그 줄에
 *   병합·아카이브·폐기 표식이 하나도 없으면 그 줄은 낡았다(아카이브 사실이 장부에 안 실렸다).
 *
 * 가드 3맹점 대응(CLAUDE.md):
 *   ① 사람이 실제로 쓰는 표기로 검사 — 장부는 「SYNK 」 접두를 떼고, `_`를 공백으로 바꿔
 *      쓴다(실측: 「발표물 제작 프롬프트 v1」·「00B 에디토리얼 브리프」). 변형을 정규화해 잡는다.
 *   ② 버그가 아직 있길 요구하는 회귀 금지 — 탐지력은 아래 픽스처가 못박고,
 *      실저장소(진짜 장부)에는 거짓양성 0건만 검사한다.
 *   ③ 자기 처방 통과 — 처방은 「그 줄에 병합·아카이브 표식을 적어라」이고, 적으면 통과한다.
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const 장부경로 = path.join(ROOT, 'docs', '_ops', '철학_리라이팅_장부.md');
const 아카이브 = path.join(ROOT, 'docs', '_archive');

/* 그 줄이 아카이브 사실을 이미 알고 있다는 표식 */
const 표식 = /병합|아카이브|폐기|_archive|완료|git 이력/;

const 정규화 = (s) => s.replace(/_/g, ' ').replace(/\s+/g, ' ');

/* 아카이브 파일 하나 → 장부가 쓸 법한 표기 변형들(확장자 제거 · SYNK 접두 제거) */
function 표기변형(파일명) {
  const 이름 = 정규화(파일명.replace(/\.[^.]+$/, ''));
  const 후보 = [이름, 이름.replace(/^SYNK /, '')];
  return [...new Set(후보)].filter((n) => n.length >= 6); // 짧은 이름은 오탐만 만든다
}

/* 핵심 판정 — 낡은 줄 목록을 돌려준다 */
function 낡은줄(장부텍스트, 아카이브파일들) {
  const 줄들 = 장부텍스트.split(/\r?\n/);
  const 걸림 = [];
  for (const 파일명 of 아카이브파일들) {
    for (const 변형 of 표기변형(파일명)) {
      for (let i = 0; i < 줄들.length; i++) {
        const 줄 = 줄들[i];
        if (정규화(줄).includes(변형) && !표식.test(줄)) {
          걸림.push({ 파일명, 변형, 행: i + 1, 줄: 줄.trim().slice(0, 120) });
        }
      }
    }
  }
  return 걸림;
}

/* ─── 탐지력: 픽스처가 진다 ───────────────────────────────────────────────── */

test('탐지 — 아카이브된 파일을 산 대상처럼 든 줄을 잡는다(SYNK 접두·밑줄 변형 포함)', () => {
  const 장부 = [
    '| docs/정본/SYNK/{기업마스터 외}: 발표물 제작 프롬프트 v1 · 온라인 사업 설계 | ⬜ |',
    '| …리라이팅_v2/00B 에디토리얼 브리프 · 07_인테리어 | ⬜ |',
  ].join('\n');
  const 걸림 = 낡은줄(장부, ['SYNK 발표물 제작 프롬프트 v1.txt', '00B_에디토리얼_브리프.txt']);
  assert.equal(걸림.length, 2, `실측 표기 두 변형을 다 잡아야 한다 — 잡힌 것: ${JSON.stringify(걸림)}`);
});

test('처방 통과 — 같은 줄에 병합·아카이브 표식을 적으면 낡은 줄이 아니다(맹점 ③)', () => {
  const 장부 = [
    '| 발표물 제작 프롬프트 v1(=③ 집필 규범 병합·아카이브 완료) · 온라인 사업 설계 | ⬜ |',
    '- 2026-08-09 00B 에디토리얼 브리프 v5를 집필 규범으로 병합했다',
  ].join('\n');
  const 걸림 = 낡은줄(장부, ['SYNK 발표물 제작 프롬프트 v1.txt', '00B_에디토리얼_브리프.txt']);
  assert.equal(걸림.length, 0, `표식 있는 줄을 신고하면 처방을 따를 수 없다: ${JSON.stringify(걸림)}`);
});

test('거짓양성 — 아카이브에 없는 이름·6자 미만 이름은 건드리지 않는다', () => {
  const 장부 = '| docs/기업철학_홈페이지_v1.md | ⬜ | 살아있는 대상이다';
  assert.equal(낡은줄(장부, ['지도.md', 'SYNK 기업마스터 구본.txt']).length, 0);
});

/* ─── 실저장소: 거짓양성만 검사(맹점 ②) — 분모를 먼저 밝힌다 ──────────────── */

test('실저장소 — 장부가 _archive 파일을 산 대상처럼 들고 있지 않다', () => {
  const 파일들 = fs.readdirSync(아카이브, { withFileTypes: true })
    .filter((d) => d.isFile())
    .map((d) => d.name);
  assert.ok(파일들.length >= 10, `_archive 파일이 ${파일들.length}개뿐 — 목록이 비면 이 검사는 공회전이다`);
  const 장부텍스트 = fs.readFileSync(장부경로, 'utf8');
  assert.ok(장부텍스트.length > 1000, '장부가 비어 있다 — 경로가 어긋났으면 검사 전체가 공회전이다');
  const 걸림 = 낡은줄(장부텍스트, 파일들);
  assert.equal(
    걸림.length, 0,
    `장부가 아카이브된 파일을 산 대상처럼 들고 있다 — 그 줄에 「(=병합·아카이브 완료)」 류 표식을 적어라:\n` +
      걸림.map((g) => `  ${g.행}행 [${g.변형}] ${g.줄}`).join('\n')
  );
});
