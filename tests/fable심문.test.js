// fable심문 회귀 — 「범위를 골랐는데 그 렌즈가 안 갔다」를 막는다.
//
// 왜 이 자리인가: 범위 ③④ 의 값어치는 **추가 렌즈**뿐이다(대상 목록은 ②와 같다).
// 렌즈가 조용히 안 붙으면 ②를 돌린 것인데 산출물·장부·보고는 전부 「범위 4로 돌았다」고
// 말한다 — 실패가 통과와 **같은 모양**이 되는 자리라 프로즈로는 못 막는다.
//
// 지키는 것:
//   ① 범위 4 는 3 의 렌즈를 **누적한다**(안 하면 「전층」인데 코드 대조가 빠진다 — 가장 조용한 실패)
//   ② 렌즈는 「## 출력 형식」 **앞**, 즉 공격 렌즈 절 안에 들어간다
//   ③ 마커가 없으면 **던진다**(원문 그대로 통과시키면 범위 표기만 남고 렌즈는 사라진다)
//   ④ 범위 1·2 는 원문을 건드리지 않는다
// 탐지력은 전부 픽스처가 진다 — 실저장소 템플릿에는 **거짓양성만** 검사한다.
'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const F = require('../tools/fable심문.js');

/* 실제 템플릿의 모양만 흉내낸 최소 픽스처 — 실저장소 문서를 쓰면
 * 「버그가 아직 있을 것」을 요구하는 회귀가 된다. */
const 픽스처 = [
  '## 공격 렌즈 (전부 적용)',
  '1. **소급 불가 구멍**: …',
  '7. **과설계·선행 구축**: …',
  '',
  '## 출력 형식',
  '발견 항목마다: [P0|P1|P2] …',
].join('\n');

test('범위 1·2 — 원문을 건드리지 않는다', () => {
  assert.strictEqual(F.렌즈덧붙이기(픽스처, 1), 픽스처);
  assert.strictEqual(F.렌즈덧붙이기(픽스처, 2), 픽스처);
});

test('범위 3 — 렌즈 8~11 이 붙고, 출력 형식 앞에 온다', () => {
  const 결과 = F.렌즈덧붙이기(픽스처, 3);
  for (const n of [8, 9, 10, 11]) {
    assert.ok(결과.includes(`${n}. **`), `렌즈 ${n} 이 없다`);
  }
  assert.ok(결과.indexOf('8. **') < 결과.indexOf('## 출력 형식'),
    '렌즈가 「## 출력 형식」 뒤에 붙었다 — 공격 렌즈 절 밖이면 렌즈로 안 읽힌다');
  assert.ok(결과.indexOf('7. **과설계') < 결과.indexOf('8. **'),
    '기존 렌즈 7 뒤에 와야 한다 — 앞에 끼면 번호가 어긋난다');
  // ③ 은 ④ 의 렌즈를 **앞당겨 쓰지 않는다**
  assert.ok(!결과.includes('12. **'), '범위 3 인데 범위 4 렌즈가 실렸다');
});

test('범위 4 — 3 의 렌즈를 누적한다 (가장 조용한 실패 자리)', () => {
  const 결과 = F.렌즈덧붙이기(픽스처, 4);
  for (const n of [8, 9, 10, 11, 12, 13]) {
    assert.ok(결과.includes(`${n}. **`),
      `렌즈 ${n} 이 없다 — 「전층」이라 부르면서 코드·운영 축이 빠지면 통과와 구분되지 않는다`);
  }
  assert.ok(결과.indexOf('8. **') < 결과.indexOf('12. **'), '누적 순서가 어긋났다');
});

test('마커가 없으면 던진다 — 조용히 원문을 통과시키지 않는다', () => {
  const 마커없음 = '## 공격 렌즈 (전부 적용)\n1. …\n';
  assert.throws(() => F.렌즈덧붙이기(마커없음, 3), (e) => {
    assert.ok(e.확인불가, '확인불가로 표시돼야 한다 — 통과가 아니다');
    return true;
  });
  // 범위 1·2 는 렌즈를 안 쓰므로 마커가 없어도 통과한다(끼울 게 없는 것과 못 끼운 것은 다르다)
  assert.strictEqual(F.렌즈덧붙이기(마커없음, 2), 마커없음);
});

test('범위 밖 숫자는 던진다', () => {
  assert.throws(() => F.렌즈덧붙이기(픽스처, 5), (e) => e.확인불가);
});

/* 실저장소 — 탐지가 아니라 **거짓양성 검사**다. 정본 템플릿이 마커를 잃으면
 * 범위 ③④ 가 통째로 죽는데 픽스처는 그걸 영원히 모른다. */
test('정본 템플릿에 삽입 마커가 실재한다', () => {
  const 정본 = path.join(__dirname, '..', 'docs', '_ops', '동결심문_프롬프트.md');
  if (!fs.existsSync(정본)) {
    console.log('  ⏭ skip — 정본 템플릿 없음(이 머신 밖)');
    return;
  }
  const 전문 = fs.readFileSync(정본, 'utf8');
  assert.ok(전문.includes('## 출력 형식'),
    '동결심문_프롬프트.md 에 「## 출력 형식」이 없다 — fable심문 범위 ③④ 가 조립 단계에서 죽는다');
  assert.ok(전문.includes('{{금지목록}}') && 전문.includes('{{대상문서}}'),
    '치환 마커가 사라졌다 — 치환 없이 보내면 빈 심문이 「통과」로 보인다');
});

/* 유호님 상시 지시(08-07 · 08-11 축 확대) — 개인정보·보안 축은 판정 재료가 아니다.
 * 2번째라 프로즈를 접고 회귀로 옮긴다: 08-07 에 「동의문」으로 닫힌 축을 08-11 심문이
 * 「redaction 공정이 0줄」이라는 새 모양으로 되살려 P0 로 올렸다. 렌즈에서 그 축을 빼도
 * 다음 개정이 조용히 되돌리면 같은 일이 난다 — 되돌리면 여기서 빨개진다. */
test('정본 템플릿이 개인정보·보안 축을 지적 대상에서 뺀다', () => {
  const 정본 = path.join(__dirname, '..', 'docs', '_ops', '동결심문_프롬프트.md');
  if (!fs.existsSync(정본)) {
    console.log('  ⏭ skip — 정본 템플릿 없음(이 머신 밖)');
    return;
  }
  const 전문 = fs.readFileSync(정본, 'utf8');
  assert.ok(/개인정보.*(지적하지 마라|범위 밖)/s.test(전문),
    '동결심문_프롬프트.md 에서 「개인정보·보안 축은 지적하지 마라」가 사라졌다 — 유호님이 닫은 결정을 심문이 되살린다(08-07 지시를 08-11 에 어긴 자리)');
  /* ⚠ `전문` 은 **마크다운 문서**(프롬프트 정본·SKILL.md)지 JS 원문이 아니다 — 이 파일의 부정 단언
   *   둘을 `코드만()` 으로 감싸지 않는다(갈래 ⓒ 비JS · 대기열 #Q72). 마크다운엔 JS 주석이 없고,
   *   렉서를 대면 본문의 `//`·URL 뒤가 잘려 「그 문구가 없다」가 거짓으로 참이 된다. */
  assert.ok(!/동의 철회 전파가 정의됐는가/.test(전문),
    '렌즈 5 에 「동의 철회 전파」가 되살아났다 — 그 문구가 P1 2건을 낳았다');
});

/* 렌즈 정본이 스킬 문서에 사본되지 않았는지 — 두 곳에 적으면 갈라지고,
 * 갈린 쪽은 언제나 조용히 통과한다(CLAUDE.md 신뢰성 §가드 맹점 ④). */
test('스킬 문서가 렌즈 본문을 사본하지 않는다', () => {
  const 스킬 = path.join(__dirname, '..', '.claude', 'skills', 'fable심문', 'SKILL.md');
  if (!fs.existsSync(스킬)) {
    console.log('  ⏭ skip — 스킬 문서 없음');
    return;
  }
  const 전문 = fs.readFileSync(스킬, 'utf8');
  const 본문조각 = F.추가렌즈[3][0].replace(/^\d+\.\s*/, '').slice(0, 20);
  assert.ok(!전문.includes(본문조각),
    `스킬에 렌즈 본문이 사본돼 있다("${본문조각}…") — 정본은 tools/fable심문.js 하나여야 한다`);
});

/* ── 심문 «대상» 목록 (2026-08-12) ────────────────────────────────────────────
 * 🔴 실측: 이 도구가 7판 돌았는데 그 세션들의 `Skill` 호출 0 · SKILL.md Read 0 이었다.
 *   목록이 스킬 문서에만 있었으니 그 7판의 대상은 매번 손으로 정해졌다 — 회차마다 대상이
 *   갈리면 판끼리 대조가 원리상 무효고(F281), 그 대조가 이 통로 전체의 존재 이유다.
 *   렌즈는 도구에 있었는데 «무엇을 심문할지»라는 더 큰 조립이 밖에 남아 있던 자리. */

test('스킬 문서가 대상 목록을 사본하지 않는다(렌즈와 같은 규칙)', () => {
  const 스킬 = path.join(__dirname, '..', '.claude', 'skills', 'fable심문', 'SKILL.md');
  if (!fs.existsSync(스킬)) { console.log('  ⏭ skip — 스킬 문서 없음'); return; }
  const 전문 = fs.readFileSync(스킬, 'utf8');
  const 샌것 = [...F.핵심4, ...F.설계전량].filter((p) => 전문.includes(p));
  assert.deepStrictEqual(샌것, [],
    `스킬에 대상 경로가 사본돼 있다 — 정본은 tools/fable심문.js 하나여야 한다: ${샌것.join(' · ')}`);
  assert.ok(전문.includes('--대상목록'),
    '스킬이 대상 목록 통로를 안 가리킨다 — 목록을 뺐는데 갈 곳을 안 알려주면 손으로 고르게 된다(F103)');
});

test('범위 — ① 은 핵심 4종, ②③④ 는 같은 문서 집합(렌즈만 두꺼워진다)', () => {
  const r1 = F.대상목록(1);
  assert.deepStrictEqual(r1.표, F.핵심4, '범위 1 이 핵심 4종이 아니다');
  assert.deepStrictEqual(r1.보강, [], '범위 1 은 「핵심 4종」이 정의라 넓히면 안 된다');
  const [r2, r3, r4] = [2, 3, 4].map(F.대상목록);
  assert.deepStrictEqual(r3.대상, r2.대상, '범위 3 의 문서 집합이 2 와 다르다(③ 은 렌즈만 추가다)');
  assert.deepStrictEqual(r4.대상, r2.대상, '범위 4 의 문서 집합이 2 와 다르다(④ 는 렌즈만 추가다)');
  for (const p of F.핵심4) assert.ok(r2.표.includes(p), `범위 2 가 핵심 4종을 안 담았다: ${p}`);
});

test('보강 — 표와 겹치지 않고, 뺀 것은 반드시 사유를 갖는다', () => {
  const r = F.대상목록(2);
  const 표 = new Set(r.표);
  const 겹침 = r.보강.filter((p) => 표.has(p));
  assert.deepStrictEqual(겹침, [], `보강이 표와 겹친다 — 같은 문서를 두 판 돌게 된다: ${겹침.join(' · ')}`);
  for (const x of r.제외) {
    assert.ok(x.사유 && x.사유.length > 5, `제외에 사유가 없다: ${x.경로} — 사유 없는 제외는 다음 회차에 다시 판단하게 된다`);
    assert.ok(!r.대상.includes(x.경로), `제외했는데 대상에 남아 있다: ${x.경로}`);
  }
});

test('없는 파일을 조용히 빼지 않는다 — 표의 항목은 실재하거나 「없음」에 뜬다(F207)', () => {
  const r = F.대상목록(2);
  const 없음 = new Set(r.없음);
  for (const p of r.표) {
    const 실재 = fs.existsSync(path.resolve(__dirname, '..', p));
    assert.ok(실재 || 없음.has(p),
      `표에 있고 디스크에 없는데 「없음」에도 안 뜬다: ${p} — 26판 돌 것을 24판 돌고 「전부 돌았다」가 된다`);
    if (실재) assert.ok(r.대상.includes(p), `실재하는 표 항목이 대상에서 빠졌다: ${p}`);
  }
});

test('--범위 는 기본값을 안 준다 — 안 주면 «확인불가» 로 멈춘다(조용히 2 로 떨어지지 않는다)', () => {
  assert.throws(() => F.범위값([]), (e) => e && e.확인불가 && /--범위/.test(e.message),
    '범위 없이도 돌아간다 — 세션은 ④를 시켰다고 믿고 장부엔 ②가 적히는 모양이 가능해진다');
  assert.throws(() => F.범위값(['--범위', '9']) && F.대상목록(9), /범위는 1~4/);
  assert.strictEqual(F.범위값(['--범위', '3']), 3, '정상 값을 못 읽는다');
});
