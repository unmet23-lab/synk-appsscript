/* ── 픽스처 ─────────────────────────────────────────────────────────────────
 * 커밋 시각을 **손으로 못박는다** — 「채번이 도장보다 나중인가」가 판정 재료라, 초 단위 실시각에
 * 기대면 같은 초에 난 커밋에서 결과가 갈린다(대조는 그 사이 입력을 얼린다 · F281). */
function git(dir, args, 날짜) {
  const env = { ...process.env };
  if (날짜) { env.GIT_AUTHOR_DATE = 날짜; env.GIT_COMMITTER_DATE = 날짜; }
  return execFileSync('git', args, { cwd: dir, encoding: 'utf8', env, stdio: ['ignore', 'pipe', 'pipe'] });
}

const 날 = (d) => `2026-01-0${d}T12:00:00+09:00`;
const ms = (d) => Date.parse(날(d));

/**
 * 라이브가 **뒤처진 채 채번이 난** 저장소를 만든다 — F474 의 상태 그대로.
 *   c0(01-01) = 라이브가 서 있는 판   ·  c1(01-02) = 그 뒤 코드 변경
 *   c2(01-03) = **채번 커밋 자신이 페이로드**(옛 기준선은 여기서 자기 diff 를 떨군다)
 * 돌려주는 것: `{ 뿌리, c0, c2, 상태파일 }`
 */
function 픽스처() {
  const 뿌리 = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'synk-기준선-')));
  git(뿌리, ['init', '-b', 'master']);
  git(뿌리, ['config', 'user.email', 'test@synk.local']);
  git(뿌리, ['config', 'user.name', 'test']);
  git(뿌리, ['config', 'commit.gpgsign', 'false']);

  const 쓰기 = (f, s) => fs.writeFileSync(path.join(뿌리, f), s, 'utf8');
  쓰기('Code.js', "const SYNK_VERSION = 'v9.237';\n");
  쓰기('엔진.js', 'function a() { return 1; }\n');
  git(뿌리, ['add', '--', 'Code.js', '엔진.js']);
  git(뿌리, ['commit', '-m', '[v9.237] 채번 — 이 판이 라이브다'], 날(1));
  const c0 = git(뿌리, ['rev-parse', 'HEAD']).trim();

  쓰기('엔진.js', 'function a() { return 2; }\n');
  git(뿌리, ['add', '--', '엔진.js']);
  git(뿌리, ['commit', '-m', '엔진 수리'], 날(2));

  /* 🔑 급소 — 채번과 코드 변경이 **한 커밋**이다. 옛 기준선(= 이 커밋)으로 diff 를 뜨면 0 이 나온다. */
  쓰기('Code.js', "const SYNK_VERSION = 'v9.239';\n");
  쓰기('보고서.js', 'function b() { return 3; }\n');
  git(뿌리, ['add', '--', 'Code.js', '보고서.js']);
  git(뿌리, ['commit', '-m', '[v9.239] 채번 + 보고서 신설'], 날(3));
  const c2 = git(뿌리, ['rev-parse', 'HEAD']).trim();

  return { 뿌리, c0, c2, 상태파일: path.join(뿌리, 'rot-state.json') };
}

/** 도장을 손으로 찍는다 — 라이브를 실제로 잰 rot-check 이 남기는 모양 그대로. */
function 도장찍기(f, { at, 라이브판 = null, 초록 = false, 지문 = 'ffffffff' }) {
  const 프로젝트들 = { '(루트)': { 지문, 초록 } };
  if (라이브판) 프로젝트들['(루트)'].라이브판 = { 종류: '뒤처짐', sha: 라이브판 };
  fs.writeFileSync(f, JSON.stringify({ [점검.도장키]: { at, 프로젝트들 } }), 'utf8');
}

/** git 이 없는 판은 fail 이 아니라 **skip** 이다 — 안 잰 것을 통과로 세지 않는다(F296). */
function 준비(t) {
  try { return 픽스처(); } catch (e) { t.skip(`git 을 못 돌린다(${e.code || e.message}) — 이 축은 안 쟀다`); return null; }
}

/** `안나간변경` 을 픽스처 위에서 돌린다(프로젝트 목록 = 뿌리 하나 · 도장 경로를 갈아 끼운다). */
function 재기(F, 상태) {
  const 옛 = process.env.SYNK_ROT_STATE;
  if (상태 === null) delete process.env.SYNK_ROT_STATE; else process.env.SYNK_ROT_STATE = 상태;
  try { return 점검.안나간변경(F.뿌리, [F.뿌리]); }
  finally { if (옛 === undefined) delete process.env.SYNK_ROT_STATE; else process.env.SYNK_ROT_STATE = 옛; }
}

const 파일들 = (r) => (r.프로젝트들[0] ? [...r.프로젝트들[0].파일들].sort() : []);

