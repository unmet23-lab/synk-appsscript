/* 「안 나간 변경」의 **기준선** 회귀 — 0 건이 무엇에 견준 0 인가 (마찰 F474 · #Q88).
 *
 * ■ 실사고 2026-08-15
 *   `tools/보안검토과녁.js` 가 「검토 대상 0건 — 대조할 것이 없다(미실행이 아니다)」를 **단언**했다.
 *   그때 라이브는 v9.237(`a074533c`)이고 HEAD 는 v9.239(`dd8b4f41`)라, 실제로 새로 나갈 바이트는
 *   **배포집합 5파일 · 31 삽입**이었다. 원인은 `배포판점검.안나간변경` 의 diff 기준선이
 *   **마지막 채번 커밋**이라는 것 하나다 — 정상 순서가 채번→커밋→push→clasp 라 **끊기는 자리는
 *   거의 언제나 채번 «뒤»**이고, 그때 기준선은 페이로드 자신이 되어 자기 diff 를 과녁 밖으로 떨군다.
 *   지침 v9.2 가드 맹점 ④(맞는 얼굴로 틀린 값)의 교과서 모양이고, 새는 방향은 「통과」였다.
 *
 * ■ 왜 실저장소로는 못 재나 (가드 맹점 ② — 탐지력은 픽스처가 진다)
 *   이 갈래가 서려면 「라이브가 뒤처져 있고 그 뒤에 채번이 났다」는 상태를 **연출**해야 한다.
 *   실저장소는 배포 직후면 어차피 초록이라 아무것도 안 재고(실측 08-15: 이 트랙 착수 시점에
 *   라이브 = 저장소였다), 옆 세션이 상시 커밋해 상태가 그날 운에 걸린다. 그래서 **전부 픽스처**다.
 *   실저장소에는 거짓양성 불변식만 건다.
 *
 * ■ 이 회귀의 대가 (새 장치엔 대가를 적는다 · CLAUDE.md 신뢰성)
 *   · 틀릴 때의 모습 = **git 을 못 부르는 판에서 통째로 skip** 된다(F296). 그때 이 축은 안 재지는데
 *     초록으로 보이므로, skip 사유를 반드시 글자로 남긴다(아래 `준비`).
 *   · 닫을 것 = **없다.** 이건 새 경보가 아니라 이미 있는 두 함수의 계약을 못박는 검사라 끌 대상이
 *     없고, 옛 검사 중 이걸로 무의미해지는 것도 없다(`보안검토과녁.test.js` 는 판정·종료 코드를,
 *     `배포판점검.test.js` 는 지문·배포집합을 진다 — 기준선을 재는 자리는 여기가 처음이다).
 */
