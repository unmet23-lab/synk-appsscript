/* 인계문 잔여 회귀 — 종결 줄의 **▶ 조각**을 「배경이다」로 단정하지 않는다 (마찰 F398).
 *
 * 무엇이 났나 (2026-08-13 실측): 인계문은 상태 칸이 ✅ 로 열리면 「⚠·⏳ 잔여는 **배경이지 지시가
 *   아니다**」로 단정하고 「새 트랙을 잡아라」로 끝냈다. 그런데 이 저장소의 **반쪽 종결**
 *   (`①판정 ✅ / ②집행 ▶`)도 ✅ 로 열린다 — 5c55e5f5 에서 남은 ②집행이 그 단정에 밀려
 *   배경이 될 뻔했다(그 세션은 상태 칸을 ▶ 로 여는 **우회**로 빠져나갔다).
 *
 * 🔑 장부의 처방 후보(「칸 안에 ▶ 가 있으면 종결로 안 읽기」)는 **재 보고 기각했다** — 아카이브
 *   ✅줄 540 중 86줄이 ▶ 를 달고도 진짜 종결이다(▶ 가 «다음 주자» 표기를 겸한다). 판정을 뒤집으면
 *   종결 여섯 중 하나가 「이어라」로 나가고, 그건 `종결줄` 주석이 일부러 피한 비싼 쪽이다.
 *   그래서 고친 것은 판정이 아니라 **단정**이다: 조각을 그대로 보이고 「가른 뒤 정하라」로 넘긴다.
 *
 * 여기서 못박는 것 다섯:
 *   ① **탐지력은 픽스처가 진다**(가드 맹점 ②) — 아래 문자열은 전부 이 저장소에 실제로 났던 상태
 *      칸이다(가드 맹점 ①). 실저장소에는 거짓양성 불변식만 건다.
 *   ② **판정은 안 뒤집혔다** — 두 갈래 모두 「새 트랙」 지시를 그대로 달고 나가야 한다.
 *   ③ **단정과 가름은 같이 못 산다** — 조각이 있는 줄에 옛 단정이 남으면 고친 게 아니다.
 *   ④ **배경 목록은 좁다** — 넓히면 그 모양은 영영 안 보인다(새는 방향을 「보인다」쪽에 둔다).
 *   ⑤ **우회 형태는 애초에 이 갈래가 아니다** — ▶ 로 여는 줄은 종결줄이 아니다.
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const 보고 = require(path.join(REPO, '.claude', 'hooks', 'lib', 'session-report.js'));

/* ── 사람이 실제로 쓰는 표기 그대로 (아카이브·산 보드에서 그대로 옮김) ────────────── */

/** 배경 = 읽는 이가 할 일이 없는 것이 표기만으로 확실한 것. */
const 배경들 = [
  ['다음=새 트랙', '✅**종결** — 장부 3상태+`defer` `e31a6a3d` · 열림 32→20 · ▶다음=새 트랙'],
  ['⏳유호 대기', '✅수리 종결 (`local_97a424b2`) — 회귀 4·**변이 2/2** · ▶⏳유호=운영 배포 판정'],
  ['다음 없음', '✅**종결** — 왕복 26/26 · ▶다음 없음(배포 트랙은 `ed8b5124` 몫)'],
  ['작업 대기열', '✅**전건 종결** — 회귀 3 · ▶다음=작업 대기열'],
  ['🎫 는 제 통로가 있다', '✅재검수1 0건 · ▶🎫**다음=`--commit deadbee` 재검수**→배포'],
];

/** 잔여 = 그 트랙이 안 끝냈을 수도 있는 것. 기계는 못 가르니 **보여야** 한다. */
const 잔여들 = [
  ['남은 차단자', '✅처분표 v4=68건 12뿌리(`145a2ccf`) · ✅**v5 12군 전건 집행** · ▶**남은 차단자=§12 픽스처 조립 하나** · 🔴F375', '남은 차단자'],
  ['남은 25건 미착수', '✅**큐 108→47 (61건 종결)** (`local_83092ce5`) — 🔑마스터=큐#103 · ▶다음=남은 25건 미착수(규칙 §0 서 있음)', '남은 25건 미착수'],
  ['F398 원 사고 모양(반쪽 종결)', '✅**①판정 종결** 82/82·46갈래 · ▶**다음 = ②집행 v5.2**(처분표 §5 지도 그대로)', '②집행 v5.2'],
  ['다음 주자가 있어도 보인다', '✅**종결** talk `5557df7` — 전량 1748/1748 · ▶다음=**§8-4 화면**(주인 없음)', '§8-4 화면'],
];

/* ── ① 배경은 안 낸다 ─────────────────────────────────────────────── */

for (const [이름, 줄] of 배경들) {
  test(`☠️ 배경 표기는 조각으로 안 낸다 — ${이름}`, () => {
    assert.equal(보고.잔여조각(줄), null, '이 모양은 읽는 이가 할 일이 없다 — 매 인계문에 한 줄씩 붙으면 소음이 된다');
  });
}

/* ── ② 진짜 잔여는 글자로 보인다 ──────────────────────────────────── */

for (const [이름, 줄, 알맹이] of 잔여들) {
  test(`☠️ 종결 줄에 남은 ▶ 잔여를 조각으로 낸다 — ${이름}`, () => {
    const 조각 = 보고.잔여조각(줄);
    assert.ok(조각, '조각이 null 이면 옛 단정이 그대로 나간다(F398 그 자리)');
    assert.ok(조각.includes(알맹이), `조각에 「${알맹이}」가 있어야 열어 볼 이유가 선다 — 받은 것: ${조각}`);
  });
}

/* ── ③ ▶ 가 없으면 아무것도 안 바뀐다 (F169 판정 보존) ─────────────── */

test('☠️ ▶ 없는 종결 줄은 조각 없음 — 옛 단정이 그대로 산다', () => {
  const 줄 = '✅**종결(`local_aecdc2fd`)** 교체 52곳 · 🔴**라이브 미배포**=v9.228 서클 P1 3건(남의 트랙)';
  assert.equal(보고.잔여조각(줄), null);
  const 문구 = 보고.종결문구(줄);
  assert.ok(문구.includes('배경이지 지시가 아니다'), 'F169 가 세운 단정은 ▶ 없는 줄에서 그대로여야 한다');
});

/* ── ④ 단정과 가름은 같이 못 산다 ─────────────────────────────────── */

test('☠️ 조각이 있으면 옛 단정을 **걷는다** — 두 문장이 같이 나가면 안 고친 것이다', () => {
  const 문구 = 보고.종결문구('✅**①판정 종결** 82/82 · ▶**다음 = ②집행 v5.2**');
  assert.ok(문구.includes('②집행 v5.2'), '조각이 글자로 실려야 한다');
  assert.ok(문구.includes('가른 뒤'), '처방은 「가른다」다 — 따를 수 있는 동작이어야 한다(F103)');
  assert.ok(!문구.includes('배경이지 지시가 아니다'),
    '단정이 남아 있으면 조각을 보여 줘도 읽는 이는 「배경이구나」로 닫는다');
});

/* ── ⑤ 판정은 안 뒤집혔다 ─────────────────────────────────────────── */

test('☠️ 두 갈래 다 「새 트랙」 지시를 그대로 단다 — 이 처방은 판정을 안 뒤집는다', () => {
  for (const 줄 of ['✅**종결** — 회귀 4 · ▶다음=남은 25건 미착수', '✅**종결** — 회귀 4']) {
    const 문구 = 보고.종결문구(줄);
    assert.ok(문구.includes('새 트랙을 잡아라'),
      '▶ 를 「이어라」로 번역하면 아카이브 ✅줄 540 중 86줄이 하면 안 되는 실행 지시가 된다');
    assert.ok(문구.startsWith('▶ **이 트랙은 종결로 적혀 있다**'), '종결 판정 자체는 그대로다');
  }
});

/* ── ⑥ 우회 형태는 애초에 이 갈래가 아니다 ────────────────────────── */

test('☠️ ▶ 로 여는 줄은 종결줄이 아니다 — 5c55e5f5 의 우회는 계속 통해야 한다', () => {
  assert.equal(보고.종결줄('▶**미완 — 다음 = ②집행 v5.2**(①판정만 ✅ 82/82)'), false);
});

/* ── ⑦ 조각은 길어도 인계문을 못 삼킨다 ──────────────────────────── */

test('☠️ 조각 길이 상한 — 인계문은 매 세션 컨텍스트에 실린다', () => {
  const 긴줄 = '✅종결 · ▶' + '가'.repeat(400);
  const 조각 = 보고.잔여조각(긴줄);
  assert.ok(조각.length <= 111, `상한을 넘으면 상태 칸 하나가 인계문을 삼킨다 — 받은 길이 ${조각.length}`);
  assert.ok(조각.endsWith('…'), '잘렸으면 잘렸다고 보여야 원본을 열 이유가 선다');
});

/* ── ⑧ 실저장소 — 거짓양성만 (가드 맹점 ② · F296: repo 밖 환경에 안 기댄다) ────── */

test('실저장소 산 보드: 조각은 null 이거나 «비지 않은» 문자열이다 (거짓양성 불변식)', (t) => {
  const dir = path.join(REPO, 'docs', '_ops', '보드');
  let names;
  try { names = fs.readdirSync(dir).filter((n) => n.endsWith('.md')); } catch (_) { names = null; }
  // 못 읽음을 「깨끗함」으로 세지 않는다 — 0건과 미실행은 같은 모양이다(F207).
  if (!names || !names.length) return t.skip('보드 폴더를 못 읽었다 — 통과가 아니라 미실행이다');

  let 잰줄 = 0;
  for (const n of names) {
    for (const line of fs.readFileSync(path.join(dir, n), 'utf8').split(/\r?\n/)) {
      if (!/^\s*\|/.test(line)) continue;
      const 칸 = line.split('|').map((c) => c.trim());
      const st = 칸[칸.length - 2] || '';
      if (!보고.종결줄(st)) continue;
      잰줄++;
      const 조각 = 보고.잔여조각(st);
      assert.ok(조각 === null || (typeof 조각 === 'string' && 조각.length > 0),
        `빈 조각은 「▶ 가 있는데 보여 줄 게 없다」로 나간다 — ${n}`);
      assert.ok(보고.종결문구(st).includes('새 트랙을 잡아라'), `종결 갈래의 다음 수가 사라졌다 — ${n}`);
    }
  }
  assert.ok(잰줄 >= 0);
  t.diagnostic(`산 보드 ✅줄 ${잰줄}개를 실제로 태웠다`); // 분모를 밝힌다(F207)
});
