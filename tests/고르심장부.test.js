'use strict';
// 고르심 장부(tools/고르심장부.js · 2026-11-11) — 심사의 예측을 보이기 전에 적고 유호님 고르심과 견주는 기록이 뜻대로 쌓이고 세어지는지 본다.
//   정본 장부(docs/_ops/고르심기록.jsonl)는 건드리지 않는다 — 모두 임시 장부(--장부)로 돌린다.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const 도구 = path.join(__dirname, '..', 'tools', '고르심장부.js');
const 임시장부 = () => path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'synk-pick-')), '고르심.jsonl');
const 돌리기 = (장부, ...args) => spawnSync(process.execPath, [도구, ...args, '--장부', 장부], { encoding: 'utf8' });
const 후보셋 = ['--후보', 'A=창가 옆빛 판', '--후보', 'B=위에서 내린 빛 판', '--후보', 'C=역광 판'];
const 예측 = (장부, 묶음, 누가, 고름, 더 = []) => 돌리기(장부, '예측', '--묶음', 묶음, '--편', '시험 편', '--단계', '이미지', '--장르', '로맨스', ...후보셋, '--누가', 누가, '--고름', 고름, ...더);

test('예측 → 고르심 → 집계: 첫째 고름이 고르심 안에 있으면 맞힘, 순위 앞 둘 안에 있으면 「앞 둘 안」', () => {
  const 장부 = 임시장부();
  let r = 예측(장부, 'm1', '아르곤', 'A', ['--순위', 'A,B,C', '--때', '2026-11-11T01:00:00.000Z']);
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /예측 적음 — m1 · 아르곤 → A/);
  r = 예측(장부, 'm1', 'gpt', 'C', ['--순위', 'C,A,B', '--때', '2026-11-11T01:01:00.000Z']);
  assert.equal(r.status, 0, r.stderr);
  r = 돌리기(장부, '고르심', '--묶음', 'm1', '--고름', 'A', '--말씀', 'A가 훨씬 낫네', '--때', '2026-11-11T02:00:00.000Z');
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /고르심 적음 — m1 → A · 아르곤 맞힘\(A\) · gpt 빗나감\(C\)/);
  const 집계 = JSON.parse(돌리기(장부, '집계', '--json').stdout);
  assert.equal(집계.닫힌, 1);
  const 줄 = (눈) => 집계.표.find((x) => x.눈 === 눈 && x.갈래 === '전체');
  assert.deepEqual([줄('아르곤').맞힘, 줄('아르곤').묶음, 줄('아르곤').둘안], [1, 1, 1]);
  assert.deepEqual([줄('gpt').맞힘, 줄('gpt').묶음, 줄('gpt').둘안], [0, 1, 1], '첫째는 빗나갔지만 순위 앞 둘(C, A) 안에 있다');
  assert.ok(집계.표.some((x) => x.눈 === '아르곤' && x.갈래 === '단계' && x.값 === '이미지' && x.비율 === 100));
  assert.ok(집계.표.some((x) => x.눈 === '아르곤' && x.갈래 === '장르' && x.값 === '로맨스'));
  assert.match(돌리기(장부, '집계').stdout, /묶음이 열 개 아래인 눈은 비율을 근거로 쓰지 않는다/);
});

test('고르심 뒤의 예측은 받지 않는다 — --뒤늦게면 적되 집계에서 빠진다', () => {
  const 장부 = 임시장부();
  assert.equal(예측(장부, 'm2', '아르곤', 'B', ['--때', '2026-11-11T01:00:00.000Z']).status, 0);
  assert.equal(돌리기(장부, '고르심', '--묶음', 'm2', '--고름', 'A', '--말씀', 'A로 가자', '--때', '2026-11-11T02:00:00.000Z').status, 0);
  const 늦은 = 예측(장부, 'm2', 'opus', 'A', ['--때', '2026-11-11T03:00:00.000Z']);
  assert.equal(늦은.status, 1);
  assert.match(늦은.stderr, /받지 않음: 묶음 m2에는 고르심이 이미 적혀 있다 — 예측은 보이기 전에 적는다/);
  assert.equal(예측(장부, 'm2', 'opus', 'A', ['--때', '2026-11-11T03:00:00.000Z', '--뒤늦게']).status, 0);
  const 집계 = JSON.parse(돌리기(장부, '집계', '--json').stdout);
  assert.deepEqual(집계.표.filter((x) => x.갈래 === '전체').map((x) => `${x.눈}:${x.맞힘}/${x.묶음}`), ['아르곤:0/1'], '뒤늦은 opus 예측(A — 답을 알고 적음)은 세지 않는다');
});

test('「없음」: 모두 물리실 것을 미리 「없음」으로 적었으면 맞힘, 고른 것이 있는데 「없음」이면 빗나감', () => {
  const 장부 = 임시장부();
  assert.equal(예측(장부, 'm3', '아르곤', '없음', ['--때', '2026-11-11T01:00:00.000Z']).status, 0);
  assert.equal(예측(장부, 'm3', 'gpt', 'B', ['--때', '2026-11-11T01:00:01.000Z']).status, 0);
  const r = 돌리기(장부, '고르심', '--묶음', 'm3', '--고름', '없음', '--말씀', '셋 다 맹해. 다시', '--때', '2026-11-11T02:00:00.000Z');
  assert.match(r.stdout, /고르심 적음 — m3 → 없음 · 아르곤 맞힘\(없음\) · gpt 빗나감\(B\)/);
});

test('한 묶음에 같은 눈의 예측이 여럿이면 고르심 전 마지막 것, 고르심을 바꾸시면 마지막 고르심으로 견준다', () => {
  const 장부 = 임시장부();
  assert.equal(예측(장부, 'm4', '아르곤', 'A', ['--때', '2026-11-11T01:00:00.000Z']).status, 0);
  assert.equal(예측(장부, 'm4', '아르곤', 'B', ['--때', '2026-11-11T01:30:00.000Z']).status, 0);
  assert.equal(돌리기(장부, '고르심', '--묶음', 'm4', '--고름', 'A', '--말씀', 'A', '--때', '2026-11-11T02:00:00.000Z').status, 0);
  let 집계 = JSON.parse(돌리기(장부, '집계', '--json').stdout);
  assert.equal(집계.표.find((x) => x.갈래 === '전체').맞힘, 0, '마지막 예측 B가 A와 다르다');
  assert.equal(돌리기(장부, '고르심', '--묶음', 'm4', '--고름', 'B,C', '--말씀', '다시 보니 B나 C', '--때', '2026-11-11T04:00:00.000Z').status, 0);
  집계 = JSON.parse(돌리기(장부, '집계', '--json').stdout);
  assert.equal(집계.표.find((x) => x.갈래 === '전체').맞힘, 1);
  assert.equal(집계.닫힌, 1);
});

test('받지 않는 꼴 — 후보에 없는 이름 · 모르는 단계 · 말씀 없는 고르심 · 예측 없는 묶음의 고르심 · 바뀐 후보', () => {
  const 장부 = 임시장부();
  assert.match(예측(장부, 'm5', '아르곤', 'D').stderr, /후보에 없는 이름: D/);
  assert.match(돌리기(장부, '예측', '--묶음', 'm5', '--편', '편', '--단계', '느낌', ...후보셋, '--누가', '아르곤', '--고름', 'A').stderr, /--단계는 기획 · 콘티 · 이미지/);
  assert.match(돌리기(장부, '고르심', '--묶음', 'm5', '--고름', 'A', '--말씀', '좋아').stderr, /묶음 m5이 장부에 없다 — 보이기 전에 예측부터 적는다/);
  assert.equal(fs.existsSync(장부), false, '받지 않은 사건은 장부에 남지 않는다');
  assert.equal(예측(장부, 'm5', '아르곤', 'A').status, 0);
  assert.match(돌리기(장부, '고르심', '--묶음', 'm5', '--고름', 'A').stderr, /--말씀이 없다/);
  assert.match(돌리기(장부, '예측', '--묶음', 'm5', '--누가', 'gpt', '--고름', 'A', '--후보', 'A=가', '--후보', 'Z=나').stderr, /이 묶음의 후보는 이미 A, B, C로 적혀 있다/);
  // 둘째 예측부터는 묶음 id · 눈 · 고름만 적어도 된다(편 · 단계 · 후보는 첫 예측의 것)
  const r = 돌리기(장부, '예측', '--묶음', 'm5', '--누가', 'gpt', '--고름', 'C');
  assert.equal(r.status, 0, r.stderr);
  assert.match(돌리기(장부, '목록').stdout, /m5 · 시험 편 · 이미지 · 후보 A, B, C · 예측 아르곤, gpt/);
});

test('--맹검 결과.json에서 눈 · 고름 · 순위를 읽는다 — 쌍이면 쌍의 고름, 아니면 기각 아닌 판 가운데 최고 점수, 모두 기각이면 「없음」', () => {
  const 장부 = 임시장부(); const dir = path.dirname(장부);
  const 결과 = (이름, 낱장, 쌍 = []) => { const p = path.join(dir, `${이름}.json`); fs.writeFileSync(p, JSON.stringify({ 이름, 눈: '아르곤', 화면: 낱장.map((x) => ({ 번호: x.번호, 파일: `${x.번호}.jpg` })), 낱장, 쌍 })); return p; };
  const 셋 = 결과('셋', [{ 번호: '01', 판정: '고쳐서 냄', 점수: 6 }, { 번호: '02', 판정: '기각', 점수: 8 }, { 번호: '03', 판정: '그대로 냄', 점수: 7 }]);
  let r = 돌리기(장부, '예측', '--묶음', 'b1', '--편', '편', '--단계', '이미지', ...후보셋, '--맹검', 셋);
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /예측 적음 — b1 · 아르곤 → C/, '점수가 가장 높아도 기각인 B는 고르지 않는다');
  const 사건 = JSON.parse(fs.readFileSync(장부, 'utf8').trim().split('\n')[0]);
  assert.deepEqual(사건.순위, ['B', 'C', 'A']);
  assert.equal(사건.근거, 셋);
  const 쌍 = 결과('쌍', [{ 번호: '01', 판정: '그대로 냄', 점수: 7 }, { 번호: '02', 판정: '그대로 냄', 점수: 6 }], [{ 쌍: '01-02', 고름: '02', 까닭: '끝 그림이 더 세다' }]);
  r = 돌리기(장부, '예측', '--묶음', 'b2', '--편', '편', '--단계', '영상', '--후보', '가=끝 화면 한 벌', '--후보', '나=끝 화면 다른 벌', '--맹검', 쌍);
  assert.match(r.stdout, /예측 적음 — b2 · 아르곤 → 나/, '쌍의 고름이 점수보다 먼저다');
  const 모두기각 = 결과('기각', [{ 번호: '01', 판정: '기각', 점수: 3 }, { 번호: '02', 판정: '기각', 점수: 4 }]);
  r = 돌리기(장부, '예측', '--묶음', 'b3', '--편', '편', '--단계', '영상', '--후보', '가=한 벌', '--후보', '나=다른 벌', '--맹검', 모두기각);
  assert.match(r.stdout, /예측 적음 — b3 · 아르곤 → 없음/);
  const 빠짐 = 결과('빠짐', [{ 번호: '01', 판정: '그대로 냄', 점수: 7 }]);
  r = 돌리기(장부, '예측', '--묶음', 'b4', '--편', '편', '--단계', '영상', '--후보', '가=한 벌', '--후보', '나=다른 벌', '--맹검', 빠짐);
  assert.equal(r.status, 1);
  assert.match(r.stderr, /맹검 결과의 화면 1장과 후보 2개의 수가 다르다/);
});
