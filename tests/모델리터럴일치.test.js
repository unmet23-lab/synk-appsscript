/**
 * **라이브로 나가는 클로드 모델 이름이 세 곳에서 갈라지지 않는다.**
 *
 * 왜 기계로 막나 (2026-08-10 실측): 유호님이 「콘텐츠 모델을 올려」라고 확정했을 때
 * `Code.js` 의 `AI_FEEDBACK_MODEL` 만 보고 고칠 뻔했다. 그런데 실제 소비자는 셋이고,
 * 나머지 둘은 **`typeof AI_FEEDBACK_MODEL === 'undefined'` 폴백에 옛 값을 리터럴로** 들고 있었다.
 * Apps Script 는 `require` 가 없어 그 폴백을 지울 수도 없다 — 리터럴은 남을 수밖에 없다.
 *
 * 갈라지면 어떻게 보이나: **아무 일도 안 일어난 것처럼 보인다.** 폴백은 상수가 로드된 정상
 * 배포에서는 안 타므로, 파일 하나가 배포에서 빠지거나 로드 순서가 어긋난 날에만 조용히
 * 옛 모델로 돈다. 그리고 로그는 「최신 모델」이라고 말한다 — `tools/모델정책.js` 머리가
 * 이름 붙인 병이 정확히 이것이고(모델만 박고 효력을 안 박아 최상급이 low 로 돌던 자리),
 * 그 파일이 결정 자리를 하나로 모은 이유다.
 *
 * 그래서 이 검사는 **값이 무엇인지**를 묻지 않는다(그건 유호님 몫이다).
 * **세 자리가 같은가**만 본다 — 값이 바뀌어도 이 검사는 안 고쳐도 된다.
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const 읽기 = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');

/* 자리마다 모양이 달라 정규식도 다르다 — 한 정규식으로 뭉치면 한쪽이 사라져도 통과한다. */
const 자리들 = [
  {
    파일: 'Code.js',
    설명: '정본 상수',
    뽑기: (s) => (s.match(/const\s+AI_FEEDBACK_MODEL\s*=\s*'([^']+)'/) || [])[1],
  },
  {
    파일: '엔진_두뇌.js',
    설명: '폴백 리터럴',
    뽑기: (s) => (s.match(/typeof\s+AI_FEEDBACK_MODEL\s*===\s*'undefined'\s*\?\s*'([^']+)'/) || [])[1],
  },
  {
    파일: '상담AI.js',
    설명: '폴백 리터럴',
    뽑기: (s) => (s.match(/typeof\s+AI_FEEDBACK_MODEL\s*===\s*'undefined'\s*\?\s*'([^']+)'/) || [])[1],
  },
];

test('배포 파일 셋의 클로드 모델 리터럴이 같다', () => {
  const 값들 = 자리들.map((자리) => {
    const v = 자리.뽑기(읽기(자리.파일));
    /* 못 뽑은 것을 통과로 세지 않는다 — 새는 방향은 언제나 「통과」다.
     * 코드 모양이 바뀌었으면 이 검사부터 고쳐야 한다는 뜻이다. */
    assert.ok(v, `${자리.파일}(${자리.설명})에서 모델 리터럴을 못 뽑았다 — 코드 모양이 바뀌었으면 이 검사의 정규식을 함께 고친다`);
    return { ...자리, 값: v };
  });

  const 기준 = 값들[0];
  for (const 자리 of 값들.slice(1)) {
    assert.strictEqual(
      자리.값, 기준.값,
      `${자리.파일}(${자리.설명}) = ${자리.값} · ${기준.파일}(${기준.설명}) = ${기준.값}\n` +
      '→ 폴백이 정본과 갈라졌다. 정상 배포에서는 안 타므로 증상이 「조용함」뿐이다 — 세 자리를 함께 옮긴다.'
    );
  }
});

test('지금 쓰는 모델이 상담AI 단가표에 있다', () => {
  /* 왜: 비용 집계가 단가표에 없는 모델을 만나면 그 행을 **합계에서 뺀다**(0 으로 세면 지출이
   * 조용히 작아 보이니까). 그런데 「빼고 경고」도 결국 사람이 읽어야 도는 장치라, 모델을 올릴 때
   * 표를 같이 안 옮기면 다음 달 보고서가 절반만 센다. 그 짝을 여기서 기계로 묶는다. */
  const 소스 = 읽기('상담AI.js');
  const 표 = 소스.slice(소스.indexOf('const 상담AI_단가'), 소스.indexOf('const 상담AI_캐시배수'));
  assert.ok(표, '상담AI.js 에서 단가표를 못 찾았다 — 이름이 바뀌었으면 이 검사도 함께 고친다');
  const 모델 = 자리들[0].뽑기(읽기('Code.js'));
  assert.ok(
    표.includes(`'${모델}'`),
    `상담AI_단가 에 ${모델} 항목이 없다 — 비용 보고서가 이 모델의 행을 합계에서 빼고 센다(지출이 작아 보인다)`
  );
});

