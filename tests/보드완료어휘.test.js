/* 보드 완료 어휘 회귀 — 「끝났다」를 사람이 쓰는 표기로 읽는가 (F554).
 *
 * 사연: 완료 어휘가 ['완료','종결','라이브'] 뿐이라 이 저장소가 실제로 쓰는 「착지」를 못 읽었다.
 * 실측 2026-08-17: 보드 표줄 **40 이 전부 활성**으로 세어지고 완료가 **0** — 그중 13 줄의 상태
 * 칸이 「착지」였다. 증상은 상한이 아니라 **점유**였다(상한은 죽은 줄을 빼고 점유 검사는 안 뺀다):
 * 끝난 트랙이 그 파일을 영원히 쥐고, board-move 는 남의 «활성» 줄을 거절하고 보드수거는
 * «완료행»만 보니 **아무도 못 치운다** = 따를 수 없는 처방(F103). 이 파일 행 판정 결함 **4번째**
 * (F322·F330·F331 뒤)라, 목록을 늘리는 것 말고 **낡음을 시끄럽게 만드는 자**(`완료의심`)를 함께 세웠다.
 *
 * 여기서 못박는 것 넷:
 *   ① 「착지」가 완료다 — 그리고 **부정 접두**(미착지)는 완료가 아니다.
 *   ② `⏳`·`⏸` 는 완료 낱말이 있어도 **활성이다.** 새는 방향이 이쪽만 조용하다: 대기 줄이
 *      완료로 접히면 보드수거가 아카이브로 가져가고, 유호님 답이 오는 날 그 트랙은 어디에도 없다.
 *   ③ `완료의심` 은 **막지 않는다** — 어떤 판정도 안 바꾸고, 이미 완료로 읽는 낱말은 안 집는다
 *      (집으면 매주 같은 10줄이 떠서 그 경고가 배경이 된다).
 *   ④ **탐지력은 픽스처가 진다** — 실저장소엔 불변식(거짓양성 0)만 건다(가드 맹점 ②).
 *      실저장소의 의심 «건수»는 못박지 않는다: 그건 「버그가 아직 있을 것을 요구하는 회귀」다.
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const 보드 = require(path.join(REPO, 'tools', 'lib', '보드.js'));
/* 자식은 **공용 통로**로 띄운다 — 직접 spawnSync 하면 「안 떴다」가 빈 stderr 가 되어
 * 「아무 말도 안 한다」를 기대하는 검사가 **조용히 초록**이 된다(`tests/훅통로.test.js` 가 금지). */
const { 훅띄우기 } = require(path.join(REPO, 'tests', 'lib', '훅띄우기.js'));
const BOARDJS = path.join(REPO, 'tools', 'board.js');
const 머리 = '# 보드\n\n| 날짜 | 트랙/작업 | 만지는 파일 | 상태 |\n|---|---|---|---|\n';

function 저장소(파일들) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'board-vocab-'));
  fs.mkdirSync(path.join(dir, 'docs', '_ops', '보드'), { recursive: true });
  for (const [이름, 내용] of Object.entries(파일들 || {})) {
    fs.writeFileSync(path.join(dir, 'docs', '_ops', '보드', `${이름}.md`), 내용, 'utf8');
  }
  fs.writeFileSync(path.join(dir, 'docs', '세션보드_아카이브.md'), '# 아카이브\n\n---\n\n', 'utf8');
  return dir;
}

const 띄우기 = (root) => 훅띄우기([BOARDJS], {
  encoding: 'utf8', env: { ...process.env, SYNK_BOARD_ROOT: root },
});

/* 사람이 실제로 쓰는 모양 그대로다(가드 맹점 ①) — 아래는 2026-08-17 보드에서 실제로 난 줄을 줄인 것이다. */
const 줄 = (상태) => `| 2026-08-17 | **어떤 트랙** | tools/lib/보드.js | ${상태} |`;

/* ── ① 「착지」가 완료다 ───────────────────────────────────────────────── */

test('☠️ 「착지」가 완료로 읽힌다 — 못 읽으면 끝난 트랙이 파일을 영구 점유한다 (F554)', () => {
  const l = 줄('✅**착지** `79ae8335` (PR #52) — 회귀 34 · 변이 9/9');
  assert.strictEqual(보드.활성행(l), false, '「착지」는 도는 트랙이 아니다');
  assert.strictEqual(보드.완료행(l), true, '완료행이어야 수거·점유해제가 집는다');
});

test('☠️ 「미착지」는 완료가 아니다 — 부정 접두가 붙은 것을 완료로 읽으면 산 트랙이 지워진다', () => {
  const l = 줄('▶미착지 — 코드 0줄');
  assert.strictEqual(보드.활성행(l), true);
  assert.strictEqual(보드.완료행(l), false);
});

test('🔑 완료 어휘는 «사람이 쓰는 표기»여야 한다 — 「착지」가 목록에 있다', () => {
  assert.ok(보드.활성어휘().완료.includes('착지'),
    '이 저장소는 커밋 제목에서도 완료를 「착지」로 쓴다(F554 실측 13줄)');
});

test('🔑 뒤쪽 서술은 완료로 뒤집지 못한다 — 첫 구절만 본다', () => {
  const l = 줄('▶작업중 (`local_deadbeef`) — 다음 회차에 착지 예정');
  assert.strictEqual(보드.활성행(l), true, '「착지」가 뒤에 있어도 첫 구절이 활성이면 활성이다');
});

test('☠️ 첫 구절 축 — **활성 어휘가 없는** 줄에서도 뒤쪽 「착지」는 완료로 못 뒤집는다', () => {
  /* 🔴 위 검사만으로는 이 축이 안 재진다(변이가 잡아냈다 · 구멍 2건 중 1): 「작업중」이 먼저
   *   걸려서 상태 칸 전체를 보게 만들어도 초록이었다. 활성 어휘를 뺀 줄이라야 첫 구절만
   *   보는지가 드러난다. 뒤쪽에 「예정」도 두지 않는다 — 그것도 활성 어휘라 같은 구멍이 생긴다. */
  const l = 줄('▶3회차 · 코드 0줄 — 착지 `79ae8335`');
  assert.strictEqual(보드.상태첫구절(l).includes('착지'), false, '첫 구절엔 「착지」가 없어야 이 검사가 성립한다');
  assert.strictEqual(보드.활성행(l), true, '뒤쪽 서술이 완료로 뒤집으면 도는 트랙이 아카이브로 나간다');
  assert.strictEqual(보드.완료행(l), false);
});

test('☠️ 장식 축 — 상태 칸 앞머리(`✅**`)를 벗긴다', () => {
  /* 🔴 완료 판정은 부분매치라 장식이 붙어도 통과한다 — 그래서 판정으로는 이 축이 안 재진다
   *   (변이 구멍 2건 중 2). 장식이 실제로 사는 자리는 **드러내기 표시**다: 안 벗기면
   *   board.js 의 완료의심 목록이 `✅**착지**` 로 떠서 읽는 사람이 낱말을 못 고른다. */
  assert.strictEqual(보드.상태첫구절(줄('✅**착지** `79ae8335`')), '착지** `79ae8335`');
});

/* ── ② 대기 줄은 완료로 접히지 않는다 (조용한 누수 방지) ──────────────────── */

for (const [기호, 뜻] of Object.entries(보드.대기기호())) {
  test(`☠️ ${기호} 가 붙은 「착지」 줄은 **활성**이다 — ${뜻} (접으면 조용히 아카이브로 나간다)`, () => {
    const l = 줄(`${기호}**v1.0 착지** — 유호님 픽 대기`);
    assert.strictEqual(보드.대기행(l), true, '먼저 대기 줄로 읽혀야 한다');
    assert.strictEqual(보드.활성행(l), true, `${기호} 는 완료 낱말을 이긴다`);
    assert.strictEqual(보드.완료행(l), false, '완료행이 되면 보드수거가 가져간다');
  });
}

test('🔑 대기 보호는 `대기행` 하나에서 파생한다 — 기호를 두 곳에 적으면 그날 갈라진다', () => {
  /* 판정 정본이 하나임을 «행동»으로 못박는다: 대기기호 전량이 그대로 활성 보호를 받는다. */
  const 전부 = Object.keys(보드.대기기호());
  assert.ok(전부.length > 0, '대기기호가 비면 이 보호는 통째로 죽는다');
  for (const 기호 of 전부) {
    assert.strictEqual(보드.활성행(줄(`${기호} 종결`)), true, `${기호} — 완료 어휘 전반에 걸려야 한다`);
  }
});

/* ── ③ 완료의심 — 막지 않고 드러내기만 ─────────────────────────────────── */

test('☠️ 완료의심이 「해소」를 잡는다 — 완료 어휘가 낡으면 시끄러워야 한다', () => {
  const l = 줄('전파 1→7 · F498 해소**');
  assert.strictEqual(보드.활성행(l), true, '판정은 그대로 활성이다(의심은 판정을 안 바꾼다)');
  assert.strictEqual(보드.완료의심(l), true);
});

test('☠️ 완료의심은 **이미 완료로 읽는 낱말**을 안 집는다 — 집으면 매주 같은 줄이 떠서 배경이 된다', () => {
  assert.strictEqual(보드.완료의심(줄('✅**착지** `79ae8335`')), false);
  for (const w of 보드.활성어휘().완료) {
    assert.ok(!보드.완료의심어휘().includes(w), `의심 어휘에 완료 어휘 「${w}」 가 섞였다`);
  }
});

test('🔑 완료의심은 완료행·대기행·유령을 안 집는다 — 대상은 «활성인 데이터 행»뿐이다', () => {
  assert.strictEqual(보드.완료의심(줄('✅**종결**')), false, '완료행은 이미 제대로 읽힌 줄이다');
  assert.strictEqual(보드.완료의심(줄('⏳ F498 해소')), false, '대기는 「못 닫는 줄」이지 낡음이 아니다');
  assert.strictEqual(보드.완료의심('| 08-17 | 트랙 | 파일 | F498 해소 |'), false, '유령(날짜 규격 밖)은 대상이 아니다');
  assert.strictEqual(보드.완료의심('그냥 글줄'), false);
});

test('🔑 완료의심은 **아무것도 막지 않는다** — 활성/완료 판정과 독립이다', () => {
  const l = 줄('전파 1→7 · F498 해소**');
  const 전 = { 활성: 보드.활성행(l), 완료: 보드.완료행(l), 대기: 보드.대기행(l) };
  보드.완료의심(l);
  assert.deepStrictEqual({ 활성: 보드.활성행(l), 완료: 보드.완료행(l), 대기: 보드.대기행(l) }, 전);
});

/* ── ④ 실저장소 — 불변식만(거짓양성 0). 건수는 안 못박는다 ──────────────── */

test('☠️ 실저장소 불변식 — 대기 줄(⏳·⏸)이 완료행인 것은 **하나도 없다**', () => {
  const 줄들 = 보드.줄들(REPO) || [];
  if (!줄들.length) return;                       // 못 읽었으면 판정하지 않는다(0건이 아니다 · F207)
  const 샌것 = 줄들.filter((r) => 보드.대기행(r.줄) && 보드.완료행(r.줄))
    .map((r) => `${r.파일}:${r.줄번호}`);
  assert.deepStrictEqual(샌것, [], '대기 줄이 완료로 접혔다 — 보드수거가 조용히 가져간다');
});

test('🔑 실저장소 불변식 — 완료의심은 활성 줄의 부분집합이다(줄을 지어내지 않는다)', () => {
  const 줄들 = 보드.줄들(REPO) || [];
  if (!줄들.length) return;
  const 의심 = 줄들.filter((r) => 보드.완료의심(r.줄));
  for (const r of 의심) {
    assert.strictEqual(보드.활성행(r.줄), true, `${r.파일}:${r.줄번호} — 의심은 활성 줄만 대상이다`);
    assert.strictEqual(보드.대기행(r.줄), false, `${r.파일}:${r.줄번호} — 대기 줄은 대상이 아니다`);
  }
});

/* ── ⑤ 배선 — 함수가 «있는 것»과 «불리는 것»은 다르다 ────────────────────
 * F547 이 정확히 이 자리에서 났다: 회귀 32건이 함수는 검사했는데 그 함수를 부르는 한 줄을
 * 지워도 전부 초록이었다. 이 저장소가 반복해 적어 둔 조항 그대로다 —
 * **「스스로 발화하지 않는 장치는 안 돈다」**. 그래서 판정이 아니라 **출력**으로 못박는다. */

test('☠️ 배선 — board.js 가 실제로 완료의심을 드러낸다(함수만 있고 안 불리면 이 장치는 없는 것이다)', () => {
  const root = 저장소({ '0badc0de': 머리 + 줄('전파 1→7 · F498 해소**') + '\n' });
  const r = 띄우기(root);
  assert.match(String(r.stderr), /완료의심/, 'board.js 가 의심을 드러내야 한다');
});

test('☠️ 배선 — 의심이 없으면 **아무 말도 안 한다** (헛경고가 상시면 그 줄은 배경이 된다)', () => {
  const root = 저장소({ '0badc0de': 머리 + 줄('▶작업중 (`local_deadbeef`) — 3회차') + '\n' });
  const r = 띄우기(root);
  assert.ok(!/완료의심/.test(String(r.stderr)), `조용해야 하는데 말했다: ${String(r.stderr).slice(0, 200)}`);
});

test('🔑 배선 — 의심은 **stderr 로만** 간다 (이 표를 파싱하는 자리가 넷이다)', () => {
  const root = 저장소({ '0badc0de': 머리 + 줄('전파 1→7 · F498 해소**') + '\n' });
  const r = 띄우기(root);
  assert.ok(!/완료의심/.test(String(r.stdout)), 'stdout 에 한 글자라도 붙으면 파싱하는 쪽이 새 줄을 만난다');
});
