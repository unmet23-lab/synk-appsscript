/* 놓은 줄 표식 — 「분모를 보고하면 그 글자가 표식이 된다」 (F612 · 2026-08-18)
 *
 * 무엇이 났나: 어느 세션이 자기 상태 칸에 실측 분모를 적었다 —
 *   `✅①분모 실측: 열림 10 = **남이 잡음 4** + 🎫1 + 빈자리 5`
 * 「🎫1」은 «놓인 줄이 1건이다»라는 **보고**인데 `놓은줄()` 은 그것을 「이 트랙을 놓았다」로 읽었다.
 * 그러면 그 세션의 **활성 트랙이 「집어도 되는 자리」로 보이고**, 남이 그 위에 선언해도
 * board-guard 가 안 막는다 — F610 이 막으려던 중복 구현의 문이 그대로 열린다.
 *
 * 🔑 **새는 방향은 「연다」다.** 그래서 좁히는 쪽이 안전해 보이지만, 좁히다 정상 용례를 죽이면
 *   이번엔 「놓아 줬는데 아무도 못 집는다」가 되고 그건 더 조용하다. 그래서 **먼저 셌다** —
 *   전수 1092 표줄 · 상태칸 🎫 스팬 75 = 정상 72 · 부정 1 · 셈 1 · 인용 1 (2026-08-18).
 *   신고문의 첫 처방(㉠ 「첫 구절의 🎫 만 표식」)은 그 셈이 죽였다: 첫 구절은 5뿐이라 **70건을 죽인다.**
 *
 * 🔑 그리고 급소는 판정이 아니라 **발생원**이었다 — 「🎫N」을 만들어 낸 것은 사람이 아니라
 *   도구의 보고문이다(`friction.js --open` 의 `🎫놓임 N` 등). 그 자리에서 표식 글자를 뺐다.
 *   ⑤ 가 그 규약을 기계로 지킨다 — 산문으로 적으면 다음 사람이 모른다(신고문 ㉡ 이 그렇게 기각됐다).
 *
 * ⚠ 탐지력은 픽스처가 진다(맹점 ② · F296). 실저장소 갈래는 «건수»를 안 박는다 — 그 수는 그날
 *   보드에 달렸다. 대신 **불변식**을 본다(표식 뒤가 수면 놓음이 아니다).
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..');
const 보드 = require(path.join(REPO, 'tools', 'lib', '보드.js'));
const 표 = require(path.join(REPO, 'tools', 'lib', '표.js'));

const 줄 = (상태) => `| 2026-08-18 | **어떤 트랙** | 만지는 파일 | ${상태} |`;

/* ── ① 신고된 그 줄 ─────────────────────────────────────────────────────── */

test('🔴 F612 그 줄 — 상태 칸의 「🎫1」은 «보고»지 «놓았다»가 아니다', () => {
  const 상태 = '✅①분모 실측: 열림 10 = **남이 잡음 4** + 🎫1 + 빈자리 5';
  assert.strictEqual(보드.놓은줄(줄(상태)), false,
    '내 활성 트랙이 「집어도 되는 자리」로 보인다 — F610 이 막으려던 중복 구현의 문이 열린다');
});

/* ── ② 셈 갈래 — 표식 뒤가 수 ───────────────────────────────────────────── */

for (const 상태 of [
  '✅**종결** — 표 17줄 중 14줄이 마감한 주인의 것**(🎫 6) · 회귀 7',
  '실측: 🎫3 · 빈자리 5',
  '열림 10 = 🎫 12건 + 나머지',
]) {
  test(`🔴 셈은 표식이 아니다 — ${상태.slice(0, 34)}…`, () => {
    assert.strictEqual(보드.놓은줄(줄(상태)), false);
  });
}

/* ── ③ 인용 갈래 — 백틱이 «양쪽»을 감쌀 때만 ────────────────────────────── */

test('🔴 백틱에 싸인 표식은 글자를 «이름으로 부르는» 것이다', () => {
  assert.strictEqual(보드.놓은줄(줄('새 JS 0개 · `🎫`=이어받기 금지의 유일한 예외 · 회귀 5')), false);
});

test('한쪽만 백틱이면 여전히 표식이다 — 좁히기가 새어 나가면 놓아 준 자리가 잠긴다', () => {
  assert.strictEqual(보드.놓은줄(줄('✅종결 · `abc1234` 🎫 다음=이어받아라')), true);
});

test('🔴 «앞»에만 백틱이 붙은 것은 인용이 아니다 — 이 저장소의 조밀한 표기가 그 모양이다', () => {
  /* 백틱 «양쪽»을 다 보지 않고 앞만 보면, 해시 인용에 표식이 바로 붙은 정상 줄이 통째로 죽는다.
   * 이 저장소는 `` `abc1234` `` 뒤에 곧바로 이어 쓰는 표기가 흔하다 — 그때 놓아 준 자리가 잠긴다.
   * (변이 M4 가 이 자리를 뚫고 살아남아 추가한 못이다 · 2026-08-18) */
  assert.strictEqual(보드.놓은줄(줄('✅종결 `abc1234`🎫**다음=이어받아라**')), true);
  assert.strictEqual(보드.놓은줄(줄('✅종결 `abc1234`🎫 잔여=재배포 1회')), true);
});

/* ── ④ 정상 용례 72건의 «모양»은 그대로 산다 (좁히기가 넘치지 않는다) ────── */

for (const 상태 of [
  '🎫**다음=이어받아라** — 실측만 하고 안 잡는다',
  '✅종결 · 🎫 잔여=재배포 뒤 1회 실행',
  '🎫**남은 3=`보드근거.js` 외** · CI 0fail',
  '🎫 해소',
  '🎫골든왕복 ⑤ 부활(38/39)',
  '🎫**이어받아도 된다** — 실측만 하고 안 잡는다',
  '✅**종결** · 🎫**PR #25 미머지 = 다음 주자 몫**',
]) {
  test(`정상 용례는 그대로 놓음이다 — ${상태.slice(0, 30)}…`, () => {
    assert.strictEqual(보드.놓은줄(줄(상태)), true, '놓아 준 자리가 잠기면 「집을 것이 없다」가 만들어진다');
  });
}

test('부정(「🎫없음」)은 옛 판 그대로 놓음이 아니다 — 이 트랙이 그 갈래를 안 건드렸다', () => {
  assert.strictEqual(보드.놓은줄(줄('완료∩주인없음∩**🎫없음** · 🆕F372 열림')), false);
});

test('한 칸에 «보고»와 «진짜 표식»이 같이 있으면 표식이 이긴다 — 하나만 살아 있어도 놓은 줄이다', () => {
  assert.strictEqual(보드.놓은줄(줄('실측 🎫3 · 🎫**다음=이어받아라**')), true);
});

/* ── ⑤ 발생원 래칫 — 도구가 「표식 + 수」를 다시 만들어 내지 못한다 ────────
 *
 * 🔑 이게 이 트랙의 진짜 처방이다. 사람이 「🎫1」을 지어낸 게 아니라 **도구가 그 문자열을
 *   내밀었고** 사람이 옮겨 적었다(F612 가 「신설 장치가 이 사각의 발생률을 올렸다」고 적은 그것).
 *   래칫 키는 **소스 내용**이다 — 행번호로 걸면 무관한 편집마다 운다(F618).
 * ⚠ 대가: 주석에서 그 사연을 설명하는 자리는 위반이 아니다(자기 처방을 막으면 F103). 코드만 본다. */

const 보고도구 = ['tools/friction.js', 'tools/대기열.js', 'tools/board.js', 'tools/보드수거.js'];

/* 주석 제거는 통로가 하나다(F401·#Q114) — 지역 사본은 저마다 다르게 틀린다.
 * 🔑 여기선 `코드만` 이다(리터럴을 **살린다**): 이 검사의 바늘 `🎫+수` 는 도구가 **내미는 글**,
 *   즉 문자열 리터럴 «안»에 산다. `부름만` 을 쓰면 바로 그 바늘을 눕혀 검사가 영원히 초록이 된다.
 * ⚠ 옛 지역 사본의 주석은 「주석·**문자열** 안의 설명을 지운다」고 적었지만, 그 정규식은
 *   `(^|[^:])\/\/` 라 `://` 만 지켰을 뿐 문자열은 손도 안 댔다 — 설명과 코드가 갈라져 있었다. */
const { 코드만, 파일소스 } = require('./lib/소스검사.js');

/** 「표식 + (수 또는 보간)」의 인접 — 이게 붙여넣기로 표식이 되는 모양이다. */
const 발생원RE = /🎫[\s*`_]{0,3}(\d|\$\{)/;

test('🔴 보고 도구가 «표식 + 수»를 내밀지 않는다 — 붙여넣으면 그 자리에서 놓음 표식이 된다', () => {
  for (const 상대 of 보고도구) {
    const 코드 = 코드만(파일소스(path.join(REPO, 상대)));
    const m = 발생원RE.exec(코드);
    assert.strictEqual(m, null,
      `${상대} 가 표식에 수를 붙여 낸다(${m && JSON.stringify(m[0])}) — 사람이 그것을 상태 칸에 옮기면 F612 가 재발한다.`
      + ' 셈 칸에서는 표식 글자를 빼고 낱말로 적는다(예: 「놓임 3」).');
  }
});

test('🔑 래칫이 실제로 그 형태를 잡는다 — 탐지력을 픽스처로 못박는다(안 도는 검사는 초록과 같은 모양이다)', () => {
  assert.ok(발생원RE.test('`  =  🔒남이 잡음 ${a} · 🎫놓임 ${b}`') === false,
    '이 문자열은 표식과 수 사이에 낱말이 있어 «인접»이 아니다 — 아래 둘이 진짜 과녁이다');
  assert.ok(발생원RE.test('`🎫 ${r.티켓.length}건은 남겼다`'), '옛 보드수거 형태를 놓쳤다');
  assert.ok(발생원RE.test('`🎫3건`'), '숫자 직결 형태를 놓쳤다');
});

/* ── ⑥ 실저장소 — 불변식만 (건수는 그날 보드에 달렸다 · F296) ──────────── */

test('실저장소 — 표식 뒤가 수인 상태 칸은 하나도 놓음이 아니다 (건수는 안 박는다)', () => {
  const dir = path.join(REPO, 'docs', '_ops', '보드');
  if (!fs.existsSync(dir)) return;                          // 못 읽으면 skip — fail 이 아니다
  /* 🔑 **아카이브까지 읽는다** — 세션별 조각에는 «도는» 줄만 남고(오늘 61), 이 표식이 실제로
   *   쌓인 곳은 마감된 줄이다(아카이브 포함 1092 · 2026-08-18 실측). 조각만 보면 분모가 한 줌이라
   *   「위반 0」이 초록과 같은 모양이 된다(F207). */
  const 판들 = fs.readdirSync(dir).filter((x) => x.endsWith('.md')).map((f) => path.join(dir, f));
  const 아카이브 = path.join(REPO, 'docs', '세션보드_아카이브.md');
  if (fs.existsSync(아카이브)) 판들.push(아카이브);
  let 본줄 = 0;
  for (const f of 판들) {
    for (const l of fs.readFileSync(f, 'utf8').split('\n')) {
      if (!보드.표줄(l)) continue;
      본줄 += 1;
      const 칸 = 표.칸나누기(l);
      const st = String(칸[칸.length - 1] || '');
      for (let i = st.indexOf('🎫'); i >= 0; i = st.indexOf('🎫', i + 1)) {
        if (!/^[\s*`_」\]]*\d/.test(st.slice(i + 2))) continue;
        /* 이 스팬은 «보고»다 — 다른 스팬이 진짜 표식이면 줄은 여전히 놓음일 수 있으니
         * 줄 전체가 아니라 **이 스팬만** 떼어 본다(분모를 안 흐린다). */
        const 홀로 = `| 2026-08-18 | **트랙** | 파일 | ${st.slice(i, i + 24)} |`;
        assert.strictEqual(보드.놓은줄(홀로), false, `셈이 표식으로 읽힌다: ${st.slice(i, i + 40)}`);
      }
    }
  }
  assert.ok(본줄 > 200, `표줄을 ${본줄}개만 봤다 — 분모가 한 줌이면 「위반 0」은 초록과 같은 모양이다(F207)`);
});
