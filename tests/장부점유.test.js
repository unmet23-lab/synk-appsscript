test('🔴 [F619·F612] 분모 줄에 **놓음 표식 글자 자체를 안 쓴다** — 보드에 옮겨 적히면 그 줄이 「놓았다」가 된다', () => {
  /* 이 줄은 사람이 보드 상태 칸에 그대로 옮겨 적는 재료다. F612 실측: 보고문에 적은 「🎫1」을
   * `놓은줄()` 이 표식으로 읽어 방금 선언한 트랙이 「집어도 된다」로 나왔다.
   *
   * ⚠ **처음엔 `놓은줄()` 로만 걸었다가 변이가 그 검사를 뚫었다** — `🎫4` 처럼 숫자가 붙은 꼴은
   *   `놓음셈RE` 가 이미 「보고지 표식이 아니다」로 걸러 준다. 즉 그 단정은 내 함수가 아니라
   *   **남의 가드**를 재고 있었고, 그래서 내 문장을 어떻게 망가뜨려도 초록이었다(못 실패하는 검사).
   *   그래서 잣대를 바꾼다: 표식 **글자 자체가 0개**여야 한다. 이건 내 문장에 대한 단정이고,
   *   상위 가드의 예외 규칙(숫자·부정어·인용)에 기대지 않는다 — 그 규칙이 바뀌어도 안 흔들린다. */
  for (const 분모 of [null, { 로컬: 0, 원격: 0, 훑음: 0 }, { 로컬: 2, 원격: 3, 훑음: 4 }]) {
    const 글 = f.가지분모줄(분모);
    assert.ok(!글.includes('🎫'),
      `🔴 분모 줄에 놓음 표식이 들어갔다 — 상위 가드의 예외에 기대는 순간 그 예외가 바뀌는 날 샌다: ${글}`);
    /* 둘째 벨트 — 실제로 보드 줄에 넣어도 「놓임」으로 안 읽힌다(위 단정이 참이면 자동이지만,
     * 표식이 🎫 말고 더 생기는 날 이쪽이 먼저 운다). */
    assert.ok(!보드.놓은줄(`| 2026-08-18 | 트랙 | 파일 | ${글.replace(/\n/g, ' ')} |`),
      `🔴 이 문장이 보드 상태 칸에 들어가면 「놓임」으로 읽힌다(F612): ${글}`);
  }
});

