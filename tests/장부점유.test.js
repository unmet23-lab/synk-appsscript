/* ── 🔴 실 저장소 — 거짓양성만 본다(탐지력은 위 픽스처가 진다) ── */
test('🔴 실 저장소 — 점유 갈래의 합이 열림 건수와 같다 (분모가 새면 여기서 걸린다)', () => {
  const rows = f.read().rows.filter(f.열렸나);
  const r = f.점유(rows.map((x) => x.id));
  if (r.모름) {
    console.log(`  ❔ 점유를 못 쟀다(${r.못본층.join(' · ')}) — 이 판은 미측정이다(F207).`);
    return;   // repo 밖 환경(git 못 부름)에서 fail 아닌 skip 으로 드러낸다(F296)
  }
  const 셈 = f.점유셈(r.표, rows.length);
  assert.ok(rows.length > 0, `열림이 ${rows.length}건이다 — 장부를 못 읽었으면 아래 0 은 통과가 아니다`);
  assert.strictEqual(셈.잡힘 + 셈.놓임 + 셈.내줄 + 셈.빈자리, rows.length);
  for (const [id, v] of r.표) {
    assert.ok(['잡힘', '놓임', '내줄'].includes(v.상태), `${id} 의 갈래가 규격 밖이다: ${v.상태}`);
    if (v.상태 === '잡힘') assert.ok(v.자리.length, `${id} 를 잡혔다고 하면서 어디인지 안 낸다`);
  }
});

test('🔴 실 저장소 — 활성줄전량이 메인과 가지를 실제로 둘 다 싣는다 (한쪽만 실으면 조용히 반쪽이 된다)', () => {
  const r = 보드.활성줄전량(REPO);
  if (r.모름) { console.log(`  ❔ 못 훑었다(${r.못본층.join(' · ')}) — 미측정(F207).`); return; }
  assert.ok(r.줄들.length > 0, '활성 줄이 0이면 점유 판정이 통째로 눈이 먼 것이다(F207)');
  for (const x of r.줄들) assert.ok(보드.활성행(x.줄), '완료·대기 줄이 섞였다 — 활성 거르기가 안 돌았다');
});
