/* ── 가지 분모의 인쇄기 (F619 남은 일 · 2026-08-18) ────────────────────────────
 *
 * F619 를 고칠 때 `가지끝()` 이 로컬+원격을 다 훑게 하고 분모 `{로컬, 원격, 훑음}` 도 돌려주게
 * 했지만, **그 값을 화면에 내는 소비자가 0이었다.** 안 읽히는 분모는 없는 것과 같고, 그러면
 * 「원격 가지를 하나도 안 봤다」와 「원격 가지가 없다」가 출력에서 여전히 같은 모양이다 —
 * 위 `점유셈` 의 「집을 수 있는 것 N」이 그 둘 다에서 똑같이 나온다. 여기서 그 자리를 판다.
 *
 * 🔑 재는 것은 문구가 아니라 **셋이 서로 다른 말을 하는가**다: 안 쟀다(`null`) · 훑었다(>0) ·
 *   0개 훑었다. 셋이 같은 문장이면 이 줄은 없는 것과 같다. */

test('🔴 [F619] 「안 쟀다」와 「0개 훑었다」가 **다른 말**이다 — 같으면 이 줄은 없는 것과 같다', () => {
  const 안잼 = f.가지분모줄(null);
  const 영 = f.가지분모줄({ 로컬: 0, 원격: 0, 훑음: 0 });
  const 있음 = f.가지분모줄({ 로컬: 1, 원격: 7, 훑음: 8 });
  assert.strictEqual(new Set([안잼, 영, 있음]).size, 3,
    `🔴 세 상태가 문장에서 안 갈렸다:\n  안잼: ${안잼}\n  영: ${영}\n  있음: ${있음}`);
  assert.match(안잼, /안 쟀다/);
  assert.doesNotMatch(안잼, /\b0개\b/,
    '🔴 「안 쟀다」를 「0개」로 적었다 — 이 함수가 없애려는 병을 자기가 낸다(F207)');
});

