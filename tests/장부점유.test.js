test('🔴 [F619 배선] 실 저장소 — `--open` 머리줄이 「집을 수 있는 것」 **바로 아래**에 분모를 낸다', () => {
  /* 장치와 그 발동 조건은 같은 커밋에서 정한다(CLAUDE.md 신뢰성) — 순수 함수만 세우고 CLI 가
   * 안 부르면 위 검사들은 전부 초록인데 화면엔 아무것도 안 나온다.
   * ⚠ 두 줄이 «붙어» 있어야 한다: 떨어뜨려 두면 읽는 사람이 안 잇고, 안 이어진 분모는 없는 분모다. */
  const { execFileSync } = require('node:child_process');
  let out;
  try {
    out = execFileSync(process.execPath, [path.join(REPO, 'tools', 'friction.js'), '--open'],
      { encoding: 'utf8', timeout: 60000 });
  } catch (e) { out = String((e && e.stdout) || ''); }
  assert.ok(out, 'CLI 를 못 띄웠다 — 빈 출력을 통과로 접지 않는다(F207)');
  const 줄들 = out.split('\n');
  const i = 줄들.findIndex((l) => /집을 수 있는 것|점유를 \*\*못 쟀다\*\*/.test(l));
  assert.ok(i >= 0, `머리줄을 못 찾았다 — 이 검사가 무엇을 재는지 모르는 상태다:\n${줄들.slice(0, 5).join('\n')}`);
  assert.match(줄들[i + 1] || '', /훑은 가지/,
    `🔴 분모가 머리줄 바로 아래에 없다: ${JSON.stringify(줄들.slice(i, i + 3))}`);
});
