/* 대기열 점유 판정 — 「이 줄을 **지금** 누가 잡고 있나」 회귀 (F406).
 *
 * 이 검사가 지키는 것: **줄머리 표식을 「지금 집을 수 있음」의 근거로 쓰지 않는다.**
 * 2026-08-13 실측 — 대기열 줄50 이 〖지금〗 초록으로 떠 있었고 세션 `eaa21f3f` 가 이미 그 일감을
 * 잡고 있었다. 옛 대조는 **씨앗 12자 substring** 하나뿐이라 트랙 이름이 갈리면 눈이 멀었고,
 * 트랙 이름은 회차가 돌 때마다 갈린다. 새는 방향이 「집으라고 부른다」라 제일 나쁘다.
 *
 * 탐지력은 픽스처가 진다 — 실저장소는 그날 보드에 따라 답이 바뀌므로 여기서 **거짓양성만** 본다
 * (CLAUDE.md 가드 맹점 ②: 버그가 아직 있을 것을 요구하는 회귀를 쓰지 않는다).
 */
const { test } = require('node:test');
const assert = require('node:assert');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const 큐 = require(path.join(ROOT, 'tools', '대기열.js'));

/** 보드 표의 한 줄을 **진짜 파서로** 넣는다 — 모양을 손으로 베끼면 파싱은 한 번도 안 검사된다. */
const 보드줄 = (트랙, 파일칸, 상태 = '🔵착수') => 큐.행(`| 2026-08-13 | **${트랙}** | ${파일칸} | ${상태} |`);
const 큐줄 = (본문, 줄번호 = 36, 층 = 'P1') => ({ 본문, 줄번호, 층 });

// ───────────────────────────────── 탐지력 (픽스처)

test('🔑 ① 씨앗 — 트랙 칸에 대기열 문구가 살아 있으면 잡힌다(옛 통로가 그대로 산다)', () => {
  const 행들 = [보드줄('라디오24 Lane B — c11 소개정+승격기', '**as**: `lib/라디오편성.js`')];
  const r = 큐.점유(큐줄('〖지금〗 **라디오24 Lane B — c11 소개정+승격기+소비자**(어쩌고)'), 행들);
  assert.ok(r, '트랙 이름이 그대로인데 못 잡았다 — 옛 통로가 죽었다');
  assert.strictEqual(r.근거, '씨앗');
});

test('🔑 ② 줄 참조 — 보드가 「대기열 P1 줄36」 으로 가리킨 줄은 잡힌다', () => {
  const 행들 = [보드줄('숙제 서클 v9.228 — 배포 검수 차단 3건 수리(대기열 P1 줄36 · 새 선언)', '**as**: `tools/서클조판.js`')];
  const r = 큐.점유(큐줄('〖지금〗 **전혀 다른 이름으로 적힌 옛 대기열 문구**', 36, 'P1'), 행들);
  assert.ok(r, '보드가 줄 번호로 자기 자리를 «스스로 적었는데» 못 읽었다');
  assert.strictEqual(r.근거, '줄참조');
});

test('☠️ ② 층이 어긋난 줄 참조는 안 믿는다 — 대기열이 편집되면 번호가 밀려 엉뚱한 줄을 잠근다', () => {
  const 행들 = [보드줄('남의 트랙(대기열 P2 줄36)', '**as**: `tools/무관.js`')];
  assert.strictEqual(큐.점유(큐줄('〖지금〗 **P1 의 36번째 줄**', 36, 'P1'), 행들), null);
});

test('🔴 ③ 판 꼬리 — `_v5` 를 인용한 대기열 줄과 `_v6` 를 선언한 보드 줄은 **같은 자리다**(F406 그 사고)', () => {
  /* 대기열 줄은 08-12 에 v5 를 적었고 도는 세션은 v6 를 선언한다. 판 꼬리를 안 떼면 원리상 못 만난다. */
  const 행들 = [보드줄(
    '과제선택 6회차 «전건 처분» — 처분표 v6 → 채택분 집행',
    '**as**: `docs/_ops/심문결과/상태기반과제선택_처분표_v6.md` · `docs/상태기반_과제선택_설계.md`',
  )];
  const r = 큐.점유(큐줄('〖지금〗 **상태 기반 과제 선택 — 설계 v2 개정**(처분표 정본 = `docs/_ops/심문결과/상태기반과제선택_처분표_v5.md`)', 50), 행들);
  assert.ok(r, '🔴 트랙 이름이 갈린 점유를 못 봤다 — 이 도구가 그 줄을 «집으라고 부른다»(F406 재발)');
  assert.match(r.근거, /^파일 /);
});

test('🔑 ④ 주인은 **가장 센 신호**가 말한다 — 파일 하나 겹친 남의 트랙이 주인으로 적히면 조용히 틀린다', () => {
  const 행들 = [
    보드줄('파일만 겹치는 남의 트랙', '**as**: `tests/숙제서클.test.js`'),
    보드줄('as 쪽 「부정 단언 × 파일 원문」 — 통로 이식', '**as**: `tools/가드계수.js`'),
  ];
  const r = 큐.점유(큐줄('〖지금〗 **as 쪽 「부정 단언 × 파일 원문」 — 통로 이식**(회귀 `tests/숙제서클.test.js` 도 인용한다)', 73, 'P3'), 행들);
  assert.strictEqual(r.근거, '씨앗');
  assert.match(r.트랙, /부정 단언/, `주인을 틀리게 적었다: ${r.트랙}`);
});

// ───────────────────────────────── 거짓양성 (픽스처) — 빈 자리를 잠그면 「일감이 없다」가 된다

test('☠️ 상태 칸의 **인용**은 선점이 아니다 — 인용을 선언으로 읽으면 근거를 적은 세션이 그 줄을 잠근다', () => {
  /* 실측 2026-08-13: 이 규칙 없이 돌렸더니 상태 칸에 「대기열 줄50」을 근거로 적은 «내» 줄이
   * 그 줄의 점유자로 잡혔다. board-guard ④ 가 같은 자리에서 이미 내린 판정과 같은 규칙이다. */
  const 행들 = [보드줄('전혀 다른 트랙', '**as**: `tools/무관.js`', '🔵착수 — 대기열 P1 줄36 이 〖지금〗 인데 이미 잡혔다 · **숙제 서클 v9.228** 참고')];
  assert.strictEqual(큐.점유(큐줄('〖지금〗 **숙제 서클 v9.228 — 배포 검수 차단**', 36, 'P1'), 행들), null);
});

test('☠️ 홑 이름은 자리가 아니다 — `Code.js` 는 규약상 병행 가능하다(자리로 세면 그 병행이 통째로 막힌다)', () => {
  const 행들 = [보드줄('남의 트랙', '**as**: `Code.js` · `index.ts`')];
  assert.strictEqual(큐.점유(큐줄('〖지금〗 **엔진 손질**(`Code.js` 의 그 함수 · `index.ts`)'), 행들), null);
});

test('☠️ 공용 장부는 자리가 아니다 — 모든 세션이 규약상 만진다(자리로 세면 매 세션 막힌다)', () => {
  const 행들 = [보드줄('남의 트랙', '**as**: `docs/_ops/마찰신호.md` · `docs/_ops/작업대기열.md`')];
  assert.strictEqual(큐.점유(큐줄('〖지금〗 **무엇**(장부 `docs/_ops/마찰신호.md` 에 적는다 · 끝내면 `docs/_ops/작업대기열.md` 갱신)'), 행들), null);
});

test('☠️ 비켜남 표기로 물러난 파일은 자리가 아니다 — 「읽기만」·🚫 을 선점으로 읽으면 비켜난 쪽이 벌을 받는다', () => {
  const 행들 = [보드줄('남의 트랙', '**as**: `docs/상태기반_과제선택_설계.md` 읽기만 · 🚫`tools/대기열.js`')];
  assert.strictEqual(
    큐.점유(큐줄('〖지금〗 **설계 개정**(`docs/상태기반_과제선택_설계.md` · `tools/대기열.js`)'), 행들),
    null,
  );
});

test('☠️ 아무 신호도 없으면 잡히지 않는다 — 「모름」을 「잡혔다」로 접으면 대기열이 통째로 빈다', () => {
  const 행들 = [보드줄('완전히 무관한 트랙', '**as**: `tools/무관.js`')];
  assert.strictEqual(큐.점유(큐줄('〖지금〗 **아무도 안 잡은 일감**', 99, 'P3'), 행들), null);
  assert.strictEqual(큐.점유(큐줄('〖지금〗 **무엇**'), []), null, '보드가 비면 아무것도 안 잡는다');
  assert.strictEqual(큐.점유(큐줄('〖지금〗 **무엇**'), null), null, '보드를 못 읽으면 «못 쟀다» 지 «잡혔다» 가 아니다');
});

// ───────────────────────────────── 실저장소 (거짓양성·분모만)

test('🔑 보드행들 은 배열이거나 null 이다 — 「못 읽음」을 빈 배열로 접으면 전부 «비었다» 가 된다', () => {
  const 행들 = 큐.보드행들();
  if (행들 === null) return;                       // 보드 폴더가 없는 환경(CI·픽스처 저장소)
  assert.ok(Array.isArray(행들));
  assert.ok(행들.length > 0, '활성 줄 0 — 분모 없는 초록이라 통과로 세지 않는다(F207)');
  for (const r of 행들) {
    assert.ok(typeof r.트랙 === 'string' && r.자리 instanceof Set, '행 모양이 갈렸다');
  }
});

test('☠️ 실저장소 — 점유 판정이 열린 항목 **전량**을 잡지는 않는다(전부 잡히면 그건 판정이 아니라 기본값이다)', () => {
  const 전체 = 큐.항목들();
  const 행들 = 큐.보드행들();
  if (전체 === null || 행들 === null || 전체.length < 3) return;
  const 잡힌 = 전체.filter((it) => 큐.점유(it, 행들));
  assert.notStrictEqual(잡힌.length, 전체.length,
    `열린 ${전체.length}건이 전부 «잡혔다» 로 나온다 — 이 판정이 대기열을 통째로 비운다`);
});

test('🔑 실저장소 — 열린 항목 전량이 줄번호를 갖는다(줄 참조 신호의 한쪽이 비면 규약이 있어도 못 읽는다)', () => {
  const 전체 = 큐.항목들();
  if (전체 === null) return;
  const 빠진 = 전체.filter((it) => !Number.isInteger(it.줄번호) || it.줄번호 < 1);
  assert.deepStrictEqual(빠진.map((it) => 큐.씨앗(it.본문)), []);
});
