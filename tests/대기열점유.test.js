test('☠️ 실저장소 — 파일 칸에만 `#Qnn` 이 있는 보드 줄은 그 자리의 «주인»으로 안 적힌다(⓪ 는 트랙 칸만 읽는다)', () => {
  /* 버그가 아직 있을 것을 요구하지 않는다(맹점 ②) — 그런 줄이 오늘 0건이면 검사할 게 없고,
   * 그건 통과다. 있으면 그 ID 로 잡힌 주인이 «그 줄»이 아니어야 한다는 것만 본다. */
  const 전체 = 큐.항목들();
  const 행들 = 큐.보드행들();
  if (전체 === null || 행들 === null) return;
  const 인용행 = 행들.filter((r) => r.큐인용 && r.큐인용.size);
  for (const 행 of 인용행) {
    for (const 키 of 행.큐인용) {
      const 항목 = 전체.find((it) => `#Q${it.id}` === 키);
      if (!항목) continue;                       // 닫힌 번호 — 대기열에 없다
      const p = 큐.점유(항목, 행들);
      assert.notStrictEqual(p && p.근거, 키,
        `${키} 를 «인용»한 줄이 조인으로 주인이 됐다 — 참 주인이 가려진다: ${행.트랙.slice(0, 60)}`);
    }
  }
});

test('🔑 실저장소 — 열린 항목 전량이 줄번호를 갖는다(줄 참조 신호의 한쪽이 비면 규약이 있어도 못 읽는다)', () => {
  const 전체 = 큐.항목들();
  if (전체 === null) return;
  const 빠진 = 전체.filter((it) => !Number.isInteger(it.줄번호) || it.줄번호 < 1);
  assert.deepStrictEqual(빠진.map((it) => 큐.씨앗(it.본문)), []);
});

test('☠️ 실저장소 — 열린 항목 전량이 영구 ID 를 갖고, ID 는 유일하다(누락=조인 사각 · 중복=두 줄이 한 자리)', () => {
  /* 이 검사가 곧 발급 규칙의 **사후** 강제다 — 사전(커밋 자리) 강제는 `tools/대기열채번검사.js` 가
   * 맡고(F461 처방 ㄴ), 판정은 그쪽과 **같은 함수** 하나다: 여기 있던 인라인 사본을 지웠다.
   * 왜 — 사본을 남겨 두면 둘이 갈리고, 갈라지는 방향은 언제나 「통과」다(CLAUDE.md 맹점 ④).
   * 사전 게이트가 있어도 이 검사는 남는다: `--no-verify`·병합·훅 미설치 기계가 실재하고,
   * 그때 마지막으로 잡는 자리가 여기다. */
  const 전체 = 큐.항목들();
  if (전체 === null) { assert.fail('대기열 파일을 못 읽었다 — 0건 초록 금지'); }
  const r = 큐.채번(전체);
  assert.ok(r.분모 > 0, '열린 줄을 0건 셌다 — 초록이 아니라 미실행이다(F207)');
  assert.deepStrictEqual(r.없음.map((it) => `줄${it.줄번호} ${큐.씨앗(it.본문)}`), [],
    `ID 없는 열린 줄 ${r.없음.length}건 — 표식 뒤에 #Q${r.최대 + 1} 부터 단다(재사용 금지)`);
  assert.deepStrictEqual(r.중복.map((d) => `#Q${d.id} (줄${d.먼저} ↔ 줄${d.나중})`), [],
    '같은 ID 가 두 줄에 있다 — 조인이 엉뚱한 줄을 잠근다');
});
