  const 행들 = [
    보드줄('파일만 겹치는 남의 트랙', '**as**: `tools/서클조판.js`'),
    보드줄('완전히 새 이름의 회차 트랙(대기열 #Q49 · 새 선언)', '**as**: `docs/전혀_다른_판.md`'),
  ];
  const r = 큐.점유(큐줄('〖지금〗 #Q49 **상태 기반 과제 선택 — 옛 이름**(`tools/서클조판.js` 인용)', 49, 'P1'), 행들);
  assert.ok(r, '🔴 ID 조인이 죽었다 — 트랙 개명마다 다시 추정으로 떨어진다');
