  const 붙은가지 = new Set(행들.filter((r) => r.출처).map((r) => r.출처.가지));
  for (const r of 기대) {
    assert.ok(붙은가지.has(r.출처.가지), `가지 ${r.출처.가지} 의 선언이 점유 분모에 안 들어갔다 — 그 트랙이 「빈 자리」로 불린다`);
  }
