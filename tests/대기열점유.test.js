/* id 는 본문에서 파생한다 — 진짜 파서(항목들)의 규칙과 같은 모양이고, 그 파서 자체는 아래
 * 실저장소 검사(전량이 정수 id)가 실제 파일로 돌린다. */
const 큐줄 = (본문, 줄번호 = 36, 층 = 'P1') => {
  const idm = /#Q(\d+)(?!\d)/.exec(본문);
  return { 본문, 줄번호, 층, id: idm ? Number(idm[1]) : null };
};

