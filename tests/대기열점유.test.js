/* 대기열 점유 판정 — 「이 줄을 **지금** 누가 잡고 있나」 회귀 (F406).
 *
 * 이 검사가 지키는 것: **줄머리 표식을 「지금 집을 수 있음」의 근거로 쓰지 않는다.**
 * 2026-08-13 실측 — 대기열 줄50 이 〖지금〗 초록으로 떠 있었고 세션 `eaa21f3f` 가 이미 그 일감을
 * 잡고 있었다. 옛 대조는 **씨앗 12자 substring** 하나뿐이라 트랙 이름이 갈리면 눈이 멀었고,
 * 트랙 이름은 회차가 돌 때마다 갈린다. 새는 방향이 「집으라고 부른다」라 제일 나쁘다.
 *
 * 탐지력은 픽스처가 진다 — 실저장소는 그날 보드에 따라 답이 바뀌므로 여기서 **거짓양성만** 본다
 * (CLAUDE.md 가드 맹점 ②: 버그가 아직 있을 것을 요구하는 회귀를 쓰지 않는다).
 */
const { test } = require('node:test');
const assert = require('node:assert');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const 큐 = require(path.join(ROOT, 'tools', '대기열.js'));

/** 보드 표의 한 줄을 **진짜 파서로** 넣는다 — 모양을 손으로 베끼면 파싱은 한 번도 안 검사된다. */
const 보드줄 = (트랙, 파일칸, 상태 = '🔵착수') => 큐.행(`| 2026-08-13 | **${트랙}** | ${파일칸} | ${상태} |`);
/* id 는 본문에서 파생한다 — 진짜 파서(항목들)의 규칙과 같은 모양이고, 그 파서 자체는 아래
 * 실저장소 검사(전량이 정수 id)가 실제 파일로 돌린다. */
const 큐줄 = (본문, 줄번호 = 36, 층 = 'P1') => {
  const idm = /#Q(\d+)(?!\d)/.exec(본문);
  return { 본문, 줄번호, 층, id: idm ? Number(idm[1]) : null };
};

