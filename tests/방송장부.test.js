'use strict';
/* 방송 되살리기의 «장부» 회귀 — 2026-09-08
 *
 * ■ 왜 이 자가 생겼나
 *   같은 날 이 자리가 **두 번** 깨졌고 두 번 다 바깥 검수가 잡았다. 시험이 하나도 없었다.
 *   ① 만든 횟수를 맨 끝에서야 적어서, 그 사이에 넘어지면 «안 센 것»이 됐다(한도 4 인데 6/6).
 *   ② ①을 고치자 그 선계수가 맨 위의 한도 검사와 부딪혀, 만들어 놓고 전환이 한 번 실패하면
 *      **날짜가 바뀔 때까지 되살아나지 못했다**(부모 판은 live 까지 갔는데 고친 판이 ready 에 멈췄다).
 *   ⇒ 두 번 다 «장부와 한도의 관계»였다. 그 관계에 자를 세운다.
 *
 * ■ 어떻게 재나 — 🔴 **소스의 그 줄을 그대로 떼어 태운다.**
 *   `bots/오버레이/방송지킴이.js` 는 맨 위에서 바로 도는 스크립트(async IIFE)라 require 하면
 *   유튜브에 붙으러 간다. 그래서 파일을 고치지 않고, 결정하는 «덩이»만 표식으로 떼어 실행한다.
 *   🚫 여기에 로직을 다시 적지 않는다 — 09-08 에 「복사본을 돌린 시험」이 검수에 잡혔다.
 *      표식이 안 맞으면 이 시험은 조용히 통과하지 않고 그 자리에서 빨개진다.
 *
 * ■ 이 자가 «안» 보는 것 — 먼저 밝힌다
 *   유튜브 API 의 실제 응답·묶기(bind)·전환은 안 본다(실행층이라 서버에서만 드러난다).
 *   여기서 재는 것은 **장부에 무엇이 적히고, 한도가 무엇을 막나** 둘뿐이다.
 */
const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const 소스 = fs.readFileSync(path.join(__dirname, '..', 'bots', '오버레이', '방송지킴이.js'), 'utf8');

/** 소스에서 한 덩이를 표식으로 떼어낸다(시작 표식부터 끝 표식까지 · 끝 표식 포함). */
function 떼기(시작, 끝) {
  const a = 소스.indexOf(시작);
  assert.notStrictEqual(a, -1, `소스에서 「${시작}」 를 못 찾았다 — 표식이 바뀌었으면 이 시험을 같이 고친다`);
  const b = 소스.indexOf(끝, a);
  assert.notStrictEqual(b, -1, `소스에서 「${끝}」 를 못 찾았다`);
  return 소스.slice(a, b + 끝.length);
}

/** 장부에 «한 줄 적는» 덩이 — 소스의 그 블록 그대로. */
const 셈덩이 = () => 떼기(
  'const 이미센것 = (장부.자리들 || []).some',
  "장부.자리들.push({ 때: 이제(), id: 자리.id, 단계: 지금, 다시쓴것: !새로만듦 });",
) + '\n}';

/** 그 덩이를 실제로 돌린다. 장부를 넣으면 바뀐 장부가 나온다. */
function 셈돌리기({ 장부, 자리id, 지금 = 'live', 새로만듦 = false }) {
  const f = new Function('장부', '자리', '지금', '새로만듦', '이제',
    셈덩이() + '\nreturn 장부;');
  return f(장부, { id: 자리id }, 지금, 새로만듦, () => '2026-09-08 21:00:00');
}

/** 한도가 무엇을 막는지 — 그 검사 줄을 소스에서 떼어 조건만 잰다. */
function 한도줄() {
  const 줄 = 소스.split(/\r?\n/).filter((l) => l.includes('장부.연것 >= 한도'));
  assert.strictEqual(줄.length, 1, '한도 검사가 한 곳이 아니다 — 둘이 되면 한쪽만 고쳐진다');
  return 줄[0];
}

/* ── ① 한도가 «만드는 것»만 막는가 ─────────────────────────────────────────── */

test('🔴 한도 검사는 «새로 여는 갈래 안»에 있다 — 되살리기까지 막으면 안 된다', () => {
  /* 09-08 회귀: 검사가 갈래 «밖»(공통 자리)에 있어서, 3/4 에서 하나를 만든 뒤 전환이 한 번
   *   실패하면 그 방송은 이미 4/4 라 날짜가 바뀔 때까지 못 살아났다. */
  const 줄들 = 소스.split(/\r?\n/);
  const i = 줄들.findIndex((l) => l.includes('장부.연것 >= 한도'));
  assert.ok(i > 0, '한도 검사를 못 찾았다');

  /* 그 줄 «위»로 거슬러 올라가며 이 검사를 감싼 것이 「새로 여는 갈래」인지 본다.
   * 되살리는 갈래(안끝난[0] 가 있는 쪽)의 로그 문장이 먼저 나오면 갈래 안에 있는 것이다. */
  const 앞 = 줄들.slice(Math.max(0, i - 8), i).join('\n');
  assert.match(앞, /else \{|되살리기는 한도를 안 본다/,
    '한도 검사가 갈래 밖(공통 자리)에 있다 — 되살리기까지 막힌다(09-08 회귀)');
  assert.match(한도줄(), /되살릴 자리도 0개/,
    '한도에 걸렸을 때의 말이 「되살릴 자리도 없다」를 안 밝힌다 — 사람이 왜 멈췄는지 못 읽는다');
});

/* ── ② 한 자리는 «한 번»만 세는가 ────────────────────────────────────────── */

test('🔴 같은 방송을 여러 번 되살려도 한도는 «한 번»만 먹는다', () => {
  /* 09-08 재검수: 다시 쓸 때마다 또 세서, 같은 방송 하나를 세 번 되살리면 한도가 3 줄었다.
   *   셈의 뜻은 「오늘 몇 개를 만들었나」이지 「몇 번 손댔나」가 아니다. */
  let 장부 = { 날: '2026-09-08', 연것: 0, 자리들: [] };
  장부 = 셈돌리기({ 장부, 자리id: 'AAA', 지금: 'ready', 새로만듦: true });
  assert.strictEqual(장부.연것, 1, '만든 자리를 안 셌다');

  for (let k = 0; k < 3; k++) 장부 = 셈돌리기({ 장부, 자리id: 'AAA', 지금: 'live' });
  assert.strictEqual(장부.연것, 1, '같은 자리를 되살릴 때마다 또 셌다 — 한도가 헛되이 줄어든다');
  assert.strictEqual(장부.자리들.length, 1, '같은 자리가 장부에 여러 줄로 쌓였다');
  assert.strictEqual(장부.자리들[0].단계, 'live', '되살린 뒤 단계가 안 갱신됐다');
});

test('🔑 «다른» 방송은 따로 센다 — 한 번만 세기가 셈을 죽이면 안 된다', () => {
  let 장부 = { 날: '2026-09-08', 연것: 0, 자리들: [] };
  for (const id of ['AAA', 'BBB', 'CCC']) 장부 = 셈돌리기({ 장부, 자리id: id, 새로만듦: true });
  assert.strictEqual(장부.연것, 3, '서로 다른 방송 셋을 하나로 셌다');
  assert.strictEqual(장부.자리들.length, 3);
});

test('🔑 처음 보는 자리를 다시 쓸 때도 한 번은 센다 — 어제 것이 오늘 한도를 안 먹진 않는다', () => {
  /* 장부가 날짜로 새로 나므로, 어제 만든 자리를 오늘 되살리면 오늘 셈에 처음 오른다.
   *   그 자리도 오늘 한 번은 센다 — 그래야 「오늘 몇 개가 도는가」가 맞는다. */
  let 장부 = { 날: '2026-09-08', 연것: 0, 자리들: [] };
  장부 = 셈돌리기({ 장부, 자리id: '어제것', 지금: 'live', 새로만듦: false });
  assert.strictEqual(장부.연것, 1);
  assert.strictEqual(장부.자리들[0].다시쓴것, true, '다시 쓴 것이라는 표시가 없다');
});

/* ── ③ 만든 즉시 적는가 ──────────────────────────────────────────────────── */

test('🔴 새 방송은 «만든 직후» 장부에 적힌다 — 그 뒤에 넘어져도 셈이 남는다', () => {
  /* 09-08 첫 지적: 맨 끝에서 한 번에 적어서, 묶기·전환·표지 중에 넘어지면 그 자리는
   *   「안 센 것」이 됐다. 저절로 끝나면 다음 실행이 또 만들어 한도와 유튜브 몫이 샜다. */
  const 만드는칸 = 떼기('말(`   만들었다 ${자리.id}`);', '말(`   장부에 먼저 적었다');
  assert.match(만드는칸, /장부\.연것 \+= 1;/, '만든 직후에 안 센다');
  assert.match(만드는칸, /fs\.writeFileSync\(장부길/, '만든 직후에 파일로 안 적는다 — 넘어지면 사라진다');
  assert.match(만드는칸, /단계: 'created'/, '만든 직후 줄의 단계가 없다');

  /* 그리고 그 자리는 끝에서 «다시» 세지 않는다(두 번 세면 한도가 반으로 준다). */
  let 장부 = { 날: '2026-09-08', 연것: 1, 자리들: [{ 때: 't', id: 'AAA', 단계: 'created' }] };
  장부 = 셈돌리기({ 장부, 자리id: 'AAA', 지금: 'live', 새로만듦: true });
  assert.strictEqual(장부.연것, 1, '만들 때 세고 끝에서 또 셌다');
  assert.strictEqual(장부.자리들[0].단계, 'live', '끝에서 단계를 안 갈았다');
});

/* ── ④ 묶임을 어느 갈래에서나 재는가 ─────────────────────────────────────── */

/** 묶임을 재고 붙이는 덩이 — 소스의 그 블록 그대로 떼어 «실제로 돌린다». */
function 묶기돌리기({ 지금묶인곳, 스트림id = 'S1', 읽기실패 = false }) {
  const 덩이 = 떼기('let 묶임 = null;', "} else 말('   이미 지금 스트림에 묶여 있다');");
  const 부른것 = [];
  const yt = async (method, url) => {
    부른것.push(method + ' ' + url);
    if (url.indexOf('part=contentDetails') >= 0) {
      if (읽기실패) throw new Error('일부러 낸 오류');
      return { items: [{ contentDetails: { boundStreamId: 지금묶인곳 } }] };
    }
    return {};
  };
  const f = new Function('yt', '자리', '스트림', '말',
    'return (async () => {\n' + 덩이 + '\nreturn 묶임; })();');
  return f(yt, { id: 'B1' }, { id: 스트림id }, () => {})
    .then((묶임) => ({ 묶임, 묶었나: 부른것.some((c) => c.indexOf('/bind?') >= 0), 부른것 }));
}

test('🔴 안 묶인 자리는 «묶는다» — 다시 쓰는 갈래로 와도 마찬가지다', async () => {
  /* 09-08 첫 지적: 새로 만드는 갈래에서만 묶어서, 만든 직후 묶기가 실패하면 그 안 묶인
   *   자리를 계속 다시 집어 들고 전환만 시도하다 실패했다(되살리기가 영영 멈춤).
   * 🔑 이 시험은 «줄이 어디 있나»가 아니라 «묶으러 가나»를 잰다 — 09-08 에 자리만 보다가
   *   `if (false && …)` 변이를 놓쳤다. 자가 결함을 지키던 그 무늬다. */
  const a = await 묶기돌리기({ 지금묶인곳: null });
  assert.strictEqual(a.묶었나, true, '안 묶인 자리인데 묶으러 안 갔다');
});

test('🔴 «다른 곳»에 묶인 자리도 지금 스트림으로 다시 묶는다', async () => {
  const b = await 묶기돌리기({ 지금묶인곳: '옛스트림', 스트림id: 'S1' });
  assert.strictEqual(b.묶었나, true, '남의 스트림에 묶인 채로 두면 전환이 계속 실패한다');
});

test('🔑 이미 «지금 스트림»에 묶였으면 다시 안 묶는다 — 헛일을 안 한다', async () => {
  const c = await 묶기돌리기({ 지금묶인곳: 'S1', 스트림id: 'S1' });
  assert.strictEqual(c.묶었나, false, '이미 묶였는데 또 묶으러 갔다');
});

test('🔑 묶임을 «못 읽었을» 때는 묶어 본다 — 모름을 묶임으로 세지 않는다', async () => {
  const d = await 묶기돌리기({ 지금묶인곳: null, 읽기실패: true });
  assert.strictEqual(d.묶었나, true, '상태를 못 읽었다고 그냥 넘어가면 안 묶인 채로 전환한다');
});
