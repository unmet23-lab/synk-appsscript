/* ── ④ 접기 — 채점이 봉인을 덮지 않는다 ───────────────────────── */

test('채점은 봉인을 덮지 않는다 — 예측 원문이 그대로 남는다', () => {
  const { 목록 } = 접기([
    온전한봉인,
    { 종류: '채점', 지문: 'a1b2c3d4e5', 날짜: '2026-08-18', 판정: '빗나감', 실제: '유지', 인용: '그냥 두자' },
  ]);
  assert.equal(목록.length, 1);
  assert.equal(목록[0].예측, '끈다', '봉인한 예측이 사라지면 이 장부는 사후 합리화가 된다');
  assert.equal(목록[0].판정, '빗나감');
  assert.equal(목록[0].실제, '유지');
  assert.equal(목록[0].인용, '그냥 두자');
});

test('같은 지문을 두 번 봉인하면 «중복»으로 드러난다 — 조용히 덮지 않는다', () => {
  const r = 접기([온전한봉인, { ...온전한봉인, 예측: '유지' }]);
  assert.deepEqual(r.중복, ['a1b2c3d4e5']);
  assert.equal(r.목록[0].예측, '끈다', '먼저 쓴 것이 이긴다 — 나중 것이 덮으면 봉인이 무의미하다');
});

test('모양이 안 적힌 옛 줄은 질문 원문으로 되살린다', () => {
  const { 모양, ...모양없음 } = 온전한봉인;
  const { 목록 } = 접기([모양없음]);
  assert.equal(목록[0].모양, '예아니오');
});

