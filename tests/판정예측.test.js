test('자유서술은 채점돼도 재현율 분모에 안 든다 (①)', () => {
  const g = 집계(접기(집계픽스처).목록);
  assert.equal(g.봉인, 7);
  assert.equal(g.대기, 1);
  assert.equal(g.무효, 1);
  assert.equal(g.자유제외, 1, '자유 1건이 분모 밖으로 빠져야 한다');
  assert.equal(g.분모, 4, '분모 = 닫힌 모양이면서 무효가 아닌 것');
  assert.equal(g.적중, 2);
  assert.equal(g.부분, 1);
  assert.equal(g.빗나감, 1);
  // 합이 맞는가 — 분모가 새면 여기서 먼저 깨진다
  assert.equal(g.적중 + g.부분 + g.빗나감, g.분모);
});

test('축·확신·근거를 따로 센다 — 단일 숫자로는 위임선을 못 긋는다', () => {
  const g = 집계(접기(집계픽스처).목록);
  assert.deepEqual(g.축별.돈, { 분모: 1, 적중: 1 });
  assert.deepEqual(g.축별.취향, { 분모: 2, 적중: 0 });
  assert.deepEqual(g.축별.방향, { 분모: 0, 적중: 0 }, '자유뿐인 축은 분모 0 — 0% 가 아니다');
  assert.deepEqual(g.확신별.상, { 분모: 2, 적중: 2 });
  assert.deepEqual(g.확신별.하, { 분모: 1, 적중: 0 });
  assert.deepEqual(g.근거별.권고있음, { 분모: 1, 적중: 1 });
  assert.deepEqual(g.근거별.추론, { 분모: 3, 적중: 1 });
});

test('분모 0 에서는 퍼센트를 만들지 않는다 (② · F207)', () => {
  const s = 비율(0, 0);
  assert.ok(!s.includes('%'), `0/0 에서 퍼센트가 나왔다: ${s}`);
  assert.ok(s.includes('안 재봤다'), '「안 재봤다」와 「0% 였다」가 같은 모양이면 안 된다');
  assert.equal(비율(1, 2), '1/2 = 50%');
  assert.ok(비율(3, 4).includes('3/4'), '분모를 늘 함께 낸다');
});

test('봉인이 0건이어도 집계가 터지지 않고 분모 0 을 낸다', () => {
  const g = 집계([]);
  assert.equal(g.봉인, 0);
  assert.equal(g.분모, 0);
  assert.equal(비율(g.적중, g.분모).includes('%'), false);
});

/* ── 시점 갈래 — 두 계기가 다른 수를 내면 둘 다 안 믿긴다 ────────── */

test('시점 게이트가 걸린 항목은 봉인 대상에서 빠진다 — 답이 올 리 없다', () => {
  const 지금 = 1000;
  const { 지금배달, 시점대기 } = 시점갈래([
    { 지문: 'a' },
    { 지문: 'b', notBefore: 2000 },
    { 지문: 'c', notBefore: 500 },
  ], 지금);
  assert.deepEqual(지금배달.map((x) => x.지문), ['a', 'c'], '지난 게이트는 지금 배달이다');
  assert.deepEqual(시점대기.map((x) => x.지문), ['b']);
});

/* ── 채점 대기 — 이 장치가 «스스로 발화하는» 유일한 자리 ────────── */

test('봉인했는데 큐에 없는 것만 채점 대기다 — 살아 있는 줄은 안 부른다', () => {
  const 목록 = [
    { 지문: 'a', 판정: '' },          // 큐에 살아 있다 → 아직 아니다
    { 지문: 'b', 판정: '' },          // 큐에서 사라졌다 → 대기
    { 지문: 'c', 판정: '적중' },      // 이미 채점됐다 → 아니다
    { 지문: 'd', 판정: '무효' },      // 이미 처분했다 → 아니다
  ];
  const 대기 = 채점대기(목록, ['a', 'c']);
  assert.deepEqual(대기.map((p) => p.지문), ['b']);
});

test('채점 대기가 0이면 빈 배열이다 — 훅이 조용해야 한다', () => {
  // 상시 뜨는 줄은 배경 소음이 되어 진짜가 섞여도 안 읽힌다.
  assert.deepEqual(채점대기([{ 지문: 'a', 판정: '' }], ['a']), []);
  assert.deepEqual(채점대기([], []), []);
  assert.deepEqual(채점대기(null, null), []);
});

test('숫자 지문이 문자열 지문과 안 어긋난다 — 둘 다 문자열로 맞춘다', () => {
  // jsonl 은 항상 문자열이지만 호출부가 숫자를 넘기면 Set 조회가 조용히 빗나가
  // 「살아 있는 줄」이 채점 대기로 뜬다 — 새는 방향이 「일감이 있다」라 눈에 띄지만 거짓이다.
  assert.deepEqual(채점대기([{ 지문: 12, 판정: '' }], ['12']), []);
});

