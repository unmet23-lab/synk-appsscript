/* 판정예측 회귀 — ⑤층(배우는) 계기. 유호님께 «묻기 전에» 봉인한 답과 그 채점.
 *
 * 탐지력은 **전부 이 픽스처가 진다** — 실제 jsonl·실제 메모리 디렉터리와 무관하게 잡힌다
 * (repo 밖 환경에 기대는 검사는 CI 에서 깨진다 · F296 · CLAUDE.md 신뢰성 조항).
 * 실저장소를 보는 검사는 맨 끝 한 벌뿐이고 그것도 **거짓양성만** 잰다.
 *
 * 못박는 실패 형태 여섯 — 전부 「맞는 얼굴로 틀린 값」 쪽이다(가드 맹점 ④):
 *   ① **분모가 부풀려지는 것** — 자유서술을 재현율에 세면 「부분 적중」이 마음대로 늘어난다.
 *      이 계기의 유일한 산출이 숫자 하나라, 분모가 새면 계기 전체가 거짓말이 된다.
 *   ② **분모 0 에서 퍼센트가 나오는 것** — 0/0 을 100% 로도 0% 로도 쓰면 «안 재봤다»가
 *      «쟀다»로 보인다(F207).
 *   ③ **모양 판정이 닫힌 질문을 자유로 흘리는 것** — 첫 판 정규식이 실제로 그랬다(실측 08-17:
 *      「붙일까요」·「켤까요」·「30 vs 40」을 흘려 18%, 다음 판은 「-ㄹ지」를 흘려 41%.
 *      이 회귀가 둘 다 잡은 뒤 **51%**). 새는 방향이 「잴 게 없다」라 **조용하다**.
 *   ④ **채점이 봉인을 덮어써서 «원래 뭐라 했는지»가 사라지는 것** — append-only 를 읽는 층에서
 *      접는다. 덮이면 이 계기는 사후 합리화 장부가 된다.
 *   ⑤ **인용 없는 채점** — 재현율은 내가 나를 채점하는 숫자다. 원문 인용이 필수가 아니면
 *      관측이 아니라 자평이고, 메모리가 지목한 「아첨으로 수렴」이 정확히 여기서 샌다.
 *   ⑥ **자기 처방을 막는 것**(맹점 ③) — 거절 메시지가 시키는 대로 채우면 통과해야 한다.
 *
 * ⚠ 이 회귀가 **못 잡는 것**을 적어 둔다: 「봉인한 예측이 정직한가」는 원리상 기계가 못 본다.
 *   기계가 지는 몫은 셋뿐 — ⓐ답이 온 뒤엔 못 봉인하게 ⓑ봉인을 못 고치게 ⓒ분모를 못 부풀리게.
 */
