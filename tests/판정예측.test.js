/* ── 실저장소 — 거짓양성만 잰다 ───────────────────────────────── */

test('[실저장소] 장부가 있으면 전부 읽히고 지문 중복이 없다', () => {
  const fs = require('node:fs');
  const { 정본경로 } = require('../tools/판정예측.js');
  if (!fs.existsSync(정본경로)) return; // 아직 안 쓴 판 — 미실행을 통과로 접지 않게 이 줄이 사유다
  const r = 접기(파싱(fs.readFileSync(정본경로, 'utf8')));
  assert.deepEqual(r.깨짐, [], '읽지 못한 줄이 있으면 그만큼 장부가 조용히 준 것이다');
  assert.deepEqual(r.중복, [], '같은 질문이 두 번 봉인됐다');
  for (const p of r.목록) {
    assert.ok(축값.includes(p.축), `모르는 축: ${p.축} (${p.지문})`);
    assert.ok(String(p.왜 || '').trim(), `「왜」가 빈 봉인: ${p.지문}`);
    if (p.판정 && p.판정 !== '무효') {
      assert.ok(String(p.인용 || '').trim(), `인용 없는 채점: ${p.지문} — 자평은 관측이 아니다(⑤)`);
    }
  }
});
