/* [2026-08-04] 파생② 전파 가드 — 개통 문서의 주제 수가 라이브 지식과 어긋나지 않는다.
 * 실사고: 그 문서가 오래 「12주제」로 적혀 있었는데 [v9.165]가 FAQ 9건을 승격해 **라이브는 21주제**였다.
 * 유호님은 그 문서를 보고 봇 능력을 판단하시는데, 9개를 못 하는 줄 알고 계셨던 셈이다.
 * 아무도 기계로 안 보고 있어서 생긴 표류다 — 이 저장소의 만성 실패(「정본 개정이 파생에 전파 안 된다」).
 * 🔑 문구가 아니라 **숫자**를 잠근다: 지식에 항목을 더하면 이 테스트가 빨개지고, 문서를 고쳐야 풀린다. */
test('[2026-08-04] ⑤ 개통 문서의 주제 수가 라이브 지식과 일치한다', () => {
  const 문서 = fs.readFileSync(path.join(ROOT, 'docs', '상담AI_개통_지금할일.md'), 'utf8');
  const 항목 = [...지식.matchAll(/주제:\s*'([^']+)',\s*확정:\s*(true|false)/g)];
  const 확정 = 항목.filter((m) => m[2] === 'true').length;
  const 인계 = 항목.filter((m) => m[2] === 'false').length;
  assert.ok(확정 > 0 && 인계 > 0, '지식에서 주제를 하나도 못 읽었다 — 패턴이 깨졌으면 이 테스트부터 고쳐라');

  const 답 = 문서.match(/답합니다 \((\d+)주제\)/);
  const 넘 = 문서.match(/넘깁니다 \((\d+)주제\)/);
  assert.ok(답 && 넘, '개통 문서에서 「답합니다 (N주제)」·「넘깁니다 (N주제)」 표기를 못 찾았다');
  assert.equal(Number(답[1]), 확정,
    `개통 문서는 답하는 주제를 ${답[1]}개로 적었는데 라이브 지식은 ${확정}개다 — 유호님이 봇 능력을 잘못 안다`);
  assert.equal(Number(넘[1]), 인계,
    `개통 문서는 넘기는 주제를 ${넘[1]}개로 적었는데 라이브 지식은 ${인계}개다`);
});
