'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const load = game => {
  const context = vm.createContext({ console });
  vm.runInContext(fs.readFileSync(path.join(root, 'experiences', game, 'atlas-learning.js'), 'utf8'), context);
  return { api: context.SynkLearning, value: value => vm.runInContext(`JSON.parse(${JSON.stringify(JSON.stringify(value))})`, context) };
};
test('shipped entry-check and Hangul bundles preserve each other\'s records across save and reopen', async () => {
  const { VENUES } = await import('../experiences/entry-check/content.mjs');
  const { caseMetadata } = await import('../experiences/entry-check/learning.mjs');
  const rows = new Map(), storage = { getItem: key => rows.get(key) ?? null, setItem: (key, value) => rows.set(key, value) };
  let tick = Date.parse('2026-10-08T00:00:00Z');
  const clock = () => new Date(tick += 1000).toISOString();
  const entryBundle = load('entry-check');
  const entry = entryBundle.api.createGame({ gameId: 'entry-check', storage, clock });
  const pid = entry.present(caseMetadata(VENUES[0].cases[0]));
  entry.delivery(pid, { audio: 'completed' });
  entry.answer(pid, entryBundle.value({ correct: false, assessable: true, choice: { selectedId: 'audit-b', correctId: 'audit-a' } }));
  entry.flush();
  const key = 'synk.atlas.learning.v1.device';
  const first = JSON.parse(rows.get(key)), original = first.events.find(event => event.type === 'practice.attempted');
  assert.deepEqual(original.choice, { selectedId: 'audit-b', correctId: 'audit-a' });
  const hangul = load('hangul-stage').api.createGame({ gameId: 'hangul-stage', storage, clock });
  assert.equal(hangul.summary().storage.available, true);
  const hid = hangul.present({ id: 'audit.hangul', itemKey: 'audit.hangul', skillId: 'ko.hangul.read', modality: 'reading', difficulty: 1, responseFormat: 'binary-choice', audioRequired: false });
  hangul.answer(hid, { correct: true, assessable: true }); hangul.flush();
  const saved = JSON.parse(rows.get(key));
  assert.deepEqual(saved.events.find(event => event.id === original.id), original);
  assert.equal(saved.events.filter(event => event.type === 'practice.attempted').length, 2);
  const reopened = load('entry-check').api.createGame({ gameId: 'entry-check', storage, clock });
  assert.equal(reopened.summary().storage.available, true);
  assert.equal(reopened.events().filter(event => event.type === 'practice.attempted').length, 2);
  assert.equal(load('hangul-stage').api.createGame({ gameId: 'hangul-stage', storage, clock }).summary().storage.available, true);
});
