/* 컷맞추기 회귀 — 눈자리를 «어떻게» 집고, 헛짚었을 때 그렇게 말하는가.
 *
 * ■ 무엇을 지키나 (실사고 2026-09-05 · 영상 굽는 길이 막혀 있었다)
 *   `영상/자산모으기.js` 가 첫 절에서 죽어 그 뒤(폰트·소리·공방 요소 전부)가 안 돌았다.
 *   구멍이 둘이었다.
 *     ① 몽글 창구에 «각도 거르개»가 없어서 얼굴이 돌아간 컷(우34·좌34)이 표정으로 섞였다.
 *        이 도구는 «눈 밖을 본체로 덮어» 표정을 만들므로, 각도 컷이 들어오면 뜻이 깨진다.
 *     ② 정본이 4K 로 갈리며 컷마다 «따로 그린» 그림이 됐다. 털이 통째로 다르므로(본체↔눈감음
 *        16.7%) 「차이」 축으로는 눈을 못 가른다 — 낱알이 붙어 몸 전체가 한 덩어리가 된다.
 *
 * 🔴 **같은 날 반대편 끝에서 한 번 더 났다.** 마린이 들어오자 초록 갈래가 눈이 아니라 가슴의
 *   초록 장식을 집었는데(몸의 0.1%) 상한만 있고 하한이 없어 **통과했다.** 그대로 두면 이 도구가
 *   장식만 갈아 끼우고 「성공」을 보고한다. 그래서 이 파일은 위아래를 둘 다 문다.
 *
 * ⚠ 이 검사가 틀릴 때의 모습 = **자를 넓혀 놓고 초록.** 그래서 합성 그림으로 «막히나»를 재고,
 *   소스에 어떤 글자가 있는지는 세지 않는다(자가 결함을 지키면 초록은 영원하다).
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const 컷맞추기 = require('../영상/컷맞추기.js');
const 마스코트 = require('../tools/lib/마스코트자산.js');

/* ── 합성 그림 ─────────────────────────────────────────────────────────────
   4K 정본 스물한 장을 읽으면 시험이 몇 분씩 걸리고, 느린 시험은 아무도 안 돌린다.
   그래서 «몸 하나 + 점 몇 개»를 손으로 지어 갈래와 자만 잰다. */
const 크기 = 200;
function 빈판() { return { w: 크기, h: 크기, d: Buffer.alloc(크기 * 크기 * 4) }; }
function 칠(im, x0, y0, x1, y1, [r, g, b]) {
  for (let y = Math.max(0, y0); y <= Math.min(크기 - 1, y1); y++) {
    for (let x = Math.max(0, x0); x <= Math.min(크기 - 1, x1); x++) {
      const o = (y * 크기 + x) * 4;
      im.d[o] = r; im.d[o + 1] = g; im.d[o + 2] = b; im.d[o + 3] = 255;
    }
  }
}
/** 몸(밝은 사각) 하나에 점 몇 개를 얹은 컷 하나. 점 = [x0,y0,x1,y1,색]. */
function 컷(점들, 몸색 = [220, 150, 140]) {
  const im = 빈판();
  칠(im, 20, 20, 179, 179, 몸색);              // 몸 160x160
  for (const [x0, y0, x1, y1, c] of 점들) 칠(im, x0, y0, x1, y1, c);
  return im;
}
const 검정 = [10, 10, 10], 초록색 = [20, 200, 40], 노랑색 = [230, 220, 20];

test('🔴 각도 컷이 영상 창구로 새 나오지 않는다 — 셋 다 (09-05 사고 ①)', () => {
  /* 각도 이름을 손으로 안 적는다 — 자산 표에서 읽는다. 각도판이 늘어나면 이 검사도 같이 넓어진다. */
  const 창구 = {
    몽글: 마스코트.몽글누끼컷,
    까몽: 마스코트.까몽누끼컷,
    마린: 마스코트.마린표정컷,
  };
  for (const [이름, 목록] of Object.entries(창구)) {
    const 각도 = 마스코트.각도컷[이름];
    assert.ok(각도.length > 0, `${이름} — 각도 컷 표가 비었다(자가 아무것도 안 지킨다)`);
    const 샌것 = 목록.filter((c) => 각도.includes(c));
    assert.deepStrictEqual(샌것, [], `${이름} 창구에 각도 컷이 섞였다: ${샌것.join(', ')}`);
    assert.ok(목록.includes('본체'), `${이름} 창구에 본체가 없다 — 덮을 바탕이 사라진다`);
  }
});

test('🔴 눈보다 훨씬 작은 것을 집으면 «못 찾은 것»이다 (마린 가슴 장식 0.1% · 하한)', () => {
  /* 몸 160x160(25,600px) 위에 초록 점 하나 15x15. 상자가 225px = 몸의 0.88% 라 하한 밑이고,
     초록 점 수는 갈래가 물러서는 선(300px)보다 많다 ⇒ «갈래는 답했는데 너무 작다»가 잰다.
     상한만 있던 옛 판은 이것을 눈으로 알고 통과했다(마린 가슴 장식이 그 꼴이었다). */
  const 점 = [[100, 150, 114, 164, 초록색]];
  const 컷그림 = { 본체: 컷(점), 눈감음: 컷(점) };
  assert.throws(
    () => 컷맞추기.눈자리찾기(컷그림),
    (e) => /너무 작다/.test(e.message),
    '작은 장식 하나를 눈으로 알고 통과했다 — 하한이 죽었다',
  );
});

test('🔴 몸을 통째로 덮어도 «못 찾은 것»이다 (상한)', () => {
  /* 몸 전체가 초록 = 눈이 아니라 몸을 집은 꼴 */
  const 온통 = 컷([], [20, 200, 40]);
  assert.throws(
    () => 컷맞추기.눈자리찾기({ 본체: 온통, 눈감음: 온통 }),
    (e) => /몸을 덮었다/.test(e.message),
    '몸 전체를 눈자리로 내주고 통과했다 — 상한이 죽었다',
  );
});

test('🔴 곁가지는 상자를 안 늘린다 — 눈 둘 옆의 작은 점 하나 (마린 가슴 꽃)', () => {
  /* 눈 둘(각 14x14 = 196px)과 멀리 떨어진 점 하나(3x3 = 9px · 가장 큰 것의 4.6%).
     곁가지 거르개가 없으면 그 점이 상자를 아래로 끌어내린다. */
  const 눈둘 = [[60, 60, 73, 73, 노랑색], [120, 60, 133, 73, 노랑색]];
  const 점 = [140, 160, 142, 162, 노랑색];
  const 없이 = 컷맞추기.눈자리찾기({ 본체: 컷(눈둘), 눈감음: 컷(눈둘) }).상자;
  const 함께 = 컷맞추기.눈자리찾기({ 본체: 컷([...눈둘, 점]), 눈감음: 컷([...눈둘, 점]) }).상자;
  assert.strictEqual(함께.y1, 없이.y1, '작은 점이 상자를 아래로 늘렸다 — 곁가지 거르개가 죽었다');
  assert.ok(함께.y1 < 150, `상자가 점(y=160)까지 내려왔다 — y1=${함께.y1}`);
});

test('🔴 한 갈래가 헛짚으면 버리고 다음 갈래가 답한다 — 그리고 어느 쪽이 답했는지 찍는다', () => {
  /* 몸이 온통 초록(①이 몸을 덮는다) + 검은 눈 둘(③ 어두운 갈래가 답해야 한다).
     검증이 «밖»에 있던 옛 판은 첫 갈래가 헛짚는 순간 곧장 죽었다. */
  const 눈둘 = [[60, 60, 82, 82, 검정], [120, 60, 142, 82, 검정]];
  const 그림 = 컷(눈둘, [20, 200, 40]);
  const 낸것 = 컷맞추기.눈자리찾기({ 본체: 그림, 눈감음: 그림 });
  assert.match(낸것.방법, /어두운 덩어리/, `초록이 헛짚었는데 다음 갈래로 못 넘어갔다: ${낸것.방법}`);
  assert.ok(낸것.상자.x0 >= 55 && 낸것.상자.x1 <= 147, '눈 둘을 감싸는 상자가 아니다');
});

test('🔴 갈래가 다 헛짚으면 무엇을 왜 버렸는지 적어 던진다 (조용한 실패 금지)', () => {
  /* 몸만 있고 눈이 없는 그림 — 어느 갈래도 눈을 못 찾는다 */
  const 민판 = 컷([]);
  assert.throws(
    () => 컷맞추기.눈자리찾기({ 본체: 민판, 눈감음: 민판 }),
    (e) => /눈자리를 못 찾았다/.test(e.message)
      && /초록갈래/.test(e.message) && /노랑갈래/.test(e.message)
      && /어두운갈래/.test(e.message) && /차이갈래/.test(e.message),
    '갈래 넷의 사연을 다 적지 않았다 — 다음 사람이 어디를 볼지 모른다',
  );
});

test('자 넷은 서로 어긋나지 않는다 — 하한 < 상한 · 곁가지는 비율', () => {
  assert.ok(컷맞추기.하한 > 0 && 컷맞추기.하한 < 컷맞추기.상한, '하한이 상한 위로 올라갔다');
  assert.ok(컷맞추기.곁가지 > 0 && 컷맞추기.곁가지 < 1, '곁가지는 «가장 큰 것에 대한 비율»이라 0~1 이다');
  assert.ok(컷맞추기.어두움 < 128 && 컷맞추기.노랑 > 0, '색 문턱이 뒤집혔다');
});

test('가이드 셋이 다 창구를 통해 컷을 받는다 — 손으로 든 목록이 없다', () => {
  /* 09-01 사고: 한 목록을 두 가이드에 그대로 써서 몽글이 까몽 컷을 읽다 죽었다. */
  const 이름들 = 컷맞추기.가이드들.map((g) => g.이름);
  assert.deepStrictEqual(이름들, ['몽글', '까몽', '마린']);
  const 창구 = [마스코트.몽글누끼컷, 마스코트.까몽누끼컷, 마스코트.마린표정컷];
  컷맞추기.가이드들.forEach((g, i) => {
    assert.strictEqual(g.컷, 창구[i], `${g.이름} 이 제 창구가 아닌 목록을 쓴다`);
  });
});
