/**
 * 인쇄본 빌더 — 치환표와 폴백 게이트 회귀.
 *
 * 08-07 실측: 폰(클라우드) 세션이 구운 인쇄본 16종 중 8종에 브랜드 3종 밖 글자가 폴백으로
 * 나갔다(☐ ─└├ ⓐⓑⓒⓓ ＿ ≡ 한자). 화면 렌더 육안으로는 원리상 안 보인다 — ⚙ 은 어느
 * 폰트로 그려도 ⚙ 로 보인다. 그래서 검사는 눈이 아니라 여기가 진다.
 *
 * 게이트의 목적은 「폴백 0」이 아니다(이모지는 어느 텍스트 폰트에도 없어 허용이 정책이다).
 * **아는 폴백만 통과시키는 것**이다 — 새 글자가 들어오면 치환표가 놓친 것이다.
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const { 치환, 폴백_점검, MANIFEST } = require('../tools/인쇄본빌드.js');

/** 임베드 스크립트(브랜드폰트_임베드.py)가 폴백을 알릴 때 찍는 줄과 같은 모양 */
const 경고줄 = (글자들) => '쓰이는 글자 900종\n⚠ 브랜드 폰트 3종 어디에도 없는 글자 '
  + `${글자들.length}개 → 폴백 발생: `
  + 글자들.map((c) => `${c} U+${c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')}`).join(' ')
  + '\n   --폴백허용 이라 통과시킨다.';

test('치환표 — 실측된 고아 글자를 종이에서 걷는다', () => {
  const 표본 = [
    ['  └─ SYNK LAB', '└'], ['  ├─ SYNK IP', '├'],
    ['**`≡`(모든 시트)** 버튼', '≡'],
    ['근거 요약: ⓐ 감응력과 ⓑ 협응력 ⓒ 한자어 ⓓ 축', 'ⓐ'],
    ['성함 ＿＿＿＿＿＿　서명', '＿'],
    ['동의함 ☐　동의하지 않음 ☐', '☐'],
  ];
  for (const [원문, 글자] of 표본) {
    assert.ok(원문.includes(글자), `표본이 낡았다: ${글자}`);
    assert.ok(!치환(원문).includes(글자), `치환표가 ${글자} 를 안 걷는다: ${치환(원문)}`);
  }
  // 뜻을 잃는 것은 일부러 안 걷는다 — 걷으면 문서가 죽는다
  assert.ok(치환('✅ 완료 · 🔴 중요').includes('✅'), '이모지 상태 언어를 걷으면 안 된다');
  // ⛔ 한자는 종이에서 바꾸지 않는다 — 그러면 화면(md)에 남아 정책이 반쪽이 된다.
  //    원문에서 없애는 게 처방이고, 통과시키면 안 되므로 치환도 예외도 없다(아래 게이트가 잡는다).
  assert.ok(치환('어원 묶음(生·活·社·會)').includes('生'), '한자를 치환으로 덮으면 원문이 안 고쳐진다');
});

test('치환이 원문을 다치지 않는다 — 걷을 게 없으면 그대로', () => {
  const 원문 = '# 제목\n\n| 열 | 값 |\n|---|---|\n| `code` | **굵게** |\n\n- 항목 → 결과 300₮\n';
  assert.strictEqual(치환(원문), 원문);
});

test('게이트 — 이모지 폴백은 통과, 모르는 글자는 잡는다', () => {
  assert.deepStrictEqual(폴백_점검(경고줄(['✅', '🔴', '⏳', '🗣', '⚙'])), [],
    '이모지는 허용 정책이다(어느 텍스트 폰트에도 없다)');
  assert.deepStrictEqual(폴백_점검(경고줄(['生', '活', '社', '會', '部'])), ['生', '活', '社', '會', '部'],
    '유호님 확정 = 문서 문자는 한글·몽골어·영어 셋뿐 · 한자가 들어오면 빌드를 깬다');
  assert.deepStrictEqual(폴백_점검('쓰이는 글자 900종\nHTML → out.html'), [],
    '경고줄이 없으면 폴백이 없는 것이다');
  assert.deepStrictEqual(폴백_점검(경고줄(['☐'])), ['☐'], '치환표가 놓친 글자를 잡아야 한다');
  assert.deepStrictEqual(폴백_점검(경고줄(['✅', '❖', '🔴'])), ['❖'], '이모지 사이에 섞여도 잡는다');
});

test('게이트 — 이모지를 코드유닛으로 자르지 않는다(서로게이트)', () => {
  /* 초판이 `(\S) U\+…` 로 표시 글자를 물어 이모지가 lone surrogate 로 읽혔고, 16종 중 14종이
   * 「모르는 글자」로 오판됐다. 표시가 아니라 U+XXXX 를 읽는지 본다 — 글자 자리를 통째로
   * 깨뜨려도(콘솔 인코딩 사고와 같은 모양) 판정이 흔들리면 안 된다. */
  const 깨진줄 = '⚠ 브랜드 폰트 3종 어디에도 없는 글자 2개 → 폴백 발생: ? U+1F604 ? U+2705';
  assert.deepStrictEqual(폴백_점검(깨진줄), [], '표시가 깨져도 코드포인트로 이모지를 알아야 한다');
});

test('매니페스트의 원본 md 가 실재한다', () => {
  const ROOT = path.join(__dirname, '..');
  const 없는것 = MANIFEST.map((d) => d.src).filter((s) => !fs.existsSync(path.join(ROOT, s)));
  assert.deepStrictEqual(없는것, [], '원본이 옮겨졌거나 이름이 바뀌었다');
});
