// 왜 «새» 파일인가: 같은 대상을 보는 tests/상담지식.test.js 가 **다른 세션의 미커밋 작업본**이라
//   지금 편집하면 내 바이트가 남의 커밋에 실려 나간다(F073). 그 세션이 놓으면 **합치는 것이 옳다** —
//   축은 갈라져 있다: 상담지식 = FAQ 정본과의 정합 / 이 파일 = 철학 정본과의 정합.
// ✅ [2026-08-14 · F410 해소] 이제 **공용 통로 `tests/lib/소스검사.js` 를 쓴다.**
//   첫 판은 그 파일이 «미추적»이라 기대면 내려받는 쪽에서 검사가 통째로 죽어서, 대신 코드에만
//   나타나는 모양(따옴표로 연 배열 원소)을 패턴으로 잡아 자기를 방어했다. 그 자체 방어가
//   **「내가 그 자리에 남긴 주석을 위반으로 읽는」 거짓양성**을 한 번 냈다(아래 ③ 의 옛 주석).
//   지금은 양쪽 저장소에 추적된 것을 실측했고, 통로를 쓰니 그 거짓양성 부류가 원리상 사라진다.
//   🔑 따옴표 앵커를 **전부 걷지는 않았다** — 그중 일부는 자체 방어가 아니라 «뜻»이다
//      (그 문자열이 금칙 «배열의 원소»인가 · 그 리터럴이 그 낱말로 «시작»하는가). 뜻인 앵커는 남기고,
//      주석을 피하려고만 있던 앵커(③ 의 `' +` 꼬리)를 걷었다.
//
// 지키는 것 — 철학 정본이 「모든 파생이 지킨다」고 못박은 두 조항이 이 봇에 «실제로» 실려 있는가:
//   ① 「하지 않는 것 ㉢」(아이끼리 비교 금지)가 금칙에 산다 — 지식 블록의 '순위 경쟁'은 앱 «안»의
//      경쟁만 막고 봇 자신의 화법은 안 막는다(2026-08-13 대조가 연 구멍)
//   ② §0 시제 규약이 **금칙과 시스템 프롬프트 양쪽**에 산다 — 한쪽만 있으면 모델이 다른 쪽을 따른다
//      (선례 = 미성년 차단 S9 · tests/상담지식.test.js ③ 가 같은 축을 이미 못박았다)
//   ③ 고친 시제 위반 2곳이 되돌아오지 않는다(미개원 수업·현장 층을 현재형으로 말하던 자리)
//   ④ 성장 네 걸음이 정본 Ⅱ-7 어휘다(「계획하고/직접 해보고」는 구판)
//
// 🔴 이 장치의 대가(틀릴 때의 모습): 이건 **문구 존재 검사**라, 규칙을 «다른 말로» 고쳐 쓰면
//   뜻은 살아 있는데 빨개진다(거짓 실패). 그때는 검사 문구를 함께 고치는 것이 정답이고,
//   반대로 규칙을 지우면 빨개진다 — 그쪽이 이 검사가 실제로 막는 사고다.
//   닫는 것: 없다. 이 파일은 상담지식.test.js 가 «안 보는» 축만 본다(안전 가드는 억지로 닫지 않는다).

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { 코드만, 코드만픽스처 } = require('./lib/소스검사.js');

const ROOT = path.resolve(__dirname, '..');
const 원문읽기 = (이름) => fs.readFileSync(path.join(ROOT, 이름), 'utf8').replace(/\r\n/g, '\n');
/* 🔑 시야가 «둘»이다 — 섞으면 한쪽이 조용히 틀린다.
 *   · `지식`·`엔진` = **주석 지운 판**. 규칙이 코드에 실렸는지 보는 자리(①②③④)가 쓴다.
 *     ③ 의 부정 단언이 «설명을 위반으로 읽던» 거짓양성이 여기서 원리상 사라진다.
 *   · `지식원문` = **원문 그대로**. 주석에 사는 것을 보는 자리(⑤ 파생 스탬프)만 쓴다 —
 *     doc-graph 는 주석을 읽으니 그 스탬프는 «코드가 아닌 것이 정상»이다.
 * ⚠ 08-14 실측 — 전부 `코드만` 으로 돌렸더니 ⑤ 가 빨개졌다. **공용 통로의 대가가 여기다**:
 *   「주석을 지운다」가 언제나 옳은 것은 아니고, 시야는 «무엇을 보는 단언인가»로 고른다.
 *   그래서 갈라 두고 이름으로 못박는다(깃발 하나로 두면 다음 사람이 또 통째로 돌린다). */
const 지식원문 = 원문읽기('contents_상담AI.js');
const 지식 = 코드만(지식원문);
const 엔진 = 코드만(원문읽기('상담AI.js'));

test('⓪ 공용 주석 제거기가 «산다» — 이 파일의 부정 단언이 딛는 바닥 (그 모듈이 요구하는 픽스처)', () => {
  // 제거기가 약해지면 ③ 이 주석을 코드로 읽어 **조용히 초록**이 된다 — 새는 방향이 늘 「통과」다.
  assert.equal(코드만(코드만픽스처.입력), 코드만픽스처.기대);
});

test('① 「하지 않는 것 ㉢」 — 아이끼리 비교 금지가 금칙 배열에 산다', () => {
  // 배열 원소는 따옴표로 열린다 — 주석은 이 모양을 못 만든다
  assert.ok(/'아이끼리 비교하지 않는다\./.test(지식),
    '금칙에 비교 금지가 없다 — 지식의 「순위 경쟁」 블록은 앱 안의 경쟁만 막고 봇 화법은 안 막는다');
  assert.ok(/'아이끼리 비교하지 않는다[^']*어제의 그 아이와만/.test(지식),
    '비교 금지에 「어제의 그 아이와만」 기준이 빠졌다 — 금지만 있고 대안이 없으면 모델이 비교를 우회한다');
});

test('② §0 시제 규약이 금칙·시스템 프롬프트 «양쪽»에 산다 (선례 = 미성년 차단 S9)', () => {
  assert.ok(/'아직 문을 열지 않은 것을 이미 하고 있다고 말하지 않는다\./.test(지식),
    '금칙에 시제 규약이 없다 — 지식 문장은 시제를 지켜도 «재조합»한 문장을 막을 자리가 사라진다');
  assert.ok(/'· 우리는 아직 문을 열지 않았다\(개원 2027-02-25/.test(엔진),
    '시스템 프롬프트 【말투】에 시제 규약이 없다 — 한쪽만 있으면 모델이 다른 쪽을 따른다');
  // 두 자리가 같은 개원일을 말해야 한다(갈리면 봇이 두 날짜를 섞어 답한다)
  assert.ok(지식.includes('2027-02-25') && 엔진.includes('2027-02-25'),
    '개원일이 양쪽에서 갈렸다 — 같은 판정을 두 곳에 적으면 갈라진다');
});

test('③ 고친 시제 위반 2곳이 되돌아오지 않는다 (미개원 수업·현장 층)', () => {
  /* ⚠ 실측 08-13: 이 줄을 맨 문자열로 쓰면 **내가 그 자리에 남긴 주석**(왜 고쳤나)을 위반으로 읽었다.
   *   그래서 옛 판은 «코드에만 있는 모양»(`… ' +` 꼬리)으로 잠갔다 — 뜻이 아니라 자체 방어였다.
   *   [08-14 · F410] 이제 `코드만` 이 주석을 지우고 넘겨 주니 그 꼬리가 필요 없다. 맨 문자열로
   *   되돌린 것은 «후퇴»가 아니다 — 옛 거짓양성의 원인(주석)이 대상에서 사라졌기 때문이다. */
  assert.ok(!지식.includes('순환으로 수업이 돌아갑니다.'),
    '「수업이 돌아갑니다」가 되살아났다 — 학생 0명인데 수업 층을 현재형으로 말한다(정본 §0 위반의 예시 그대로)');
  assert.ok(!/'시즌마다 팀이 K컬처 실전 프로젝트/.test(지식),
    '크루 프로젝트가 다시 현재형으로 시작한다 — 정본 Ⅱ-1 은 이 항목을 「개원과 함께 연다」에 둔다');
  assert.ok(/개원하는 날부터 시즌마다 팀이 K컬처 실전 프로젝트/.test(지식),
    '크루 프로젝트 블록이 미래형 머리를 잃었다');
});

test('④ 성장 네 걸음이 정본 Ⅱ-7 어휘다', () => {
  assert.ok(/배우고\(Learn\) → 방향을 정하고\(Plan\) → 겪고\(Experience\) → 기록하는\(Record\)/.test(지식),
    '네 걸음 어휘가 정본과 다르다 — 정본 Ⅱ-7·조직계보 정본이 「이 4단계 어휘만 쓴다」로 못박은 자리');
  assert.ok(!/계획하고\(Plan\)/.test(지식), '구판 어휘 「계획하고(Plan)」가 남아 있다');
});

test('⑤ 이 파일이 철학 정본의 파생임을 스탬프로 밝힌다', () => {
  // ⚠ 판 «번호»는 검사하지 않는다 — 정본이 오르면 파생이 빨개지는 것이 정상이고(정본 머리 `:14`
  //   「올리지 않는 것이 처방이다」), 여기서 번호를 고정하면 그 빨강을 이 검사가 지워 버린다.
  /* 🔑 여기만 **원문**을 본다 — 파생 스탬프는 주석이라 `코드만` 판에는 원리상 없다.
   *   `지식` 으로 재면 「스탬프가 사라졌다」가 영원히 빨갛다(실측 08-14). */
  assert.ok(/파생: docs\/SYNK_철학\.md@v\d+\.\d+/.test(지식원문),
    '파생 스탬프가 사라졌다 — doc-graph 가 이 봇을 철학 파생으로 못 세면 낡음이 화면에서 사라진다');
});
