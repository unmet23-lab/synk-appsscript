/**
 * 교재 읽기본 — 「합쳐졌나」와 「지면이 살았나」 회귀.
 *
 * 이 빌더가 조용히 나빠지는 길은 정확히 둘이고, 둘 다 **오류 없이 통과처럼 보인다**:
 *
 *  ① **2과가 빠진 채 「완주본」이 나온다.** 권1 원고는 두 파일로 갈려 있어(중복 사본 금지의 결과)
 *     2과 본문만 `docs/_archive/…초안_v1.md` §③ 에 산다. 제목이 조금만 바뀌어도 잘라내기가
 *     빈손이 되는데, 그때 나오는 HTML 은 **1·3~8과가 멀쩡해서 정상으로 보인다**.
 *     → 그래서 `합치기` 는 못 찾으면 **던진다**. 여기서 그 던짐을 픽스처로 못박는다.
 *
 *  ② **지면 목업이 문단으로 풀린다.** 이 원고의 본체는 ``` 펜스 안의 박스 그림이다.
 *     펜스를 모르는 렌더러에 물리면 박스가 문단으로 흘러 나오는데, **글자는 다 있어서**
 *     grep 으로도 눈으로도 「내용은 다 있다」로 읽힌다. → 펜스 → `<pre>` 를 못박는다.
 *
 * 탐지력은 픽스처가 진다(CLAUDE.md 가드 맹점 ②). 실저장소는 **거짓양성만** — 원고가 자라도
 * 안 깨질 것(2과가 실제로 들어갔나)만 본다.
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const { 렌더 } = require('../tools/lib/마크다운.js');
const { 합치기, 절잘라내기, 목차만들기, 빌드, OUT } = require('../tools/교재읽기본.js');

const 펜스 = '```';

/* ── ① 합치기 ─────────────────────────────────────────────────────────── */

const 본편_픽스처 = [
  '# 시냅스 코어 권1 — 전과 원고',
  '',
  '# 1과 「소리를 얻다」',
  '',
  '1과 본문이다.',
  '',
  '# 2과 「이름을 말하다」',
  '',
  '> **전문은 초안 v1 이 정본** — 재수록하지 않는다.',
  '',
  '# 3과 「세계를 가리키다」',
  '',
  '3과 본문이다.',
].join('\n');

const 초안_픽스처 = [
  '# 초안 v1',
  '',
  '## ② 권1 문법 지도',
  '',
  '지도다.',
  '',
  '## ③ 2과 완전 원고 — 「이름을 말하다」 (16p 지면 전문)',
  '',
  '### [p1] 도입 스프레드',
  '',
  펜스,
  '2과  이름을 말하다',
  '┌─ 소리 카드 ─┐',
  펜스,
  '',
  '#### ① 형태 FORM',
  '',
  '은/는 이다.',
  '',
  '## ④ 문법 카드 변주 샘플',
  '',
  '변주다.',
].join('\n');

test('2과 본문이 실제로 자리에 들어간다 — 안내 한 줄은 밀려난다', () => {
  const { md, 합친줄수 } = 합치기(본편_픽스처, 초안_픽스처);

  assert.ok(md.includes('[p1] 도입 스프레드'), '초안 §③ 의 지면이 안 들어왔다');
  assert.ok(md.includes('┌─ 소리 카드 ─┐'), '지면 목업이 안 들어왔다');
  assert.ok(md.includes('① 형태 FORM'), '§③ 하위 절이 안 들어왔다');
  assert.ok(!md.includes('재수록하지 않는다'), '갈아 끼우지 않고 안내 줄이 남았다');
  assert.ok(합친줄수 > 5, '합친 줄 수가 실제 분량과 안 맞는다: ' + 합친줄수);

  // 이웃 과를 먹지 않았다 — 잘라내기가 한 칸 넘치면 3과가 2과 안으로 빨려 들어간다
  const i2 = md.indexOf('# 2과'), i3 = md.indexOf('# 3과');
  assert.ok(i3 > i2, '3과가 사라졌다');
  assert.ok(md.slice(i3).includes('3과 본문이다.'), '3과 본문이 먹혔다');
  assert.ok(!md.slice(i2, i3).includes('변주다.'), '§④ 까지 넘겨 잘랐다');
  assert.ok(!md.includes('지도다.'), '§③ 아닌 절이 딸려 왔다');
});

test('2과 정본이 사라지면 조용히 넘어가지 않고 던진다', () => {
  // 실패 모양: 초안 쪽 제목이 바뀌거나 파일이 정리돼 §③ 이 없어진다.
  const 정본없음 = 초안_픽스처.replace('## ③ 2과 완전 원고 — 「이름을 말하다」 (16p 지면 전문)', '## ③ (이관됨)');
  assert.throws(() => 합치기(본편_픽스처, 정본없음), /2과 완전 원고/,
    '2과 없이 「완주본」 이 구워지면 1·3~8과가 멀쩡해서 아무도 못 알아챈다');

  // 본편 쪽 자리가 없어지는 반대 방향도 같다
  const 자리없음 = 본편_픽스처.replace('# 2과 「이름을 말하다」', '# 둘째 과');
  assert.throws(() => 합치기(자리없음, 초안_픽스처), /2과/);
});

test('절잘라내기 — 층이 더 깊은 제목은 경계가 아니다', () => {
  const md = ['## A', '가', '#### 깊은 제목', '나', '## B', '다'].join('\n');
  const r = 절잘라내기(md, 2, /A/);
  assert.ok(r.몸.includes('나'), '#### 에서 잘라 버렸다 — 절 본문이 통째로 날아간다');
  assert.ok(!r.몸.includes('다'), '## B 를 넘겨 잘랐다');
});

/* ── ② 지면 목업 ──────────────────────────────────────────────────────── */

test('``` 펜스는 <pre> 로 살아남는다 — 문단으로 풀리면 안 된다', () => {
  const md = ['본문 앞.', '', 펜스, '┌────────┐', '│ 안녕 │  ← 칸 맞춤이 뜻이다', '└────────┘', 펜스, '', '본문 뒤.'].join('\n');
  const html = 렌더(md);

  assert.match(html, /<pre>/, '펜스가 <pre> 가 안 됐다 — 박스 그림이 문단으로 풀린다');
  assert.ok(html.includes('┌────────┐\n│ 안녕 │'),
    '줄바꿈이 접혔다 — 박스는 줄이 접히는 순간 그림이 아니게 된다');
  assert.ok(!/<p>[^<]*┌/.test(html), '목업이 <p> 로 새어 나왔다');
});

test('펜스 안의 md 문법은 서식으로 먹지 않는다', () => {
  // 지면 목업 안에는 **·|·# 가 그림으로 들어 있다. 여기서 서식이 걸리면 칸이 밀린다.
  const md = [펜스, '| 이름 | 나라 |', '**굵게 아님**', '# 제목 아님', 펜스].join('\n');
  const html = 렌더(md);
  assert.ok(html.includes('**굵게 아님**'), '펜스 안에서 굵게가 먹었다');
  assert.ok(!html.includes('<table>'), '펜스 안 파이프를 표로 읽었다');
  assert.ok(!html.includes('<h1>'), '펜스 안 # 을 제목으로 읽었다');
});

test('표는 백틱 안 파이프에 밀리지 않는다 (lib/표.js 통로)', () => {
  const html = 렌더('| 과 | 명령 |\n|---|---|\n| 1 | `a | b` |');
  const 칸 = html.match(/<td>/g) || [];
  assert.strictEqual(칸.length, 2, '백틱 안 파이프를 칸막이로 셌다: ' + html);
});

/* ── ③ 실저장소 — 거짓양성만 ───────────────────────────────────────────── */

test('실저장소 원고로 구우면 2과가 든 한 장이 나온다', () => {
  const 본편 = path.join(__dirname, '..', 'docs', '교재_시냅스코어_권1_원고_v2.md');
  if (!fs.existsSync(본편)) { test.skip('원고 md 가 없다 — 실저장소 검사 건너뜀'); return; }

  const r = 빌드();
  const html = fs.readFileSync(OUT, 'utf8');

  assert.ok(r.과수 >= 9, `과가 ${r.과수}개뿐이다 — 1~8과+부록이 안 잡혔다`);
  assert.ok(r.합친줄수 > 100, `2과가 ${r.합친줄수}줄뿐이다 — 16p 전문이 아니다`);
  assert.ok(html.includes('data-synk-theme'), '킷 토큰이 안 실렸다');

  // 과별 h1 앵커가 목차와 짝이 맞는가 — 안 맞으면 목차 링크가 빈 곳을 가리킨다
  const 앵커 = [...html.matchAll(/<h1 id="([^"]+)"/g)].map((m) => m[1]);
  const 링크 = [...html.matchAll(/<nav>[\s\S]*?<\/nav>/g)].join('')
    .match(/href="#([^"]+)"/g)?.map((s) => s.slice(7, -1)) || [];
  assert.ok(링크.length > 0, '목차가 비었다');
  for (const l of 링크) assert.ok(앵커.includes(l), `목차 링크가 없는 자리를 가리킨다: ${l}`);
});
