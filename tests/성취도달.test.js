'use strict';
/**
 * 🏅 성취 이력 되읽기 — 「오늘의 한 문장」이 **그 학생이 해낸 것**을 근거로 쓰는가
 *                        (대기열 #Q104 · 시트층 도달 6/6 · 설계 §8-6)
 *
 * ■ 왜 «실행» 검사인가
 *   시트층 도달 장부(`엔진_셋업확장.js` `수집도달_`)가 재는 것은 「지목한 파일의 코드에 탭 이름이
 *   실재하는가」까지다 — 소비자를 적어 두고 읽는 몸을 비워도 초록이다(설계 §8 「⚠ 천장」).
 *   그래서 여기서는 `aiStudioBatch_` 를 **가짜 의존으로 실제로 태워**, 모델에게 건네는 문자열이
 *   `achievements` 유무에 따라 정말 달라지는지를 잰다. 과녁은 「읽는다」가 아니라 「다음에 줄 것이
 *   바뀐다」다.
 *
 * ■ 이 시험이 **가장 중요하게** 막는 것 — 철학 「하지 않는 것 ㉢」(학생끼리 비교하지 않는다).
 *   `achievements` 에는 등수에서 나온 업적이 둘 섞여 있다(`명예의 전당 입성` = 월간 랭킹 3위 이내 ·
 *   `TOP10 단골` = 10위 이내 3연속). 그것이 학생에게 가는 글의 근거로 실리면 **어느 화면에도 두지
 *   않기로 한 비교가 문장으로 되살아난다.** 그런데 그 실패는 «조용하다» — 프롬프트에 한 조각이
 *   더 붙을 뿐이라 어느 검사도 안 빨개진다. 그래서 여기서 이름으로 직접 잰다.
 *
 * ■ 이 시험이 틀릴 때의 모습 (대가를 함께 적는다)
 *   ①~⑤ 절 중 ① 만 재고 나머지는 의존이 없어 던지므로 아래 `태우기` 는 예외를 삼킨다. 그 삼킴이
 *   ① 자체의 실패까지 가릴 수 있으므로 **잡힌 호출이 0건이면 실패로 떨어뜨린다**(미실행은 통과와
 *   같은 모양이다 · F207). 그리고 업적 이름은 **하나도 리터럴로 안 적는다** — 정본(`엔진_운영배치.js`)
 *   에서 뽑아 쓴다. 시험이 이름을 손으로 들고 있으면 정본이 바뀔 때 **검사만 조용히 낡는다.**
 */
const test = require('node:test');
