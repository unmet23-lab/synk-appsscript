/**
 * 중성축 지면 전파 회귀 — 「덮어쓰는 도구」의 치환이 조용히 틀리지 않게 지킨다 (2026-08-19).
 *
 * 왜 이 파일이 필요한가:
 *   `tools/중성축_지면전파.js` 는 지면 47벌을 **한 번에 덮어쓴다.** 그런데 치환이 틀리면 결과는
 *   「색이 조금 이상한 그림」이라 사람 눈에도 CI 에도 안 걸린다 — #Q103 이 적은 그 자리다
 *   (「색·물성 계산이 조용히 틀리면 그림에만 나타나고 아무도 못 잰다」). 그런데도 이 도구는
 *   2026-08-19 작동대장에서 **회귀 0(맨몸)** 으로 새로 들어왔다. 원인은 실력이 아니라 **모양**이었다:
 *   전량이 최상위 스크립트라 픽스처를 물릴 자리가 없었다. 그래서 순수부를 함수로 떼고 여기서 잰다.
 *
 * 무엇을 잡고 무엇을 안 잡는가:
 *   ○ 잡는다 — 연쇄 치환(A→B 인데 B 가 또 다른 규칙의 «구» 라서 두 번 바뀜) · 대소문자 누락 ·
 *     rgb() 공백 표기 변형 누락 · 맵에 없는 색을 건드림 · 잔재 검산이 눈머는 것
 *   ✗ 안 잡는다 — 정박점·유도값의 «옳음»(그건 `tests/중성축.test.js` 와 유호님 확정 사안이다)
 *
 * 🔑 탐지력은 **픽스처**가 진다(가드 맹점 ②). 실저장소는 이미 전파가 끝나 안 깨져 있으므로,
 *   실저장소만 검사하면 도구가 눈멀어도 초록이다. 그래서 아래 ④⑤⑥ 은 «일부러 깨뜨린 맵»으로
 *   재고, 실저장소(⑧)에는 **거짓양성만** 묻는다.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const 전파 = require(path.join(ROOT, 'tools', '중성축_지면전파.js'));

test('① 라이브러리로 열린다 (그러지 않으면 아래 전부가 헛돈다)', () => {
  for (const 이름 of ['치환', '잔재', '과녁들', '맵', 'rgb']) {
    assert.ok(전파[이름], `tools/중성축_지면전파.js 가 ${이름} 을 안 내보낸다`);
  }
  assert.equal(Object.keys(전파.맵).length, 11, '중립 11색이 아니다 — 유도표가 바뀌었으면 이 수도 함께 고친다');
});

test('② hex 치환 — 대소문자를 가리지 않는다', () => {
  const 맵 = { '#0F1730': '#08090C' };
  for (const 원문 of ['#0F1730', '#0f1730', '#0F1730', '#0f1730']) {
    const r = 전파.치환(`color: ${원문};`, 맵);
    assert.equal(r.텍스트, 'color: #08090C;', `${원문} 이 안 옮겨졌다`);
    assert.equal(r.hex, 1);
  }
});

test('③ rgb()/rgba() — 공백 표기가 제각각이어도 잡고, 나머지는 원문 보존', () => {
  const 맵 = { '#0F1730': '#08090C' };            // rgb(15,23,48) → rgb(8,9,12)
  const 판 = [
    ['rgb(15,23,48)', 'rgb(8,9,12)'],
    ['rgb( 15 , 23 , 48 )', 'rgb( 8 , 9 , 12 )'],
    ['rgba(15, 23, 48, .5)', 'rgba(8, 9, 12, .5)'],
    ['rgba( 15,23,48 , 0.25 )', 'rgba( 8,9,12 , 0.25 )'],
  ];
  for (const [전, 후] of 판) {
    const r = 전파.치환(전, 맵);
    assert.equal(r.텍스트, 후, `${전} 이 ${r.텍스트} 로 나왔다 — ${후} 여야 한다`);
    assert.equal(r.rgb, 1);
  }
});

test('④ 연쇄 치환 금지 — 실제 맵의 «새 hex» 가 어느 «구 hex» 와도 겹치지 않는다', () => {
  const 구들 = new Set(Object.keys(전파.맵).map((h) => h.toUpperCase()));
  const 겹침 = Object.entries(전파.맵).filter(([, 신]) => 구들.has(신.toUpperCase()));
  assert.deepEqual(
    겹침, [],
    '새 hex 가 다른 규칙의 구 hex 이기도 하다 — 치환이 순서에 따라 «두 번» 일어나 값이 조용히 어긋난다.\n' +
    '       유도표를 고쳤다면 정박점을 다시 잡거나, 치환을 한 홉으로 묶어야 한다.'
  );
});

test('⑤ ④의 탐지력 — 일부러 연쇄를 만든 맵에서는 실제로 두 번 바뀐다(픽스처)', () => {
  /* 이 픽스처가 없으면 ④ 는 「지금 안 겹친다」만 말하고, 겹쳤을 때 무슨 일이 나는지는 아무도 모른다. */
  const 연쇄맵 = { '#AAAAAA': '#BBBBBB', '#BBBBBB': '#CCCCCC' };
  const r = 전파.치환('#AAAAAA', 연쇄맵);
  assert.equal(r.텍스트, '#CCCCCC', '연쇄가 나지 않았다 — 이 픽스처가 낡았으면 ④ 의 근거도 낡은 것이다');
  assert.equal(r.hex, 2, '두 번 치환된 것이 세어지지 않았다');
});

test('⑥ 맵에 없는 값은 건드리지 않는다 (부분 일치·이웃 숫자 포함)', () => {
  const 맵 = { '#0F1730': '#08090C' };
  const 안건드릴것 = [
    '#0F1731',                      // 한 자리 다름
    'rgb(150,23,48)',               // 첫 숫자가 15 로 시작하지만 150 이다
    'rgb(15,230,48)',               // 둘째가 23 으로 시작하지만 230 이다
    'rgb(15,23,480)',               // 셋째가 48 로 시작하지만 480 이다
    'hsl(15,23%,48%)',              // rgb 가 아니다
  ];
  for (const 전 of 안건드릴것) {
    const r = 전파.치환(전, 맵);
    assert.equal(r.텍스트, 전, `${전} 을 건드렸다 — ${r.텍스트}`);
    assert.equal(r.hex + r.rgb, 0, `${전} 에서 치환이 세어졌다`);
  }
});

test('⑦ 잔재() 가 남은 구 색을 실제로 잡는다 — 그리고 치환 뒤엔 0 이다 (왕복)', () => {
  const 맵 = { '#0F1730': '#08090C' };
  const 더러운판 = 'a{color:#0f1730} b{background:rgb( 15 , 23 , 48 )}';

  const 남음 = 전파.잔재(더러운판, 맵);
  assert.equal(남음.length, 2, `잔재를 ${남음.length}건 봤다 — hex 1 + rgb 1 = 2 여야 한다: ${남음.join(' · ')}`);

  const { 텍스트 } = 전파.치환(더러운판, 맵);
  assert.deepEqual(전파.잔재(텍스트, 맵), [], `치환 뒤에도 잔재가 남았다: ${텍스트}`);
});

test('⑧ 실저장소 — 과녁은 실재 파일만이고, 지금 잔재 0 이다 (거짓양성만 본다)', (t) => {
  let 과녁;
  try {
    과녁 = 전파.과녁들();
  } catch (e) {
    return t.skip(`과녁을 못 셌다(저장소 밖이거나 지면방이 안 선다): ${e.message}`);
  }
  if (!과녁.length) return t.skip('과녁 0벌 — 이 판에는 잴 지면이 없다(못 잰 것이지 초록이 아니다)');

  const 없는것 = 과녁.filter((p) => !fs.existsSync(p));
  assert.deepEqual(없는것, [], '과녁에 실재하지 않는 경로가 섞였다');

  const 남음 = [];
  for (const p of 과녁) {
    for (const 이름 of 전파.잔재(fs.readFileSync(p, 'utf8'), 전파.맵)) {
      남음.push(`${path.relative(ROOT, p)} : ${이름}`);
    }
  }
  assert.deepEqual(
    남음, [],
    `퇴역색이 과녁에 되살아났다 ${남음.length}건 — 되살린 커밋을 찾거나 \`node tools/중성축_지면전파.js --적용\` 을 돌린다:\n       ` +
    남음.slice(0, 10).join('\n       ')
  );
});
