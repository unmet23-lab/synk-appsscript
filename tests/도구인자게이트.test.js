/* ── ④ 거짓양성 예방 — 선언이 **자기 낱말**을 덮는가 (이 장치의 대가를 기계가 진다) ── */

test('🔑 ④ 선언한 `아는플래그` 가 그 도구의 **자기 낱말**과 정확히 같다 (양방향)', () => {
  /* 🔴 **두 방향을 다 봐야 한다** — 2026-08-18 변이가 한 방향만 보던 첫 판을 구멍으로 잡았다.
   *   ㉠ 빠짐(선언 ⊉ 비교낱말) → **되던 명령이 죽는다**(F103). 이 장치가 틀릴 때의 모습.
   *   ㉡ 군더더기(선언 ⊋ 비교낱말) → 자식 프로세스 인자를 선언에 끼우면 **그 낱말이 CLI 에서
   *      통과하면서 아무것도 안 한다**(형제 F592 모양). 첫 판은 선언을 「자기 낱말」에 접었기
   *      때문에 이 방향을 **원리상** 못 쟀다 — `비교낱말`(코드가 스스로 증명한 것)로 잰다.
   * ⚠ **남는 대가**: 추출기가 못 보는 표기로 낱말을 읽는 도구는 ㉡에 걸린다(거짓양성). 처방은
   *   「선언에서 빼라」가 아니라 **추출기를 넓혀라**다 — 그래서 아래 문구가 그렇게 말한다.
   *   ⚠ 추출기가 그 도구를 통째로 못 본 경우(`비교낱말` 0)는 ㉡을 안 잰다 — 그건 「군더더기」가
   *     아니라 「안 보인다」이고, 둘을 같은 적색으로 두면 처방이 갈린다. */
  const 빠진것 = [];
  const 군더더기 = [];
  for (const r of 도구들) {
    if (!r.선언) continue;                                   // 게이트 없는 것은 위 래칫의 몫이다
    const 선언 = new Set(r.선언.낱말);
    const 비교 = new Set(r.비교낱말);
    for (const 낱말 of r.비교낱말) if (!선언.has(낱말)) 빠진것.push(`${r.파일}: ${낱말}`);
    if (r.비교낱말.length) {
      for (const 낱말 of r.선언.낱말) if (!비교.has(낱말)) 군더더기.push(`${r.파일}: ${낱말}`);
    }
  }
  assert.deepEqual(빠진것, [],
    `㉠ 선언에 없는데 도구가 «자기 인자로» 읽는 낱말: ${빠진것.join(' · ')}\n`
    + '  이대로 두면 **되던 명령이 죽는다** — 이 장치가 틀릴 때의 모습이 정확히 이것이다(F103).');
  assert.deepEqual(군더더기, [],
    `㉡ 선언에 있는데 도구가 argv 와 «비교하지 않는» 낱말: ${군더더기.join(' · ')}\n`
    + '  자식 프로세스에 넘기는 인자라면 선언에서 빼라 — 넣으면 그 낱말이 CLI 에서 통과하면서\n'
    + '  아무것도 안 한다(「받은 척」이 초록으로 나간다 · 형제 F592).\n'
    + '  🔑 도구가 **정말로** 그 낱말을 읽는데 여기 걸렸다면 선언을 깎지 마라 — 추출기가 못 보는\n'
    + '     표기다. `tests/lib/도구인자.js` 의 `인자층()` 을 그 표기까지 넓히는 것이 처방이다.');
});

