/* [반출 식별자] `tools/geminilm-export.js` 의 내용 게이트 회귀 — **없던 검사를 짓는다.**
 *
 * ■ 왜 이 파일이 새로 생겼나 (실측 · 2026-08-29)
 *   ① 그 파일 머리말이 *"회귀 테스트가 { scanPII, DEFAULT_OUT }만 물어본다"* 고 적고,
 *      PII 목록 주석이 *"이 파일의 회귀 테스트가 잡은 실결함"* 이라고 적는데,
 *      **그 테스트가 저장소에 없었다.** `scanPII` 는 전 저장소에 5회 나오고 전부 도구 두 벌 «안»이었다.
 *      문서가 없는 검사를 가리키던 자리다(`guard-blind-to-its-own-claim` 계열).
 *   ② 그리고 그 게이트는 정본이 「안 나가는 것」으로 못박은 다섯 중 셋을 **못 잡고 있었다**:
 *          scanPII('학생 바트자르갈 (student_id: S2027-0143, 생일 2011-04-02)')  →  []
 *      이 반증 한 줄이 아래 첫 검사다. 다시 빈 배열이 되면 그 순간 빨개진다.
 *
 * ■ 이 파일이 지키는 것
 *   ㉠ 반증 회귀 — 이름·student_id·생년이 라벨과 함께 있으면 잡는다.
 *   ㉡ **탐지력** — 오탐이 0인 것과 «검사가 죽어서» 0인 것이 같은 모양이면 안 된다(정직 조항).
 *      그래서 잡아야 하는 픽스처와 잡으면 안 되는 픽스처를 **둘 다** 못박는다.
 *   ㉢ 정본 대조 — profiles 열이 늘면 분류를 강제한다(조용한 통과 금지 · 「확인 불가」로 던진다).
 *   ㉣ 실코퍼스 소음 — 지금 실물에서 이 축이 몇 벌을 «새로» 막는지 못박는다.
 *      우는 검사는 꺼지므로, 소음이 늘면 그 커밋에서 알아야 한다.
 *      🔴 **갈래별로 센다**(문서 = 저장소 안 · 기억 = 저장소 «밖»). 합쳐 세면 한 갈래가 죽어도
 *      다른 갈래가 문턱을 채워 조용히 초록이 된다 — 08-30 에 실제로 그랬다(아래 ㉣ 절 머리말).
 *
 * ■ 이 검사가 «안» 보는 것 (「없다」가 아니라 안 재봤다/못 잰다)
 *   · 라벨 없는 맨 이름(「바트자르갈이 어제…」) — 원리상 못 잡는다. 도구 주석의 「안 잡는 것 ①」.
 *   · 라벨 없는 맨 학생ID(`SYNK-042`) — 일부러 뺐다(문서 예시가 31파일). 도구 주석 「안 잡는 것 ②」.
 *   · 이 저장소 «밖»(SYNK-talk·Supabase) — 과녁 밖(`cross-repo-blindness`).
 *
 * ■ 🟠 아는 위험 — 이 게이트는 **한 편집 거리에서 운다**(08-30 실측 · 고치지 않고 적어 둔다)
 *   실코퍼스 두 갈래 77,199줄에 「이름/name/보호자명 + 값」 꼴이 **357줄** 있고 지금 걸리는 것은
 *   **0줄**이다. 그런데 그 0은 «값 꼴이 안전해서»가 아니라 **그 357줄이 우연히 케밥표기 영문이거나
 *   괄호·굵게를 달고 있어서**다. 직접 재봤다:
 *       ✅ `이름: 까몽**(까맣다 + 몽글의 「몽」)`   ✅ `name: abandoned-audio-orphan`
 *       🔴 `이름: 까몽`   🔴 `name: 몽글`   🔴 `이름: 마린`      ← 괄호 하나 뗀 순간
 *   이 저장소는 가이드 셋(몽글·까몽·마린)을 문서에 상시 쓴다(`guide-trio-canon`). 누가 그 한 줄을
 *   적는 날 **저장소 전체 테스트와 CI 가 빨개진다**. 그 줄이 `memory/` 쪽이면 고칠 파일이
 *   **저장소 밖**이고 매시 동기화가 되돌려 놓는다.
 *   ⇒ 그때 할 일은 **셋**이고, 고르기 전에 **「누가 잡았나」를 먼저 갈라야 한다**(09-01 실측):
 *     ㉠ 진짜 식별자면 그 파일을 고친다.
 *     ㉡ 오탐이고 **라벨 축에만** 걸리면 그 **값**을 `ALLOW` 에 넣는다(값 단위 예외).
 *     ㉢ **형식 축이 이미 잡던 값이면 값 꼴을 조인다** — 09-01 이 그 경우였다(`휴대전화: 010-…`).
 *        `scanPII` 는 겹침을 접어 조용한데 이 ㉣ 검사만 `scan라벨_` 을 직접 불러 울었다.
 *        🔴 그 자리에 ㉡(ALLOW)을 쓰면 **형식 축의 눈까지 같이 감긴다** — ALLOW 는 두 축이 함께
 *          본다. 즉 「소음을 줄이려다 진짜 게이트를 연다」. 갈라야 하는 이유가 그것이다.
 *   🚫 아직 안 걸린 값을 미리 `ALLOW` 에 넣지는 않았다 — ALLOW 는 「실제로 만난 안전값」의 자리고,
 *     안 만난 값을 넣으면 그 낱말에 대해 게이트가 영원히 눈을 감는다.
 */
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const G = require('../tools/geminilm-export.js');
const { scanPII, 식별라벨_, 식별열_별칭, 비식별열_, 골격정본_ } = G;

const 종류 = (hits) => [...new Set(hits.map((h) => h.kind))].sort();

/* ── ㉠ 반증 회귀 — 이 한 줄이 이 파일이 태어난 이유다 ───────────────── */
test('🔴 08-29 반증: 라벨 붙은 student_id·생년을 잡는다(옛 판은 빈 배열이었다)', () => {
  const hits = scanPII('학생 바트자르갈 (student_id: S2027-0143, 생일 2011-04-02)');
  assert.notDeepEqual(hits, [], '빈 배열 — 옛 판으로 되돌아갔다(형식 없는 식별자가 통째로 사각이다)');
  assert.ok(종류(hits).includes('학생ID(라벨)'), `student_id 를 못 잡았다 — 잡힌 것: ${종류(hits).join(',') || '없음'}`);
  assert.ok(종류(hits).includes('생년(라벨)'), `생년을 못 잡았다 — 잡힌 것: ${종류(hits).join(',')}`);
});

test('이름은 라벨이 붙으면 잡는다 — 형식이 없어 라벨이 유일한 손잡이다', () => {
  ['이름: 바트자르갈', '보호자명: 김유호', '학생명: Batzargal', '이름_몽골: Батзаргал'].forEach((줄) => {
    assert.ok(scanPII(줄).some((h) => h.kind === '이름(라벨)'), `못 잡았다 → ${줄}`);
  });
});

test('연락처·메신저 식별자도 라벨로 잡는다', () => {
  // ⚠ 픽스처는 «형식 축이 못 잡는» 값이어야 한다(+976 을 붙이면 몽골 전화번호 축이 먼저 잡아
  //   08-30 겹침 접기에 걸리고, 그러면 이 검사가 라벨 축이 아니라 형식 축을 재게 된다).
  assert.ok(scanPII('보호자연락처: 8811-3344').some((h) => h.kind === '연락처(라벨)'), '보호자 연락처를 못 잡았다');
  assert.ok(scanPII('messenger_link: 17841400000000001').some((h) => h.kind === '메신저(라벨)'), 'messenger_link 를 못 잡았다');
});

test('🔴 같은 자리의 같은 값이 두 축에 두 번 세어지지 않는다 — 건수가 부풀면 표에서 진짜가 밀려난다', () => {
  const 겹침 = scanPII('phone: +976 9911 2233');
  assert.equal(겹침.length, 1, `한 값이 ${겹침.length}건으로 세어진다: ${JSON.stringify(겹침)}`);
  assert.equal(겹침[0].kind, '몽골 전화번호', '겹칠 때 남는 축이 형식 축이 아니다');
  // 접었다고 탐지력이 주는 것은 아니다 — 겹친 자리도 여전히 «막힌다»
  assert.ok(scanPII('보호자연락처: +976 8811 3344').length > 0, '겹침을 접다가 위반 자체를 놓쳤다');
});

/* ── ㉡ 탐지력 — 「0건」이 성공 얼굴을 하지 못하게 ───────────────────── */
test('🔴 잡으면 안 되는 것을 안 잡는다 — 헛도는 게이트는 곧 꺼진다', () => {
  const 통과해야 = [
    // 기억 파일 머리말 — 라벨만 보는 1차 판은 여기서 **348파일**을 막았다(08-29 실측)
    'name: abandoned-audio-orphan',
    'name: student-id-longevity-design',
    // 산문 속의 「이름:」 — 값이 낱말 하나가 아니면 사람 이름이 아니다
    '이름: 까몽**(까맣다 + 몽글의 「몽」)',
    '이름: 자리를 만드는 하나',
    '이름: SYNK LAB**(대외 브랜드 단일 원칙)',
    // 코드 스팬은 이름이 아니다
    '이름: `content.viewed`',
    // 스키마 설명 줄 — 값이 열 이름 나열이다
    "profiles 열: user_id·이름·이름_몽골·role·class_name",
    // 낱말 «안»은 라벨이 아니다(한글은 낱말 경계가 없다 — 앞 글자를 못박아 막는다)
    '파일이름: 굽기결과.png',
    '옛이름: 필살기노트',
    /* 🔴 콜론 없는 «공백만» 구분자는 값 꼴이 좁은 축에만 열어 뒀다(도구의 `띄` 플래그).
     *   이름 축까지 열면 아래 산문이 전부 「이름 = 사람 이름」으로 걸린다 — 그 판을 실제로 재보고 닫았다. */
    '이름 자리를 만드는 하나',
    '이름 까몽 확정',
    '보호자명 없이도 발송된다',
  ];
  const 샌것 = 통과해야.filter((줄) => scanPII(줄).length);
  assert.deepEqual(샌것, [], `오탐 ${샌것.length}건 — 이 게이트는 첫날부터 울면 꺼진다:\n  ` +
    샌것.map((s) => s + '  →  ' + JSON.stringify(scanPII(s))).join('\n  '));
});

test('옛 축(형식 있는 값)은 그대로 산다 — 증축이 기존 탐지를 갉아먹지 않았다', () => {
  assert.ok(종류(scanPII('010-1234-5678')).includes('휴대폰번호'));
  assert.ok(종류(scanPII('연락 주세요 hello@example.com')).includes('이메일'));
  // 자격증명은 길이를 고정하지 않는다 — 한 글자 긴 값이 경계에서 미끄러지던 실결함의 회귀
  assert.ok(종류(scanPII('AIza' + 'a'.repeat(36))).includes('API 키'), '한 글자 긴 API 키가 통과한다');
  // ALLOW 는 값 단위 예외다 — 파일 단위가 아니다
  assert.deepEqual(scanPII('문의: hello@synk.im'), [], 'ALLOW 값이 막힌다 — 공개 창구 하나에 파일이 통째로 빠진다');
});

test('스캔은 줄 번호를 정확히 짚는다 — 「어디에」가 없으면 사람이 못 고친다', () => {
  const hits = scanPII('첫 줄\n둘째 줄\n이름: 바트자르갈\n넷째 줄');
  assert.equal(hits.length, 1);
  assert.equal(hits[0].line, 3, '줄 번호가 어긋난다');
});

/* ── ㉢ 정본 대조 — 한 값을 두 곳이 알지 않게 ───────────────────────── */
test('🔴 열 목록을 베끼지 않는다 — 정본(엔진_셋업확장.js sheetSkeleton_)에서 읽는다', () => {
  const { 열 } = 식별라벨_();
  const 골격 = fs.readFileSync(골격정본_, 'utf8');
  const m = 골격.match(/\[\s*'profiles'\s*,\s*\[([^\]]*)\]\s*\]/);
  assert.ok(m, '정본에서 profiles 행을 못 찾았다 — 도구가 던져야 하는데 여기서 먼저 잡혔다');
  const 정본열 = m[1].split(',').map((s) => s.trim().replace(/^'|'$/g, '')).filter(Boolean);
  assert.deepEqual(열, 정본열, '도구가 읽은 열과 정본이 갈렸다');
  // 분류 전수 — 새 열이 어느 쪽에도 없으면 «조용한 통과»가 된다
  const 미분류 = 정본열.filter((c) => !(c in 식별열_별칭) && !비식별열_.includes(c));
  assert.deepEqual(미분류, [], `profiles 새 열이 분류 안 됐다: ${미분류.join(', ')} — ` +
    'tools/geminilm-export.js 의 식별열_별칭(식별자) 또는 비식별열_(아닌 것)에 넣어라');
  // 별칭 키가 정본에 없는 유령이면 그 축은 영원히 안 돈다(조용한 0건)
  const 유령 = Object.keys(식별열_별칭).filter((c) => !정본열.includes(c));
  assert.deepEqual(유령, [], `식별열_별칭 키가 정본 열에 없다: ${유령.join(', ')} — 그 축은 아무것도 안 잡는다`);
});

test('🔴 게이트를 못 세우면 «0건»이 아니라 던진다 — 조용한 폴백 금지', () => {
  // 정본을 못 읽는 상황을 흉내 낸다: 모듈을 새 경로로 다시 로드할 수 없으므로 파서 계약만 잰다.
  const 도구 = fs.readFileSync(path.join(__dirname, '..', 'tools', 'geminilm-export.js'), 'utf8');
  /* 🔴 구간을 자를 땐 «못 찾으면 던진다» — `indexOf` 가 -1 이면 `slice(x, -1)` 이 오류가 아니라
   *   **파일 꼬리 전체**를 준다. 그러면 아래 단언들이 11.7배 넓은 구간을 재면서 조용히 통과한다
   *   (08-30 재검증 실측: 910자 → 10,652자인데 throw 개수가 우연히 같아 초록). 같은 병이
   *   `tests/반출통로.test.js` 에서 실동작 결함으로 터졌고, 여기 남아 있던 것은 잠복이었다. */
  const 시작 = 도구.indexOf('function 식별라벨_(');
  const 끝 = 도구.indexOf('// 값 꼴 검사');
  assert.notEqual(시작, -1, '시작 표식을 못 찾았다 — 「0건」이 아니라 여기서 죽는 게 맞다');
  assert.notEqual(끝, -1, '끝 표식을 못 찾았다 — 이대로 slice 하면 파일 꼬리를 통째로 재게 된다');
  const fn = 도구.slice(시작, 끝);
  assert.ok(fn.includes('확인 불가'), '못 잰 상태를 「확인 불가」로 드러내지 않는다');
  assert.equal((fn.match(/throw new Error/g) || []).length, 4,
    '던지는 자리가 넷이 아니다 — ①정본 못 읽음 ②profiles 행 못 찾음 ③열 목록 빔 ④새 열 미분류');
  assert.ok(!/return \[\]/.test(fn), '실패를 빈 배열로 접는다 — 그 순간 「0건」이 성공 얼굴을 한다');
});

/* ── ㉣ 실코퍼스 소음 — 첫날부터 우는 검사가 되지 않았나 ─────────────
 * 🔴 [08-30 수리 · 이 절이 「0건이 성공 얼굴」을 하고 있었다]
 *   첫 판은 두 갈래를 **합쳐** 세고 `후보.length > 100` 하나로 분모를 지켰다. 그런데
 *   갈래 하나(`기억`)는 **저장소 밖**(하네스 memory 폴더)이고 `G.walk()` 는 없는 폴더에
 *   예외 없이 `[]` 를 준다. 그래서 문서 갈래 191벌만으로 문턱이 충족되고, **CI·새 체크아웃·
 *   다른 기계에서는 기억 336벌이 언제나 0인데 검사가 한 마디도 안 했다.**
 *   실증: `SYNK_MEMORY_DIR=<없는 곳> node --test tests/반출식별자.test.js` → 기억 0 · 문서 191 ·
 *   그런데 **pass 9 · fail 0**. `.github/workflows/syntax-check.yml` 이 도는 자리가 정확히 그 조건이다.
 *
 *   ⇒ **합산 문턱 하나로는 두 갈래의 죽음을 못 가른다.** 갈래별로 세고 판정을 가른다:
 *     · 뿌리가 **있는데** 분모가 얇다 → 🔴 빨강. 걷기가 죽은 것이다.
 *     · 뿌리가 **없다** → **skip(사유 동봉)**. 저장소 밖 폴더가 없는 것은 CI 의 «정상»이라
 *       빨갛게 만들면 안 된다(우는 검사는 꺼진다). 그러나 조용히 초록으로 넘기면 그게 이 병이다 —
 *       그래서 「이 기계에서는 못 쟀다」가 **실행 출력에 남는다**. 안 잰 것과 0건을 눈으로 가른다. */
const 최소분모_ = 100;   // 두 갈래 모두 오늘 실측 191·336 — 이 아래로 떨어지면 걷기가 죽은 것이다

/** 갈래 하나를 걷는다. 뿌리가 없으면 «못 쟀다»로 돌려준다 — 0벌로 접지 않는다. */
function 갈래_(뿌리) {
  const 잼 = fs.existsSync(뿌리.root);
  return { prefix: 뿌리.prefix, root: 뿌리.root, 잼, 후보: 잼 ? G.walk(뿌리.root) : [] };
}

test('🔴 실코퍼스 갈래가 갈래별로 살아 있다 — 합산 문턱은 한 갈래의 죽음을 안 알려준다', () => {
  const 갈래들 = G.SOURCE_ROOTS.map(갈래_);
  assert.ok(갈래들.length >= 2,
    `SOURCE_ROOTS 가 ${갈래들.length}갈래뿐 — 갈래가 접히면 아래 검사도 같이 접힌다`);
  const 죽은 = 갈래들.filter((g) => g.잼 && g.후보.length < 최소분모_)
    .map((g) => `${g.prefix}: 뿌리는 있는데 ${g.후보.length}벌(<${최소분모_}) — ${g.root}`);
  assert.deepEqual(죽은, [], '걷기가 죽었다(뿌리는 있는데 분모가 얇다):\n  ' + 죽은.join('\n  '));
  // 못 잰 갈래는 실패가 아니라 **출력에 남긴다** — 저장소 밖 뿌리가 없는 것은 CI 의 정상이다
  갈래들.filter((g) => !g.잼).forEach((g) => {
    console.log(`  ⚠ [${g.prefix}] 이 기계에서는 못 쟀다 — 뿌리가 없다: ${g.root}  (0건이 아니라 «안 잰 것»)`);
  });
});

for (const 뿌리 of G.SOURCE_ROOTS) {
  test(`🔴 [${뿌리.prefix}] 이 축이 실물에서 새로 막는 파일은 0벌이다(우는 검사는 꺼진다)`, (t) => {
    const g = 갈래_(뿌리);
    if (!g.잼) {
      t.skip(`이 기계에서는 «${g.prefix}» 코퍼스를 못 쟀다 — 뿌리가 없다(${g.root}). `
        + '저장소 밖 폴더라 CI·새 체크아웃에서는 정상이지만, 이것은 **0건이 아니라 «안 잰 것»**이다.');
      return;
    }
    assert.ok(g.후보.length >= 최소분모_,
      `[${g.prefix}] 수집 후보가 ${g.후보.length}벌뿐(<${최소분모_}) — 걷기가 죽었는데 0건이 나오는 중일 수 있다`);
    const 새로막힌 = [];
    for (const abs of g.후보) {
      const hits = G.scan라벨_(fs.readFileSync(abs, 'utf8'));
      if (hits.length) 새로막힌.push(path.basename(abs) + ' → ' + hits.slice(0, 2).map((h) => h.kind + ' ' + h.value).join(' · '));
    }
    assert.deepEqual(새로막힌, [], `[${g.prefix}] 라벨 축이 실물 ${새로막힌.length}벌을 새로 막는다(분모 ${g.후보.length}벌) — ` +
      '전부 진짜 식별자면 그 파일을 고치고, 오탐이면 값 꼴 검사를 조여라(둘 중 하나를 «반드시» 하고 이 줄을 갱신):\n  ' +
      새로막힌.join('\n  '));
  });
}
