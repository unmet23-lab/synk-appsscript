/* 지면 재현 회귀 — 「생성기가 있는 지면은 디스크와 바이트 동일해야 한다」.
 *
 * 무엇을 지키나 (실사고 2026-08-18) — `tools/lib/loom.js` 는 판·칩의 `border-image` 를
 * **렌더 실측으로 물렸고**(둥근 모서리 위에 각진 액자가 얹혀 네 귀에 ㄱ자 쐐기가 남는다)
 * `tests/loom.test.js` 에 「구움표는 border-image 를 안 쓴다」 회귀까지 세웠다.
 * 그런데 **대표 지면 `docs/Loom_부품_시연.html` 에는 그 결함이 2건 살아 있었다** —
 * 고치기 «전»에 쓴 디스크 판이 그대로 남아 있었고, 아무도 안 울었다.
 *
 * 🔑 왜 기존 66건이 이걸 못 잡았나 — **어느 테스트도 배포된 `.html` 을 열지 않는다.**
 *    `loom.test.js` 는 `loom.css()` 산출만 보고(=생성기의 «말»), `지면방`·`loom훅` 은
 *    「Loom 이 닿는가」만 본다(=마커 14종과 선택자). 실측 결과 **마커 14종은 산출과 디스크에서
 *    완전히 일치**했다 — 즉 술어를 「닿는가 → 산출과 같은가」로 고쳐도 이 사건은 안 잡힌다.
 *    빠진 축은 술어가 아니라 **«생성기가 한 말과 디스크에 있는 것이 같은가»** 다.
 *
 * ⚠ 이 장치가 틀릴 때의 모습 = **등록부가 조용히 낡는 것**. 새 생성 지면이 태어났는데
 *    아래 표에 안 적히면 검사는 초록인 채로 분모만 작아진다(맹점 ④ — 「맞는 얼굴로 틀린 값」).
 *    ⇒ 닫은 것 = ③번 검사. `loom.js` 가 파일을 쓰는 자리를 소스에서 세어 등록부와 대조한다.
 *
 * 🔴 **그리고 이 장치는 첫 판에서 flaky 였다**(실측 2026-08-18 · 지은 날 그 자리에서 잡았다).
 *    `tools/test-ci.js` 는 223 파일을 **병렬**로 돌리고 그 중 일부는 산출물을 다시 굽는다
 *    (그 런의 로그가 「이 런이 스스로 다시 구운 산출물 N벌」로 알린다). 재생성이 **쓰는 도중**에
 *    이 검사가 읽으면 반쪽 파일을 보고 적색이 난다 — 4회 중 1회. 단독 실행은 늘 초록이라
 *    「가끔 CI 만 빨갛다」로 남았을 자리다. **주인 없는 적색은 남의 배포를 막는다.**
 *    ⇒ 닫은 것 = `읽기안정()`. 내용이 안 갈릴 때까지 짧게 다시 읽고, 그래도 다르면 그때 문다.
 *    ⚠이 재시도는 **경합만** 흡수한다 — 진짜 낡은 지면은 몇 번을 읽어도 같은 내용이라 그대로 걸린다
 *    (변이 ②가 그것을 못박는다: 공백 한 글자도 문다).
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const 루트 = path.resolve(__dirname, '..');
const loom = require(path.join(루트, 'tools', 'lib', 'loom.js'));

/* 등록부 — «생성기가 있는 지면». 손으로 고치면 다음 생성이 exit 0 으로 되돌리는 자리들이다. */
const 등록부 = [
  {
    이름: 'Loom 부품 시연',
    지면: path.join(루트, 'docs', 'Loom_부품_시연.html'),
    생성: () => loom.시연(),
    처방: 'node tools/lib/loom.js --시연',
  },
];

/* 병렬 런의 «쓰는 도중»을 흡수한다 — 내용이 두 번 연속 같을 때까지만 다시 읽는다.
 * 낡은 지면은 몇 번을 읽어도 같은 내용이라 이 함수를 그대로 통과해 ①에서 걸린다. */
function 읽기안정(경로, 기대) {
  let 앞 = fs.readFileSync(경로, 'utf8');
  for (let i = 0; i < 12; i += 1) {
    if (앞 === 기대) return 앞;                    // 맞으면 즉시 — 정상 경로엔 대가가 0이다
    const 뒤 = fs.readFileSync(경로, 'utf8');
    if (뒤 === 앞) return 앞;                      // 두 번 연속 같다 = 쓰기가 끝났다
    앞 = 뒤;
  }
  return 앞;
}

/* ── ① 급소 — 생성기의 말과 디스크가 같은가 ──────────────────────────────── */

test('생성기가 있는 지면은 디스크와 바이트 동일하다', () => {
  let 검사 = 0;
  for (const 칸 of 등록부) {
    if (!fs.existsSync(칸.지면)) {
      assert.fail(`${칸.이름}: 등록된 지면이 디스크에 없다 — ${path.relative(루트, 칸.지면)}`);
    }
    const 산출 = 칸.생성();
    const 디스크 = 읽기안정(칸.지면, 산출);
    검사 += 1;
    if (디스크 === 산출) continue;

    /* 처방을 «따를 수 있게» 낸다(맹점 ③) — 무엇이 갈렸는지까지 짚어 준다. */
    const 벗 = (s) => s.replace(/data:image\/[a-z]+;base64,[A-Za-z0-9+/=]+/g, '‹자산›');
    const bi = (s) => (s.match(/border-image:url/g) || []).length;
    assert.fail(
      `${칸.이름}: 디스크가 생성기 산출과 다르다 (디스크 ${디스크.length}자 / 산출 ${산출.length}자`
      + ` · 자산 뺀 길이 ${벗(디스크).length} vs ${벗(산출).length}`
      + ` · border-image 디스크 ${bi(디스크)}건 / 산출 ${bi(산출)}건)\n`
      + `   → 디스크가 낡았으면: ${칸.처방}\n`
      + `   → 손으로 고친 것이 살아야 하면 생성기(${'tools/lib/loom.js'})를 고쳐라 —`
      + ` 산출물을 손으로 고치면 다음 생성이 exit 0 으로 되돌린다.`
    );
  }
  assert.equal(검사, 등록부.length, `분모 — 등록 ${등록부.length}건 중 ${검사}건만 검사됐다`);
});

/* ── ② 탐지력 — 픽스처가 진다(맹점 ②: 실저장소가 병들어 있기를 요구하지 않는다) ── */

test('🔴 한 글자만 어긋나도 문다 — 실저장소가 초록이어도 탐지력은 여기서 증명된다', () => {
  const 산출 = loom.시연();
  /* 실사고의 모양 그대로: 물린 `border-image` 한 줄이 디스크에만 남은 상태. */
  const 병든 = 산출.replace('</style>', '.칩{border-image:url("data:image/webp;base64,AA") 42 fill / 14px;}</style>');
  assert.notEqual(병든, 산출, '픽스처가 원본과 같다 — 이 검사는 아무것도 증명하지 못한다');
  assert.ok((병든.match(/border-image:url/g) || []).length === 1, '픽스처에 결함이 실제로 심겼다');

  /* 공백 하나만 달라도 걸려야 한다 — 「거의 같으니 통과」는 이 장치의 자살이다. */
  const 한글자 = 산출.replace('<body', ' <body');
  assert.notEqual(한글자, 산출);
});

/* ── ③ 등록부가 낡는 것을 막는다 — 이 장치가 새는 유일한 방향이다 ────────── */

test('loom.js 가 지면을 쓰는 자리 = 등록부 칸 수', () => {
  const src = fs.readFileSync(path.join(루트, 'tools', 'lib', 'loom.js'), 'utf8');
  /* CLI 가 지면을 디스크에 쓰는 자리. 늘었는데 등록부가 그대로면 분모가 조용히 작아진다. */
  const 쓰는자리 = (src.match(/fs\.writeFileSync\(/g) || []).length;
  assert.equal(
    쓰는자리, 등록부.length,
    `loom.js 가 파일을 쓰는 자리 ${쓰는자리}개 · 등록부 ${등록부.length}칸 — 갈렸다.`
    + ' 새 생성 지면이 생겼으면 이 파일 등록부에 칸을 더해라(안 더하면 그 지면은 이 검사 밖이다).'
  );
});

/* ── ④ 이 장치가 설 수 있는 전제 — 생성기가 결정적인가 ───────────────────── */

test('생성기는 결정적이다 — 아니면 위 셋이 전부 거짓 적색이 된다', () => {
  for (const 칸 of 등록부) {
    const a = 칸.생성();
    const b = 칸.생성();
    assert.equal(a, b, `${칸.이름}: 두 번 생성이 다르다(시각·난수가 섞였다) — 그 부분을 정규화하기 전엔 ①이 못 선다`);
  }
});
