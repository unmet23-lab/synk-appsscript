test('🔴 탐지력 — **주석에만** 있는 탭 이름은 도달이 아니다(가드는 자기 설명에 눈이 먼다)', () => {
  /* 이 계열 장부의 대표 실패다 — 형제 저장소의 행동층이 「문자열 규칙으로 통일하면 그 순간
   * 주석이 초록이 된다」고 적어 둔 자리. 여기서는 사람이 실제로 쓰는 표기 셋을 다 재본다. */
  for (const 주석 of ["// 이 탭은 'a_log' 다\n", "/* a_log 를 언젠가 읽는다 */\n", "/** a_log */\n"]) {
    const r = 재다((i) => { i.원문['엔진_가짜.js'] = 주석 + 'function 읽는함수_(ss) { return 1; }\n'; });
    assert.deepEqual(종류들(r), ['지목'], `주석 표기 ${JSON.stringify(주석)} 가 도달로 통과했다 — 설명이 코드로 읽혔다`);
  }
  /* 거짓양성도 함께 잰다 — 주석 «과» 코드에 둘 다 있으면 통과해야 한다(아니면 실저장소가 빨개진다). */
  const 성한것 = 재다((i) => { i.원문['엔진_가짜.js'] = "// a_log 설명\nconst t = 'a_log';\nfunction 읽는함수_(ss) { return t; }\n"; });
  assert.deepEqual(성한것.위반, [], '코드에 실재하는데도 빨개진다 — 따를 수 없는 빨강은 장부를 통째로 무시하게 만든다(F103)');
});

