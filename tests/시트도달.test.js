// ── ② 실저장소 — 거짓양성 0 · **분모와 함께** 읽는다(F207) ────────────────────

test('🔑 실저장소 — 장부가 초록이다 · 그리고 몇 종을 재고 초록인지 밝힌다', () => {
  const r = 읽다(ROOT);
  assert.deepEqual(r.위반.map((v) => `${v.종류}/${v.탭 || '-'}: ${v.말}`), [], '시트층 도달 장부 위반');
  assert.ok(r.탭.length >= 9, `수집 탭 ${r.탭.length}종 — 분모가 줄었다. 0이나 소수면 골격의 수집 표식이 통째로 날아간 것이고, 그때 「위반 0」은 거짓말이다`);
  assert.equal(r.셈.전체, r.탭.length);
  assert.equal(r.셈.제품 + r.셈.자산 + r.셈.도달0, r.셈.전체, '제품+자산+도달0 이 전체와 안 맞는다 — 어느 탭이 두 번 세어지거나 빠졌다');
});

test('🔑 실저장소 — 래칫에 슬랙이 없다(오늘의 빚이 곧 상한이라 한 칸만 늘어도 빨개진다)', () => {
  const r = 읽다(ROOT);
  assert.ok(r.셈.도달0 <= r.상한.도달0, `도달0 ${r.셈.도달0} > 상한 ${r.상한.도달0}`);
  assert.ok(r.셈.손 <= r.상한.손, `손 ${r.셈.손} > 상한 ${r.상한.손}`);
  /* 상한이 실측보다 크면 그 차이만큼 **조용히 늘 수 있는 방**이 생긴다 — 래칫의 뜻은
   * 「오늘의 빚을 숫자로 고정」이지 「여유를 둔다」가 아니다. 빚을 갚으면 상한도 같이 내린다. */
  assert.equal(r.셈.도달0, r.상한.도달0, `상한(${r.상한.도달0})이 실측(${r.셈.도달0})보다 크다 — 빚을 갚았으면 상한도 함께 내려라(래칫은 내리는 쪽으로만 움직인다)`);
  assert.equal(r.셈.손, r.상한.손, `손 상한(${r.상한.손})이 실측(${r.셈.손})보다 크다 — 같은 이유`);
});

