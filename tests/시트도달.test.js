'use strict';
/**
 * [v9.243] 시트층 «도달» 장부 회귀 — 「모였는데 안 닿았다」를 **이 층에서도** 기계가 본다.
 *
 * ■ 발단(실측 2026-08-16)
 *   형제 저장소(SYNK-talk `lib/이벤트검증.js`)에는 도달 래칫이 셋 있다 — 그런데 셋 다
 *   **앱 사건 14종**만 센다. 정작 `docs/엔진도달_설계.md` §2-1 이 「지금 실제로 데이터가
 *   쌓이는 유일한 곳」이라 부른 시트층에는 도달 검사가 **0**이었다. 그 층을 열어 세니
 *   수집 장부 9종 중 **5종이 도달 0**이었다(quiz_log·talk_log·voice_log·talk_index_log·
 *   self_declare_log). 앱층의 래칫 셋은 전부 바닥(3·0·2)인데, 오늘 실제로 모이는 것의
 *   절반 이상이 아무도 안 읽는 채로 쌓이고 있었고 **그 0이 어느 화면에도 안 보였다.**
 *
 * ■ 이 층 고유의 함정 = **사람 화면을 도달로 세는 것**
 *   `talk_index_log` 가 그 표본이다. 주간 리포트 꼬리가 그것을 읽으므로 「읽는 코드가 있다」는
 *   참인데, 읽어서 사람에게 보여줄 뿐 다음에 줄 것을 안 바꾼다. 철학 부록 A-1 이 각주로만
 *   적어 둔 갈림(㉠ 행 「모였나 ✓·닿았나 ✗」)이고, 이제 장부가 그것을 진다.
 *   ⚠ 그래서 이 회귀는 **「talk_index_log 는 사유다」를 못박지 않는다** — 그건 버그가 아직
 *     있을 것을 요구하는 회귀다(CLAUDE.md 맹점②). 래칫만 잰다: 내려가면 언제나 통과한다.
 *
 * ■ 탐지력은 **픽스처**가 진다 · 실저장소에는 거짓양성과 **분모**만 묻는다(F207)
 *   실저장소가 초록인 것만으로는 탐지력이 0인 검사와 구분이 안 된다. 아래 ①의 픽스처들이
 *   위반 여섯 종류를 **실제로 재본다**.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
