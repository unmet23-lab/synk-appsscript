'use strict';
/* 몽골어 출구 문 — 「검수 후 노출」을 사람 기억이 아니라 기계가 지킨다.
 *
 * ■ 왜 (2026-09-07 · 유호 확정 「몽골어가 들어가는 모든 번역은 노출 전에 1차 검수를 지난다」)
 *   그날 실측: 학생·학부모가 보는 코드의 몽골어 조각 880개 중 **검문 장부에 지문이 있는 것은 3개**.
 *   검문 도구는 다섯 겹이 잘 돌고 있었는데, 그 겹을 지나는 글이 없었다. 「검수 후 노출」이
 *   사람 기억에만 있었고 기억은 880개를 못 지킨다.
 *
 * ■ 이 자가 지키는 것 둘
 *   ① **새로 들어온 미검문 몽골어가 0** — 기준선에도 장부에도 없는 조각이 있으면 빨강.
 *   ② **기준선은 줄어들기만 한다** — 늘면 빨강. 이게 없으면 「기준선에 넣으면 되지」로
 *      이 문이 조용히 헐거워진다(기억 `test-guards-the-defect` 의 그 무늬).
 *
 * ■ 이 자가 «안» 보는 것 — 먼저 밝힌다
 *   · 문서·설계·장부의 몽골어(사람만 읽는다) · 홍보물·영상 자막(발행 통로가 따로 있다)
 *   · 「검문을 지났다」가 「몽골어가 맞다」는 아니다 — 마지막 도장은 원어민이 찍는다.
 *   · 주석 줄은 뺀다(학생에게 안 간다).
 */
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const 출구 = require(path.join(ROOT, 'tools', '몽골어출구.js'));

test('🔴 학생 화면에 «검문도 기준선도 안 지난» 몽골어가 새로 들어오지 않았다', () => {
  const 조각 = 출구.모으기();
  const 잰 = 출구.잰것들();
  const 기준선 = 출구.기준선읽기();
  const 새것 = [];
  for (const [f, v] of 조각) {
    if (잰.has(f) || 기준선.has(f)) continue;
    새것.push(`${v.자리[0]}  ${v.글.slice(0, 50)}`);
  }
  assert.deepStrictEqual(새것, [],
    '검문을 안 지난 몽골어가 학생 접점에 새로 들어왔다 — 노출 전에 태운다:\n'
    + 새것.map((s) => '  · ' + s).join('\n')
    + '\n  태우는 법: node tools/몽골어대조.js "<한국어 원문>" "<몽골어>"'
    + '\n  🔑 원문이 없으면 그 자체가 결함이다 — 무엇을 옮긴 것인지 모르는 문장은 학생에게 못 낸다.');
});

test('🔑 기준선은 «줄어들기만» 한다 — 늘면 이 문이 헐거워진 것이다', () => {
  const 기준선 = 출구.기준선읽기();
  if (!기준선.size) return;   // 아직 안 세웠으면 잴 것이 없다
  const 적힌수 = JSON.parse(fs.readFileSync(출구.기준선경로, 'utf8')).개수;
  assert.strictEqual(기준선.size, 적힌수, '기준선 파일의 「개수」와 실제 지문 수가 다르다 — 손으로 고쳤나');

  /* 기준선 안의 지문이 «지금 코드에 실재»하는지도 본다. 코드에서 사라진 지문이 남아 있으면
   * 분모가 부풀어 「줄어들고 있다」는 착시가 생긴다. */
  const 조각 = 출구.모으기();
  const 유령 = [...기준선].filter((f) => !조각.has(f));
  assert.ok(유령.length <= 기준선.size,
    '기준선에 코드에 없는 지문이 있다 — 기준선을 다시 쓴다: node tools/몽골어출구.js --기준선쓰기');
});

test('🔑 조각 뽑는 자가 «몽골어»와 «몽골어를 인용한 한국어»를 가른다', () => {
  // 진짜 몽골어 문안
  assert.ok(출구.몽골어인가('Өнөөдөр юу сурсан бэ? Надад зааж өгөөч!'), '몽골어 문장을 못 알아본다');
  // 몽골어 낱말을 인용한 한국어 해설 — 이건 학생에게 가는 문안이 아니다
  assert.ok(!출구.몽골어인가('요일이 속격(`Даваа гарагийн`)이어야 뒤 명사를 꾸민다'),
    '한국어 해설문을 몽골어로 세고 있다 — 09-07 에 이 구멍으로 엉뚱한 넉 줄을 검문에 태웠다');
  // 짧은 조각은 안 센다(문안이 아니라 표식일 때가 많다)
  assert.ok(!출구.몽골어인가('Бат'), '이름 한 낱말을 문안으로 세고 있다');
});

test('🔴 검문 한 판의 갈래는 «종료코드»가 아니라 «종합 줄»이 정한다 (09-08 실측)', () => {
  const 종합 = (줄) => `모델: gemini-3.8-flash\n\n■ 종합: ${줄}\n   장부: docs/_ops/몽골어검문.jsonl\n`;
  // 자식이 종료 도중 죽어 종료코드가 크래시 값이 돼도, 판정은 이미 났다.
  const 크래시 = 3221226505; // Windows 0xC0000409 — 옛 판이 제미나이 호출 뒤 process.exit() 로 끊다가 냈다
  assert.strictEqual(출구.한판읽기(종합('🟡 반쪽 — 두 겹만 쟀다(뜻은 안 쟀다)'), 크래시).갈래, '통과',
    '반쪽 판정을 «못 쟀다»로 세고 있다 — 이 오해가 855개 대청소를 세 개 만에 멈췄다');
  assert.strictEqual(출구.한판읽기(종합('🔴 사람 검수 필요 (문법 판정: 파손)'), 크래시).갈래, '검수',
    '「사람 눈으로 가라」는 판정이 난 것이지 막힌 게 아니다');
  assert.strictEqual(출구.한판읽기(종합('✅ 기계 검문 통과'), 0).갈래, '통과');
  // 종합 줄이 «아예 없을» 때만 못 쟀다 — 벽으로 세는 것은 이것뿐이다.
  assert.strictEqual(출구.한판읽기('확인 불가: 열쇠 파일이 없다', 2).갈래, '불가');
  assert.strictEqual(출구.한판읽기('', null).갈래, '불가');
});

test('🔴 «층이 미실행»은 지적이 아니라 «답이 없는 것»이다 — 갈라 세지 않으면 거짓 숫자가 선다 (09-08)', () => {
  /* 맞춤법 층(spellcheck.mn)에는 시간당 몫이 있다. 130개를 태워 보니 서른 몇 개째부터 벽에 닿아
   * 72개가 「층 미실행」이었는데, 뭉쳐 세면 「맞춤법 지적 63건」이 된다 — 진짜 지적은 3건이었다.
   * 🔑 이 갈래가 없으면 벽에 닿은 뒤로도 계속 태워 «반쪽의 반쪽»만 쌓이고 크레딧이 나간다. */
  const 종합 = (줄) => `모델: gemini-3.8-flash\n\n■ 종합: ${줄}\n   장부: docs/_ops/몽골어검문.jsonl\n`;
  assert.strictEqual(출구.한판읽기(종합('🔴 사람 검수 필요 (맞춤법 층 미실행 (원문없음 · 두 겹만))'), 2).갈래, '못잼',
    '「안 쟀다」를 「사람 눈으로 가라」와 같이 세고 있다');
  assert.strictEqual(출구.한판읽기(종합('🔴 사람 검수 필요 (맞춤법 층 미실행(spellcheck.mn 못 닿음 — 사람 검수 필요))'), 2).갈래, '못잼',
    '다섯 겹 갈래의 미실행 문구도 같은 갈래여야 한다');
  // 진짜 지적은 그대로 «검수»다 — 이 둘이 섞이면 이 갈래가 무의미해진다.
  assert.strictEqual(출구.한판읽기(종합('🔴 사람 검수 필요 (맞춤법 의심 1건 (원문없음 · 두 겹만))'), 2).갈래, '검수');
  assert.strictEqual(출구.한판읽기(종합('🔴 사람 검수 필요 (문법 판정: 어색 (원문없음 · 두 겹만))'), 2).갈래, '검수');
});
