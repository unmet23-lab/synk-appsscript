/* 자율기록 회귀 — 자율주행 갈림길을 유호님 바탕화면까지 나르는 통로(유호 상시 지시 2026-08-09).
 *
 * 탐지력은 **전부 이 픽스처가 진다** — 실제 jsonl·실제 바탕화면 상태와 무관하게 잡힌다
 * (repo 밖 환경에 기대는 검사는 CI 에서 깨진다 · CLAUDE.md 신뢰성 조항).
 *
 * 못박는 실패 형태 넷:
 *   ① **깨진 줄이 조용히 사라지는 것** — 기록이 준 걸 아무도 모르는 게 최악이다.
 *   ② **`되돌리기` 빈 채로 들어가는 것** — 목록만 늘고 유호님 판정 재료가 안 된다.
 *   ③ **판정이 결정을 덮어써서 「원래 뭐였는지」가 사라지는 것** — append-only 를 읽는 층에서 접는다.
 *   ④ **자기 처방을 막는 것**(가드 세 맹점 ③) — 거절 메시지가 시키는 대로 채우면 통과해야 한다.
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert');

const { 파싱, 다음번호, 검증, 접기, HTML, esc, 결과값, 필수 } = require('../tools/자율기록.js');

const 온전한결정 = {
  종류: '결정',
  번호: 1,
  날짜: '2026-08-09',
  영역: '앱 화면',
  제목: '답장 화면을 최신 1건만 보여준다',
  고른것: '최신 교정 1건 + 버튼 둘',
  대안: ['전체 목록', '읽음 표시 추가'],
  근거: '학생이 매일 여는 화면이라 고를 게 많으면 안 연다',
  되돌리기: 'talk `app/corrections.tsx` 한 화면 — 반나절',
  저장소: 'talk',
  커밋: 'abc1234',
};

/* ── 파싱 ─────────────────────────────────────────────────── */

test('파싱: 빈 줄과 공백 줄은 세지 않는다', () => {
  const r = 파싱('{"번호":1}\n\n  \n{"번호":2}\n');
  assert.strictEqual(r.length, 2);
});

test('파싱: 깨진 줄은 버리지 않고 깨짐으로 남는다 — 조용히 사라지면 준 걸 모른다', () => {
  const r = 파싱('{"번호":1}\n{이건 JSON 이 아니다\n');
  assert.strictEqual(r.length, 2);
  assert.strictEqual(r[1].깨짐, 2, '깨진 줄의 줄번호가 남아야 연다');
  assert.match(r[1].원문, /JSON 이 아니다/);
});

test('파싱: JSON 이지만 객체가 아닌 줄도 깨짐이다', () => {
  const r = 파싱('"그냥 문자열"\n42\n');
  assert.strictEqual(r.filter((x) => x.깨짐).length, 2);
});

/* ── 다음번호 ─────────────────────────────────────────────── */

test('다음번호: 빈 기록은 1', () => {
  assert.strictEqual(다음번호([]), 1);
});

test('다음번호: 최대값+1 — 중간이 비어도 뒤에 붙는다(번호는 안정 ID 다)', () => {
  assert.strictEqual(다음번호([{ 번호: 1 }, { 번호: 5 }, { 번호: 3 }]), 6);
});

test('다음번호: 깨진 줄·번호 없는 줄은 세지 않는다', () => {
  assert.strictEqual(다음번호([{ 깨짐: 2, 원문: 'x' }, { 번호: 2 }, {}]), 3);
});

/* ── 검증 (맹점 ②·④) ─────────────────────────────────────── */

test('검증: 온전한 결정은 통과', () => {
  assert.deepStrictEqual(검증(온전한결정), []);
});

test('검증: 「되돌리기」가 없으면 거절 — 바꾸는 비용이 없으면 판정 재료가 아니다', () => {
  const d = { ...온전한결정 };
  delete d.되돌리기;
  const 문제 = 검증(d);
  assert.strictEqual(문제.length, 1);
  assert.match(문제[0], /되돌리기/);
});

test('검증: 필수 넷이 모두 검사된다 — 하나만 남기고 지워도 각각 잡힌다', () => {
  for (const k of 필수) {
    const d = { ...온전한결정 };
    d[k] = '   ';
    assert.ok(검증(d).some((m) => m.includes(k)), `${k} 가 공백인데 통과했다`);
  }
});

test('검증: 대안이 배열도 문자열도 아니면 잡는다', () => {
  assert.ok(검증({ ...온전한결정, 대안: { a: 1 } }).some((m) => m.includes('대안')));
});

test('맹점③ 자기 처방 — 거절이 시키는 대로 「되돌리기」를 채우면 그대로 통과한다', () => {
  const 거절된것 = { 제목: 'ㄱ', 고른것: 'ㄴ', 근거: 'ㄷ' };
  assert.ok(검증(거절된것).length > 0);
  assert.deepStrictEqual(검증({ ...거절된것, 되돌리기: '파일 한 곳 · 30분' }), []);
});

/* ── 접기 (맹점 ③ = 원본 보존) ────────────────────────────── */

test('접기: 판정이 없으면 결과는 대기', () => {
  const { 목록 } = 접기([온전한결정]);
  assert.strictEqual(목록[0].결과, '대기');
});

test('접기: 판정이 얹혀도 결정 본문(고른것·근거)은 그대로 남는다', () => {
  const { 목록 } = 접기([
    온전한결정,
    { 종류: '판정', 번호: 1, 날짜: '2026-08-12', 결과: '바꿈', 메모: '전체 목록으로' },
  ]);
  assert.strictEqual(목록[0].결과, '바꿈');
  assert.strictEqual(목록[0].판정메모, '전체 목록으로');
  assert.strictEqual(목록[0].고른것, 온전한결정.고른것, '판정이 결정을 덮어쓰면 안 된다');
});

test('접기: 판정이 두 번이면 뒤(=최신)가 이긴다 — append-only 를 읽는 층에서 접는다', () => {
  const { 목록 } = 접기([
    온전한결정,
    { 종류: '판정', 번호: 1, 결과: '유지' },
    { 종류: '판정', 번호: 1, 결과: '바꿈' },
  ]);
  assert.strictEqual(목록[0].결과, '바꿈');
});

test('접기: 모르는 결과값은 대기로 떨어진다 — 오타가 「판정됨」으로 보이지 않게', () => {
  const { 목록 } = 접기([온전한결정, { 종류: '판정', 번호: 1, 결과: '바꾸자' }]);
  assert.strictEqual(목록[0].결과, '대기');
});

test('접기: 번호 중복은 조용히 덮지 않고 드러낸다 — 동시 세션 채번 충돌의 유일한 지문', () => {
  const { 목록, 중복 } = 접기([온전한결정, { ...온전한결정, 제목: '다른 결정' }]);
  assert.deepStrictEqual(중복, [1]);
  assert.strictEqual(목록.length, 1);
  assert.strictEqual(목록[0].제목, 온전한결정.제목, '먼저 쓴 것이 남는다');
});

test('접기: 번호순으로 정렬된다(파일 순서가 아니라)', () => {
  const { 목록 } = 접기([
    { ...온전한결정, 번호: 3 },
    { ...온전한결정, 번호: 1 },
    { ...온전한결정, 번호: 2 },
  ]);
  assert.deepStrictEqual(목록.map((d) => d.번호), [1, 2, 3]);
});

test('접기: 대안이 문자열이어도 배열로 정규화된다(렌더가 갈리지 않게)', () => {
  const { 목록 } = 접기([{ ...온전한결정, 대안: '하나뿐' }]);
  assert.deepStrictEqual(목록[0].대안, ['하나뿐']);
});

test('접기: 깨진 줄은 목록 밖으로 빠지되 깨짐에 남는다', () => {
  const { 목록, 깨짐 } = 접기([온전한결정, { 깨짐: 7, 원문: 'xx' }]);
  assert.strictEqual(목록.length, 1);
  assert.strictEqual(깨짐.length, 1);
});

/* ── HTML ─────────────────────────────────────────────────── */

test('esc: 꺾쇠·따옴표가 태그로 새지 않는다', () => {
  assert.strictEqual(esc('<b>"&</b>'), '&lt;b&gt;&quot;&amp;&lt;/b&gt;');
});

test('HTML: 결정 본문이 이스케이프돼 들어간다 — 제목의 꺾쇠가 마크업이 되지 않는다', () => {
  const h = HTML(접기([{ ...온전한결정, 제목: '<script>깨기</script>' }]), '2026-08-09 12:00');
  assert.ok(h.includes('&lt;script&gt;깨기'), '제목이 이스케이프되지 않았다');
  assert.ok(!h.includes('<script>깨기'), '태그가 그대로 새어 나갔다');
});

test('HTML: 카드마다 판정·영역이 data 속성으로 붙는다(필터가 그걸로 돈다)', () => {
  const h = HTML(접기([온전한결정]), '');
  assert.ok(h.includes('data-r="대기"'));
  assert.ok(h.includes('data-a="앱 화면"'));
});

test('HTML: 「바꾸려면」 칸이 카드마다 렌더된다 — 이게 없으면 목록만 길어진다', () => {
  const h = HTML(접기([온전한결정]), '');
  assert.ok(h.includes('바꾸려면'));
  assert.ok(h.includes('반나절'));
});

test('HTML: 안 고른 대안이 보인다 — 「왜 이걸 안 골랐나」가 수정의 재료다', () => {
  const h = HTML(접기([온전한결정]), '');
  assert.ok(h.includes('전체 목록'));
  assert.ok(h.includes('읽음 표시 추가'));
});

test('HTML: 대기 건수가 머리에 뜬다', () => {
  const h = HTML(접기([온전한결정, { ...온전한결정, 번호: 2 }]), '');
  assert.match(h, /대기<b>2<\/b>/);
});

test('HTML: 깨진 줄·번호 중복이 화면에 경고로 뜬다 — 정본 손상이 조용하면 안 된다', () => {
  const h = HTML(접기([온전한결정, { ...온전한결정, 제목: '중복' }, { 깨짐: 3, 원문: 'x' }]), '');
  assert.ok(h.includes('번호가 겹칩니다'));
  assert.ok(h.includes('읽지 못한 줄'));
});

test('HTML: 0건이어도 깨지지 않고 빈 상태를 말한다', () => {
  const h = HTML(접기([]), '');
  assert.ok(h.includes('아직 기록된 결정이 없습니다'));
});

test('HTML: 코랄은 면으로만 쓴다 — 라이트 배경 코랄 글자는 킷 철칙 ② 위반', () => {
  const h = HTML(접기([온전한결정]), '');
  const 글자로쓴것 = [...h.matchAll(/color:\s*var\(--coral\)/g)];
  /* 유일한 예외 = 다크 머리(navy2) 위 숫자. 라이트 카드 쪽엔 하나도 없어야 한다. */
  assert.strictEqual(글자로쓴것.length, 1, '코랄 글자가 다크 머리 밖으로 번졌다');
  assert.ok(/\.counts \.hot b\{color:var\(--coral\)\}/.test(h), '그 하나는 다크 머리 안이어야 한다');
});

test('HTML: script 여는 태그와 닫는 태그 수가 맞는다(F047 지문)', () => {
  const h = HTML(접기([온전한결정]), '');
  assert.strictEqual((h.match(/<script\b/g) || []).length, (h.match(/<\/script\s*>/g) || []).length);
});

test('결과값: 네 가지뿐 — 늘리면 필터·배지 CSS 도 같이 늘려야 한다', () => {
  assert.deepStrictEqual(결과값, ['대기', '유지', '바꿈', '보류']);
});
