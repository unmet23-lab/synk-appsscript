// tests/시트흉내계약.test.js — 가짜 시트 흉내의 «계약»을 기계로 물린다 (#Q85 · F460)
// 실행: node tests/시트흉내계약.test.js
//
// ■ 이 파일이 지키는 것
//   흉내가 라이브 Sheets 와 갈라지는 것을 «양쪽 방향»으로 잡는다.
//     · 착한 쪽(흉내가 너그러움) → 조용한 초록  (F460 1번째: Date 삼킴 미흉내 → 라이브만 중복 적재)
//     · 사나운 쪽(흉내가 엄함)   → 거짓 적색    (F460 2번째: 폭 1 쓰기가 나머지 9열을 날림)
//   두 사고 다 «변이»가 잡았다 — 평소 초록으로는 원리상 안 보인다.
//
// ■ 탐지력은 **픽스처가 진다** (지침 v9.2 「가드·회귀의 네 맹점」 ②)
//   실저장소에는 「공용 통로가 계약을 지킨다」는 **거짓양성 검사만** 둔다.
//   「버그가 아직 있을 것」을 요구하는 검사는 하나도 없다 — 아래 갈라짐 검사도 부분집합이라,
//   면제된 파일이 공용 통로로 이주하면 목록이 줄 뿐 빨개지지 않는다(자기 처방을 막지 않는다 · 맹점 ③).
//
// ■ 라이브 Sheets 를 부르지 않는다
//   계약은 문서·픽스처로 진다. 부르는 순간 시험이 네트워크·자격증명에 기대고 CI 에서 깨진다(F296).

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { 시트흉내, 계약검사, 계약조항 } = require('./lib/시트흉내.js');

const TESTS = __dirname;

/* ─────────────────────────────────────────────────────────────
   1. 실저장소 — 거짓양성만 (공용 통로가 계약을 지키는가)
   ───────────────────────────────────────────────────────────── */

test('공용 통로 `시트흉내` 가 계약 6조를 전부 지킨다', () => {
  const 위반 = 계약검사(시트흉내);
  assert.deepEqual(위반, [],
    '공용 흉내가 자기 계약을 어긴다 — 이 흉내를 쓰는 모든 시험이 한꺼번에 같은 방향으로 틀어진다:\n'
    + 위반.map((v) => '  · ' + v.조 + ' → ' + v.무엇).join('\n'));
});

test('계약검사는 «첫행» 두 관례를 다 받는다 — 통짜 격자(첫행 1)에서도 같은 판정이 나온다', () => {
  /* 이 저장소에 두 관례가 다 있다: `data` 가 2행부터인 것(발화퀄리티)과 헤더까지 담는 통짜 격자(궤적·접수감시).
   *   한 관례만 받으면 나머지 흉내들은 이주할 수 없고, 그러면 계약은 적혀만 있고 안 물린다. */
  const 통짜 = (옵션) => 시트흉내({ 첫행: 1, 행들: (옵션.행들 || []).map((r) => r.slice()) });
  const sh = 통짜({ 행들: [['헤더'], ['x']] });
  assert.equal(sh.getLastRow(), 2, '통짜 격자에서 getLastRow 가 어긋난다');
  sh.getRange(2, 1, 1, 1).clearContent();
  assert.equal(sh.getLastRow(), 1, '통짜 격자에서 「비운 꼬리는 안 센다」가 안 지켜진다');
});

/* ─────────────────────────────────────────────────────────────
   2. 변이 픽스처 — 탐지력 (착한 쪽·사나운 쪽 둘 다 빨개지는가)
   ───────────────────────────────────────────────────────────── */

/** 흉내 하나를 만들되 `범위` 객체의 메서드를 갈아끼운다. */
const 범위뒤틀기 = (바꾸기) => (옵션) => {
  const sh = 시트흉내(옵션);
  const 원래 = sh.getRange.bind(sh);
  sh.getRange = function (r, c, n, w) {
    const rng = 원래(r, c, n, w);
    바꾸기(rng, { sh, r, c, n: n || 1, w: w || 1, i0: r - sh.첫행 });
    return rng;
  };
  return sh;
};

/** 흉내 자체(시트 층)를 갈아끼운다. */
const 시트뒤틀기 = (바꾸기) => (옵션) => {
  const sh = 시트흉내(옵션);
  바꾸기(sh);
  return sh;
};

