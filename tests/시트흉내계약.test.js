test('변이 픽스처 — 뒤튼 흉내를 계약검사가 «전부» 잡는다(착한 쪽·사나운 쪽 둘 다)', () => {
  const 놓친 = [];
  변이들.forEach((m) => {
    const 위반 = 계약검사(m.만들기);
    if (!위반.some((v) => v.조 === m.조)) {
      놓친.push(`${m.방향} · ${m.이름} → 「${m.조}」 를 못 잡았다 (잡은 것: ${JSON.stringify(위반.map((v) => v.조))})`);
    }
  });
  assert.deepEqual(놓친, [], '계약검사의 탐지력에 구멍이 있다:\n  · ' + 놓친.join('\n  · '));

  // 분모를 함께 낸다 — 「0 놓침」이 「0건 돌았다」와 같은 모양이 되면 안 된다(F207)
  assert.equal(변이들.length, 9, '변이 수가 바뀌었다 — 분모를 보고에 그대로 쓰므로 여기도 같이 고친다');
  const 착함 = 변이들.filter((m) => m.방향 === '착함').length;
  const 사나움 = 변이들.filter((m) => m.방향 === '사나움').length;
  assert.ok(착함 >= 1 && 사나움 >= 1, `한 방향만 덮었다 — 착함 ${착함} · 사나움 ${사나움}`);
});

test('변이 픽스처가 계약 6조를 «하나도 안 빼고» 덮는다', () => {
  const 덮인 = new Set(변이들.map((m) => m.조));
  const 빈조 = Object.values(계약조항).filter((조) => !덮인.has(조));
  assert.deepEqual(빈조, [],
    '변이가 없는 조항이 있다 — 그 조항은 «적혀만 있고» 탐지력이 0이다:\n  · ' + 빈조.join('\n  · '));
});

/* ─────────────────────────────────────────────────────────────
   3. 갈라짐 예방 — 되읽는 쓰기 흉내를 «새로» 지으면 공용 통로를 쓴다
   ───────────────────────────────────────────────────────────── */

/** 정의부만 센다 — 호출(`.setValues(`)은 앞에 점이 있다. */
const 정의됨 = (src, 이름) => new RegExp('(^|[^.\\w])' + 이름 + '\\s*[:(]').test(src);

/**
 * 지금 남아 있는 손수 지은 «되읽는» 흉내 — 실측 2026-08-15(#Q85).
 * 이 목록은 **상한이지 하한이 아니다**: 이주해서 사라지면 검사는 그대로 초록이다.
 * 사유를 적는 이유 = 다음 사람이 「왜 아직 여기 있나」를 안 물어도 되게.
 *
 * 08-15 이주분 4(궤적·접수감시·크루카드·v9125회귀)는 공용 통로로 옮겨 여기서 뺐다.
 * 남은 둘은 «시트 흉내»가 아니라 다른 것이다 — 그래서 통로를 태울 자리가 아니다.
 */
const 면제 = {
  'safety.test.js': '캡처 전용(w.push) — 쓴 값을 되읽지 않아 F460 두 방향으로 샐 수 없다',
  '접수감시.test.js': '한 시험 전용 덮어쓰기 스텁 — 「행이 밀린 상태」를 만들려고 getRange 를 그 시험에서만 갈아끼운다(시트 흉내가 아니라 시나리오다)'
};

test('되읽는 쓰기 흉내를 «새로» 지으면 공용 통로를 쓴다 — 면제 목록 밖이면 빨개진다', () => {
  const 발견 = fs.readdirSync(TESTS)
    .filter((f) => f.endsWith('.test.js'))
    .filter((f) => {
      const src = fs.readFileSync(path.join(TESTS, f), 'utf8');
      return 정의됨(src, 'setValues') && 정의됨(src, 'getValues');
    });

  assert.ok(발견.length > 0, '탐지기가 0건을 냈다 — 통로가 바뀌었을 수 있다(0건은 초록이 아니라 미측정이다 · F207)');

  const 새로생김 = 발견.filter((f) => !Object.prototype.hasOwnProperty.call(면제, f));
  assert.deepEqual(새로생김, [],
    '시트 흉내를 손으로 새로 지었다 — `tests/lib/시트흉내.js` 의 `시트흉내()` 를 쓴다.\n'
    + '  (그 흉내가 계약과 다르게 굴어야 하는 «이유»가 있으면, 이 파일의 `면제` 에 사유와 함께 적는다)\n'
    + '  새로 잡힌 파일: ' + JSON.stringify(새로생김));

  // 낡은 면제는 치운다 — 없는 파일을 면제해 두면 목록이 지도 노릇을 못 한다
  const 사라진 = Object.keys(면제).filter((f) => !fs.existsSync(path.join(TESTS, f)));
  assert.deepEqual(사라진, [], '면제 목록에 없는 파일이 있다 — 지운다: ' + JSON.stringify(사라진));
});
