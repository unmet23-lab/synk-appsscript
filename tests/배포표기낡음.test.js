#!/usr/bin/env node
/* 버전 이력의 «미배포» 표기가 낡았는지 — docs/버전_이력.md 자기모순 검사
 *
 * 무엇을 지키나 (2026-08-14 · 두 번째 실측): v9.215~219 다섯 항목이 「⛔ **미배포**」로 서 있는데,
 *   같은 파일 아래 [v9.220] 줄은 「배포 완주 … **v9.215~220 을 한 번에** 밀었다」고 적고 있었다.
 *   문서가 자기 자신과 어긋난 채 이틀을 갔고, **그 자리를 이종 검수가 두 번 지적했다** —
 *   한 번은 v9.220 이 배포되던 날(그 줄이 스스로 기록해 뒀다), 또 한 번은 08-14 `c0f148aa` 재검수
 *   P3 두 건(「v9.217 은 미배포라 ④ 닿았나 ✗」). 같은 절차에서 두 번째면 실수가 아니라 시스템 결함이다.
 *   검수자는 문서를 읽고 판정하므로, 낡은 표기는 **매번 새 지적으로 되살아나고** 그 지적을 처분하는
 *   비용이 세션마다 다시 든다.
 *
 * 탐지 능력은 **픽스처가 진다** — 아래 가짜 이력 문자열에서 잰다.
 *   실저장소(docs/버전_이력.md)에는 **거짓양성만** 묻는다(CLAUDE.md 가드 맹점 ②).
 *
 * ⚠ **대가 — 이 장치가 틀릴 때의 모습**: 이건 «문서 안의 자기모순»만 본다. 라이브에 올라갔는데
 *   그 사실을 **문서 어디에도 안 적은** 경우는 못 잡는다(모순이 없으니 초록이다). 그 층은 repo 밖이라
 *   CI 가 못 재고(F296), 재는 자리는 이미 있다 — `node tools/배포판점검.js --라이브`.
 *   그래서 이 검사의 초록은 「배포 표기가 최신이다」가 아니라 **「이 파일이 자기와 안 싸운다」**로 읽는다.
 * ⚠ **닫은 것 = 없다.** 이 자리를 보던 검사가 0개였다(`grep -rn 미배포 tests/` 실측 = 무관한 3건뿐).
 *   기존 검사를 줄이는 대신 파일 하나·순수 함수 하나로 끝냈다(훅·상주 계기 신설 0).
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const 정본 = path.resolve(__dirname, '..', 'docs', '버전_이력.md');

/** 'v9.215' → [9, 215]. 비교는 두 칸 숫자로 한다(문자열 비교면 v9.99 > v9.215 가 된다). */
const 판번호 = (s) => String(s).split('.').map(Number);
const 이하 = (a, b) => (a[0] !== b[0] ? a[0] < b[0] : a[1] <= b[1]);
const 범위안 = (v, 가, 나) => 이하(가, v) && 이하(v, 나);

/** 항목 머리 — `**[v9.217]** …` 와 `## [v9.221] …` 두 모양이 다 쓰인다. */
const 머리 = /^(?:##\s*)?\*{0,2}\[v(\d+\.\d+)\]/;
/** 표기 줄 — 프로즈 속 「미배포」 언급(회고·설명)과 가르려고 **표식 모양**만 문다. */
const 미배포표식 = /^\s*[-*]?\s*⛔\s*\*{0,2}\s*미배포/;
/** 배포 기록이 덮는 판 범위 — 「v9.215~220」·「v9.215~v9.220」 둘 다. */
const 배포범위 = /v(\d+\.\d+)\s*~\s*v?(\d+(?:\.\d+)?)/g;
const 배포기록 = /배포\s*(?:완주|됨)/;

/**
 * 「⛔미배포」로 서 있는 판이, 같은 파일의 배포 기록이 «덮는다»고 적은 범위 안에 드는가.
 * @returns {{버전:string, 근거:string}[]} 모순 목록(비면 깨끗)
 */
function 낡은미배포(md) {
  const 줄들 = String(md).split(/\r?\n/);
  const 미배포판 = [];
  const 덮인범위 = [];
  let 현재 = null;
  for (const 줄 of 줄들) {
    const m = 머리.exec(줄);
    if (m) { 현재 = m[1]; continue; }
    if (현재 && 미배포표식.test(줄)) 미배포판.push(현재);
    if (배포기록.test(줄)) {
      배포범위.lastIndex = 0;
      let r;
      while ((r = 배포범위.exec(줄)) !== null) {
        const 가 = 판번호(r[1]);
        /* 「v9.215~220」의 뒤쪽은 마이너만 적힌다 — 앞쪽 메이저를 물려받는다. */
        const 뒤 = r[2].includes('.') ? 판번호(r[2]) : [가[0], Number(r[2])];
        덮인범위.push({ 가, 나: 뒤, 줄: 줄.trim() });
      }
    }
  }
  const 결과 = [];
  for (const v of 미배포판) {
    const 판 = 판번호(v);
    const 덮음 = 덮인범위.find((r) => 범위안(판, r.가, r.나));
    if (덮음) 결과.push({ 버전: `v${v}`, 근거: 덮음.줄.slice(0, 120) });
  }
  return 결과;
}

/* ── 픽스처 — 탐지력은 여기서 잰다 ─────────────────────────────────────────── */
const 픽스처머리 = '# 버전 이력\n\n';
const 미배포항목 = (v, 표기 = '- ⛔ **미배포** — 다음 묶음에 합류.') => `**[v${v}]** 무언가 고침 (2026-01-01)\n- 회귀 1.\n${표기}\n\n`;
const 배포항목 = (v, 줄) => `**[v${v}]** 무언가 고침 (2026-01-02)\n- ✅ **배포 완주 2026-01-02** — ${줄}\n\n`;

test('탐지 — 「미배포」 판이 뒤 항목의 배포 범위 안에 들면 잡는다 (v9.215~219 실사고 모양)', () => {
  const md = 픽스처머리
    + 미배포항목('9.10') + 미배포항목('9.11')
    + 배포항목('9.12', '**v9.10~12 를 한 번에** 밀었다.');
  const 낡음 = 낡은미배포(md);
  assert.deepStrictEqual(낡음.map((x) => x.버전), ['v9.10', 'v9.11'],
    '자기모순 2건을 다 잡아야 한다 — 하나만 잡으면 남은 하나가 다음 검수에서 또 지적된다');
});

test('탐지 — 범위를 「v9.10~v9.12」로 적어도 같은 판정이다 (표기 흔들림에 안 뚫린다)', () => {
  const md = 픽스처머리 + 미배포항목('9.11') + 배포항목('9.12', 'v9.10~v9.12 묶음.');
  assert.strictEqual(낡은미배포(md).length, 1);
});

test('탐지 — 「✅배포됨」으로만 적힌 기록도 범위를 낸다', () => {
  const md = 픽스처머리 + 미배포항목('9.11')
    + '**[v9.12]** 무언가 (2026-01-02)\n- ✅ **배포됨** — v9.10~12 한 묶음.\n\n';
  assert.strictEqual(낡은미배포(md).length, 1);
});

test('거짓양성 0 — 배포 범위 밖의 「미배포」는 그대로 둔다(아직 안 나간 판을 빨갛게 만들면 가드를 끈다)', () => {
  const md = 픽스처머리 + 미배포항목('9.9') + 배포항목('9.12', 'v9.10~12 를 한 번에 밀었다.');
  assert.deepStrictEqual(낡은미배포(md), []);
});

test('거짓양성 0 — 표식이 아니라 회고 프로즈 속 「미배포」는 안 문다', () => {
  const md = 픽스처머리
    + '**[v9.11]** 무언가 (2026-01-01)\n  🔑 이 줄이 오래 「미배포」로 서 있어 검수가 지적했다 — 그 지적은 이 배포가 해소다.\n\n'
    + 배포항목('9.12', 'v9.10~12 를 한 번에 밀었다.');
  assert.deepStrictEqual(낡은미배포(md), []);
});

test('거짓양성 0 — 마이너 숫자 비교는 문자열이 아니다 (v9.99 가 v9.215 보다 크지 않다)', () => {
  const md = 픽스처머리 + 미배포항목('9.99') + 배포항목('9.220', 'v9.215~220 를 한 번에 밀었다.');
  assert.deepStrictEqual(낡은미배포(md), [], 'v9.99 는 215~220 밖이다 — 문자열 비교면 여기서 거짓양성이 난다');
});

/* ── 실저장소 — 거짓양성만 묻는다 ──────────────────────────────────────────── */
test('🔴 실저장소 docs/버전_이력.md 에 낡은 「미배포」 표기가 없다', () => {
  const md = fs.readFileSync(정본, 'utf8');
  const 낡음 = 낡은미배포(md);
  assert.deepStrictEqual(낡음, [],
    '이 판들은 문서 자신이 「배포 완주」라고 적은 범위 안이다 — 표기를 갱신해라:\n'
    + 낡음.map((x) => `  · ${x.버전} ← ${x.근거}`).join('\n'));
});

module.exports = { 낡은미배포 };
