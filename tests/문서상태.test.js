/* 문서 상태 줄 파서 회귀 — 2026-08-09 신설.
 *
 * 왜: `tools/문서상태.js` 의 **첫 판이 자기가 읽어야 할 8줄 중 7줄을 못 봤다.** 정규식이
 *   `\*{0,2}` 로 굵게 자리를 **세고** 있었는데, 사람이 실제로 쓴 표기는 `✅**확정**` —
 *   굵게가 이모지와 낱말 **사이**에 들어갔다. 증상은 조용했다: 목록이 짧게 나올 뿐
 *   오류가 없어서, 분모(❔ 상태 줄 없음 66/67)를 안 봤으면 「아직 안 넣었구나」로 읽혔다.
 *
 * 무엇을 지키나:
 *   ① 표기 변이 전수를 잡는다 — 굵게 위치·띄어쓰기·전각 콜론·주석/인용 두 통로.
 *   ② 거짓양성을 안 낸다 — 머리 12줄 밖의 「상태:」·다른 낱말·모르는 상태값.
 *   ③ 실저장소에는 **거짓양성만** 검사한다(가드 맹점 ②: 버그가 아직 있길 요구하는 회귀 금지).
 *      탐지력의 정본은 위 픽스처고, 여기서는 「상태값이 셋 중 하나인가」만 본다.
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const { 상태읽기, 상태들 } = require('../tools/문서상태.js');

const 임시 = fs.mkdtempSync(path.join(os.tmpdir(), 'synk-문서상태-'));
function 픽스처(이름, 본문) {
  const p = path.join(임시, 이름);
  fs.writeFileSync(p, 본문, 'utf8');
  return p;
}

test('① 표기 변이 — 사람이 굵게를 어디 찍든 같게 읽는다', () => {
  const 변이 = [
    ['굵게 없음',        '# 제목\n\n> 상태: ✅확정 · 2026-08-09 — 판단 정본.\n',                 '✅확정'],
    ['낱말만 굵게',      '# 제목\n\n> **상태**: ✅**확정** · 2026-08-09\n',                       '✅확정'],  // ☠️ 첫 판이 놓친 그 표기
    ['통째 굵게',        '# 제목\n\n> **상태: ✅확정** · 2026-08-09\n',                           '✅확정'],
    ['이모지 뒤 띄어쓰기','# 제목\n\n> 상태: ✅ 확정 · 2026-08-09\n',                             '✅확정'],
    ['전각 콜론',        '# 제목\n\n> **상태**：🔵**논의중** · 2026-08-09\n',                     '🔵논의중'],
    ['HTML 주석 통로',   '<!-- 상태: 🔄개편중 · 2026-08-09 — 렌더링 문서라 주석 -->\n# 제목\n',   '🔄개편중'],
  ];
  for (const [이름, 본문, 기대] of 변이) {
    const r = 상태읽기(픽스처(`v-${변이.findIndex((x) => x[0] === 이름)}.md`, 본문));
    assert.ok(r, `${이름}: 상태 줄을 못 봤다 — 이게 첫 판의 실패 형태다`);
    assert.equal(r.상태, 기대, `${이름}: 상태값이 다르다`);
  }
});

test('② 거짓양성 — 상태 줄이 아닌 것을 상태로 읽지 않는다', () => {
  const 아닌것 = [
    ['머리 12줄 밖',   '# 제목\n' + '\n'.repeat(14) + '> 상태: ✅확정\n'],
    ['다른 낱말',      '# 제목\n\n> 진행상태: ✅확정\n'],          // 「상태」 앞에 글자가 붙으면 다른 뜻이다
    ['모르는 상태값',  '# 제목\n\n> 상태: 🟡보류중 · 2026-08-09\n'],  // 셋 밖은 조용히 접지 않는다
    ['인용/주석 아님', '# 제목\n\n상태: ✅확정\n'],                 // 본문 산문의 언급
    ['상태 줄 없음',   '# 제목\n\n> 유호님 확정 2026-08-05\n'],
  ];
  for (const [이름, 본문] of 아닌것) {
    const r = 상태읽기(픽스처(`n-${이름.replace(/[^\w가-힣]/g, '')}.md`, 본문));
    assert.equal(r, null, `${이름}: 상태가 아닌 줄을 상태로 읽었다`);
  }
});

test('③ 실저장소 — 상태값은 셋 중 하나여야 한다(탐지력은 픽스처가 진다)', () => {
  const ROOT = path.resolve(__dirname, '..');
  const 후보 = ['DESIGN.md', 'docs/제품방향.md'].map((r) => path.join(ROOT, r)).filter((p) => fs.existsSync(p));
  assert.ok(후보.length, '검사 대상 문서가 하나도 없다 — 경로가 바뀌었는지 본다');
  let 표기된것 = 0;
  for (const p of 후보) {
    const r = 상태읽기(p);
    if (!r) continue;              // 미표기는 결함이 아니다(유호님이 정하는 값이다) — 분모는 도구가 낸다
    표기된것 += 1;
    assert.ok(상태들.includes(r.상태), `${p}: 모르는 상태값 ${r.상태}`);
  }
  assert.ok(표기된것 >= 1, '실저장소에서 상태 줄을 한 건도 못 읽었다 — 파서가 죽었을 수 있다');
});

test.after(() => fs.rmSync(임시, { recursive: true, force: true }));
