/**
 * 「쓰는 문자 셋뿐」이 **커밋 때** 발동하는지 — F351 · F379 회귀.
 *
 * 무엇이 병이었나: 규칙은 2026-08-07 유호님 확정인데 그걸 지키는 장치가
 * `tests/문서문자.test.js` **하나뿐**이었고 그건 스위트를 돌릴 때만 발화한다. 그래서
 *   ① 위반은 늘 「남이 커밋한 뒤 남이 발견」이 됐다 — 고칠 수 있는 사람과 발견하는 사람이
 *      **반드시 달라지는** 구조였다(발견자에게 그 파일은 남의 작업중 선언이다).
 *   ② 형제 저장소(SYNK-talk) 세션은 여기 스위트를 애초에 안 돌리므로 **원리상** 안 잡혔다.
 *      실측 2026-08-12: 교정 프롬프트에 금지 문자가 «보기»로 들어간 채 커밋됐고, 그 파일은
 *      전문이 그대로 모델 `system` 에 실린다(문서 흠이 아니라 모델 입력 오염).
 *
 * 그래서 이 파일이 재는 것은 «정규식이 잡느냐»가 아니다 — 그건 `문서문자.test.js` 몫이다.
 * 여기는 **발동 시점과 등록층**을 잰다: 인덱스를 보는가 · 면제가 따라왔는가 · 훅이 실제로 부르는가.
 *
 * ⚠ 이 파일에도 그 글자를 적지 않는다 — 전부 `String.fromCodePoint` 로 조립한다.
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');
const { 훅띄우기 } = require('./lib/훅띄우기.js');

const ROOT = path.join(__dirname, '..');
const 검사기 = path.join(ROOT, 'tools', '옛글자검사.js');
const 글자 = String.fromCodePoint(0x683C);       // 실제로 새 나갔던 그 자리(U+683C)

function git(인자, cwd) {
  return execFileSync('git', 인자, { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

/** 픽스처 저장소를 하나 만들고 콜백에 넘긴다 — 실저장소는 위반이 0이라 탐지력을 못 잰다. */
function 픽스처(fn) {
  const 사본 = fs.mkdtempSync(path.join(os.tmpdir(), 'synk-옛글자훅-'));
  try {
    git(['init', '-q'], 사본);
    return fn(사본);
  } finally {
    fs.rmSync(사본, { recursive: true, force: true, maxRetries: 3 });
  }
}

/** 검사기를 그 저장소 안에서 돌린다 — `{코드, 출력}`. 저장소를 **cwd 로만** 준다(형제가 그렇게 부른다).
 *  🔑 `훅띄우기` 를 쓴다 — 직접 spawn 하면 **훅이 안 떴을 때가 「통과」와 같은 모양**이 된다
 *    (통과를 기대하는 칸은 훅이 죽어도 초록이다 · tests/lib/훅띄우기.js 머리말).
 *  ⚠ 통과코드가 셋인 이유: 0 깨끗 · 1 걸림 · 2 아무것도 못 봤다. 셋 다 이 도구의 «결과»고,
 *    그 밖(크래시)은 결과가 아니라 사고라 던지게 둔다. */
function 돌린다(cwd, 인자 = ['--cached'], 환경 = {}) {
  const r = 훅띄우기([검사기, ...인자], {
    cwd, encoding: 'utf8', env: { ...process.env, ...환경 }, 통과코드: [0, 1, 2],
  });
  return { 코드: r.status, 출력: String(r.stderr || '') + String(r.stdout || '') };
}

const 쓰기 = (뿌리, p, s) => {
  fs.mkdirSync(path.dirname(path.join(뿌리, p)), { recursive: true });
  fs.writeFileSync(path.join(뿌리, p), s, 'utf8');
};

test('스테이징된 옛 글자를 커밋 전에 잡는다 — 자리와 코드포인트를 대 준다', () => {
  픽스처((사본) => {
    쓰기(사본, 'src/화면.ts', `const 라벨 = '${글자}';\n`);
    git(['add', 'src/화면.ts'], 사본);

    const { 코드, 출력 } = 돌린다(사본);
    assert.strictEqual(코드, 1, `막아야 한다 — 실제 출력:\n${출력}`);
    assert.match(출력, /src\/화면\.ts:1\s+U\+683C/,
      '어느 파일 몇 줄 어느 글자인지를 대야 한다 — 안 그러면 받는 사람이 못 고친다');
  });
});

/* 🔴 이 저장소에서 가장 중요한 한 칸이다. `git add` 뒤에 작업 트리를 고쳐도 **커밋되는 것은
 *   인덱스**다. 작업 트리를 읽는 구현은 두 방향으로 다 틀린다: 스테이징된 위반을 놓치고
 *   (= 그대로 커밋된다), 스테이징 안 된 위반으로 남의 커밋을 막는다. 앞쪽이 특히 나쁘다 —
 *   새는 방향이 「통과」이기 때문이다. */
test('작업 트리가 아니라 인덱스를 본다 — 양방향', () => {
  픽스처((사본) => {
    // ㉠ 깨끗한 것을 스테이징하고 작업 트리만 더럽힌다 → 이번 커밋엔 안 들어가므로 통과해야 한다
    쓰기(사본, '깨끗.md', '한글 · Latin · Монгол\n');
    git(['add', '깨끗.md'], 사본);
    쓰기(사본, '깨끗.md', `나중에 더럽혔다 ${글자}\n`);
    const 깨끗한쪽 = 돌린다(사본);
    assert.strictEqual(깨끗한쪽.코드, 0,
      `스테이징 안 된 작업 트리 위반으로 커밋을 막으면 안 된다 — 실제 출력:\n${깨끗한쪽.출력}`);

    // ㉡ 더러운 것을 스테이징하고 작업 트리를 되돌린다 → 커밋될 실물이 더러우므로 막아야 한다
    쓰기(사본, '두번째.md', `${글자}\n`);
    git(['add', '두번째.md'], 사본);
    쓰기(사본, '두번째.md', '되돌렸다\n');
    const 더러운쪽 = 돌린다(사본);
    assert.strictEqual(더러운쪽.코드, 1,
      `스테이징된 위반은 작업 트리가 깨끗해도 막아야 한다 — 실제 출력:\n${더러운쪽.출력}`);
    assert.match(더러운쪽.출력, /두번째\.md:1/);
  });
});

