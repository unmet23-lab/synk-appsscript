/* 🔴 여러 파일을 **한 프로세스**로 긁는다(파일마다 git 을 띄우면 200파일 커밋이 6.7초였다 —
 *   실측 2026-08-12 · 느린 가드는 결국 꺼지고, 꺼진 가드는 없는 가드다). 그 대신 `cat-file --batch`
 *   출력을 손으로 자르게 됐고, **자르는 길이는 바이트다.** 문자로 세면 한글이 든 파일에서 경계가
 *   밀려 그 뒤 전량이 어긋나는데 — 어긋난 검사는 예외를 던지지 않고 **조용히 초록**이 된다.
 *   그래서 「한글이 잔뜩 든 파일들 **뒤에** 위반을 둔다」로 잰다. 경계가 밀리면 여기서 놓친다. */
test('여러 파일을 한 번에 긁어도 경계가 안 밀린다 — 한글 뒤에 숨은 위반', () => {
  픽스처((사본) => {
    /* ⚠ 이름을 `01`·`99` 로 못박는 이유: 목록은 **git 이 정렬해서** 준다. 「나중에 add 했으니
     *   뒤에 온다」는 가정은 틀렸고, 실제로 그 가정 때문에 이 칸이 변이를 놓쳤다(실측 1회 —
     *   한글 이름 `마지막.md` 가 `문서0.md` 보다 앞서서 **첫 레코드**가 됐다). 위반이 첫
     *   레코드면 경계가 밀려도 잡히므로, 이 시험은 위반이 **맨 뒤**일 때만 의미가 있다. */
    const 이름들 = [];
    for (let i = 0; i < 12; i++) {
      const p = `01문서${i}.md`;
      // 멀티바이트를 충분히 섞는다 — 바이트 길이와 문자 길이가 크게 갈리게
      쓰기(사본, p, `한글 본문 · Монгол хэл · 여러 줄\n`.repeat(20));
      이름들.push(p);
    }
    const 마지막 = '99마지막.md';
    쓰기(사본, 마지막, `앞은 전부 한글이었다 ${글자}\n`);
    이름들.push(마지막);
    git(['add', ...이름들], 사본);

    const { 코드, 출력 } = 돌린다(사본);
    assert.strictEqual(코드, 1, `한글 파일 뒤의 위반을 놓쳤다(경계가 밀렸다):\n${출력}`);
    assert.match(출력, /99마지막\.md:1\s+U\+683C/, `자리가 어긋났다:\n${출력}`);
  });
});

