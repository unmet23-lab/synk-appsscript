/* 두 문서를 기계로 묶는다 — 이 대장의 첫 사고가 「§5-1 에는 있는데 대장에는 없다」였다(3건이 부품
 * 목록 밖에 있었다). 손으로 채워 넣고 끝내면 8번째에 똑같이 벌어진다. 표식은 파싱된 표 행에서만
 * 세므로 머리말의 규약 설명·CLI 예시는 안 잡힌다(문서를 고칠 때마다 숫자가 흔들리면 아무도 안 믿는다). */
test('🔴 §5-1 전건이 대장에 줄로 서 있다 — 갈리면 대장이 다시 위험을 감춘다', () => {
  const 감사 = fs.readFileSync(path.join(ROOT, 'docs', '앱기능_역할별_전수분석.md'), 'utf8');
  const 절 = 감사.split(/^### 5-1\./m)[1];
  assert.ok(절, '§5-1(Glide 유일 입구 전수표)을 못 찾았다 — 절 번호가 바뀌었으면 이 대조도 같이 옮겨라');
  const 전수 = 절.split(/^#{2,3} /m)[0].split(/\r?\n/).filter((l) => /^\|\s*\d+\s*\|/.test(l)).length;
  assert.ok(전수 > 0, '§5-1 표에서 행을 하나도 못 읽었다 — 표 형식이 바뀌면 이 검사가 조용히 0을 통과시킨다');

  const p = 대장.파싱(fs.readFileSync(대장.대장경로(), 'utf8'));
  const 표식 = p.구역들.flatMap((g) => g.행들).filter((행) => 행.상태.includes('Glide 의존')).length;
  assert.equal(표식, 전수,
    `§5-1 은 ${전수}건인데 대장 표식은 ${표식}개 — 그 차이만큼 대장만 보는 사람에게 위험이 안 보인다`);
});

