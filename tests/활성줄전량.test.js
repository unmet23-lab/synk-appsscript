/* 활성줄전량 — 「지금 살아 있는 활성 줄 전량」의 **한 벌** 계약 (F610 ㉡ · 유호 지시 2026-08-18)
 *
 * 왜 이 파일이 따로 있나:
 *   합치기(메인 + 미머지 가지 → 활성만 → 중복 접기)가 **두 곳에 각자** 적혀 있었다 —
 *   `tools/대기열.js:보드행들` 과 `.claude/hooks/board-guard.js` 의 겹침 분모. `tools/friction.js`
 *   가 세 번째가 될 뻔했고(F610 신고문이 그 자리를 예고했다), CLAUDE.md 는 「3번째 = 원인을
 *   쓸 수 없게 만든다」라고 못박는다. 그래서 합치기를 `tools/lib/보드.js:활성줄전량` 한 벌로 모았다.
 *
 * 🔑 **갈라지면 어떤 모습인가** — 같은 자리를 한쪽은 「잡혔다」, 다른 쪽은 「비었다」로 말한다.
 *   그리고 「비었다」쪽이 이기면 두 세션이 같은 트랙을 판다. 새는 방향이 «부른다»라 조용하다.
 *   아래 검사는 그 갈라짐이 **되살아날 수 있는 네 자리**를 각각 못박는다.
 *
 * ⚠ 탐지력은 전부 픽스처가 진다(맹점 ② · F296) — 실저장소 갈래는 「안 죽는다」만 본다.
 *   그리고 래칫은 **행번호가 아니라 소스 내용**으로 건다(F618: 행번호 키는 무관한 편집마다 운다).
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..');
const 보드 = require(path.join(REPO, 'tools', 'lib', '보드.js'));

const 줄 = (트랙, 상태 = '작업중') => `| 2026-08-18 | ${트랙} | 만지는 파일 | ${상태} |`;
const 메인줄 = (파일, 트랙, 상태) => ({ 줄: 줄(트랙, 상태), 파일, 줄번호: 1, 사유: [], 날짜: '2026-08-18' });
const 가지출력 = (...쌍들) => 쌍들.map(([가지, 파일, 트랙, 상태]) => 보드.가지끝줄(가지, 파일, 줄(트랙, 상태))).join('\n');

/* ── ① 가지제외파일 — 「내 파일의 가지판은 내 줄이다」는 **접기 전에** 일어나야 한다 ────── */

test('🔴 가지제외파일은 «가지 쪽에만» 건다 — 그 파일의 메인 줄은 접기의 씨앗이라 남아야 한다', () => {
  /* board-guard 의 「메인」은 편집 전 판(`옛줄`)이고 전부 자기 파일이다. 그 줄들이 빠지면
   * master 에 이미 든 줄이 「가지에만 있는 선언」으로 되살아나 **정당한 선언을 거짓 차단**한다(F221).
   * 그래서 제외는 가지 루프에만 있어야 한다 — 이 검사가 그 자리를 못박는다. */
  const 본문 = '**내 트랙**';
  const r = 보드.활성줄전량(REPO, {
    메인: [메인줄('mine0001.md', 본문, '작업중')],
    가지제외파일: 'mine0001.md',
    출력: 가지출력(['내가지', 'mine0001.md', 본문, '작업중']),
  });
  assert.strictEqual(r.줄들.length, 1, '메인 줄까지 함께 빠졌다 — 접기의 씨앗이 사라진다');
  assert.strictEqual(r.줄들[0].가지, '', '내 가지판이 「가지 선언」으로 올라가면 F291 면제가 꺼진다');
  assert.strictEqual(r.분모.메인, 1);
  assert.strictEqual(r.분모.가지, 0, '제외한 뒤의 수여야 한다');
});

test('🔴 가지제외파일은 «남의» 가지 선언까지 지우지 않는다 — 지우면 겹침이 통째로 사라진다', () => {
  const r = 보드.활성줄전량(REPO, {
    메인: [],
    가지제외파일: 'mine0001.md',
    출력: 가지출력(['내가지', 'mine0001.md', '**내 트랙**'], ['남가지', 'other002.md', '**남의 트랙**']),
  });
  assert.deepStrictEqual(r.줄들.map((x) => x.파일), ['other002.md']);
  assert.strictEqual(r.줄들[0].가지, '남가지');
});

/* ⚠ **안 잰 것**(F348): 글자가 «완전히 같은» 줄이 서로 다른 가지에 둘 있으면 여기 오기 전에
 *   `가지끝파싱` 이 이미 하나로 접는다(2026-08-18 픽스처로 확인). 그 경우 «어느 가지인가»는
 *   먼저 파싱된 쪽이 이긴다. 옛 판도 같은 입력을 받았으니 이 트랙이 만든 변화는 아니고,
 *   겹침 판정은 살아남은 줄이 그대로 내므로 방향은 「막는다」다 — 조용히 통과하지 않는다. */
test('실측 기록 — 글자가 같은 두 가지 선언은 파서 층에서 이미 하나로 접힌다(이 통로의 문제가 아니다)', () => {
  const 같은 = 줄('**글자가 같은 트랙**');
  const 파싱 = 보드.가지끝파싱([
    보드.가지끝줄('가지하나', 'mine0001.md', 같은),
    보드.가지끝줄('가지둘', 'other002.md', 같은),
  ].join('\n'));
  assert.strictEqual(파싱.length, 1, '이 값이 2로 바뀌면 위 ⚠ 를 지우고 아래 기대도 고친다');
  assert.strictEqual(파싱[0].출처.가지, '가지하나', '먼저 파싱된 쪽이 이긴다');
});

test('가지제외파일이 없으면 둘 다 후보다 — 걸러냄은 부르는 쪽이 시킬 때만 일어난다', () => {
  const r = 보드.활성줄전량(REPO, {
    메인: [],
    출력: 가지출력(['내가지', 'mine0001.md', '**갑**'], ['남가지', 'other002.md', '**을**']),
  });
  assert.deepStrictEqual(r.줄들.map((x) => x.파일).sort(), ['mine0001.md', 'other002.md']);
});

/* ── ② 접는 키는 `trim()` 이다 — 층마다 꼬리 공백이 갈린다 ─────────────────────── */

test('🔴 꼬리 공백만 다른 같은 줄을 두 번 세지 않는다 — 둘째가 「가지에만 있는 남의 선언」이 된다', () => {
  /* 메인은 파일을 쪼갠 것이고 가지는 diff 를 판 것이다. 날문자로 접으면 같은 줄이 두 번 서고,
   * board-guard 는 그 둘째를 «master 에 없는 선언»으로 읽어 **정당한 선언을 거짓 차단**한다(F221). */
  const 본문 = 줄('**한 트랙**');
  const r = 보드.활성줄전량(REPO, {
    메인: [{ 줄: `${본문}   `, 파일: 'aaaaaaaa.md', 줄번호: 1, 사유: [], 날짜: '2026-08-18' }],
    출력: 가지출력(['어떤가지', 'aaaaaaaa.md', '**한 트랙**']),
  });
  assert.strictEqual(r.줄들.length, 1, '꼬리 공백 하나로 같은 줄이 둘이 됐다');
});

/* ── ③ 분모 — 「못 봤다」와 「0건」을 가른다 (F207) ──────────────────────────── */

test('🔴 분모는 «활성 거르기 전»의 날수다 — 활성 0건과 «가지를 못 봄»이 반환값에서 갈린다', () => {
  const r = 보드.활성줄전량(REPO, {
    메인: [],
    출력: 가지출력(['가지A', 'aaaaaaaa.md', '**끝난 트랙**', '✅종결']),
  });
  assert.strictEqual(r.줄들.length, 0, '완료 줄은 활성이 아니다');
  assert.strictEqual(r.분모.가지, 1, '활성 0건이라고 «가지를 안 봤다»가 되면 안 된다');
  assert.strictEqual(r.모름, false);
});

test('🔴 못 본 층의 분모는 `null` 이다 — 0 으로 접으면 분모가 거꾸로 샌다', () => {
  const r = 보드.활성줄전량(REPO, { 메인: null, 실행: () => null });
  assert.strictEqual(r.분모.메인, null);
  assert.strictEqual(r.분모.가지, null);
  assert.deepStrictEqual(r.못본층, ['메인 보드', '미머지 가지']);
  assert.strictEqual(r.모름, true);
});

test('분모의 가지 셈은 «제외한 뒤»의 수다 — 안 볼 줄을 분모에 세면 부르는 쪽이 헛것을 기다린다', () => {
  const r = 보드.활성줄전량(REPO, {
    메인: [],
    가지제외파일: 'mine0001.md',
    출력: 가지출력(['내가지', 'mine0001.md', '**갑**'], ['남가지', 'other002.md', '**을**']),
  });
  assert.strictEqual(r.분모.가지, 1);
});

/* ── ④ 가지우선 — 같은 줄이 두 층에 다 있을 때 어느 이름표를 다나 ──────────────── */

test('🔴 가지우선: 세션이 «자기 가지 위»에 서 있으면 그 선언은 가지 줄이다 — 기본값은 반대다', () => {
  /* 워크트리+PR 규약(08-15) 뒤로 이건 예외가 아니라 상시다: 자기 선언이 디스크에도 있고
   * 가지 diff 에도 있다. 「메인」 이름표를 달면 출력이 「메인 보드에 있다」고 말하는데
   * `origin/master` 엔 없다 — 실측 2026-08-18 에 실저장소 회귀가 그 자리를 잡았다. */
  const 인자 = () => ({
    메인: [메인줄('aaaaaaaa.md', '**한 트랙**', '작업중')],
    출력: 가지출력(['worktree-x', 'aaaaaaaa.md', '**한 트랙**', '작업중']),
  });
  const 기본 = 보드.활성줄전량(REPO, 인자());
  assert.strictEqual(기본.줄들.length, 1);
  assert.strictEqual(기본.줄들[0].가지, '', '기본은 메인 우선 — board-guard 의 F291 면제가 여기 걸려 있다');

  const 우선 = 보드.활성줄전량(REPO, { ...인자(), 가지우선: true });
  assert.strictEqual(우선.줄들.length, 1, '이름표만 바뀐다 — 줄이 늘면 그건 옛 판의 이중 계상이다');
  assert.strictEqual(우선.줄들[0].가지, 'worktree-x');
});

test('가지우선이어도 «가지에만» 있는 줄과 «메인에만» 있는 줄은 그대로다', () => {
  const r = 보드.활성줄전량(REPO, {
    메인: [메인줄('aaaaaaaa.md', '**메인만**', '작업중')],
    출력: 가지출력(['가지B', 'bbbbbbbb.md', '**가지만**', '작업중']),
    가지우선: true,
  });
  const 표 = new Map(r.줄들.map((x) => [x.파일, x.가지]));
  assert.strictEqual(표.get('aaaaaaaa.md'), '');
  assert.strictEqual(표.get('bbbbbbbb.md'), '가지B');
});

/* ── ⑤ 등록층 — 세 소비자가 **실제로** 이 통로를 쓴다 (안 쓰는 벌은 초록과 모양이 같다) ── */

const 소비자 = [
  ['tools/대기열.js', '점유 판정'],
  ['.claude/hooks/board-guard.js', '겹침 분모'],
  ['tools/friction.js', '장부 점유'],
];

/* 주석 제거는 통로가 하나다(F401·#Q114) — 지역 사본은 저마다 다르게 틀린다.
 * 🔑 여기선 `부름만` 이다(리터럴 «속»을 눕힌다): 이 검사의 바늘은 `활성줄전량(` 이라는 **호출**이라,
 *   문자열이 그 이름을 언급만 해도 세면 안 된다. 옛 지역 사본은 그 눕히기를 **안 했다** —
 *   주석엔 「문자열을 지운다」고 적혀 있었지만 정규식은 `://` 만 지켰다(설명과 코드의 갈라짐). */
const { 부름만, 파일소스 } = require('./lib/소스검사.js');

test('🔴 세 소비자가 전부 `활성줄전량` 을 부른다 — 하나라도 빠지면 그 도구만 반쪽 분모로 돈다', () => {
  for (const [상대, 쓰임] of 소비자) {
    const 코드 = 부름만(파일소스(path.join(REPO, 상대)));
    assert.ok(/활성줄전량\s*\(/.test(코드), `${상대}(${쓰임})가 공용 통로를 안 부른다`);
  }
});

test('🔴 소비자가 합치기를 «다시 적을» 수 없다 — 옛 통로(가지줄들 직접 호출)가 되살아나면 잡는다', () => {
  /* 래칫 키는 **소스 내용**이다(행번호가 아니다 · F618). 되살아나는 모양은 하나뿐이고
   * — 그 파일이 `가지줄들` 을 직접 불러 자기 손으로 합치는 것 — 그게 정확히 옛 판이었다. */
  for (const [상대, 쓰임] of 소비자) {
    const 코드 = 부름만(파일소스(path.join(REPO, 상대)));
    assert.ok(!/가지줄들\s*\(/.test(코드),
      `${상대}(${쓰임})가 \`가지줄들\` 을 직접 부른다 — 합치기가 두 벌이 되고 갈라진 쪽은 「비었다」고 말한다`);
  }
});

test('🔑 정본은 자기 처방을 안 막는다 — `보드.js` 자신은 이 래칫에 안 걸린다', () => {
  /* 처방이 가리키는 파일이 위반이면 그 순간 이 가드는 「고칠 방법이 없다」가 된다(F103). */
  const 코드 = 부름만(파일소스(path.join(REPO, 'tools', 'lib', '보드.js')));
  assert.ok(/가지줄들\s*\(/.test(코드), '정본은 당연히 부른다 — 부르지 않으면 합칠 재료가 없다');
});

/* ── ⑥ 실저장소 — 거짓양성만 (탐지력은 위 픽스처가 진다 · F296) ─────────────── */

test('실저장소 — 안 죽고, 못 본 층은 언제나 이름으로 말한다', () => {
  const r = 보드.활성줄전량(REPO);
  assert.ok(Array.isArray(r.줄들));
  assert.ok(Array.isArray(r.못본층));
  assert.strictEqual(r.모름, r.못본층.length > 0, '모름과 못본층이 갈라지면 둘 중 하나가 거짓말이다');
  for (const x of r.줄들) {
    assert.strictEqual(typeof x.줄, 'string');
    assert.strictEqual(typeof x.가지, 'string');
    assert.strictEqual(typeof x.놓음, 'boolean');
  }
  /* 접혔는지만 본다 — 건수는 그날 보드에 달렸으니 박지 않는다. */
  const 키들 = r.줄들.map((x) => x.줄.trim());
  assert.strictEqual(new Set(키들).size, 키들.length, '같은 줄이 두 번 실렸다 — 접기가 안 돈다');
});
