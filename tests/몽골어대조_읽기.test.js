'use strict';
/* 몽골어 검문 — «재기 전에 글을 어떻게 읽나» 회귀 (2026-09-06)
 *
 * 무엇을 지키나: 09-06 에 캐러셀 원고 넷이 「전건 탈락」으로 장부에 찍혔는데, 다시 재 보니 그 탈락의
 *   상당 부분이 **글이 아니라 자** 쪽이었다. 세 구멍이 함께 물었다:
 *     ⓐ 몽골어«만» 든 원고를 `--원문` 없이 넣으면 첫 `---`(슬라이드 구분)에서 잘려
 *        머리말 네 줄이 「한국어 원문」이 됐다 → 뜻 대조가 «머리말 vs 본문»을 재고 큰 차이를 쏟아냈다.
 *     ⓑ 뽑은 줄들을 **빈칸**으로 이어 붙여, 마침표 없는 제목 줄이 다음 문장에 달라붙었다
 *        (`…төлөвшдөг Хичээлээр…`) → 문법 층이 «없는 파손»을 봤다.
 *     ⓒ HTML 주석(`<!-- 몽골어검문: 대상 -->`)이 본문으로 실려 다섯 층에 다 들어갔다.
 *
 * 🔑 재는 것은 «소스에 그 글자가 있나»가 아니라 «그 입력을 넣으면 막히나»다
 *   ([[test-guards-the-defect]] — 자가 결함을 지키면 초록은 영원하다).
 * ⚠ 여기서 «못» 재는 것: 실제 제미나이·codex 왕복(키가 있어야 돈다). 이 파일은 왕복 «전»만 잰다.
 */
const { test } = require('node:test');
const assert = require('node:assert');
const path = require('node:path');

const 대조 = require(path.join(path.resolve(__dirname, '..'), 'tools', '몽골어대조.js'));

/* 캐러셀 원고의 실제 꼴 — 머리말 넉 줄 + `---` 로 갈린 슬라이드들. 한글은 한 자도 없다. */
const 몽골어만든원고 = [
  '# AI-ийн эрин үед хүнд юу үлдэх вэ?',
  '훅: SYNK LAB — Улаанбаатар дахь солонгос хэлний сургалтын төв',
  '언어: mn',
  '<!-- 몽골어검문: 대상 -->',
  '---',
  '## AI хариултыг өгнө',
  '',
  'Гэвч **юуг асуухыг** тань зааж өгөхгүй.',
  '---',
  '🔑 Эдгээр нь өөрөө биеэрээ туулж байж төлөвшдөг',
  '',
  'Хичээлээр дамжуулж болдоггүй төрлийн хүч учраас.',
].join('\n');

test('🔴 몽골어만 든 원고는 «짝 파일»로 읽지 않는다 — 앞 토막에 한글이 없으면 거절한다', () => {
  /* 거절해야 부르는 쪽이 「--원문 을 주라」는 안내로 떨어진다. 안 거절하면 조용히 엉뚱하게 갈린다. */
  assert.strictEqual(대조.파일분해(몽골어만든원고), null);
});

test('진짜 짝 파일(한국어 / --- / 몽골어)은 그대로 갈린다', () => {
  const 짝 = '한국 사람을 처음 만났어요.\n---\nБи анх удаа солонгос хүнтэй уулзлаа.';
  const r = 대조.파일분해(짝);
  assert.ok(r, '짝 파일이 null 로 떨어지면 안 된다');
  assert.strictEqual(r.원문, '한국 사람을 처음 만났어요.');
  assert.strictEqual(r.번역, 'Би анх удаа солонгос хүнтэй уулзлаа.');
});

test('🔴 제목 줄과 다음 문장이 한 문장으로 붙지 않는다 — 줄바꿈으로 잇는다', () => {
  const 뽑힌 = 대조.실물에서뽑기(몽골어만든원고);
  /* 붙어 버린 꼴이 나오면 문법 층이 «없는 파손»을 본다 */
  assert.ok(
    !/төлөвшдөг Хичээлээр/.test(뽑힌),
    '마침표 없는 제목 줄이 다음 문장에 달라붙었다 — 09-06 「전건 탈락」의 절반이 이 자리다',
  );
  assert.ok(/төлөвшдөг\nХичээлээр/.test(뽑힌), '두 줄이 줄바꿈으로 갈려 있어야 한다');
});

test('🔴 HTML 주석은 본문이 아니다 — 다섯 층 어디에도 안 들어간다', () => {
  const 뽑힌 = 대조.실물에서뽑기(몽골어만든원고);
  assert.ok(!/몽골어검문/.test(뽑힌), 'HTML 주석이 본문으로 실렸다');
  assert.ok(!/<!--|-->/.test(뽑힌), '주석 기호가 남았다');
});

test('머리말·마크다운 표식은 걷고 몸통 글자는 남긴다', () => {
  const 뽑힌 = 대조.실물에서뽑기(몽골어만든원고);
  assert.ok(!/^훅:/m.test(뽑힌) && !/^언어:/m.test(뽑힌), '머리말 줄이 남았다');
  assert.ok(!/[#*`]/.test(뽑힌), '마크다운 표식이 남았다');
  assert.ok(/юуг асуухыг/.test(뽑힌), '굵게 안의 몸통 글자가 사라졌다');
  assert.ok(!/^---$/m.test(뽑힌), '슬라이드 구분줄이 남았다');
});

/* ── 맞춤법 층 — 라틴 앞자락 ───────────────────────────────────────────────── */
const 맞춤 = require(path.join(path.resolve(__dirname, '..'), 'tools', 'lib', '몽골어맞춤법.js'));

test('🔴 K-соёлын — 걸린 것이 라틴 앞자락뿐이면 통과시킨다', () => {
  /* 사전이 «соёлын» 을 제안했다 = 붙임표 뒤 토막을 안다 ⇒ 문제는 `K-` 하나뿐이다 */
  assert.strictEqual(맞춤.라틴앞자락뿐('K-соёлын', ['соёлын', 'соёлынх', 'сойлон']), true);
});

test('🔴 뒤 토막이 틀렸으면 그대로 의심으로 남는다 — 자가 죽지 않는다', () => {
  /* 제안에 «соёлийн» 이 없다 = 사전이 그 토막을 모른다 ⇒ 통과시키면 안 된다 */
  assert.strictEqual(맞춤.라틴앞자락뿐('K-соёлийн', ['соёлын', 'соёлынх']), false);
});

test('제안을 못 받았으면 판정하지 않는다 — 「모름」은 통과가 아니다', () => {
  assert.strictEqual(맞춤.라틴앞자락뿐('K-соёлын', null), false);
  assert.strictEqual(맞춤.라틴앞자락뿐('K-соёлын', undefined), false);
});

test('붙임표가 없거나 앞자락이 라틴이 아니면 이 길로 안 온다', () => {
  assert.strictEqual(맞춤.라틴앞자락뿐('соёлын', ['соёл']), false);
  assert.strictEqual(맞춤.라틴앞자락뿐('Монгол-соёлын', ['соёлын']), false);
});
