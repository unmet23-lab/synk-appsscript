// tools/화면배율.mjs — 배율 셈. 브라우저로 재는 부분은 공개 페이지가 드는 일이라 여기서 돌리지 않는다.
import test from 'node:test';
import assert from 'node:assert/strict';
import { 늘어난배율, 기기들, 기본기준 } from '../tools/화면배율.mjs';

const 유호님 = 기기들.find((기기) => 기기.이름 === '유호님 화면');

test('걸려야 할 판: 1280×800 쇼릴이 유호님 화면을 덮으면 기준을 넘는다', () => {
  const 배율 = 늘어난배율({ 칸폭: 유호님.w, 칸높이: 유호님.h, 원본폭: 1280, 원본높이: 800, 맞춤: 'cover', 화소비: 유호님.화소비 });
  assert.equal(배율, 1.69);
  assert.ok(배율 >= 기본기준);
});

test('통과해야 할 판: 1920×1200 쇼릴은 기준 아래다', () => {
  const 배율 = 늘어난배율({ 칸폭: 유호님.w, 칸높이: 유호님.h, 원본폭: 1920, 원본높이: 1200, 맞춤: 'cover', 화소비: 유호님.화소비 });
  assert.equal(배율, 1.13);
  assert.ok(배율 < 기본기준);
});

test('cover는 더 늘어난 축으로, contain은 덜 늘어난 축으로 잰다', () => {
  // 세로 720p를 넓은 칸에 cover로 깔면 폭이 정한다.
  assert.equal(늘어난배율({ 칸폭: 1440, 칸높이: 900, 원본폭: 720, 원본높이: 1280, 맞춤: 'cover', 화소비: 1.5 }), 3);
  // 같은 칸에 contain이면 높이가 정한다 — 그래서 자르지 않는 스크린은 늘어나지 않는다.
  assert.equal(늘어난배율({ 칸폭: 1440, 칸높이: 900, 원본폭: 720, 원본높이: 1280, 맞춤: 'contain', 화소비: 1.5 }), 1.05);
});

test('object-fit의 나머지 값: fill은 cover처럼, none은 늘어나지 않고, scale-down은 1을 넘지 않는다', () => {
  assert.equal(늘어난배율({ 칸폭: 800, 칸높이: 400, 원본폭: 400, 원본높이: 400, 맞춤: 'fill' }), 2);
  assert.equal(늘어난배율({ 칸폭: 800, 칸높이: 400, 원본폭: 400, 원본높이: 400, 맞춤: 'none', 화소비: 2 }), 2);
  assert.equal(늘어난배율({ 칸폭: 800, 칸높이: 800, 원본폭: 400, 원본높이: 400, 맞춤: 'scale-down' }), 1);
  assert.equal(늘어난배율({ 칸폭: 200, 칸높이: 200, 원본폭: 400, 원본높이: 400, 맞춤: 'scale-down' }), 0.5);
});

test('화소비가 그대로 곱해진다 — 같은 칸도 휴대폰에서는 세 배 많은 화소가 든다', () => {
  assert.equal(늘어난배율({ 칸폭: 156, 칸높이: 208, 원본폭: 540, 원본높이: 720, 맞춤: 'cover', 화소비: 3 }), 0.87);
  assert.equal(늘어난배율({ 칸폭: 156, 칸높이: 208, 원본폭: 156, 원본높이: 208, 맞춤: 'cover', 화소비: 3 }), 3);
});

test('크기를 모르면 숫자를 지어내지 않는다', () => {
  assert.equal(늘어난배율({ 칸폭: 100, 칸높이: 100, 원본폭: 0, 원본높이: 0 }), null);
  assert.equal(늘어난배율({ 칸폭: 0, 칸높이: 100, 원본폭: 100, 원본높이: 100 }), null);
});
