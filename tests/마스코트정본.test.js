/* 마스코트 정본 회귀 — 「지면이 «지금» 마스코트를 쓰나」.
 *
 * 🔴 **같은 원인으로 세 번 잡혔다. 그래서 이 파일이 있다.**
 *   · F443 (08-14 · 실수) — 「왜 예전버전으로 만들어준거야」. 파일명이 같아도 판이 갈린다
 *     (`마스코트_렌더` = 확정 «전» · `마스코트_정본` = 확정 «후»).
 *   · F479 (08-15 · 교정) — 「이걸로 바뀌었는데 왜 예전버전으로?」. 원인 = 그림 경로를 토큰이
 *     아니라 **손 경로**(`마스코트_누끼`)로 박아 둠. 수리는 «브랜드킷 조립 도구 한 곳»만 고쳤다.
 *   · 2026-08-19 (교정) — 캐러셀 7컷이 그대로 구판이었다. 브랜드킷은 고쳤는데 **캐러셀은
 *     아무도 안 봤다**. 즉 두 번의 수리가 «그 호출부»만 고쳤고, 옛 통로는 살아 있었다.
 *
 *   CLAUDE.md 신뢰성: **3번째 = 원인을 쓸 수 없게 만든다** — 호출부마다 고치는 대신
 *   **옛 통로를 테스트로 금지**한다. 이 파일이 그 금지다.
 *
 * ══ 무엇을 막나 ═══════════════════════════════════════════════════════════
 *   학생·학부모가 보는 지면(`지면방` 이 「입는다」로 판정한 전량)이 **구판 마스코트 경로**를
 *   들면 fail. 어느 파일의 몇 줄인지 이름째 낸다.
 *
 * ⚠**분모를 밝힌다**(F207) — 0건이 「깨끗하다」와 같은 모양이면 안 되므로 몇 벌을 봤는지 센다.
 * ⚠구판을 «지우지» 않는다 — 옛 자산은 그대로 두고(유호님이 배치한 자산이다) **지면이 그걸
 *   가리키는 것만** 막는다. 자산 삭제는 비가역이라 이 검사의 일이 아니다.
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const path = require('node:path');
const fs = require('node:fs');

const 루트 = path.resolve(__dirname, '..');
const 지면방 = require(path.join(루트, 'tools', 'lib', '지면방.js'));
const 토큰 = JSON.parse(fs.readFileSync(path.join(루트, 'docs', '디자인_토큰.json'), 'utf8'));

/** 구판 통로 — 지면이 이 경로를 가리키면 「예전 버전」이 화면에 나간다. */
const 구판경로 = [
  '마스코트_누끼',   // F479 가 지목한 그 경로(체리 젤리 렌더의 누끼)
  '마스코트_렌더',   // F443 — 확정 «전» 판. 토큰의 `특별` 슬롯이 여기라 «지면»에서만 막는다
];

/** 정본 = 토큰이 든다(손 목록 금지 — 정본이 갈리면 이 검사가 저절로 따라간다). */
const 정본사진 = 토큰['재질']['펠트']['정본사진'];

test('🔑 분모 — 토큰이 정본 사진 슬롯을 들고 있다 (없으면 아래가 통째로 공회전한다)', () => {
  assert.ok(정본사진 && 정본사진['평상복'], '토큰 재질.펠트.정본사진.평상복 이 없다');
  const p = path.join(루트, 정본사진['평상복']);
  assert.ok(fs.existsSync(p), `정본 평상복 사진이 실재하지 않는다: ${정본사진['평상복']}`);
});

test('🔴 입는 지면 전량이 «지금» 마스코트를 쓴다 — 구판 경로 0건 (F443·F479 계열 3번째)', () => {
  const 입는것 = 지면방.점검().갈래.입는다;
  assert.ok(입는것.length >= 15, `분모가 수상하다 — 입는 지면 ${입는것.length}벌(대상 소실은 통과가 아니다)`);

  const 흠 = [];
  for (const r of 입는것) {
    const 절대 = path.join(루트, r.경로);
    if (!fs.existsSync(절대)) continue;
    const html = fs.readFileSync(절대, 'utf8');
    /* `src`·`url()` 만 본다 — 주석이나 설명문에 옛 이름이 «적히는» 것은 위반이 아니다
     * (검사가 자기 설명을 신고하면 그 검사는 곧 꺼진다). */
    for (const m of html.matchAll(/(?:src\s*=\s*"|url\(\s*'?)([^"')]+)/g)) {
      const 경로 = m[1];
      for (const 옛 of 구판경로) if (경로.includes(옛)) 흠.push(`${r.경로} → ${경로}`);
    }
  }
  assert.deepEqual(흠, [],
    `구판 마스코트를 가리키는 지면 ${흠.length}건 — 정본은 토큰 재질.펠트.정본사진.평상복`
    + `(=${정본사진['평상복']})다.\n  유호 확정 08-15: 평소=코랄(평상복) · 특별한 순간=체리.`
    + `\n  ⚠고칠 때 alt 문구도 같이 본다 — 「체리 젤리」라고 적힌 채 그림만 바꾸면 대체 텍스트가 거짓말을 한다.`);
});

test('🔑 탐지력 픽스처 — 구판 경로를 실제로 문다 (실저장소가 깨끗해도 힘을 증명한다)', () => {
  /* 실저장소는 지금 0건이라, 실물만 보면 이 검사는 아무것도 증명하지 못한다(가드 맹점 ②). */
  const 병든지면 = '<img class="shot" src="마스코트_누끼/본체.png" alt="x">';
  const 잡힘 = [...병든지면.matchAll(/(?:src\s*=\s*"|url\(\s*'?)([^"')]+)/g)]
    .some((m) => 구판경로.some((옛) => m[1].includes(옛)));
  assert.ok(잡힘, '구판 경로를 못 물었다 — 이 검사는 장식이다');

  const 성한지면 = `<img class="shot" src="${정본사진['평상복'].replace('docs/캐릭터/', '')}" alt="x">`;
  const 거짓양성 = [...성한지면.matchAll(/(?:src\s*=\s*"|url\(\s*'?)([^"')]+)/g)]
    .some((m) => 구판경로.some((옛) => m[1].includes(옛)));
  assert.ok(!거짓양성, '정본 경로를 물었다 — 거짓 적색은 우회를 정상 통로로 만든다(F103)');
});
