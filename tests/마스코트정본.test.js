/** 이 축의 분모 — 사람·AI 가 «참조로 읽는» 층. 코드(tools/)는 축 ③ 소관이다(F671 ▶). */
const 참조층 = ['docs/', 'bots/', '.claude/'];
/** 기록 자체가 옛 이름을 대야 하는 자리 — 여기서 신고하면 검사가 자기 장부를 문다. */
const 장부층 = ['docs/_ops/장부/', 'docs/_ops/보드/', 'docs/세션보드_아카이브.md'];

/** 본문 한 벌에서 위반 줄 번호를 낸다.
 *
 * 🔑 **실저장소 검사와 픽스처가 «같은 이 함수»를 쓴다** — 처음엔 픽스처가 이 판정을 복사해
 *   갖고 있었는데, 그러면 진짜 매처가 망가져도 픽스처는 멀쩡히 초록이라 탐지력 증명이 거짓이 된다.
 *   이 파일이 방금 `구판경로` 에서 고친 것과 **정확히 같은 병**이다(맹점 ④ · 목록은 하나에서 파생). */
function 위반줄(본문) {
  const 줄 = 본문.split('\n');
  /* 퇴역 배너가 선 줄 — 이 아래는 「알고 남긴 기록」이다. 없으면 -1(면제 0). */
  const 배너줄 = 줄.findIndex((L) => L.includes('퇴역') && L.includes('2026-08-19'));
  const 흠 = [];
  for (let i = 0; i < 줄.length; i++) {
    const L = 줄[i];
    const 옛 = 구판경로.find((t) => L.includes(t));
    if (!옛) continue;
    /* 신호 둘 — ㉠「정본」이라 부른다 ㉡확장자까지 붙은 구체적 자산 포인터 */
    const 정본이라부름 = L.includes('정본');
    const 자산포인터 = new RegExp(`${옛}[^\\s'"\`)]*\\.(png|md|json|mp4|webp)`).test(L);
    if (!정본이라부름 && !자산포인터) continue;
    /* 면제 ㉠ — 배너 «아래»인가 (바닥에 낱말만 뿌리는 우회를 막으려 위치를 본다) */
    if (배너줄 !== -1 && i > 배너줄) continue;
    /* 면제 ㉡ — 그 줄이나 «바로 붙은» 줄이 퇴역을 밝히고 있나.
     * ±1 인 이유: 기록 보정은 「주장 바로 옆에 단서를 단다」가 자연스러운 모양이고(HTML 은
     * 줄이 접힌다), 멀리 떨어진 낱말로 끄는 길은 위 배너 «위치» 규칙이 이미 막는다. */
    const 곁 = 줄.slice(Math.max(0, i - 1), i + 2).join('\n');
    if (/퇴역|삭제했|삭제됐|⛔/.test(곁)) continue;
    흠.push({ 줄번호: i + 1, 내용: L.trim().slice(0, 90) });
  }
  return 흠;
}

function 정본선언위반() {
  const { execSync } = require('node:child_process');
  /* ⚠`git ls-files` 는 한글 경로를 8진 이스케이프로 낸다 — 그대로 쓰면 파일을 못 열고
   *   «0건»이 나온다(실측 08-20: 그 거짓 초록을 한 번 밟았다). `-z` = 원본 바이트. */
  const 전체 = execSync('git ls-files -z', { cwd: 루트, encoding: 'buffer' })
    .toString('utf8').split('\0').filter(Boolean);
  const 대상 = 전체.filter((f) =>
    참조층.some((p) => f.startsWith(p)) && !장부층.some((p) => f.startsWith(p)) && !f.startsWith('tests/'));

  const 흠 = [];
  for (const f of 대상) {
    let s; try { s = fs.readFileSync(path.join(루트, f), 'utf8'); } catch { continue; }
    if (!구판경로.some((옛) => s.includes(옛))) continue;
    for (const v of 위반줄(s)) 흠.push(`${f}:${v.줄번호}  ${v.내용}`);
  }
  return { 분모: 대상.length, 흠 };
}

