'use strict';
/**
 * 주석 제거는 **통로가 하나다** — 사본을 못 만들게 기계로 막는다 (F401 계열 · 대기열 P3 줄73).
 *
 * ■ 왜 as 에도 있나 (talk 에 이미 있는데)
 *   「지역 사본 0벌」은 **talk 안에서만 참이었다.** 공용 통로도 계수기도 회귀도 셋 다 talk 에만
 *   서 있었고, as 는 이 축으로 **한 번도 안 재졌다**. 처음 대 보니 사본 20벌이었다(2026-08-13).
 *   각 사본이 저마다 다르게 틀렸다 — 어떤 것은 줄머리 `//` 만 지우고(인라인이 산다), 어떤 것은
 *   `[^:]` 로 `https://` 만 지키고(`'// 문자열'` 은 못 지킨다), 어떤 것은 문자열과 주석을 한
 *   정규식으로 같이 처리해 **순서에 기댔다**. 갈라진 쪽의 증상은 언제나 「통과」다.
 *
 * ■ 🔴 계수기는 여기서 «안 돈다» — 그리고 그것을 숨기지 않는다
 *   `tools/가드계수.js` 는 `acorn` 파서를 쓰는데 **as 엔 `package.json` 도 `node_modules` 도
 *   없다**(실측). 그래서 계수기를 as 로 «복사하지 않았다» — 복사하면 영원히 안 도는 도구가
 *   하나 늘 뿐이고, 그것이야말로 이 트랙이 없애려는 「같은 판정을 두 곳에 적어 갈라지는」
 *   결함이다. 계수기는 **뿌리 경로를 인자로 받으므로** talk 판 하나로 두 저장소를 다 잰다:
 *       node ../SYNK-talk/tools/가드계수.js .      (as 를 잰다 · `--json` 있음)
 *   👉 그러므로 **as 의 사본 수는 이 파일이 못 지킨다.** 여기가 지키는 것은 «통로의 힘»이고,
 *      사본 census 는 위 명령으로 사람이 잰다. 못 재는 것을 재는 척하지 않는다(F207).
 *
 * ■ 무엇을 재나
 *   ①②③ 탐지력 — 픽스처가 진다. 순수 JS 라 의존이 0이고 CI 에서 그대로 돈다.
 *   ④ 갈라짐 — as 판이 talk 판과 **바이트로 같은가**. 형제 저장소가 없으면 fail 이 아니라
 *     **skip** 이다(F296: repo 밖 환경에 기댄 검사가 CI 를 깨뜨린 자리).
 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const { 코드만, 줄맞춰코드만, 구간, 코드만픽스처, 상위집합픽스처 } = require('./lib/소스검사.js');

const 여기 = path.join(__dirname, 'lib', '소스검사.js');
const 형제 = path.join(__dirname, '..', '..', 'SYNK-talk', 'tests', 'lib', '소스검사.js');

/* ── ① 공용 통로의 힘 — 값으로 못박는다 ─────────────────────────────────────── */

test('옛 픽스처가 그대로 통과한다 — 블록·줄·JSX 주석을 다 본다', () => {
  assert.equal(코드만(코드만픽스처.입력), 코드만픽스처.기대);
});

test('사본들이 저마다 지키던 것을 «하나»가 전부 진다', () => {
  for (const c of 상위집합픽스처) {
    assert.equal(코드만(c.입력), c.기대, `흡수 실패: ${c.왜}`);
  }
  assert.ok(상위집합픽스처.length >= 6, '픽스처가 줄었다 — 흡수 근거가 사라진다');
});

test('앵커를 못 찾으면 «던진다» — 조용한 빈 문자열은 미실행을 초록으로 만든다', () => {
  assert.throws(() => 구간('const a = 1;', '없는앵커', null), /못 찾았다/);
});

/* ── ② as 의 사본들이 «실제로» 틀리던 자리 ───────────────────────────────────
 * 아래 셋은 이 저장소에서 걷어낸 사본 20벌이 저마다 틀리던 모양 그대로다.
 * 되돌리면 여기가 빨개진다 — 「무엇을 잃는가」를 값으로 남긴다. */

test('🔴 인라인 주석도 지운다 — `학생ID채번`·`상담지식` 사본이 놓치던 자리', () => {
  /* 옛 판은 「줄머리의 `//` 부터 줄 끝까지」만 지웠다(`(^|\n)[ \t]*` 로 시작을 못박은 정규식).
   * 그래서 `const x = 1; // SYNK-001` 의 주석이 «코드»로 세어졌다. */
  assert.equal(코드만("const x = 1; // SYNK-001 을 여기서 만들면 안 된다").trim(), 'const x = 1;');
});

test('🔴 문자열 속 `//` 는 주석이 아니다 — `[^:]` 어림법이 못 지키던 자리', () => {
  /* 옛 판: `(^|[^:])\/\/.*$` — `://` 만 지켰다. 앞이 콜론이 아닌 `'// …'` 는 잘렸다. */
  assert.equal(코드만("const 쓰기 = '// 이건 문자열이다';"), "const 쓰기 = '// 이건 문자열이다';");
  assert.equal(코드만("const u = 'https://x/평균';"), "const u = 'https://x/평균';");
});

test('🔴 문자열과 주석을 «순서»로 풀지 않는다 — `safety.rawWrites` 가 기대던 자리', () => {
  /* 그 사본의 주석이 스스로 적어 둔 걱정: 「안 지우면 'http://x' 뒤를 주석으로 오인해
   * 같은 줄의 진짜 쓰기를 숨긴다」. 렉서는 순서에 안 기댄다. */
  const 줄 = "Logger.log('http://x'); d.setValues([[row[0]]]);";
  assert.equal(코드만(줄), 줄, '문자열 뒤의 «진짜 코드»가 주석으로 오인돼 사라졌다');
});

/* ── ③ 줄 맞춘 판 — 렉서는 하나, 공백 정책만 둘 ─────────────────────────────── */

test('줄맞춰코드만 은 «줄 수»를 원문 그대로 둔다 — 행 번호로 짚는 소비자가 있다', () => {
  /* as 의 소비자 둘: `tests/훅통로.test.js`(위반 행 번호) · `tools/실행층점검.js`(함수 구간). */
  const 입력 = ['const a = 1;', '// 버리지 않고 눕힌다', '', 'const b = 2;'].join('\n');
  const 나온것 = 줄맞춰코드만(입력);
  assert.equal(나온것.split('\n').length, 4, '줄이 줄면 짚는 행 번호가 밀린다');
  assert.ok(!/버리지/.test(나온것), '주석이 안 눕혀졌다');
  assert.equal(코드만(입력).split('\n').length, 3, '두 판이 갈라진 이유가 사라졌다');
});

test('여러 줄 주석도 줄 수를 지킨다 — 블록이 접히면 함수 구간이 통째로 밀린다', () => {
  const 입력 = ['const a = 1;', '/* 한 줄', ' * 두 줄', ' */', 'const b = 2;'].join('\n');
  assert.equal(줄맞춰코드만(입력).split('\n').length, 5);
  assert.ok(!/두 줄/.test(줄맞춰코드만(입력)));
});

/* ── ④ 갈라짐 — 두 저장소가 «같은 것»을 쓰는가 ───────────────────────────────
 * 목록은 하나에서 파생돼야 한다. 여기가 갈라지면 as 계수와 talk 계수가 다른 것을 세고,
 * 두 숫자를 대조할 수 없게 된다. 형제 저장소가 없으면 skip — fail 이 아니다(F296). */

test('as 판이 talk 판과 «바이트로» 같다 — 정본은 하나다', { skip: fs.existsSync(형제) ? false : '형제 저장소 SYNK-talk 없음 — 대조할 수 없다(같다는 뜻이 아니다)' }, () => {
  assert.equal(
    fs.readFileSync(여기, 'utf8'), fs.readFileSync(형제, 'utf8'),
    '두 저장소의 공용 통로가 갈라졌다 — 한쪽만 고쳐진 날 그쪽 가드가 조용히 눈먼다.\n'
    + '   고칠 것이 있으면 talk 판을 고치고 그대로 복사한다(talk 이 정본).',
  );
});
