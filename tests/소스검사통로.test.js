  /* 실측 거짓양성 후보 그대로다(2026-08-18 전수). 하나라도 잡히면 멀쩡한 코드에 처방이 나간다. */
  assert.equal(겨눔(String.raw`https?:\/\/[^\s]+`), null, 'URL 을 주석 제거기로 읽는다');
