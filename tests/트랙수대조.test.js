/* 트랙수대조 회귀 — 트랙에 적힌 수가 정본과 어긋날 때 «무는가», 그리고 못 잴 때 «그렇게 말하는가».
 *
 * ■ 무엇을 지키나 (2026-09-05 · 유호 지시 「자 만들어줘」로 선 자의 짝)
 *   트랙은 색인이라 수가 많은데 되잴 방법이 안 적혀 있으면 조용히 낡는다. 그날 실측:
 *     · 말투 판정 분모가 82 로 적힌 채 실제로는 99 였다(문안이 늘며 17곳이 붙었다)
 *     · crewcard 배포 지문은 **세 번째로** 낡아 있었다 — 그 줄이 스스로 「수를 여기 적지 말라」고
 *       적어 두고도 수를 적고 있었다
 *   둘 다 «자가 없어서» 아무도 못 알았다.
 *
 * 🔴 **이 검사의 급소는 «못잼»이다.** 대조는 무늬로 수를 집는데, 문서 한 줄이 고쳐지면 무늬가
 *   죽는다. 죽은 무늬는 아무것도 못 집고 ⇒ 「어긋남 0」이라는 **거짓 초록**을 낸다. 자가 헛도는데
 *   초록이 나오는 것이 이 저장소가 여러 번 밟은 자리다(기억 `zero-is-a-success-face-taxonomy`).
 *   그래서 아래 ③④⑤ 가 「못 집었을 때 못 집었다고 말하는가」를 따로 문다.
 *
 * ⚠ 이 검사가 틀릴 때의 모습 = **실물 트랙에 매여 초록.** 트랙 문구는 매일 바뀌므로 여기서
 *   실제 수를 단정하면 남의 커밋마다 빨개진다. 그래서 ①~⑦ 은 합성 트리로 자만 재고,
 *   ⑧ 하나만 실물에 대 「무늬가 아직 살아 있는가」를 본다 — 그것이 낡으면 빨개지는 것이 옳다.
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { 대조하기, 대조표, 갈래검사 } = require('../tools/lib/트랙수대조.js');

/* ── 합성 트리 — 실물 문서를 안 건드리고 «자»만 잰다 ────────────────────────── */
const 트랙본 = [
  '## 0-소급. 학생이 오기 전에만 할 수 있는 것 — 색인 섰다 · 남은 것 = 실물 판정 189건 · 집행 다섯',
  '- ⏳ **189건 실물 판정은 «나중에 한 번에»**. 194건 중 실물로 확정한 것은 다섯이다.',
  '## 0-지원. 창업·정부 지원사업 17건 — 마감이 걸렸다',
  '## 0-말투. 대외 문안 말투 — 남은 것 = **99곳 판정**',
  '',
].join('\n');
const 색인본 = '> ⏳ **아래 194건 중 189건은 «후보»다 — 실물 판정은 미뤄 뒀다**\n';
const 실행지본 = '**합계 17 = 접수 완료 11 + 진행 중 3 + 유호님 손 대기 2 + 안 넣기로 함 1**\n';

/** 합성 저장소를 짓는다. `고침` 으로 파일 한 벌을 갈아 끼우거나(문자열) 지운다(null). */
function 트리(고침 = {}) {
  const 뿌리 = fs.mkdtempSync(path.join(os.tmpdir(), 'synk-트랙수-'));
  const 넣기 = (rel, 글) => {
    if (글 === null) return;                       // null = 그 파일이 «없는» 트리
    const p = path.join(뿌리, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, 글, 'utf8');
  };
  넣기('docs/_ops/트랙.md', '트랙' in 고침 ? 고침.트랙 : 트랙본);
  넣기('docs/소급불가_색인_2026-09-03.md', '색인' in 고침 ? 고침.색인 : 색인본);
  넣기('docs/정부지원금_실행지.md', '실행지' in 고침 ? 고침.실행지 : 실행지본);
  return 뿌리;
}
const 이름들 = (목록) => 목록.map((x) => x.이름);

test('① 수가 다 맞으면 어긋남 0 · 못잼 0', () => {
  const r = 대조하기(트리());
  assert.deepStrictEqual(r.어긋남, [], `어긋남이 났다: ${JSON.stringify(r.어긋남)}`);
  assert.deepStrictEqual(r.못잼, [], `못잰 것이 있다: ${JSON.stringify(r.못잼)}`);
  assert.ok(r.맞음.length >= 4, `맞음이 ${r.맞음.length}건뿐이다 — 대조표가 비었나`);
});

test('🔴 ② 트랙 수가 정본과 다르면 문다 (이 자의 본디 일)', () => {
  const r = 대조하기(트리({ 트랙: 트랙본.replace('실물 판정 189건', '실물 판정 188건') }));
  assert.strictEqual(r.어긋남.length, 1, `어긋남이 ${r.어긋남.length}건이다`);
  assert.match(r.어긋남[0].이름, /소급 — 판정 대기/);
  assert.strictEqual(r.어긋남[0].트랙값, 188);
  assert.strictEqual(r.어긋남[0].참값, 189);
  assert.ok(r.어긋남[0].뜻, '어긋남에 «무엇을 센 값인지»가 없다 — 읽는 사람이 못 고친다');
});

test('🔴 ③ 트랙 무늬가 죽으면 «못잼»으로 든다 — 조용한 0 이 아니다', () => {
  /* 트랙 문구가 고쳐져 무늬가 아무것도 못 집는 판. 옛 판이라면 「어긋남 0」으로 초록이었다. */
  const r = 대조하기(트리({ 트랙: 트랙본.replace('남은 것 = 실물 판정 189건', '남은 것 = 실물판정 189개') }));
  assert.deepStrictEqual(r.어긋남, [], '무늬가 죽었는데 어긋남으로 셌다');
  assert.ok(이름들(r.못잼).some((n) => /소급 — 판정 대기/.test(n)),
    `못잼에 안 담겼다 — 거짓 초록이다: ${JSON.stringify(r.못잼)}`);
  assert.match(r.못잼.find((x) => /소급 — 판정 대기/.test(x.이름)).사유, /트랙에서 수를 못 집었다/);
});

test('🔴 ④ 정본 파일이 없으면 «못잼» — 없는 것을 맞다고 읽지 않는다', () => {
  const r = 대조하기(트리({ 색인: null }));
  const 걸린것 = r.못잼.filter((x) => /소급/.test(x.이름));
  assert.strictEqual(걸린것.length, 2, `소급 두 항목이 다 못잼이어야 한다: ${JSON.stringify(r.못잼)}`);
  assert.match(걸린것[0].사유, /이 없다/);
  assert.deepStrictEqual(r.어긋남, [], '파일이 없는 것을 «어긋남»으로 셌다');
});

test('🔴 ⑤ 정본에서 수를 못 집으면 «못잼» — 파일은 있는데 그 줄이 사라진 판', () => {
  const r = 대조하기(트리({ 색인: '> 이 문서에는 이제 그 문장이 없다.\n' }));
  assert.ok(이름들(r.못잼).some((n) => /소급/.test(n)), '정본 무늬가 죽었는데 조용히 넘어갔다');
  assert.match(r.못잼.find((x) => /소급/.test(x.이름)).사유, /정본 .* 에서 수를 못 집었다/);
});

test('🔴 ⑥ 합계가 갈래의 합과 다르면 문다 (합계 = 갈래+갈래)', () => {
  /* 11+3+2+1 = 17 인데 합계만 18 로 적힌 판 */
  const r = 대조하기(트리({ 실행지: 실행지본.replace('합계 17 =', '합계 18 =') }));
  const 걸린것 = r.어긋남.filter((x) => /갈래의 합/.test(x.이름));
  assert.strictEqual(걸린것.length, 1, `갈래 합 검사가 안 물었다: ${JSON.stringify(r.어긋남)}`);
  assert.strictEqual(걸린것[0].트랙값, 18);
  assert.strictEqual(걸린것[0].참값, 17);
});

test('⑦ 무거운 자는 기본에서 안 돈다 — 느린 검사는 아무도 안 돌린다', () => {
  const 무거운것 = 대조표.filter((x) => x.무겁다);
  assert.ok(무거운것.length > 0, '무거운 항목이 하나도 없다 — 이 검사가 뜻을 잃었다');
  const 기본 = 대조하기(트리());
  for (const 항 of 무거운것) {
    assert.ok(![...기본.맞음, ...기본.어긋남, ...기본.못잼].some((x) => x.이름 === 항.이름),
      `${항.이름} 이 기본에서 돌았다 — 기본은 빨라야 한다`);
  }
});

test('🔴 ⑧ 실물 저장소에서 무늬가 아직 살아 있다 — 죽으면 여기서 빨개져야 한다', () => {
  /* 실물의 «수»를 단정하지 않는다(트랙은 매일 바뀐다). 다만 대조표의 무늬가 실제 문서에서
     뭔가를 집는지는 본다 — 못 집으면 이 자가 헛도는 것이고, 그때 빨개지는 것이 옳다. */
  const r = 대조하기(path.resolve(__dirname, '..'));
  assert.deepStrictEqual(r.못잼, [],
    `실물에서 못 잰 항목이 있다 — 문서가 고쳐져 무늬가 죽었으면 tools/lib/트랙수대조.js 의 대조표를 같이 고친다:\n`
    + r.못잼.map((x) => `  · ${x.이름} — ${x.사유}`).join('\n'));
  assert.ok(r.맞음.length + r.어긋남.length >= 4, '실물에서 잰 항목이 너무 적다');
});

test('대조표가 제 꼴을 지킨다 — 이름·뜻·무늬가 다 있다', () => {
  for (const 항 of 대조표) {
    assert.ok(항.이름 && 항.뜻, `${항.이름 || '이름 없는 항목'} 에 «무엇을 센 값인지»가 없다`);
    assert.ok(항.트랙 instanceof RegExp, `${항.이름} 의 트랙 무늬가 정규식이 아니다`);
    assert.ok(항.참.파일 || 항.참.돌린다, `${항.이름} 에 참값을 낼 자리가 없다`);
  }
  for (const 항 of 갈래검사) {
    assert.ok(항.이름 && 항.뜻 && 항.파일 && 항.무늬 instanceof RegExp, `${항.이름} 의 꼴이 어긋났다`);
  }
});
