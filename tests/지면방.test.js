/* 지면방 회귀 — `tools/lib/지면방.js` (Loom L5 의 등록층).
 *
 * 무엇을 지키나 — 이 장치의 실패는 **전부 «통과»의 얼굴로 온다**:
 *   ① **미분류를 못 잡는 것.** 새 HTML 이 셋 중 어디에도 안 적혔는데 초록이면,
 *      다음 새 지면은 또 손 CSS 로 태어나고 아무도 모른다. 이게 L5 의 존재 이유다.
 *   ② **`docs/` 최상위 와일드카드 제외.** 살아있는 새 지면이 거의 전부 거기서 태어나므로,
 *      거기에 `docs/*_0814.html` 같은 규칙 하나를 두면 새 지면이 **조용히 삼켜진다** —
 *      미분류 0(초록)인데 분모만 작아진다. 파일의 「대가」 절이 닫기로 한 바로 그 구멍.
 *   ③ **사유·조건 없는 항목.** 이유 없는 제외가 곧 등록층의 구멍이다(브랜드렌더린트와 같은 문법).
 *      실제로 첫 판에 「한 벌」이라는 예외구를 뒀더니 조건 없는 보류가 하나 통과했다.
 *   ④ **두 목록이 갈라지는 것.** `브랜드렌더린트.js` 의 등록층에 있는 파일이 여기서 「제외」로
 *      적히면 두 장치가 서로 다른 세상을 본다 — 갈라지는 방향은 언제나 통과다.
 *
 * 탐지력은 **픽스처가 진다**(맹점 ② — 실저장소가 병들어 있기를 요구하지 않는다).
 * 실저장소에는 «거짓양성 0» 만 검사한다.
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const path = require('node:path');

const 루트 = path.resolve(__dirname, '..');
const 지면방 = require(path.join(루트, 'tools', 'lib', '지면방.js'));

/* ── ① 매칭 — 글롭이 «/ 를 넘지 않는다» ────────────────────────────────── */

test('맞나 — `*` 는 디렉터리 경계를 넘지 않는다', () => {
  assert.ok(지면방.맞나('docs/tools/*', 'docs/tools/synk_palette.html'));
  assert.ok(!지면방.맞나('docs/tools/*', 'docs/tools/하위/깊은.html'),
    '`*` 가 / 를 넘으면 하위 디렉터리가 통째로 조용히 삼켜진다');
  assert.ok(!지면방.맞나('docs/엔진/*.html', 'docs/엔진/_원고/Loom_소개서.html'),
    '원고방은 엔진 갈래 패턴에 물리면 안 된다 — 원고가 «입는다»가 되면 재현 대조가 깨진다');
});

test('맞나 — 디렉터리 없는 패턴은 파일명 꼬리에 물린다', () => {
  assert.ok(지면방.맞나('*_자립형.html', 'docs/홈페이지_시안/병합판_자립형.html'));
  assert.ok(!지면방.맞나('*_자립형.html', 'docs/홈페이지_시안/병합판.html'));
});

/* ── ② 탐지력 — 픽스처로 못박는다 ─────────────────────────────────────── */

test('규칙검증 — 사유 없는 항목을 잡는다', () => {
  const 흠 = 지면방.규칙검증([{ 판정: '제외', 패턴: 'docs/x.html', 사유: '   ' }]);
  assert.equal(흠.length, 1);
  assert.match(흠[0], /사유 없는 항목/);
});

test('규칙검증 — 조건 없는 보류를 잡는다 (예외구를 두지 않는다)', () => {
  const 흠 = 지면방.규칙검증([{ 판정: '보류', 패턴: 'docs/x.html', 사유: '⏳나중에 한다.' }]);
  assert.equal(흠.length, 1, '조건 없는 보류는 영구 보류다 — 반드시 빨개져야 한다');
  assert.match(흠[0], /조건/);
  // 조건을 적으면 통과한다 — 검사가 «따를 수 있는 처방»인지 되먹여 본다(맹점 ③).
  assert.deepEqual(지면방.규칙검증([{ 판정: '보류', 패턴: 'docs/x.html', 사유: '⏳ 조건 = 유호 픽.' }]), []);
});

test('규칙검증 — docs 최상위 와일드카드 제외를 잡는다 (「대가」 절이 닫기로 한 구멍)', () => {
  for (const 패턴 of ['docs/*.html', 'docs/*_0814.html', 'docs/펠트코랄_*.html']) {
    const 흠 = 지면방.규칙검증([{ 판정: '제외', 패턴, 사유: '일회성 판정 재료.' }]);
    assert.equal(흠.length, 1, `${패턴} 이 통과하면 새 지면이 조용히 삼켜진다`);
    assert.match(흠[0], /최상위 와일드카드/);
  }
  // 하위 디렉터리는 갈래가 이름으로 갈려 있어 패턴이 정직하다 — 막지 않는다.
  assert.deepEqual(지면방.규칙검증([{ 판정: '제외', 패턴: 'docs/tools/*', 사유: '도구.' }]), []);
});

test('분모확인 — 빈 목록은 「깨끗함」이 아니라 예외다', () => {
  /* 실저장소에선 이 분기가 영영 안 밟히므로 «순수 함수로 떼어» 픽스처로 문다.
   * 안 떼어 뒀을 땐 `return []` 변이가 시험 12건을 전부 초록으로 통과했다(08-16 변이 실측). */
  assert.throws(() => 지면방.분모확인([]), /0건/);
  assert.deepEqual(지면방.분모확인(['docs/a.html']), ['docs/a.html']);
});

test('입은표시 — 마커가 있어야만 「입었다」다 (늘 참이면 전파율이 통째로 거짓이 된다)', () => {
  const 마커 = require(path.join(루트, 'tools', 'lib', 'loom.js')).마커;
  assert.ok(지면방.입은표시(`<style>${마커('불릿')}\n.x{}</style>`),
    'loom.js 가 실제로 박는 마커를 못 알아보면 전파가 영원히 0으로 읽힌다');
  assert.ok(!지면방.입은표시('<style>.x{color:red}</style>'), '마커 없는 손 CSS 를 「입었다」로 세면 안 된다');
  assert.ok(!지면방.입은표시('<!-- loom 을 입힐 예정 -->'), '낱말 「loom」이 본문에 있다고 입은 것이 아니다');
});

test('분류 — 어디에도 안 적힌 경로는 미분류다 (L5 의 유일한 적색)', () => {
  const r = 지면방.분류('docs/새로_태어난_지면_' + '테스트' + '.html');
  assert.equal(r.판정, '미분류');
  assert.equal(r.사유, null);
});

test('분류 — 첫 매치가 이긴다(개별 등재가 패턴보다 위)', () => {
  // 자개 캐러셀은 `docs/캐릭터/*`(제외) 보다 위에 개별 「보류」로 적혀 있다.
  assert.equal(지면방.분류('docs/캐릭터/자개_캐러셀_예시_0814.html').판정, '보류');
  assert.equal(지면방.분류('docs/캐릭터/캐릭터_시안_v1.html').판정, '제외');
});

/* ── ③ 실저장소 — 거짓양성만 본다 ─────────────────────────────────────── */

test('실저장소 — 미분류 0 · 규칙 흠 0', (t) => {
  let r;
  try { r = 지면방.점검(); } catch (e) {
    // repo 밖 환경(git 없음·얕은 클론)에 기댄 검사는 CI 에서 깨진다 — fail 이 아니라 skip 으로 드러낸다.
    return t.skip('git ls-files 를 못 돌렸다: ' + e.message);
  }
  assert.deepEqual(r.규칙흠, [], '규칙 자체에 흠이 있다');
  assert.deepEqual(r.갈래.미분류.map((x) => x.경로), [],
    '분류 안 된 HTML 이 있다 — tools/lib/지면방.js 에 한 줄 추가한다(제외면 사유를, 보류면 조건을)');
});

test('실저장소 — 분모가 살아 있다(0건은 «안 봤다»와 같은 모양이다)', (t) => {
  let r;
  try { r = 지면방.점검(); } catch (e) { return t.skip('git ls-files 를 못 돌렸다: ' + e.message); }
  assert.ok(r.전파.분모 > 0, '「입는다」가 0이면 이 장치는 아무것도 안 지킨다');
  assert.ok(r.갈래.제외.length > 0, '제외가 0이면 분류를 안 돌린 것이다');
  // 진척 자체는 회귀로 못박지 않는다 — 지면을 하나 옮길 때마다 빨개지면 그 회귀가 일을 막는다.
});

/* ── ④ 두 등록층이 갈라지지 않는가 ────────────────────────────────────── */

test('브랜드렌더린트 등록층은 전부 「입는다」나 「보류」다 — 갈라지면 두 장치가 다른 세상을 본다', () => {
  const 린트 = require(path.join(루트, 'tools', '브랜드렌더린트.js'));
  const 대상 = 린트.대상 || 린트.등록층;
  if (!Array.isArray(대상)) {
    assert.fail('브랜드렌더린트 가 등록층을 export 하지 않는다 — 교차검사가 원리적으로 못 선다');
  }
  /* 🔴 빈 배열이면 `어긋남` 도 빈 배열이라 **이 검사가 통과한다** — 「0건」과 「안 봤다」가
   *    같은 모양인 자리다(CLAUDE.md 「초록은 분모와 함께만 읽는다」). 분모부터 못박는다. */
  assert.ok(대상.length > 0, '등록층이 비었다 — 교차검사가 0건을 «깨끗함»으로 읽고 있었다');
  const 어긋남 = 대상
    .map((p) => ({ 경로: p, 판정: 지면방.분류(p.replace(/\\/g, '/')).판정 }))
    .filter((x) => x.판정 !== '입는다' && x.판정 !== '보류');
  assert.deepEqual(어긋남, [],
    '린트가 «대외물»로 등재한 지면을 지면방이 «제외»로 적었다 — 한쪽이 낡았다');
});

test('펠트문서가 «굽는» 지면은 전부 「입는다」다 — 굽고 있는데 분모에 없으면 전파율이 거짓이다', () => {
  const 펠트문서 = require(path.join(루트, 'tools', '펠트문서.js'));
  /* ⚠이름이 겹친다 — `펠트문서.지면방` 은 {원고,산출} **디렉터리 짝**이고,
   *   `tools/lib/지면방.js` 는 **판정 등록층**이다. 층이 다르다(굽는 통로 ↔ 분모).
   *   굽는 쪽이 분모의 부분집합인지만 본다. */
  const 짝 = 펠트문서.지면짝들();
  assert.ok(짝.length > 0, '굽는 짝이 0 — 분모를 못 셌다(0건이 아니다)');
  const 어긋남 = 짝
    .map((p) => path.relative(루트, p.산출).replace(/\\/g, '/'))
    .map((경로) => ({ 경로, 판정: 지면방.분류(경로).판정 }))
    .filter((x) => x.판정 !== '입는다');
  assert.deepEqual(어긋남, [],
    '굽기가 스킨을 입히고 있는 지면이 지면방에서 「입는다」가 아니다 — 전파 분모가 실제보다 작다');
});
