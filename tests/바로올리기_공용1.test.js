test('공용 작업본: 고치던 문서가 HEAD보다 새 origin 판 위에 다시 짜였으면 그 판을 바탕으로 3방향 — 그 뒤 origin 고침과 함께 따라간다', async (t) => {
  const v0 = '# 트랙\n\n## 가\n- 가 항목 하나는 길게 써서 다른 줄과 헷갈리지 않게 한다\n\n## 나\n- 나 항목 하나는 길게 써서 다른 줄과 헷갈리지 않게 한다\n';
  const 판 = 새판(t, { 파일: { 'docs/_ops/트랙.md': v0 } });
  const B = 판.공용.머리();
  const v1 = v0.replace('- 가 항목 하나는', '- 가 항목 둘은 origin이 새로 더한 줄이다\n- 가 항목 하나는');
  판.남push({ 'docs/_ops/트랙.md': v1 });
  // 공용 작업본의 세션이 최신(v1) 판 위에 제 줄을 얹어 둔다 — HEAD는 아직 v0
  판.공용.쓰기('docs/_ops/트랙.md', `${v1}- 나 항목 셋은 공용 작업본 세션이 쓰는 중인 줄이다\n`);
  const v2 = v1.replace('- 가 항목 둘은 origin이 새로 더한 줄이다', '- 가 항목 둘은 origin이 새로 더하고 다시 고친 줄이다');
  const O = 판.남push({ 'docs/_ops/트랙.md': v2 });
  assert.equal(판.공용.머리(), B);
  const r = await 도구.따라가기({ 저장소: 판.공용.폴더, 실행: true });
  assert.equal(r.결과, '따라감', JSON.stringify(r));
  assert.equal(판.공용.머리(), O);
  assert.equal(판.공용.읽기('docs/_ops/트랙.md'), `${v2}- 나 항목 셋은 공용 작업본 세션이 쓰는 중인 줄이다\n`, 'origin의 다시 고친 줄 + 세션의 새 줄');
  assert.deepEqual(판.공용.상태(), [' M docs/_ops/트랙.md']);
});

test('공용 작업본: 가장 가까운 origin 판을 바탕으로 3방향을 해도 작업본이 받은 적 없는 origin의 새 줄은 지우지 않는다', async (t) => {
  const v0 = '# 노트\n\n## 가\n### 가 첫 항목은 길게 써서 다른 줄과 헷갈리지 않게 한다\n- 가 첫 항목 내용 줄\n\n## 나\n### 나 첫 항목은 길게 써서 다른 줄과 헷갈리지 않게 한다\n- 나 첫 항목 내용 줄\n';
  const 판 = 새판(t, { 파일: { 'docs/현장노트/노트.md': v0 } });
  const B = 판.공용.머리();
  // 공용 작업본이 따라가지 못하는 사이 남이 가 절에 항목을 더한다 — 공용 작업본 파일은 이 항목을 받은 적이 없다
  const v1 = v0.replace('\n\n## 나', '\n\n### 가 절에 origin이 더한 항목\n- 가 절 새 항목 내용 줄\n\n## 나');
  판.남push({ 'docs/현장노트/노트.md': v1 });
  // 공용 작업본 세션이 옛 판(v0) 위에 나 절 항목을 써서 조각으로 올렸다 — origin은 v1 + 그 항목, 작업본은 v0 + 그 항목 + 아직 안 올린 줄.
  // 작업본과 가장 가까운 origin 판은 「v1 + 그 항목」이라, 그 판을 바탕으로 그대로 합치면 가 절 새 항목을 작업본이 지운 줄로 본다(10-21).
  const 나항목 = '\n### 나 절에 세션이 쓴 항목\n- 증상: 나 절 항목 증상 줄\n- 원인: 나 절 항목 원인 줄\n- 고침: 나 절 항목 고침 줄\n- 다시 확인: 나 절 항목 확인 줄\n';
  const 안올린 = '- 덧붙임: 세션이 아직 올리지 않은 줄\n';
  판.공용.쓰기('docs/현장노트/노트.md', `${v0}${나항목}${안올린}`);
  const O = 판.남push({ 'docs/현장노트/노트.md': `${v1}${나항목}` });
  assert.equal(판.공용.머리(), B);
  const r = await 도구.따라가기({ 저장소: 판.공용.폴더, 실행: true });
  assert.equal(r.결과, '따라감', JSON.stringify(r));
  assert.equal(판.공용.머리(), O);
  assert.equal(판.공용.읽기('docs/현장노트/노트.md'), `${v1}${나항목}${안올린}`, 'origin이 더한 가 절 항목은 남고, 올라간 나 절 항목은 한 번만, 안 올린 줄은 그 뒤에');
  assert.deepEqual(판.공용.상태(), [' M docs/현장노트/노트.md']);
});

test('공용 작업본: origin도 지운 경로의 「스테이징된 지움」은 남의 스테이징으로 막지 않고 따라간다 — 작업본에 남긴 파일은 그대로', async (t) => {
  const 판 = 새판(t, { 파일: { 'docs/글/붙여넣기.html': '<p>옛 판</p>\n', 'docs/글2/붙여넣기.html': '<p>옛 판 둘</p>\n', 'a.txt': '1\n' } });
  const O = 판.남push({ 'docs/글/붙여넣기.html': null, 'docs/글2/붙여넣기.html': null, '.gitignore': 'docs/글/붙여넣기.html\n', 'a.txt': '2\n' }, '붙여넣기 판은 저장소 밖으로');
  // 공용 작업본의 세션도 같은 일을 해 두었다: 지움만 스테이징하고 새로 만든 판은 작업본에 둔다(하나는 무시 규칙 안, 하나는 미추적)
  판.공용.쓰기('.gitignore', 'docs/글/붙여넣기.html\n');
  판.공용.g('rm', '-q', '--cached', 'docs/글/붙여넣기.html', 'docs/글2/붙여넣기.html');
  판.공용.쓰기('docs/글/붙여넣기.html', '<p>새로 만든 판</p>\n');
  판.공용.쓰기('docs/글2/붙여넣기.html', '<p>새로 만든 판 둘</p>\n');
  const r = await 도구.따라가기({ 저장소: 판.공용.폴더, 실행: true });
  assert.equal(r.결과, '따라감', JSON.stringify(r));
  assert.equal(판.공용.머리(), O);
  assert.equal(판.공용.읽기('docs/글/붙여넣기.html'), '<p>새로 만든 판</p>\n', '작업본의 새 판은 지우지 않는다');
  assert.equal(판.공용.읽기('docs/글2/붙여넣기.html'), '<p>새로 만든 판 둘</p>\n');
  assert.equal(판.공용.읽기('a.txt'), '2\n');
  assert.deepEqual(판.공용.상태(), ['?? docs/글2/붙여넣기.html']);
});

