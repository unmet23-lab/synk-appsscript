/**
 * 기능체크 «렌즈»(③) + «아는 미완» 동봉(②) 회귀 — 2026-08-17 · 유호 픽 「1,2,3 한벌로」
 *
 * ③ 왜 렌즈인가:
 *   옛 판의 2회차는 **같은 프롬프트 재추첨**이었다. 실측(다회차 런 43개): 겹침률 22.6% 로 값은 했지만
 *   **25개(58%)에서 2회차가 새 지적을 0건** 냈다. 그래서 주사위를 다시 굴리는 대신 각도를 가른다.
 *   ⚠ 이 파일이 지키는 급소는 「회차마다 다르다」가 아니라 **「렌즈 말고는 같다」**다 —
 *     diff·철학·방향까지 같이 흔들리면 갈린 원인이 렌즈인지 재료인지 못 가른다(F045: 조건은 하나씩).
 *   ⚠ 그리고 렌즈는 **기능체크에만** 걸린다. 1단계 버그 검수는 `codex exec review` 라 커스텀
 *     프롬프트를 원리상 못 받는다(도구 머리말 ⛔막다른 길). 그 사실이 바뀌면 이 주석이 낡는다.
 *
 * ② 왜 「아는 미완」인가:
 *   기각 81건 중 66건(81%)이 기능체크였고, 오판의 결이 하나다 — 저장소가 **스스로 미완이라고 적어둔
 *   칸**을 새 결함으로 집는다. 그래서 그 장부를 프롬프트에 함께 준다.
 *   ⚠ 급소는 「올리지 마라」로 **억제하지 않는 것**이다. 억제하면 진짜 결함이 그 목록에 겹칠 때 함께
 *     가려진다(가드 맹점 ④). 그래서 「면죄부가 아니다」 문구를 회귀로 못 박는다 — 그게 빠지는 순간
 *     이 블록은 검수를 끄는 장치가 된다.
 *
 * ⚠ 실저장소(보드 디렉터리)에 기대는 검사는 **skip 으로 드러낸다**(F296) — CI·클라우드엔 그 판이 다르다.
 */

const test = require('node:test');
const assert = require('node:assert');

const R = require('../tools/codex-review.js');

/* ── ③ 렌즈 ─────────────────────────────────────────────────────────── */

test('렌즈 — 1회차는 전면(추가 지시 없음) · 2회차는 다른 각도', () => {
  assert.strictEqual(R.기능렌즈(1).이름, '전면');
  assert.strictEqual(R.기능렌즈(1).지시, '', '1회차에 지시가 붙으면 옛 판과의 대조가 깨진다');
  assert.notStrictEqual(R.기능렌즈(2).이름, R.기능렌즈(1).이름);
  assert.ok(R.기능렌즈(2).지시.length > 0, '2회차가 빈 지시면 그냥 재추첨이다 — ③이 안 된 것');
});

test('렌즈 — 회차가 목록보다 커도 죽지 않는다(clamp)', () => {
  assert.ok(R.기능렌즈(3), '--회차 3 에서 undefined 를 집으면 프롬프트가 통째로 깨진다');
  assert.strictEqual(R.기능렌즈(9).이름, R.기능렌즈들[R.기능렌즈들.length - 1].이름);
  assert.strictEqual(R.기능렌즈(0).이름, '전면', '0·음수도 첫 렌즈로 접힌다');
});

test('회차별 프롬프트가 «렌즈만» 다르다 — 나머지 재료는 같다', () => {
  const diff = '--- a/x.js\n+++ b/x.js\n@@ -1 +1 @@\n-old\n+new';
  const 제안 = ['제안 하나 — 채택 범위: 좁게'];
  const 미완 = { 줄들: ['  · 트랙 A\n      상태: ⛔ 막힘'], 전체: 1 };
  const p1 = R.기능체크프롬프트(diff, 제안, '', '', R.기능렌즈(1), 미완);
  const p2 = R.기능체크프롬프트(diff, 제안, '', '', R.기능렌즈(2), 미완);

  assert.notStrictEqual(p1, p2, '두 회차가 같은 문자열이면 각도를 안 가른 것이다');
  assert.ok(p2.includes(R.기능렌즈(2).지시), '2회차 프롬프트에 그 렌즈의 지시가 실려야 한다');
  assert.ok(!p1.includes(R.기능렌즈(2).지시), '1회차에 2회차 지시가 새면 두 회차가 같아진다');

  // 렌즈 지시를 들어내면 나머지는 **바이트가 같아야** 한다 — 이게 「조건 하나씩」의 기계 표현이다
  const 벗기기 = (p, 렌즈) => (렌즈.지시 ? p.replace(렌즈.지시 + '\n', '') : p);
  assert.strictEqual(벗기기(p1, R.기능렌즈(1)), 벗기기(p2, R.기능렌즈(2)),
    'diff·제안·미완까지 함께 달라지면 갈린 원인이 렌즈인지 재료인지 못 가른다(F045)');
});

test('두 회차 모두 전수 체크 지시를 유지한다 — 렌즈가 본업을 지우지 않는다', () => {
  for (const i of [1, 2]) {
    const p = R.기능체크프롬프트('diff', [], '', '', R.기능렌즈(i), null);
    assert.ok(p.includes('하나도 빠짐없이'), `${i}회차가 전수 체크를 안 시킨다`);
    assert.ok(p.includes('--- 변경 내용 ---'), `${i}회차에 diff 가 안 실린다`);
  }
});

/* ── ② 아는 미완 ────────────────────────────────────────────────────── */

test('아는미완블록 — 재료가 없으면 빈 문자열(블록을 지어내지 않는다)', () => {
  assert.strictEqual(R.아는미완블록(null), '');
  assert.strictEqual(R.아는미완블록({ 줄들: [], 전체: 0 }), '');
});

test('아는미완블록 — 억제가 아니라 «다른 점을 대라»여야 한다', () => {
  const b = R.아는미완블록({ 줄들: ['  · 트랙 A\n      상태: ⛔'], 전체: 1 });
  assert.ok(b.includes('어떻게 다른지'), '「다른 점을 대라」가 빠지면 그냥 억제가 된다');
  assert.ok(b.includes('면죄부가 아니다'),
    '이 문구가 빠지면 진짜 결함이 장부와 겹칠 때 함께 가려진다(가드 맹점 ④)');
  assert.ok(b.includes('트랙 A'), '실제 장부 줄이 실려야 한다');
});

test('아는미완블록 — 잘렸으면 잘렸다고 밝힌다(no silent caps)', () => {
  const 안잘림 = R.아는미완블록({ 줄들: ['  · A'], 전체: 1 });
  assert.ok(!안잘림.includes('전체 1줄 중'), '안 잘렸는데 잘렸다고 하면 안 된다');
  const 잘림 = R.아는미완블록({ 줄들: ['  · A'], 전체: 40 });
  assert.ok(/전체 40줄 중 최근 1줄/.test(잘림),
    '조용히 자르면 「전부 줬다」로 읽힌다 — 분모를 밝혀야 한다');
});

test('아는미완줄들 — 실저장소 보드를 읽는다(형태만)', (t) => {
  const r = R.아는미완줄들();
  if (r.오류) return t.skip(`보드 디렉터리를 못 읽었다(${r.오류}) — CI·클라우드에선 판이 다르다`);
  assert.ok(Array.isArray(r.줄들), '줄들은 배열이어야 한다');
  assert.ok(typeof r.전체 === 'number' && r.전체 >= r.줄들.length,
    '전체는 실은 줄 수보다 작을 수 없다 — 분모가 분자보다 작으면 보고가 거짓말한다');
  if (r.전체 === 0) return t.skip('보드에 줄이 0이다 — 탐지력은 위 픽스처 검사가 진다');
  assert.ok(r.줄들.every((l) => l.includes('상태:')), '각 줄은 트랙과 상태를 함께 들어야 한다');
});

test('아는미완줄들 — 상한이 실제로 듣는다', (t) => {
  const r = R.아는미완줄들(2);
  if (r.오류) return t.skip('보드 디렉터리를 못 읽었다');
  assert.ok(r.줄들.length <= 2, `상한 2 를 줬는데 ${r.줄들.length}줄이 나왔다`);
});
