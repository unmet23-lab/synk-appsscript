/* ── ② 래칫 — 실저장소에 남은 자리를 «이름»으로 고정한다 ───────────────────── */

/**
 * 아직 손조립인 자리. **왜 못 고치는지**를 함께 적는다 — 이유 없는 예외는 다음 사람이 못 지운다.
 *
 * ■ 키가 «행번호»가 아니라 «행 내용의 지문»인 이유 (F618 · 2026-08-18)
 *   옛 판의 키는 `파일:행번호` 였다. 그러면 **그 위에 한 줄만 더해도** 같은 자리가 밀려
 *   「손조립하는 자리가 늘었다」로 운다 — 실측: F614 수리가 `보드근거.js` 위쪽에 29줄을 더하자
 *   179 → 208 로 밀렸고, 실제로 늘어난 자리는 **0**인데 화면엔 위반 1건이 떴다.
 *   장치가 안 도는 게 아니라 **정확히 도는 모양으로 틀린 값**을 낸다(가드 맹점 ④).
 *   그리고 그 처방(「정본을 써라」)은 이미 «남의 줄이 잠갔다»로 유예된 자리를 가리키니
 *   따를 수도 없다 — 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103).
 *   ⚠ 재발이 **보장**돼 있었다: 행번호는 편집의 부산물이라 「안 늘렸다」를 증명해도 다음 편집에 또 운다.
 *
 * 🔑 그래서 키 = 그 줄을 공백 정규화한 뒤의 **sha1 앞 8자리**다. 행이 밀려도 안 울고,
 *   그 줄의 **내용이 바뀌면** 운다 — 래칫이 원래 재려던 축이 그것이다.
 *   🔑 지문이라 **이 파일이 자기를 물지 않는다**: 아래 목록이 원문을 그대로 실으면 훑기가
 *     그것을 위반으로 세고, 그 순간 목록을 적을 방법이 사라진다(위 「이어붙여 짓는다」와 같은 축).
 *   🔑 **배열**이지 객체가 아니다 — 한 파일에 «글자가 같은» 자리가 둘이면 객체 키로는 하나로 접혀
 *     하나를 갚아도 조용히 통과한다. 다중집합으로 세면 개수까지 지킨다(F618 ㉡ 이 진 약점).
 *
 * ⚠ 대가: 지문은 사람이 못 읽는다. 그래서 ①`사유` 에 어디인지 적고 ②아래 실패문이 **지금의
 *   행번호**를 함께 낸다 — 키는 내용, 안내는 행번호다. 목록을 갱신할 땐 실패문의 지문을 그대로 옮긴다.
 */
const 남은자리 = [
  { 파일: 'tools/lib/보드근거.js', 지문: 'bcf95e09', 사유: '남의 활성 보드 줄(`86d6d162`)이 이 파일을 잠갔다 — F574 (그 줄은 그 뒤 ✅종결)' },
  { 파일: 'tools/이해대장.js', 지문: '3d545cb7', 사유: '남의 활성 보드 줄(`24ba4d6b` · 가지 `worktree-ledger-blocker-split`)이 잠갔다 — 후보 목록 첫 줄' },
  { 파일: 'tools/이해대장.js', 지문: 'eb22f570', 사유: '위와 같은 줄 — 워크트리 갈래의 후보 push' },
];

/** 줄 → 키. 공백만 정규화한다(들여쓰기·줄바꿈 정리로는 안 울리게). */
const 줄지문 = (줄) => 해시.createHash('sha1').update(String(줄).replace(/\s+/g, ' ').trim(), 'utf8').digest('hex').slice(0, 8);
const 키 = (e) => `${e.파일}  ${e.지문}`;

function js들(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === '.git' || e.name === 'worktrees') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) js들(p, out);
    else if (e.name.endsWith('.js')) out.push(p);
  }
  return out;
}

/** @param {{뿌리?: string, 폴더?: string[]}} [옵션] 회귀 주입구 — 픽스처를 훑게 갈아끼운다(F296). */
function 훑기(옵션) {
  const o = 옵션 || {};
  const 밑 = o.뿌리 || REPO;
  const 걸린것 = [];
  let 파일수 = 0;
  for (const 뿌리 of (o.폴더 || ['tools', '.claude/hooks', 'tests']).map((d) => path.join(밑, d))) {
    if (!fs.existsSync(뿌리)) continue;
    for (const f of js들(뿌리)) {
      파일수 += 1;
      줄맞춰코드만(fs.readFileSync(f, 'utf8')).split('\n').forEach((줄, i) => {
        if (!손조립인가(줄)) return;
        /* 키는 **내용의 지문**이고 행번호는 사람에게 「어디를 보라」고 말하는 데만 쓴다(F618). */
        걸린것.push({ 파일: path.relative(밑, f).replace(/\\/g, '/'), 지문: 줄지문(줄), 줄번호: i + 1 });
      });
    }
  }
  return { 걸린것, 파일수 };
}

test('② 분모 — 훑은 파일이 실제로 있다(0벌을 훑어도 「위반 0」은 초록이다)', () => {
  const { 파일수 } = 훑기();
  assert.ok(파일수 >= 300, `훑은 파일이 ${파일수}벌뿐이다 — 걸음이 깨졌다(2026-08-17 실측 362벌)`);
});

/**
 * 걸린 자리와 유예 목록을 **다중집합으로** 대조한다 — 순수 함수라 픽스처가 탐지력을 진다(맹점 ②).
 * 🔑 집합이 아니라 다중집합인 이유: 같은 파일에 글자가 같은 자리가 둘이면 집합은 하나로 접고,
 *   그때 **한 건을 갚고 한 건을 더해도 조용히 통과한다**(F618 ㉡ 이 진 약점 그대로).
 */
function 대조(걸린것, 목록) {
  const 남은셈 = new Map();
  for (const e of 목록) 남은셈.set(키(e), (남은셈.get(키(e)) || 0) + 1);
  const 새것 = [];
  for (const e of 걸린것) {
    const k = 키(e);
    if (남은셈.get(k) > 0) 남은셈.set(k, 남은셈.get(k) - 1);
    else 새것.push(`${e.파일}:${e.줄번호}  (지문 ${e.지문})`);
  }
  return { 새것, 사라진것: [...남은셈].filter(([, n]) => n > 0).map(([k]) => k) };
}

test('② 래칫 — 손으로 형제 경로를 조립하는 자리가 «고정된 목록 그대로»다', () => {
  const { 걸린것 } = 훑기();
  const { 새것, 사라진것 } = 대조(걸린것, 남은자리);

  assert.deepEqual(새것, [],
    '형제 경로를 **손으로** 조립하는 자리가 늘었다 — 갈라지면 워크트리에서 조용히 형제를 못 찾는다.\n'
    + `   → \`require('${정본상대}').형제경로(root)\` 를 쓴다(자리만 답한다 · 존재 판정은 부르는 쪽이 그대로 한다).\n`
    + '   ⚠ 줄을 **옮기기만** 했다면 이건 안 뜬다(키는 내용의 지문이다 · F618). 떴다면 내용이 바뀌었거나 늘었다.\n'
    + '   유예해야 할 자리면 위 `남은자리` 에 `{ 파일, 지문, 사유 }` 로 넣는다 — 지문은 위 괄호의 값 그대로.');

  assert.deepEqual(사라진것, [],
    '빚을 갚았으면 **목록에서도 지운다** — 남겨 두면 다음 사람이 「아직 3건 남았다」로 읽는다.\n'
    + `   지울 줄: ${사라진것.join(' · ')}`);
});

test('② 자기 처방을 스스로 막지 않는다 — 정본은 이 검사를 통과한다', () => {
  /* 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103). 처방이 가리키는 파일이 위반이면
   * 그 순간 이 가드는 「고칠 방법이 없다」가 된다. 정본은 이름을 **인자로** 받으므로 안 걸린다. */
  const { 걸린것 } = 훑기();
  assert.ok(!걸린것.some((e) => e.파일 === 정본상대), `정본 자신이 위반이다: ${정본상대}`);
});

/* ── ③ 정본의 계약 — 자리만 답하고 존재는 «안» 본다 ─────────────────────────
 * 부르는 쪽 셋의 술어가 각자 다르다(디렉터리냐 · `.git` 이 있냐 · 그 안의 특정 파일이 있냐).
 * 정본이 존재 판정을 껴안는 순간 그중 둘이 조용히 틀린다 — 그래서 계약을 값으로 못박는다. */

test('③ 아무것도 없는 자리에도 «경로»를 답한다 — 존재 판정은 부르는 쪽 몫이다', () => {
  const 임시 = fs.mkdtempSync(path.join(os.tmpdir(), 'synk-통로-'));
  try {
    const 자리 = 형제저장소.형제경로(path.join(임시, '없는저장소'));
    assert.equal(typeof 자리, 'string');
    assert.ok(자리.endsWith(형제저장소.기본이름), `형제 이름으로 안 끝난다: ${자리}`);
    assert.ok(!fs.existsSync(자리), '픽스처가 애초에 비어 있지 않다 — 이 검사가 무의미해진다');
  } finally {
    fs.rmSync(임시, { recursive: true, force: true });
  }
});

test('③ 형제 이름은 인자로 갈 수 있다 — 형제가 늘어도 사본을 안 만든다', () => {
  const 자리 = 형제저장소.형제경로(REPO, 'SYNK-무언가');
  assert.ok(자리.endsWith('SYNK-무언가'), `이름 인자가 안 먹는다: ${자리}`);
  assert.equal(path.dirname(자리), path.dirname(형제저장소.형제경로(REPO)),
    '같은 부모 아래여야 한다 — 이름만 갈리는 축이다');
});

/* ── ⑦ 래칫의 «키»가 행번호가 아니다 — 픽스처가 그 축을 진다 (F618 · 2026-08-18) ────────
 *
 * 이 넷이 래칫이 재려는 축의 전부다. 위 ② 는 실저장소라 오늘의 빚 3건에만 답하고,
 * 「줄을 밀면 어떻게 되나」는 실저장소가 우연히 안 밀린 날엔 한 번도 안 돌아본다 —
 * 그 자리가 정확히 F618 이 난 곳이다(장치가 도는 모양으로 틀린 값을 냈다).
 */

/** 픽스처 저장소 하나 — `tools/` 밑에 준 파일들을 깔고 뿌리를 돌려준다. */
function 픽스처(파일맵) {
  const 밑 = fs.mkdtempSync(path.join(os.tmpdir(), 'ratchet-'));
  fs.mkdirSync(path.join(밑, 'tools'), { recursive: true });
  for (const [이름, 본문] of Object.entries(파일맵)) fs.writeFileSync(path.join(밑, 'tools', 이름), 본문, 'utf8');
  return 밑;
}

/* 바늘을 **이어붙여 짓는다** — 원문을 그대로 실으면 이 파일이 ② 에 걸린다(위 「바늘」과 같은 축). */
const 손조립줄 = (앞) => `${앞} = path.resolve(root, ${점점}, '${'SYNK' + '-' + 'talk'}');`;

test('🔴 ⑦ 줄을 «밀기만» 하면 지문이 안 바뀐다 — F618 이 난 자리다', () => {
  const 한줄 = 손조립줄('  const 형제');
  const 밑 = 픽스처({ 'a.js': `${한줄}\n` });
  const 앞 = 훑기({ 뿌리: 밑, 폴더: ['tools'] }).걸린것;
  fs.writeFileSync(path.join(밑, 'tools', 'a.js'), `\n\n\n\n\n${한줄}\n`, 'utf8');
  const 뒤 = 훑기({ 뿌리: 밑, 폴더: ['tools'] }).걸린것;

  assert.strictEqual(앞.length, 1);
  assert.strictEqual(앞[0].지문, 뒤[0].지문, '줄만 밀렸는데 키가 바뀌었다 — 무관한 편집마다 「위반이 늘었다」로 운다(F618)');
  assert.notStrictEqual(앞[0].줄번호, 뒤[0].줄번호, '픽스처가 애초에 안 밀렸다 — 이 검사가 무의미해진다');
});

test('🔴 ⑦ 들여쓰기만 달라져도 같은 지문이다 — 포맷 정리로 빚이 「새 위반」이 되면 안 된다', () => {
  const 밑 = 픽스처({ 'a.js': `${손조립줄('const 형제')}\n`, 'b.js': `${손조립줄('      const 형제')}\n` });
  const r = 훑기({ 뿌리: 밑, 폴더: ['tools'] }).걸린것;
  assert.strictEqual(r.length, 2);
  assert.strictEqual(r[0].지문, r[1].지문);
});

test('🔴 ⑦ 내용이 바뀌면 지문이 바뀐다 — 안 바뀌면 래칫이 재려던 축을 잃는다', () => {
  const 밑 = 픽스처({ 'a.js': `${손조립줄('const 형제')}\n`, 'b.js': `${손조립줄('const 딴이름')}\n` });
  const r = 훑기({ 뿌리: 밑, 폴더: ['tools'] }).걸린것;
  assert.notStrictEqual(r[0].지문, r[1].지문);
});

test('🔴 ⑦ 글자가 같은 자리가 둘이면 **둘 다** 센다 — 개수까지 지켜야 하나를 갚아도 안 조용하다', () => {
  /* 키를 객체로 잡으면 여기서 하나로 접히고, 그때 한 건을 갚고 한 건을 더해도 통과한다
   * (F618 ㉡ 이 진 약점이 그것이다). 그래서 위 ② 는 다중집합으로 센다. */
  const 한줄 = 손조립줄('  const 형제');
  const 밑 = 픽스처({ 'a.js': `${한줄}\n${한줄}\n` });
  const r = 훑기({ 뿌리: 밑, 폴더: ['tools'] }).걸린것;
  assert.strictEqual(r.length, 2, '같은 글자의 두 자리를 하나로 접었다');
  assert.strictEqual(r[0].지문, r[1].지문);
  assert.deepStrictEqual(r.map((e) => e.줄번호), [1, 2], '안내용 행번호는 여전히 각각이어야 한다');
});

test('🔴 ⑦ 대조는 «행번호»가 아니라 지문으로 짝짓는다 — 밀린 줄은 새 위반이 아니다', () => {
  const 목록 = [{ 파일: 'tools/a.js', 지문: 'aaaa1111', 사유: '유예' }];
  const 밀린것 = [{ 파일: 'tools/a.js', 지문: 'aaaa1111', 줄번호: 999 }];
  assert.deepStrictEqual(대조(밀린것, 목록), { 새것: [], 사라진것: [] },
    '행번호가 키에 섞이면 무관한 편집마다 「위반이 늘었다」로 운다(F618)');
});

test('🔴 ⑦ 대조는 «개수»를 지킨다 — 하나 갚고 하나 더해도 조용하지 않다', () => {
  const 목록 = [
    { 파일: 'tools/a.js', 지문: 'dup00000', 사유: '유예 1' },
    { 파일: 'tools/a.js', 지문: 'dup00000', 사유: '유예 2' },
  ];
  const 한건만 = [{ 파일: 'tools/a.js', 지문: 'dup00000', 줄번호: 1 }];
  const r = 대조(한건만, 목록);
  assert.deepStrictEqual(r.새것, []);
  assert.strictEqual(r.사라진것.length, 1, '갚은 한 건을 목록에서 지우라고 말해야 한다');

  const 세건 = [1, 2, 3].map((n) => ({ 파일: 'tools/a.js', 지문: 'dup00000', 줄번호: n }));
  assert.strictEqual(대조(세건, 목록).새것.length, 1, '늘어난 한 건을 새 위반으로 세야 한다');
});

test('🔴 ⑦ 파일이 다르면 같은 지문이어도 다른 자리다 — 키에 파일이 빠지면 남의 빚으로 내 빚이 가려진다', () => {
  const 목록 = [{ 파일: 'tools/a.js', 지문: 'same0000', 사유: '유예' }];
  const 딴파일 = [{ 파일: 'tools/b.js', 지문: 'same0000', 줄번호: 1 }];
  const r = 대조(딴파일, 목록);
  assert.strictEqual(r.새것.length, 1);
  assert.strictEqual(r.사라진것.length, 1);
});
