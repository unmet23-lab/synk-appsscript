'use strict';
/**
 * 형제 저장소 경로는 **통로가 하나다** — 사본을 못 만들게 기계로 막는다 (🎫 `local_91e2b70a` · F564 후속).
 *
 * ■ 왜 있나 (2026-08-17 실측)
 *   「SYNK-talk 은 어디 있나」의 답이 **네 벌**로 갈라져 있었고 전부 경로 «모양»으로 짐작했다.
 *   갈라진 쪽의 증상은 언제나 「통과」다 — 형제를 못 찾으면 그 갈래가 `못잼` 으로 접히거나
 *   통째로 건너뛰어지고, 그때 거짓 talk 인용·미대조 커밋이 조용히 지나간다(F564 가 그 첫 발각).
 *   네 벌을 같은 ROOT 넷에 대 본 값은 정본(`.claude/hooks/lib/형제저장소.js`) 머리말에 있다 —
 *   급소는 마지막 줄이다: `.claude/worktrees/` **밖**의 워크트리에서는 **네 벌 다** 눈이 멀었고,
 *   이 기계엔 그런 워크트리(`head-ci`)가 실제로 살아 있었다.
 *
 * ■ 무엇을 재나 — 셋
 *   ① 탐지력 — **픽스처가 진다**(F296 · 실저장소가 우연히 깨끗한 날에도 판정을 낸다).
 *      바늘이 실제로 쓰이던 네 모양을 다 잡고, **합법인 세 모양은 안 잡는지**까지 못박는다.
 *   ② 래칫 — 실저장소에 남은 자리를 **이름으로** 고정한다. 늘어도 빨갛고 목록이 어긋나도 빨갛다.
 *      🔑 「0건」이 아니라 래칫인 이유: 남은 3건은 **남의 활성 보드 줄이 잠근 파일**이라 지금
 *      아무도 못 고친다(F574). 0 을 우기면 따를 수 없는 처방이 되고, 그러면 가드가 꺼진다(F103).
 *      빚을 숨기지 말고 «세어» 둔다 — 잠금이 풀리는 날 이 목록에서 지우면 그게 곧 갚음이다.
 *   ③ 정본의 계약 — 「자리만 답하고 존재는 안 본다」. 이게 깨지면 부르는 쪽 셋의 술어가
 *      각자 다르므로(디렉터리냐 · `.git` 이 있냐 · 그 안의 특정 파일이 있냐) 그중 둘이 조용히 틀린다.
 *
 * ■ ⚠ 대가 — **못 보는 자리를 적어 둔다**(맹점 ④)
 *   · 바늘이 «글자»다 — `path.join(x, 위, 이름)` 처럼 변수로 조립하면 못 본다. 그 모양이 늘면
 *     이 줄이 먼저 낡는다. 대신 ③ 과 `tests/형제저장소해석.test.js` ⑤ 가 **행동**으로 받친다.
 *   · `.js` 만 훑는다(`.mjs`·`.cjs`·셸·파이썬은 분모 밖). `tools/*.py` 는 형제를 안 만진다(실측).
 *   · 훑는 뿌리는 `tools/`·`.claude/hooks/`·`tests/` 셋뿐이다. 그래서 ② 는 **분모부터** 단언한다 —
 *     걸음이 깨져 0벌을 훑어도 「위반 0」은 초록으로 보인다(F207).
 *   닫는 것 = 없다(탐지를 좁히는 조항이 아니다).
 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const { 줄맞춰코드만 } = require('./lib/소스검사.js');

const REPO = path.join(__dirname, '..');
const 정본상대 = '.claude/hooks/lib/형제저장소.js';
const 형제저장소 = require(path.join(REPO, 정본상대));

/* ── 바늘 ────────────────────────────────────────────────────────────────────
 * 🔑 **이어붙여 짓는다** — 그러지 않으면 이 파일 자신이 ② 에 걸려 가드가 자기를 문다
 *   (`tests/소스검사통로.test.js` 가 같은 자리에서 먼저 쓴 수법). 그래서 조각으로 둔다. */
const 위 = new RegExp(`['"\`]\\.${'\\.'}['"\`]`);              // '..' 리터럴
const 형제이름 = new RegExp(`['"\`]SYNK${'-'}talk['"\`]`);      // 'SYNK-talk' 리터럴
const 조립 = /path\.(?:join|resolve)\s*\(/;

/** 한 줄이 «형제 경로를 손으로 조립하는» 자리인가. */
function 손조립인가(줄) {
  return 조립.test(줄) && 위.test(줄) && 형제이름.test(줄);
}

/* ── ① 탐지력 — 픽스처가 진다 ───────────────────────────────────────────────
 * 잡아야 하는 넷 = 실제로 갈라져 있던 네 벌의 모양 그대로. 잡으면 안 되는 셋 = 이 저장소가
 * 실제로 쓰는 합법 표기(되돌리면 거짓양성이 나고, 따를 수 없는 처방은 가드를 끄게 만든다). */
const 이름 = 'SYNK' + '-talk';
const 점점 = "'." + ".'";

test('① 갈라져 있던 네 모양을 다 잡는다', () => {
  const 잡을것 = [
    [`const 형제 = path.resolve(root, ${점점}, '${이름}');`, '보드근거·계약동기화 판'],
    [`const 형제 = path.resolve(as.replace(꼬리, ''), ${점점}, '${이름}');`, '보드낡음 판(꼬리 벗기기)'],
    [`후보.push(path.resolve(m[1], ${점점}, '${이름}'));`, '형제초록·이해대장 판(후보 목록)'],
    [`if (s === 'talk') return path.join(ROOT, ${점점}, '${이름}');`, '자율기록 판(이름→경로)'],
  ];
  for (const [줄, 왜] of 잡을것) assert.ok(손조립인가(줄), `못 잡는다: ${왜}`);
});

test('① 합법인 세 모양은 안 잡는다 — 거짓양성은 가드를 끄게 만든다', () => {
  const 통과할것 = [
    [`process.env.SYNK_OWNER_SIBLINGS = '../${이름}';`, '이음매에 넣는 «값» — 경로 조립이 아니다'],
    [`const SIBLING_DEFAULT = ['${이름}'];`, '형제 «이름» 목록 — 자리를 안 짓는다'],
    [`fs.mkdirSync(path.join(임시, '${이름}'), { recursive: true });`, '픽스처가 짓는 형제 — 위(`..`)가 없다'],
  ];
  for (const [줄, 왜] of 통과할것) assert.ok(!손조립인가(줄), `거짓양성: ${왜}`);
});

test('① 주석 속 표기는 안 센다 — 사연을 적어 둔 자리가 위반이 되면 사연을 못 적는다', () => {
  const 줄 = `// 경로 규칙은 path.join(root, ${점점}, '${이름}') 였다`;
  assert.ok(손조립인가(줄), '픽스처가 애초에 안 걸린다 — 이 검사가 무의미해진다');
  assert.equal(줄맞춰코드만(줄).trim(), '', '주석이 안 눕혀졌다 — ② 가 주석을 위반으로 셀 것이다');
});

/* ── ② 래칫 — 실저장소에 남은 자리를 «이름»으로 고정한다 ───────────────────── */

/** 아직 손조립인 자리. **왜 못 고치는지**를 함께 적는다 — 이유 없는 예외는 다음 사람이 못 지운다. */
const 남은자리 = {
  'tools/lib/보드근거.js:208': '남의 활성 보드 줄(`86d6d162`)이 이 파일을 잠갔다 — F574 (그 줄은 그 뒤 ✅종결 · 179→208 은 F614 수리가 위쪽에 29줄을 더해 «같은 자리»가 밀린 것이다)',
  'tools/이해대장.js:141': '남의 활성 보드 줄(`24ba4d6b` · 가지 `worktree-ledger-blocker-split`)이 잠갔다 (140→141 은 인자 게이트 부착이 위쪽에 `require` 한 줄을 더해 «같은 자리»가 밀린 것이다 · 2026-08-18)',
  'tools/이해대장.js:143': '위와 같은 줄',
};

function js들(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === '.git' || e.name === 'worktrees') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) js들(p, out);
    else if (e.name.endsWith('.js')) out.push(p);
  }
  return out;
}

function 훑기() {
  const 걸린것 = [];
  let 파일수 = 0;
  for (const 뿌리 of ['tools', '.claude/hooks', 'tests'].map((d) => path.join(REPO, d))) {
    for (const f of js들(뿌리)) {
      파일수 += 1;
      줄맞춰코드만(fs.readFileSync(f, 'utf8')).split('\n').forEach((줄, i) => {
        if (손조립인가(줄)) 걸린것.push(`${path.relative(REPO, f).replace(/\\/g, '/')}:${i + 1}`);
      });
    }
  }
  return { 걸린것, 파일수 };
}

test('② 분모 — 훑은 파일이 실제로 있다(0벌을 훑어도 「위반 0」은 초록이다)', () => {
  const { 파일수 } = 훑기();
  assert.ok(파일수 >= 300, `훑은 파일이 ${파일수}벌뿐이다 — 걸음이 깨졌다(2026-08-17 실측 362벌)`);
});

test('② 래칫 — 손으로 형제 경로를 조립하는 자리가 «고정된 목록 그대로»다', () => {
  const { 걸린것 } = 훑기();
  const 기대 = Object.keys(남은자리).sort();
  const 실제 = [...걸린것].sort();
  const 새것 = 실제.filter((k) => !기대.includes(k));
  const 사라진것 = 기대.filter((k) => !실제.includes(k));

  assert.deepEqual(새것, [],
    '형제 경로를 **손으로** 조립하는 자리가 늘었다 — 갈라지면 워크트리에서 조용히 형제를 못 찾는다.\n'
    + `   → \`require('${정본상대}').형제경로(root)\` 를 쓴다(자리만 답한다 · 존재 판정은 부르는 쪽이 그대로 한다).`);

  assert.deepEqual(사라진것, [],
    '빚을 갚았으면 **목록에서도 지운다** — 남겨 두면 다음 사람이 「아직 3건 남았다」로 읽는다.\n'
    + `   지울 줄: ${사라진것.map((k) => `${k} (${남은자리[k]})`).join(' · ')}`);
});

test('② 자기 처방을 스스로 막지 않는다 — 정본은 이 검사를 통과한다', () => {
  /* 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103). 처방이 가리키는 파일이 위반이면
   * 그 순간 이 가드는 「고칠 방법이 없다」가 된다. 정본은 이름을 **인자로** 받으므로 안 걸린다. */
  const { 걸린것 } = 훑기();
  assert.ok(!걸린것.some((k) => k.startsWith(정본상대)), `정본 자신이 위반이다: ${정본상대}`);
});

/* ── ③ 정본의 계약 — 자리만 답하고 존재는 «안» 본다 ─────────────────────────
 * 부르는 쪽 셋의 술어가 각자 다르다(디렉터리냐 · `.git` 이 있냐 · 그 안의 특정 파일이 있냐).
 * 정본이 존재 판정을 껴안는 순간 그중 둘이 조용히 틀린다 — 그래서 계약을 값으로 못박는다. */

test('③ 아무것도 없는 자리에도 «경로»를 답한다 — 존재 판정은 부르는 쪽 몫이다', () => {
  const 임시 = fs.mkdtempSync(path.join(os.tmpdir(), 'synk-통로-'));
  try {
    const 자리 = 형제저장소.형제경로(path.join(임시, '없는저장소'));
    assert.equal(typeof 자리, 'string');
    assert.ok(자리.endsWith(형제저장소.기본이름), `형제 이름으로 안 끝난다: ${자리}`);
    assert.ok(!fs.existsSync(자리), '픽스처가 애초에 비어 있지 않다 — 이 검사가 무의미해진다');
  } finally {
    fs.rmSync(임시, { recursive: true, force: true });
  }
});

test('③ 형제 이름은 인자로 갈 수 있다 — 형제가 늘어도 사본을 안 만든다', () => {
  const 자리 = 형제저장소.형제경로(REPO, 'SYNK-무언가');
  assert.ok(자리.endsWith('SYNK-무언가'), `이름 인자가 안 먹는다: ${자리}`);
  assert.equal(path.dirname(자리), path.dirname(형제저장소.형제경로(REPO)),
    '같은 부모 아래여야 한다 — 이름만 갈리는 축이다');
});
