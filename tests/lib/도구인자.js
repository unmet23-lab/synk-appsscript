/**
 * `tools/` 의 «인자 층»을 읽는 공용 통로 — **분모·게이트 여부·자기 낱말을 한 곳에서** 판정한다.
 *
 * ■ 🔴 왜 손 목록이 아닌가
 *   손으로 적은 도구 목록은 **새 도구가 생기는 날 조용히 낡는다**(형제 F435 가 정확히 그것).
 *   그래서 분모는 디렉터리에서 파생하고, 「게이트를 걸었나」도 코드에서 읽는다.
 *
 * ■ 🔴 모든 판정은 `코드만` 을 지난 **코드**만 본다 (산문은 코드가 아니다)
 *   실측 2026-08-18 · 이 트랙을 짜면서 **두 번** 걸렸다:
 *     · `grep -c -- '--운영' tools/작업본소유자.js` 가 2 를 냈다 → 둘 다 **주석**이었다.
 *       그대로 믿었으면 「이 저장소에도 조준축이 있다」는 틀린 전제로 설계했다.
 *     · `grep -l 인자게이트 tools/*.js` 가 `작업본소유자.js` 를 냈다 → 그것도 **주석**이다.
 *       그대로 믿었으면 게이트 보유 수가 부풀고, 그 부푼 분모가 「덜 남았다」로 읽힌다.
 *   👉 형제 저장소가 같은 병을 두 번 겪고(#Q111 주석 속 낱말이 도구를 «승격» · F594 `앱시작.js`)
 *      렉서 통로로 옮겼다. 여기서는 **처음부터** 그 통로(`tests/lib/소스검사.js` 의 `코드만`)를 쓴다.
 *      사본을 만들지 않는다 — 렉서는 그 파일 하나다(F401).
 *
 * ⚠ **이 스캐너가 틀릴 때의 모습** (v9.2 맹점 ④ — 맞는 얼굴로 틀린 값)
 *   자기 낱말 추출(`낱말들`)이 도구가 실제로 읽는 낱말을 **못 보면**, 아래 ④가 그 낱말을 요구하지
 *   않는다. 그러면 게이트를 달 때 선언에서 빠지고 **되던 명령이 죽는다** — 거짓양성이 「검사
 *   시점」에서 「부착 시점」으로 미뤄질 뿐이다. 새는 방향이 「덜 요구한다」라 적색이 아니다.
 *   👉 그래서 ㉠줄 단위로 훑고(짝 밀림 손해를 한 줄에 가둔다) ㉡추출한 낱말은 **부착할 때 사람이
 *      그 파일을 직접 연다**. 이것이 남는 대가고, 지금 닫지 않는다.
 *   🔑 **닫은 것**: 옛 방식(원문 `grep`)을 이 통로가 대체한다 — 위 실측 두 건이 그 방식의 값이다.
 */
const fs = require('node:fs');
const path = require('node:path');
const { 파일소스, 코드만 } = require('./소스검사.js');

/** 이 저장소가 실제로 쓰는 낱말 모양 — `--키=값` 꼴은 0건이다(2026-08-18 전수 실측). */
const 낱말모양 = /^--[가-힣A-Za-z0-9_-]+$/;

/**
 * 코드가 **낱말 그 자체로** 인용한 `--…` 전량 (자식 프로세스 인자도 여기 섞인다).
 *
 * 🔴 **줄 단위로 훑는다** — 파일 전체에 전역 토크나이저를 돌리면 앞에서 짝이 **한 번만** 어긋나도
 *   (정규식 리터럴 속 따옴표 하나면 된다) 그 뒤가 통째로 밀린다. 형제 저장소 실측: 그 방식으로
 *   조각 104개를 뽑고도 찾던 낱말이 0개였다. 줄 단위는 손해가 **그 한 줄에 갇힌다.**
 * ⚠ 백틱도 본다 — 안 보면 그만큼 «덜 요구»한다.
 */
function 낱말들(코드) {
  const 나온것 = new Set();
  for (const 줄 of String(코드).split('\n')) {
    for (const 조각 of 줄.match(/'[^']*'|"[^"]*"|`[^`]*`/g) || []) {
      const 속 = 조각.slice(1, -1);
      if (낱말모양.test(속)) 나온것.add(속);
    }
  }
  return [...나온것];
}

const 이름꼴 = '[A-Za-z_$가-힣][\\w$가-힣]*';
const 정규식escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * 이름 «앞» 경계 — 붙어 있는 더 긴 이름은 그 이름의 증거가 아니다.
 *
 * 🔴 **`\b` 를 쓸 수 없다**: JS 의 `\b` 는 ASCII 낱말 경계라 한글 식별자엔 **원리상 안 붙는다.**
 *   실측 2026-08-18(이 트랙): argv 이름이 `인자` 인데 `작업가지.js` 에 `우회_인자(…)` 가 있어
 *   그 호출이 «`인자(`» 로 읽혔고, 그 안의 git 인자(`--abbrev-ref` 류)가 **자기 낱말로 승격**됐다.
 *   새는 방향이 「선언에 남의 낱말을 넣어라」라서, 따르면 그 낱말이 CLI 에서 통과한다(F592 모양).
 */
const 맨이름앞 = '(?<![\\w$가-힣])';

/** argv 를 담는 이름 전부 — 이 저장소가 쓰는 두 모양(`const 인자 = process.argv.slice(2)` · 직접)과
 *  그것을 받는 함수의 **매개변수 꼴**(`재심완료보고(argv)`)을 따라간다. */
function argv이름들(코드) {
  const 이름 = new Set(['process.argv']);
  let m;
  const 직접 = new RegExp(`(?:const|let|var)\\s+(${이름꼴})\\s*=\\s*process\\.argv`, 'g');
  while ((m = 직접.exec(코드))) 이름.add(m[1]);
  /* `함수(argv)` 로 넘기는 자리 — 받는 쪽 매개변수 이름까지 따라가야 그 함수 안의 비교가 보인다. */
  for (const v of [...이름]) {
    const esc = 정규식escape(v);
    const 넘김 = new RegExp(`(${이름꼴})\\s*\\(\\s*${esc}\\b[^)]*\\)`, 'g');
    while ((m = 넘김.exec(코드))) {
      const 함수 = 정규식escape(m[1]);
      const d = new RegExp(`function\\s+${함수}\\s*\\(\\s*(${이름꼴})`).exec(코드)
        || new RegExp(`(?:const|let|var)\\s+${함수}\\s*=\\s*(?:async\\s*)?\\(?\\s*(${이름꼴})`).exec(코드);
      if (d) 이름.add(d[1]);
    }
  }
  return [...이름];
}

/**
 * 화살표 함수의 **몸통**을 잘라 낸다 — `=>` 바로 뒤부터.
 *   · `{ … }` 꼴이면 짝 맞는 `}` 까지.
 *   · 식 꼴이면 깊이 0 의 `;` 나 `,` 까지(둘 다 없으면 줄 끝).
 * 🔑 «근처»가 아니라 «안»을 봐야 하는 이유는 위 `도우미이름들` 머리말에 실측으로 적혀 있다.
 */
function 화살표몸통(코드, 시작) {
  const s = String(코드);
  let i = 시작;
  while (i < s.length && /\s/.test(s[i])) i += 1;
  if (s[i] === '{') {
    let 깊이 = 0;
    for (let j = i; j < s.length; j += 1) {
      if (s[j] === '{') 깊이 += 1;
      else if (s[j] === '}') { 깊이 -= 1; if (깊이 === 0) return s.slice(i, j + 1); }
    }
    return s.slice(i);
  }
  let 깊이 = 0;
  for (let j = i; j < s.length; j += 1) {
    const c = s[j];
    if ('([{'.includes(c)) 깊이 += 1;
    else if (')]}'.includes(c)) { 깊이 -= 1; if (깊이 < 0) return s.slice(i, j); }
    else if (깊이 === 0 && (c === ';' || c === ',' || c === '\n')) return s.slice(i, j);
  }
  return s.slice(i);
}

/**
 * 낱말을 대신 읽어 주는 «도우미» 이름 전부 — 두 꼴이 있고, **이 저장소의 주력은 둘째**다.
 *
 * ㉠ argv 를 **넘겨받는** 꼴: `값(인자, '--열기')` — 형제 저장소의 주력.
 * ㉡ argv 를 **닫아 쥔** 꼴(클로저): `const 있나 = (f) => 인자.includes(f);` 뒤에 `있나('--열기')`.
 *
 * 🔴 **㉡을 못 보면 이 저장소에서 스캐너가 통째로 뒤집힌다**(2026-08-18 실측 · 이 트랙에서 걸렸다):
 *   `작업가지.js` 의 자기 낱말이 `--닫기 --열기 --훅` 인데, ㉠만 보던 판은 그 셋을 **자식후보**로
 *   밀어내고 대신 `--abbrev-ref`·`--porcelain` 같은 **git 인자를 자기 낱말로** 냈다. 그대로
 *   선언하면 ⓐ진짜 낱말이 게이트에 막혀 **되던 명령이 죽고**(F103) ⓑgit 인자가 CLI 에서 통과한다.
 *   두 방향이 동시에 틀리는 자리라 픽스처로 못박는다.
 *
 * 🔴 **몸통은 «그 함수의 몸통»으로 정확히 잘라야 한다 — 문자 창 어림은 뒤집힌다**(같은 날 실측).
 *   처음엔 선언 뒤 400자를 창으로 봤다. 그러자 argv 를 읽는 도우미 «근처에 있을 뿐인» 다른 화살표
 *   함수까지 도우미로 등록됐다 — `작업가지.js` 의 `gh` 가 그 자리이고, 그래서 `gh(['--version'])`
 *   의 **git 인자가 자기 낱말로** 올라왔다. 새는 방향이 「선언에 남의 낱말을 넣어라」다.
 */
function 도우미이름들(코드, argv이름) {
  const 이름 = new Set();
  for (const v of argv이름) {
    const esc = 정규식escape(v);
    /* ㉠ 넘겨받는 꼴 — **정의부를 호출로 읽지 않는다.**
     * 🔴 실측 2026-08-18: `작업가지.js` 의 `function gh(인자, 옵션 = {})` 는 매개변수 이름이
     *   argv 변수와 **같다**(`인자`). 그래서 그 «정의»가 「gh 가 argv 를 넘겨받는다」로 읽혔고,
     *   `gh(['--version'])`·`git(['status', '--porcelain'])` 의 **git 인자가 자기 낱말로** 올라왔다.
     *   이름 가림(shadowing)은 이 저장소처럼 한글 인자 이름을 쓰는 곳에서 흔하다. */
    const 넘김 = new RegExp(`(${이름꼴})\\s*\\(\\s*${esc}\\s*,`, 'g');
    let m;
    while ((m = 넘김.exec(코드))) {
      const 앞 = 코드.slice(Math.max(0, m.index - 24), m.index);
      if (/(?:function|class)\s*$/.test(앞)) continue;                       // 정의부다
      if (new RegExp(`(?:const|let|var)\\s+${정규식escape(m[1])}\\s*=\\s*$`).test(앞)) continue;
      이름.add(m[1]);
    }
    /* ㉡ 닫아 쥔 꼴 — **그 화살표 함수의 몸통 안에서만** 그 argv 이름을 «맨이름»으로 읽는가 */
    const 읽는가 = new RegExp(`${맨이름앞}${esc}\\s*(?:\\.(?:includes|indexOf|lastIndexOf)\\s*\\(|\\[)`);
    const 선언 = new RegExp(`(?:const|let|var)\\s+(${이름꼴})\\s*=\\s*(?:async\\s*)?\\(?[^)\\n]*\\)?\\s*=>`, 'g');
    while ((m = 선언.exec(코드))) {
      if (읽는가.test(화살표몸통(코드, 선언.lastIndex))) 이름.add(m[1]);
    }
  }
  return [...이름];
}

/**
 * 도구 하나의 인자 층.
 *
 * 🔑 **자기 낱말은 «소스에 있나»가 아니라 «argv 파생과 비교되나»로 센다.** 형제 저장소가 여기서
 *   비싸게 배웠다: 옛 판이 자식 프로세스 인자(`git --name-only` 류)까지 선언을 요구했고,
 *   **시키는 대로 선언하면 그 낱말이 CLI 에서 통과한다** — 처방을 따르면 병이 생겼다(F103).
 */
function 인자층(코드) {
  const argv읽나 = /process\.argv/.test(코드);
  if (!argv읽나) return { argv읽나: false, 낱말: [], 자식후보: [] };
  const argv이름 = argv이름들(코드);
  const 대상 = [...argv이름, ...도우미이름들(코드, argv이름)];
  const 결과 = new Set();
  for (const v of 대상) {
    const esc = 정규식escape(v);
    const 꼴들 = [
      new RegExp(`${맨이름앞}${esc}[^;\\n]{0,100}?\\.(?:includes|indexOf|lastIndexOf)\\(\\s*(['"\`])(--[^'"\`]+)\\1`, 'g'),
      new RegExp(`${맨이름앞}${esc}\\s*\\([^)\\n]{0,60}?(['"\`])(--[^'"\`]+)\\1`, 'g'),
      new RegExp(`${맨이름앞}${esc}[^;\\n]{0,140}?===\\s*(['"\`])(--[^'"\`]+)\\1`, 'g'),
      new RegExp(`(['"\`])(--[^'"\`]+)\\1\\s*===[^;\\n]{0,140}?${맨이름앞}${esc}`, 'g'),
    ];
    for (const p of 꼴들) { let m; while ((m = p.exec(코드))) if (낱말모양.test(m[2])) 결과.add(m[2]); }
  }
  /* 이미 선언한 목록도 자기 낱말이다 — 게이트를 건 도구는 여기서 자기 축을 스스로 밝힌다. */
  const d = 코드.match(/const\s+아는플래그\s*=\s*\[([^\]]*)\]/);
  if (d) for (const w of 낱말들(`[${d[1]}]`)) 결과.add(w);
  return {
    argv읽나: true,
    낱말: [...결과].sort(),
    자식후보: 낱말들(코드).filter((w) => !결과.has(w)).sort(),
  };
}

/** 선언한 `아는플래그` — 없으면 `null`. */
function 선언목록(코드) {
  const m = 코드.match(/const\s+아는플래그\s*=\s*\[([^\]]*)\]/);
  return m ? { 낱말: 낱말들(`[${m[1]}]`) } : null;
}

/**
 * 게이트의 «답»을 실제로 쓰는가 — 부르기만 하면 **부르지 않은 것과 같다.**
 * 셋 중 하나여야 한다: ⓐ`if (인자게이트(…))` ⓑ`return 인자게이트(…)` ⓒ변수로 받고 뒤에서 씀.
 * @returns {string|null} 위반 사유 · 정상이면 null
 */
function 답을쓰나(코드) {
  const i = 코드.search(/인자게이트\s*\(/);
  if (i === -1) return '부르지 않는다';
  const 앞 = 코드.slice(Math.max(0, i - 60), i);
  if (/if\s*\(\s*$/.test(앞) || /return\s+$/.test(앞)) return null;
  const m = 앞.match(/(?:const|let|var)\s+([^\s=]+)\s*=\s*$/);
  if (!m) return '답을 안 받는다(맨 호출문)';
  /* ⚠ `\b` 를 안 쓴다 — JS 의 `\b` 는 ASCII 낱말 경계라 한글 변수명(`플래그오류`)엔 **원리상 안 붙는다.** */
  return 코드.slice(i).includes(m[1]) ? null : `답(${m[1]})을 받고도 안 쓴다`;
}

/**
 * **분모** — 그 디렉터리에서 `process.argv` 를 «코드로» 읽는 도구 전부.
 * 🔑 하위 디렉터리(`tools/lib/`)는 안 본다 — 그건 도구가 아니라 부품이다.
 */
function CLI도구들(디렉터리) {
  return fs.readdirSync(디렉터리)
    .filter((f) => f.endsWith('.js'))
    .map((f) => {
      const 코드 = 코드만(파일소스(path.join(디렉터리, f)));
      return {
        파일: f,
        코드,
        게이트: /인자게이트\s*\(/.test(코드),
        선언: 선언목록(코드),
        ...인자층(코드),
      };
    })
    .filter((r) => r.argv읽나);
}

