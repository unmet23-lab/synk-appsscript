/**
 * 종결 ↔ 배포 결속 회귀 — 「✅종결」을 적기 전에 **배포가 갈렸는지 실제로 재는가**.
 *
 * 왜 있나 (2026-08-12 · `local_57ec0a96` 실측):
 *   리허설 Edge Function 14종 중 **6종이 소스와 달랐고 2종은 아예 없었다.** 빠진 것이 전부 그날
 *   「✅종결」로 장부에 적힌 것들이었다 — `학습자상태.mjs`(v7 집중띠 축) · `꼬리.mjs`(철학 Ⅱ-8) ·
 *   `회고.mjs`(시즌 회고 v3). 장부는 종결인데 배관은 안 섰고, 그 상태가 **✅ 와 똑같은 모양**이었다.
 *   철학 게이트 ④의 「닿았나」가 ✗ 인데 아무도 안 셌다(F302 재발 경로).
 *
 *   🔑 급소는 **도구가 없던 게 아니다.** `SYNK-talk/tools/배포대조.js` 는 그때도 있었고 종료코드를
 *      0/1/2 로 이미 갈라 두었다 — 그런데 **아무도 안 돌렸다.** 장치는 스스로 발화하지 않으면
 *      안 돈다(CLAUDE.md 신뢰성: 「장치와 그 발동 조건은 같은 커밋에서 정한다」).
 *      그래서 이 커밋이 더한 것은 도구가 아니라 **발동**(`/close` 3-b)이고, 이 파일이 그 발동을 못박는다.
 *
 * 탐지 층 두 벌 (CLAUDE.md: repo 밖 환경에 기대는 검사는 CI 에서 깨진다):
 *   · 이 저장소 안 = 스킬 원문. **항상 돈다.**
 *   · 형제 저장소(SYNK-talk) = 있으면 재고 **없으면 skip 으로 드러낸다.** fail 로 하면 CI 가
 *     빨개지고, 조용히 통과시키면 미실행이 초록과 같은 모양이 된다.
 */

const test = require('node:test');
const assert = require('node:assert');
const path = require('node:path');
const fs = require('node:fs');

const ROOT = path.resolve(__dirname, '..');
const 스킬 = (name) =>
  fs.readFileSync(path.join(ROOT, '.claude', 'skills', name, 'SKILL.md'), 'utf8');

/** `/close` 가 가리키는 형제 저장소의 도구. 없을 수 있다(클론 하나만 받은 기계·CI).
 *  자리는 정본 통로에서 — 손으로 `ROOT/..` 를 적으면 워크트리에서 늘 skip 이다(`..` = `worktrees/`). */
const 배포대조경로 = path.join(
  require(path.join(ROOT, '.claude', 'hooks', 'lib', '형제저장소.js')).형제경로(ROOT),
  'tools', '배포대조.js',
);

test('🔑 /close 에 배포 대조 «발동»이 있다 — 단계가 사라지면 도구는 있는데 아무도 안 돌리는 옛 상태로 돌아간다', () => {
  const close = 스킬('close');

  assert.match(close, /###\s*3-b\./,
    '3-b 단계가 통째로 없다 — 종결 선언과 배포 상태를 잇는 자리가 사라졌다');
  assert.match(close, /배포대조\.js/,
    '단계는 있는데 부를 명령이 없다 — 제목만 남은 단계는 안 돈다');

  /* 🔴 순서가 곧 의미다: 배포 대조는 **보드에 종결을 적는 4단계보다 앞**이어야 한다.
   *    뒤에 두면 「✅종결」을 이미 적은 뒤에 갈림을 알게 되고, 그때는 고칠 동기가 사라진다. */
  const 대조자리 = close.indexOf('배포대조.js');
  const 보드자리 = close.indexOf('### 4. 보드 줄');
  assert.ok(대조자리 > 0 && 보드자리 > 0, '두 단계 중 하나를 못 찾았다 — 절 제목이 바뀌었다');
  assert.ok(대조자리 < 보드자리,
    '배포 대조가 보드 갱신 «뒤»로 갔다 — 종결을 적은 다음에 재면 이 장치의 목적이 사라진다');
});

test('☠️ 종료코드 셋을 스킬이 «전부» 적었다 — 「못 쟀다」가 빠지면 미실행이 초록으로 샌다', () => {
  const close = 스킬('close');

  /* 0·1·2 가 각각 무슨 뜻인지 스킬이 말해야 한다. 「0 이면 통과」만 적힌 스킬은
   * 미측정(2)을 통과로 읽는다 — 그게 이 저장소가 반복해 당한 실패 모양이다. */
  for (const [코드, 뜻] of [['0', '같다'], ['1', '다르다'], ['2', '미측정']]) {
    assert.ok(close.includes(코드) && close.includes(뜻),
      `종료코드 ${코드}(${뜻}) 의 뜻이 스킬에 없다 — 읽는 쪽이 셋을 못 가른다`);
  }

  assert.match(close, /못 쟀|못쟀/,
    '「못 쟀으면 못 쟀다고 적는다」가 없다 — 초록을 분모와 함께 읽으라는 조항이 이 자리에서 끊긴다');
});

test('🔑 다르면 «종결이 아니다»라고 못박는다 — 갈림을 알고도 ✅ 로 닫으면 장치가 무의미하다', () => {
  const close = 스킬('close');
  const 구역 = close.slice(close.indexOf('### 3-b.'), close.indexOf('### 4. 보드 줄'));

  assert.ok(구역.length > 200, '3-b 구역이 비었다 — 제목만 남았다');
  assert.match(구역, /종결\s*」?\s*이?\s*아니|아니다/,
    '「다르면 종결이 아니다」는 판정이 없다 — 재기만 하고 판정을 안 하면 그 숫자는 아무것도 안 막는다');
  assert.match(구역, /⛔배포 0|배포 0/,
    '재배포를 못 했을 때 보드에 무엇을 적을지가 없다 — 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103)');
});

test('☠️ 스킬이 시키는 명령이 «실재한다» — 형제 저장소가 없으면 fail 이 아니라 skip 으로 드러낸다', (t) => {
  if (!fs.existsSync(배포대조경로)) {
    t.skip(`SYNK-talk 이 이 기계에 없다 — 실저장소 층 미측정(${배포대조경로})`);
    return;
  }

  const 소스 = fs.readFileSync(배포대조경로, 'utf8');

  /* 🔴 스킬이 「0/1/2 로 갈린다」고 약속했으니 도구가 실제로 그렇게 가르는지 본다.
   *    갈라지는 날 스킬이 거짓말을 하고, 그 거짓말은 «초록» 쪽으로 샌다. */
  assert.match(소스, /exitCode\s*=\s*1/,
    '배포대조가 「다르다」에 종료코드 1 을 안 준다 — /close 3-b 의 설명이 거짓이 된다');
  assert.match(소스, /exitCode\s*=\s*2/,
    '배포대조가 「미측정」에 종료코드 2 를 안 준다 — 못 잰 것이 통과와 같은 값이 된다');
});

test('☠️ /close 가 적은 상대 경로로 실제로 그 도구에 닿는다 — 경로가 틀리면 그 자리에서 죽는다', (t) => {
  const close = 스킬('close');
  const m = close.match(/cd\s+(\.\.[^\s&|]*)\s*&&\s*node\s+(tools\/[^\s`]+)/);
  assert.ok(m, '3-b 의 실행 줄에서 「cd <경로> && node <도구>」를 못 뽑았다 — 형식이 바뀌었다');

  /* 상대 경로는 **사람이 서 있는 자리**에서 푼다 — 그건 주저장소지 워크트리가 아니다.
   * `ROOT` 로 풀면 워크트리에서 `..` 이 `worktrees/` 를 가리켜 이 검사가 늘 skip 된다
   * (코드 트랙은 규약상 워크트리에서 짓는다 — 즉 정작 스킬을 고치는 판에서 안 돌았다). */
  const 기준 = require(path.join(ROOT, '.claude', 'hooks', 'lib', '형제저장소.js')).주저장소(ROOT);
  const 목표 = path.join(기준, m[1], m[2]);
  if (!fs.existsSync(path.join(기준, m[1]))) {
    t.skip(`형제 저장소가 이 기계에 없다 — 경로 실측 미실행(${m[1]})`);
    return;
  }
  assert.ok(fs.existsSync(목표),
    `스킬이 시키는 경로에 파일이 없다: ${목표} — 처방이 실행층과 끊겼다(F103)`);
});
