'use strict';
/**
 * [09-03] 주간 점수 «두 통로» 일치 — 한 학생을 두 접점이 다르게 말하지 않는가.
 *
 * ■ 왜 이 검사가 따로 필요한가
 *   같은 주의 같은 학생을 **메신저 다이제스트**(만족도팩 `MJ_messengerDigest_`)와
 *   **학부모 주간 메일**(엔진_운영배치 `parentWeeklyDigestCore_`)이 각각 계산한다. 규약이 갈리면
 *   +10 지급·-5 스토어 구매인 주에 한쪽은 +5P, 다른 쪽은 +10P 를 말한다 — 학부모와 학생이
 *   서로 다른 숫자를 듣는다. 09-02 에 실제로 그 상태였고(codex P1 a2cf05b13aaf·88d6f514a6cf)
 *   `2359bbc52` 가 메신저 쪽을 정본 자로 되돌려 닫았다.
 *
 * ■ 이미 있는 검사와 무엇이 다른가 — **문구가 아니라 행동으로 잰다**
 *   safety.test.js:1520 이 같은 자리를 지키지만 «판정식 문자열이 있는가»로 잰다. 그래서
 *   뜻이 같은데 문구만 바뀌어도 빨개지고(실제로 09-03 에 앵커를 한 번 갈아 끼웠다), 반대로
 *   문구가 같은 채 **다른 변수를 더하도록** 바뀌면 못 본다. 여기서는 두 판정식을 소스에서
 *   뽑아 **실제 함수로 만들어** 같은 입력에 같은 답을 내는지 본다.
 *   ⇒ 문구 변화에 강하고, 뜻이 갈리는 순간에만 빨개진다.
 *
 * ■ 대가(틀릴 때의 모습)
 *   판정식을 정규식으로 뽑으므로 «판정을 식 하나로 두지 않는» 모양으로 바뀌면 뽑기가 실패한다.
 *   그때는 조용히 통과하지 않고 **뽑기 실패 자체를 적색으로** 낸다(아래 첫 두 단언).
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const 만족도팩 = fs.readFileSync(path.join(ROOT, '만족도팩.js'), 'utf8');
const 운영배치 = fs.readFileSync(path.join(ROOT, '엔진_운영배치.js'), 'utf8');

/** 소스 구간에서 「획득 판정식」을 뽑아 실제로 부를 수 있는 함수로 만든다. */
function 판정뽑기(소스, 이름) {
  const m = 소스.match(new RegExp('const\\s+' + 이름 + '\\s*=\\s*([^;]+);'));
  assert.ok(m, 이름 + ' 판정식을 못 뽑았다 — 판정을 식 하나로 두지 않는 모양으로 바뀌었다(조용히 통과시키지 않는다)');
  return { 식: m[1].trim(), 부르기: new Function('pts', 'rs', 'return !!(' + m[1] + ');') };
}
/** 그 판정이 «합계에 실제로 걸렸는가» — 식만 있고 안 쓰이면 없는 것과 같다. */
function 합계배선(소스, 이름) {
  return new RegExp('if\\s*\\(\\s*' + 이름 + '\\s*&&\\s*pts\\s*!==\\s*0\\s*\\)\\s*ptsW\\[sid\\]').test(소스);
}

const 메신저구간 = 만족도팩.slice(
  만족도팩.indexOf('function MJ_messengerDigest_('),
  만족도팩.indexOf('function MJ_msgSection_('));
const 메일구간 = 운영배치.slice(
  운영배치.indexOf('function parentWeeklyDigestCore_'),
  운영배치.indexOf('function restoreDrill'));

/* 표본 — 실제로 point_logs 에 앉는 모양들. 「스토어 구매」와 「정정」을 가르는 것이 이 판정의 전부다. */
const 표본 = [
  { pts: 10, rs: '오늘의 도전', 뜻: '평범한 지급' },
  { pts: 3, rs: '칭찬·집중력', 뜻: '칭찬' },
  { pts: -5, rs: '스토어 구매(간식)', 뜻: '정상 구매 차감 — 획득이 아니다' },
  { pts: -5, rs: '스토어·교환', 뜻: '정상 구매 차감(다른 표기)' },
  { pts: -10, rs: '정정·일일한도(오늘의 도전)', 뜻: '정정 — 획득에서 되돌린다' },
  { pts: -3, rs: '정정·중복(하루 1명)', 뜻: '정정(다른 사유)' },
  { pts: 0, rs: '메모만', 뜻: '0점 행' },
  { pts: -1, rs: '', 뜻: '사유 없는 음수' },
];

test('🔑 두 통로의 «획득» 판정이 같은 입력에 같은 답을 낸다 — 문구가 아니라 행동으로 잰다', () => {
  const 메신저 = 판정뽑기(메신저구간, '획득');
  const 메일 = 판정뽑기(메일구간, 'isE');
  const 어긋남 = [];
  표본.forEach((s) => {
    const a = 메신저.부르기(s.pts, s.rs);
    const b = 메일.부르기(s.pts, s.rs);
    if (a !== b) 어긋남.push(`${s.뜻}(pts=${s.pts} · "${s.rs}") → 메신저 ${a} · 학부모메일 ${b}`);
  });
  assert.deepEqual(어긋남, [],
    '두 접점이 한 학생을 다르게 말한다:\n  ' + 어긋남.join('\n  ') +
    `\n  (메신저 식: ${메신저.식} · 학부모메일 식: ${메일.식})`);
});

test('🔴 그 판정이 «합계에 걸려» 있다 — 식만 있고 안 쓰이면 없는 것과 같다', () => {
  assert.ok(합계배선(메신저구간, '획득'), '메신저 쪽 획득 판정이 ptsW 합계에 안 걸렸다');
  assert.ok(합계배선(메일구간, 'isE'), '학부모 메일 쪽 isE 판정이 ptsW 합계에 안 걸렸다');
});

test('🔴 스토어 구매는 «획득이 아니다» — 09-02 에 두 통로를 갈랐던 바로 그 행', () => {
  const 메신저 = 판정뽑기(메신저구간, '획득');
  const 메일 = 판정뽑기(메일구간, 'isE');
  ['스토어 구매(간식)', '스토어·교환', '상점 사용'].forEach((rs) => {
    assert.equal(메신저.부르기(-5, rs), false, `메신저가 「${rs}」 차감을 획득으로 센다`);
    assert.equal(메일.부르기(-5, rs), false, `학부모 메일이 「${rs}」 차감을 획득으로 센다`);
  });
});

test('🔴 정정 음수는 «되돌림»이라 합계에 들어간다 — 빼면 부풀린 수가 나간다(codex P2 4d0fe949)', () => {
  const 메신저 = 판정뽑기(메신저구간, '획득');
  const 메일 = 판정뽑기(메일구간, 'isE');
  ['정정·일일한도(오늘의 도전)', '정정·중복(하루 1명)'].forEach((rs) => {
    assert.equal(메신저.부르기(-10, rs), true, `메신저가 「${rs}」 을 안 되돌린다`);
    assert.equal(메일.부르기(-10, rs), true, `학부모 메일이 「${rs}」 을 안 되돌린다`);
  });
});

test('한 주를 통째로 더해도 두 통로가 같은 수를 낸다 — 판정 하나가 아니라 «합계»로 잰다', () => {
  const 메신저 = 판정뽑기(메신저구간, '획득');
  const 메일 = 판정뽑기(메일구간, 'isE');
  /* 09-02 에 갈렸던 그 주: +10 지급 · -5 스토어 · -3 정정.
   *   참값 = 10 + (-3) = 7. 스토어는 획득이 아니므로 빠진다. */
  const 한주 = [{ pts: 10, rs: '오늘의 도전' }, { pts: -5, rs: '스토어 구매(간식)' }, { pts: -3, rs: '정정·중복(하루 1명)' }];
  const 더하기 = (판정) => 한주.reduce((a, r) => a + (판정.부르기(r.pts, r.rs) && r.pts !== 0 ? r.pts : 0), 0);
  const m = 더하기(메신저), p = 더하기(메일);
  assert.equal(m, p, `같은 주를 메신저는 ${m}P, 학부모 메일은 ${p}P 로 말한다`);
  assert.equal(m, 7, `참값 7P 와 다르다(${m}P) — 스토어 차감이 섞였거나 정정이 빠졌다`);
});
