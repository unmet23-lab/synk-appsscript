'use strict';
/* 급수커버리지 회귀 — 「TOPIK 4급 보장의 재료가 있나」를 세는 자가 **자기 결함을 다시 내지 않게**.
 *
 * 🔴 이 시험이 지키는 것은 「숫자가 얼마인가」가 아니다 — 그 수는 뱅크·요목이 자라면 바뀐다.
 *   지키는 것은 **판정의 «방향»** 셋이다:
 *     ① 있는 것을 없다고 세지 않는다(거짓 빨강) — 첫 실행이 셋을 그렇게 셌다.
 *     ② 없는 것을 있다고 세지 않는다(거짓 초록) — ❔ 는 ✅ 가 아니다.
 *     ③ 못 읽은 것을 「빠짐 0건」으로 접지 않는다(확인 불가는 종료 2).
 */
const test = require('node:test');
const assert = require('node:assert');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const 자 = require(path.join(ROOT, 'tools', '급수커버리지.js'));
const { 뱅크읽기 } = require(path.join(ROOT, 'tools', 'lib', '문법뱅크.js'));

const 급찾기 = (결과, 급) => 결과.급별.find((r) => r.급 === 급);

test('① 대조군 — 뱅크·요목이 둘 다 읽힌다(하나라도 안 읽히면 이 시험이 먼저 운다)', () => {
  const 결과 = 자.재기();
  assert.ok(결과.뱅크총수 >= 60, `뱅크가 ${결과.뱅크총수}종뿐이다 — 파서가 깨졌을 가능성이 크다`);
  assert.strictEqual(결과.급별.length, 5, '우리 과정 상한은 5급이다(6급 반은 열지 않는다)');
  for (const r of 결과.급별) {
    assert.ok(r.요목문형수 + r.대조불가.length > 0,
      `Lv${r.급} 요목에서 아무것도 못 읽었다 — 「빠짐 0」이 아니라 파서가 깨진 것이다`);
  }
});

/* ── ① 거짓 빨강 — 08-31 첫 실행이 실제로 낸 결함이다.
 *   요목과 뱅크가 «같은 문형»을 다르게 적어서 「없다」로 셌다. 세 짝을 못박는다. */
test('② 🔴 표기가 다른 같은 문형을 «없다» 로 세지 않는다 (첫 실행이 낸 결함)', () => {
  const 결과 = 자.재기();
  const 짝들 = [
    { 급: 5, 요목: '-을수록', 뱅크id: 'G704' },        // 뱅크 `-(으)ㄹ수록`
    { 급: 2, 요목: '-ㄴ 적이 있다', 뱅크id: 'G509' },   // 뱅크 `-(으)ㄴ 적이 있다`
    { 급: 2, 요목: '-ㄹ 수 있다/없다', 뱅크id: 'G402' }, // 뱅크 `-(으)ㄹ 수 있다/없다`
  ];
  for (const { 급, 요목, 뱅크id } of 짝들) {
    const r = 급찾기(결과, 급);
    assert.ok(!r.빠진것.some((x) => x.문형 === 요목),
      `Lv${급} 「${요목}」 을 «없다» 로 셌다 — 뱅크 ${뱅크id} 에 표기만 다르게 실재한다(거짓 빨강)`);
    const 붙음 = r.맞은것.some((x) => x.문형 === 요목) || r.비슷한것.some((x) => x.문형 === 요목);
    assert.ok(붙음, `Lv${급} 「${요목}」 이 어느 칸에도 안 잡혔다 — 요목 파서가 그 줄을 놓쳤다`);
  }
});

/* ── ② 거짓 초록 — 반대 방향. 느슨하게 풀면 뜻이 다른 문형이 서로 붙는다. */
/* 🔁 08-31 — 이 시험은 하루에 **두 번** 앵커를 잃었다. 「없는 것」에 걸어 뒀는데 그날 유호님
 *   판정으로 `-는 반면에` 가 채워졌고(G713), 이어 `-는 셈이다` 도 채워졌다(G716). 실물의 빈칸은
 *   «채우는 것이 목표»라 앵커로 못 쓴다 — 채워지는 순간 시험은 초록인 채 아무것도 안 물게 된다.
 *   ⇒ 매처를 **주입 데이터**로 직접 문다. 뱅크·요목이 어떻게 자라도 이 축은 안 흔들린다. */
/* 자는 급수들 전량을 돈다 — 한 급만 담은 Map 을 주면 나머지 급에서 죽는다(빈 칸으로 채운다). */
const 요목주입 = (급, 문형들) =>
  new Map(자.급수들.map((g) => [g, {
    문형들: g === 급 ? 문형들.map((문형) => ({ 문형, 분류: '시험' })) : [],
    대조불가: [],
  }]));
const 뱅크주입 = (쌍들) =>
  쌍들.map(([id, 이름], i) => ({ id, 이름, 도입급: 4, 재출현급: null, 근거: '요' , 순번: i }));

test('③ 🔴 뜻이 다른 문형을 «있다» 로 붙이지 않는다 — 매처를 직접 문다(실물 빈칸에 안 건다)', () => {
  /* 뱅크가 `-는 대신에`(대체) 만 쥐었는데 `-는 반면에`(대조) 가 통과하면,
   * 우리는 없는 재료를 있다고 믿는다. 이 둘은 실제로 뱅크에 나란히 있지만(G708·G713),
   * 그 사실과 무관하게 **매처가 둘을 붙이면 안 된다**는 것이 이 축이다. */
  const r = 자.재기({ 뱅크: 뱅크주입([['G708', '-는 대신에']]), 요목: 요목주입(4, ['-는 반면에']) })
    .급별.find((x) => x.급 === 4);
  assert.deepStrictEqual(r.맞은것, [], '대체(-는 대신에)가 대조(-는 반면에)로 통과했다(거짓 초록)');
  assert.deepStrictEqual(r.비슷한것, [], '❔ 로도 붙으면 안 된다 — 표기차가 아니라 다른 문형이다');
  assert.strictEqual(r.빠진것.length, 1, '「-는 반면에」 가 🔴 로 안 남았다');

  /* 반대 방향도 같이 문다 — 축이 «전부 🔴» 로 기울면 시험은 통과하되 자는 죽는다. */
  const s = 자.재기({ 뱅크: 뱅크주입([['G713', '-는 반면에']]), 요목: 요목주입(4, ['-는 반면에']) })
    .급별.find((x) => x.급 === 4);
  assert.strictEqual(s.맞은것.length, 1, '같은 문형인데 ✅ 가 안 났다 — 자가 아무것도 못 붙인다');

  /* 그리고 실물에서도 둘이 «두 행»으로 남아 있어야 한다 — 누가 「중복이니 정리」하면 같은 사고다. */
  const { GRAMMAR_BANK } = 뱅크읽기();
  const 찾기 = (이름) => GRAMMAR_BANK.filter((g) => g[1] === 이름);
  for (const 이름 of ['-는 반면에', '-는 대신에']) {
    assert.strictEqual(찾기(이름).length, 1, `「${이름}」 이 뱅크에 없거나 둘이다`);
  }
  assert.notStrictEqual(찾기('-는 반면에')[0][0], 찾기('-는 대신에')[0][0],
    '대조와 대체가 같은 ID 로 합쳐졌다 — 뜻이 다른 문형이다');
});

/* ── 2·3차 수리(08-31 · Lv3 가려내기)가 붙인 축들. 셋 다 «없다/있다» 사이의 자리를 만든다. */
test('③-b 슬래시 갈림 위치만 다른 같은 문형을 «없다» 로 세지 않는다 (-아서/어서 = -아/어서)', () => {
  const 결과 = 자.재기();
  const lv1 = 급찾기(결과, 1);
  assert.ok(!lv1.빠진것.some((x) => x.문형 === '-아서/어서'),
    '「-아서/어서」 를 «없다» 로 셌다 — 뱅크 G308 `-아/어서` 와 갈림 위치만 다르다(거짓 빨강)');
});

test('③-c 나열은 «부분 보유» 로 센다 — 넷 중 하나를 「있다」로도 「없다」로도 세지 않는다', () => {
  const 결과 = 자.재기();
  const lv3 = 급찾기(결과, 3);
  const 간접 = lv3.비슷한것.find((x) => x.문형.startsWith('-다고/'));
  assert.ok(간접, '「-다고/-냐고/-라고/-자고 하다」 가 ❔ 칸에 없다 — 전개가 안 돌았다');
  assert.match(간접.축, /부분보유 1\/4/, `축이 「${간접.축}」 이다 — 넷 중 하나만 쥔 사실이 안 드러난다`);
  assert.ok(간접.빠진갈래.length === 3, '빠진 갈래 셋(-냐고/-라고/-자고 하다)이 안 적혔다');
  assert.ok(!lv3.맞은것.some((x) => x.문형.startsWith('-다고/')), '부분 보유가 ✅ 로 샜다');
});

test('③-d 🔴 접미사 피동·사동이 통사적 피동·사동에 «붙지 않는다» — 거짓 초록의 급소', () => {
  const 결과 = 자.재기();
  const lv3 = 급찾기(결과, 3);
  /* `-이/히/리/기-`(먹히다·잡히다)와 `-아/어지다`(만들어지다)는 **다른 문법**이다.
   * 뱅크가 뒤엣것만 쥐었는데 앞엣것까지 통과하면, 없는 재료를 있다고 믿게 된다. */
  for (const 접미사 of ['-이/히/리/기-', '-이/히/리/기/우-']) {
    assert.ok(lv3.빠진것.some((x) => x.문형 === 접미사),
      `「${접미사}」 가 «없다» 칸을 벗어났다 — 통사적 피동/사동(G605·G606)은 이것의 대체가 아니다`);
  }
  /* 반대로 통사적 쪽은 실제로 쥐고 있으니 ✅ 여야 한다(둘을 같이 떨어뜨리는 것도 오답이다). */
  for (const 통사 of ['-아/어지다', '-게 하다']) {
    assert.ok(lv3.맞은것.some((x) => x.문형 === 통사), `「${통사}」 는 뱅크에 있는데 ✅ 가 아니다`);
  }
});

test('③-e 산문 속 콜론을 구분자로 읽지 않는다 — 멀쩡한 문형이 분모 밖으로 새면 커버리지가 좋아 보인다', () => {
  const 결과 = 자.재기();
  const lv3 = 급찾기(결과, 3);
  const 전부 = [...lv3.맞은것, ...lv3.비슷한것, ...lv3.빠진것].map((x) => x.문형);
  assert.ok(전부.some((f) => f.includes('마련이다')),
    '「-기/-게 마련이다」 가 분모에 없다 — 그 줄의 `:` 는 산문 콜론인데 구분자로 읽혔다');
  assert.ok(전부.some((f) => f.includes('바람에')), '「-는 바람에」 가 분모 밖이다 — 콜론 없는 줄을 못 읽었다');
});

test('④ ❔ 는 ✅ 가 아니다 — 표기차·대조불가를 통과 칸에 섞지 않는다', () => {
  const 결과 = 자.재기();
  for (const r of 결과.급별) {
    const 겹침 = r.맞은것.filter((a) => r.비슷한것.some((b) => b.문형 === a.문형));
    assert.strictEqual(겹침.length, 0, `Lv${r.급} 에서 같은 문형이 ✅ 와 ❔ 양쪽에 들었다`);
    /* 대조불가(요목에 이름이 없는 [확장]·[심화] 항목)는 분모 밖이다 — 문형 수에 안 섞인다. */
    assert.strictEqual(r.요목문형수, r.맞은것.length + r.비슷한것.length + r.빠진것.length,
      `Lv${r.급} 분모가 안 맞는다 — 어느 칸에도 안 든 문형이 있으면 조용히 사라진다`);
  }
});

test('⑤ 🔴 보장선(4급) 은 «셀 수 있는 상태» 여야 한다 — 못 세면 보장의 근거가 없다', () => {
  const 결과 = 자.재기();
  const lv4 = 급찾기(결과, 4);
  assert.ok(lv4.요목문형수 > 0,
    'Lv4 요목에서 문형을 하나도 못 읽었다 — 「빠짐 0」이 아니라 **보장의 재료를 못 재는 상태**다');
  assert.ok(lv4.보유.도입 + lv4.보유.재출현 > 0, 'Lv4 뱅크 보유가 0 — 파서가 급수 칸을 놓쳤다');
});

test('⑥ 종료코드 — 빠짐이 있으면 1, 모르는 플래그는 2 (미실행이 통과와 같은 얼굴이면 안 된다)', () => {
  const 돌리기 = (인자들) => {
    try {
      execFileSync(process.execPath, [path.join(ROOT, 'tools', '급수커버리지.js'), ...인자들],
        { encoding: 'utf8', stdio: 'pipe' });
      return 0;
    } catch (e) { return e.status; }
  };
  const 결과 = 자.재기();
  const 빠짐있나 = 결과.급별.some((r) => r.빠진것.length > 0);
  assert.strictEqual(돌리기([]), 빠짐있나 ? 1 : 0, '빠짐 유무와 종료코드가 어긋난다');
  assert.strictEqual(돌리기(['--없는플래그']), 2, '모르는 플래그를 조용히 무시하면 딴 과녁을 재고 초록이 된다');
  assert.strictEqual(돌리기(['--급', '6']), 2, '6급은 우리 과정 밖이다 — 받으면 안 된다');
});
