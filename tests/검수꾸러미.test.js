/* 검수 꾸러미·회수 회귀 — 몽골어 검수자가 받는 것과 우리가 되받는 것을 기계로 못박는다.
 *
 * 설계 정본 = `docs/몽골어_검수_꾸러미_설계.md`(유호님 지시 2026-08-12 「검수자가 진짜 쉽게」).
 *
 * 여기서 못박는 것 다섯 — 전부 **초판이 실제로 샜던 자리**다:
 *   ① `\|` 이스케이프 — 검수 대상 문장 «안에» `|` 가 있다(`TAG_MN[t] \|\| t`). 소박한 split 은
 *      그 행에서 열이 밀리고, **밀린 결과는 오류가 아니라 「이상한 문장」**이라 검수자에게 그대로 나간다.
 *   ② 표 선별 — 검수표는 작업지이면서 판정 근거 문서라 표가 섞여 있다. 초판은 열 수로만 골라
 *      **L 을 35 가 아닌 44 로** 냈다(§1 조립 판정표·§2 개수표가 딸려 왔다).
 *   ③ **조각 수 대조** — 낸 수와 정본 선언이 갈리면 빨개진다. 조용한 0건·조용한 과잉이 이 도구의
 *      가장 나쁜 결말이라 실저장소에 대고 검사한다.
 *   ④ 회수 — **자리표시자를 잃으면 🔴**. 이걸 놓치면 모든 학부모에게 같은 이름·숫자가 나간다.
 *   ⑤ 회수 — **확정 열을 머리에서 못 찾으면 세운다**. 자리를 짐작해 읽으면 엉뚱한 열을 회수한다.
 *
 * ⚠ 탐지력은 **픽스처가 진다**(실물 검수 결과가 아직 0건이다 · CLAUDE.md 가드 맹점 ②).
 *   실저장소에는 「거짓양성이 없는가」만 묻는다.
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const path = require('path');

const REPO = path.join(__dirname, '..');
const 꾸러미 = require(path.join(REPO, 'tools', '검수꾸러미.js'));
const 회수 = require(path.join(REPO, 'tools', '검수회수.js'));

/* ── ① 이스케이프된 파이프 ───────────────────────────────────────────── */

test('셀가르기 — `\\|` 는 열을 가르지 않는다(문장 안의 파이프를 지킨다)', () => {
  const 줄 = '| `TAG_MN` 매핑 | `2102` | **`:2141`** (누출 = `TAG_MN[t] \\|\\| t`) |';
  const 셀 = 꾸러미.셀가르기(줄);
  assert.strictEqual(셀.length, 3, '이스케이프를 못 지키면 열이 늘어난다');
  assert.ok(셀[2].includes('|'), '되돌리지 않으면 원문이 깨진 채 검수자에게 나간다');
});

test('셀가르기 — 진짜 구분자는 그대로 가른다', () => {
  assert.deepStrictEqual(꾸러미.셀가르기('| a | b | c |'), ['a', 'b', 'c']);
});

/* ── ② 표 선별 = 「누가 쓰는 열인가」 ───────────────────────────────── */

test('벗기기 — 백틱·굵게는 md 문법이라 시트에서 걷어낸다', () => {
  assert.strictEqual(꾸러미.벗기기('**`{이름} 학생`**'), '{이름} 학생');
});

test('자리표시자 — 중괄호만 잡고 중복은 접는다', () => {
  assert.strictEqual(꾸러미.자리표시자('{이름} 학생 {N}회 {이름}'), '{이름} {N}');
  assert.strictEqual(꾸러미.자리표시자('자리표시자 없는 문장'), '');
});

/* ── ③ 실저장소 — 낸 조각 수가 정본 선언과 같은가 ──────────────────── */

test('실저장소 — 묶음마다 낸 조각 수 = 선언값 (갈라지면 조용히 샌다)', () => {
  for (const 묶음 of 꾸러미.묶음들) {
    const { 조각, 경고 } = 꾸러미.조각들(묶음);
    assert.deepStrictEqual(경고, [], `${묶음.코드}: 못 담은 행이 있다 — ${경고.join(' / ')}`);
    assert.strictEqual(조각.length, 묶음.선언,
      `${묶음.코드}(${묶음.파일}): ${조각.length}조각을 냈는데 선언은 ${묶음.선언}이다. ` +
      '검수표를 고쳤다면 tools/검수꾸러미.js 의 `선언` 을 같이 고친다.');
  }
});

test('실저장소 — 조각의 한국어 원문이 비어 있지 않다(빈 행을 조각으로 세지 않는다)', () => {
  for (const 묶음 of 꾸러미.묶음들) {
    const { 조각 } = 꾸러미.조각들(묶음);
    assert.ok(조각.length > 0, `${묶음.코드}: 조각 0 — 표식 축이 죽었는지 본다`);
    for (const c of 조각) assert.ok(c.한국어.trim().length > 0, `${묶음.코드}: 빈 원문이 조각으로 들어갔다`);
  }
});

test('실저장소 — 섹션 열은 «언어 중립 코드»다(검수자가 못 읽는 한국어가 매 행에 실리면 안 된다)', () => {
  for (const 묶음 of 꾸러미.묶음들) {
    const { 조각 } = 꾸러미.조각들(묶음);
    for (const c of 조각) {
      assert.ok(!/[가-힣]/.test(c.섹션),
        `${묶음.코드}: 섹션 「${c.섹션}」 에 한글이 있다 — 설계 벽 ①(읽을 수 없다)이 산출물에 남는다`);
    }
  }
});

/* ── ④⑤ 회수 — 픽스처가 탐지력을 진다 ─────────────────────────────── */

const 머리 = ['№', 'Хэсэг', 'Солонгос эх', 'AI ноорог', 'Монгол — баталгаажсан', 'Итгэлтэй эсэх', 'Хэвээр үлдээх', 'Тайлбар'];
const 행 = (n, ko, 초안, 확정, 확신도 = '') => [String(n), '§1', ko, 초안, 확정, 확신도, '', ''];

test('회수 — 자리표시자를 잃으면 🔴 (전원에게 같은 이름이 나가는 실수)', () => {
  const r = 회수.검사(머리, [행(1, '{이름} 학생의 한 주 소식입니다.', '{이름} сурагчийн мэдээ.', 'Батболд сурагчийн мэдээ.')]);
  const 심각 = r.문제.filter((p) => p.급 === '🔴');
  assert.strictEqual(심각.length, 1, '실제 이름을 적어 넣은 행을 못 잡았다');
  assert.ok(심각[0].말.includes('{이름}'));
});

test('회수 — 자리표시자를 지키면 통과한다(거짓양성 없음)', () => {
  const r = 회수.검사(머리, [행(1, '{이름} 학생의 한 주 소식입니다.', '{이름} сурагчийн мэдээ.', '{이름} сурагчийн 7 хоногийн мэдээ.')]);
  assert.deepStrictEqual(r.문제.filter((p) => p.급 === '🔴'), []);
  assert.strictEqual(r.채움, 1);
});

test('회수 — 빈 확정 칸은 「통과」가 아니라 «미작업»으로 센다(분모와 함께 읽는다)', () => {
  const r = 회수.검사(머리, [
    행(1, '이번 주 소식', 'Мэдээ', 'Мэдээ'),
    행(2, '왕관을 받았어요', 'Титэм', ''),
    행(3, '집에서 칭찬해 주세요', 'Магтаарай', '   '),
  ]);
  assert.strictEqual(r.총, 3);
  assert.strictEqual(r.채움, 1);
  assert.deepStrictEqual(r.빈, [2, 3], '빈 칸을 조용히 건너뛰면 0건 회수와 전건 회수가 같은 모양이 된다');
});

test('회수 — 확정 열을 머리에서 못 찾으면 세운다(자리를 짐작해 읽지 않는다)', () => {
  const r = 회수.검사(['№', '한국어', '몽골어'], [['1', 'a', 'b']]);
  assert.strictEqual(r.채움, 0);
  assert.strictEqual(r.문제.length, 1);
  assert.strictEqual(r.문제[0].급, '🔴');
});

test('회수 — 원문 숫자가 안 보이면 🟡 로만 알린다(몽골어 표기 차이는 막지 않는다)', () => {
  const r = 회수.검사(머리, [행(1, '3일만 더 달라고 부탁해 보세요', '—', 'Гурав хоног нэмж гуйна уу')]);
  const 급들 = r.문제.map((p) => p.급);
  assert.ok(급들.includes('🟡'), '숫자 소실을 아예 안 보면 「없는 숫자」의 뒷면을 놓친다');
  assert.ok(!급들.includes('🔴'), '표기 차이로 회수를 막으면 따를 수 없는 처방이 된다(F103)');
});

test('회수 — 자리표시자 안의 숫자는 「원문 숫자」로 세지 않는다', () => {
  const r = 회수.검사(머리, [행(1, '등원 {N}회', 'ирц {N} удаа', 'ирц {N} удаа')]);
  assert.deepStrictEqual(r.문제, [], '{N} 을 숫자로 세면 매 행이 노랗게 된다 = 늘 참인 경고');
});

test('회수 — 초안을 그대로 옮긴 것을 집계한다(막지는 않는다 — 검수표가 그러라고 했다)', () => {
  const r = 회수.검사(머리, [
    행(1, 'a', 'Ноорог', 'Ноорог'),
    행(2, 'b', 'Ноорог2', 'Өөрчилсөн'),
  ]);
  assert.strictEqual(r.항목.filter((x) => x.초안그대로).length, 1);
  assert.deepStrictEqual(r.문제, []);
});

test('회수 — 초안이 없는 묶음(—)은 「초안 그대로」로 세지 않는다', () => {
  const r = 회수.검사(머리, [행(1, 'a', '—', '—')]);
  assert.strictEqual(r.항목[0].초안그대로, false, 'L 묶음은 초안이 없어 전 행이 「그대로」로 잡히면 집계가 무의미해진다');
});
