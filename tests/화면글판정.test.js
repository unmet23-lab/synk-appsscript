// ── 규칙 하나하나 — 시간표를 손으로 짓는다(30fps, 세 장마다) ──
function 짓기(spans, 길이 = 10) {
  const frames = [];
  for (let f = 0; f <= Math.round(길이 * 30) - 1; f += 3) {
    const t = f / 30;
    frames.push({ f, items: spans.filter((s) => t >= s.from - 1e-9 && t < s.to - 1e-9).map((s) => ({ t: s.t, b: s.b || [100, s.y ?? 300, 900, (s.y ?? 300) + (s.h ?? 80)], o: s.o ?? 1, fs: s.fs || 60, c: s.c || 'rgb(255, 255, 255)' })) });
  }
  return { fps: 30, step: 0.1, 길이, frames };
}

