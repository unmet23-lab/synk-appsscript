function 풀기(name) {
  const d = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures', '화면글', `${name}.json`), 'utf8'));
  const frames = [];
  let k = 0, items = [];
  for (let f = 0; f <= d.끝프레임; f += d.every) {
    while (k < d.바뀜.length && d.바뀜[k][0] <= f) { items = d.바뀜[k][1]; k++; }
    frames.push({ f, items });
  }
  return { fps: d.fps, step: d.every / d.fps, 길이: d.길이, frames };
}

