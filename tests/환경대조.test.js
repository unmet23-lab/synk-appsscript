'use strict';
/**
 * `tools/환경대조.js` 회귀 — 「이 검사의 답을 코드가 정하나, 기계가 정하나」를 재는 도구.
 *
 * ■ 왜 픽스처가 탐지력을 지나 (맹점 ②)
 *   이 도구의 실동작 한 판은 **스위트 전체를 여러 번** 돌리는 것이라 회귀로 못 쓴다(수 분×축 수).
 *   그래서 순수 층(TAP 읽기 · 두 판 대조)만 픽스처로 재고, 실행 층은 등록층으로 본다.
 *
 * ■ 이 도구가 새면 어느 방향인가 — **전부 「뒤집힘 0」쪽**이다. 그래서 그쪽을 이름 대고 막는다:
 *   ㉠ TAP 을 못 읽으면 판이 비고, 빈 판끼리 견주면 「뒤집힘 0」이다(= 통과와 같은 모양 · F207)
 *   ㉡ 같은 이름이 둘인 검사를 하나로 접으면 「한쪽만 뒤집힌 판」이 사라진다
 *   ㉢ 한쪽에만 있는 검사를 조용히 버리면 「파일이 안 돌았다」가 「같다」로 읽힌다
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { 파일소스 } = require('./lib/소스검사');

const ROOT = path.resolve(__dirname, '..');
const SRC = 파일소스(path.join(ROOT, 'tools', '환경대조.js'));
const { 읽기, 대조, 묶음, 축들 } = require('../tools/환경대조.js');

// ── ① TAP 읽기 ───────────────────────────────────────────────────────────────

test('🔑 읽기 — 통과·실패·건너뜀 셋을 가른다(건너뜀을 통과로 접으면 미실행이 초록이 된다)', () => {
  const tap = [
    'TAP version 13',
    '# Subtest: 가',
    'ok 1 - 가',
    'not ok 2 - 나',
    'ok 3 - 다 # SKIP 형제 저장소가 이 기계에 없다',
    '  ---',
    '  duration_ms: 1',
    '  ...',
    '1..3',
  ].join('\n');
  const 판 = 읽기(tap);
  assert.deepEqual(판.get('가'), ['통과']);
  assert.deepEqual(판.get('나'), ['실패']);
  assert.deepEqual(판.get('다'), ['건너뜀'], '# SKIP 을 통과로 읽었다 — 미실행이 통과와 같은 모양이 된다(F207)');
  assert.equal(판.size, 3, `분모가 틀렸다(${판.size}) — 요약줄·YAML 블록을 검사로 셌을 수 있다`);
});

test('🔴 읽기 — 같은 이름이 둘이면 «모아 둔다»(접으면 한쪽만 뒤집힌 판이 사라진다)', () => {
  const 판 = 읽기('ok 1 - 같은이름\nnot ok 2 - 같은이름\n');
  assert.deepEqual(판.get('같은이름').sort(), ['실패', '통과'], '두 벌을 하나로 접었다');
});

test('🔑 읽기 — 번호는 키가 아니다(회차마다 갈린다 · 병렬 실행)', () => {
  const a = 읽기('ok 7 - 어떤검사\n');
  const b = 읽기('ok 4519 - 어떤검사\n');
  assert.deepEqual(대조(a, b).뒤집힘, [], '번호가 달라졌다고 뒤집힘으로 셌다 — 그러면 매 회차가 전부 빨갛다');
});

// ── ② 대조 ───────────────────────────────────────────────────────────────────

test('🔴 대조 — 상태가 갈리면 «뒤집힘»이다(이 도구의 존재 이유)', () => {
  const 기준 = 읽기('ok 1 - 가\nok 2 - 나\n');
  const 변형 = 읽기('not ok 1 - 가\nok 2 - 나\n');
  const r = 대조(기준, 변형);
  assert.deepEqual(r.뒤집힘, [{ 이름: '가', 기준: '통과', 변형: '실패' }]);
  assert.equal(r.기준분모, 2);
  assert.equal(r.변형분모, 2);
});

test('🔴 대조 — 통과↔건너뜀도 뒤집힘이다(F617 의 지도대장이 정확히 그 모양이었다)', () => {
  const r = 대조(읽기('ok 1 - 가 # SKIP 없다\n'), 읽기('ok 1 - 가\n'));
  assert.deepEqual(r.뒤집힘, [{ 이름: '가', 기준: '건너뜀', 변형: '통과' }],
    '건너뜀과 통과를 같다고 봤다 — 「이 기계에선 아예 안 돈다」가 안 보이게 된다');
});

test('🔴 대조 — 한쪽에만 있는 검사는 «같다»로 안 접는다(파일이 안 돌았을 수 있다)', () => {
  const r = 대조(읽기('ok 1 - 가\nok 2 - 나\n'), 읽기('ok 1 - 가\n'));
  assert.deepEqual(r.뒤집힘, [], '없는 것을 뒤집힘으로 셌다');
  assert.deepEqual(r.한쪽에만, [{ 이름: '나', 어디: '기준에만' }],
    '한쪽에만 있는 검사를 조용히 버렸다 — 「스위트가 안 돌았다」가 「답이 같다」로 읽힌다(F207)');
});

test('🔑 대조 — 같은 판끼리는 조용하다 (거짓양성 0)', () => {
  const 판 = 읽기('ok 1 - 가\nnot ok 2 - 나\nok 3 - 다 # SKIP 사유\n');
  const r = 대조(판, 읽기('ok 9 - 가\nnot ok 8 - 나\nok 7 - 다 # SKIP 다른 사유\n'));
  assert.deepEqual([r.뒤집힘, r.한쪽에만], [[], []],
    '같은 판인데 뒤집혔다 — 번호나 SKIP 사유 문구를 판정에 섞었다');
});

test('🔑 묶음 — 순서는 판정이 아니다(파일이 병렬이라 회차마다 갈린다)', () => {
  assert.equal(묶음(['실패', '통과']), 묶음(['통과', '실패']));
});

// ── ③ 등록층 — 순수 층이 맞아도 안 불리거나 잘못 불리면 장식이다 ─────────────

test('🔴 등록층 — 빈 판을 «판정»으로 접지 않는다(스폰 실패가 「뒤집힘 0」이 된다)', () => {
  assert.match(SRC, /if \(!판\.size\)/, '판이 비었을 때 멈추지 않는다 — 빈 판끼리 견주면 언제나 「뒤집힘 0」이다(F207)');
  assert.match(SRC, /!남판\.size/, '남이 준 판이 비어도 그대로 대조한다 — 같은 거짓 초록이다');
});

test('🔴 등록층 — 스위트 판정은 종료코드가 아니라 **본문**으로 한다', () => {
  /* 과녁은 `돌리기()` **몸통 하나**다 — 파일 전체로 넓히면 클론 실패 판정(`git clone` 의 종료코드,
   * 이건 정당하다)까지 물어 「따를 수 없는 처방」이 된다(F103 · 이 단언이 실제로 그렇게 처음 빨개졌다). */
  const s = SRC.indexOf('function 돌리기(');
  assert.notEqual(s, -1, '`돌리기` 를 못 찾았다 — 이 회귀가 낡았다');
  const 몸 = SRC.slice(s, SRC.indexOf('\nfunction ', s + 1));
  assert.ok(!/r\.status/.test(몸),
    '스위트의 종료코드를 판정에 썼다 — 적색이 «정상»인 축(뒤집힘을 재는 중)에서 판이 통째로 버려진다');
  assert.match(몸, /읽기\(r\.stdout/, '본문을 안 읽는다 — 무엇으로 판정하는지가 사라졌다');
});

test('🔴 등록층 — 기준 환경은 `ci모사환경` 한 벌에서 온다(조리법을 두 곳에 안 적는다 · F389)', () => {
  assert.match(SRC, /require\('\.\/lib\/ci모사환경\.js'\)/, '기준 환경을 여기서 따로 조립한다 — 갈라지면 test-ci 와 다른 것을 잰다');
});

test('🔴 등록층 — refs 축은 «내용이 같은지» 확인한 뒤에만 잰다(조건은 하나씩 바꾼다)', () => {
  assert.match(SRC, /status', '--porcelain'/, '더러운 작업본에서 클론한다 — ref 집합과 내용이 같이 바뀐다');
  assert.match(SRC, /여기 !== 저기/, '클론 HEAD 가 같은지 안 본다 — 「ref 만 바꿨다」가 실측이 아니라 선언이 된다');
});

test('🔑 등록층 — 못 재는 축을 이름 대고 남긴다(F348 · 안 잰 것을 안 잰 채 두지 않는다)', () => {
  assert.match(SRC, /플랫폼/, '못 재는 축을 안 밝힌다 — 「전수」가 아닌 것이 「전수」로 읽힌다');
  assert.match(SRC, /--기준만/, '다른 기계가 판을 넘길 통로가 없다 — 그 축은 영영 미측정으로 남는다');
});

test('🔑 축 목록이 비지 않는다 — 0축을 돌고 「뒤집힘 0」을 내면 통과와 같은 모양이다', () => {
  assert.ok(축들.length >= 3, `축이 ${축들.length}개뿐이다 — 분모가 사라졌다`);
  for (const a of 축들) {
    assert.ok(a.이름 && a.설명, '축에 이름이나 설명이 없다 — 보고서에서 무엇을 흔든 판인지 못 읽는다');
    assert.ok(a.환경 || a.클론, `축 ${a.이름} 이 아무것도 안 흔든다 — 기준과 같은 판을 재고 「뒤집힘 0」을 낸다`);
  }
});

test('🔴 등록층 — 이 회귀가 CI 스위트에 실제로 든다(파일만 있고 안 도는 검사는 초록과 같은 모양이다)', () => {
  assert.ok(fs.existsSync(path.join(ROOT, 'tests', '환경대조.test.js')));
  assert.match(파일소스(path.join(ROOT, 'tools', 'test-ci.js')), /tests/,
    'CI 러너가 tests 를 안 본다 — 이 파일이 안 돌면 위 전부가 장식이다');
});
