/* 룸입히기 회귀 — `tools/lib/룸입히기.js` (Loom 을 «얹는» 공용 통로).
 *
 * 무엇을 지키나 — 얹는 절차가 `발표물빌드.js` 안에만 살아서, 나머지 지면(생성기 5벌·손파일
 * 4벌)이 같은 절차를 필요로 하는 순간 호출부마다 베껴졌다. 베끼면 갈라지고, 갈라지면
 * **조용히 통과한다**(CLAUDE.md 신뢰성 절 · 새는 방향은 언제나 「통과」다).
 *
 * 이 스위트가 무는 급소 둘 — 둘 다 «초록의 얼굴»로 오는 실패다:
 *   ① **멱등이 깨진다** — 생성기는 돌 때마다 얹으므로, 안 뜯고 얹으면 블록이 겹겹이 쌓인다.
 *      파일만 커지고 화면은 멀쩡해서 아무도 못 본다.
 *   ② **훅 0 인데 얹는다**(F517②) — 부품이 0개인 채 마커만 켜져 `지면방` 전파가 거짓 초록이 된다.
 *
 * 탐지력은 **픽스처가 진다**(가드 맹점 ②). 실저장소는 지금 안 깨져 있어서, 실물만 검사하면
 * 배선을 통째로 끊어도 전부 초록이다. ⇒ 아래는 «병든 지면»을 손으로 만들어 무는지 본다.
 *
 * 🔑 픽스처의 CSS 는 **진짜 `loom.css()` 출력**이다. 축소 모형으로 쓰면 선택자 문법이 실물과
 *    갈리고, 갈리는 방향은 언제나 「통과」다.
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const path = require('node:path');

const 루트 = path.resolve(__dirname, '..');
const 입 = require(path.join(루트, 'tools', 'lib', '룸입히기.js'));

const 지면 = (마크업, 스타일 = 'p{color:red}') =>
  `<html><head><style>${스타일}</style></head><body>${마크업}</body></html>`;

/* 부품 클래스는 «전역»이라 범위 프리셋에서도 닿는다 — 훅이 서는 가장 작은 마크업. */
const 닿는마크업 = '<span class="칩">가</span>';
/* 맨요소뿐 = 범위(`.룸`) 프리셋에선 아무것도 안 닿는다. 발표물 6벌이 이 상태였다. */
const 안닿는마크업 = '<h2>제목</h2><ol><li>가</li></ol>';

/* ── ① 급소 — 멱등 ─────────────────────────────────────────────────────── */

test('🔴 두 번 입혀도 Loom 블록은 1개다 — 멱등(생성기가 매번 부른다)', () => {
  const 한번 = 입.입히기(지면(닿는마크업));
  assert.equal(한번.얹음, true, '훅이 있는데 안 얹었다');
  assert.equal(입.겹침수(한번.html), 1);

  const 두번 = 입.입히기(한번.html);
  assert.equal(입.겹침수(두번.html), 1, '두 번째에 블록이 겹쳤다 — 생성기가 돌 때마다 한 겹씩 쌓인다');

  const 세번 = 입.입히기(두번.html);
  assert.equal(세번.html, 두번.html, '세 번째 출력이 두 번째와 다르다 — 멱등이 아니다');
});

test('뜯기 — 얹힌 것을 되뜯으면 원본으로 돌아온다(1:1 대조가 서는 근거)', () => {
  const 원본 = 지면(닿는마크업);
  const r = 입.입히기(원본);
  assert.equal(입.뜯기(r.html), 원본, '되뜯은 것이 원본과 다르다');
});

/* ── ② 급소 — 훅 0 이면 안 얹는다 (F517②) ──────────────────────────────── */

test('🔴 훅 0 이면 안 얹는다 — 「부품 0인 채 마커만 켜진 초록」을 막는 게이트', () => {
  const r = 입.입히기(지면(안닿는마크업));
  assert.equal(r.얹음, false, '훅 0 인데 얹었다 — 전파가 거짓 초록이 된다');
  assert.equal(r.훅.length, 0);
  assert.ok(!/loom부품:/.test(r.html), '안 얹었다면서 마커가 들어갔다');
});

test('훅이 서면 얹는다 — 게이트가 «막기만» 하고 안 통과시키는 것도 결함이다', () => {
  const r = 입.입히기(지면(닿는마크업));
  assert.equal(r.얹음, true);
  assert.ok(r.훅.length > 0, `훅이 0 이다 — 거짓 적색 쪽으로 샌다(닿은 것: ${r.훅.join('·')})`);
  assert.ok(/\/\*loom부품:/.test(r.html), '얹었다면서 부품 마커가 없다');
});

/* ── ③ 자리 — 원고 CSS «뒤»여야 부품이 특정도 동점에서 이긴다 ──────────── */

test('🔴 Loom 은 원고의 마지막 `</style>` **뒤**에 앉는다 — 앞이면 동점에서 원고가 이긴다', () => {
  const r = 입.입히기(지면(닿는마크업, '.칩{color:red}'));
  const 원고자리 = r.html.indexOf('.칩{color:red}');
  const 룸자리 = r.html.indexOf('<style data-loom=');
  assert.ok(원고자리 >= 0 && 룸자리 > 원고자리,
    'Loom 이 원고 CSS 앞에 앉았다 — 훅은 늘고 화면은 그대로인 「맞는 얼굴로 틀린 값」이 된다');
});

test('`</style>` 이 없으면 던진다 — 조용히 엉뚱한 자리에 넣지 않는다', () => {
  assert.throws(() => 입.얹기('<html><body><span class="칩">가</span></body></html>', 'x', '부품만'),
    /<\/style>/, '얹을 자리가 없는데 안 던졌다');
});

/* ── ④ 대가 — 「정규식 객체를 안 내보낸다」가 실제로 서 있나 ────────────── */

test('🔴 뜯기정규식은 «만들어» 준다 — `/g` 객체를 공유하면 `.test()` 가 번갈아 갈린다', () => {
  assert.equal(typeof 입.뜯기정규식, 'function', '정규식 «객체»를 내보내면 lastIndex 를 공유한다');
  const 얹힌 = 입.입히기(지면(닿는마크업)).html;
  /* 같은 입력에 두 번 물어도 같은 답이어야 한다 — 공유 객체였다면 여기서 true→false 로 갈린다. */
  assert.equal(입.뜯기정규식(false).test(얹힌), true);
  assert.equal(입.뜯기정규식(false).test(얹힌), true, '같은 입력에 답이 갈렸다 — lastIndex 사고');
});

test('겹침수 — 손으로 두 겹 만든 지면을 «세어서» 잡는다(있나/없나로는 못 본다)', () => {
  const 한겹 = 입.입히기(지면(닿는마크업)).html;
  const 두겹 = 한겹.replace('</body>', '<style data-loom="부품만">/*loom부품:x*/</style></body>');
  assert.equal(입.겹침수(두겹), 2, '두 겹인데 못 셌다 — 멱등 깨짐을 영영 못 본다');
});
