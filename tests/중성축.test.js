/**
 * 중성축 회귀 — 킷의 중립 11색이 «정박점 2개에서 유도된 값 그대로»인지 지킨다 (조항 ⓗ · 2026-08-18).
 *
 * 왜 이 파일이 필요한가:
 *   유도기(`tools/중성축.js`)를 짓고 한 번 돌리는 것만으로는 아무것도 안 지켜진다 — 다음 사람이
 *   토큰 JSON 의 회색 하나를 손으로 「조금만」 고치면 그 순간 킷은 유도의 산물이 아니게 되고,
 *   그런데도 모든 테스트가 초록이다(형식·유일성·대비표는 손으로 고친 값도 통과시킨다).
 *   CLAUDE.md 「장치와 그 발동 조건은 같은 커밋에서 정한다」 — 이 파일이 그 발동 조건이다.
 *
 * 무엇을 잡고 무엇을 안 잡는가:
 *   ○ 잡는다 — 중립 11색의 손 편집 · 정박점만 바꾸고 나머지를 안 돌린 반쪽 개정 · 이름/팔레트 갈라짐
 *   ✗ 안 잡는다 — 정박점 자체의 «옳음». 그건 유호님 확정 사안이라 기계가 판정할 자리가 아니다.
 *     (정박점을 바꾸면 이 테스트는 **함께 바꾸라고** 말한다 — 상수 두 개가 여기 적혀 있는 이유다.)
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const 토큰 = require(path.join(ROOT, 'docs', '디자인_토큰.json'));

/* 유호님 확정 2026-08-18 — 이 두 값이 중립 11색 전부의 원천이다 */
const 정박다크 = '#08090C';
const 정박라이트 = '#FAFAF9';

/* 유도기가 내놓아야 할 11칸. 값을 여기 적는 것이 아니라 **도구를 돌려 대조**한다 —
 * 값을 적으면 그 순간 정본이 둘이 되고, 둘은 반드시 갈라진다. */
const 유도 = require(path.join(ROOT, 'tools', '중성축.js'));

test('① 유도기가 라이브러리로 열린다(그러지 않으면 아래 전부가 헛돈다)', () => {
  assert.equal(typeof 유도.유도, 'function', 'tools/중성축.js 가 유도()를 안 내보낸다');
  assert.equal(유도.기본다크, 정박다크, `유도기의 기본 다크 정박점이 ${유도.기본다크} — 이 테스트는 ${정박다크} 를 안다`);
  assert.equal(유도.기본라이트, 정박라이트, `유도기의 기본 라이트 정박점이 ${유도.기본라이트} — 이 테스트는 ${정박라이트} 를 안다`);
});

/* ⚠ 관할이 갈렸다 (2026-08-20 · 조항 ⓙ) — 중립 11색 중 **Paper·Ink 두 칸의 소유권이 조항 ⓙ
 * (2027 킷 「내일 꾸러미」)로 넘어갔다**: Paper #FBF7F0(양모 종이) · Ink #2B2320(따뜻한 먹).
 * 두 칸을 유도값에 계속 물리면 유호님 확정끼리 싸우고, 정박점을 새 값으로 옮기면 유도가
 * **퇴역 대기 9색의 값을 전부 다시 계산**해 다크 지면들이 입고 있는 값이 흔들린다(둘 다 사고).
 * 그래서 이 회귀의 관할은 **퇴역 대기 9색**으로 좁힌다 — 그 9색이 다크 팔레트 트랙에서
 * 재배선·삭제되는 날 이 파일도 함께 진다. */
const 조항J소유 = new Set(['Paper', 'Ink']);

test('② 퇴역 대기 중립 9색 = 정박점에서 유도한 값 그대로 (손 편집 차단 · Paper·Ink 는 조항 ⓙ 소유)', () => {
  const 표 = 유도.유도(정박다크, 정박라이트, 토큰);
  assert.equal(표.length, 11, `유도가 ${표.length}칸 — 11칸이어야 한다`);
  const 킷 = Object.fromEntries(토큰.색.킷.map((c) => [c.이름, c]));
  const 어긋남 = [];
  for (const r of 표) {
    if (조항J소유.has(r.신)) continue;               // 조항 ⓙ 가 값을 진다 — tests/토큰정본·브랜드색이 지킨다
    const c = 킷[r.신];
    if (!c) { 어긋남.push(`${r.신} 이 킷에 없다`); continue; }
    if (c.hex !== r.새hex) 어긋남.push(`${r.신} hex ${c.hex} ≠ 유도값 ${r.새hex}`);
    if (c.팔레트 !== r.팔레트) 어긋남.push(`${r.신} 팔레트 「${c.팔레트}」 ≠ 「${r.팔레트}」`);
  }
  assert.deepEqual(어긋남, [],
    `중립색이 유도와 갈라졌다 — 손으로 고쳤다면 되돌리고, 정박점을 바꿀 생각이면\n` +
    `      node tools/중성축.js --다크 <hex> --라이트 <hex> --적용 && node tools/중성축_뒷정리.js --적용\n` +
    `      을 돌린 뒤 이 파일의 정박점 상수 2개도 함께 옮겨라:\n      ${어긋남.join('\n      ')}`);
});

test('③ 유도의 «약속»이 실제로 지켜진다 — 각 색의 바닥 대비가 구판 대비와 ±0.25 안', () => {
  const 표 = 유도.유도(정박다크, 정박라이트, 토큰);
  const 깨짐 = 표
    .filter((r) => r.구대비 != null)
    .filter((r) => Math.abs(r.새대비 - r.구대비) > 0.25)
    .map((r) => `${r.신} ${r.구대비.toFixed(2)}→${r.새대비.toFixed(2)}`);
  assert.deepEqual(깨짐, [],
    `조항 ⓗ 의 유도 규칙은 「구판 대비를 보존한다」인데 안 지켜졌다: ${깨짐.join(', ')}`);
});

test('④ 무채화 — 중립 11색의 채도폭이 정박점 이하다(색이 다시 새어들지 않는다)', () => {
  const 표 = 유도.유도(정박다크, 정박라이트, 토큰);
  const 폭 = (hex) => { const v = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)); return Math.max(...v) - Math.min(...v); };
  const 상한 = Math.max(폭(정박다크), 폭(정박라이트));
  const 넘김 = 표.filter((r) => 폭(r.새hex) > 상한).map((r) => `${r.신} ${r.새hex} 폭 ${폭(r.새hex)}`);
  assert.deepEqual(넘김, [], `채도폭 상한 ${상한} 초과: ${넘김.join(', ')} — 중립축에 색상이 돌아왔다`);
});

test('⑤ 구 이름(Navy·Cream·Slate)이 킷에서 사라졌다 — 이름이 색을 거짓말하지 않는다', () => {
  const 구 = ['Navy', 'Navy 2', 'Navy 3', 'Navy Ink', 'Cream', 'Cream 2', 'Cream 3', 'Slate', 'Slate 2'];
  const 남음 = 토큰.색.킷.map((c) => c.이름).filter((n) => 구.includes(n));
  assert.deepEqual(남음, [], `킷에 구 이름이 남았다: ${남음.join(', ')} — 무채로 내린 색을 색상 이름으로 부르면 그 자리에서 거짓이다`);
});

test('⑥ 시맨틱·마스코트 허용바닥이 살아있는 킷 이름만 참조한다(개명 반쪽 착지 차단)', () => {
  const 이름들 = new Set(토큰.색.킷.map((c) => c.이름));
  const 나쁨 = [];
  for (const [모드, 표] of Object.entries(토큰.색.시맨틱)) {
    if (모드.startsWith('_')) continue;
    for (const [자리, 값] of Object.entries(표)) if (!이름들.has(값)) 나쁨.push(`시맨틱.${모드}.${자리} = ${값}`);
  }
  for (const n of (토큰.색.마스코트?.허용바닥?.이름들 || [])) if (!이름들.has(n)) 나쁨.push(`허용바닥.이름들 = ${n}`);
  const 최고 = 토큰.색.마스코트?.허용바닥?.가장잘뜨는곳;
  if (최고 && !이름들.has(최고)) 나쁨.push(`허용바닥.가장잘뜨는곳 = ${최고}`);
  assert.deepEqual(나쁨, [], `죽은 이름을 가리키는 참조: ${나쁨.join(' · ')}`);
});
