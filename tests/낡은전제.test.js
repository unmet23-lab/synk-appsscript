'use strict';
/**
 * 낡은 전제 래칫 — 유호님이 「안 쓴다」고 확정한 동선의 낱말이 **다시 늘지 않게** 막는다.
 *
 * ■ 왜 있나 (F623 · 2026-08-18 유호 교정)
 *   `tests/장부유실.test.js` 주석이 `claude/*` 를 「클라우드·**폰** 세션 가지」라 부르고 있었고,
 *   나는 그것을 실물과 대조 없이 읽어 **「폰이라 방치된다」를 판정 근거로** 삼았다. 그날 실측은
 *   정반대였다 — `origin/claude/*` 7개가 전부 그날 커밋된 클라우드(웹) 세션이고 폰 유래는 0개.
 *   유호 교정: **「폰으로 작업하는 게 없는데 왜 폰 관련 작업을 계속 하고 있어? 저번에 말했었는데」**
 *
 *   급소는 재료가 없었던 게 아니다. 나는 그 가지 목록을 같은 세션에서 **이미 봤고**, 그러고도
 *   주석을 정본처럼 읽었다. 그리고 새 주석 두 곳에 같은 전제를 **다시 적었다** — 그게 이 병의
 *   본체다: 낡은 전제는 틀린 채로 조용히 있다가, 읽은 사람이 그것을 근거로 쓰고 재생산한다.
 *   회귀는 하나도 안 빨개진다(전제는 어느 검사의 과녁도 아니다).
 *
 * ■ 이 검사가 «지는» 것과 «안 지는» 것 — 축을 좁혀야 안 꺼진다
 *   ✅ 진다: **총량이 느는 것**. 새 세션이 「폰」을 새로 적으면 여기가 빨개진다.
 *   ❌ 안 진다: 「이 한 줄이 판정 근거인가 역사 서술인가」. 기계가 그 둘을 못 가른다 —
 *      억지로 가르려 들면 거짓양성이 쏟아지고, 거짓양성이 쏟아지는 검사는 곧 꺼지거나 우회된다
 *      (F103). 그 판별은 사람 몫으로 남긴다.
 *   그래서 **래칫**이다: 내려가면 언제나 통과하고 올라가면 빨개진다. 역사 서술을 정리해 줄면
 *      그건 통과이고(아래 하한이 그때 같이 내려간다), 새로 적으면 막힌다.
 *
 * ■ 대가 (새 장치엔 대가를 함께 적는다 — CLAUDE.md 신뢰성)
 *   · 틀릴 때의 모습 = **거짓 적색**. 그 사건의 역사를 새로 쓰는 정당한 커밋(장부 신고문을 코드
 *     주석으로 옮기는 등)이 여기서 막힌다. 눈에 보이는 방향이라 안전한 쪽이고, 처방은 아래 상한을
 *     그 커밋에서 함께 올리며 **왜 늘었는지 한 줄 적는 것**이다.
 *   · 닫는 것 1개 = 「유호님이 안 쓴다고 확정한 동선이 무엇인가」를 사람 기억이 아니라 이 파일이
 *     든다. 지금 한 줄이지만, 확정이 늘면 여기 한 줄씩 는다.
 *   · ⚠ 이 검사는 **문서(`docs/`)를 안 본다** — 장부·보드·아카이브의 언급은 증거라 보존이 원칙이고
 *     (F623 이 그렇게 닫혔다) 거기까지 세면 상한이 매일 흔들려 이 장치가 먼저 꺼진다.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');

/** 접은 동선 — 「확정」에는 **언제·누가·무슨 말로** 를 적는다(사유 없는 줄은 다음 사람이 못 지운다). */
const 접은동선 = Object.freeze([
  {
    이름: '폰(휴대폰) 작업 동선',
    확정: '2026-08-18 유호님 「폰으로 작업하는 게 없는데 왜 폰 관련 작업을 계속 하고 있어? 이거 내가 저번에 말했었는데」',
    /* ⚠ 「폰트」가 이 저장소에 흔하다(지도·인쇄 트랙). 그걸 안 빼면 상한이 폰트 작업마다 흔들려
     *   이 검사가 먼저 꺼진다 — 재는 층이 값을 깨뜨리는 자리다(F045 ②). */
    셈: (줄) => (줄.match(/폰(?!트)/g) || []).length,
    /* 실측 2026-08-18(이 트랙이 ㉮㉰㉯ 를 착지시킨 뒤) — 아래 `세기()` 가 그날 낸 값 그대로다.
     * ⚠ 첫 판은 이 값을 `grep -c` 로 채웠다가 그 자리에서 빨개졌다(51 vs 57): grep 은 **줄 수**를,
     *   이 검사는 **출현 횟수**를 센다. 한 줄에 둘 이상 나오는 자리가 실제로 있었다.
     *   상한은 반드시 **이 파일의 `세기()`** 로 채운다 — 재는 층이 다르면 상한이 처음부터 거짓이다(F045 ②). */
    상한: { tools: 57, '.claude/hooks': 33, tests: 130 },
  },
]);

const js들 = (dir, out = []) => {
  let 목록 = [];
  try { 목록 = fs.readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of 목록) {
    if (e.name === 'node_modules' || e.name === '.git' || e.name === 'worktrees') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) js들(p, out);
    else if (e.name.endsWith('.js')) out.push(p);
  }
  return out;
};

function 세기(방, 셈) {
  const 파일들 = js들(path.join(ROOT, 방));
  let 합 = 0;
  for (const f of 파일들) 합 += 셈(fs.readFileSync(f, 'utf8'));
  return { 합, 파일수: 파일들.length };
}

for (const 동선 of 접은동선) {
  test(`🔴 래칫 — 「${동선.이름}」 낱말이 코드층에서 **늘지 않는다** (내려가면 통과)`, () => {
    const 실측 = [];
    for (const [방, 상한] of Object.entries(동선.상한)) {
      const { 합, 파일수 } = 세기(방, 동선.셈);
      /* 분모부터 밝힌다 — 훑기가 깨져 0벌을 읽어도 「0건」은 통과와 같은 모양이다(F207). */
      assert.ok(파일수 > 0, `${방} 에서 .js 를 0벌 읽었다 — 걸음이 깨졌다(미측정은 통과가 아니다)`);
      실측.push(`${방} ${합}/${상한}`);
      assert.ok(합 <= 상한,
        `「${동선.이름}」 언급이 ${방} 에서 ${합}개로 늘었다(상한 ${상한}).\n`
        + `   확정: ${동선.확정}\n`
        + '   → 낡은 전제를 **판정 근거로** 새로 적었는지 먼저 본다(F623 이 그 사고였다).\n'
        + '   → 그 사건의 역사를 정당하게 새로 쓴 것이면 이 파일의 상한을 같은 커밋에서 올리고\n'
        + '     **왜 늘었는지 한 줄** 적는다. 조용히 올리면 이 래칫은 장식이 된다.');
    }
    console.log(`  ℹ ${동선.이름} — ${실측.join(' · ')}`);
  });

  test(`🔑 상한이 실측보다 헐렁하지 않다 — 「${동선.이름}」 (빚을 갚았으면 상한도 내린다)`, () => {
    /* 래칫만 있으면 상한이 영원히 옛 실측에 머문다. 정리로 줄어든 만큼은 상한도 내려야 다음 증가를
     * 잡는다 — 안 그러면 「줄인 만큼 다시 늘려도 통과」가 되어 래칫이 그 폭만큼 눈이 먼다.
     * ⚠ 막지 않고 **보고만** 한다: 막으면 정리하는 커밋이 그 자리에서 빨개져, 버그가 아직 있을 것을
     *   요구하는 회귀가 된다(맹점 ②). */
    const 헐렁 = [];
    for (const [방, 상한] of Object.entries(동선.상한)) {
      const { 합 } = 세기(방, 동선.셈);
      if (합 < 상한) 헐렁.push(`${방} ${합} < 상한 ${상한}`);
    }
    if (헐렁.length) {
      console.log(`  ⚠ 상한이 실측보다 높다 — 그 폭만큼 래칫이 눈이 멀어 있다: ${헐렁.join(' · ')}`);
      console.log('    → 줄인 커밋에서 상한도 같이 내린다(tests/낡은전제.test.js 의 `상한`).');
    }
  });
}

test('🔴 등록층 — 이 회귀가 CI 스위트에 실제로 든다(파일만 있고 안 도는 검사는 초록과 같은 모양이다)', () => {
  const 러너 = fs.readFileSync(path.join(ROOT, 'tools', 'test-ci.js'), 'utf8');
  assert.match(러너, /tests/, 'CI 러너가 tests 를 안 본다 — 이 파일이 안 돌면 위 전부가 장식이다');
  assert.ok(fs.existsSync(path.join(ROOT, 'tests', '낡은전제.test.js')));
});
