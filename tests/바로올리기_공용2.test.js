  // r1을 고친 세션이 조각으로 올리면 r1은 작업본·T 둘 다에서 사라져 자리를 가르지 않는다 — P1은 받은 줄로 보아 origin이 지운 대로
  const O2 = 판.남push({ 'docs/_ops/결정.md': `${머리}${r1w}${r3}${N}` }, 'r1 고침 조각');
