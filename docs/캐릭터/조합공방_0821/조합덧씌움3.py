# -*- coding: utf-8 -*-
"""조합판에 산 글자를 붓는다 — 3차판. 2차(조합덧씌움2.py)와 다른 점은 **좌표의 출처** 하나다.
2차는 본문 자리를 손좌표(150/596/692…)로 박아, 카드를 줄이면 글이 카드 위쪽에 쏠리거나 넘쳤다.
3차는 굽기가 함께 낸 `<출력>.png.칸.json`(카드의 화면 픽셀 상자)을 읽어 **카드 안에 앉힌다** —
판마다 다시 재지 않는다. 대비 실측은 2차 그대로(후광 고리 최악값).

08-22 보조줄 수리: 키릴 줄이 **정답을 누설**하고 있었다(「…кофе уудаг.」의 уудаг = 마시다).
문제는 «커피를 ___» 인데 보조줄이 그 빈칸을 채워 줬으니 이 문항은 아무것도 재지 못했다.
게다가 **정확히 거꾸로**였다 — 번역하면 안 되는 것(문제)은 번역하고, 못 읽으면 통째로 무용지물인
것(힌트)은 한국어만이었다. 층별 규칙(성장공방_0821/인계.md §4)대로 다시 부었다.

  쓰는 법:  python 조합덧씌움3.py <바탕이름> [없음|층별|전면] [급수]
            기본 = 층별 · 3급 (성장판 목업과 같은 학생)
"""
import io, json, os, sys

import PIL.ImageChops as C
from PIL import Image, ImageDraw, ImageFilter, ImageFont

여기 = os.path.dirname(os.path.abspath(__file__))
굵 = r"C:\Windows\Fonts\malgunbd.ttf"
보통 = r"C:\Windows\Fonts\malgun.ttf"
키릴서체 = r"C:\Windows\Fonts\segoeui.ttf"   # 맑은고딕엔 몽골 키릴 ө·ү 글리프가 없다(두부 실측)
잉크 = (0xFB, 0xF7, 0xF0)      # Paper
보조 = (0xED, 0xE7, 0xDC)      # Oat
보조2 = (0xC7, 0xBF, 0xB2)     # Stone

이름 = sys.argv[1]
갈래 = sys.argv[2] if len(sys.argv) > 2 else "층별"     # 없음 | 층별 | 전면
                                                      # ⚠이름을 「보조」로 두면 색 상수를 덮는다
급수 = int(sys.argv[3]) if len(sys.argv) > 3 else 3

# ── 층별 규칙(성장공방_0821/인계.md §4)의 이 화면 집행 ──────────────────────────────
#   ㉠ 문제 문장 = 학습 대상의 «맥락» → 급수 연동(1~2급만 병기 · 3급부터 걷힌다 = 승급의 실물 보상)
#   ㉡ 보기 ①②③ = 학습 대상 «자체» → 어느 급수에서도 병기하지 않는다.
#      번역하면 학생이 몽골어끼리 짝지어 고르므로 문항이 «한국어를» 재지 못한다.
#   ㉢ 힌트 = 읽어야 «행동이 바뀌는» 문장 → 항상 병기(못 읽으면 힌트가 통째로 무용지물).
#   ⚠㉠의 키릴 거울은 **빈칸을 빈칸으로 둔다.** 몽골어도 동사가 끝에 오므로 자리가 그대로 맞는다.
문제키릴 = (갈래 == "전면") or (갈래 == "층별" and 급수 <= 2)
보기키릴 = (갈래 == "전면")
힌트키릴 = 갈래 in ("층별", "전면")

# ⚠몽골어 문안은 **검수 전 표본**이다 — 이 판으로 정하는 것은 「어디에 넣나」뿐.
몽 = {
    "문제": "Би өглөө болгон кофе ___.",          # 빈칸 보존 — уудаг 을 넣으면 정답 누설
    "힌트": "Шингэн зүйлд хэрэглэдэг үг.",        # ⚠키릴 서체엔 한글이 없다 — 「마시다」를 넣으면 두부(□)
    "보기": ("уудаг", "иддэг", "үздэг"),
}

# ⚠**낡은 경로였다** — `렌더/` 하위 폴더는 없어졌는데(08-23 실측) 이 두 줄이 그대로 남아
#   스크립트가 통째로 안 돌고 있었다. 옆 세 공방(오늘·소식·학부모)과 같게 «여기» 바로 아래를 본다.
바탕길 = os.path.join(여기, 이름 + ".png")
칸길 = 바탕길 + ".칸.json"
# ⚠**채택판은 꼬리가 없다** — 오늘·소식·학부모 공방과 같은 규약으로 통일했다(08-23).
#   세 공방이 서로 다른 이름 규약을 쓰면 「어느 게 현행인가」를 파일 이름이 못 말한다.
꼬리 = "" if (갈래 == "층별" and 급수 == 3) else "_%s%d급" % (갈래, 급수)

im = Image.open(바탕길).convert("RGB")
W, H = im.size
d = ImageDraw.Draw(im)

# ── 본문 자리 — 카드 칸에서 뽑는다 ──────────────────────────────────────────────
#   왼 들여쓰기 98 · 줄새 96 · 키릴 내림 210 은 2차 채택판의 «비례»를 그대로 옮긴 값이다
#   (2차 실측: 카드 좌 52 → 글 150 · 카드 위 479 → 글 596 · 블록 596~852).
#   ⚠광학 보정 −12: PIL 의 text top 은 폰트 상자 위끝이라 글자는 그보다 아래에서 시작한다.
#     기하 중앙에 그대로 앉히면 «아래로 처져» 보인다.
#   ⚠블록 높이는 «줄 수»를 따른다 — 키릴 줄이 빠졌는데 3줄 높이로 앉히면 글이 위로 뜬다.
칸들 = json.load(io.open(칸길, encoding="utf-8"))
칸 = 칸들["카드"]
좌 = int(round(칸["좌"] + 98))
블록 = 256 if 문제키릴 else 172
줄1 = int(round((칸["위"] + 칸["아래"]) / 2 - 블록 / 2 - 12))
줄2, 몽골 = 줄1 + 96, 줄1 + 210


def 글(x, y, 본문, 크기, 색, bold=True, 서체=None):
    f = ImageFont.truetype(서체 or (굵 if bold else 보통), 크기)
    d.text((x, y), 본문, font=f, fill=색)
    return (x, y, 본문, 크기, bold, 서체)


기록 = []
색표 = {}


def 적는다(표이름, 색, x, y, 본문, 크기, bold=True, 서체=None):
    """글을 붓고 «대비 실측이 다시 찾을 수 있게» 이름·색과 함께 장부에 적는다."""
    기록.append((표이름, 글(x, y, 본문, 크기, 색, bold, 서체)))
    색표[표이름] = 색


# ── 카드 위: 문제 (keep-all 은 짧은 줄로 손수 보장 · 위계는 밀도) ──
적는다("문제줄1", 잉크, 좌, 줄1, "저는 아침마다", 62, True)
적는다("문제줄2", 잉크, 좌, 줄2, "커피를 ___.", 62, True)
if 문제키릴:
    적는다("문제몽", 보조2, 좌, 몽골, 몽["문제"], 34, False, 키릴서체)

# ── 알약 위: 보기 — 알약도 자기 칸을 말한다(3차). 2차 손좌표(1244/1496/1748)는 알약을 옮기자
#    글이 알약 아래로 흘러내렸다. 알약 세로 중앙 − 30(48px 글의 반) − 12(광학 보정)에 앉힌다.
for 번, 본문 in enumerate(("①  마셔요", "②  먹어요", "③  봐요")):
    알 = 칸들["알약%d" % (번 + 1)]
    중 = (알["위"] + 알["아래"]) / 2
    if 보기키릴:
        py = int(round(중 - 42 - 12))
        적는다(본문[:1], 잉크, 190, py, 본문, 48, False)
        적는다(본문[:1] + "몽", 보조2, 190 + 62, py + 60, 몽["보기"][번], 26, False, 키릴서체)
    else:
        적는다(본문[:1], 잉크, 190, int(round(중 - 30 - 12)), 본문, 48, False)

# ── 화면 바닥: 힌트 — 두 줄이면 한 줄이던 자리의 «세로 중심»을 지킨다 ──
힌트y = 1910 if 힌트키릴 else 1930
적는다("힌트", 보조, 150, 힌트y, "힌트 — 「마시다」는 액체에 씁니다", 37, False)
if 힌트키릴:
    적는다("힌트몽", 보조2, 150, 힌트y + 50, 몽["힌트"], 28, False, 키릴서체)

낸것 = os.path.join(여기, "조합판_v1" + 꼬리 + ".png")   # 채택판 이름은 «_그릇만» 을 뗀 것이다
im.save(낸것)
print("구움:", os.path.basename(낸것),
      "· 갈래 %s · %d급 · 문제키릴 %s · 보기키릴 %s · 힌트키릴 %s"
      % (갈래, 급수, 문제키릴, 보기키릴, 힌트키릴))


# ── 대비 실측 — 블록마다 후광 고리 최악값 ──
def 상대휘도(r, g, b):
    def f(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def 대비(a, b):
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


바탕 = Image.open(바탕길).convert("RGB")
bl = 바탕.load()
print()
print("%-10s %10s %10s  %s" % ("블록", "평균대비", "최악대비", "판정"))
print("-" * 52)
최악표 = "AAA"
for 표이름, (x, y, 본문, 크기, bold, 서체) in 기록:
    m = Image.new("L", 바탕.size, 0)
    dm = ImageDraw.Draw(m)
    f = ImageFont.truetype(서체 or (굵 if bold else 보통), 크기)
    dm.text((x, y), 본문, font=f, fill=255)
    고리 = C.subtract(m.filter(ImageFilter.MaxFilter(5)), m)
    gl = 고리.load()
    L글 = 상대휘도(*색표[표이름])
    ls = []
    x0, y0 = max(0, x - 20), max(0, y - 20)
    x1, y1 = min(W, x + 1000), min(H, y + 크기 * 2 + 40)
    for yy in range(y0, y1):
        for xx in range(x0, x1):
            if gl[xx, yy] > 128:
                ls.append(상대휘도(*bl[xx, yy]))
    ls.sort()
    평균 = 대비(L글, sum(ls) / len(ls))
    나쁨 = 대비(L글, ls[int(len(ls) * 0.95)])
    표 = "AAA" if 나쁨 >= 7 else ("AA" if 나쁨 >= 4.5 else "X")
    if 표 != "AAA":
        최악표 = 표
    print("%-10s %9.2f %9.2f  %s" % (표이름, 평균, 나쁨, 표))
print("전체:", 최악표)
