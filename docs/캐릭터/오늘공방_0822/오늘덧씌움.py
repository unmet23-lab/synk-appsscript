# -*- coding: utf-8 -*-
"""「오늘」 탭에 산 글자를 붓는다 — 그릇의 화면 칸(<출력>.png.칸.json)을 읽어 앉힌다.

손좌표를 쓰지 않는 규율은 조합덧씌움3·성장덧씌움과 같다: **그릇을 옮기면 글이 따라와야 한다.**
그래서 여기엔 픽셀 상수가 «칸 안에서의 여백»으로만 나오고, 칸의 자리는 한 줄도 안 적혀 있다.

쓰기:  python 오늘덧씌움.py 오늘판_v1_그릇만 [없음|층별|전면]
       → 오늘판_v1[_층별].png  +  대비 실측표
"""
import io, json, os, sys

import PIL.ImageChops as C
from PIL import Image, ImageDraw, ImageFilter, ImageFont

여기 = os.path.dirname(os.path.abspath(__file__))
굵 = r"C:\Windows\Fonts\malgunbd.ttf"
보통 = r"C:\Windows\Fonts\malgun.ttf"
키릴 = r"C:\Windows\Fonts\segoeui.ttf"   # ⚠맑은고딕엔 몽골 키릴 ө·ү 글리프가 없다(두부 실측)
잉크 = (0xFB, 0xF7, 0xF0)      # Paper
보조 = (0xED, 0xE7, 0xDC)      # Oat
보조2 = (0xC7, 0xBF, 0xB2)     # Stone

이름 = sys.argv[1] if len(sys.argv) > 1 else "오늘판_v1_그릇만"
보조갈래 = sys.argv[2] if len(sys.argv) > 2 else "층별"   # 없음 | 층별 | 전면
바탕길 = os.path.join(여기, 이름 + ".png")
칸들 = json.load(io.open(바탕길 + ".칸.json", encoding="utf-8"))

im = Image.open(바탕길).convert("RGB")
W, H = im.size
d = ImageDraw.Draw(im)
기록 = []


def 글(x, y, 본문, 크기, 색, bold=True, 서체=None, 가운데=False):
    f = ImageFont.truetype(서체 or (굵 if bold else 보통), 크기)
    if 가운데:
        x = int(x - d.textlength(본문, font=f) / 2)
    d.text((x, y), 본문, font=f, fill=색)
    return (x, y, 본문, 크기, bold, 서체)


도 = 칸들["도전"]
카폭 = 도["우"] - 도["좌"]
카높 = 도["아래"] - 도["위"]
안여백 = 124          # 성장판과 같은 좌여백(카드 폭의 13%) — 화면끼리 마진선이 갈리면 다른 앱이 된다
글좌 = 도["좌"] + 안여백

# ⚠몽골어는 **검수 전 표본**이다(철학 정본 §0 파생 게이트 — 몽골어 검수).
# 층별 규칙(08-22 기본값): UI 라벨엔 안 붙이고 **읽어야 행동이 바뀌는 문장**에만 붙인다.
몽 = {"제목": "Өнөөдөр",
      "도전": "Өчигдрийн өгүүлбэрээ ярьж үзье",
      "탭0": "Өнөөдөр", "탭1": "Миний ахиц", "탭2": "Мэдээ"}
전면 = 보조갈래 == "전면"
키릴줄 = 보조갈래 != "없음"

# ── 제목 — 카드에 붙여 한 덩어리로 읽히게(성장판과 같은 150px 띄움) ──
기록.append(("제목", 글(도["좌"] + 8, 도["위"] - (150 if not 전면 else 186), "오늘", 60, 잉크, True)))
if 전면:
    기록.append(("제목몽", 글(도["좌"] + 8, 도["위"] - 116, 몽["제목"], 30, 보조2, False, 서체=키릴)))

# ── ① 오늘의 도전 — 하루의 «한 가지» ────────────────────────────────────────────
#   🔑 밑줄(코랄 실)의 자리는 **그릇이 정한다** — 카드 세로의 84.3% 지점이다(굽기 좌표 z=0.84).
#      글을 밑줄에 맞추는 것이지 밑줄을 글에 맞추는 것이 아니다(밑줄은 구워져 못 움직인다).
밑줄y = 도["위"] + 카높 * 0.8429

y = 도["위"] + 70
기록.append(("라벨", 글(글좌, y, "오늘의 도전", 34, 보조2, False)))
y += 62
for 줄 in ("어제 배운 문장으로", "한 번 말해 볼까요"):
    기록.append(("큰줄%d" % len([k for k, _ in 기록 if k.startswith("큰줄")]),
                 글(글좌, y, 줄, 56, 잉크, True)))
    y += 84
if 키릴줄:
    # 「읽어야 행동이 바뀌는 문장」이라 보조줄이 붙는 자리다(라벨 「오늘의 도전」에는 안 붙는다).
    기록.append(("도전몽", 글(글좌, y + 12, 몽["도전"], 28, 보조2, False, 서체=키릴)))

# 시작 줄 — 코랄 밑줄 «바로 위»에 앉는다. 76px 은 34px 글자의 아래끝과 밑줄 사이 숨이다.
기록.append(("시작", 글(글좌, 밑줄y - 76, "30초면 충분해요", 34, 보조, False)))

# ── ② 할 일 셋 — 단추가 «했나»를 말하므로 글은 이름만 든다 ─────────────────────────
#   ⚠상태를 글로 또 쓰지 않는다(「했어요」 금지) — 꿰맨 단추가 이미 그 말을 하고 있고,
#     같은 신호를 두 번 주면 화면이 시끄러워진다(4계 ②).
# 🔴유호 지시 08-23 「네 번째 줄 넣어줘」 — 넷째는 **다시쓰기(학3)**다.
#   소식 탭에 첨삭이 «도착»하면 여기에 다시쓰기가 «할 일»로 뜬다: 두 탭이 서로를 부른다.
할일 = (("숙제 3문장 쓰기", True), ("첨삭 받은 문장 다시 쓰기", False),
        ("선생님께 답장 쓰기", False), ("주말 강의 보기", False))
for 번, (이름표, 했나) in enumerate(할일):
    칸 = 칸들["할일%d" % 번]
    폭 = 칸["우"] - 칸["좌"]
    단추x = 칸["좌"] + 폭 * 0.0950      # 굽기 좌표 x=−0.98 을 칸 폭(±1.21)으로 되돌린 값
    중 = (칸["위"] + 칸["아래"]) / 2
    기록.append(("할일%d" % 번, 글(단추x + 92, 중 - 26, 이름표, 40,
                                 보조2 if 했나 else 보조, not 했나)))

# ── ③ 탭바 글자 — 지금 탭만 밝고 나머지는 물러선다(4계 ②) ───────────────────────────
if "탭0" in 칸들:
    for 번, 이름표 in enumerate(("오늘", "나의 성장", "소식")):
        탭 = 칸들["탭%d" % 번]
        가 = (탭["좌"] + 탭["우"]) / 2
        중 = (탭["위"] + 탭["아래"]) / 2
        지금 = (번 == 0)               # 이 화면이 «오늘»이다
        기록.append(("탭%d" % 번, 글(가, 중 - 22, 이름표, 34, 보조 if 지금 else 보조2, 지금, 가운데=True)))
        if 전면:
            기록.append(("탭%d몽" % 번, 글(가, 중 + 20, 몽["탭%d" % 번], 24, 보조2, False,
                                        서체=키릴, 가운데=True)))

꼬리 = "" if 보조갈래 == "층별" else "_" + 보조갈래
낸것 = os.path.join(여기, "오늘판_v1" + 꼬리 + ".png")
im.save(낸것)
print("구움:", os.path.basename(낸것))


# ── 대비 실측 — 블록마다 후광 고리 최악값(조합판·성장판과 같은 잣대) ─────────────────
def 상대휘도(r, g, b):
    def f(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def 대비(a, b):
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


바탕 = Image.open(바탕길).convert("RGB")
bl = 바탕.load()
색표 = {"라벨": 보조2, "시작": 보조, "도전몽": 보조2, "제목몽": 보조2,
        "할일0": 보조2, "할일1": 보조, "할일2": 보조, "할일3": 보조,
        "탭0": 보조, "탭1": 보조2, "탭2": 보조2}
색표.update({"탭%d몽" % i: 보조2 for i in range(3)})
print()
print("%-10s %10s %10s  %s" % ("블록", "평균대비", "최악대비", "판정"))
print("-" * 52)
최악 = "AAA"
for 표이름, (x, y, 본문, 크기, bold, 서체) in 기록:
    m = Image.new("L", 바탕.size, 0)
    dm = ImageDraw.Draw(m)
    f = ImageFont.truetype(서체 or (굵 if bold else 보통), 크기)
    dm.text((x, y), 본문, font=f, fill=255)
    고리 = C.subtract(m.filter(ImageFilter.MaxFilter(5)), m)
    gl = 고리.load()
    글색 = 색표.get(표이름, 잉크)
    L글 = 상대휘도(*글색)
    ls = []
    x0, y0 = max(0, int(x) - 20), max(0, int(y) - 20)
    x1, y1 = min(W, int(x) + 1000), min(H, int(y) + 크기 * 2 + 40)
    for yy in range(y0, y1):
        for xx in range(x0, x1):
            if gl[xx, yy] > 128:
                ls.append(상대휘도(*bl[xx, yy]))
    if not ls:
        continue
    ls.sort()
    평균 = 대비(L글, sum(ls) / len(ls))
    나쁨 = 대비(L글, ls[int(len(ls) * 0.95)])
    표 = "AAA" if 나쁨 >= 7 else ("AA" if 나쁨 >= 4.5 else "X")
    if 표 != "AAA":
        최악 = 표
    print("%-10s %9.2f %9.2f  %s" % (표이름, 평균, 나쁨, 표))
print("전체:", 최악)
