# -*- coding: utf-8 -*-
"""「소식」 탭에 산 글자를 붓는다 — 그릇의 화면 칸(<출력>.png.칸.json)을 읽어 앉힌다.

손좌표를 안 쓰는 규율은 조합·성장·오늘 덧씌움과 같다: **그릇을 옮기면 글이 따라와야 한다.**
여기에 나오는 픽셀 상수는 전부 «칸 안에서의 여백»이고, 칸의 자리는 한 줄도 안 적혀 있다.

🔑 이 화면에만 있는 것이 하나 있다 — **날짜 열**. 소식이 소식인 까닭의 절반은 «언제 왔나»이고,
   오늘 탭과 이 화면을 실제로 가르는 것도 그 열이다. 그런데 그것을 굽지 않았다:
   부품이 아니라 «본문»이라 여기서 붙인다. 이 세계가 싸게 넓어지는 방식이 그것이다.

쓰기:  python 소식덧씌움.py 소식판_v1_그릇만 [없음|층별|전면]
       → 소식판_v1[_층별].png  +  대비 실측표
"""
import io, json, os, sys

import PIL.ImageChops as C
from PIL import Image, ImageDraw, ImageFilter, ImageFont

여기 = os.path.dirname(os.path.abspath(__file__))
굵 = r"C:\Windows\Fonts\malgunbd.ttf"
보통 = r"C:\Windows\Fonts\malgun.ttf"
키릴 = r"C:\Windows\Fonts\segoeui.ttf"   # ⚠맑은고딕엔 몽골 키릴 ө·ү 글리프가 없다(두부 실측)
잉크 = (0xFB, 0xF7, 0xF0)      # Paper
보조 = (0xED, 0xE7, 0xDC)      # Oat
보조2 = (0xC7, 0xBF, 0xB2)     # Stone

이름 = sys.argv[1] if len(sys.argv) > 1 else "소식판_v1_그릇만"
보조갈래 = sys.argv[2] if len(sys.argv) > 2 else "층별"   # 없음 | 층별 | 전면
바탕길 = os.path.join(여기, 이름 + ".png")
칸들 = json.load(io.open(바탕길 + ".칸.json", encoding="utf-8"))

im = Image.open(바탕길).convert("RGB")
W, H = im.size
d = ImageDraw.Draw(im)
기록 = []

# ── 해상도 풀기 (트랙 §6) ──────────────────────────────────────────────────────
#   칸의 «자리»는 JSON 이 주므로 이미 상대적이다. 묶여 있던 것은 칸 «안»의 여백과 글자 크기뿐이다.
#   ⇒ 카드 폭에서 배율을 뽑아 그 둘에만 곱한다. 1080px 판에서는 배 = 1.0 이라 옛 산출과 같다.
_기준카드폭 = 945.0          # 1080px 판에서 이 칸의 폭(칸 JSON 실측) — 배율의 뿌리다
배 = (칸들["새소식"]["우"] - 칸들["새소식"]["좌"]) / _기준카드폭


def 픽(v):
    """1080px 판 기준의 픽셀 값 → 지금 판의 픽셀 값. **칸 안 여백·오프셋 전용**이다
    (칸의 자리는 JSON 이 이미 상대적으로 준다)."""
    return int(round(v * 배))



def 글(x, y, 본문, 크기, 색, bold=True, 서체=None, 가운데=False, 오른쪽=False):
    f = ImageFont.truetype(서체 or (굵 if bold else 보통), 픽(크기))
    if 가운데:
        x = int(x - d.textlength(본문, font=f) / 2)
    elif 오른쪽:
        x = int(x - d.textlength(본문, font=f))
    d.text((x, y), 본문, font=f, fill=색)
    return (x, y, 본문, 크기, bold, 서체)


카 = 칸들["새소식"]
카폭 = 카["우"] - 카["좌"]
카높 = 카["아래"] - 카["위"]
안여백 = 픽(124)          # 성장판·오늘판과 같은 좌여백 — 화면끼리 마진선이 갈리면 다른 앱이 된다
글좌 = 카["좌"] + 안여백

# ⚠몽골어는 **검수 전 표본**이다(철학 정본 §0 파생 게이트 — 몽골어 검수).
# 층별 규칙(08-22 기본값): UI 라벨엔 안 붙이고 **읽어야 행동이 바뀌는 문장**에만 붙인다.
몽 = {"제목": "Мэдээ",
      "첨삭": "Багшийн засвар ирлээ",
      "탭0": "Өнөөдөр", "탭1": "Миний ахиц", "탭2": "Мэдээ"}
전면 = 보조갈래 == "전면"
키릴줄 = 보조갈래 != "없음"

# ── 제목 — 카드에 붙여 한 덩어리로(성장판·오늘판과 같은 150px 띄움) ──
기록.append(("제목", 글(카["좌"] + 픽(8), 카["위"] - 픽(150 if not 전면 else 186), "소식", 60, 잉크, True)))
if 전면:
    기록.append(("제목몽", 글(카["좌"] + 픽(8), 카["위"] - 픽(116), 몽["제목"], 30, 보조2, False, 서체=키릴)))

# ── ① 새 첨삭 — 학2. 학생에게 가장 값진 도착물 ────────────────────────────────
#   🔑 밑줄(코랄 실)의 자리는 **그릇이 정한다** — 카드 세로의 84.3% 지점(굽기 좌표 z = 카드z−0.48).
#      글이 밑줄에 맞추는 것이지 밑줄이 글에 맞추는 것이 아니다(밑줄은 구워져 못 움직인다).
밑줄y = 카["위"] + 카높 * 0.8429

y = 카["위"] + 픽(70)
기록.append(("라벨", 글(글좌, y, "새 첨삭", 34, 보조2, False)))
y += 픽(62)
for 줄 in ("어제 쓴 3문장에", "선생님 첨삭이 왔어요"):
    기록.append(("큰줄%d" % len([k for k, _ in 기록 if k.startswith("큰줄")]),
                 글(글좌, y, 줄, 56, 잉크, True)))
    y += 픽(84)
if 키릴줄:
    # 「읽어야 행동이 바뀌는 문장」이라 보조줄이 붙는 자리다(라벨 「새 첨삭」에는 안 붙는다).
    기록.append(("첨삭몽", 글(글좌, y + 픽(12), 몽["첨삭"], 28, 보조2, False, 서체=키릴)))

# 시작 줄 — 코랄 밑줄 «바로 위». 76px 은 34px 글자 아래끝과 밑줄 사이 숨이다.
기록.append(("시작", 글(글좌, 밑줄y - 픽(76), "지금 확인하기", 34, 보조, False)))

# ── ② 소식 넷 — 이름 왼쪽 · 날짜 오른쪽 ────────────────────────────────────────
#   ⚠상태를 글로 또 쓰지 않는다(「안 읽음」 금지) — 빈 단추가 이미 그 말을 하고 있고,
#     같은 신호를 두 번 주면 화면이 시끄러워진다(4계 ②). 대신 **밝기**로 갈린다:
#     안 읽은 것은 밝고 굵게(Oat·bold) · 읽은 것은 물러선다(Stone·보통).
소식 = ((u"우리 반 이번 주 목표", u"오늘", False),
        (u"8월 27일 휴원 안내", u"어제", False),
        (u"선생님이 왕관을 주셨어요", u"3일 전", True),
        (u"명예의 전당에 올랐어요", u"지난주", True))
for 번, (이름표, 날짜, 읽음) in enumerate(소식):
    칸 = 칸들["줄%d" % 번]
    폭 = 칸["우"] - 칸["좌"]
    단추x = 칸["좌"] + 폭 * 0.0950      # 굽기 좌표 x=−0.98 을 칸 폭(±1.21)으로 되돌린 값
    중 = (칸["위"] + 칸["아래"]) / 2
    기록.append(("소식%d" % 번, 글(단추x + 픽(92), 중 - 픽(26), 이름표, 40,
                                 보조2 if 읽음 else 보조, not 읽음)))
    # 날짜 — 오른쪽 정렬. 여백은 왼쪽 단추까지의 거리와 같은 선으로 잡는다(좌우가 같은 숨).
    기록.append(("날짜%d" % 번, 글(칸["우"] - (단추x - 칸["좌"]), 중 - 픽(16), 날짜, 28,
                                 보조2, False, 오른쪽=True)))

# ── ③ 탭바 글자 — 지금 탭만 밝고 나머지는 물러선다(4계 ②) ─────────────────────
if "탭0" in 칸들:
    for 번, 이름표 in enumerate(("오늘", "나의 성장", "소식")):
        탭 = 칸들["탭%d" % 번]
        가 = (탭["좌"] + 탭["우"]) / 2
        중 = (탭["위"] + 탭["아래"]) / 2
        지금 = (번 == 2)               # 이 화면이 «소식»이다
        기록.append(("탭%d" % 번, 글(가, 중 - 픽(22), 이름표, 34, 보조 if 지금 else 보조2, 지금, 가운데=True)))
        if 전면:
            기록.append(("탭%d몽" % 번, 글(가, 중 + 픽(20), 몽["탭%d" % 번], 24, 보조2, False,
                                        서체=키릴, 가운데=True)))

꼬리 = "" if 보조갈래 == "층별" else "_" + 보조갈래
낸것 = os.path.join(여기, "소식판_v1" + 꼬리 + ".png")
im.save(낸것)
print("구움:", os.path.basename(낸것))


# ── 대비 실측 — 블록마다 후광 고리 최악값(앞 세 화면과 같은 잣대) ─────────────────
def 상대휘도(r, g, b):
    def f(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def 대비(a, b):
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


바탕 = Image.open(바탕길).convert("RGB")
bl = 바탕.load()
색표 = {"라벨": 보조2, "시작": 보조, "첨삭몽": 보조2, "제목몽": 보조2,
        "소식0": 보조, "소식1": 보조, "소식2": 보조2, "소식3": 보조2,
        "탭0": 보조2, "탭1": 보조2, "탭2": 보조}
색표.update({"날짜%d" % i: 보조2 for i in range(4)})
색표.update({"탭%d몽" % i: 보조2 for i in range(3)})
print()
print("%-10s %10s %10s  %s" % ("블록", "평균대비", "최악대비", "판정"))
print("-" * 52)
최악 = "AAA"
for 표이름, (x, y, 본문, 크기, bold, 서체) in 기록:
    m = Image.new("L", 바탕.size, 0)
    dm = ImageDraw.Draw(m)
    f = ImageFont.truetype(서체 or (굵 if bold else 보통), 픽(크기))
    dm.text((x, y), 본문, font=f, fill=255)
    고리 = C.subtract(m.filter(ImageFilter.MaxFilter(5)), m)
    gl = 고리.load()
    글색 = 색표.get(표이름, 잉크)
    L글 = 상대휘도(*글색)
    ls = []
    x0, y0 = max(0, int(x) - 20), max(0, int(y) - 20)
    x1, y1 = min(W, int(x) + 1000), min(H, int(y) + 크기 * 2 + 40)
    for yy in range(y0, y1):
        for xx in range(x0, x1):
            if gl[xx, yy] > 128:
                ls.append(상대휘도(*bl[xx, yy]))
    if not ls:
        # ⚠«못 쟀다»를 조용히 건너뛰지 않는다 — 그러면 「대비가 좋다」와 「안 재봤다」가 같은 모양이 된다.
        print("%-10s %9s %9s  못 쟀다(고리 화소 0)" % (표이름, "-", "-"))
        최악 = "못잼"
        continue
    if not ls:
        # ⚠700px 판에서 실제로 났다 — 가드가 없어 0 으로 나눴다(08-23).
        print("%-10s %9s %9s  못 쟀다(고리 화소 0)" % (표이름, "-", "-"))
        최악표 = "못잼"
        continue
    ls.sort()
    평균 = 대비(L글, sum(ls) / len(ls))
    나쁨 = 대비(L글, ls[int(len(ls) * 0.95)])
    표 = "AAA" if 나쁨 >= 7 else ("AA" if 나쁨 >= 4.5 else "X")
    if 표 != "AAA":
        최악 = 표
    print("%-10s %9.2f %9.2f  %s" % (표이름, 평균, 나쁨, 표))
print("전체:", 최악)
