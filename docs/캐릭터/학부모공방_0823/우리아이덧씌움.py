# -*- coding: utf-8 -*-
"""「우리 아이」 탭에 산 글자를 붓는다 — 그릇의 화면 칸(<출력>.png.칸.json)을 읽어 앉힌다.

손좌표를 안 쓰는 규율은 앞 네 화면과 같다: **그릇을 옮기면 글이 따라와야 한다.**

🔑 달력 칸(`달력`)은 **단추 «중심»들의 바운딩 박스**다 — 5열 4행이므로
   열 i 중심 = 좌 + 폭·i/4 · 행 j 중심 = 위 + 높·j/3 으로 되돌린다.
   격자 좌표를 여기에 손으로 적지 않는 것이 요점이다(굽기가 간격을 바꾸면 글이 따라온다).

쓰기:  python 우리아이덧씌움.py 우리아이판_v1_그릇만 [없음|층별|전면]
       → 우리아이판_v1[_층별].png  +  대비 실측표
"""
import io, json, os, sys

import PIL.ImageChops as C
from PIL import Image, ImageDraw, ImageFilter, ImageFont

여기 = os.path.dirname(os.path.abspath(__file__))
굵 = r"C:\Windows\Fonts\malgunbd.ttf"
보통 = r"C:\Windows\Fonts\malgun.ttf"
키릴 = r"C:\Windows\Fonts\segoeui.ttf"   # ⚠맑은고딕엔 몽골 키릴 ө·ү 글리프가 없다(두부 실측)
잉크 = (0xFB, 0xF7, 0xF0)      # Paper
보조 = (0xED, 0xE7, 0xDC)      # Oat
보조2 = (0xC7, 0xBF, 0xB2)     # Stone

이름 = sys.argv[1] if len(sys.argv) > 1 else "우리아이판_v1_그릇만"
보조갈래 = sys.argv[2] if len(sys.argv) > 2 else "층별"   # 없음 | 층별 | 전면
바탕길 = os.path.join(여기, 이름 + ".png")
칸들 = json.load(io.open(바탕길 + ".칸.json", encoding="utf-8"))

im = Image.open(바탕길).convert("RGB")
W, H = im.size
d = ImageDraw.Draw(im)
기록 = []


def 글(x, y, 본문, 크기, 색, bold=True, 서체=None, 가운데=False, 오른쪽=False):
    f = ImageFont.truetype(서체 or (굵 if bold else 보통), 크기)
    if 가운데:
        x = int(x - d.textlength(본문, font=f) / 2)
    elif 오른쪽:
        x = int(x - d.textlength(본문, font=f))
    d.text((x, y), 본문, font=f, fill=색)
    return (x, y, 본문, 크기, bold, 서체)


카 = 칸들["요약"]
카높 = 카["아래"] - 카["위"]
안여백 = 124          # 앞 네 화면과 같은 좌여백 — 화면끼리 마진선이 갈리면 다른 앱이 된다
글좌 = 카["좌"] + 안여백

# ⚠몽골어는 **검수 전 표본**이다. 학부모 앱은 학생 앱보다 몽골어 비중이 크다 —
#   결제자가 부모이고, 부모는 한국어를 못 읽는 쪽이 많다(층별 규칙의 실제 시험대가 여기다).
몽 = {"제목": "Манай хүүхэд",
      "질문": "Гэртээ асуулт асууя",
      "탭0": "Манай хүүхэд", "탭1": "Тайлан", "탭2": "Мэдээ"}
전면 = 보조갈래 == "전면"
키릴줄 = 보조갈래 != "없음"

# ── 제목 ──
기록.append(("제목", 글(카["좌"] + 8, 카["위"] - (150 if not 전면 else 186), "우리 아이", 60, 잉크, True)))
if 전면:
    기록.append(("제목몽", 글(카["좌"] + 8, 카["위"] - 116, 몽["제목"], 30, 보조2, False, 서체=키릴)))

# ── ① 이번 주 요약 — 부1. 코랄 밑줄이 «집에서 물어볼 질문»을 가리킨다 ──────────
#   🔑 부1 은 「이번 주 요약」과 「집에서 물어볼 질문」 두 카드였다. 한 그릇에 담되
#      코랄은 **뒤쪽**에 선다 — 학부모가 실제로 «할» 것은 요약을 읽는 게 아니라 묻는 것이다.
밑줄y = 카["위"] + 카높 * 0.8429

y = 카["위"] + 70
기록.append(("라벨", 글(글좌, y, "이번 주", 34, 보조2, False)))
y += 62
for 줄 in ("「-고 있다」를 배웠고", "네 번 스스로 말했어요"):
    기록.append(("큰줄%d" % len([k for k, _ in 기록 if k.startswith("큰줄")]),
                 글(글좌, y, 줄, 56, 잉크, True)))
    y += 84
if 키릴줄:
    # 🔴**2판 실측 — 키릴 줄에 한국어를 섞으면 두부(□)가 뜬다.** `segoeui.ttf` 에는 한글 글리프가
    #   없어서 「-고 있다」가 «-□ □□» 로 찍혔다(맑은고딕에 키릴 ө·ү 가 없는 것의 정확한 반대).
    #   ⇒ 보조줄은 **한 문자 체계만** 쓴다. 문법 이름은 한국어 줄이 이미 말했으니 여기선 뺀다.
    기록.append(("요약몽", 글(글좌, y + 12, "Энэ долоо хоногт 4 удаа өөрөө ярьсан", 28, 보조2,
                            False, 서체=키릴)))

기록.append(("질문", 글(글좌, 밑줄y - 76, "집에서 물어보세요 — 「지금 뭐 하고 있어?」", 34, 보조, False)))

# ── ② 출석 4주 — 부2. 열 머리글과 주 설명 ─────────────────────────────────────
달 = 칸들["달력"]
열폭 = (달["우"] - 달["좌"]) / 4          # 5열 → 사이 넷
행높 = (달["아래"] - 달["위"]) / 3        # 4행 → 사이 셋
for i, 요일 in enumerate(("월", "화", "수", "목", "금")):
    기록.append(("요일%d" % i, 글(달["좌"] + 열폭 * i, 달["위"] - 74, 요일, 30, 보조2, False, 가운데=True)))
# 주 라벨 — 아래가 이번 주다. 왼쪽에 세로로 세우면 폭을 먹으므로 달력 아래 한 줄로 말한다.
기록.append(("주설명", 글(달["좌"], 달["아래"] + 52, "최근 4주 — 맨 아랫줄이 이번 주예요", 28, 보조2, False)))

# ── ③ 범례 — 실물 단추 «옆»에 뜻을 적는다 ────────────────────────────────────
#   ⚠글자로 ●·✕ 를 그리지 않는다(그릇이 이미 그려 뒀다). 여기서는 **뜻만** 붙인다.
for 번, 뜻 in enumerate(("학원에 온 날", "한국어로 말한 날")):
    범 = 칸들["범례%d" % 번]
    중 = (범["위"] + 범["아래"]) / 2
    기록.append(("범례%d" % 번, 글(범["우"] + 24, 중 - 20, 뜻, 28, 보조, False)))

# ── ④ 결석 미리 알리기 — 단추가 없는 줄이라 «눌러서 여는 것»이다 ──────────────
칸 = 칸들["보내"]
중 = (칸["위"] + 칸["아래"]) / 2
기록.append(("보내", 글(칸["좌"] + 안여백, 중 - 26, "결석 미리 알리기", 40, 보조, True)))
기록.append(("보내꼬리", 글(칸["우"] - (안여백 - 40), 중 - 16, "열기", 28, 보조2, False, 오른쪽=True)))

# ── ⑤ 탭바 글자 — 지금 탭만 밝고 나머지는 물러선다(4계 ②) ───────────────────
if "탭0" in 칸들:
    for 번, 이름표 in enumerate(("우리 아이", "리포트", "소식")):
        탭 = 칸들["탭%d" % 번]
        가 = (탭["좌"] + 탭["우"]) / 2
        중 = (탭["위"] + 탭["아래"]) / 2
        지금 = (번 == 0)
        기록.append(("탭%d" % 번, 글(가, 중 - 22, 이름표, 34, 보조 if 지금 else 보조2, 지금, 가운데=True)))
        if 전면:
            기록.append(("탭%d몽" % 번, 글(가, 중 + 20, 몽["탭%d" % 번], 24, 보조2, False,
                                        서체=키릴, 가운데=True)))

꼬리 = "" if 보조갈래 == "층별" else "_" + 보조갈래
낸것 = os.path.join(여기, "우리아이판_v1" + 꼬리 + ".png")
im.save(낸것)
print("구움:", os.path.basename(낸것))


# ── 대비 실측 — 앞 네 화면과 같은 잣대 ────────────────────────────────────────
def 상대휘도(r, g, b):
    def f(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def 대비(a, b):
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


바탕 = Image.open(바탕길).convert("RGB")
bl = 바탕.load()
색표 = {"라벨": 보조2, "질문": 보조, "요약몽": 보조2, "제목몽": 보조2, "주설명": 보조2,
        "범례0": 보조, "범례1": 보조, "보내": 보조, "보내꼬리": 보조2,
        "탭0": 보조, "탭1": 보조2, "탭2": 보조2}
색표.update({"요일%d" % i: 보조2 for i in range(5)})
색표.update({"탭%d몽" % i: 보조2 for i in range(3)})
print()
print("%-10s %10s %10s  %s" % ("블록", "평균대비", "최악대비", "판정"))
print("-" * 52)
최악 = "AAA"
for 표이름, (x, y, 본문, 크기, bold, 서체) in 기록:
    m = Image.new("L", 바탕.size, 0)
    dm = ImageDraw.Draw(m)
    f = ImageFont.truetype(서체 or (굵 if bold else 보통), 크기)
    dm.text((x, y), 본문, font=f, fill=255)
    고리 = C.subtract(m.filter(ImageFilter.MaxFilter(5)), m)
    gl = 고리.load()
    글색 = 색표.get(표이름, 잉크)
    L글 = 상대휘도(*글색)
    ls = []
    x0, y0 = max(0, int(x) - 20), max(0, int(y) - 20)
    x1, y1 = min(W, int(x) + 1000), min(H, int(y) + 크기 * 2 + 40)
    for yy in range(y0, y1):
        for xx in range(x0, x1):
            if gl[xx, yy] > 128:
                ls.append(상대휘도(*bl[xx, yy]))
    if not ls:
        continue
    ls.sort()
    평균 = 대비(L글, sum(ls) / len(ls))
    나쁨 = 대비(L글, ls[int(len(ls) * 0.95)])
    표 = "AAA" if 나쁨 >= 7 else ("AA" if 나쁨 >= 4.5 else "X")
    if 표 != "AAA":
        최악 = 표
    print("%-10s %9.2f %9.2f  %s" % (표이름, 평균, 나쁨, 표))
print("전체:", 최악)
