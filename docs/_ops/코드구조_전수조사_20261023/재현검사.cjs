const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
// 감사용 최소 재현: 실제 앱/네트워크/계정/DB를 실행하지 않는다.
const root = path.resolve(__dirname, '../../../..');
const app = fs.readFileSync(path.join(root, 'SYNK-talk/App.js'), 'utf8');
const match = app.match(/const 견줌읽기 = useCallback\(async \(\) => \{([\s\S]*?)\n  \}, \[세션\]\);/);
assert(match, 'Actual App callback not found');
const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;
const callback = new AsyncFunction('세션', '진행받기', 'set견줌값', match[1]);
const events = [];
let state = { owner: 'synthetic_A', value: 7 };
let resolveA;
const pendingA = new Promise(resolve => { resolveA = resolve; });
const read = token => token === 'synthetic_A' ? pendingA : Promise.resolve({ owner: 'synthetic_B', value: 0 });
const write = value => { state = value; events.push(value.owner); };
(async () => {
  const a = callback({ 학생번호: 'synthetic_A', access_token: 'synthetic_A' }, read, write);
  const beforeBResponse = state.owner;
  await callback({ 학생번호: 'synthetic_B', access_token: 'synthetic_B' }, read, write);
  assert.equal(state.owner, 'synthetic_B');
  resolveA({ owner: 'synthetic_A', value: 7 });
  await a;
  assert.equal(state.owner, 'synthetic_A');
  const tips = fs.readFileSync(path.join(root, 'synk-tips/site/assets/app.js'), 'utf8');
  const loader = tips.match(/  function load\(url\) \{([\s\S]*?)\n  \}/);
  assert(loader, 'Actual tips load function not found');
  let calls = 0;
  const context = vm.createContext({ fetch: async () => { calls++; if(calls === 1) throw Error('synthetic offline'); return { json: async () => [] }; } });
  vm.runInContext('var index = null, loading = null; function load(url) {' + loader[1] + '\n}; this.runLoad=load;', context);
  const first = context.runLoad('/synthetic-index.json');
  await first.catch(() => {});
  const second = context.runLoad('/synthetic-index.json');
  await second.catch(() => {});
  assert.equal(first, second);
  assert.equal(calls, 1);
  const result = { scope: 'Extracted current function bodies only; fake promises/fetch; no app/server/network execution', app_progress: { oldOwnerBeforeNewResponse: beforeBResponse, completionOrder: events, ownerAfterOldResponse: state.owner, result: 'stale A overwrites B' }, tips_search: { fetchCalls: calls, sameRejectedPromise: first === second, result: 'second attempt cannot recover without page reload' } };
  fs.writeFileSync(path.join(__dirname, '재현결과.json'), JSON.stringify(result, null, 2) + '\n');
  console.log(JSON.stringify(result));
})().catch(error => { console.error(error); process.exitCode = 1; });
