# 동료 판 조각표(src/face-map.json) — 동영상 안 말 덩어리를 범수 대사 자리에 맞춘다(소리 덩어리끼리 짝 · 안은 곧게, 현장노트 「Flow 진행컷을 다른 목소리에 입 맞출 때」).
# 조각: at~to(영화 초)를 판 src의 start부터 rate 빠르기로 튼다. 원본 재기: q3 말 0.58~2.70 · 2.88~4.55 · 4.72~6.26, c3 말 0.56~1.62 · 1.90~3.54 · 3.90~4.76 · 6.70~7.38(가운데 5.54~6.42는 되풀이라 안 씀), V2 말 1.48~2.36 · 4.06~4.90 · 7.58~8.88.
import json
P = []
def 조각(src, at, to, start, rate=1.0):
    P.append({"src": src, "at": round(at, 3), "to": round(to, 3), "start": round(start, 3), "rate": round(rate, 3)})
# 첫 사건: 「그거 어디 쓰려고?」 · 듣는 얼굴 · 「다들 뭐에 쓰는데?」 · 듣는 얼굴(「…몰라.」) — 「어제 뭐 물어봤어?」 「…오늘 점심 뭐 먹지.」는 휴대폰 쪽 판 — 피식
조각('V2', 2.08, 3.0, 1.44, 1.03)
조각('V2', 3.0, 4.07, 2.40, 1.0)
조각('V2', 4.07, 5.09, 4.02, 0.857)
조각('V2', 5.09, 5.65, 3.2, 1.0)
조각('V2', 7.93, 8.4, 6.3, 1.0)
# 질문 셋(n03 · n04 · n05) + 듣는 얼굴(p02 · p04) — 대답 「어… 가끔?」은 휴대폰 쪽 판
조각('q3', 8.4, 10.36, 0.52, 1.116)
조각('q3', 10.36, 10.91, 6.4, 1.0)
조각('q3', 10.91, 12.48, 2.84, 1.113)
조각('q3', 14.46, 16.11, 4.70, 0.9625)
조각('q3', 16.11, 16.76, 6.35, 1.0)
# 결론(n06) · 조건(n08 앞 「하나라도 예면,」 — 「그때 결제해.」는 얼굴 가까이, 원본 끝 자리에서 그림이 바뀐다)
조각('c3', 16.76, 17.95, 0.54, 0.97)
조각('c3', 21.34, 22.24, 3.87, 0.95)
P.append({"src": "c3", "at": 22.24, "to": 23.17, "start": 6.5, "rate": 0.95, "z": 1.32})
# 끝: 「그 돈으로」까지 얼굴 — 「점심이나 사.」는 점심 그림
조각('V2', 26.82, 27.27, 7.54, 1.08)
json.dump(P, open('src/face-map.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(len(P), '조각')
