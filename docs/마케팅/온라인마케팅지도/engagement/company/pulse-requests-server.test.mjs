test('files no draft points at are swept after a day, whatever crashed; files in use and fresh ones stay',async t=>{
  const f=await fixture(t),draft=await f.start(),{store}=f.app,dir=join(f.options.dataDir,'pulse-request-media');await f.upload(draft.csrf);
  const [used]=store.get('pulseRequests',draft.id).files,old=new Date(Date.now()-2*86400000);
  const orphan='00000000-0000-4000-8000-000000000001.png',part='00000000-0000-4000-8000-000000000002.part',fresh='00000000-0000-4000-8000-000000000003.png',foreign='keep-me.txt';
  for(const name of [orphan,part,fresh,foreign])await writeFile(join(dir,name),png);
  for(const name of [orphan,part,foreign,used.diskName])await utimes(join(dir,name),old,old);
  await f.app.pulseRequests.pruneDrafts();
  assert.deepEqual((await readdir(dir)).sort(),[used.diskName,fresh,foreign].sort());
});
test('a send that stopped halfway and was never tried again leaves nothing behind after 14 days, and removing a file takes the moved copy too',async t=>{
  const f=await fixture(t),draft=await f.start(),{store}=f.app,dir=join(f.options.dataDir,'pulse-request-media'),media=join(f.options.dataDir,'studio-media'),old=new Date(Date.now()-15*86400000).toISOString();
  await f.upload(draft.csrf);
  const row=store.get('pulseRequests',draft.id),[file]=row.files;
  await mkdir(media,{recursive:true});await rename(join(dir,file.diskName),join(media,file.diskName));
  const second=(await f.upload(draft.csrf,{name:'b.png',slot:'side'})).data.file;
  const secondDisk=store.get('pulseRequests',draft.id).files.find(item=>item.id===second.id).diskName;await rename(join(dir,secondDisk),join(media,secondDisk));
  assert.equal((await f.call('/pulse/api/request/media/'+second.id,{method:'DELETE',csrf:draft.csrf})).status,200);
  assert.equal((await readdir(media)).includes(secondDisk),false,'taken away means gone from both folders');
  store.put('pulseRequests',draft.id,{...store.get('pulseRequests',draft.id),status:'sending',sendingAt:old,sendingId:'stopped',updatedAt:old});
  await f.app.pulseRequests.pruneDrafts();
  assert.equal(store.get('pulseRequests',draft.id),null);
  assert.equal((await readdir(media)).includes(file.diskName),false);
  assert.equal((await readdir(dir)).includes(file.diskName),false);
});
