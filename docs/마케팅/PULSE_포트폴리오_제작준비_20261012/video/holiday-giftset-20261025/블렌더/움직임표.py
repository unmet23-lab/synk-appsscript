def cam_raw(film, orient, cut, t):
    c = path(BASE[(film, orient, cut[0])], t)
    ox, oy, oz = cam_offset(film, cut[0], t)
    tx, ty, tz = c["tgt"]
    return {**c, "tgt": (tx + ox, ty + oy, tz + oz)}


def cam_at(film, orient, cut, t):
    """컷 안 카메라. 모션 블러용 앞뒤 시각이 컷 밖이면 컷 안의 움직임을 곧게 늘려 쓴다(옆 컷 카메라와 섞이지 않게)."""
    lo, hi = cut[1] / FPS, (cut[2] - 1) / FPS
    if t < lo:
        a, b = cam_raw(film, orient, cut, lo), cam_raw(film, orient, cut, 2 * lo - t)
        return {k: _lerp(b[k], a[k], 2.0) for k in a}
    if t > hi:
        a, b = cam_raw(film, orient, cut, hi), cam_raw(film, orient, cut, 2 * hi - t)
        return {k: _lerp(b[k], a[k], 2.0) for k in a}
    return cam_raw(film, orient, cut, t)


def state(film, orient, f, dt=0.0):
    """프레임 f(+dt초)의 장면 값. u · 뚜껑 나감은 스톱모션이라 dt를 보지 않는다. 제품 · 금가루 시각은 컷 안으로 묶는다."""
    cut = cut_at(film, f)
    t = min(max(f / FPS + dt, cut[1] / FPS), (cut[2] - 1) / FPS)
    tq = (f // 2) * 2 / FPS
    jar = prod_of(film, "jar", t)
    amp = prod_of(film, "amp", t)
    return {
        "cut": cut[0], "scene": cut[3], "t": t, "f": f,
        "u": u_of(film, tq), "lid_out": lid_out_of(film, tq),
        "jar": jar, "amp": amp, "hero": HERO[film], "print_x": PRINT_X[film], "rim_fade": RIM_FADE[film],
        "cam": cam_at(film, orient, cut, f / FPS + dt) if cut[3] != "black" else None,
        "shutter": shutter_of(film, f / FPS),
        "samples": SAMPLES.get(cut[3], 64),
        "dust": DUST[film],
    }


