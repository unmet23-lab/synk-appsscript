def ease(kind, x):
    x = min(1.0, max(0.0, x))
    if kind == "lin":
        return x
    if kind == "in":        # 점점 빨라짐 — 휘둘러 나감
        return x ** 3
    if kind == "out":       # 빠르게 들어와 멎음
        return 1 - (1 - x) ** 3
    return x * x * (3 - 2 * x)   # "s"


def ramp(t, t0, t1, a, b, kind="s"):
    if t <= t0:
        return a
    if t >= t1:
        return b
    return a + (b - a) * ease(kind, (t - t0) / (t1 - t0))


def _lerp(a, b, x):
    if isinstance(a, tuple):
        return tuple(p + (q - p) * x for p, q in zip(a, b))
    return a + (b - a) * x


def path(keys, t):
    """keys = [(초, {값}, 다음 열쇠까지의 이음새)] — 빠진 값은 앞 열쇠에서 이어받는다."""
    full, cur = [], {}
    for tk, kv, e in keys:
        cur = {**cur, **kv}
        full.append((tk, dict(cur), e))
    if t <= full[0][0]:
        return full[0][1]
    for (t0, a, e), (t1, b, _) in zip(full, full[1:]):
        if t <= t1:
            x = ease(e, (t - t0) / (t1 - t0))
            return {k: _lerp(a[k], b[k], x) for k in a}
    return full[-1][1]


