def ease(kind, x):
    x = min(1.0, max(0.0, x))
    if kind == "lin":
        return x
    if kind == "in":
        return x ** 3
    if kind == "out":
        return 1 - (1 - x) ** 3
    if kind.startswith("exp"):      # 지수로 잦아듦(원본의 물러남 · 멎어 감): exp3 = (1 − e^(−3x)) / (1 − e^(−3))
        k = float(kind[3:] or 4)
        return (1 - math.exp(-k * x)) / (1 - math.exp(-k))
    if kind.startswith("acc"):      # 지수로 빨라짐: acc3
        k = float(kind[3:] or 4)
        return (math.exp(k * x) - 1) / (math.exp(k) - 1)
    return x * x * (3 - 2 * x)      # "s"


def ramp(t, t0, t1, a, b, kind="s"):
    if t <= t0:
        return a
    if t >= t1:
        return b
    return a + (b - a) * ease(kind, (t - t0) / (t1 - t0))


def _lerp(a, b, x):
    if isinstance(a, tuple):
        return tuple(p + (q - p) * x for p, q in zip(a, b))
    return a + (b - a) * x


def path(keys, t):
    """keys = [(초, {값}, 다음 열쇠까지의 이음새)] — 빠진 값은 앞 열쇠에서 이어받는다."""
    full, cur = [], {}
    for tk, kv, e in keys:
        cur = {**cur, **kv}
        full.append((tk, dict(cur), e))
    if t <= full[0][0]:
        return full[0][1]
    for (t0, a, e), (t1, b, _) in zip(full, full[1:]):
        if t <= t1:
            x = ease(e, (t - t0) / (t1 - t0))
            return {k: _lerp(a[k], b[k], x) for k in a}
    return full[-1][1]


def frame_w(c, orient="v"):
    """그 카메라의 겨냥 거리에서 화면 가로 폭(m)."""
    half = 18.0 / c["lens"] * (9 / 16 if orient == "v" else 1.0)
    return 2 * c["d"] * half


def truck(keys, anchors, t0, t1, orient="v", step=1 / 240):
    """옆 이동(m): 원본에서 잰 초당 화면 폭 %(로그 사이 보간)에 그 시각 화면 폭을 곱해 쌓는다. 돌려주는 것은 시각 → 이동 함수."""
    def rate(t):
        if t <= anchors[0][0]:
            return anchors[0][1]
        for (ta, ra), (tb, rb) in zip(anchors, anchors[1:]):
            if t <= tb:
                x = (t - ta) / (tb - ta)
                return math.exp(math.log(ra) + (math.log(rb) - math.log(ra)) * x)
        return anchors[-1][1]
    ts, xs = [t0], [0.0]
    t = t0
    while t < t1:
        tm = t + step / 2
        xs.append(xs[-1] + rate(tm) / 100 * frame_w(path(keys, tm), orient) * step)
        t += step
        ts.append(t)

    def at(tt):
        if tt <= t0:
            return 0.0
        if tt >= ts[-1]:
            return xs[-1]
        i = int((tt - t0) / step)
        f = (tt - ts[i]) / step
        return xs[i] + (xs[i + 1] - xs[i]) * f
    return at


