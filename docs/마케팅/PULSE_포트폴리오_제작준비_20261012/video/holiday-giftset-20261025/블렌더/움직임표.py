def cam_offset(film, cut, t):
    """옆 이동 겹: 세계 (x, y, z) 덧셈. 닫힘은 −전체에서 시작해 0에서 끝난다(상자가 오른쪽에서 들어와 가운데)."""
    x = y = z = 0.0
    if (film, cut) in TRUCKS:
        f, sign, a0, a1 = TRUCKS[(film, cut)]
        m = sign * f(min(max(t, a0), a1))
        if cut == "닫힘":
            m -= CLOSE_X
        dx, dy = TRUCK_DIR.get((film, cut), (1.0, 0.0))
        x, y = m * dx, m * dy
    if (film, cut) in CRANE:
        t0, _, t2, _, z2 = CRANE[(film, cut)]
        k = ramp(t, t0, t2, 0.0, z2, "lin")      # 원본 세로 흐름은 +12~16 %/초로 거의 일정(Fable 3차 P2-1 — 두 램프는 t1에서 멎었다)
        x += k * KNOT_UP[0]
        y += k * KNOT_UP[1]
    return x, y, z


