def cuts():
    src = json.load(open(SRC, encoding="utf-8"))["컷"]
    t, out = 0.0, []
    for s in src:
        n = s["컷"]
        c = C[n]
        L = c.get("길이") or s["길이"]
        out.append(dict(컷=f"C{n:02d}", 번호=n, 편=s["편"], 편컷=s["편컷"], 원본초=[s["시작초"], round(min(s["끝초"], s["시작초"] + L), 3)],
                        원본길이=s["길이"], 우리초=[round(t, 2), round(t + L, 2)], 길이=round(L, 2), 회상=n in FLASH,
                        화면=c["화면"], 카메라=c["카메라"], 빛=c["빛"], 말=[dict(누가=w, 대사=s_, 입=m) for w, s_, m in c["말"]],
                        입맞춤="있음" if any(m for _, _, m in c["말"]) else "없음", 소리=c["소리"], 제품=c["제품"], 얼굴=c["얼굴"], 글=c.get("글", ""),
                        원본그림=(s.get("원본첫프레임") or {}).get("첫", {}).get("그림", "")))   # 65 검은 화면은 첫 프레임 그림이 없다
        t += L
    return out


def table(cs):
    rows = ["| 컷 | 원본 컷(원본 초) | 우리 초(길이) | 우리 화면 | 카메라(원본 실측) | 빛 | 말 · 입 | 소리 | 제품 · 화면 글 |",
            "|---|---|---|---|---|---|---|---|---|"]
    for ep, name in (("시작", "시작 편"), ("끝", "끝 편")):
        part = [c for c in cs if c["편"] == ep]
        rows.append(f"| **{name} {part[-1]['우리초'][1] - part[0]['우리초'][0]:.2f}초 · {len(part)}컷** | | | | | | | | |")
        for c in part:
            say = " / ".join(f"{m['누가']} 「{m['대사']}」 · 입 {'보임' if m['입'] else '안 보임'}" for m in c["말"]) or "말 없음"
            extra = " · ".join(x for x in (c["제품"] if c["제품"] != "-" else "", c["글"]) if x) or "-"
            cut = c["컷"] + (" 〔회상〕" if c["회상"] else "")
            short = f" — 원본 {c['원본길이']:.2f}초에서 줄임" if abs(c["원본길이"] - c["길이"]) > 0.01 else ""
            rows.append(f"| {cut} | {c['번호']} ({c['원본초'][0]:.2f}–{c['원본초'][1]:.2f}) | {c['우리초'][0]:.2f}–{c['우리초'][1]:.2f} ({c['길이']:.2f}){short} | "
                        f"{c['화면']} | {c['카메라']} | {c['빛']} | {say} | {c['소리']} | {extra} |")
    return "\n".join(rows)


