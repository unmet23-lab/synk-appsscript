#!/usr/bin/env node
/* 검문 커버리지 시험 — 「우리 몽골어 검문이 «무엇을» 잡고 «무엇을» 못 잡나」를 센다.
 *
 * ■ 옆의 `몽골어검문.yaml` 과 «다른 것을» 잰다 — 헷갈리면 둘 다 못 쓴다.
 *   · `몽골어검문.yaml`  = **한 층**(문법 채점)을 **두 모델**에게 풀린다 → 「갈아탈까」를 답한다.
 *   · 이 파일           = **파이프라인 전부**를 **파손 종류별로** 통과시켜 본다 → 「무엇을 놓치나」를 답한다.
 *   앞의 것은 이 파일이 묻는 질문에 원리상 답할 수 없다(파이프라인을 안 돌린다).
 *
 * ■ 어떻게 재나
 *   한국어 원문을 «참»으로 고정하고 **몽골어만** 알려진 방식으로 부순다. 부순 것이 통과하면
 *   그 종류가 우리 맹점이다. 안 부순 것(대조군)이 걸리면 거짓 경보다 — 둘 다 재야 뜻이 있다.
 *
 * ■ 이 시험이 실제로 값을 한 날 (2026-09-02 · 이 파일이 태어난 까닭)
 *   일곱 중 여섯은 잡혔는데 **하나가 ✅통과 도장을 받고 나갔다** — 낱말 바꿔치기
 *   (шалгалтын→хуримын · 시험장→결혼식장). 역번역은 「왜냐하면 **결혼식장**에 AI 가 함께
 *   들어가지 않으니까」라고 글자 그대로 찍어 놨는데도 통과였다:
 *     문법층은 한국어 원문을 «안 보고», 맞춤법층에겐 хуримын 이 «실재하는 낱말»이라서.
 *   ⇒ 구멍은 「자가 모자라다」가 아니라 **「역번역↔원문을 뜻으로 대조하는 층이 없다」**였고,
 *     그 자리에 ⑤(codex 뜻 대조)를 세웠다. 다시 돌리니 그 문항이 exit 2 로 잡히고
 *     대조군은 그대로 통과했다(거짓 경보 0).
 *
 * ■ 🔴 손으로만 돌린다. 훅·CI 에 안 문다.
 *   한 문항이 제미나이 2회 + codex 1회를 쓴다. 일곱이면 스물한 번이라 벤더 한도를 태운다.
 *   자동으로 돌 자리가 아니다 — **검문기를 고친 뒤** 사람이 한 번 돌리는 자리다.
 *
 * 쓰는 법:  node evals/검문커버리지.js            (전부)
 *          node evals/검문커버리지.js 0 6        (문항 번호만 골라서 — 통과했던 것만 다시 볼 때)
 */
// <!-- 몽골어검문: 면제 · 여기 몽골어는 «일부러 부순» 시험 문항이다. 검문 대상 문안이 아니라 검문기를 재는 자다 -->
'use strict';
const { execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

/* 한국어 = 참. 절대 안 바꾼다. 성한 몽골어 = `docs/AI활용문안_몽골어_검수표` §4 초안. */
const KO = '저희는 그것을 막지 않습니다 — 대신 가르칩니다. 무엇을 AI에게 맡겨도 되고, 무엇은 내 손으로 해야 실력이 남는지. 시험장에는 AI가 같이 들어가지 않으니까요.';
const 성한것 = 'Бид үүнийг хориглодоггүй — харин зааж өгдөг. Юуг AI-д даалгаж болох вэ, юуг өөрийн гараар хийж байж чадвар үлдэх вэ. Учир нь шалгалтын танхимд AI хамт орохгүй шүү дээ.';

const 문항 = [
  { n: 0, 무엇: '(대조군 — 안 부쉈다)', 통과해야하나: true, mn: 성한것 },
  { n: 1, 무엇: '철자 한 글자(зааж → зaaж · 라틴 a 섞음)', 통과해야하나: false,
    mn: 성한것.replace('зааж', 'зaaж') },
  { n: 2, 무엇: '격어미 잘못(танхимд → танхимт)', 통과해야하나: false,
    mn: 성한것.replace('танхимд', 'танхимт') },
  { n: 3, 무엇: '뜻 반대 — 부정어 제거(хориглодоггүй → хориглодог)', 통과해야하나: false,
    mn: 성한것.replace('хориглодоггүй', 'хориглодог') },
  { n: 4, 무엇: '뜻 반대 — 「가르친다」를 「안 가르친다」로', 통과해야하나: false,
    mn: 성한것.replace('зааж өгдөг.', 'зааж өгдөггүй.') },
  { n: 5, 무엇: '어순 파손(첫 문장 뒤섞기)', 통과해야하나: false,
    mn: 'Хориглодоггүй үүнийг бид — өгдөг зааж харин. ' + 성한것.split('. ').slice(1).join('. ') },
  /* 🔴 이 문항이 2026-09-02 에 ⑤층을 낳았다. 문법이 «완벽한 채로» 딴 얘기가 되는 계열이고,
   *   AI 번역이 낯선 낱말을 그럴듯한 다른 낱말로 갈아 끼울 때 나는 무늬가 정확히 이것이다. */
  { n: 6, 무엇: '낱말 바꿔치기(шалгалтын → хуримын · 시험장→결혼식장)', 통과해야하나: false,
    mn: 성한것.replace('шалгалтын', 'хуримын') },
];

const 고른것 = process.argv.slice(2).filter((a) => /^\d+$/.test(a)).map(Number);
const 돌릴것 = 고른것.length ? 문항.filter((c) => 고른것.includes(c.n)) : 문항;
const 방 = fs.mkdtempSync(path.join(os.tmpdir(), 'synk-커버리지-'));
const 결과 = [];

for (const c of 돌릴것) {
  const f = path.join(방, `${c.n}.txt`);
  fs.writeFileSync(f, KO + '\n---\n' + c.mn, 'utf8');
  let out = '', code = 0;
  try {
    out = execFileSync('node', [path.join(ROOT, 'tools', '몽골어대조.js'), '--파일', f],
      { encoding: 'utf8', timeout: 300_000, windowsHide: true, maxBuffer: 16 * 1024 * 1024 });
  } catch (e) { out = String(e.stdout || ''); code = e.status == null ? -1 : e.status; }

  /* exit 0 = 통과 · 2 = 검수 필요 · 그 밖 = 실행 오류(둘 중 어느 쪽도 아니다 — 갈라 적는다). */
  const 통과 = code === 0;
  const 실행오류 = code !== 0 && code !== 2;
  const 맞나 = 실행오류 ? null : (통과 === c.통과해야하나);
  const 어느층 = [];
  if (/■ 문법[\s\S]*?판정:\s*(어색|파손)/.test(out)) 어느층.push('문법');
  if (/■ 맞춤법[\s\S]*?\n  ✖/.test(out)) 어느층.push('맞춤법');
  if (/■ 말투[\s\S]*?\n  ✖/.test(out)) 어느층.push('말투');
  if (/■ 뜻 대조[\s\S]*?\n  ✖/.test(out)) 어느층.push('뜻');
  결과.push({ ...c, 통과, 실행오류, 맞나, 어느층, 사유: (/■ 종합:.*?\((.*)\)\s*$/m.exec(out) || [, ''])[1] });
  process.stderr.write(`${c.n} ${맞나 === null ? '⚠실행오류' : 맞나 ? '✅' : '🔴'} (${통과 ? '통과' : '검수필요'}${어느층.length ? ' · ' + 어느층.join('+') : ''})\n`);
}

const 옳게 = 결과.filter((r) => r.맞나 === true).length;
const 오류 = 결과.filter((r) => r.맞나 === null).length;
const L = ['# 검문 커버리지 — 무엇을 잡고 무엇을 놓치나', '',
  `**${옳게} / ${결과.length} 옳게 판정**` + (오류 ? ` · ⚠ 실행오류 ${오류}(잰 것도 못 잰 것도 아니다)` : '') + '\n',
  '| # | 부순 방식 | 결과 | 운 층 | 맞나 |', '|---|---|---|---|---|'];
for (const r of 결과) {
  L.push(`| ${r.n} | ${r.무엇} | ${r.실행오류 ? '⚠실행오류' : r.통과 ? '통과' : '검수필요'} | ${r.어느층.join(' + ') || '—'} | ` +
    `${r.맞나 === null ? '⚠' : r.맞나 ? '✅' : (r.통과해야하나 ? '🔴 거짓경보' : '🔴 **놓쳤다**')} |`);
}
L.push('', '> 🔴 「놓쳤다」가 하나라도 있으면 **그 종류가 지금 우리 맹점**이다 — 층을 하나 더 세울 자리다.',
  '> 「거짓경보」는 반대 방향의 병이다: 자가 요란하면 사람이 자를 안 본다.');
const 표 = path.join(방, '커버리지.md');
fs.writeFileSync(표, L.join('\n'), 'utf8');
process.stderr.write(`\n표: ${표}\n`);
process.exit(결과.every((r) => r.맞나 === true) ? 0 : 2);
