// talk 쪽은 운영 v48 배포판 가지 머리(e13f6fe)의 lib/. 빌드 옵션은 tools/synk-personal-build.js의 build()와 같다.
// git 객체를 직접 읽어 쓴다(Windows tar의 한글 경로 문제를 피함).
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const app = 'C:/Users/q1212/Documents/SYNK-appsscript', talk = 'C:/Users/q1212/Documents/SYNK-talk';
const base = path.join(__dirname, 'build');
const extract = (repo, rev, prefixes, dest) => {
  const list = execFileSync('git', ['-C', repo, 'ls-tree', '-r', '-z', rev, '--', ...prefixes], { maxBuffer: 1 << 28 }).toString('utf8').split('\0').filter(Boolean);
  let n = 0;
  for (const row of list) {
    const [meta, file] = row.split('\t'); const [mode, type, oid] = meta.split(' ');
    if (type !== 'blob' || mode === '120000') continue;
    if (!/\.(mjs|js|cjs|json)$/.test(file)) continue;
    const out = path.join(dest, file); fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, execFileSync('git', ['-C', repo, 'cat-file', 'blob', oid], { maxBuffer: 1 << 28 })); n++;
  }
  return n;
};
const esbuild = require(path.join(app, 'experiences/synk-account/node_modules/esbuild'));
const build = (talkRoot, appRoot) => {
  const entry = `const model=require(${JSON.stringify(path.join(appRoot, 'experiences/synk-account/src/personal-data.mjs'))});module.exports={model,...require('./lib/synk-personal-store'),...require('./lib/synk-personal-server'),...require('./lib/synk-personal-media'),...require('./lib/synk-auth')};`;
  return esbuild.buildSync({ absWorkingDir: talkRoot, stdin: { contents: entry, resolveDir: talkRoot, sourcefile: 'synk-personal-entry.cjs' }, bundle: true, write: false, platform: 'neutral', format: 'cjs', target: 'es2022', charset: 'utf8',
    banner: { js: '// Generated by tools/synk-personal-build.js. Canonical account + product validators; no deployment.' } }).outputFiles[0].text;
};
fs.rmSync(base, { recursive: true, force: true });
const appPrefixes = ['atlas', 'experiences/synk-account/src', 'experiences/path-travel', 'experiences/path-vr', 'experiences/conversation-rehearsal', 'experiences/family-album'];
const out = {};
for (const [name, rev] of [['a', 'd951cd544~1'], ['b', 'origin/master']]) {
  const root = path.join(base, name), talkRoot = path.join(root, 'SYNK-talk'), appRoot = path.join(root, 'SYNK-appsscript');
  out[name] = { app: extract(app, rev, appPrefixes, appRoot), talk: extract(talk, 'e13f6fe', ['lib'], talkRoot) };
  const text = build(talkRoot, appRoot);
  fs.writeFileSync(path.join(__dirname, `bundle-${name}.js`), text);
  out[name].bytes = Buffer.byteLength(text);
}
