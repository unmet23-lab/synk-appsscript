const WORD = /[가-힣A-Za-z0-9]+/gu;
function tokenize(text) {
  const out = [];
  for (const match of text.matchAll(WORD)) out.push({ word: match[0], start: match.index, end: match.index + match[0].length });
  out.forEach((token, i) => {
    const gap = text.slice(token.end, i + 1 < out.length ? out[i + 1].start : text.length);
    token.pauseAfter = i === out.length - 1 || /[,，、…·.!?;:~—-]/u.test(gap);
    token.question = /\?/u.test(gap);
    token.prev = out[i - 1]?.word;
    token.next = out[i + 1]?.word;
  });
  return out;
}

const jong = char => { const code = char.charCodeAt(0) - 0xac00; return code >= 0 && code <= 11171 ? code % 28 : -1; };
// 「중요한 사실」·「그런 사실」처럼 꾸밈을 받는 「사실」은 군더더기가 아니다.
function adnominal(word) {
  if (['그', '이', '저'].includes(word)) return true;
  if (TOPIC_PRONOUNS.has(word) || word.endsWith('면')) return false;
  const last = word.at(-1);
  if (last === '는') return /(?:하|있|없|되|알|모르|믿|보|듣|느끼)는$/u.test(word);
  if (['은', '을', '를'].includes(last)) return false;
  return [4, 8].includes(jong(last));
}

function fillerOf(token) {
  const word = FILLER_BY_FORM.get(token.word);
  if (!word) return null;
  if (word === '그') return token.pauseAfter || GEU_NEXT.has(token.next) ? word : null;
  if (word === '막') return JUST.has(token.prev) ? null : word;
  if (word === '이제') return token.next === '막' ? null : word;
  if (word === '사실') return token.prev && adnominal(token.prev) ? null : word;
  if (word === '뭐') return token.question ? null : word;
  return word;
}

function countList(map) {
  return [...map.entries()].map(([word, value]) => ({ word, count: value.count, first: value.first })).sort((a, b) => b.count - a.count || a.first - b.first).map(({ word, count }) => ({ word, count }));
}
function bump(map, word, index) { const entry = map.get(word) || { count: 0, first: index }; entry.count += 1; map.set(word, entry); }

function stem(word) {
  for (const particle of PARTICLES) if (word.length - particle.length >= 2 && word.endsWith(particle)) return word.slice(0, -particle.length);
  return word;
}

export function habits(text) {
  const tokens = tokenize(text), fillers = new Map(), hedges = new Map(), absolutes = new Map(), words = new Map();
  tokens.forEach((token, i) => {
    const filler = fillerOf(token);
    if (filler) { bump(fillers, filler, i); return; }
    const hedge = HEDGE_BY_FORM.get(token.word);
    if (hedge) { bump(hedges, hedge, i); return; }
    const absolute = ABSOLUTE_BY_FORM.get(token.word);
    if (absolute) { bump(absolutes, absolute, i); return; }
    const base = stem(token.word);
    if (base.length < 2 || STOP.has(token.word) || STOP.has(base) || PREDICATE_END.test(base) || AUXILIARY.test(token.word) || AUXILIARY.test(base) || /^\d+$/u.test(base)) return;
    bump(words, base, i);
  });
  for (const { word, re } of HEDGES) for (const match of text.matchAll(re)) bump(hedges, word, match.index);
  for (const match of text.matchAll(/한\s?번도/gu)) bump(absolutes, '한 번도', match.index);
  const repeats = new Map([...words].filter(([, value]) => value.count >= 3));
  return { fillers: countList(fillers), hedges: countList(hedges), repeats: countList(repeats), absolutes: countList(absolutes) };
}

// ── 문장 나누기와 요소 찾기 ──────────────────────────────────────────
// 받아쓰기 글에는 마침표가 없을 때가 많아 「~요·~니다·~죠」 같은 끝말 뒤 띄어쓰기에서도 나눈다.
const SENTENCE_BREAK = /(?<=[.!?。！？…])\s+|\n+|(?:(?<=[가-힣](?:요|니다|죠))(?<!(?:필|중|수)요)|(?<=[가-힣]다)(?<!(?:보|마|바)다))\s+(?=[가-힣A-Za-z0-9"'“‘(])/u;
export function splitSentences(text) {
  return text.split(SENTENCE_BREAK).map(part => part.trim()).filter(Boolean);
}
const GREETING = /^(?:네[,.\s]|안녕하(?:세요|십니까)|반갑습니다|좋은 (?:아침|오후|저녁)|[^.!?\n]{0,20}(?:팀|부|실|파트|본부)\s?[가-힣]{2,4}입니다)/u;

function zoneOf(element, sentences, turnId) {
  if (element.zone === 'end') {
    if (turnId === 'close') return sentences;
    return sentences.length >= 2 ? [sentences.at(-1)] : [];
  }
  if (element.zone === 'start') {
    let start = 0;
    while (start < 2 && start < sentences.length - 1 && GREETING.test(sentences[start])) start += 1;
    return sentences.slice(start, start + 1);
  }
  return sentences;
}

const LIMIT = 60;
function clip(sentence, index, length) {
  if (sentence.length <= LIMIT) return sentence;
  let start = Math.max(0, index - 20), end = Math.min(sentence.length, start + LIMIT);
  if (end < index + length) { end = Math.min(sentence.length, index + length + 10); start = Math.max(0, end - LIMIT); }
  if (/[\udc00-\udfff]/u.test(sentence[start] || '')) start -= 1;
  if (/[\ud800-\udbff]/u.test(sentence[end - 1] || '')) end += 1;
  return `${start > 0 ? '…' : ''}${sentence.slice(start, end).trim()}${end < sentence.length ? '…' : ''}`;
}

function evidenceOf(element, sentences, turnId) {
  for (const sentence of zoneOf(element, sentences, turnId)) for (const pattern of element.patterns) {
    const match = pattern.exec(sentence);
    if (match) return clip(sentence, match.index, match[0].length);
  }
  return null;
}

const syllableCount = text => (text.match(/[가-힣]/gu) || []).length;

function checkScenario(scenario) { if (!Object.hasOwn(ELEMENTS, scenario)) throw new TypeError('연습할 상황을 확인해 주세요.'); }
function checkTurn(turnId) { if (turnId !== undefined && turnId !== null && !TURNS.includes(turnId)) throw new TypeError('대화 순서를 확인해 주세요.'); }

// found: 답에서 찾은 요소 전부(근거 문장 조각과 함께). missing: 이 턴의 질문이 묻는 요소 가운데 빠진 것(중요한 순서).
// turnId가 없으면 대화 전체를 본다고 보고 모든 필수 요소를 살핀다. 「가능할 때만 대안」처럼 선택 요소는 빠져도 missing에 넣지 않는다.
export function analyzeAnswer({ scenario, text, turnId } = {}) {
  checkScenario(scenario); checkTurn(turnId);
  const source = typeof text === 'string' ? text.normalize('NFC') : '';
  const sentences = splitSentences(source), found = [], missing = [];
  for (const element of ELEMENTS[scenario]) {
    const evidence = evidenceOf(element, sentences, turnId ?? null);
    if (evidence) found.push({ id: element.id, label: element.label, evidence });
    else if (!element.optional && (!turnId || element.turns.includes(turnId))) missing.push(element);
  }
  missing.sort((a, b) => a.priority - b.priority);
  return { scenario, turnId: turnId ?? null, found, missing: missing.map(({ id, label, why, example }) => ({ id, label, why, example })), ...habits(source), sentences: sentences.length, syllables: syllableCount(source) };
}

// 말한 시간과 빠르기(한글 음절/분). 판정은 하지 않는다. 비교는 화면이 「내 첫 기록 대비」로 한다.
export function speakingStats({ text, durationMs } = {}) {
  const seconds = Number.isFinite(durationMs) && durationMs > 0 ? Math.round(durationMs / 1000) : 0;
  const syllables = typeof text === 'string' ? syllableCount(text) : 0;
  return { seconds, syllablesPerMinute: Number.isFinite(durationMs) && durationMs >= 1000 && syllables > 0 ? Math.round(syllables * 60000 / durationMs) : null };
}

function hash(value) {
  let h = 2166136261;
  for (let i = 0; i < value.length; i++) { h ^= value.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

// 빠진 요소 가운데 가장 중요한 것을 짚는 상대의 되묻기 한 줄. 빠진 게 없으면 null.
// turnId는 상대가 이 줄을 말한 뒤 이어서 할 턴이다. 그 턴의 질문이 이미 묻는 요소는 뒤로 미뤄 같은 질문을 두 번 하지 않는다.
// seed(세션 id 등)를 넘기면 세션마다 다른 줄이 나오고, avoid에 이미 보여 준 줄을 넣으면 그 줄은 건너뛴다.
export function counterLine({ scenario, practice, missingIds = [], intensity = 'normal', turnId, seed = '', avoid = [] } = {}) {
  checkScenario(scenario); checkTurn(turnId);
  if (!INTENSITY_IDS.includes(intensity)) throw new TypeError('상대 반응 세기를 확인해 주세요.');
  if (!Array.isArray(missingIds)) throw new TypeError('빠진 요소 목록을 확인해 주세요.');
  const missing = ELEMENTS[scenario].filter(element => !element.optional && missingIds.includes(element.id)).sort((a, b) => a.priority - b.priority);
  if (!missing.length) return null;
  const fresh = turnId ? missing.filter(element => !element.turns.includes(turnId)) : missing;
  const target = (fresh.length ? fresh : missing)[0], lines = COUNTER_LINES[scenario][target.id][intensity];
  const who = practice && typeof practice === 'object' ? `${practice.counterpart ?? ''}/${practice.goal ?? ''}` : '';
  const start = hash(`${scenario}|${target.id}|${turnId ?? ''}|${who}|${seed}`) % lines.length;
  for (let i = 0; i < lines.length; i++) { const line = lines[(start + i) % lines.length]; if (!avoid.includes(line)) return line; }
  return lines[start];
}

const TURN_TIP = { opening: 0, specific: 1, concise: 1, pressure: 1, close: 2 };
const objectParticle = word => jong(word.at(-1)) > 0 ? '을' : '를';

// 이번 답에서 빠진 것만 짚는 팁 한 줄. 같은 요소라도 턴마다 다른 문장, avoid에 든 문장은 다시 내지 않는다.
// 빠진 요소가 없으면 말버릇(평가하는 말 → 군더더기 → 얼버무림 → 되풀이한 말) 순서로 보고, 짚을 게 없으면 null.
export function nextTip(analysis, { avoid = [] } = {}) {
  if (!analysis || typeof analysis !== 'object') throw new TypeError('먼저 답을 살펴봐 주세요.');
  checkScenario(analysis.scenario);
  const tips = TIPS[analysis.scenario], offset = TURN_TIP[analysis.turnId] ?? 0, candidates = [];
  for (const missing of analysis.missing || []) {
    const lines = tips[missing.id];
    if (lines) for (let i = 0; i < lines.length; i++) candidates.push(lines[(offset + i) % lines.length]);
  }
  const decline = analysis.scenario === 'refusal' && analysis.found?.find(item => item.id === 'decline');
  if (decline && /(?:것|거) 같|듯/u.test(decline.evidence)) candidates.push('거절하는 문장을 「~것 같아요」 없이 「어려워요」로 끝내면 더 분명하게 들려요.');
  const absolute = analysis.absolutes?.[0];
  if (absolute && ['feedback', 'apology'].includes(analysis.scenario)) candidates.push(`‘${absolute.word}’ 같은 말은 사실보다 평가로 들릴 수 있어요. 언제 무엇을 봤는지로 바꿔 보세요.`);
  const filler = analysis.fillers?.[0], fillerTotal = (analysis.fillers || []).reduce((sum, item) => sum + item.count, 0);
  if (filler && fillerTotal >= 2) candidates.push(`‘${filler.word}’${objectParticle(filler.word)} ${filler.count}번 썼어요. 그 자리에서 한 박자 쉬어 보세요.`, `‘${filler.word}’ 대신 잠깐 멈춰 보세요. 쉬는 틈이 생각할 시간을 줘요.`);
  const hedge = analysis.hedges?.[0], hedgeTotal = (analysis.hedges || []).reduce((sum, item) => sum + item.count, 0);
  if (hedge && hedgeTotal >= 2) candidates.push(`${analysis.hedges.map(item => `‘${item.word}’`).join('·')} 같은 얼버무리는 말이 ${hedgeTotal}번 나왔어요. 확실한 부분은 끝까지 단정해서 말해 보세요.`, `‘${hedge.word}’${objectParticle(hedge.word.replace(/[^가-힣]/gu, '') || '요')} 빼고 말해 보세요. 같은 내용도 더 단단하게 들려요.`);
  const repeat = analysis.repeats?.[0];
  if (repeat) candidates.push(`‘${repeat.word}’${objectParticle(repeat.word)} ${repeat.count}번 썼어요. 한 번은 다른 말로 바꿔 보세요.`);
  return candidates.find(tip => !avoid.includes(tip)) ?? null;
}
