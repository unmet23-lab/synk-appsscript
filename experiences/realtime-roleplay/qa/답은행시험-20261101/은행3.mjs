export const 반응표 = Object.fromEntries(반응들.map((r) => [r.id, r]));
const 고름 = (목록, 변형) => 목록[((변형 % 목록.length) + 목록.length) % 목록.length];
const 순간글 = (값, 단계id) => (Array.isArray(값) ? 값 : 값?.[단계id] || 값?.기본 || null);
export function 말목록(r, 단계id) { return r.말 || 순간글(r.순간별, 단계id); }
function 질문목록(r, 단계id) { return r.질문 ? 순간글(r.질문, 단계id) : null; }

/** 그 순간에 고를 수 있는 반응 — {id, 뜻, 예시, 예(그 순간에 실제로 틀 말)} */
export function 고를반응(단계id) {
  return 반응들.filter((r) => !r.순간 || r.순간.includes(단계id)).map((r) => ({
    id: r.id, 뜻: r.뜻, 예시: r.예시, 예: r.완결 ? 순간[단계id].한국어로[0] : 고름(말목록(r, 단계id), 0),
  }));
}

/** 하온 답 만들기 — 고른 반응(중심부터, 최대 둘) + 아직 안 들은 다음 미션의 이끔. 돌려줌: {글, 조각(녹음 줄들), 이끔미션}
 *  들은: 반응을 고르지 않았어도 학습자가 말한 미션(고르기가 알려 줌) — 반응이 둘로 모자라도 들은 것을 다시 묻지 않게(11-01 확정 뒤 더함: 「몽골 바트 · 노래 · 사인」에 이름을 또 물었다). */
// 3판: 두 조각에 겹치면 어색했던 말(2판 판정 — 「고마워요 … 고마워요」 · 「그럼요! … 그럼요!」 · 「짠! 짠!」 · 「안녕~ 안녕~」)
const 겹말 = ['고마워요', '헤헤', '그럼요', '좋아요', '짠', '안녕', '진짜요', '반가워요'];
const 겹침 = (a, b) => 겹말.some((k) => a.includes(k) && b.includes(k));
/** 목록에서 피할 글들과 안 겹치는 변형을 변형 번호부터 차례로 찾는다. 없으면 null */
function 안겹친변형(목록, 변형, 피할) {
  for (let k = 0; k < 목록.length; k++) { const t = 고름(목록, 변형 + k); if (!피할.some((p) => 겹침(t, p))) return t; }
  return null;
}

export function 조립(단계id, ids, 변형 = 0, 들은 = []) {
  let rs = ids.slice(0, 최대반응).map((id) => 반응표[id]).filter(Boolean);
  if (!rs.length) throw new Error(`고른 반응이 없다: ${ids.join(',')}`);
  if (rs.some((r) => r.완결)) { const 글 = 고름(순간[단계id].한국어로, 변형); return { 글, 조각: [글], 이끔미션: null }; }
  const 끝난 = new Set([...끝난미션[단계id], ...rs.flatMap((r) => r.미션 || []), ...들은]); // 뺀 반응이 들은 미션도 남긴다
  if (rs.length > 1) rs = rs.filter((r) => !r.혼자만); // 인사는 혼자일 때만(「와, 이름 예뻐요! 네, 안녕하세요!」 순서가 어색했다)
  if (!rs.length) rs = [반응표[ids[0]]];
  if (rs.length > 1 && rs[1].둘째안됨) rs = [rs[0]];
  let 이끔말; let 이끔미션;
  if (단계id === '끝') { 이끔미션 = '마무리'; 이끔말 = rs.some((r) => r.긴마무리) ? 이끔.마무리길게[0] : 이끔.마무리짧게[0]; }
  else if (단계id === '작별뒤') { 이끔미션 = '작별'; 이끔말 = 고름(이끔.작별, 변형); }
  else {
    이끔미션 = 이끔순서.find((m) => !끝난.has(m)) || '사인끝';
    const 내질문 = 이끔미션 === 순간미션[단계id] ? rs.map((r) => 질문목록(r, 단계id)).find(Boolean) : null;
    이끔말 = 내질문 ? 고름(내질문, 변형) : 고름(이끔[이끔미션], rs.some((r) => r.이끔변형) ? 1 : 변형);
  }
  // 첫 조각: 이끔과 안 겹치는 변형이 있으면 그것을, 없으면 원래대로. 둘째 조각: 첫 조각 · 이끔과 안 겹치는 변형, 없으면 둘째 반응을 뺀다
  const 첫목록 = 말목록(rs[0], 단계id);
  const 조각 = [안겹친변형(첫목록, 변형, [이끔말]) || 고름(첫목록, 변형)];
  if (rs[1]) { const 둘 = 안겹친변형(말목록(rs[1], 단계id), 변형 + 1, [조각[0], 이끔말]); if (둘) 조각.push(둘); }
  return { 글: [...조각, 이끔말].join(' '), 조각: [...조각, 이끔말], 이끔미션 };
}

export function 되묻기(단계id) { return 순간[단계id].되묻기; }

/** 녹음할 줄 수(겹치는 문장은 한 번) */
export function 녹음줄수() {
  const 줄 = new Set();
  for (const r of 반응들) {
    if (r.말) r.말.forEach((t) => 줄.add(t));
    if (r.순간별) Object.values(r.순간별).flat().forEach((t) => 줄.add(t));
    if (Array.isArray(r.질문)) r.질문.forEach((t) => 줄.add(t)); else if (r.질문) Object.values(r.질문).flat().forEach((t) => 줄.add(t));
  }
  Object.values(이끔).flat().forEach((t) => 줄.add(t));
  for (const s of Object.values(순간)) { s.되묻기.forEach((t) => 줄.add(t)); s.한국어로.forEach((t) => 줄.add(t)); }
  return 줄.size;
}
