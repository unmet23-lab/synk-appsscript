/** 그 순간에 고를 수 있는 묶음 전부 — {id, 뜻, 예시, 답(그대로 틀 문장들)} */
export function 묶음들(단계id) {
  const s = 순간[단계id];
  if (!s) throw new Error(`모르는 순간: ${단계id}`);
  const 공통들 = 공통
    .filter((g) => !s.빼는공통.includes(g.id))
    .map((g) => ({ id: g.id, 뜻: g.뜻, 예시: g.예시, 답: g.한국어로 ? s.한국어로 : g.머리.map((h) => `${h} ${꼬리[단계id]}`) }));
  return [...s.묶음.map(({ id, 뜻, 예시, 답 }) => ({ id, 뜻, 예시, 답 })), ...공통들];
}

export function 되묻기(단계id) { return 순간[단계id].되묻기; }

/** 녹음할 줄 수(겹치는 문장은 한 번) — 공통 머리와 꼬리는 따로 굽고 문장 경계에서 잇는다 */
export function 녹음줄수() {
  const 줄 = new Set();
  for (const [id, s] of Object.entries(순간)) {
    s.묶음.forEach((b) => b.답.forEach((t) => 줄.add(t)));
    s.되묻기.forEach((t) => 줄.add(t));
    s.한국어로.forEach((t) => 줄.add(t));
    줄.add(꼬리[id]);
  }
  공통.forEach((g) => (g.머리 || []).forEach((t) => 줄.add(t)));
  return 줄.size;
}
