/** Gemini generateContent 몸통 — 소리(wav)를 듣고 받아적기 · 판단 · 반응 · 들은것 · 확신을 JSON으로 */
export function 듣기본문(순간, wav) {
  const d = 단계[순간];
  const 목록 = 은행.고를반응(순간);
  const 줄 = 목록.map((r) => `- ${r.id} — ${r.뜻} / 예: ${r.예시.join(' · ')} / 하온 반응 예: 「${r.예}」`).join('\n');
  return {
    systemInstruction: { parts: [{ text: 지시 }] },
    contents: [{ role: 'user', parts: [
      { text: `지금 순간: ${d.상황}\n하온이 방금 한 말: 「${d.앞말}」\n\n반응(id — 학습자 말의 뜻 / 학습자 말 예 / 하온 반응 예):\n${줄}\n\n아래 소리가 학습자가 방금 한 말이다.` },
      { inlineData: { mimeType: 'audio/wav', data: Buffer.from(wav).toString('base64') } },
    ] }],
    generationConfig: {
      temperature: 0,
      responseMimeType: 'application/json',
      responseSchema: {
        type: 'OBJECT', required: ['받아적기', '판단', '반응', '들은것', '확신'],
        properties: {
          받아적기: { type: 'STRING' },
          판단: { type: 'STRING', enum: ['고름', '되묻기'] },
          반응: { type: 'ARRAY', items: { type: 'STRING', enum: 목록.map((r) => r.id) } },
          들은것: { type: 'ARRAY', items: { type: 'STRING', enum: 은행.들을미션 } },
          확신: { type: 'NUMBER' },
        },
      },
    },
  };
}

/** 소리 한 차례 → {받아적기, 판단, 반응, 들은것, 확신, 모델, ms, 사용, 건넘}. 모델이 몫 · 과부하(429 · 503) · 8초 넘김이면 다음 모델로
 *  (쉼을 주면 8초를 넘긴 모델은 10분 동안 맨 뒤로 — 공급사.mjs 제미나이부르기).
 *  모델 답은 그대로 믿지 않는다 — 그 순간에 없는 반응 · 미션은 버리고, 남은 반응이 없으면 되묻기 */
export async function 듣고고르기(순간, wav, { 키, 모델들 = 듣기모델들, 시한ms = 8000, 쉼 = null } = {}) {
  if (!단계[순간]) throw Object.assign(new Error(`모르는 순간: ${순간}`), { 상태: 400 });
  const { 출력: o, 모델, ms, 사용, 건넘 } = await 제미나이부르기(듣기본문(순간, wav), { 모델들, 키, 시한ms, 쉼 });
  const 허용 = new Set(은행.고를반응(순간).map((r) => r.id));
  const 반응 = [...new Set(Array.isArray(o.반응) ? o.반응 : [])].filter((id) => 허용.has(id)).slice(0, 은행.최대반응);
  const 판단 = o.판단 === '고름' && 반응.length ? '고름' : '되묻기';
  // 사인은 부탁.사인 · 부탁.사인덧붙임을 고른 차례에만 들은 것으로 친다 — 사인 부탁은 늘 그 반응으로 받으니, 반응 없이 「사인」만 들었다는 것은
  // 잘못 들은 것이다(11-02 「사진 같이 찍어도 돼요?」를 사인으로 넣어 하온이 부탁받지 않은 사인을 「짠! 다 됐어요」로 끝냈다 — 장면의 중심 미션)
  const 들은것 = [...new Set(Array.isArray(o.들은것) ? o.들은것 : [])].filter((m) => 은행.들을미션.includes(m))
    .filter((m) => m !== '사인' || 반응.some((id) => id.startsWith('부탁.사인')));
  return { 받아적기: String(o.받아적기 || '').trim().slice(0, 300), 판단, 반응: 판단 === '고름' ? 반응 : [], 들은것, 확신: Number(o.확신) || 0, 모델, ms, 사용, 건넘 };
}

/** 고른 것 → 하온 답 조각(글 · 소리 주소)과 다음 순간. 되묻기는 그 순간의 되묻기 줄(차례마다 돌려 쓴다) */
export function 답짓기(순간, 고름, 변형 = 0) {
  if (고름.판단 === '고름') {
    const r = 은행.조립(순간, 고름.반응, 변형, 고름.들은것 || []);
    return { 조각: 조각들(r.조각), 다음순간: 다음순간표[r.이끔미션] || 순간 };
  }
  const 줄 = 은행.되묻기(순간);
  return { 조각: 조각들([줄[변형 % 줄.length]]), 다음순간: 되묻기다음[순간] || 순간 };
}

/** 학습자가 8초쯤 말이 없을 때 — 그 순간의 되묻기 줄(천천히 다시 묻기). 사인을 다 해 준 「끝」에서는 기다리지 않고 작별로 */
export function 침묵도움(순간, 변형 = 0) {
  if (순간 === '끝') return { 조각: 조각들([은행.이끔.마무리길게[0]]), 다음순간: '작별뒤' };
  if (!은행.순간[순간] || 순간 === '작별뒤') return { 조각: [], 다음순간: 순간 };
  const 줄 = 은행.되묻기(순간);
  return { 조각: 조각들([줄[변형 % 줄.length]]), 다음순간: 순간 };
}

/** 시간 상한 20초 전 — 하온이 먼저 마무리하고(「아쉽지만 오늘은 시간이 다 됐어요.」 + 긴 마무리) 작별을 기다린다. 이미 작별 순간이면 말하지 않는다 */
export function 시간마무리(순간) {
  if (['작별뒤', '끝남'].includes(순간)) return { 조각: [], 다음순간: 순간 };
  return { 조각: 조각들([시간끝, 은행.이끔.마무리길게[0]]), 다음순간: '작별뒤' };
}
