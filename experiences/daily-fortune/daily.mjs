function jitter(seed, field) {
  const value = hash(`${seed}/${field}`) % 4;
  return value === 0 ? -1 : value === 3 ? 1 : 0;
}

function sajuBasis(relation, mine, today) {
  const t = `오늘 일진의 ${today.name}${josa(today.name, '이', '가')}`;
  const m = `내 일간 ${mine.name}`;
  if (relation === 'same') return `${t} ${m}${josa(mine.name, '과', '와')} 같은 ${mine.element} 기운이라 내 리듬대로 가기 좋은 날이에요.`;
  if (relation === 'supported') return `${t} ${m}${josa(mine.name, '을', '를')} 살려 주는 날이에요.`;
  if (relation === 'expressing') return `${m}${josa(mine.name, '이', '가')} 오늘 일진의 ${today.name}${josa(today.name, '을', '를')} 키워 주는 날이라 표현이 잘 풀려요.`;
  if (relation === 'organizing') return `${m}${josa(mine.name, '이', '가')} 오늘 일진의 ${today.name}${josa(today.name, '을', '를')} 다스리는 날이라 정리가 잘돼요.`;
  return `${t} ${m}${josa(mine.name, '을', '를')} 다듬어 주는 날이라 천천히 가면 좋아요.`;
}

function westernBasis(relation, sign, own, day) {
  const opening = `오늘은 ${day.label} 기운이 도는 날이라,`;
  if (relation === 'same') return `${opening} 같은 ${own.label} 별자리인 ${sign}${josa(sign, '과', '와')} 잘 맞아요.`;
  if (relation === 'complement') return `${opening} ${own.label} 별자리인 ${sign}에게 힘을 보태 줘요.`;
  if (relation === 'neutral') return `${opening} ${own.label} 별자리인 ${sign}에게는 무난하게 흘러가요.`;
  return `${opening} ${own.label} 별자리인 ${sign}${josa(sign, '은', '는')} 속도를 조금 늦추면 편안해요.`;
}

/** 날짜별 「오늘의 원소」(별자리용). 4일 묶음마다 네 원소를 한 번씩 섞은 순서로 둔다. */
export function westernDayElement(date) {
  const day = dayNumber(date), block = Math.floor(day / 4);
  const order = shuffledOrder(4, `western-day/${block}`);
  return { element: WESTERN_ELEMENTS[WESTERN_ELEMENT_IDS[order[mod(day, 4)]]], block };
}

function koreanCard(saju, date) {
  const shape = sajuShape(saju);
  if (!shape) return null;
  if (shape.birthDate && date < shape.birthDate) throw new RangeError('출생일 이전 날짜예요.');
  const day = dayNumber(date), today = dayPillar(date);
  const relation = elementRelation(shape.stem.element, today.stem.element);
  const cycle = Math.floor((day + 17) / 10);
  const k = 2 * cycle + (today.stem.index % 2);
  const seed = `saju/${shape.birthDate}/${shape.birthTime ?? '?'}`;
  const pools = SAJU_POOLS[relation], base = SAJU_RELATIONS[relation];
  const branch = branchRelation(shape.branch, today.branch);
  // 일지와 오늘 지지가 육합이면 한 칸 올리고 충이면 한 칸 내린다. 삼합은 애정 칸만 올린다.
  const shift = branch === 'sixHarmony' ? 1 : branch === 'clash' ? -1 : 0;
  const daySeed = `${seed}/${date}`;
  const overall = clamp(base.overall + shift, 2, 5);
  const levels = { overall };
  for (const field of ['love', 'money', 'work']) {
    levels[field] = clamp(base[field] + shift + (field === 'love' && branch === 'threeHarmony' ? 1 : 0) + jitter(daySeed, field), 2, 5);
  }
  const luckChoices = [generatingOf(shape.stem.element), shape.stem.element, generatedBy(shape.stem.element)];
  const luckyElement = luckChoices[hash(`${daySeed}/luck`) % 3];
  const [colorName, hex] = SAJU_COLORS[luckyElement][hash(`${daySeed}/color`) % 3];
  const numbers = ELEMENT_NUMBERS[luckyElement];
  const hours = BRANCHES.filter(item => item.element === luckyElement && TIME_LABELS[item.index]);
  const tag = tagFor(overall);
  return {
    date, mode: 'korean', weekday: weekdayOf(date), relation, label: base.label, tag, tagLabel: tag ? TAGS[tag] : null,
    headline: rotationPick(pools.headlines, `${seed}/headline/${relation}`, k),
    message: rotationPick(pools.messages, `${seed}/message/${relation}`, k),
    levels, do: rotationPick(pools.do, `${seed}/do/${relation}`, k), dont: rotationPick(pools.dont, `${seed}/dont/${relation}`, k),
    luckyColor: { name: colorName, hex }, luckyNumber: numbers[hash(`${daySeed}/number`) % numbers.length],
    luckyItem: rotationPick(pools.items, `${seed}/item/${relation}`, k),
    luckyTime: TIME_LABELS[hours[hash(`${daySeed}/time`) % hours.length].index],
    basis: sajuBasis(relation, shape.stem, today.stem), note: NOTES.korean,
    signId: null, signLabel: `${shape.stem.name} 일간`, birthDate: shape.birthDate, birthTime: shape.birthTime,
    dayMaster: { hanja: shape.stem.hanja, name: shape.stem.name, image: shape.stem.image },
    dayPillar: { hanja: today.hanja, hangul: today.hangul }, luckyElement,
  };
}

function westernCard(signId, date) {
  const profile = getZodiacProfile(signId);
  const own = signElement(signId);
  const { element: dayElement, block } = westernDayElement(date);
  const relation = westernRelation(own.id, dayElement.id);
  const seed = `western/${signId}`, daySeed = `${seed}/${date}`;
  const pools = WESTERN_POOLS[dayElement.id], base = WESTERN_RELATIONS[relation];
  // 여섯 날에 한 번꼴로 총운을 한 칸 낮춰 같은 원소 별자리끼리도 흐름이 조금씩 다르게 한다.
  const overall = clamp(base.overall - (hash(`${daySeed}/overall`) % 6 === 0 ? 1 : 0), 2, 5);
  const levels = { overall };
  for (const field of ['love', 'money', 'work']) {
    levels[field] = clamp(base.overall - 1 + (WESTERN_FLAVOR[dayElement.id] === field ? 1 : 0) + jitter(daySeed, field), 2, 5);
  }
  const [colorName, hex] = WESTERN_COLORS[dayElement.id][hash(`${daySeed}/color`) % 3];
  const tag = tagFor(overall);
  return {
    date, mode: 'western', weekday: weekdayOf(date), relation, label: base.label, tag, tagLabel: tag ? TAGS[tag] : null,
    headline: rotationPick(pools.headlines, `${seed}/headline/${dayElement.id}`, block),
    message: rotationPick(pools.messages, `${seed}/message/${dayElement.id}`, block),
    levels, do: rotationPick(pools.do, `${seed}/do/${dayElement.id}`, block), dont: rotationPick(pools.dont, `${seed}/dont/${dayElement.id}`, block),
    luckyColor: { name: colorName, hex }, luckyNumber: hash(`${daySeed}/number`) % 9 + 1,
    luckyItem: rotationPick(pools.items, `${seed}/item/${dayElement.id}`, block), luckyTime: null,
    basis: westernBasis(relation, profile.label, own, dayElement), note: NOTES.western,
    signId, signLabel: profile.label, birthDate: null, birthTime: null,
    signElement: { ...own }, dayElement: { ...dayElement },
  };
}

/**
 * 오늘 카드.
 * @param {{ mode: 'western'|'korean', signId?: string, saju?: object, date?: string }} options
 * @returns 카드 객체(얼림). 사주 일간이 유보되면 null.
 */
export function getDailyCard({ mode, signId, saju, date = seoulDateKey() } = {}) {
  if (!['western', 'korean'].includes(mode)) throw new TypeError('한국 사주와 별자리 운세 중 하나를 골라 주세요.');
  assertSupportedDate(date);
  const card = mode === 'korean' ? koreanCard(saju, date) : westernCard(signId, date);
  return card && deepFreeze(card);
}
