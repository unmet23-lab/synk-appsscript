/** 마지막 글자에 받침이 있나(한글 음절만 본다) */
export const 받침있음 = (글) => { const c = 글.codePointAt(글.length - 1) - 0xac00; return c >= 0 && c < 11172 && c % 28 !== 0; };
/** 반말 부름 꼬리 — 받침 있으면 「아」, 없으면 「야」(「자수르」의 「르」는 받침 없음 → 「야」) */
export const 부름꼬리 = (이름) => (받침있음(이름) ? '아' : '야');

// 2판(11-02 둘째, 코디 요청): 첫 판에서 선배 부름이 「아/야」와 뭉개진 이름(마이 · 투안 · 자수르)과 귀마다 갈린 엥흐진을
// 「아/야」 없이 「○○! 여기야!」로 부른다. 꼬리표는 부르는 힘이 나게 1화 줄 가운데 사람을 부르는 말에 쓴 [cheerful]
