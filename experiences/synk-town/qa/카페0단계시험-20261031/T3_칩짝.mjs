if (process.argv[1]?.endsWith('T3_칩짝.mjs')) {
  const 뿌리 = path.join(밖뿌리, 'T3칩');
  fs.mkdirSync(뿌리, { recursive: true });
  for (const 누구 of Object.keys(판표)) {
    const 폴더 = path.join(뿌리, 누구);
    if (fs.existsSync(폴더) && fs.readdirSync(폴더).some((f) => f.startsWith('답'))) {
      console.error(`[T3칩] 답이 든 폴더는 덮지 않는다: ${폴더}`);
      process.exit(2);
    }
  }
  const 표지 = path.join(뿌리, '_표지.jpg');
  await 화면찍기([{ 파일: 표지, 블록: [{ 꼴: '머리', 왼: '종이 시제품', 오른: '한 판' }, { 꼴: '제목', 글: '한국어 공부 앱의 나흘' }, { 꼴: '작은글', 글: '글은 말.txt에 있어요.' }] }]);
  for (const [누구, 판] of Object.entries(판표)) {
    const 폴더 = path.join(뿌리, 누구);
    fs.rmSync(폴더, { recursive: true, force: true });
    fs.mkdirSync(폴더, { recursive: true });
    fs.writeFileSync(path.join(폴더, '말.txt'), `${판짝[판]}\n`);
    fs.writeFileSync(path.join(폴더, '질문.md'), 질문글());
    fs.copyFileSync(표지, path.join(폴더, '정지컷_01.jpg'));
  }
  fs.writeFileSync(path.join(뿌리, '판.json'), JSON.stringify(판표, null, 2) + '\n');
  console.log('[T3칩] 시험관 여섯 폴더 →', 뿌리);
}
