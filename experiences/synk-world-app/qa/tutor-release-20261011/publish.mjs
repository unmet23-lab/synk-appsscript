import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const work=path.resolve('.tmp/tutor-release-20261011'),repo='C:/Users/q1212/Documents/synk-policy';
const plan=JSON.parse(fs.readFileSync(path.join(work,'candidate.json'))),apply=process.argv.includes('--apply');
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const git=(args,options={})=>execFileSync('git',['-C',repo,...args],{encoding:'utf8',maxBuffer:20e6,windowsHide:true,...options});
const current=execFileSync('gh',['api','repos/unmet23-lab/synk-policy/branches/main','--jq','.commit.sha'],{encoding:'utf8',windowsHide:true}).trim();
assert.equal(current,plan.baseline,'Public parent advanced; compare before publishing');
assert.equal(plan.referenceMissing.length,0);
assert.ok(plan.changes.every(e=>e.path.startsWith('world/')&&!e.path.split('/').some(x=>['qa','tests','node_modules','docs'].includes(x))));
for(const e of plan.changes)assert.equal(sha(fs.readFileSync(path.join(plan.payload,e.path))),e.sha256,e.path);
const switchReport=JSON.parse(fs.readFileSync('experiences/synk-world-app/qa/tutor-switch-20261011/release-candidate-20261012/report.json'));
const homeReport=JSON.parse(fs.readFileSync('experiences/synk-world-app/qa/home-expressions-20261011/release-candidate-20261012/report.json'));
assert.ok(switchReport.checks.every(c=>c.pass));assert.ok(!switchReport.failure);assert.ok(homeReport.checks.every(c=>c.pass));assert.ok(!homeReport.failure);
const env={...process.env,GIT_INDEX_FILE:path.join(work,'publish.index')};
git(['read-tree',plan.baseline],{env});
const names=plan.changes.map(e=>path.join(plan.payload,e.path).replaceAll('\\','/'));
const oids=git(['hash-object','-w','--no-filters','--stdin-paths'],{input:names.join('\n')+'\n'}).trim().split('\n');
assert.equal(oids.length,plan.changes.length);
for(let i=0;i<oids.length;i++)assert.equal(oids[i],plan.changes[i].blob,plan.changes[i].path);
git(['update-index','-z','--index-info'],{env,input:plan.changes.map((e,i)=>`100644 ${oids[i]}\t${e.path}\0`).join('')});
const tree=git(['write-tree'],{env}).trim();
const diffs=git(['diff','--name-only','-z',plan.baseline,tree]).split('\0').filter(Boolean).sort();
assert.deepEqual(diffs,plan.changes.map(e=>e.path).sort());
assert.equal(git(['diff','--name-only','--diff-filter=D',plan.baseline,tree]).trim(),'');
const message=path.join(work,'release-message.txt');fs.writeFileSync(message,'Publish WORLD mascot tutors, guided practice and expression corrections\n\nConnect the chosen tutor across Maru, games, daily Korean and cafe practice.\nPreserve existing account and wardrobe runtime; add approved primary Hangul clips required by guided listening.\nSource: SYNK-appsscript 4e57536c0.\n');
const commit=git(['commit-tree',tree,'-p',plan.baseline,'-F',message]).trim();
const receipt={createdAt:new Date().toISOString(),repository:'unmet23-lab/synk-policy',parent:plan.baseline,commit,tree,sourceCommit:plan.sourceCommit,changedFiles:plan.changes.length,deleted:0,sharedCheckoutWrites:0,forcePush:false,published:false,candidate:plan.payload};
fs.writeFileSync(path.join(work,'publication.json'),JSON.stringify(receipt,null,2)+'\n');
if(apply){
 const games=JSON.parse(fs.readFileSync('experiences/synk-world-app/qa/tutor-release-20261011/candidate-games/report.json'));
 assert.equal(games.ok,true,'Game component verification must pass');
 const latest=execFileSync('gh',['api','repos/unmet23-lab/synk-policy/branches/main','--jq','.commit.sha'],{encoding:'utf8',windowsHide:true}).trim();assert.equal(latest,plan.baseline);
 process.stdout.write(git(['push','origin',commit+':refs/heads/main']));
 receipt.published=true;receipt.publishedAt=new Date().toISOString();fs.writeFileSync(path.join(work,'publication.json'),JSON.stringify(receipt,null,2)+'\n');
}
console.log(JSON.stringify(receipt));
