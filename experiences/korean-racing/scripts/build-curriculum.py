# A/B are source learning bands, not TOPIK levels. Count unique spellings here.
by_word = {}
for row in sorted(source, key=lambda r: (r['grade'], r['rank'])):
    if row['grade'] in ('A', 'B'):
        by_word.setdefault(row['word'], row)
selected = []
topic_rows = []
for title, text, mode in topics:
    group = []
    for token in text.split():
        word, _, icon = token.partition(':')
        if word not in by_word:
            raise ValueError('Curated word missing from source A/B: ' + word)
        if word not in selected:
            selected.append(word)
        group.append((word, icon))
    topic_rows.append((title, group, mode))
for word, row in sorted(by_word.items(), key=lambda item: (item[1]['grade'], item[1]['rank'])):
    if word not in selected and len(selected) < 2000:
        selected.append(word)
assert len(selected) == 2000

words = []
for i, word in enumerate(selected, 1):
    row = by_word[word]
    words.append({'id': f'w{i:04}', 'word': word, 'pos': row['pos'], 'sourceBand': row['grade'],
                  'sourceEntry': row['original'], 'sourceRank': row['rank'], 'icon': ''})
word_map = {w['word']: w for w in words}
stages = []
for i, (title, group, mode) in enumerate(topic_rows, 1):
    ids = []
    for word, icon in group:
        word_map[word]['icon'] = icon
        ids.append(word_map[word]['id'])
    stages.append({'id': f's{i:03}', 'number': i, 'title': title, 'mode': mode,
                   'words': ids, 'band': 'theme'})
covered = {wid for s in stages for wid in s['words']}
remaining = [w for w in words if w['id'] not in covered]
for i in range(0, len(remaining), 5):
    group = remaining[i:i+5]
    n = len(stages) + 1
    band = 'foundation' if all(w['sourceBand'] == 'A' for w in group) else 'extension'
    title = ('기초 듣기' if band == 'foundation' else '확장 듣기') + f' {n:03}'
    stages.append({'id': f's{n:03}', 'number': n, 'title': title, 'mode': 'listen',
                   'words': [w['id'] for w in group], 'band': band})
assert len(stages) == 400
assert len({wid for s in stages for wid in s['words']}) == 2000
module = '// Generated by scripts/build-curriculum.py. NIKL 2003, KOGL type 1.\n'
module += 'export const WORDS=' + json.dumps(words, ensure_ascii=False, separators=(',', ':')) + ';\n'
module += 'export const STAGES=' + json.dumps(stages, ensure_ascii=False, separators=(',', ':')) + ';\n'
(ROOT / 'curriculum.js').write_text(module, encoding='utf-8')
