// Derive the first-meeting screen from the approved cards and existing life kit.
// No model calls, new voices, or changes to the canonical pictures.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const sharp=require('C:/Users/q1212/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const root=path.resolve(__dirname,'../..'),talk=path.resolve(root,'../SYNK-talk');
const art=require(path.join(root,'tools/lib/마스코트자산.js'));
const life=require(path.join(talk,'lib/마스코트생명.js'));
const voices=require(path.join(talk,'lib/가이드목소리.js'));
const cards=JSON.parse(fs.readFileSync(path.join(root,'docs/캐릭터/소개글_정본.json'),'utf8')).카드;
const target=path.join(__dirname,'assets/tutors');
const sha=buffer=>crypto.createHash('sha256').update(buffer).digest('hex');
const records=[],profiles=[];
fs.mkdirSync(target,{recursive:true});
const ids={마린:'marin',까몽:'kkamong',몽글:'mongle'};
function sourceFor(name,cut){return path.join(root,name==='마린'?art.마린경로(cut):name==='까몽'?art.까몽경로(cut,{누끼:true}):art.경로(cut,{누끼:true}));}
function record(file,source){const entry={file,source:path.relative(root,source).replaceAll('\\','/'),sourceSha256:sha(fs.readFileSync(source)),sha256:sha(fs.readFileSync(path.join(target,file)))};records.push(entry);return entry;}
(async()=>{
 for(const name of Object.keys(ids)){
  const id=ids[name],card=cards.find(c=>c.캐릭터===name),cuts=life.표정컷[name];
  const base=await sharp(sourceFor(name,'본체')).resize(1024,1024).ensureAlpha().raw().toBuffer();
  // One common crop for every face: the outer body never changes position.
  let left=1024,top=1024,right=0,bottom=0;
  for(let y=0;y<1024;y++){let count=0,lo=1024,hi=0;for(let x=0;x<1024;x++)if(base[(y*1024+x)*4+3]>160){count++;lo=Math.min(lo,x);hi=Math.max(hi,x);}if(count>12){left=Math.min(left,lo);right=Math.max(right,hi);top=Math.min(top,y);bottom=Math.max(bottom,y);}}
  left=Math.max(0,left-24);top=Math.max(0,top-24);right=Math.min(1023,right+24);bottom=Math.min(1023,bottom+24);
  const crop={left,top,width:right-left+1,height:bottom-top+1},images={};
  for(const [emotion,stem] of Object.entries(cuts)){
   const cut=stem.slice(name.length+1),source=sourceFor(name,cut),file=`${id}-${emotion}.webp`;
   const scaled=await sharp(source).resize(1024,1024).png().toBuffer();
   await sharp(scaled).extract(crop).resize(480,480,{fit:'contain',background:'#00000000'}).webp({quality:90}).toFile(path.join(target,file));
   // Every consumer reads this URL; only changed image bytes invalidate its cache.
   images[emotion]=`${file}?v=${record(file,source).sha256.slice(0,12)}`;
  }
  const sounds={};
  for(const situation of ['기본','기쁨','안심']){
   sounds[situation]=[];
   for(const voice of voices.배치[name][situation]){
    const stem=voices.소리들[name][voice],source=path.join(talk,'assets/sfx',`synk-voice-${stem}.wav`),file=`${stem}.wav`;
    fs.copyFileSync(source,path.join(target,file));sounds[situation].push(file);record(file,source);
   }
  }
  const reactions=Object.fromEntries(['normal','repeat'].map((key,i)=>[key,life.탭반응고르기(name,.5,i?3:1)]));
  profiles.push({id,name,card,images,sounds,reactions});
 }
 fs.writeFileSync(path.join(__dirname,'tutor-profiles.mjs'),'// Generated by prepare-tutors.cjs from the approved character cards.\nexport const TUTORS = '+JSON.stringify(profiles,null,2)+';\n');
 fs.writeFileSync(path.join(target,'sources.json'),JSON.stringify({cardSource:'docs/캐릭터/소개글_정본.json',cardSourceSha256:sha(fs.readFileSync(path.join(root,'docs/캐릭터/소개글_정본.json'))),reactionSource:'../SYNK-talk/lib/마스코트생명.js',soundSource:'../SYNK-talk/lib/가이드목소리.js',transform:'common canonical crop, 480px WebP; unchanged WAV; runtime keeps base body behind a face-only mask',files:records},null,2)+'\n');
 console.log(`Tutor assets ready: ${profiles.length} tutors, ${records.length} source records`);
})().catch(error=>{console.error(error);process.exitCode=1;});
