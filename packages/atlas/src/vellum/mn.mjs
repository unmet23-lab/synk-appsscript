// 몽골어 줄 — 보통 눈높이 · 기능 글(말하는 사람 default). WORLD 짧은 연습(4-1)에 보이는 종류만(문항 위 이유 · 판 끝 문장).
// 세 겹 대조(11-11, tools/몽골어대조.js --구독 — 아르곤 문법 · flash 직역 · spellcheck.mn 맞춤법): 처음 초안의 「уулзах(만나다)」 직역,
// 횟수 겹침(удаагаас … удаа), 시간 뜻 모호, 명사 없는 「алдсан:」, 「зүйл(물건)」을 고쳤다. 이름에는 격 어미를 붙이지 않는다 —
// 이름이 한국어라 모음조화를 맞출 수 없어 「…: 「이름」.」 꼴로 둔다. 「」 낫표는 WORLD가 모든 화면 언어에서 한국어 학습 대상 이름에
// 쓰는 표지라 그대로 둔다(아르곤은 몽골어 따옴표 «»를 권함 — 4-1 화면 검수에서 함께 본다).
// 마지막 판: 아르곤 문법 「정상」 · 맞춤법 의심 0 · flash와 Opus 직역이 원문 뜻과 같다(마지막 네 줄은 스키마 없이 부름 — 현장 노트 AI_CLI).
// 셋째 겹 Fable은 4-1 화면 검수의 최종에서.
const one = sentence => ({ standard: { default: [sentence] } });

const retry = (s, name) =>
  s.other
    ? `Саяхан алдсан үг хэллэг: 「${name}」. Өөр асуултад хариулж үзье.`
    : `Саяхан алдсан үг хэллэг: 「${name}」. Дахин нэг оролдъё.`;

const shaky = (s, name) =>
  s.reviews === 1
    ? `Өмнө нь алдсан үг хэллэг: 「${name}」. ${s.days} хоног өнгөрсөн тул дахин давтъя.`
    : `「${name}」: ${s.reviews} оролдлогоос ${s.misses} удаа алдсан. ${s.days} хоног өнгөрсөн тул дахин давтъя.`;

export const MN = Object.freeze({
  'unit.retry': one(retry),
  'unit.shaky': one(shaky),
  'unit.due': one(
    (s, name) =>
      `「${name}」: сүүлд үзсэнээс хойш ${s.days} хоног болжээ. Мартахаасаа өмнө дахин нэг давтъя.`,
  ),
  'unit.new': one((_, name) => `Анх удаа танилцаж байна: 「${name}」.`),
  'skill.up': one(
    (s, name) => `「${name}」: дараалан ${s.streak} удаа бие даан зөв хариуллаа. Нэг шат ахиулъя.`,
  ),
  'skill.ease': one((_, name) => `「${name}」: арай хялбараас нь дахин эхэлье.`),
  'pace.breather': one(
    (s, name) => `Дараалан ${s.misses} удаа алдлаа. Амсхийгээд сайн мэддэгээ давтъя: 「${name}」.`,
  ),
  idle: one(() => 'Өнөөдөр давтах ёстой бүхнээ давтлаа. Одоо хөнгөн дасгалаар үргэлжлүүлье.'),
  'day.capped': one(() => 'Өнөөдөртөө ингээд дуусгая. Үлдсэнийг маргааш давтъя.'),
  'pace.stubborn': one(
    () => 'Байнга алддаг үг хэллэгээ энэ удаад түр орхиё. Дараагийн удаа өөр аргаар дахин оролдъё.',
  ),
});
