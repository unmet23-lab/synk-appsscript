    return s.reviews === 1
      ? `Өнөөдөр алдсан үг хэллэг: «${name}». Дахин давтъя.`
      : `«${name}»: ${s.reviews} оролдлогоос ${s.misses} удаа алдсан. Өнөөдөр дахин давтъя.`;
