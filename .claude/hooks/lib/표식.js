/* 표식 — 「어느 트랙인가」를 가리키는 번호를 **한 곳에서** 읽는다 (마찰 F203).
 *
 * 🔴 실측 2026-08-07: `board-guard`(④ 자리 겹침)와 `track-collision`(표식 겹침)이 같은 판정을
 *   각자 `F0\d{2}` 라고 적고 있었다. 그때 장부는 이미 **F203** 이라 F100 이후 **104개** 번호가
 *   두 가드 모두에서 통째로 안 보였다. 조건 하나만 바꾼 대조(파일은 서로 다르게, 번호만 교체):
 *     F094 → 막음 · F123 → 통과 · F203 → 통과 · ②-20 → 막음
 *   새는 방향은 언제나 「통과」다. 대가는 실사고였다 — 두 세션이 같은 `F123` 을 나란히 선언해
 *   가드는 내내 조용했고, 한참 뒤 사람 눈에 띄어서야 한쪽이 비켜났다.
 *   ⚠ 회귀도 같이 눈이 멀어 있었다: 픽스처가 전부 F050·F065·F070·F094 라 **초록이 구멍을 덮었다.**
 *
 * 🔑 목록은 하나에서 파생시킨다(CLAUDE.md 신뢰성 ④). 같은 판정을 두 곳에 적으면 갈라지고,
 *   갈라진 쪽의 증상은 조용한 통과다 — 여기선 이미 갈라져 있었다(한쪽은 `^` 앵커, 한쪽은 `\b` 전역).
 *
 * ⚠ **정규식을 내보내지 않는다.** `/g` 정규식은 `lastIndex` 를 들고 다녀서 `.test()`·`.exec()` 로
 *   재사용하면 한 번 걸러 통과한다 — 그것도 「통과」 쪽으로 새는 모양이라, 호출부가 잘못 쓸 수
 *   없게 **값**만 돌려준다.
 */
'use strict';

const 장부 = 'F\\d{3}'; //            마찰 장부 — F001…F999 (`F0`+두자리로 적혀 있던 자리)
const 절단 = '[①②③④⑤]-\\d+'; //     절단문서 항목 — `②-20`
const 버전 = '\\[v\\d+\\.\\d+\\]'; // 배포 버전 — `[v9.186]`

/** 트랙 **머리**의 표식 하나 (없으면 `null`).
 *  머리에서만 뽑는다 — 본문에서의 인용(「지금 ②-20 을 두 세션이 판다」)은 선점이 아니라 참조라,
 *  문장 어디서나 세면 남을 언급만 해도 막힌다(board-guard ④ 의 거짓양성 검사가 이 자리를 지킨다). */
function 머리(트랙칸) {
  const m = String(트랙칸 || '')
    .replace(/^[\s*_`~>🔵🟢🟡🔴⚠️✅⏸]+/u, '') // 굵게·상태 이모지 같은 장식은 표식이 아니다
    .match(new RegExp(`^(?:${장부}|${절단}|${버전})`));
  return m ? m[0] : null;
}

/** 문장 어디서나 표식을 훑는다 — 커밋 제목 대조용(거기선 인용도 신호다). 없으면 빈 배열. */
function 훑기(text) {
  return String(text || '').match(new RegExp(`\\b${장부}\\b|${버전}`, 'g')) || [];
}

module.exports = { 머리, 훑기 };
