#!/usr/bin/env node
/* 되돌림판정 — 「남의 줄을 **지웠다**」와 「그 줄을 **제자리에서 고쳤다**」를 가른다 (F189 · 2026-08-07).
 *
 * 🔴 왜 생겼나 — `git-scope-guard` 규칙⑨(F187 되돌림 탐지)의 첫 판은 판정이 하나뿐이었다:
 *   *남의 커밋이 더한 줄이 내 작업본에 **문자열로** 남아 있나.* 그러면 공유 문서의 그 줄을
 *   **고치는** 순간 원문이 사라지므로 되돌림으로 잡힌다. 실측: 절단문서 ①-8 종결 커밋(`02cd32d`)이
 *   앞 커밋의 진행표 한 줄에 8번을 끼워 넣는 편집인데 차단됐고, 작업본은 HEAD 기준이라 스테일도
 *   아니었다. **새는 방향이 나빴다**: 처방(그 줄 복원)을 따르면 내 수정이 사라지므로 따를 수 없고,
 *   남는 문이 `GIT_SCOPE_BYPASS=1` 뿐인데 그건 ⑨만이 아니라 **전 규칙**을 끈다
 *   — 따를 수 없는 처방이 우회를 정상 통로로 만든다(F103 형태).
 *
 * 🔑 그런데 「`+` 줄이 하나라도 있으면 수정」으로 가르면 **F187 이 통째로 새어 나간다.** 도구가 옛 판으로
 *   덮어쓴 자리도 diff 에선 `-남의줄 / +내줄` 한 블록으로 붙어 나오고, 그 `+` 줄은 원본과 아주 닮았다
 *   (기본값 한 자리만 다른 꼴). 그래서 통과에 **적극적 증거**를 요구한다 — 세 관문을 다 지나야 수정이다.
 *
 * 🔧 왜 훅 본문이 아니라 별도 모듈인가 — 이 판정은 git 도 파일시스템도 안 보는 **순수 함수**인데,
 *   훅 안에 있으면 프로세스를 띄워야만 만질 수 있어 관문 하나하나의 탐지력을 못 박을 수가 없다
 *   (변이 3건이 실제로 그 자리로 샜다: 판정 불가·블록 못 찾음·문맥 줄 경계). 여기로 꺼내면 검사가
 *   직접 부른다. 판정층은 여전히 하나다 — 훅은 이 모듈을 **읽기만** 한다.
 */
'use strict';

/** 통합 diff 본문을 **변경 블록**으로 자른다 — 문맥 줄 사이에 낀 `-`/`+` 의 연속 한 덩어리. */
function 변경블록(diff텍스트) {
  const 블록 = [];
  let 현재 = null;
  let 본문 = false;
  for (const raw of String(diff텍스트 == null ? '' : diff텍스트).split('\n')) {
    /* `@@` 앞은 파일 머리말이다(`--- a/…` · `+++ b/…`). 안 걸러내면 그 두 줄이 변경으로 읽힌다. */
    if (raw.startsWith('@@')) { 본문 = true; 현재 = null; continue; }
    if (!본문 || raw.startsWith('\\')) continue;   // `\ No newline at end of file` 은 변경이 아니다
    const c = raw[0];
    if (c === '-' || c === '+') {
      if (!현재) { 현재 = { 빼기: [], 더하기: [] }; 블록.push(현재); }
      (c === '-' ? 현재.빼기 : 현재.더하기).push(raw.slice(1).replace(/\r$/, '').trim());
    } else 현재 = null;                            // 문맥 줄이 나오면 블록이 끊긴다
  }
  return 블록;
}

/** 앞에서 겹치는 길이 + 뒤에서 겹치는 길이가 원본의 60% 이상인가 (끼워 넣기·부분 수정의 모양). */
function 닮았나(원본, 새것) {
  if (!원본 || !새것) return false;
  let 앞 = 0;
  while (앞 < 원본.length && 앞 < 새것.length && 원본[앞] === 새것[앞]) 앞 += 1;
  let 뒤 = 0;
  while (뒤 < 원본.length - 앞 && 뒤 < 새것.length - 앞
         && 원본[원본.length - 1 - 뒤] === 새것[새것.length - 1 - 뒤]) 뒤 += 1;
  return (앞 + 뒤) / 원본.length >= 0.6;
}

/**
 * 사라진 줄 하나가 **제자리 수정**인가 (아니면 되돌림으로 센다).
 * @param 줄       남의 커밋이 더했는데 지금 작업본에 없는 줄(다듬은 상태)
 * @param 블록들   내 작업본 diff(`git diff HEAD -- <파일>`)의 변경 블록 — 못 쟀으면 null
 * @param 지운줄   남의 그 커밋이 **지운** 줄들의 Set(다듬은 상태) — 이전 판의 지문이다
 */
function 제자리수정인가(줄, 블록들, 지운줄) {
  if (!블록들) return false;                        // 못 쟀다 — 판정 불가를 통과로 번역하지 않는다
  const b = 블록들.find((x) => x.빼기.includes(줄));
  if (!b) return false;                             // 그 줄이 어디서 사라졌는지 못 짚었다
  /* 짧은 줄(`}` · `});`)은 어디에나 있어 「닮았다」가 우연히 참이 된다 — ⑨의 길이 하한과 같은 이유다. */
  const 새줄 = b.더하기.filter((x) => x.length >= 8);
  if (!새줄.length) return false;                   // 관문① 순수 삭제 — 대체한 것이 없다
  const 지운것 = 지운줄 || new Set();
  if (새줄.some((x) => 지운것.has(x))) return false; // 관문② 그 커밋의 **이전 판**이 돌아왔다 = 되돌림
  return 새줄.some((x) => 닮았나(줄, x));            // 관문③ 갈아치운 게 아니라 고친 것인가
}

module.exports = { 변경블록, 닮았나, 제자리수정인가 };
