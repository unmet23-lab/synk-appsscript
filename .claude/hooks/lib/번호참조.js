/* 접두(바탕화면·운영자료·운영) + 숫자 + 「번」이 **붙어 있을 때만** 문다.
 * 🔑 이 좁음이 곧 **신고 통로**다 — 접두를 떼면(「바탕화면을 «35번» 같은 번호로」) 안 물리므로,
 *   위반을 «설명»하는 글은 위반이 되지 않는다. 넓히려거든 `처방` 과 그 회귀를 같이 고쳐라.
 *   따를 수 없는 처방은 우회를 정상 통로로 만든다(F103).
 * ⚠ **팩토리로 낸다**(`const re = ...` 가 아니라 `() => /.../g`). 전역 정규식은 `lastIndex` 를
 *   들고 다녀서 같은 입력에 번갈아 참·거짓을 낸다 — 줄마다 `.test()`·`.match()` 를 부르는
 *   호출부에서 하나 걸러 하나씩 놓치고, 새는 방향은 여기서도 「통과」다. */
const 번호참조 = () => /(?:바탕화면\s*(?:운영자료\s*)?|운영자료\s*|운영\s*)\d+\s*번/g;

/** 본문에서 걸린 표기들 — 빈 배열이면 깨끗하다. 자리를 안 따지는 자리(쓰는 순간)용. */
function 걸린것(본문) {
  return String(본문 || '').match(번호참조()) || [];
}

/**
 * 한 파일 본문에서 걸린 자리를 `파일:줄  표기` 로 낸다 — 빈 배열이면 깨끗하다.
 * 🔑 본문을 **인자로 받는다**: 스위트는 작업 트리를 읽고 훅은 편집 결과를 읽는데, 그 차이는
 *   «수집»의 몫이지 «판정»의 몫이 아니다(옛글자 lib 과 같은 규약).
 */
function 걸린줄(파일, 본문) {
  const 결과 = [];
  String(본문 || '').split(/\r?\n/).forEach((ln, i) => {
    const m = ln.match(번호참조());
    if (m) 결과.push(`${파일}:${i + 1}  ${m.join(' · ')}`);
  });
  return 결과;
}

