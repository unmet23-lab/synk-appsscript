    //   인계문에 「미커밋 9건」이 적혔고, 그 9건은 전부 옆 세션의 살아있는 작업본이었다.
    //   새 세션이 그걸 제 것으로 알고 커밋하면 사고다(F073) — 그래서 가르는 도구를 같이 준다.
