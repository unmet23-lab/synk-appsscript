/** 넘기는 🎫 가 말하는 일감이 **이미 끝났는지**의 증거 한 줄 (F374).
 *
 * 🔑 `낡음()` 과 축이 다르다 — 저건 「사본이 원본과 같은가」(F343)고 이건 「그 일이 이미
 *   됐는가」다. 사본이 원본과 **완벽히 같아도** 그 일감은 죽어 있을 수 있다: 실측 2건이
 *   그랬다(`de6b34d5` 는 검수 장부에 이미 있었고 `c0f148aa` 뒤로 365 커밋이 쌓여 있었다).
 *
 * ⚠ 🎫 가 있을 때만 부른다 — git 을 몇 번 부르므로 마감 훅의 값을 그냥 쓰지 않는다.
 * ⚠ 모듈이 없거나 던지면 **조용히 빠진다.** 인계문이 이것 때문에 안 나가는 쪽이 더 나쁘다. */
function 티켓증거(cwd, track) {
  try {
    const 낡음모듈 = require(path.join(String(cwd || '.'), 'tools', 'lib', '보드낡음.js'));
    const 말 = 낡음모듈.말들(낡음모듈.증거칸(track.track, track.state, String(cwd || '.')));
    if (!말.length) return null;
    return `   🎫 대조(기계 · F374): ${말.join(' | ')}`;
  } catch (_) {
    return null;
  }
}

/**
 * 인계문에 실린 보드 줄 사본이 **지금도 원본과 같은가** (마찰 F343 원인 쪽 · 2026-08-12).
 *
 * 왜 여기서 재나: 인계문은 세션 A 가 **마감하며** 만들어 저장하고, 세션 B 가 **나중에** 읽는다.
 *   쓰는 시점의 A 는 「그 뒤로 더 일할지」를 원리상 모른다 — 그래서 이음매는 단언을 낮췄다.
 *   그런데 **읽는 시점에는 잴 수 있다**(CLAUDE.md: 현재 상태는 현재를 읽어 판정한다 · 잴 수 있는 건 잰다).
 *   실측 사고에서 낡은 것은 정확히 **상태 칸**이었다(🎫 과녁이 `52eac5b2` → `c0f148aa` 로 옮겨졌다).
 *
 * 🔑 축은 **생사가 아니라 낡음**이다. 심장박동으로 「살아있다」를 재면 방금 쓰인 인계문은 늘
 *   「그 세션 살아있음」이 되고(박동이 30분 식어야 죽는다), 매번 뜨는 경고는 곧 아무도 안 읽는다.
 *   물어야 할 것은 「그 세션이 사나」가 아니라 **「내가 집을 과녁이 아직 그 과녁인가」**다.
 *
 * 🔑 대조는 **같은 파서로** 한다 — 원본을 `표.칸나누기` 로 다시 갈라 상태 칸끼리 비교한다.
 *   날 문자열 `includes` 로 재면 백틱 안 파이프·양끝 공백에서 갈리고(그 사연 = tools/lib/표.js),
 *   갈린 쪽 증상은 **거짓 「바뀜」**이라 결국 경고를 끄게 만든다.
 * ⚠ 줄 고르기 규칙을 여기 다시 적지 않는다 — 파일 안 **어느 줄이든** 그 사본과 같으면 「그대로」다.
 *   `boardTrack` 의 고르기(지문→해시→마지막)를 베끼면 같은 판정이 두 곳에 살고 갈라진다(가드 맹점 ④).
 * ⚠ 넓은 쪽(`표줄`)으로 훑는다. 좁은 쪽(`데이터행`)을 쓰면 원본이 규격을 어겨 «유령»이 된 순간
 *   과녁은 그대로인데 「바뀜」이 뜬다 — 거짓양성은 이 경고의 유일한 사망 원인이다.
 *
 * @returns null(대조할 사본이 안 실렸다) | { 판정: '그대로'|'바뀜'|'사라짐', 경로, 사본 }
 */
function 낡음(cwd, message) {
  const 전문 = String(message || '');
  const 상태줄 = 전문.split('\n').find((l) => l.startsWith(상태접두));
  const 경로 = (전문.match(원줄패턴) || [])[1];
  if (!상태줄 || !경로) return null;          // 옛 인계문·트랙 없는 세션 — 대조 대상이 없다
  const 사본 = 상태줄.slice(상태접두.length).trim();
  if (!사본) return null;

  let 본문;
  try { 본문 = fs.readFileSync(path.join(String(cwd || '.'), 경로), 'utf8'); } catch (_) {
    /* 파일 자체가 없다 = 그 세션의 보드 파일이 통째로 치워졌다. 「못 쟀다」가 아니라 「사라짐」이다 —
     * 그 사본을 지시로 읽으면 안 된다는 결론은 바뀜과 같고, 여기서 침묵하면 그게 새는 방향이다. */
    return { 판정: '사라짐', 경로, 사본 };
  }
  const 지금 = 본문.split(/\r?\n/).filter((l) => 보드.표줄(l)).map((l) => (표.칸나누기(l)[3] || '').trim());
  if (지금.includes(사본)) return { 판정: '그대로', 경로, 사본 };
  return { 판정: 지금.length ? '바뀜' : '사라짐', 경로, 사본 };
}

/** `낡음()` 의 판정을 다음 세션이 첫 화면에서 읽을 한 줄로. 「그대로」면 **아무 말도 안 한다**
 *  (매번 뜨는 줄은 곧 배경이 되고, 배경이 된 경고는 진짜 낡음도 못 세운다). */
function 낡음경고(v) {
  if (!v) return null;
  if (v.판정 === '바뀜') {
    return '🔴 **위 「상태/다음」은 낡았다 — 방금 원본을 읽어 대조했다**: `' + v.경로 + '` 의 상태 칸이 '
      + '이 글이 쓰인 뒤 바뀌었다(그 세션이 마감 뒤에도 일했다 · F343). 🎫·다음 할 일은 **그 파일을 지금 열어** '
      + '읽고 시작한다 — 사본의 과녁으로 재검수·배포 같은 값비싼 조작을 돌리면 그대로 헛돈다.';
  }
  if (v.판정 === '사라짐') {
    return '🔴 **위 「상태/다음」이 원본에 더 이상 없다 — 방금 대조했다**: `' + v.경로 + '` 에서 그 줄이 '
      + '아카이브로 옮겨졌거나 지워졌다(F343). 사본을 지시로 읽지 말고 `node tools/board.js` 로 '
      + '지금 상태를 확인한 뒤 새 트랙을 잡는다.';
  }
  return null;
}

