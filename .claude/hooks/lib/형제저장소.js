'use strict';

const path = require('path');
const worktrees = require(path.join(__dirname, 'worktrees.js'));

/** 이 저장소의 형제 이름. 늘어나면 여기 한 줄이 정본이다. */
const 기본이름 = 'SYNK-talk';

/** 워크트리 안에서 물어도 **주저장소**를 답한다. 못 풀면 `root` 그대로(⚠①). */
function 주저장소(root) {
  return worktrees.mainWorktree(path.resolve(String(root || '.')));
}

/** 형제 저장소가 **있어야 할 자리**. 있는지는 안 본다(머리말 ⚠). */
function 형제경로(root, 이름 = 기본이름) {
  return path.resolve(주저장소(root), '..', String(이름));
}

module.exports = { 기본이름, 주저장소, 형제경로 };
