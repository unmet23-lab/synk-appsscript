// 옛글자 — 한자·가나 판정의 **단일 출처**.
//
// 이 파일은 판정 정의만 맡는다. `tools/lib/옛글자.js`와 수동 검사기가 이 정규식을 재사용한다.
// 훅 파일이나 `tools/githooks/pre-commit`의 존재만으로 자동 등록됐다고 보지 않는다. 실제 보호 여부는
// 현재 하네스 설정과 `git config core.hooksPath`를 그때 확인한다.
//
// 🔴 범위 경계를 **글자로 적지 않는다** — 적으면 이 파일 자신이 문서문자 스캔에 걸린다.
// 🔴 보고도 글자로 하지 않는다 — 위반을 **신고하는 글**에 그 글자를 인용하면 그 자리가
//    새 위반이 된다(F298 실측: 그렇게 번진 것이 보드 파일 2벌 · F103 계열).
//    그래서 아래 `짚기` 는 언제나 `U+XXXX` 표기만 돌려준다.
'use strict';

// 한자+가나 판정 클래스.
// [vNEXT] 리뷰 P2-① 확장: 구판(통합·확장A·기본 가나)은 한국어 독음 호환한자(U+F900–FAFF)·반각
//   가나(U+FF66–FF9F)·astral 면(가나 보충 U+1AFF0–1B16F · 2·3면 한자 U+20000–3FFFF)을 «통과»로
//   흘렸다. 2·3면은 통째로 막는다 — 그 면은 전부 한자 구역이라 정당한 코드포인트가 나올 자리가
//   없고, 확장 블록을 좁게 좇으면 유니코드가 판을 낼 때마다 이 목록이 낡는다(낡는 방향은 통과다).
//   사본 네 벌(이 파일·엔진_콘텐츠AI.js·talk lib·talk eval-score)은 글자로 같아야 한다 — 회귀가 대조.
const 옛글자 = new RegExp('[\\u3040-\\u30FF\\u3400-\\u4DBF\\u4E00-\\u9FFF\\uF900-\\uFAFF\\uFF66-\\uFF9F\\u{1AFF0}-\\u{1B16F}\\u{20000}-\\u{3FFFF}]', 'gu');

/** 글에 든 옛 글자의 **코드포인트 집합**을 돌려준다(글자 자체는 담지 않는다). */
function 찾기(text) {
  const 본 = new Set();
  for (const m of String(text).match(옛글자) || []) 본.add(m.codePointAt(0));
  return [...본];
}

/** 코드포인트들을 사람이 읽을 표기로 — `U+5C3A` 형태. 글자는 절대 넣지 않는다. */
function 짚기(코드들) {
  return 코드들.map((c) => 'U+' + c.toString(16).toUpperCase().padStart(4, '0')).join(' · ');
}

module.exports = { 옛글자, 찾기, 짚기 };
