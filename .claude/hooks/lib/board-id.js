/* board-id — 보드 줄에서 **세션 지문**을 뽑는 한 곳 (마찰 F165).
 *
 * 왜 있나 (2026-08-07 실사고):
 *   보드 줄의 주인을 찾는 도구가 둘인데(인계문 생성기 `session-report.boardTrack`,
 *   이관 도구 `board-move` 원칙 ⑥) **둘 다 줄에 적힌 커밋 해시로만** 찾았다.
 *   해시는 이 저장소의 *관행*이지 규칙이 아니다 — 「양보 종결」처럼 코드 커밋이 하나도
 *   안 나간 트랙은 줄에 해시가 없다. 그래서 세션 `a0b27c60` 의 인계문이 「내 줄을 못 찾았다,
 *   정말 없으면 멈춰라」로 나갔고, 다음 세션은 **보드에 멀쩡히 있는 자기 줄**을 두고
 *   멈출 뻔했다. board-move 쪽 증상은 반대다 — 재료가 없으니 원칙 ⑥이 그냥 통과한다
 *   (살아있는 세션의 줄을 아무 경고 없이 아카이브로 옮긴다 · F146 이 그 사고였다).
 *
 * 🔑 재료를 늘리는 게 아니라 **재료를 한 곳에서 만든다.** 두 도구가 각자 「어느 줄이
 *   누구 것인가」를 적으면 갈라지고, 갈라진 쪽의 증상은 언제나 「통과」다(CLAUDE.md 신뢰성 ④).
 *   정책은 각자다 — 인계문은 **모르면 모름으로 두고**(남의 줄을 이어받는 게 더 큰 사고),
 *   이관은 **의심되면 멈춘다**(안 옮겨도 잃는 게 없다). 뽑는 자리만 공유한다.
 *
 * ⚠ 접두를 **요구한다**. 접두 없는 8자리 hex 는 커밋 해시와 생김새가 같아서, 그냥 8자리를
 *   지문으로 읽으면 남의 커밋 해시가 적힌 줄이 내 줄로 판정된다(새는 방향 = 이어받기).
 */
'use strict';

/** 세션 id → 보드에 적는 지문(8자리). `작업본소유자.짧게` 와 같은 규칙 —
 *  둘이 갈라지면 도구마다 다른 줄을 내 줄이라 하므로 회귀가 동일성을 못박는다. */
function 지문(sid) {
  return String(sid || '').replace(/^[a-z]+_/, '').slice(0, 8).toLowerCase();
}

/** 줄에 **직접 적힌** 세션 지문들. `local_302d8acd` 처럼 접두가 붙은 것만 센다. */
function 줄의지문(line) {
  const 표 = String(line || '').match(/\b[a-z]+_[0-9a-f]{8}\b/gi) || [];
  return [...new Set(표.map((t) => t.slice(t.indexOf('_') + 1).toLowerCase()))];
}

/** 이 줄이 그 세션 것이라고 **줄 스스로 말하는가.** 추측하지 않는다 — 적혀 있어야 참이다. */
function 줄이말하나(line, sid) {
  const 나 = 지문(sid);
  return !!나 && 줄의지문(line).includes(나);
}

module.exports = { 지문, 줄의지문, 줄이말하나 };
