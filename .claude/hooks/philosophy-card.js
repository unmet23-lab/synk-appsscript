#!/usr/bin/env node
/**
 * philosophy-card — 세션 시작에 **판단 정본의 게이트 문장만** 띄운다.
 *
 * 왜 있나 (2026-08-10 · 유호님 질문 「지금 이 철학도 니가 읽고 있나?」에서 실측):
 *   메모리 autonomous-build-mode 에 「판단 정본 = docs/SYNK_철학.md 정독(상시 08-09)」이 적혀 있는데
 *   **그걸 발화시키는 장치가 하나도 없었다.** SessionStart 훅 6개(rot-check·session-handoff·인계문수거·
 *   작업본소유자·session-decisions·대기열) 어디에도 철학이 없어서, 세션은 그 파일을 **열 이유가 생길 때만**
 *   열었다. 자율주행은 유호님이 안 보는 사이 판정을 쌓는 트랙이라, 기준이 안 실린 채 도는 것이 가장 비싸다.
 *   CLAUDE.md — 「프로즈보다 기계 강제로 옮긴다 · 스스로 발화하지 않는 장치는 안 돈다」.
 *
 * 설계:
 *   ① **전문을 싣지 않는다** — 철학 정본은 13,459자(29KB)로 매 턴 상주하는 CLAUDE.md(21KB)보다 크다.
 *      컨텍스트 비용은 남은 턴 수만큼 곱해지므로(CLAUDE.md 실행 §), 실제로 **판정을 가르는 두 자리**만
 *      싣고 나머지는 주소로 넘긴다: Ⅰ 한 문장(궁극 가치) + Ⅰ-3(「똑똑하게」 3층 = 전 산출물이 지나는 게이트).
 *   ② **판정을 두 곳에 적지 않는다** — 카드 문구를 여기 베끼지 않고 정본에서 **뽑아 온다**.
 *      베끼면 정본이 개정될 때 카드만 낡아, 세션은 낡은 기준으로 판정하면서 초록을 본다.
 *      (v1.1→v1.3 처럼 하루에 세 번 개정되는 문서다 — 사본은 반드시 갈라진다.)
 *   ③ **못 뽑으면 조용히 넘어가지 않는다** — 앵커가 깨졌는데 빈 출력을 내면 「기준 없음」이 「통과」처럼 보인다.
 *      미실행과 통과는 같은 모양이면 안 된다(F207). 무엇이 왜 안 됐는지 말하고 비정상 종료한다.
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = process.env.CLAUDE_PROJECT_DIR || path.resolve(__dirname, '..', '..');
const 정본 = path.join(ROOT, 'docs', 'SYNK_철학.md');

/** 터미널 한 줄로 읽히게 — 굵게·표식 문법만 걷는다(뜻은 안 건드린다) */
function 평문(s) {
  return s.replace(/\*\*/g, '').replace(/`/g, '').trim();
}

/** 다음 절이 여는 줄 — 빈 줄 없이 절이 바뀌어도 그 자리를 넘어가지 않는다. */
const 절머리 = /^(#{1,6}\s|\*\*\d+\.\s|>\s|\||-{3,}\s*$)/;

/**
 * 정본에서 한 자리를 뽑는다 — 시작 줄부터 **빈 줄(=절의 끝) 전까지** 모은다.
 *
 * 🔴 **한 줄만 집으면 안 된다** (2026-08-12 실측 · 유호님 「잘 작성돼 있는지」 검토에서 나왔다):
 *   `lines[i + 1]` 하나만 읽던 판은 정본의 그 절이 **두 줄로 갈리는 순간 뒷줄을 조용히 버렸다.**
 *   앵커는 찾았으니 아래 실패 처리(exit 1)도 **안 걸린다** — 세션은 반쪽 기준으로 판정하면서
 *   초록을 본다. 이 훅이 막으려고 만들어진 상태가 정확히 그것이다(F207 — 미실행과 통과가
 *   같은 모양이면 안 된다). 「지금은 한 줄이라 맞다」는 근거가 못 된다: 이 정본은 하루에
 *   세 번 개정되는 문서이고(v1.1→v1.3), 절이 길어지는 방향으로만 자란다.
 *
 * @param {string} md   정본 전문
 * @param {RegExp} 앵커  그 자리를 여는 줄
 * @param {boolean} 다음줄  true = 앵커 다음 줄부터 본문(소제목-본문 두 줄 구조)
 */
function 뽑기(md, 앵커, 다음줄) {
  const lines = md.split(/\r?\n/);
  const i = lines.findIndex((l) => 앵커.test(l));
  if (i < 0) return null;
  const 시작 = 다음줄 ? i + 1 : i;
  const 모음 = [];
  for (let j = 시작; j < lines.length; j++) {
    const l = lines[j];
    if (!l.trim()) break;                     // 빈 줄 = 절의 끝
    if (j > 시작 && 절머리.test(l)) break;     // 빈 줄 없이 다음 절이 붙어도 넘어가지 않는다
    모음.push(l.trim());
  }
  const body = 모음.join(' ');
  return body ? 평문(body) : null;
}

/**
 * 인용 블록(`>` 로 이어지는 여러 줄)을 통째로 뽑는다 — **줄을 살려서** 잇는다.
 *
 * 🔴 왜 뽑기() 를 못 쓰나: `절머리` 에 `>` 가 들어 있어서, 뽑기() 는 인용 블록의 **둘째 줄에서 멈춘다.**
 *   그 자리가 하필 「우리가 하지 않는 것 넷」이라, 그냥 두면 카드가 ㉠ 하나만 싣고 ㉡㉢㉣ 를 조용히 버린다
 *   — 08-12 에 고친 「한 줄만 집던 병」과 **같은 병이 다른 문으로** 재발하는 모양이다.
 * 🔑 그리고 ' ' 가 아니라 '\n' 으로 잇는다: 금지 조항 넷이 한 줄로 뭉치면 읽는 쪽이 셋째·넷째를 흘린다.
 *   카드의 목적은 글자를 나르는 게 아니라 **판정 직전에 걸리게 하는 것**이다.
 */
function 인용뽑기(md, 앵커) {
  const lines = md.split(/\r?\n/);
  const i = lines.findIndex((l) => 앵커.test(l));
  if (i < 0) return null;
  const 모음 = [];
  for (let j = i; j < lines.length; j++) {
    const l = lines[j].trim();
    if (!l.startsWith('>')) break;              // 인용이 끝나면 그 자리가 블록의 끝
    모음.push(평문(l.replace(/^>\s?/, '')));
  }
  return 모음.length ? 모음.join('\n   ') : null;
}

/** 머리 한 줄 + `- ` 목록을 뽑는다(이해 3층처럼 층이 나뉜 자리) — 층마다 줄을 살린다. */
function 목록뽑기(md, 앵커) {
  const lines = md.split(/\r?\n/);
  const i = lines.findIndex((l) => 앵커.test(l));
  if (i < 0) return null;
  const 모음 = [평문(lines[i])];
  for (let j = i + 1; j < lines.length; j++) {
    if (!lines[j].trim().startsWith('- ')) break;
    모음.push(`  ${평문(lines[j])}`);
  }
  return 모음.length > 1 ? 모음.join('\n   ') : null;
}

/** 카드 한 자리의 길이 상한.
 *  절이 자라도 **매 세션 상주 비용**은 정본 전문(13,459자)으로 돌아가면 안 된다(설계 ①).
 *  그렇다고 조용히 자르면 위에서 고친 그 병이 길이 축으로 되살아나므로,
 *  **자르되 잘린 사실을 카드 본문에 박는다** — stderr 는 세션 화면에서 안 보일 수 있다. */
const 자리상한 = Number(process.env.SYNK_PHILOSOPHY_CARD_MAX || 1800);

function 상한적용(s, 이름) {
  if (s.length <= 자리상한) return s;
  return `${s.slice(0, 자리상한)} …\n⚠ [철학카드] ${이름}이 ${s.length}자로 늘어 **여기서 잘렸다**`
    + ' — 카드가 반쪽이다. 정본을 직접 열어라: docs/SYNK_철학.md';
}

function main() {
  if (!fs.existsSync(정본)) {
    console.error(`[철학카드] 판단 정본이 없다: ${정본} — 이 세션은 기준 없이 도는 중이다(워크트리면 정상).`);
    process.exit(1);
  }
  const md = fs.readFileSync(정본, 'utf8');
  const ver = (md.match(/<!--\s*정본:\s*(v[\d.]+)\s*-->/) || [, '(판 미상)'])[1];

  // 앵커 = 정본의 구조 그 자체. 절 번호가 바뀌면 여기서 빨개져야 한다(조용한 낡음 금지).
  const 가치 = 뽑기(md, /^\*\*한 문장:/, false);
  const 게이트 = 뽑기(md, /^\*\*3\. 「똑똑하게」/, true);
  // v1.4 신설 — 아래 셋이 안 실리면 카드가 **자기가 시킨 것을 안 싣는 상태**가 된다:
  //   ②엔진 조항이 「㉠㉡㉢ 중 어디에 보태는지 대라」고 시키는데 ㉠㉡㉢ 이 카드에 없으면
  //   그 지시는 세션이 못 따르는 지시다 — 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103).
  const 금지 = 인용뽑기(md, /^>\s*\*\*그리고 우리가 하지 않는 것 넷/);
  const 대상 = 뽑기(md, /^⚠\*\*적용 대상을 가른다/, false);
  const 이해 = 목록뽑기(md, /^\*\*「이해」는 세 층이다/);

  const 자리 = [
    ['Ⅰ 한 문장', 가치, '**한 문장:'],
    ['Ⅰ-3 「똑똑하게」', 게이트, '**3. 「똑똑하게」'],
    ['Ⅰ 하지 않는 것 넷', 금지, '> **그리고 우리가 하지 않는 것 넷'],
    ['Ⅰ-3 적용 대상', 대상, '⚠**적용 대상을 가른다'],
    ['Ⅰ-3 이해 3층', 이해, '**「이해」는 세 층이다'],
  ];
  const 빠진것 = 자리.filter(([, v]) => !v);
  if (빠진것.length) {
    console.error('[철학카드] 정본에서 게이트 문장을 못 찾았다 — 절 구조가 바뀌었다.'
      + 자리.map(([이름, v, 앵커]) => `\n  · ${이름}: ${v ? 'OK' : `못 찾음(앵커 ${앵커})`}`).join('')
      + '\n  → 이 세션은 판단 기준이 반쪽만 실린 채 돈다. 정본을 직접 열거나 앵커를 고쳐라: docs/SYNK_철학.md');
    process.exit(1);
  }

  console.log(`📐 판단 정본 — docs/SYNK_철학.md ${ver} · **모든 기능·콘텐츠·마케팅 판정이 이 네 자리를 지난다**`);
  console.log(`\n【궁극 가치】 ${상한적용(가치, '궁극 가치')}`);
  console.log(`\n【🚫 하지 않는 것 넷 — 판단이 갈리면 여기부터 읽는다】\n   ${상한적용(금지, '하지 않는 것')}`);
  console.log(`\n【「똑똑하게」 3층 = 산출물 게이트】 ${상한적용(게이트, '게이트')}`);
  console.log(`\n   ${상한적용(대상, '적용 대상')}`);
  console.log(`\n   ${상한적용(이해, '이해 3층')}`);
  console.log('\n▶ 여기 실린 것은 Ⅰ의 게이트뿐이다 — Ⅱ 교육·Ⅲ 대외 철학과 부록 A(대장)는 안 실렸다.'
    + ` 굵직한 기획·외부 공개물·새 기능은 정본을 직접 열고 판정한다(전문 ${md.length.toLocaleString('en-US')}자는 매 턴 상주시키지 않는다).`
    + '\n▶ 그리고 **시제**: 우리는 아직 미개원이다(학생 0명). 대장에 없는 것을 현재형으로 쓰지 않는다 — 정본 §0.');
}

if (require.main === module) main();
module.exports = { 뽑기, 인용뽑기, 목록뽑기, 평문, 상한적용, 자리상한 };
