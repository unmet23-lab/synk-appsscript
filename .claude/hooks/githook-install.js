#!/usr/bin/env node
/* githook-install — git 훅을 **세션 시작에** 깐다 (SessionStart 훅).
 *
 * 🔴 왜 있나 (F628 잔여 · 2026-08-18 클라우드 컨테이너 `cse_01RMwzh13hN8xA69dZTwuRxV` 실측):
 *   `.git/hooks` 는 **버전 관리 밖**이라 clone 에 안 딸려온다. 클라우드 세션은 매번 새로 clone 된
 *   컨테이너라 **훅 0개로 시작한다** — 실측: `install-githooks --check` 가 3건 전부 「미설치」(exit 1)였고,
 *   그 컨테이너의 SessionStart 훅들이 그날 낸 커밋 8건은 `Session-Id` 트레일러가 **전부 비어 있었다**.
 *   그런데 저장소 어디에도 `tools/install-githooks.js` 를 **부르는 자리가 없었다**(등록 0). 즉 그 도구는
 *   「누가 기억하면 도는」 물건이었고, 기억한 세션에서만 돌았다(직전 세션 `ad0673f3` 이 F628 을
 *   고치다가 손으로 깐 그 한 번이 그날의 유일한 설치다).
 *
 *   그 결과로 클라우드에서 **한 번도 안 돈** 게이트들:
 *     · `prepare-commit-msg` — 커밋 주인 표식(F041·F628). CLAUDE.md 가 「커밋 주인은 이걸로 읽는다」고
 *       못박은 재료가 주 통로에서 통째로 비었다.
 *     · `commit-msg` — 커밋 **메시지**의 원시 제어문자 차단(F454). 그 훅 머리말이 스스로 「가장 비싼
 *       자리」라 적은 것이다: 메시지에 박힌 바이트는 이력 재작성 말고 되돌릴 길이 없다.
 *     · `pre-commit` — 계약 동기화·계약 동봉·이해대장 동봉 게이트.
 *   CLAUDE.md 신뢰성: **스스로 발화하지 않는 장치는 안 돈다** — 장치와 발동 조건은 같은 커밋에서 정한다.
 *   이 파일이 그 발동 조건이다.
 *
 * 🔑 판정은 여기서 안 한다 — `tools/install-githooks.js` 하나가 진다(같은 판정을 두 곳에 적으면
 *   갈라지고, 갈라지는 방향은 언제나 「통과」다). 여기는 **부르는 자리**와 **소음 정책**만 맡는다.
 *   그래서 「무엇을 깔지·무엇을 덮지 않을지」(F391 보류)는 전부 그 도구의 몫이고, 그 도구가 낸
 *   처방문은 **그대로** 흘려보낸다 — 여기서 다시 쓰면 두 처방이 갈린다(F103).
 *
 * 🔧 설치기는 **내 곁에서** 찾고, 대상 저장소는 설치기의 기존 이음매(`SYNK_GITHOOKS_ROOT`)가 정한다.
 *   설치기 머리말과 같은 원칙이다 — 대상 저장소를 바꿔도 도구의 부품이 바뀌는 것은 아니다.
 *   그래서 여기엔 새 이음매가 0개다(회귀는 그 이음매 하나로 픽스처를 만든다).
 *
 * ⚠ 플래그를 **안 붙이고** 부른다(`--check` 만 예외). 설치기에 인자 게이트를 다는 트랙이 지금
 *   열려 있어(PR #111 · 아는 플래그 = `--check`), 새 플래그를 여기서 만들면 그 PR 이 착지하는 날
 *   이 훅이 조용히 거부당한다. 소음 정책은 플래그가 아니라 **이 파일**이 진다.
 *
 * ── 대가 (새 장치엔 대가를 함께 적는다 · CLAUDE.md 신뢰성) ──────────────────────────
 * ① **행동이 바뀐다.** `pre-commit` 이 깔리므로, 지금까지 클라우드에서 그냥 통과하던 커밋이
 *    이제 계약·동봉 게이트에 **막힐 수 있다.** 그게 이 트랙의 목적이지만, 「어제는 되던 게
 *    오늘 안 된다」로 보이는 자리다 — 막히면 그 게이트의 처방을 따르면 된다(전부 처방을 낸다).
 * ② **틀릴 때의 모습 = 「깔았다」고 말하면서 안 도는 것.** 실행비트가 안 붙거나(파일시스템),
 *    hooksPath 가 딴 데를 가리키면 설치기는 0으로 끝나는데 훅은 안 돈다 — 새는 방향이 「통과」다.
 *    → 그래서 **자기 exit code 를 믿지 않는다**: 깐 뒤 `--check` 로 결과를 다시 재고, 그래도
 *      「설치 필요」면 조용히 넘어가지 않고 exit 1 로 운다(F207 — 미실행을 통과로 번역하지 않는다).
 * ③ **순서는 계약이 아니다.** SessionStart 항목들의 실행 순서는 보장된 게 아니라, 같은
 *    SessionStart 안에서 남의 훅이 내는 커밋(예: 보드수거)까지 잡는다고 **약속하지 않는다**.
 *    이 훅이 보장하는 것은 「SessionStart 가 끝난 뒤 이 세션이 내는 커밋」이다. 등록을 배열
 *    맨 앞에 두는 것은 그 확률을 올리는 것이지 증명이 아니다.
 * ④ **닫을 것: 없다.** 이 장치가 대신하는 것은 「사람이 기억해서 부른다」인데 그건 끌 장치가
 *    아니다. `tests/커밋트레일러.test.js` 의 배선 검사는 계속 **skip** 이어야 한다 — CI 에는
 *    훅이 애초에 없고, 거기서 fail 을 요구하면 repo 밖 환경에 기댄 검사가 된다(F296).
 * ────────────────────────────────────────────────────────────────────────────────
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

/* 입력은 안 쓴다 — 하지만 **읽어야 한다.** 안 읽으면 훅 통로가 파이프에 남은 stdin 때문에
 * 막히는 자리가 있어, 등록 명령들도 전부 `IFS= read -r -d ''` 로 먼저 비운다. */
try { fs.readFileSync(0, 'utf8'); } catch (_) { /* 입력 없이도 진행 */ }

const 설치기 = path.join(__dirname, '..', '..', 'tools', 'install-githooks.js');
const 뿌리 = process.env.CLAUDE_PROJECT_DIR || process.cwd();

/* 실행 불가는 **드러낸다** — 조용한 건너뜀은 「깔렸다」와 같은 모양이다(F044). */
if (!fs.existsSync(설치기)) {
  process.stderr.write(`[githook설치] 설치기가 없어 git 훅을 **못 깔았다** — ${설치기}\n`);
  process.exit(1);
}

const 돌리기 = (...인자) => {
  const r = spawnSync(process.execPath, [설치기, ...인자], {
    cwd: 뿌리, encoding: 'utf8', timeout: 30_000,
  });
  const 글 = `${r.stdout || ''}${r.stderr || ''}`.trim();
  /* spawn 자체가 실패했거나(=r.error) 시그널로 죽으면 status 가 null 이다. null 을 0 으로 읽으면
   * **안 돈 것이 통과가 된다** — 그래서 모르면 1(=할 일 있음)로 읽는다. */
  const 코드 = r.error || r.status === null ? 1 : r.status;
  return { 코드, 글, 죽음: !!r.error || r.status === null };
};

/* ① 먼저 **묻는다.** 깔 필요가 없으면 아무 말도 안 한다 — 매 세션 뜨는 4줄은 그 자체가 비용이고
 *   (컨텍스트는 남은 턴 수만큼 곱해진다), 상시 소음은 진짜 경보를 죽인다. */
const 사전 = 돌리기('--check');
if (사전.코드 === 0) process.exit(0);
if (사전.죽음) {
  process.stderr.write(`[githook설치] 설치 상태를 **못 쟀다**(설치기가 안 돌았다) — ${사전.글 || '출력 없음'}\n`);
  process.exit(1);
}

/* 몇 건인지는 설치기가 스스로 센 숫자를 읽는다 — 여기서 다시 세면 두 분모가 갈린다. */
const 필요 = (/(\d+)건 설치 필요/.exec(사전.글) || [])[1];

// ② 깐다.
const 설치 = 돌리기();
if (설치.코드 !== 0) {
  /* F391 보류(설치본에만 있는 줄)·그 밖의 실패. 처방문은 설치기 것을 **그대로** 낸다. */
  process.stderr.write(`[githook설치] git 훅을 **못 깔았다** — 아래는 설치기가 낸 말이다.\n${설치.글}\n`);
  process.exit(1);
}

// ③ 깐 결과를 **다시 잰다**(위 대가 ②). exit 0 은 「썼다」지 「돈다」가 아니다.
const 사후 = 돌리기('--check');
if (사후.코드 !== 0) {
  process.stderr.write(
    `[githook설치] 설치기는 성공이라는데 **재보니 아직 「설치 필요」다** — 맞는 얼굴로 틀린 값이다.\n${사후.글}\n`
  );
  process.exit(1);
}

process.stdout.write(
  `[githook설치] git 훅 ${필요 ? `${필요}건` : ''}을 깔았다 — 이 저장소 사본은 훅 0개로 시작한다`
  + `(clone 에 .git/hooks 는 안 딸려온다 · F628). 이제 커밋에 주인 표식·제어문자·계약 게이트가 붙는다.\n`
);
process.exit(0);
