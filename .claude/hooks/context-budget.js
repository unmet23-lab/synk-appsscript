#!/usr/bin/env node
// context-budget — 컨텍스트가 「끊을 지점」에 닿았는지 알린다 (Stop 훅)
//
// 왜 있나 — 2026-08-04 실측으로 전제가 뒤집혔다.
//   이 저장소의 **바닥값(컴팩트해도 안 줄어드는 상주분)이 68,539 토큰**이다.
//   시스템 프롬프트 + 도구 스키마 + CLAUDE.md(17.5KB) + MEMORY.md(23.7KB).
//   그래서:
//     · 컴팩트 도달점  = 바닥 68.5k + 요약문 ≈ 73k
//     · 새 세션 시작점 = 68.5k  ← **더 작고, 요약 손실이 0이다**
//   결론 = 이 저장소에서 컴팩트는 세션 재시작보다 열등하다. 알릴 것은 「컴팩트하라」가 아니라
//   **「지금이 끊을 지점이다」**이고, 끊기가 안전하려면 미커밋이 0이어야 하므로 그것도 같이 본다.
//
// 왜 훅이 컴팩트를 「걸지」 않고 「알리기만」 하나 — 못 걸어서다(공식 문서 실측):
//   훅은 이벤트에 반응만 하고 이벤트를 일으키지 못한다 · 슬래시 명령 실행 불가 ·
//   autoCompactEnabled 는 on/off 뿐이고 **임계값은 하드코딩이라 못 바꾼다** ·
//   PreCompact 훅은 컴팩트를 **막는** 방향만 된다(exit 2). 즉 살 수 있는 건 알림층뿐이다.
//   같은 이유로 **세션을 자동으로 끄는 것도 불가능하다**(`continue:false` 도 턴만 멈춘다).
//
// 재료가 추정이 아니다 — 트랜스크립트 jsonl 의 assistant 레코드에 API 가 돌려준 **실제 usage** 가 박힌다.
//   컨텍스트 = input_tokens + cache_read_input_tokens + cache_creation_input_tokens
//   (바이트 수로 추정하면 시스템 프롬프트·도구 스키마가 안 잡혀 실제의 절반이 나온다 — 08-04 실측)
//   컴팩트가 일어나도 이 값은 API 가 실제로 받은 양이라 자동으로 내려간다.
//
// ⚠ 트랜스크립트는 비동기로 쓰여 현재 턴이 아직 안 실렸을 수 있다(공식 문서). 이 훅이 읽는 값은
//   **최대 한 턴 뒤처진다**(≈5k). 정밀 계측기가 아니라 신호등이다.
//
// 절대 막지 않는다. 끊을지 말지는 유호님 판단이고, 훅은 판단 재료만 준다.
'use strict';
const fs = require('fs');
const path = require('path');
const store = require(path.join(__dirname, 'lib', 'handoff-store.js'));
const report = require(path.join(__dirname, 'lib', 'session-report.js'));
// 컨텍스트를 재는 규칙과 바닥값은 **공용 통로 하나**에서 온다 — 이 값을 읽는 훅이
// track-boundary 까지 둘이 됐고, 두 곳에 적으면 갈라진다(CLAUDE.md 가드 등록층 ④ · F063).
// ⚠ 2026-08-16(#Q98): 창·임계·단계 판정도 **같은 통로로 옮겼다.** 여기 두면 「훅이 몇 번 울었나」를
//   재는 쪽이 규칙을 베껴 적게 되고, 베낀 규칙은 한쪽만 고쳐도 조용히 갈라진다(등록층 ④).
//   근거 주석(131세션 시뮬레이션·유호 확정 08-12·결함 ⑤)은 전부 그 파일로 함께 옮겼다.
const {
  currentContext, FLOOR, windowFor, thresholds, levelOf, 발동판정,
} = require(path.join(__dirname, 'lib', 'context-size.js'));

// 임계(🟡300k·🔴300k·⚫500k·STEP 100k)와 창 표, 그리고 그 숫자를 정한 131세션 시뮬레이션·
// 유호 확정 08-12·결함 ⑤ 의 근거는 전부 `lib/context-size.js` 에 있다 — 재는 쪽과 **같은 통로**다.

function headOf(stage) {
  if (stage === 1) return '슬슬 트랙을 닫을 준비';
  if (stage === 2) return '지금 끊을 지점이다';
  if (stage === 3) return '한참 지났다 — 지금 끊어라';
  // 4번째부터는 「몇 번째로 말하는지」를 세어 보여준다 — 같은 문구가 반복되면 배경이 된다.
  // 단계 번호 = 그 세션에서 이번이 몇 번째 발화인지와 같다(단계당 1회니까).
  return `${stage}번째 경고 — 아직 안 끊었다`;
}

let input;
try {
  input = JSON.parse(fs.readFileSync(0, 'utf8'));
} catch (_) {
  process.exit(0); // 입력을 못 읽으면 조용히 — 이 훅은 안전장치가 아니라 계기판이다
}

const tp = String(input.transcript_path || '');
if (!tp || !fs.existsSync(tp)) process.exit(0);

const info = currentContext(tp); // 규칙은 lib/context-size.js 에 있다(두 훅 공용)
if (info === null) process.exit(0);

const ctx = info.tokens;
const WINDOW = windowFor(info.model);
const T = thresholds(WINDOW); // 창을 안 뒤에야 임계가 정해진다

const cwd = input.cwd || process.cwd();
const sid = input.session_id;

// 🔑 **모델 «관측»은 이 자리에서만 찍힌다** — 재심 배선 ㉠(모델 변경)의 급소다(2026-08-17 · F548).
//   전사에서 모델을 뽑는 통로는 `message.usage` 줄인데 그건 어시스턴트가 한 턴을 마쳐야 찍힌다.
//   그래서 SessionStart(=판정하는 자리)에는 **값이 원리상 없고**, 거기서 적으려 했더니 장부가
//   영영 비어 ㉠ 이 발동 0 이었다. 판정은 그대로 대기열이 지고, 여기선 **적기만** 한다.
//   ⚠ 아래 `발동판정` 이 대부분의 턴에서 곧장 exit 하므로 **그 앞**에 둔다 — 뒤에 두면
//     컨텍스트가 임계에 닿은 세션에서만 관측이 찍혀 표본이 통째로 편향된다.
//   ⚠ 계기판이지 가드가 아니다 — 여기서 터져도 컨텍스트 경고를 죽이지 않는다.
try {
  const 신호 = require(path.join(__dirname, '..', '..', 'tools', 'lib', '재심신호.js'));
  const wt = require(path.join(__dirname, 'lib', 'worktrees.js'));
  // 장부는 **한 벌**이어야 한다 — 워크트리마다 따로 쌓이면 지워질 때 관측이 함께 사라진다.
  신호.관측하기({ 뿌리: wt.mainWorktree(cwd), 모델: info.model });
} catch (_) { /* 관측이 실패해도 세션은 방해하지 않는다 */ }

const prev = store.readStage(cwd, sid);

// 🔑 발동 여부는 **함수 하나**가 정한다 — 되감기(`tools/훅발동.js`)가 같은 함수를 쓴다.
//   내려갈 때 카운터를 따라 내리는 이유(컴팩트 한 번이 알림 400k 구간을 통째로 삼킨다)와
//   억제 규칙 셋의 근거는 그 함수 주석에 있다. 여기서 다시 적으면 갈라진다.
const 판정 = 발동판정(ctx, info.model, prev);
if (판정.다음단계 !== prev) store.writeStage(cwd, sid, 판정.다음단계);
if (!판정.발동) process.exit(0);
const stage = 판정.단계;

// 🔴 **첫 도달에만** AI 를 깨워 정리를 시킨다 — 세션당 정확히 1회.
// 유호님 08-04: "지금은 자동화가 아니야. 억지로 내가 신경써야" — 화면에 문구만 띄우는 건
// 계기판이지 자동화가 아니었다. 여기서 AI 가 커밋·보드 줄·메모리를 끝내 두면
// 유호님에게 남는 손일은 **창을 닫는 것 하나**가 된다(그건 어떤 훅도 대신 못 한다).
const wake = prev < 2 && stage >= 2;

const dirty = report.dirtyCount(cwd);
const pct = Math.round((ctx / WINDOW) * 100);
const k = (n) => `${Math.round(n / 1000)}k`;

// 끊기 절차 — 「인계되는 것은 커밋·보드 줄·메모리 셋뿐」(CLAUDE.md 세션 규약)
//
// ⚠ 절차를 나열하지 않는다. 08-04 실측: 경고가 8번 떴는데도 세션은 786k 까지 갔다.
//   부족한 건 알림이 아니라 **끊는 비용**이었다 — 커밋·보드·메모리 셋을 손으로 하려니
//   「나중에」가 됐다. 그래서 알림을 늘리는 대신 **한 줄로 실행되게** 한다(유호님 확정, 08-04).
//   `/close` 스킬이 그 셋을 순서대로 처리한다(.claude/skills/close/SKILL.md).
const CLOSE = '**`/close`**';
let steps;
if (dirty === null) {
  steps = `${CLOSE} 라고 입력하면 미커밋 확인·커밋·보드 줄·인계까지 한 번에 끝난다.`;
} else if (dirty > 0) {
  steps = `미커밋 ${dirty}건 — ${CLOSE} 라고 입력하면 범위 지정 커밋·보드 줄·인계까지 한 번에 끝난다.`;
} else {
  steps = `미커밋 0건 — ${CLOSE} 로 보드 줄만 정리하면 끝. 지금 끊으면 잃는 게 없다.`;
}

/* ㈎ 여기도 같은 게이트를 지난다 (F661 ㈎ · 유호 픽 2026-08-19) — 바통을 떨구는 자리가 둘이라,
 * 한쪽만 고치면 「🔴 를 넘긴 세션」에서 빈 인계문이 그대로 돌아온다. **판정은 재지 않고 받는다**:
 * `buildHandoff` 가 커밋·보드 줄을 재며 `메타` 를 채우고, `store.drop` 이 그 값을 보고 거른다.
 * ⚠ 커밋도 보드 줄도 없이 🔴(150k)에 닿는 세션은 드물지만 0이 아니다 — 긴 조사·독해만 하고
 *   아무것도 안 남긴 세션이 정확히 그 모양이다. */
const 메타 = {};
const handoffMsg = report.buildHandoff(cwd, sid, { dirty, 메타 });

// 🔴 부터 **바통을 떨군다** — 세션이 어떻게 끝나든(창을 그냥 닫아 SessionEnd 가 못 돌아도)
// 다음 세션이 이어받게 하는 보험이다. 평범한 종료는 session-end-handoff 가 따로 떨군다.
if (stage >= 2) store.drop(cwd, sid, handoffMsg, { ctx, trigger: `context-${stage === 3 ? 'last' : 'hard'}`, ...메타 });
// 🔴 부터는 **파일로도** 남긴다 — 바통(자동 입력)이 안 닿는 자리(다른 계정·폰)의 보조 통로.
// 유호님 08-04: "새 세션에서 바로 이어서 할 수 있게 프롬프트나 텍스트파일을 전달".
if (stage >= 2 && !메타.실을것없음) report.writeHandoffFile(cwd, handoffMsg, { sessionId: report.hostSessionId(sid), reason: `컨텍스트 ${Math.round(ctx / 1000)}k` });

// ⚠ 퍼센트를 앞세우지 않는다 — **거짓 안심을 준다**(유호님 "오푸스·페이블만 쓸 것", 08-04).
//   그 둘은 창이 1M 이라 끊어야 할 지점에서도 「31%」로 보인다. 실제 근거는 창 점유율이 아니라
//   **한 턴마다 그만큼을 통째로 다시 읽는다**는 것이다(하루 비용의 88% 가 그 재읽기였다).
//   그래서 절대값과 턴당 재읽기를 앞에 놓고, 퍼센트는 괄호 안 참고로만 남긴다.
/* ⚠ 인계문 전문은 **한 화면에 한 벌만** 나간다 (유호님 08-12: "인계문이 계속 2개가 나가고 있거든?").
 *   범인은 이 훅 하나다 — `systemMessage` 가 전문을 싣고, `wake` 의 `additionalContext` 가 AI 에게
 *   **같은 전문을 코드 블록으로 또 내라**고 시켰다. 문구까지 서로 어긋났다: 화면 쪽은 「복붙 불필요」,
 *   AI 쪽은 「복사해 붙이면 됩니다」. 유호님이 어느 말을 따라야 하는지가 사라진다.
 *   ⚠ F122(블록이 두 번 나감)와 **다른 축이다** — 그건 지시하는 훅이 **둘**이라 겹친 것이라
 *   `blockOrder` 의 세션당 1회 표식으로 닫혔고, 이건 **한 훅 «안»**이라 그 표식에 안 걸린다.
 *   가르는 기준 = **어느 쪽이 실제로 복사되는가.** AI 의 코드 블록에는 복사 버튼이 붙고,
 *   `systemMessage` 는 줄마다 접두가 붙어 접힌다(08-12 화면 실측). 그래서 **깨울 때는 전문을
 *   AI 쪽에 양보하고 여기엔 자리만 가리킨다** — 대신 보조 사본 경로를 같이 적어 AI 가 블록을
 *   안 내도 전문이 사라지지 않게 한다(새는 방향을 「없음」이 아니라 「한 벌」로 둔다).
 *   깨우지 않는 발화(2회차 이후)에는 AI 블록이 아예 없으므로 여기가 **유일한** 화면 사본이라 전문을 싣는다. */
/* 🔑 **인계문 전문은 이 통로로 안 나간다** — 유호님 확정 08-12("인계문 이거 말고 예전 방식…
 *   복붙하기 쉽게 되있는거 그거 하나만 떴으면 좋겠는데"). systemMessage 는 줄마다 `Stop says:`
 *   접두가 붙어 접히고 복사 버튼이 없다 — 같은 글이 화면에 두 벌인데 **쓸 수 있는 건 AI 코드 블록
 *   하나뿐**이었다. 그래서 화면 사본은 여기가 아니라 그쪽 한 벌로 몬다.
 *   ⚠ 첫 판(08-12 오전)은 이걸 `wake` 일 때만 껐다 — 그래서 🟡·반복 발화는 그대로 쏟았고 유호님
 *     화면에 다시 나타났다(실측 스크린샷 285k). **단계로 가르는 문제가 아니라 통로의 문제였다.**
 *   ⚠ F096(「파일 경로 안내는 실물의 대체가 안 된다」)과 충돌하지 않는다 — 그건 **깨워진 AI 가
 *     블록을 안 낸** 자리이고, 실물은 지금도 🔴 wake 의 `blockOrder` 가 낸다. 여기서 지우는 것은
 *     실물이 아니라 그 «중복» 사본이다. 사본이 0 이 되지 않게 세 통로를 같이 가리킨다. */
/* 🔴 **인계 통로 안내도 안 낸다 — 줄 수 자체가 증상이다** (유호님 08-12 스크린샷 4번째 지적).
 *   앞 세 판은 「전문을 빼면 된다」로 갔다(463d6b7a·d180ade9·3307856a). 전문은 빠졌는데 그 자리에
 *   안내 4줄이 들어앉아 유호님 화면은 그대로였다 — `Stop says:` 접두가 **줄마다** 붙어 9번 찍혔고,
 *   `\n\n` 이 만든 빈 줄은 `Stop says:` 만 덩그러니 남았다. 즉 새던 것은 「전문이냐 안내냐」가
 *   아니라 **줄 수**였고, 회귀는 전문 실재만 봐서 안내가 늘어도 초록이었다.
 *   ⚠ 안내를 지워도 통로는 안 사라진다 — `steps` 가 이미 「`/close` 로 인계까지 끝난다」고 말하고,
 *     🔴 wake 는 `blockOrder` 가 복사 가능한 실물을 낸다. 여기서 지운 건 그 셋의 **목차**뿐이다.
 *   🔑 이번엔 프로즈가 아니라 기계로 못박는다 — 회귀가 systemMessage 의 **줄 수 상한과 빈 줄 0**
 *     을 잰다(`tests/컨텍스트예산.test.js`). 다음 사람이 한 줄 더 붙이면 그 자리에서 빨개진다. */
const msg =
  `${levelOf(ctx, T)} [context-budget] 컨텍스트 ${k(ctx)} — ${headOf(stage)}. ` +
  `**한 턴마다 ${k(ctx)} 를 다시 읽는다**(창 ${k(WINDOW)} 의 ${pct}% — 창은 기준이 아니다).\n` +
  `${steps}\n` +
  `왜 컴팩트가 아니라 종료인가: 바닥값이 ${k(FLOOR)}라 컴팩트 도달점(≈${k(FLOOR + 5000)})이 ` +
  `새 세션 시작점(${k(FLOOR)})보다 크다. 세션 재시작이 더 작고 요약 손실도 0이다.`;

