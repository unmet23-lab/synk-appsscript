#!/usr/bin/env node
'use strict';
/**
 * decision-catch — 유호님 말에 «확정 무늬»가 있으면 **그 자리에서** 결정.md 에 적으라고 띄운다.
 *                  (UserPromptSubmit 훅)
 *
 * ■ 왜 있나 (유호 픽 2026-09-01 ㉯ · 하네스재판정_0901 §4-B4)
 *   세션 시작 훅이 **스스로** 경고하고 있다:
 *     「🔑 유호님이 뭔가 정하시면 **그 자리에서** `node tools/결정.js --추가` — 세션 끝에 적으면 안 적힌다.」
 *   그리고 `결정.js` 가 태어난 까닭 자체가 유호님 신고였다 —
 *     「결정하고 말했을 때 니가 자주 기억을 못 한다」(08-19).
 *   즉 «적어야 한다»는 이미 두 곳에 적혀 있고, 그런데도 새는 자리다. 「적어 둔다고 막히지 않는다」.
 *   ⇒ 유호님 말이 **아직 처리되기 전에** 서는 검사가 필요하다. 그게 UserPromptSubmit 이다.
 *
 * ■ 설계 판정 넷
 *   ① **막지 않는다.** 평문 stdout 만 낸다(이 이벤트는 평문이 그대로 컨텍스트로 들어간다).
 *      유호님 말을 훅이 삼키는 일은 어떤 경우에도 없어야 한다.
 *   ② **좁게 잡고, 판정은 나에게 넘긴다.** 무늬는 「정하는 말투」만 본다. 그래도 거짓 양성이 남으므로
 *      문구가 **「단순 작업 지시면 무시하라」**를 같이 말한다 — 훅이 판정하지 않는다.
 *   ③ **세션 스로틀 없음.** 유호님은 한 세션에 여러 번 정하신다. 스로틀을 두면 둘째부터 샌다.
 *   ④ **네트워크·git 을 안 쓴다.** 정규식뿐이다(이 이벤트 기본 타임아웃은 30초로 짧다).
 *
 * ■ 대가 (틀릴 때의 모습)
 *   - 「테스트 돌려보자」 같은 작업 지시에도 뜬다 → 그래서 ②의 문구가 «무시해도 된다»를 명시한다.
 *   - 반대로 무늬 없는 확정(「응」·「1번」 같은 짧은 픽)은 **못 잡는다.** 이 훅은 그물이지 벽이 아니다 —
 *     내가 판정을 여쭙고 답을 받은 자리는 여전히 내가 적어야 한다.
 */

const 무늬 = [
  /(으로|로|것으로|이걸로|그걸로)\s*(하자|가자|간다|하지|정하자|가지)/,
  /(하자|가자|하기로|가기로|정했|정하자|결정했|확정)\b/,
  /기억해\s*(줘|둬|주라|둬라)/,
  /앞으로는?\b/,
  /다시는\b/,
  /(하지|쓰지|만들지|열지|넣지)\s*마/,
  /(금지|그만하자|빼자|넣자|바꾸자|없애자|살리자|접자)/,
  /(안 ?할래|안 ?한다|안 ?해도 ?돼|하지 ?않는다)/,
];

let s = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (d) => (s += d));
process.stdin.on('end', () => {
  let 입력;
  try { 입력 = JSON.parse(s || '{}'); } catch { process.exit(0); }
  const 말 = String(입력.prompt || '');
  if (!말.trim()) process.exit(0);
  if (말.trim().startsWith('/')) process.exit(0); // 슬래시 명령은 확정이 아니다

  const 걸림 = 무늬.filter((r) => r.test(말));
  if (!걸림.length) process.exit(0); // 0건이면 완전 침묵

  console.log(
    '🔑 **이 말에 «정하는» 무늬가 있다.**\n' +
    '유호님이 방향·기준·금지를 **정하신 것이면**, 답하기 «전에» 그 자리에서 적는다:\n' +
    '`node tools/결정.js --추가 "<결정문>" --근거 "유호 확정 <날짜> 「<유호님 말 그대로>」"`\n' +
    '(되돌릴 수 없는 것 — 라이브·자격증명·개인정보·외부 발송·대량 삭제 — 이면 `--성격 안전`)\n' +
    '그리고 `docs/_ops/결정.md` 는 공용 원장이니 **고친 그 커밋에서 바로 민다.**\n' +
    '⚠ 단순 작업 지시(「돌려보자」·「확인하자」)면 **이 알림을 그냥 무시한다** — 훅은 판정하지 않는다.'
  );
  process.exit(0);
});
setTimeout(() => process.exit(0), 20000);
