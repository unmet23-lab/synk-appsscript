//   이번에 발견된 경로는 우연이었다 — 예상 밖 테스트 적색을 「고칠 것」으로 보지 않고
//   파봤기 때문이다. 그건 재현 가능한 장치가 아니라서 기계로 옮긴다.
//
// 무엇을 보나 — 세 신호. 하나라도 걸리면 알린다.
//   ① 내가 **이번 세션에 만진** 파일에 남의 커밋이 닿았다
//   ② 내가 **보드에 선언한** 파일에 남의 커밋이 닿았다 (아직 안 만졌어도 그 자리는 내 자리다)
//   ③ 남의 커밋 제목이 내 보드 줄과 **같은 표식**을 쓴다 (F0NN · [v9.NNN])
//      — 파일이 안 겹쳐도 트랙은 겹칠 수 있다. 오늘이 정확히 그 경우였다.
//
// ⚠ **allow 는 어떤 신호에서도 내지 않는다.** Edit 매처엔 board-guard·memory-index-guard·
//   doc-propagation 이 함께 걸려 있어, 여기서 allow 를 내면 그것들의 판정을 덮는다.
//   ①②③④ 는 정보만 준다: systemMessage(유호님 눈) + additionalContext(AI 눈).
//   ①남의 커밋이 내 편집을 금지할 근거가 없고, ④는 다른 트리라 되돌림이 저쪽 몫이다.
//
// 🔴 **⑤ 만 deny 다** (마찰 F239 · 2026-08-08 실사고):
//   ⑤ 는 F221 이 세운 그날 정확히 짚었는데 **막지 못했다** — additionalContext 는 Edit **결과와
//   함께** 도착한다. 알림을 읽는 시점엔 내 바이트가 이미 남의 작업본에 앉아 있었고, 처방문의
//   「계속하기 전에 보드를 읽는다」는 구조적으로 실행 시점이 없다. 실물: `board-guard.js` 가
//   `let` 이중 선언 SyntaxError 상태가 됐고 — 그 창에서 auto-commit 이 돌았으면 훅이 통째로
//   죽은 판이 master 로 나간다. edit-stamp 도 못 막는다(그 바이트의 지문은 진짜 내 것이라
//   「내가 쓴 것」 검사를 그대로 통과한다). 신호는 정확했고 늦지도 않았다 — **알림이라 편집을
//   세우지 못한 것**이라, 고칠 자리는 탐지가 아니라 출력이다.
//   deny 는 다른 가드를 덮지 않는다(allow 와 달리 편집 자체가 안 일어난다).
//   출구는 **같은 편집을 한 번 더 요청하는 것**이다 — 파일당 1회만 막는다(아래 `알린동승`).
