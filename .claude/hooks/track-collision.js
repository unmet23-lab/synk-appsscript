//   🔑 근본 원인은 규약 위반이 아니다 — **규약을 다 지켜도 안 보이는 자리**다.
//      CLAUDE.md 는 "열기 직전 `git log --oneline -10`" 을 시킨다. 그건 했다. 그런데
//      상대 커밋은 그 **25분 뒤에** 착지했다. 시작 시 로그는 스냅샷이라, 세션이 길어질수록
//      「내가 본 저장소」와 「지금 저장소」의 간격이 벌어진다. 발동층이 아예 없던 자리다.
