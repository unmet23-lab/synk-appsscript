function 묶기(fs) {
  const out = []
  let cur = []
  let 그림 = new Set()
  for (const f of fs) {
    const 이것 = (f.근거 || []).flatMap(그림경로)
    const 합 = new Set([...그림, ...이것])
    if (cur.length && (cur.length >= 지적한도 || 합.size > 그림한도)) {
      out.push(cur)
      cur = []
      그림 = new Set()
    }
    cur.push(f)
    for (const p of 이것) 그림.add(p)
  }
  if (cur.length) out.push(cur)
  return out
}
