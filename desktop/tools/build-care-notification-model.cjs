'use strict';
const path=require('node:path'),fs=require('node:fs'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'../..');
function build(output=path.join(root,'desktop/src/care-notification-model.cjs')){
  const entry="import * as model from './experiences/relationship-care/model.mjs';\nimport worker from '../SYNK-talk/lib/synk-care-push-worker.js';\nexport const shouldNotify=worker.createCarePushDue(model);\n";
  require('esbuild').buildSync({stdin:{contents:entry,resolveDir:root,sourcefile:'care-notification-model-entry.mjs'},bundle:true,platform:'node',format:'cjs',target:'node24',outfile:output,legalComments:'none',banner:{js:'// Generated by desktop/tools/build-care-notification-model.cjs from the canonical Care model and push due predicate. Do not edit.'}});
  return {output,sha256:crypto.createHash('sha256').update(fs.readFileSync(output)).digest('hex')};
}
