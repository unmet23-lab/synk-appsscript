'use strict';

// The frozen desktop application does not install npm packages on a member's PC.
const fs=require('node:fs');
const path=require('node:path');
const esbuild=require('esbuild');
const parse5Root=path.resolve(path.dirname(require.resolve('parse5')),'..');
const packageRoot=path.dirname(path.dirname(parse5Root));
const entitiesRoot=path.resolve(path.dirname(require.resolve('entities',{paths:[parse5Root]})),'..');
const output=path.resolve(__dirname,'../src/estimate-html5.cjs');
const licenses=[parse5Root,entitiesRoot].map(dir=>{
  const pkg=JSON.parse(fs.readFileSync(path.join(dir,'package.json'),'utf8'));
  const text=fs.readFileSync(path.join(dir,'LICENSE'),'utf8').trim().replace(/\r\n/g,'\n');
  return '/* '+pkg.name+' '+pkg.version+'\n'+text+'\n*/';
});
const result=esbuild.buildSync({
  absWorkingDir:packageRoot, stdin:{contents:"export { parse } from 'parse5';",resolveDir:packageRoot,sourcefile:'estimate-html5-entry.mjs'},
  bundle:true,platform:'node',format:'cjs',target:'node24',legalComments:'inline',write:false,
  banner:{js:['// Generated by desktop/tools/build-estimate-html-parser.cjs with the root package lock.',...licenses].join('\n')}
});
const bytes=result.outputFiles[0].contents;
if(process.argv.includes('--check')){
  if(!fs.existsSync(output)||!fs.readFileSync(output).equals(Buffer.from(bytes)))throw Error('견적 HTML 파서가 잠금 파일의 버전과 다릅니다.');
}else fs.writeFileSync(output,bytes);
